def slow_window(data, st, L, h, q0, c, s):
    """Сценарное окно одного окна модели в лоб, по барам (numpy; места — в общем массиве данных). Цепочка баров: настоящие
       st … t с множителем 1, потом бары куска q0 … q0 + h − 1 с множителем f = s · c. У бара: шаг close — множитель · r;
       ширина — |множитель| · g; шаг средней цены — множитель · e − (множитель прошлого бара цепочки) · (сдвиг средней цены
       прошлого бара от его close; он хранится на месте следующего бара ряда)."""
    f = np.float32(s) * np.float32(c)
    chain = [(st + i, np.float32(1.0)) for i in range(L - h)] + [(q0 + j, f) for j in range(h)]
    out = np.empty((4, L), np.float32)
    for i, (p, m) in enumerate(chain):
        out[0, i] = m * data.r[p]
        out[3, i] = np.abs(m) * data.chan_g[p]
        pp, m_prev = chain[i - 1] if i else (p - 1, np.float32(1.0))
        for ch in range(2):
            out[1 + ch, i] = m * data.chan_e[ch][p] - m_prev * data.chan_d[ch][pp + 1]
    return out


def slow_piece(data, seg, st, L, h, k):
    """Кусок k окна в лоб, по определению шапки: (первый бар, годен, сторона, размер c, кусок и его замер — в последних
       band барах до «сейчас» включительно и вне окна)."""
    K, ref = SCEN['pieces'], SCEN['ref']
    t = st + L - 1 - h
    q0 = st - int(round(k * (SCEN['band'] - ref - L) / (K - 1))) - h
    bars = np.arange(q0 - ref, q0 + h)
    inside = bars.min() >= t - SCEN['band'] + 1 and bars.max() <= st - 1
    if q0 - ref < seg:
        return q0, False, 0.0, 1.0, inside
    r, g = data.r[bars].astype(np.float64), data.chan_g[bars].astype(np.float64)
    move = float(r[ref:].sum())
    ok = bool(np.isfinite(r).all() and np.isfinite(g).all() and abs(move) > SCEN['zero'])
    g_now = float(data.chan_g[t - ref + 1:t + 1].astype(np.float64).mean())
    c = float(np.clip((g_now + 1e-6) / (float(g[:ref].mean()) + 1e-6), SCEN['clip'][0], SCEN['clip'][1]))
    return q0, ok, (1.0 if move > 0 else -1.0), c, inside


