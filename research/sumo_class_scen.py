def splice(data, W, st_t, L, h, q0_t, c_t, s):
    """Сценарное окно (n, 4, L): первые L − h баров — настоящего окна W, последние h — бары ряда q0 … q0 + h − 1, умноженные
       на c (размер) и s (+1 — кусок как был, −1 — зеркало: каждый бар перевёрнут целиком). Арифметика — как у окна модели
       (gw) и суррогата (flip_multi) кода обучения. f = s · c. Шаг close — f · r. Шаг средней цены бара (HL/2, HLC/3) —
       f · e − (множитель прошлого бара) · d: e — сдвиг средней цены бара от прошлого close, d — сдвиг средней цены прошлого
       бара от его close; у первого бара куска прошлый бар — «сейчас» (настоящий: множитель 1, d его собственный), у
       остальных — предыдущий бар куска (множитель f). Ширина бара — c · g (зеркало ширину не меняет). Свой хвост
       (q0 = st + L − h) при c = 1: s = +1 — настоящее окно бит в бит, s = −1 — окно шага 0 бит в бит."""
    import torch
    if W.dim() != 3 or W.shape[1] != 4 or len(data.chan_t) != 2:
        raise ValueError(f"🍆 АЙ, ОШИБКА! окно модели — {tuple(W.shape)}, ждал (n, 4, L): close, HL/2, HLC/3, ширина")
    idx = q0_t[:, None] + torch.arange(h, device=W.device)[None, :]      # места баров куска в ряду
    f = (float(s) * c_t)[:, None]
    fp = f.expand(-1, h).clone()                           # множитель бара, стоящего перед каждым баром куска
    fp[:, 0] = 1.0
    j0 = st_t + (L - h)                                    # место первого бара хвоста: d_[j0] — сдвиг бара «сейчас»
    chans = [f * data.r_t[idx]]
    for e_, d_ in data.chan_t:                             # d_[q] — сдвиг средней цены бара q − 1 от его close
        dp = d_[idx]
        dp[:, 0] = d_[j0]
        chans.append(f * e_[idx] - fp * dp)
    chans.append(c_t[:, None] * data.chan_g_t[idx])
    return torch.cat([W[:, :, :L - h], torch.stack(chans, dim=1)], dim=2)


def lr_feats(T, X, S, cols):
    """Сводки окна для регрессии (как lr_feats в SuMo_Pred_D1): из ориентированной формы X (окна, каналы, L) — конец пути
       против среднего, последний шаг, ходы за 4 / 16 / 63 шага (в системе окна, в его делителях), ширина последнего бара;
       плюс боковые входы модели cols."""
    import torch
    x0 = (X[:, 0] if X.dim() == 3 else X).double()
    f = [x0[:, -1], x0[:, -1] - x0[:, -2], x0[:, -1] - x0[:, -5], x0[:, -1] - x0[:, -17], x0[:, -1] - x0[:, 0]]
    if X.dim() == 3 and X.shape[1] > T.N_PATH:
        f.append(X[:, T.N_PATH, -1].double())
    out = torch.stack(f, dim=1)
    if cols:
        out = torch.cat([out, S[:, list(cols)].double()], dim=1)
    return out.cpu().numpy()


class TorchBackend:
    """Окна одного ассета и части кодом обучения: настоящее окно, окно со знаками баров, сценарное окно; logit моделей
       источника. off — место в общем массиве данных, от которого считаны ряды куска (r, g у score_windows)."""
    def __init__(self, T, data, P, models, L, off):
        self.T, self.data, self.P, self.models, self.L, self.off = T, data, P, models, L, int(off)
        self.tags = list(models)
        cols = {tuple(getattr(m, 'side_cols', None) or ()) for m in models.values()}
        if len(cols) != 1:
            raise ValueError("🍆 АЙ, ОШИБКА! у моделей источника разные боковые входы")
        self.side_cols = cols.pop()

    def _t(self, x, dtype):
        import torch
        return torch.from_numpy(np.ascontiguousarray(x, dtype=dtype)).to(self.T.DEVICE)

    def inputs(self, W):
        """Форма и боковые входы окна W — как у суррогатов обучения: история настоящая, ориентация и делитель — по W."""
        return self.T.to_shapes(W, self.P['fl']), self.T.side_feats(self.data, self.P['st_t'], self.L, W, self.P['fl'])

    def logits(self, X, S_):
        return {tag: np.asarray(self.T.score(m, X, S=S_), dtype=np.float64) for tag, m in self.models.items()}

    def real(self):
        return self.logits(self.P['X'], self.P['S'])

    def win_signs(self, sg):
        return self.data.flip_multi(self.P['st_t'], self.L, self._t(sg, np.float32), self.P['W'])

    def signs(self, sg):
        return self.logits(*self.inputs(self.win_signs(sg)))

    def win_splice(self, h, q0, c, s):
        return splice(self.data, self.P['W'], self.P['st_t'], self.L, h, self._t(np.asarray(q0) + self.off, np.int64),
                      self._t(c, np.float32), s)

    def splice(self, h, q0, c, s):
        return self.logits(*self.inputs(self.win_splice(h, q0, c, s)))

    def lr_feats(self):
        return lr_feats(self.T, self.P['X'], self.P['S'], self.side_cols)

    def orient(self):
        return self.T.orient_sign(self.P['W'], self.P['fl']).cpu().numpy()


class NumpyBackend:
    """Заменитель на стенде: окно — шаги close (один канал), «модель» — функция окна proxy; два «сида» — малый независимый
       шум logit. Те же действия, что у TorchBackend."""
    def __init__(self, r, g, st, L, proxy, rng, tags):
        self.r, self.g, self.st, self.L = np.asarray(r, np.float32), np.asarray(g, np.float32), np.asarray(st, np.int64), L
        self.proxy, self.rng, self.tags = proxy, rng, list(tags)
        self.W = self.r[self.st[:, None] + np.arange(L)[None, :]]

    def _out(self, Wn):
        lg = self.proxy(Wn.astype(np.float64))
        return {tag: lg + self.rng.normal(0.0, STAND['seed_noise'], len(lg)) for tag in self.tags}

    def real(self):
        return self._out(self.W)

    def win_signs(self, sg):
        return self.W * np.asarray(sg, np.float32)[:, 1:]

    def signs(self, sg):
        return self._out(self.win_signs(sg))

    def win_splice(self, h, q0, c, s):
        tail = (np.float32(s) * np.asarray(c, np.float32))[:, None] * self.r[np.asarray(q0)[:, None] + np.arange(h)[None, :]]
        return np.concatenate([self.W[:, :self.L - h], tail], axis=1)

    def splice(self, h, q0, c, s):
        return self._out(self.win_splice(h, q0, c, s))

    def _shape(self):
        W = self.W.astype(np.float64)
        div = np.maximum(np.median(np.abs(W), axis=1), 1e-9)
        x = np.cumsum(W, axis=1)
        x = x - x.mean(axis=1, keepdims=True)
        s = np.where(x[:, -1] < -ORIENT_EPS * div, -1.0, 1.0)
        return s, s[:, None] * x / div[:, None], div

    def lr_feats(self):
        _, x0, div = self._shape()
        return np.stack([x0[:, -1], x0[:, -1] - x0[:, -2], x0[:, -1] - x0[:, -5], x0[:, -1] - x0[:, -17],
                         x0[:, -1] - x0[:, 0], self.g[self.st + self.L - 1] / div], axis=1)

    def orient(self):
        return self._shape()[0]


def score_windows(B, r, g, st, L, sg4):
    """Всё, что 'score' кладёт в кэш по окнам одного ассета и части. B — окна и logit (TorchBackend или заменитель стенда);
       r, g — шаг close и ширина бара ряда, откуда берутся куски (NaN — пропуск); st — начала окон в этом ряду; sg4 — знаки
       суррогата линейки. По хвостам SCEN['tails'] (столбцы): orc — оракул шага 0, logit настоящего окна минус окна с
       зеркальным хвостом; mv — ход close настоящего хвоста, pv — ход такого же куска до «сейчас»; a — у каждого куска logit
       сценария «кусок как был» минус «его зеркало» (средний по сидам, размер 'fit'; NaN — кусок негоден); ub — биты «кусок
       как был идёт вверх»; <сид>__D — стрелка сида; Draw — стрелка размера 'raw' (средняя по сидам); lc — средний log c
       годных кусков; lv — средний logit сценарных окон (годные куски, обе ориентации, сиды; размер 'fit'). Плюс logit
       настоящего окна и суррогата линейки (sp, s4), сводки окна для регрессии (lrf) и знак его ориентации (sg). Второе
       возвращаемое — счётчики кусков по хвостам."""
    tails, K, tags = SCEN['tails'], SCEN['pieces'], B.tags
    st = np.asarray(st, dtype=np.int64)
    n, H = len(st), len(tails)
    sums = series_sums(r, g)
    sp, s4 = B.real(), B.signs(sg4)
    out = {'a': np.full((n, H, K), np.nan, np.float16), 'ub': np.zeros((n, H), np.uint8)}
    for k in ('orc', 'mv', 'pv', 'lc', 'lv') + (('Draw',) if 'raw' in SCEN['sizes'] else ()):
        out[k] = np.full((n, H), np.nan, np.float32)
    for tag in tags:
        out[f"{tag}__sp"], out[f"{tag}__s4"] = sp[tag].astype(np.float32), s4[tag].astype(np.float32)
        out[f"{tag}__D"] = np.full((n, H), np.nan, np.float32)
    stat = {}
    for j, h in enumerate(tails):
        lt = B.signs(TL.tail_signs(n, L, h))
        out['orc'][:, j] = np.mean([sp[t] - lt[t] for t in tags], axis=0)
        now1 = st + L - h
        out['mv'][:, j] = sums['rcs'][st + L] - sums['rcs'][now1]
        out['pv'][:, j] = sums['rcs'][now1] - sums['rcs'][now1 - h]
        plan = piece_plan(sums, st, L, h)
        ok, u = plan['ok'], plan['u']
        a = {size: {tag: np.full((n, K), np.nan) for tag in tags} for size in SCEN['sizes']}
        lv = np.zeros(n)                                   # сумма logit сценарных окон по годным кускам (размер 'fit')
        for k in range(K):
            q0 = np.where(ok[:, k], plan['q0'][:, k], now1 - h)    # негодный кусок: считаем h баров до «сейчас», итог — NaN
            for size in SCEN['sizes']:
                c = plan['c'][:, k] if size == 'fit' else np.ones(n, np.float32)
                up, dn = B.splice(h, q0, c, 1.0), B.splice(h, q0, c, -1.0)
                for tag in tags:
                    a[size][tag][:, k] = np.where(ok[:, k], up[tag] - dn[tag], np.nan)
                if size == 'fit':
                    lv += np.where(ok[:, k], np.mean([(up[t] + dn[t]) / 2 for t in tags], axis=0), 0.0)
        for tag in tags:
            out[f"{tag}__D"][:, j] = arrow_mean(u * a['fit'][tag])
        out['a'][:, j] = np.mean([a['fit'][t] for t in tags], axis=0).astype(np.float16)
        out['ub'][:, j] = (((u > 0) & ok) * (1 << np.arange(K))[None, :]).sum(axis=1).astype(np.uint8)
        if 'raw' in SCEN['sizes']:
            out['Draw'][:, j] = np.mean([arrow_mean(u * a['raw'][t]) for t in tags], axis=0)
        nv = ok.sum(axis=1)
        lc = np.log(plan['c'].astype(np.float64))
        out['lc'][:, j] = np.where(nv > 0, np.where(ok, lc, 0.0).sum(axis=1) / np.maximum(nv, 1), np.nan)
        out['lv'][:, j] = np.where(nv > 0, lv / np.maximum(nv, 1), np.nan)
        stat[str(h)] = {'pieces': int(ok.size), 'valid': int(ok.sum()), 'lo': int((ok & (plan['c'] <= SCEN['clip'][0])).sum()),
                        'hi': int((ok & (plan['c'] >= SCEN['clip'][1])).sum()), 'arrows': int((nv >= SCEN['min_valid']).sum()),
                        'windows': n}
    out['lrf'] = np.clip(B.lr_feats(), -3e4, 3e4).astype(np.float16)
    out['sg'] = np.asarray(B.orient()).astype(np.int8)
    return out, stat


