def cache_dir(tf, part):
    return OUT_DIR + f"cache/scen_{tf}_{part}_f{SCEN['floor']:g}/"


def cache_cfg():
    """Всё, от чего зависит содержимое кэша: при других настройках сценария кэш считается заново."""
    return {'ver': SCEN_VER, 'floor': SCEN['floor'], 'tails': list(SCEN['tails']), 'pieces': SCEN['pieces'],
            'band': SCEN['band'], 'ref': SCEN['ref'], 'clip': list(SCEN['clip']), 'sizes': list(SCEN['sizes']),
            'min_valid': SCEN['min_valid'], 'zero': SCEN['zero']}


def _same_cfg(info):
    return all(info.get(k) == v for k, v in cache_cfg().items())


def save_asset(tf, part, a, out, info):
    os.makedirs(cache_dir(tf, part), exist_ok=True)
    tmp = cache_dir(tf, part) + f"{a}.tmp.npz"
    np.savez(tmp, info=np.array(json.dumps(TL._jsonable({**cache_cfg(), **info}), ensure_ascii=False)), **out)
    os.replace(tmp, cache_dir(tf, part) + f"{a}.npz")


def asset_info(tf, part, a, tags=None, fp=None):
    """Запись о посчитанном ассете (или None: файла нет, он с другими настройками сценария, моделями или данными)."""
    p = cache_dir(tf, part) + f"{a}.npz"
    if not os.path.isfile(p):
        return None
    try:
        with np.load(p) as d:
            info = json.loads(str(d['info']))
    except Exception:                                      # недописанный файл (обрыв записи) — как будто его нет
        return None
    other = (tags is not None and info.get('tags') != list(tags)) or (fp is not None and info.get('fp') != fp)
    return None if other or not _same_cfg(info) else info


def load_cache(tf, part):
    p = cache_dir(tf, part) + '_done.json'
    if not os.path.isfile(p):
        return None
    with open(p, encoding='utf-8') as fh:
        meta = json.load(fh)
    if not _same_cfg(meta):
        return None
    res = {}
    for a in meta['assets']:
        fn = cache_dir(tf, part) + f"{a}.npz"
        if not os.path.isfile(fn):
            return None
        with np.load(fn) as d:
            res[a] = {k: d[k] for k in d.files if k != 'info'}
    return {'meta': meta, 'res': res}


