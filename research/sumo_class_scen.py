def stand_world(kind, seed, assets=None, bars=None):
    """Мир стенда — у каждого ассета шаги close и ширина бара: 'coin' — шаги независимы; 'saw' — AR(1) с φ < 0 (после шага
       чаще шаг против него); 'pattern' — «узор»: знак шага с вероятностью p_pat равен произведению знаков пяти прошлых шагов
       (PAT_LAGS назад), размеры шагов независимы. Мир зеркально симметричен (знаков в произведении нечётное число), а знаки
       двух шагов на любом расстоянии до 30 баров не связаны: регрессия, линейная по сводкам прошлого, про следующий шаг не
       знает ничего."""
    rng = np.random.default_rng(seed)
    n, out = bars or STAND['bars'], {}
    for i in range(assets or STAND['assets']):
        eps = rng.normal(size=n)
        if kind == 'coin':
            x = eps
        elif kind == 'saw':
            phi = STAND['phi']
            x = np.empty(n)
            x[0] = eps[0]
            for t in range(1, n):
                x[t] = phi * x[t - 1] + math.sqrt(1.0 - phi ** 2) * eps[t]
        else:
            keep = np.where(rng.random(n) < STAND['p_pat'], 1.0, -1.0)
            sg = np.where(rng.random(n) < 0.5, -1.0, 1.0)
            for t in range(max(PAT_LAGS), n):
                sg[t] = keep[t] * np.prod([sg[t - k] for k in PAT_LAGS])
            x = sg * (np.abs(eps) + 0.05)
        out[f"S{i}USDT"] = (x, np.abs(x) + np.abs(rng.normal(size=n)))
    return out


def proxy_pattern(Wv):
    """Заменитель модели мира «узор»: доля шагов окна, чей знак равен произведению знаков прошлых шагов по узору мира, минус
       доля остальных. От зеркала окна не меняется (знаков в каждом слагаемом чётное число) — как сеть F1."""
    sg, m = np.sign(Wv), max(PAT_LAGS)
    prod = sg[:, m:].copy()
    for k in PAT_LAGS:
        prod *= sg[:, m - k:sg.shape[1] - k]
    return 8.0 * prod.mean(axis=1)


def stand_cache(world, seed, kind, src):
    """Кэш 'score' мира стенда — тем же счётом (score_windows), что у настоящего; «модель» — заменитель: у «узора» — свой,
       у остальных — «пила» окна шага 0 (чем чаще шаг идёт против прошлого, тем окно «реальнее»)."""
    L, rng, tags = 64, np.random.default_rng(1000 + seed), ['stand_a', 'stand_b']
    proxy = proxy_pattern if kind == 'pattern' else TL.proxy_logit
    t0, res, infos = pd.Timestamp(STAND['t0']).value, {}, []
    for a, (x, gx) in world.items():
        st = np.arange(len(x) - L + 1, dtype=np.int64)
        B = NumpyBackend(x, gx, st, L, proxy, rng, tags)
        out, stat = score_windows(B, x, gx, st, L, TL.stand_block_signs(rng, len(st), L, 4))
        t = t0 + (st + L - 1) * STAND['step_ns']
        out.update({'st': st, 't': t, 'wk': t // TL.WEEK_NS})
        res[a] = out
        infos.append({'stat': stat})
    meta = {**cache_cfg(), 'tf': 'stand', 'part': TL.part_of(src), 'tags': tags,
            'items': [{'tag': t_, 'src': src} for t_ in tags], 'assets': list(res), 'stat': sum_stat(infos)}
    return {'meta': meta, 'res': res}


def world_run(kind, seed, both=True, assets=None, bars=None, show=False):
    """Мир стенда тем же счётом, что 'run': VAL — своя реализация мира; both — ещё и TUNE (регрессия VAL учится на нём)."""
    caches = {'confirm': stand_cache(stand_world(kind, 500 + seed, assets, bars), 500 + seed, kind, 'confirm')}
    if both:
        caches['search'] = stand_cache(stand_world(kind, seed, assets, bars), seed, kind, 'search')
    return run_tf('стенд', caches, show=show)


