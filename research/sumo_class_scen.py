def series_sums(r, g):
    """Накопленные суммы ряда: bad[j] — сколько пропусков среди баров [0, j); rcs[j], gcs[j] — суммы шага close и ширины
       бара по барам [0, j) (пропуск — 0). r, g — шаг close и ширина бара в медианных барах, NaN — пропуск."""
    r, g = np.asarray(r, dtype=np.float64), np.asarray(g, dtype=np.float64)
    fin = np.isfinite(r) & np.isfinite(g)

    def acc(x):
        return np.concatenate([[0.0], np.cumsum(np.where(fin, x, 0.0))])
    return {'bad': np.concatenate([[0], np.cumsum(~fin)]).astype(np.int64), 'rcs': acc(r), 'gcs': acc(g), 'n': len(r)}


def piece_offsets(L):
    """На сколько баров раньше начала окна кончается кусок k: от 0 (прямо перед окном) до band − ref − L, равномерно. Кусок k
       хвоста h — бары st − off_k − h … st − off_k − 1; вместе с ref барами замера перед ним он не выходит за последние band
       баров до «сейчас» включительно ни при каком h."""
    K, span = SCEN['pieces'], SCEN['band'] - SCEN['ref'] - L
    if not 2 <= K <= 8 or span < K - 1:
        raise ValueError(f"🍆 АЙ, ОШИБКА! кусков {K} (нужно от 2 до 8) в полосе {span} баров")
    return np.round(np.arange(K) * span / (K - 1)).astype(np.int64)


def piece_plan(sums, st, L, h):
    """Куски хвоста h для окон с началами st (места — в ряду sums). Возвращает (окна, K): q0 — первый бар куска; ok — кусок
       годен (он и ref баров перед ним — без пропусков и не раньше начала ряда, ход close не ноль); u — сторона куска как был
       (+1 — вверх, −1 — вниз); c — множитель размера 'fit': средняя ширина ref баров до «сейчас» включительно / средняя
       ширина ref баров перед куском, в границах SCEN['clip']. Бары после «сейчас» не читаются."""
    ref, eps = SCEN['ref'], 1e-6
    st = np.asarray(st, dtype=np.int64)
    if 2 * h > L or ref > L - h:
        raise ValueError(f"🍆 АЙ, ОШИБКА! хвост h = {h} при окне L = {L} и замере {ref} баров")
    end = st[:, None] - piece_offsets(L)[None, :]          # бар сразу за куском: кусок — бары end − h … end − 1
    q0 = end - h
    a0 = q0 - ref                                          # первый бар замера активности куска
    ok = a0 >= 0
    e_, q_, a_ = np.maximum(end, 0), np.maximum(q0, 0), np.maximum(a0, 0)
    ok &= (sums['bad'][e_] - sums['bad'][a_]) == 0
    mv = sums['rcs'][e_] - sums['rcs'][q_]
    ok &= np.abs(mv) > SCEN['zero']
    now1 = st + L - h                                      # бар сразу за «сейчас»
    g_now = (sums['gcs'][now1] - sums['gcs'][now1 - ref]) / ref
    g_pc = (sums['gcs'][q_] - sums['gcs'][a_]) / ref
    c = np.clip((g_now[:, None] + eps) / (g_pc + eps), SCEN['clip'][0], SCEN['clip'][1])
    return {'q0': q0, 'ok': ok, 'u': np.where(mv > 0, 1.0, -1.0), 'c': c.astype(np.float32)}


def arrow_mean(ua, need=None):
    """D: среднее u · a по годным кускам (последняя ось; NaN — кусок негоден). Годных меньше need — стрелки нет (NaN)."""
    need = SCEN['min_valid'] if need is None else need
    ok = np.isfinite(ua)
    nv = ok.sum(-1)
    return np.where(nv >= need, np.where(ok, ua, 0.0).sum(-1) / np.maximum(nv, 1), np.nan)


def piece_sets(K):
    """Прореженные наборы кусков для (6): {число кусков: [наборы номеров]} — каждый k-й кусок, все сдвиги."""
    out = {}
    m = 1
    while m <= K:
        if K % m == 0:
            out[m] = [np.arange(s, K, K // m) for s in range(K // m)]
        m *= 2
    return out


