def _tab(heads, rows):
    """Таблица в лог. heads — столбцы: (заголовок, ширина) или '│' (разделитель групп); rows — строки клеток без
       разделителей. Клетки прижаты вправо; ширина 0 — как есть."""
    def line(cells):
        it = iter(cells)
        return '   ' + ' '.join('│' if h == '│' else f"{next(it):>{h[1]}}" for h in heads)
    print(line([h[0] for h in heads if h != '│']))
    for row in rows:
        print(line(row))


