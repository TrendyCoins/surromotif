def _points(stats):
    """Доля и планка ±2 ошибки по списку групп (в %); группа меньше SCEN['plot_min_n'] окон или без ошибки — пропуск."""
    ok = np.array([bool(s) and s['n'] >= SCEN['plot_min_n'] and bool(np.isfinite(s['se'])) for s in stats])
    y = np.array([100.0 * s['acc'] if o else np.nan for s, o in zip(stats, ok)], dtype=np.float64)
    e = np.array([200.0 * s['se'] if o else np.nan for s, o in zip(stats, ok)], dtype=np.float64)
    return y, e, ok


