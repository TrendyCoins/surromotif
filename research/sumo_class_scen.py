def _sigm(x):
    return 1.0 / (1.0 + np.exp(-np.clip(x, -30, 30)))


def lr_fit(Fm, y, ridge=None, iters=40, chunk=500_000):
    """Логистическая регрессия (метод Ньютона, как lr_fit в SuMo_Pred_D1) на стандартизованных признаках:
       logit = w0 + Σ w_i · (x_i − μ_i) / σ_i; малый ridge — против вырожденных столбцов (свободный член не штрафуется)."""
    ridge = SCEN['lr_ridge'] if ridge is None else ridge
    y = np.asarray(y, dtype=np.float64)
    n, k = Fm.shape
    mu = Fm.mean(axis=0, dtype=np.float64)
    sd = Fm.std(axis=0, dtype=np.float64)
    sd[~(sd > 1e-12)] = 1.0
    w = np.zeros(k + 1)
    ym = min(max(float(y.mean()), 1e-6), 1 - 1e-6)
    w[0] = math.log(ym / (1 - ym))
    reg = ridge * n * np.eye(k + 1)
    reg[0, 0] = 0.0
    it = 0
    for it in range(iters):
        Hm, gr = np.zeros((k + 1, k + 1)), np.zeros(k + 1)
        for a in range(0, n, chunk):
            Z = np.column_stack([np.ones(min(chunk, n - a)), (Fm[a:a + chunk].astype(np.float64) - mu) / sd])
            p = _sigm(Z @ w)
            gr += Z.T @ (p - y[a:a + chunk])
            Hm += (Z * (p * (1 - p))[:, None]).T @ Z
        step = np.linalg.solve(Hm + reg, gr + reg @ w)
        w -= step
        if np.max(np.abs(step)) < 1e-10:
            break
    return {'w': w.tolist(), 'mu': mu.tolist(), 'sd': sd.tolist(), 'iters': it + 1, 'n': int(n)}


def lr_pred(fit, Fm, chunk=500_000):
    w, mu, sd = np.asarray(fit['w']), np.asarray(fit['mu']), np.asarray(fit['sd'])
    out = np.empty(len(Fm))
    for a in range(0, len(Fm), chunk):
        out[a:a + chunk] = w[0] + ((Fm[a:a + chunk].astype(np.float64) - mu) / sd) @ w[1:]
    return out


def _lr_sub(n, rng):
    return np.sort(rng.choice(n, size=SCEN['lr_max'], replace=False)) if n > SCEN['lr_max'] else np.arange(n)


def _crossfit(X, y, first, rng):
    """Прогноз крест-накрест: регрессия учится на одной половине строк (first / не first), прогноз — на другой."""
    z = np.full(len(y), np.nan)
    for tr, te in ((first, ~first), (~first, first)):
        i_tr = np.where(tr)[0]
        i_tr = i_tr[_lr_sub(len(i_tr), rng)]
        if len(i_tr) >= SCEN['min_n'] and te.any():
            z[te] = lr_pred(lr_fit(X[i_tr], y[i_tr]), X[te])
    return z


def lr_source(F, fits=None):
    """Регрессия (3) источника по хвостам. Строка годна, если у окна есть окно «сейчас» в этой части и ход настоящих h баров
       не ноль. Признаки — сводки окна «сейчас» (lrf), цель — «ход по знаку ориентации окна». fits — регрессии другого периода
       (для VAL — обученные на TUNE): тогда здесь только прогноз; None — крест-накрест по половинам периода (обучение на одной
       половине недель, прогноз на другой). Вторая регрессия — с добавленной стрелкой (D со знаком ориентации окна, в своих
       sd), на строках со стрелкой. Возвращает (по хвостам: z, zd — logit «по ходу окна» у строк (NaN — нет), s — знак
       ориентации окна «сейчас» (0 — нет); как обучена) и регрессии на всех строках периода — для другого периода."""
    c, g = F['cols'], F['g']
    rng = np.random.default_rng(SCEN['lr_seed'])
    N = len(g)
    out, fits_all = {'how': 'обучена на TUNE' if fits is not None else HOW_CROSS,
                     'n_feat': int(c['lrf'].shape[1])}, {}
    for j, h in enumerate(SCEN['tails']):
        pw, mv, D = c['pw'][:, j], c['mv'][:, j].astype(np.float64), c['D'][:, j].astype(np.float64)
        rows = np.where((pw >= 0) & (np.abs(mv) > SCEN['zero']))[0]
        z, zd, s_now = np.full(N, np.nan, np.float32), np.full(N, np.nan, np.float32), np.zeros(N, np.int8)
        if len(rows) < 2 * SCEN['min_n']:
            out[h] = {'z': z, 'zd': zd, 's': s_now, 'n': int(len(rows))}
            continue
        p = pw[rows]
        s = c['sg'][p].astype(np.float64)
        X = c['lrf'][p].astype(np.float32)
        y = (np.sign(mv[rows]) == s).astype(np.float64)
        s_now[rows] = s.astype(np.int8)
        sd_d = float(np.nanstd(D[rows]))
        has = np.isfinite(D[rows])
        Xd = np.column_stack([X[has], (D[rows][has] * s[has] / (sd_d if sd_d > 0 else 1.0)).astype(np.float32)])
        yd = y[has]
        if fits is not None and h in fits:
            z[rows] = lr_pred(fits[h]['lr'], X)
            zd[rows[has]] = lr_pred(fits[h]['lrd'], Xd)
        else:
            first = g[rows] < np.median(np.unique(g[rows]))      # первая половина недель периода
            z[rows] = _crossfit(X, y, first, rng)
            zd[rows[has]] = _crossfit(Xd, yd, first[has], rng)
            i_all, i_d = _lr_sub(len(rows), rng), _lr_sub(int(has.sum()), rng)
            fits_all[h] = {'lr': lr_fit(X[i_all], y[i_all]), 'lrd': lr_fit(Xd[i_d], yd[i_d])}
        out[h] = {'z': z, 'zd': zd, 's': s_now, 'n': int(len(rows)), 'base': float(y.mean())}
        del X, Xd
    return out, fits_all


