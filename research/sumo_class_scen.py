def check_first(B, store, part, asset, sums, st, sg4):
    """Сверки (а)–(г) шапки на первом посчитанном ассете части; не прошло — стоп: сценарные окна не те, за кого себя выдают."""
    import torch
    P, L, n, K = B.P, B.L, len(st), SCEN['pieces']
    W, eq = P['W'], torch.equal
    one = np.ones(n, np.float32)
    own, mir = True, True
    for h in SCEN['tails']:
        now1 = st + L - h
        Wp = B.win_splice(h, now1, one, 1.0)
        Xp, Sp = B.inputs(Wp)
        own = own and bool(eq(Wp, W) and eq(Xp, P['X']) and eq(Sp, P['S']))
        mir = mir and bool(eq(B.win_splice(h, now1, one, -1.0), B.win_signs(TL.tail_signs(n, L, h))))
    ev = store.get(part, SCEN['ruler_null'])
    Xn, Sn = B.inputs(B.win_signs(sg4))
    twin = bool(eq(ev['Xn'], Xn) and eq(ev['Sn'], Sn))
    store._set.clear()
    anat, seen = True, 0
    for h in SCEN['tails']:
        plan = piece_plan(sums, st, L, h)
        for k in sorted({0, K - 1}):
            rows = np.where(plan['ok'][:, k])[0]
            if not len(rows):
                continue
            seen += len(rows)
            q0 = np.where(plan['ok'][:, k], plan['q0'][:, k], st + L - 2 * h)
            c = plan['c'][:, k]
            r_t = B._t(rows, np.int64)
            Wu, Wd = B.win_splice(h, q0, c, 1.0)[r_t], B.win_splice(h, q0, c, -1.0)[r_t]
            a = L - h
            idx = B._t(q0[rows] + B.off, np.int64)[:, None] + torch.arange(h, device=W.device)[None, :]
            c_t = B._t(c[rows], np.float32)[:, None]
            ok = eq(Wu[:, :, :a], W[r_t][:, :, :a]) and eq(Wd[:, :, :a], W[r_t][:, :, :a])
            ok = ok and eq(Wu[:, 0, a:], c_t * B.data.r_t[idx]) and eq(Wd[:, 0, a:], -Wu[:, 0, a:])
            ok = ok and eq(Wu[:, 3, a:], c_t * B.data.chan_g_t[idx]) and eq(Wd[:, 3, a:], Wu[:, 3, a:])
            ok = ok and eq(Wd[:, 1:3, a + 1:], -Wu[:, 1:3, a + 1:])
            j0 = P['st_t'][r_t] + a
            for ch, (_, d_) in enumerate(B.data.chan_t):       # стык: сумма двух ориентаций = −2 · сдвиг бара «сейчас»
                two = Wu[:, 1 + ch, a] + Wd[:, 1 + ch, a] + 2.0 * d_[j0]
                ok = ok and bool((two.abs() <= 1e-4 * (1.0 + c_t[:, 0] * B.data.chan_g_t[idx[:, 0]])).all())
            anat = anat and bool(ok) and bool(torch.isfinite(Wu).all() and torch.isfinite(Wd).all())
    chk = {'asset': asset, 'part': part, 'n': n, 'own': own, 'mirror': mir, 'twin': twin, 'anatomy': anat and seen > 0,
           'pieces_seen': seen}
    chk['ok'] = own and mir and twin and chk['anatomy']
    yn = {k: '✅' if chk[k] else '❌' for k in ('own', 'mirror', 'twin', 'anatomy')}
    print(f"   🔎 сверки на {asset} {part} ({n} окон): (а) свой хвост как кусок — настоящее окно бит в бит {yn['own']} | (б) "
          f"его зеркало — окно шага 0 бит в бит {yn['mirror']} | (в) суррогаты линейки = набор проверки пула {yn['twin']} | "
          f"(г) анатомия сценарного окна ({seen} окон с кусками) {yn['anatomy']}")
    if not chk['ok']:
        raise RuntimeError("🍆 АЙ, ОШИБКА! сверка (а) / (б) / (в) / (г) не прошла — сценарные окна не те; стоп до разбора")
    return chk


def asset_ctx(T, pdata, part, a, models):
    """Окна ассета a в части part (набор проверки пула; вызывать внутри floor_override) и всё для счёта сценариев: st —
       начала окон в общем массиве данных, lo — место, от которого взяты ряды кусков r, g (прошлое — только из своей части
       ряда), B — окна и logit, sg4 — знаки суррогата линейки. None — окон меньше, чем берёт Flow."""
    L, data = T.POOL['L'], pdata['data']
    store = T.pool_asset_store(data, L, pdata['sid'][a], pdata['t_cut'])
    n_all = int(len(store.w[part]))
    if n_all < FL.FLOW['min_windows']:
        print(f"   {a:<11} {part}: окон {n_all} < {FL.FLOW['min_windows']} — не считается")
        return None
    P = store.positives(part)
    n = int(len(P['st']))
    if n != n_all:
        raise RuntimeError(f"🍆 АЙ, ОШИБКА! {a} {part}: набор проверки взял подвыборку ({n} из {n_all}) — окна не подряд, "
                           f"линия M не считается; подними DATA['max_eval'] кода обучения")
    st = np.asarray(P['st'], dtype=np.int64)
    seg = int(data.seg0[st[0]])
    if not (data.seg0[st] == seg).all():
        raise RuntimeError(f"🍆 АЙ, ОШИБКА! {a} {part}: окна части лежат в разных кусках ряда")
    lo = max(seg, int(st.min()) - SCEN['band'] - L)
    hi = int(st.max()) + L
    return {'store': store, 'P': P, 'st': st, 'lo': lo, 'seg': seg, 'r': data.r[lo:hi], 'g': data.chan_g[lo:hi],
            'B': TorchBackend(T, data, P, models, L, lo), 'sg4': FL.twin_signs(T, part, n, L, SCEN['ruler_null']).numpy()}


def score_asset(T, pdata, part, a, models, fc, tc, need_check):
    """Один ассет части: сценарии и запись для кэша. fc, tc — кэши Flow и шага 0 для справочных сверок (или None).
       Возвращает (массивы, запись о счёте, сверки или None) — или None, если окон мало."""
    L, data = T.POOL['L'], pdata['data']
    ctx = asset_ctx(T, pdata, part, a, models)
    if ctx is None:
        return None
    store, st, lo, r, g, B, sg4 = (ctx[k] for k in ('store', 'st', 'lo', 'r', 'g', 'B', 'sg4'))
    chk = check_first(B, store, part, a, series_sums(r, g), st - lo, sg4) if need_check else None
    out, stat = score_windows(B, r, g, st - lo, L, sg4)
    out.update({'st': st, 't': np.asarray(data.t[st + L - 1], dtype=np.int64), 'wk': np.asarray(B.P['wk'], dtype=np.int64)})
    flow, tail = None, None
    fr = fc['res'].get(a) if fc is not None else None
    if fr is not None and np.array_equal(fr['t'].astype(np.int64), out['t']):
        d = np.concatenate([np.abs(out[f"{t}__sp"].astype(np.float64) - fr[f"{t}__sp"].astype(np.float64))
                            for t in B.tags if f"{t}__sp" in fr] or [np.zeros(0)])
        if len(d):
            flow = {'n': int(len(d)), 'med': float(np.median(d)), 'max': float(d.max()),
                    'big': int((d > SCEN['chk_big']).sum())}
    tr = tc['res'].get(a) if tc is not None else None
    if tr is not None and np.array_equal(tr['st'].astype(np.int64), st):
        d = [np.abs(out['orc'][:, j] - np.mean([tr[f"{t}__sp"].astype(np.float64) - tr[f"{t}__t{h}"].astype(np.float64)
                                               for t in B.tags], axis=0))
             for j, h in enumerate(SCEN['tails']) if all(f"{t}__t{h}" in tr for t in B.tags)]
        jj = [(j, TL.TAIL['tails'].index(h)) for j, h in enumerate(SCEN['tails']) if h in TL.TAIL['tails']]
        mv = max([float(np.max(np.abs(out[k][:, j] - tr[k][:, i]))) for j, i in jj for k in ('mv', 'pv')] or [math.nan])
        if d:
            tail = {'n': int(sum(len(v) for v in d)), 'max': float(max(v.max() for v in d)), 'mv': mv}
    store._pos.clear()
    store._set.clear()
    return out, {'stat': stat, 'flow': flow, 'tail': tail, 'n': len(st)}, chk


def sum_refs(infos):
    """Итог справочных сверок части по записям ассетов: logit настоящих окон против кэша Flow; оракул и ходы против
       кэша шага 0."""
    fl = [x['flow'] for x in infos if x.get('flow')]
    tl = [x['tail'] for x in infos if x.get('tail')]
    flow = {'n': 0}
    if fl:
        n = sum(x['n'] for x in fl)
        flow = {'n': n, 'med': max(x['med'] for x in fl), 'max': max(x['max'] for x in fl),
                'big': sum(x['big'] for x in fl) / n}
        flow['exact'] = flow['max'] == 0.0
        flow['ok'] = flow['med'] <= SCEN['chk_med'] and flow['big'] <= SCEN['chk_share']
    tail = {'n': sum(x['n'] for x in tl), 'max': max(x['max'] for x in tl), 'mv': max(x['mv'] for x in tl)} if tl else {'n': 0}
    return flow, tail


