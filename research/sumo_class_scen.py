def build_frame(C, src):
    """Строки источника — все окна части у всех ассетов кэша C. logit — средний по сидам источника; линейка — квантили logit
       суррогатов sflip4 источника; линия M — по окнам ассета подряд (формула сайта). Столбцы по хвостам — (окна, хвосты):
       D — стрелка (средняя по сидам), D0, D1 … — стрелка каждого сида, Draw, orc, mv, pv, lc, lv — как в кэше; bk — корзина
       цвета окна «сейчас» (−1 — показания нет); pw — номер строки окна «сейчас» (окно того же ассета, которое кончается на
       h баров раньше; −1 — такого нет). Столбцы по окнам: ia — номер ассета, t — время последнего бара, qt — квартал, sg —
       знак ориентации окна, sp, s4 — logit настоящего окна и его суррогата линейки, a, ub, lrf — как в кэше. g — номер недели
       строки, G — недель; rows — строки каждого ассета."""
    tags = [it['tag'] for it in C['meta']['items'] if it['src'] == src]
    res = C['res']
    assets = [a for a in C['meta']['assets'] if a in res and tags and all(f"{t}__sp" in res[a] for t in tags)]
    if not assets:
        return None

    def avg(a, key):
        return np.mean([res[a][f"{t}__{key}"].astype(np.float64) for t in tags], axis=0)

    q, zk = FL.ruler(np.concatenate([avg(a, 's4') for a in assets]))
    tails, cols, rows, base = SCEN['tails'], {}, [], 0

    def put(k, v):
        cols.setdefault(k, []).append(v)

    for ia, a in enumerate(assets):
        r = res[a]
        n = len(r['st'])
        sp = avg(a, 'sp')
        lm = FL.line_m(FL.to_z(sp, q, zk))
        st = r['st'].astype(np.int64)
        put('sp', sp.astype(np.float32))
        put('s4', avg(a, 's4').astype(np.float32))
        put('ia', np.full(n, ia, dtype=np.int16))
        put('wk', r['wk'].astype(np.int64))
        put('t', r['t'].astype(np.int64))
        put('qt', (r['t'].astype('datetime64[ns]').astype('datetime64[M]').astype(np.int64) // 3).astype(np.int32))
        Ds = [r[f"{t}__D"] for t in tags]
        put('D', np.mean(Ds, axis=0).astype(np.float32))
        for i, d in enumerate(Ds):
            put(f"D{i}", d)
        for k in ('orc', 'mv', 'pv', 'lc', 'lv', 'a', 'ub', 'lrf', 'sg') + (('Draw',) if 'Draw' in r else ()):
            put(k, r[k])
        pw = np.stack([TL.prev_window(st, h) for h in tails], axis=1)
        put('bk', np.stack([TL.basket_of(np.where(pw[:, j] >= 0, lm[np.maximum(pw[:, j], 0)], np.nan))
                            for j in range(len(tails))], axis=1))
        put('pw', np.where(pw >= 0, pw + base, -1).astype(np.int32))
        rows.append((base, base + n))
        base += n
        res[a] = None                                      # строки ассета собраны — массивы кэша больше не нужны
    for k in list(cols):
        cols[k] = np.concatenate(cols[k])
    wk_u, g = np.unique(cols.pop('wk'), return_inverse=True)
    return {'src': src, 'tags': tags, 'assets': assets, 'cols': cols, 'g': g.astype(np.int64), 'G': int(len(wk_u)),
            'rows': rows, 'stat': C['meta'].get('stat')}


