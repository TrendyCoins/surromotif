def _acct(x):
    """«Доля (t)»."""
    return f"{_acc(x)} ({_f(x['t'], '+.1f')})" if x and x['n'] >= SCEN['min_n'] else '—'


def _accn(x):
    """«Доля (тыс. окон)»."""
