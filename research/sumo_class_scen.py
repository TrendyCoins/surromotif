def run_tf(tf, caches, show=True):
    """Все числа одного ТФ: caches — {источник: кэш части}. Регрессия VAL — обученная на TUNE (нет кэша TUNE — крест-накрест
       на самом VAL). Возвращает ({источник: числа}, вердикт)."""
    res, fits = {}, None
    for src in SCEN['sources']:
        C = caches.get(src)
        if C is None:
            continue
        F = build_frame(C, src)
        if F is None:
            print(f"\n⚪ {tf} {TL.SRC_RU[src]}: в кэше нет моделей источника — пропуск")
            continue
        lr, fits_src = lr_source(F, fits if src == 'confirm' else None)
        if src == 'search':
            fits = fits_src
        res[src] = eval_frame(F, lr)
        res[src]['lr_w'] = {h: x['lr']['w'] for h, x in fits_src.items()}     # веса регрессии, обученной на этом периоде
        del F, lr
        if show:
            show_source(tf, src, res[src])
    return res, verdict_tf(res)


