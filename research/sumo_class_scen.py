def hit(x):
    """Попадание по запасу x (сторона × знак хода): > 0 — да, 0 — пополам."""
    return (x > 0) + 0.5 * (x == 0)


def se_clusters(v, g, G):
    """Ошибка суммы вкладов строк v (вклады в сумме дают ноль). Строки одной недели календаря — один кластер (все ассеты
       вместе: рынки синхронны); то же считается блоками из 4 недель, и берётся бо́льшая из двух ошибок (режимы рынка и
       горизонты в десятки баров держатся дольше недели; так же в D1). Блоков меньше SCEN['min_blocks'] — только недели.
       Возвращает (ошибка, недель со строками)."""
    s = np.bincount(g, weights=v, minlength=G)
    has = np.bincount(g, minlength=G) > 0
    Gn = int(has.sum())
    if Gn < 2:
        return math.nan, Gn
    se = math.sqrt(Gn / (Gn - 1) * float(np.sum(s * s)))
    blk = np.arange(G) // 4
    sb = np.bincount(blk, weights=s)
    Bn = int((np.bincount(blk, weights=has) > 0).sum())
    if Bn >= SCEN['min_blocks']:
        se = max(se, math.sqrt(Bn / (Bn - 1) * float(np.sum(sb * sb))))
    return se, Gn


def mean_se(y, g, G):
    """Среднее y и его ошибка (se_clusters): (среднее, ошибка, строк, недель); у группы меньше SCEN['min_n'] окон или
       SCEN['min_weeks'] недель ошибки нет (она была бы занижена)."""
    y = np.asarray(y, dtype=np.float64)
    n = len(y)
    if n == 0:
        return math.nan, math.nan, 0, 0
    m = float(y.mean())
    se, Gn = se_clusters((y - m) / n, g, G)
    return m, (se if TL.enough(n, Gn) else math.nan), n, Gn


def acc_of(m, g, G):
    """Доля попаданий по запасу m (> 0 — попадание, 0 — пополам), её ошибка и t против 50%."""
    a, se, n, Gn = mean_se(hit(np.asarray(m, dtype=np.float64)), g, G)
    return {'n': n, 'acc': a, 'se': se, 't': TL._t(a, se, 0.5), 'weeks': Gn}


def cl_diff2(y1, m1, y2, m2, g, G):
    """Разность среднего y1 в группе m1 и среднего y2 в группе m2 (маски строк, группы могут пересекаться) и её ошибка:
       неделя входит в обе суммы разом — общий сдвиг недели в разности сокращается."""
    n1, n2 = int(m1.sum()), int(m2.sum())
    if n1 == 0 or n2 == 0:
        return {'d': math.nan, 'se': math.nan, 't': math.nan}
    a, b = float(y1[m1].mean()), float(y2[m2].mean())
    v = np.zeros(len(g))
    v[m1] += (y1[m1] - a) / n1
    v[m2] -= (y2[m2] - b) / n2
    se, _ = se_clusters(v, g, G)
    w1, w2 = int((np.bincount(g[m1], minlength=G) > 0).sum()), int((np.bincount(g[m2], minlength=G) > 0).sum())
    if not (TL.enough(n1, w1) and TL.enough(n2, w2)):
        se = math.nan
    return {'d': a - b, 'se': se, 't': TL._t(a - b, se)}


def paired(y1, y2, g, G):
    """Разность средних двух мерок на одних и тех же строках, её ошибка и t."""
    d, se, n, _ = mean_se(np.asarray(y1, dtype=np.float64) - np.asarray(y2, dtype=np.float64), g, G)
    return {'d': d, 'se': se, 't': TL._t(d, se), 'n': n}


def conf_groups(conf, m, g, G):
    """(2): доля попаданий (запас m) по группам уверенности conf — SCEN['groups'] равных по числу окон групп (от самых
       неуверенных к самым уверенным) и верхние доли SCEN['tops']."""
    ng = SCEN['groups']
    gi = np.searchsorted(np.quantile(conf, np.linspace(0, 1, ng + 1)[1:-1]), conf, side='right')
    groups = [acc_of(m[gi == i], g[gi == i], G) for i in range(ng)]
    tops = {}
    for q in SCEN['tops']:
        top = conf >= np.quantile(conf, 1 - q)
        tops[q] = acc_of(m[top], g[top], G)
    return groups, tops


def duel(ma, mb_, g, G):
    """Два правила на одних строках (запасы ma, mb_; строки, где у какого-то стороны нет, уже убраны): согласие и кто прав
       в спорах — доля споров, где право первое."""
    agree = (ma > 0) == (mb_ > 0)
    dis = acc_of(ma[~agree], g[~agree], G)
    return {'agree': float(agree.mean()) if len(agree) else math.nan, 'dis_n': dis['n'], 'dis': dis['acc'], 'dis_t': dis['t']}


def placebo_z(F, j):
    """(9): сторона стрелки против хода той же монеты через k недель (k — из SCEN['placebo_shifts']): доля попаданий и z
       против 50% у каждого сдвига. Час и день недели у стрелки и хода те же; связь с ближайшим будущим порвана. Назад —
       не ближе 2 недель: ход недельной давности на 1H лежит в прошлом, которое стрелка видит (её куски — оттуда)."""
    c, g, G = F['cols'], F['g'], F['G']
    D, mv, t = c['D'][:, j].astype(np.float64), c['mv'][:, j].astype(np.float64), c['t']
    out = []
    for k in SCEN['placebo_shifts']:
        mv2 = np.zeros(len(D))
        for a0, a1 in F['rows']:
            ta = t[a0:a1]
            jj = np.clip(np.searchsorted(ta, ta + k * TL.WEEK_NS), 0, len(ta) - 1)
            mv2[a0:a1] = np.where(ta[jj] == ta + k * TL.WEEK_NS, mv[a0:a1][jj], 0.0)
        ok = np.isfinite(D) & (np.abs(mv2) > SCEN['zero'])
        x = acc_of(D[ok] * np.sign(mv2[ok]), g[ok], G)
        out.append({'k': k, 'n': x['n'], 'acc': x['acc'], 'z': x['t']})
    return out


def rule_pass(arrow, diff):
    """Правило (4) на одном срезе: стрелка точнее регрессии на rule_gain и на rule_t ошибок и сама выше 50% на rule_t ошибок."""
    t = SCEN['rule_t']
    return bool(np.isfinite(diff['t']) and np.isfinite(arrow['t']) and diff['d'] >= SCEN['rule_gain'] and diff['t'] >= t
                and arrow['t'] >= t)


def eval_tail(F, lr, j):
    """Все числа одного хвоста источника — разделы (1)–(10) шапки. None — стрелок слишком мало."""
    c, g, G, names, K = F['cols'], F['g'], F['G'], F['assets'], SCEN['pieces']
    D, mv = c['D'][:, j].astype(np.float64), c['mv'][:, j].astype(np.float64)
    truth = np.abs(mv) > SCEN['zero']
    rb = np.where(truth & np.isfinite(D))[0]
    if len(rb) < 2 * SCEN['min_n']:
        return None
    Db, sgn, gb = D[rb], np.sign(mv[rb]), g[rb]
    m = Db * sgn                                           # запас стрелки: > 0 — попала
    y = hit(m)
    x = {'n_truth': int(truth.sum()), 'arrow': acc_of(m, gb, G), 'oracle': acc_of(c['orc'][rb, j].astype(np.float64), gb, G)}
    up_a, up_t = float((Db > 0).mean()), float((sgn > 0).mean())
    x['base'] = {'up_arrow': up_a, 'up_truth': up_t, 'blind': up_a * up_t + (1 - up_a) * (1 - up_t)}
    x['groups'], x['tops'] = conf_groups(np.abs(Db), m, gb, G)
    # (3) регрессия — на окнах, где есть и стрелка, и регрессия
    x['lr'] = None
    z, s_now = lr[SCEN['tails'][j]]['z'][rb].astype(np.float64), lr[SCEN['tails'][j]]['s'][rb].astype(np.float64)
    cm = np.isfinite(z) & (s_now != 0)
    if cm.sum() >= 2 * SCEN['min_n']:
        ma, gc = m[cm], gb[cm]
        ml = z[cm] * s_now[cm] * sgn[cm]                   # запас регрессии в тех же направлениях
        mld = lr[SCEN['tails'][j]]['zd'][rb].astype(np.float64)[cm] * s_now[cm] * sgn[cm]
        q = SCEN['rule_top']
        ta = np.abs(Db[cm]) >= np.quantile(np.abs(Db[cm]), 1 - q)
        tl = np.abs(z[cm]) >= np.quantile(np.abs(z[cm]), 1 - q)
        L_ = {'n': int(cm.sum()), 'arrow': acc_of(ma, gc, G), 'lr': acc_of(ml, gc, G), 'diff': paired(hit(ma), hit(ml), gc, G),
              'arrow_top': acc_of(ma[ta], gc[ta], G), 'lr_top': acc_of(ml[tl], gc[tl], G),
              'diff_top': cl_diff2(hit(ma), ta, hit(ml), tl, gc, G), **duel(ma, ml, gc, G)}
        okd = np.isfinite(mld)
        L_['lrd'] = acc_of(mld[okd], gc[okd], G)
        L_['lrd_diff'] = paired(hit(mld[okd]), hit(ml[okd]), gc[okd], G)
        L_['rule'] = {'all': rule_pass(L_['arrow'], L_['diff']), 'top': rule_pass(L_['arrow_top'], L_['diff_top']),
                      'knows': any(np.isfinite(v) and v >= SCEN['rule_t'] for v in (L_['arrow']['t'], L_['arrow_top']['t']))}
        x['lr'] = L_
    # (5) цвет «сейчас»
    bk = c['bk'][rb, j]
    masks = {name: np.isin(bk, ks) for name, ks, _ in TL.SIDES}
    x['sides'] = {name: acc_of(m[mk], gb[mk], G) for name, mk in masks.items()}
    x['baskets'] = [acc_of(m[bk == b], gb[bk == b], G) for b in range(5)]
    x['no_line'] = int((bk < 0).sum())
    x['orange_grey'] = cl_diff2(y, masks['orange'], y, masks['grey'], gb, G)
    # (6) куски
    a = c['a'][rb, j].astype(np.float32)
    okp = np.isfinite(a)
    nv = okp.sum(axis=1)
    u = np.where(((c['ub'][rb, j][:, None] >> np.arange(K)[None, :]) & 1) > 0, 1.0, -1.0).astype(np.float32)
    ua = u * a
    x['kcurve'] = {}
    for mk, sets in piece_sets(K).items():
        need, hs, ns = max(1, -(-mk * SCEN['min_valid'] // K)), 0.0, 0
        for idx in sets:
            Dm = arrow_mean(ua[:, idx], need)
            ok = np.isfinite(Dm)
            hs += float(hit(Dm[ok] * sgn[ok]).sum())
            ns += int(ok.sum())
        x['kcurve'][mk] = hs / max(ns, 1)
    maj = np.where(okp, np.sign(ua), 0.0).sum(axis=1)       # стрелка «по голосам»: за какую сторону больше кусков
    x['majority'] = acc_of((maj * sgn)[maj != 0], gb[maj != 0], G)
    same = ((np.sign(ua) == np.sign(Db)[:, None]) & okp).sum(axis=1) / np.maximum(nv, 1)
    x['votes'] = {k_: acc_of(m[mk], gb[mk], G) for k_, mk in (('all', same == 1), ('most', (same >= 0.75) & (same < 1)),
                                                                  ('split', same < 0.75))}
    x['pieces'] = {'valid': float(nv.mean()), 'lc_sd': float(np.nanstd(c['lc'][rb, j]))}
    # (7) размер
    x['raw'] = None
    if 'Draw' in c:
        Dr = c['Draw'][rb, j].astype(np.float64)
        ok = np.isfinite(Dr)
        mr = Dr[ok] * sgn[ok]
        x['raw'] = {'acc': acc_of(mr, gb[ok], G), 'diff': paired(y[ok], hit(mr), gb[ok], G),
                    'agree': float((np.sign(Dr[ok]) == np.sign(Db[ok])).mean())}
    # (8) простые правила
    pv = c['pv'][rb, j].astype(np.float64)
    ok = np.abs(pv) > SCEN['zero']
    mp = -np.sign(pv[ok]) * sgn[ok]
    x['pullback'] = {'acc': acc_of(mp, gb[ok], G), **duel(m[ok], mp, gb[ok], G)}
    su = np.where(okp, u, 0.0).sum(axis=1)
    ok = su != 0
    md = su[ok] * sgn[ok]
    x['drift'] = {'acc': acc_of(md, gb[ok], G), **duel(m[ok], md, gb[ok], G)}
    # (9) контроли
    pz = placebo_z(F, j)
    x['placebo'] = {'shifts': pz, 'acc': float(np.nanmean([v['acc'] for v in pz])), 'z': [v['z'] for v in pz]}
    sh, se, _, _ = mean_se(np.where(okp, a > 0, False).sum(axis=1) / np.maximum(nv, 1), gb, G)
    x['asis'] = {'share': sh, 'se': se, 't': TL._t(sh, se, 0.5)}
    # (11) уровень правдоподобия: средний logit настоящего окна, окна с зеркальным хвостом, сценарного окна и суррогата
    real, null = float(c['sp'][rb].mean(dtype=np.float64)), float(c['s4'][rb].mean(dtype=np.float64))
    lvl = {'real': real, 'mirror': real - float(c['orc'][rb, j].mean(dtype=np.float64)),
           'scen': float(np.nanmean(c['lv'][rb, j].astype(np.float64))), 'null': null}
    gap = real - null
    x['level'] = {**lvl, 'mirror_gap': (real - lvl['mirror']) / gap if gap > 0.05 else math.nan,
                  'scen_gap': (real - lvl['scen']) / gap if gap > 0.05 else math.nan}
    # (10) устойчивость
    ia, n_as = c['ia'][rb], len(names)
    btc = ia == (names.index('BTCUSDT') if 'BTCUSDT' in names else -1)
    site = np.isin(ia, [i for i, a_ in enumerate(names) if a_ in SCEN['site']])
    cnt = np.bincount(ia, minlength=n_as)
    pa = (np.bincount(ia, weights=y, minlength=n_as) / np.maximum(cnt, 1))[cnt >= SCEN['min_n']]
    x['assets'] = {'btc': acc_of(m[btc], gb[btc], G), 'site': acc_of(m[site], gb[site], G),
                   'min': float(pa.min()) if len(pa) else math.nan, 'med': float(np.median(pa)) if len(pa) else math.nan,
                   'max': float(pa.max()) if len(pa) else math.nan, 'above': int((pa > 0.5).sum()), 'of': int(len(pa))}
    _, qi = np.unique(c['qt'][rb], return_inverse=True)
    qn = np.bincount(qi)
    pq = (np.bincount(qi, weights=y) / qn)[qn >= SCEN['min_n']]
    x['quarters'] = {'acc': pq.tolist(), 'above': int((pq > 0.5).sum()), 'of': int(len(pq))}
    Ds = [c[f"D{i}"][rb, j].astype(np.float64) for i in range(len(F['tags']))]
    x['seeds'] = {'acc': [float(hit(d_ * sgn).mean()) for d_ in Ds], 'same': math.nan, 'corr': math.nan}
    if len(Ds) >= 2:
        x['seeds']['same'] = float((np.sign(Ds[0]) == np.sign(Ds[1])).mean())
        x['seeds']['corr'] = float(np.corrcoef(Ds[0], Ds[1])[0, 1])
    return x


def eval_frame(F, lr):
    out = {'tags': F['tags'], 'assets': len(F['assets']), 'n': int(len(F['g'])), 'weeks': F['G'], 'stat': F['stat'],
           'lr_how': lr['how'], 'lr_feat': lr['n_feat'], 'tails': {}}
    for j, h in enumerate(SCEN['tails']):
        x = eval_tail(F, lr, j)
        if x is not None:
            out['tails'][h] = x
    z = [v for x in out['tails'].values() for v in x['placebo']['z'] if np.isfinite(v)]
    out['placebo'] = {'n': len(z), 'mean': float(np.mean(z)) if z else math.nan,
                      'sd': float(np.std(z)) if len(z) > 2 else math.nan}
    return out


def verdict_tf(res, src='confirm'):
    """Правило (4) одного ТФ по источнику src (решает VAL — 'confirm'; TUNE — справочно): 'valuable' — стрелка ценна;
       'known' — стрелка выше 50%, но не точнее регрессии (знание есть и без модели); 'nothing' — стрелка от монетки не
       отличается; 'no_val' — источник не посчитан или у него нет регрессии."""
    R = res.get(src)
    rows = [(h, x['lr']['rule']) for h, x in (R['tails'].items() if R else ()) if x.get('lr')]
    if not rows:
        return {'state': 'no_val', 'where': []}
    where = [(h, k) for h, r in rows for k in ('all', 'top') if r[k]]
    state = 'valuable' if where else ('known' if any(r['knows'] for _, r in rows) else 'nothing')
    return {'state': state, 'where': where}


