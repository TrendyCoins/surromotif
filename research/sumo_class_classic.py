        real = market_events(P, rd, ctx, bar_ns, '5M')
        rand, same = [], True
        for j in range(4):
            sg = LV.rand_signs('ST', j, 0, P['T'], rand_from=P['T'][0])
            Pm = LV.mirror_bars(P, sg)
            same &= np.array_equal(flat_share(Pm['c']), flat_share(P['c']), equal_nan=True)
            same &= np.allclose(vol_level(Pm), vol_level(P), rtol=1e-9, equal_nan=True)
            rand.append(market_events(Pm, rd, ctx, bar_ns, '5M'))
        wk_all = np.concatenate([real['B3']['wk']] + [r['B3']['wk'] for r in rand])
        B = LV.boot_setup(wk_all, [3], 300)
