    bar_ns = 15 * 60 * 10 ** 9
    n = 60_000
    lv = lfilter([1.0], [1.0, -0.995], rng.normal(0, 0.07, n))
    sig = np.exp(lv - lv.mean())
    steps = sig * ar1(rng.standard_normal(n), np.full(n, -0.3))
    steps[rng.random(n) < 0.02] = 0.0
    P = LV.synth_ohlc(steps, rng, sig, 0.6, bar_ns=bar_ns)
    keep = dict(LV.LEV)
    LV.LEV.update({'tune_start': str(pd.Timestamp(P['T'][5000])), 'val_start': str(pd.Timestamp(P['T'][32_000]))})
