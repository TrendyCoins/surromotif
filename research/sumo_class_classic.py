def ema(x, span):
    """EMA: alpha = 2 / (span + 1), старт — с первого значения (как ta.ema)."""
    x = np.asarray(x, dtype=np.float64)
    out = np.empty(len(x))
    if not len(x):
        return out
    a = 2.0 / (span + 1.0)
    out[0] = x[0]
    if len(x) > 1:
        out[1:], _ = lfilter([a], [1.0, -(1.0 - a)], x[1:], zi=[(1.0 - a) * x[0]])
    return out


def rma(x, n, i0):
    """Средняя Уайлдера (alpha = 1 / n) ряда x с бара i0: на баре i0 + n − 1 — среднее x[i0 : i0 + n], дальше
       y_t = y_(t−1) + (x_t − y_(t−1)) / n (как ta.rma). До бара i0 + n − 1 — NaN."""
    x = np.asarray(x, dtype=np.float64)
    out = np.full(len(x), np.nan)
    j = i0 + n - 1
    if len(x) <= j:
        return out
    out[j] = x[i0:j + 1].mean()
    if len(x) > j + 1:
        a = 1.0 / n
        out[j + 1:], _ = lfilter([a], [1.0, -(1.0 - a)], x[j + 1:], zi=[(1.0 - a) * out[j]])
    return out


def rsi(c, n):
    """RSI Уайлдера по close (как ta.rsi): средний рост up и среднее падение dn за n баров (средняя Уайлдера); dn = 0 — 100,
       up = 0 — 0, иначе 100 − 100 / (1 + up / dn). NaN до бара n."""
    c = np.asarray(c, dtype=np.float64)
    d = np.r_[0.0, np.diff(c)]
    up = rma(np.maximum(d, 0.0), n, 1)
    dn = rma(np.maximum(-d, 0.0), n, 1)
    with np.errstate(divide='ignore', invalid='ignore'):
        r = 100.0 - 100.0 / (1.0 + up / dn)
    r = np.where(dn == 0, 100.0, np.where(up == 0, 0.0, r))
    r[~np.isfinite(up) | ~np.isfinite(dn)] = np.nan
    return r


def _roll(x, w, how):
    """Скользящий max / min окна из w баров, кончающегося на баре (NaN, пока баров меньше w)."""
    return getattr(pd.Series(np.asarray(x, dtype=np.float64)).rolling(w, min_periods=w), how)().to_numpy()


def _roll_mean_std(x, w):
    """Скользящие среднее и стандартное отклонение (без поправки n − 1) окна из w баров, кончающегося на баре, — двумя
       проходами по каждому окну, как np.std (онлайн-формулы pandas на ценах с большим средним теряют знаки); NaN, пока баров
       меньше w."""
    x = np.asarray(x, dtype=np.float64)
    n = len(x)
    mu, sd = np.full(n, np.nan), np.full(n, np.nan)
    if n < w:
        return mu, sd
    V = np.lib.stride_tricks.sliding_window_view(x, w)
    for a in range(0, len(V), 200_000):
        blk = V[a:a + 200_000]
        m = blk.mean(axis=1)
        mu[w - 1 + a:w - 1 + a + len(blk)] = m
        sd[w - 1 + a:w - 1 + a + len(blk)] = np.sqrt(((blk - m[:, None]) ** 2).mean(axis=1))
    return mu, sd


def _prev(x):
    """Значение на прошлом баре (у первого — NaN)."""
    return np.r_[np.nan, np.asarray(x, dtype=np.float64)[:-1]]


def signals(P):
    """События шести сигналов на куске P (c, h, l, atr): {код: (бары t, ставка d: +1 / −1, сила)}. Индикаторы — с бара warm и
       только там, где ATR годен."""
    c, h, l, atr = (np.asarray(P[k], dtype=np.float64) for k in ('c', 'h', 'l', 'atr'))
    n = len(c)
    ok = (np.arange(n) >= CL['warm']) & np.isfinite(atr) & (atr > 0)
    dc = np.r_[np.nan, np.diff(c)]
    out = {}
    with np.errstate(invalid='ignore', divide='ignore'):
        # A1: откат бара >= 1 ATR
        m = ok & (np.abs(dc) >= CL['bar_atr'] * atr) & (dc != 0)
        t = np.flatnonzero(m)
        out['A1'] = (t, -np.sign(dc[t]), np.abs(dc[t]) / atr[t])
        # A2: RSI вошёл за 30 / 70
        nr, lo, hi = CL['rsi']
        R = rsi(c, nr)
        Rp = _prev(R)
        dn = ok & (R < lo) & (Rp >= lo)
        up = ok & (R > hi) & (Rp <= hi)
        t = np.flatnonzero(dn | up)
        out['A2'] = (t, np.where(dn[t], 1.0, -1.0), np.where(dn[t], lo - R[t], R[t] - hi))
        # A3: выход за полосу Боллинджера
        w, k = CL['bb']
        mid, sd = _roll_mean_std(c, w)
        top, bot = mid + k * sd, mid - k * sd
        a_ = ok & (sd > 0) & (c > top) & (_prev(c) <= _prev(top))
        b_ = ok & (sd > 0) & (c < bot) & (_prev(c) >= _prev(bot))
        t = np.flatnonzero(a_ | b_)
        out['A3'] = (t, np.where(a_[t], -1.0, 1.0), np.abs(c[t] - mid[t]) / sd[t] - k)
        # B1: пробой канала Дончиана (high / low прошлых баров)
        wd = CL['don']
        hh, ll = _prev(_roll(h, wd, 'max')), _prev(_roll(l, wd, 'min'))
        bu = ok & (c > hh) & (_prev(c) <= _prev(hh))
        bd = ok & (c < ll) & (_prev(c) >= _prev(ll))
        t = np.flatnonzero(bu | bd)
        out['B1'] = (t, np.where(bu[t], 1.0, -1.0), np.where(bu[t], c[t] - hh[t], ll[t] - c[t]) / atr[t])
        # B2: MACD пересёк сигнальную
        f_, s_, g_ = CL['macd']
        line = ema(c, f_) - ema(c, s_)
        hist = line - ema(line, g_)
        hp = _prev(hist)
        cr = ok & (hist != 0) & (hp != 0) & np.isfinite(hp) & (np.sign(hist) != np.sign(hp))
        t = np.flatnonzero(cr)
        out['B2'] = (t, np.sign(hist[t]), np.abs(line[t]) / atr[t])
        # B3: знак хода за 64 бара — каждый бар
        L = CL['mom']
        mom = np.r_[np.full(L, np.nan), c[L:] - c[:-L]] if n > L else np.full(n, np.nan)
        mm = ok & np.isfinite(mom) & (mom != 0)
        t = np.flatnonzero(mm)
        out['B3'] = (t, np.sign(mom[t]), np.abs(mom[t]) / (math.sqrt(L) * atr[t]))
    return {k: (t.astype(np.int64), d.astype(np.int8), s.astype(np.float64)) for k, (t, d, s) in out.items()}


