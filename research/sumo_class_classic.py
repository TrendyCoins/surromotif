def load_tf_caches(tf):
    """Кэши ТФ как в 'run' Levels: Flow (logit реала, линейка sflip4 источника) и Levels (logit случайных рынков). Нет кэша —
       (None, причина). Иначе — ({источник: (C, Z, q, zk, lg, tags)}, ассеты: BTC и пул — в порядке Levels)."""
    caches, assets = {}, None
    for src, part in CL['periods'].items():
        C, Z = FL.load_cache(tf, part), LV.load_lev_cache(tf, part)
        if C is None:
            return None, f"нет кэша Flow ({tf} {part}) — сначала 'score' Flow"
        if Z is None:
            return None, f"нет кэша Levels ({tf} {part}) — сначала Levels MODE 'score', JOB '{tf}' (GPU)"
        if Z['meta'].get('fp') != C['meta'].get('fp'):
            raise ValueError(f"🍆 АЙ, ОШИБКА! {tf} {part}: кэши Flow и Levels — с разных данных")
        lg, tags = FL.src_logits(C, src)
        if not lg or set(tags) != set(Z['meta']['tags']):
            raise ValueError(f"🍆 АЙ, ОШИБКА! {tf} {part}: модели кэшей Flow ({tags}) и Levels ({Z['meta']['tags']}) разные")
        q, zk = FL.ruler(np.concatenate([x['s4'] for x in lg.values()]))
        for a in list(lg):
            C['res'][a] = {'t': C['res'][a]['t']}
        caches[src] = (C, Z, q, zk, lg, tags)
        chk = Z['meta'].get('check', {})
        print(f"🎨 {tf} {src}: модели {', '.join(tags)} | ассетов {len(lg)} | сверки 'score' Levels: "
              f"{'✅' if chk.get('ok') else '❌'} ({chk.get('asset')})")
        assets = set(lg) if assets is None else assets & set(lg)
    order = [a for a in LV.ASSETS if a in assets] + sorted(a for a in assets if a not in LV.ASSETS)
    return caches, order


def run_tf(tf):
    """'run' одного ТФ: события всех ассетов (реал и случайные рынки), статистика, печать. Нет кэша — (None, причина)."""
    t1 = time.time()
    caches, assets = load_tf_caches(tf)
    if caches is None:
        return None, assets
    acc = {k: {'real': [], 'rand': []} for k in SIGNALS}
    info = {}
    for ia, a in enumerate(assets):
        bars = LV.load_asset(a, tf)
        rdg = LV.readings_asset(a, tf, bars, caches, CL['n_rand'])
        info[a] = asset_events(a, ia, tf, bars, rdg, CL['n_rand'], acc)
