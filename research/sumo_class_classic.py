def direct_indicators(P):
    """Индикаторы и события — прямым счётом бар за баром (стенд)."""
    c, h, l, atr = (np.asarray(P[k], dtype=np.float64) for k in ('c', 'h', 'l', 'atr'))
    n = len(c)
    nr, lo, hi = CL['rsi']
    # RSI Уайлдера
    up = np.full(n, np.nan)
    dn = np.full(n, np.nan)
    g = [max(c[i] - c[i - 1], 0.0) for i in range(1, n)]
    s = [max(c[i - 1] - c[i], 0.0) for i in range(1, n)]
    up[nr], dn[nr] = np.mean(g[:nr]), np.mean(s[:nr])
    for i in range(nr + 1, n):
        up[i] = up[i - 1] + (g[i - 1] - up[i - 1]) / nr
        dn[i] = dn[i - 1] + (s[i - 1] - dn[i - 1]) / nr
    R = np.full(n, np.nan)
    for i in range(nr, n):
        R[i] = 100.0 if dn[i] == 0 else (0.0 if up[i] == 0 else 100.0 - 100.0 / (1.0 + up[i] / dn[i]))

    def ema_d(x, span):
        a = 2.0 / (span + 1.0)
        y = np.empty(len(x))
        y[0] = x[0]
        for i in range(1, len(x)):
            y[i] = a * x[i] + (1 - a) * y[i - 1]
        return y
    w, k = CL['bb']
    wd = CL['don']
    line = ema_d(c, CL['macd'][0]) - ema_d(c, CL['macd'][1])
    hist = line - ema_d(line, CL['macd'][2])
    ev = {kk: ([], [], []) for kk in SIGNALS}

    def add(kk, t, d, st):
        ev[kk][0].append(t)
        ev[kk][1].append(d)
        ev[kk][2].append(st)
    mid = np.full(n, np.nan)
    sd = np.full(n, np.nan)
    for i in range(w - 1, n):
        mid[i] = np.mean(c[i - w + 1:i + 1])
        sd[i] = np.std(c[i - w + 1:i + 1])
    hh = np.full(n, np.nan)
    ll = np.full(n, np.nan)
    for i in range(wd, n):
        hh[i], ll[i] = h[i - wd:i].max(), l[i - wd:i].min()
    for t in range(max(CL['warm'], 1), n):
        if not (np.isfinite(atr[t]) and atr[t] > 0):
            continue
        dc = c[t] - c[t - 1]
        if abs(dc) >= CL['bar_atr'] * atr[t] and dc != 0:
            add('A1', t, -np.sign(dc), abs(dc) / atr[t])
        if R[t] < lo <= R[t - 1]:
            add('A2', t, 1, lo - R[t])
        elif R[t] > hi >= R[t - 1]:
            add('A2', t, -1, R[t] - hi)
        if sd[t] > 0:
            if c[t] > mid[t] + k * sd[t] and c[t - 1] <= mid[t - 1] + k * sd[t - 1]:
                add('A3', t, -1, abs(c[t] - mid[t]) / sd[t] - k)
            elif c[t] < mid[t] - k * sd[t] and c[t - 1] >= mid[t - 1] - k * sd[t - 1]:
                add('A3', t, 1, abs(c[t] - mid[t]) / sd[t] - k)
        if c[t] > hh[t] and c[t - 1] <= hh[t - 1]:
            add('B1', t, 1, (c[t] - hh[t]) / atr[t])
        elif c[t] < ll[t] and c[t - 1] >= ll[t - 1]:
            add('B1', t, -1, (ll[t] - c[t]) / atr[t])
        if hist[t] != 0 and hist[t - 1] != 0 and np.sign(hist[t]) != np.sign(hist[t - 1]):
            add('B2', t, np.sign(hist[t]), abs(line[t]) / atr[t])
        if t >= CL['mom'] and c[t] != c[t - CL['mom']]:
            mv = c[t] - c[t - CL['mom']]
            add('B3', t, np.sign(mv), abs(mv) / (math.sqrt(CL['mom']) * atr[t]))
    return {kk: (np.array(a_, dtype=np.int64), np.array(b_, dtype=np.int8), np.array(c_, dtype=np.float64))
            for kk, (a_, b_, c_) in ev.items()}


