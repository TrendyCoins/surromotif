def week_bars():
    return 7 * 1440 // STAND['bar_min']


def regimes(rng, n):
    """Режим «вкл / выкл»: отрезки геометрической длины, в среднем reg_len баров «вкл», доля «вкл» — reg_share."""
    S_ = STAND
    reg = np.zeros(n, dtype=bool)
    i, on = 0, rng.random() < S_['reg_share']
    while i < n:
        mean = S_['reg_len'] if on else S_['reg_len'] * (1 - S_['reg_share']) / S_['reg_share']
        ln = int(rng.geometric(1.0 / mean))
        reg[i:i + ln] = on
        i += ln
        on = not on
    return reg


def episode_signs(reg, rng):
    """Знак сноса у каждого эпизода режима (+1 / −1, монетка), вне режима — 0."""
    start = reg & ~np.r_[False, reg[:-1]]
    lab = np.cumsum(start)
    sg = np.where(rng.random(int(start.sum()) + 1) < 0.5, -1.0, 1.0)
    return np.where(reg, sg[lab], 0.0)


def ar1(e, phi):
    """u_t = φ_t u_(t−1) + √(1 − φ_t²) e_t — дисперсия 1 при любом φ_t."""
    u = np.empty(len(e))
    q = np.sqrt(1.0 - phi * phi)
    prev = 0.0
    for t in range(len(e)):
        prev = phi[t] * prev + q[t] * e[t]
        u[t] = prev
    return u


def world_series(kind, seed, ia):
    """Синтетический ряд мира kind (см. шапку, (ст3)): кусок цены с ATR, живостью и vr (synth_ohlc Levels); у «тренда» ещё
       'reg' — режим на баре (его знает заменитель)."""
    S_ = STAND
    rng = np.random.default_rng([seed, ia, 11])
    bar_ns = S_['bar_min'] * 60 * 10 ** 9
    n = S_['warm'] + 2 * S_['weeks'] * week_bars()
    e = rng.standard_normal(n)
    sig = np.full(n, S_['sigma'])
    reg = None
    if kind in ('vol', 'zero'):
        lv = lfilter([1.0], [1.0, -S_['vol_rho']], rng.normal(0, S_['vol_eps'], n))
        sig = S_['sigma'] * np.exp(lv - lv.mean())
    if kind == 'saw':
        steps = sig * ar1(e, np.where(regimes(rng, n), S_['ac1_saw'], 0.0))
    elif kind == 'trend':
        reg = regimes(rng, n)
        steps = sig * (e + S_['drift'] * episode_signs(reg, rng))
    elif kind == 'vol':
        steps = sig * ar1(e, np.where(sig < np.median(sig), S_['ac1_quiet'], 0.0))
    else:
        steps = sig * e
    P = LV.synth_ohlc(steps, rng, sig, S_['wick'], t0=S_['t0'], bar_ns=bar_ns)
    if reg is not None:
        P['reg'] = reg
    return P


def proxy(kind, W, scale, rng, reg=None):
    """MRI-заменитель (ст3) на окнах шагов W (окна × 64; окно k кончается на баре k + 64): «пила» и «ноль» — −AC1 окна;
       «вола» — одна вола окна (тише — выше); «тренд» — знание режима на последнем баре окна (reg; у суррогата линейки — нет):
       функция окна, которая видела бы режим, совпала бы с силой сигнала тренда (ход за 64 бара) и пропала бы в слоях силы,
       а стенду нужно проверить, что машинка находит знание цвета сверх силы; плюс шум."""
    S_ = STAND
    if kind in ('saw', 'zero'):
        x = W - W.mean(1, keepdims=True)
        den = (x * x).sum(1)
        ac = np.where(den > 0, (x[:, 1:] * x[:, :-1]).sum(1) / np.where(den > 0, den, 1.0), 0.0)
        lg = -S_['px_ac'] * ac
    elif kind == 'trend':
        lg = S_['px_reg'] * (np.zeros(len(W)) if reg is None else reg[CL['win']:].astype(np.float64))
    else:
        lg = -S_['px_vol'] * np.log(np.maximum(np.abs(W).mean(1), 1e-12) / scale)
    return lg + rng.normal(0, S_['px_noise'], len(lg))


def world_events(kind, seed):
    """Мир (ст3): ряды, заменитель MRI у реала и случайных рынков (та же функция на их окнах; у «тренда» — то же знание режима
       реала: будущее случайного рынка от него не зависит), линейка — суррогаты «знак каждого шага — монетка», линия M, события
       шести сигналов. Возвращает (E, число монет); LEV['tune_start'] / ['val_start'] на время мира — границы его периодов
       (вызывающий восстанавливает LEV)."""
    S_ = STAND
    rng = np.random.default_rng([seed, 99])
    bar_ns = S_['bar_min'] * 60 * 10 ** 9
    n_r, L = S_['n_rand'], CL['win']
    assets = [world_series(kind, seed, ia) for ia in range(S_['assets'])]
    T0 = assets[0]['T']
    LV.LEV.update({'tune_start': str(pd.Timestamp(T0[S_['warm']])),
                   'val_start': str(pd.Timestamp(T0[S_['warm'] + S_['weeks'] * week_bars()]))})
    shift = S_['px_shift'].get(kind, 0.0)
    lg_real, lg_s4, lg_rand, signs = [], [], [[] for _ in range(n_r)], []
    for ia, P in enumerate(assets):
        W = LV._windows(P['c'])
        scale = float(np.median(np.abs(np.diff(P['c']))))
        reg = P.get('reg')
        lg_real.append(proxy(kind, W, scale, rng, reg) + shift)
        lg_s4.append(proxy(kind, W * LV.coin_signs(len(W), L, rng), scale, rng))
        sg_a = []
        for j in range(n_r):
            sg = LV.rand_signs(f"W{ia}", j, 0, P['T'], rand_from=T0[0])
            sg_a.append(sg)
            Wj = W * sg[np.arange(L, len(P['c']))[:, None] + np.arange(-(L - 1), 1)[None, :]]
            lg_rand[j].append(proxy(kind, Wj, scale, rng, reg))
        signs.append(sg_a)
    q, zk = FL.ruler(np.concatenate(lg_s4))
    acc = {k: {'real': [], 'rand': []} for k in SIGNALS}
    pad = np.full(L, np.nan)
    for ia, P in enumerate(assets):
        z = FL.to_z(lg_real[ia], q, zk)
        ctx = piece_ctx(P, bar_ns)
        rds = [(P, {'lm': np.r_[pad, EF.line_parts(z)[0]], 'z': np.r_[pad, z]})]
        for j in range(n_r):
            zx = FL.to_z(lg_rand[j][ia], q, zk)
            rds.append((LV.mirror_bars(P, signs[ia][j]), {'lm': np.r_[pad, EF.line_parts(z, zx)[0]], 'z': np.r_[pad, zx]}))
        for mk, (Pm, rd) in enumerate(rds):
            for k, tab in market_events(Pm, rd, ctx, bar_ns, '5M').items():
                tab['a'] = np.full(len(tab['per']), ia, dtype=np.int16)
                tab['mk'] = np.full(len(tab['per']), mk, dtype=np.int8)
                acc[k]['real' if mk == 0 else 'rand'].append(tab)
    E = {k: {mk: cat(v) for mk, v in d.items()} for k, d in acc.items()}
    return E, len(assets)


def world_eval(kind, seed, nvs):
    """Мир (ст3) целиком: события и статистика ТФ (бутстреп — n_boot стенда, одни повторы на все nv) при каждом nv частей vl;
       LEV восстанавливается. Возвращает {nv: статистика}."""
    keep = dict(LV.LEV)
    try:
        E, n_a = world_events(kind, seed)
        Bs = boot_sets(E, STAND['n_boot'], seed)
        return {nv: tf_stats(E, n_a, 0, nv, light=True, Bs=Bs) for nv in nvs}
    finally:
        LV.LEV.clear()
        LV.LEV.update(keep)


