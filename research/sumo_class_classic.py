def _pp(x):
    """lin_stat в п.п.: точка [95%] (t)."""
    if not x or not np.isfinite(x.get('d', math.nan)):
        return '—'
    return f"{100 * x['d']:+.2f} [{100 * x['ci'][0]:+.2f}; {100 * x['ci'][1]:+.2f}] ({_f(x['t'], '+.1f')})"


def _pct(x):
    if not x or not np.isfinite(x.get('d', math.nan)):
        return '—'
    return f"{100 * x['d']:.2f}%"


def _pair(st, key='D'):
    """Поиск / подтверждение одной справочной строки."""
    return ' | '.join(_pp((st.get(src) or {}).get(key)) for src in PERIODS)


