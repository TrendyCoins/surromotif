def outcomes(P, t, d, bar_ns, hm):
    """Исходы событий (бары t, ставки d): hit на горизонтах CL['h'] (1 — цена через h баров ушла в сторону ставки, 0 — против,
       −1 — исхода нет: ровно на месте, ряд кончился или внутри h баров дыра во времени); hs — то же на главном горизонте hm
       с пропуском бара (вход на close бара t + 1); y — ход по ставке за hm баров в ATR бара события (NaN — исхода нет)."""
    c, T, atr = np.asarray(P['c'], np.float64), np.asarray(P['T'], np.int64), np.asarray(P['atr'], np.float64)
    n = len(c)
    t = np.asarray(t, dtype=np.int64)
    d = np.asarray(d, dtype=np.float64)

    def move(a, h):
        e = a + h
        ok = e < n
        ee = np.minimum(e, n - 1)
        aa = np.minimum(a, n - 1)
        ok &= (T[ee] - T[aa]) == h * bar_ns
        return ok, d * (c[ee] - c[aa])

    def to_hit(ok, mv):
        return np.where(ok & (mv > 0), 1, np.where(ok & (mv < 0), 0, -1)).astype(np.int8)

    hit = np.full((len(t), len(CL['h'])), -1, dtype=np.int8)
    for j, h in enumerate(CL['h']):
        hit[:, j] = to_hit(*move(t, h))
    ok, mv = move(t, hm)
    with np.errstate(invalid='ignore', divide='ignore'):
        y = np.where(ok, mv / atr[t], np.nan) if len(t) else np.zeros(0)
    ok1, mv1 = move(t + 1, hm)
    hs = to_hit(ok1 & (t + 1 < n), mv1)
    return hit, hs, y


def lagged(x, T, k, bar_ns):
    """x бара t − k (k баров назад без дыры во времени), иначе NaN — цвет сутки / неделю назад."""
    x = np.asarray(x, dtype=np.float64)
    T = np.asarray(T, dtype=np.int64)
    out = np.full(len(x), np.nan)
    if len(x) > k:
        ok = (T[k:] - T[:-k]) == k * bar_ns
        out[k:] = np.where(ok, x[:-k], np.nan)
    return out


def flat_share(c):
    """Доля баров, у которых close не сдвинулся, среди 200 баров до бара (closed='left') — грубая сетка цены, как в Atlas."""
    z = (np.r_[np.nan, np.diff(np.asarray(c, dtype=np.float64))] == 0).astype(np.float64)
    return pd.Series(z).rolling(CL['flat_win'], closed='left').mean().to_numpy()


def vol_level(P):
    """Уровень волы vl: средний истинный диапазон 64 баров окна MRI (t − 63 … t) к среднему истинному диапазону 4032 баров до
       окна (t − 4095 … t − 64) — норма монеты на горизонте базы линии M. NaN, пока истории меньше."""
    tr = LG.true_range(P['h'], P['l'], P['c'])
    win = pd.Series(tr).rolling(CL['win'], min_periods=CL['win']).mean().to_numpy()
    base = pd.Series(tr).rolling(CL['base'], min_periods=CL['base']).mean().shift(CL['win']).to_numpy()
    with np.errstate(invalid='ignore', divide='ignore'):
        return np.where(base > 0, win / base, np.nan)


def piece_ctx(P, bar_ns):
    """Общее у реала и случайных рынков куска (зеркало бара не меняет ширину, истинный диапазон, ход по модулю): годный бар (живой
       нормировщик, ATR, не грубая сетка, прошлый бар — без дыры во времени), период, неделя, группа часа суток, vl."""
    flat = flat_share(P['c'])
    T = np.asarray(P['T'], dtype=np.int64)
    cont = np.r_[False, np.diff(T) == bar_ns]
    with np.errstate(invalid='ignore'):
        good = (np.asarray(P['live'], dtype=bool) & np.isfinite(P['atr']) & (P['atr'] > 0) & (flat < CL['flat_max']) & cont)
    return {'good': good, 'per': period_codes(T), 'wk': (T // WEEK_NS).astype(np.int32),
            'hr': ((T // HOUR_NS) % 24 // CL['hour_group']).astype(np.int8), 'vl': vol_level(P)}


def market_events(P, rd, ctx, bar_ns, tf, keep_t=False):
    """События шести сигналов на одном рынке (реал или случайный): только годные бары с цветом и в периоде. Таблица сигнала:
       per, wk, hr — период, неделя, группа часа; lm — log M бара, lmd / lmw — сутки / неделю назад, z — MRI без линии; vl, vr —
       вола, st — сила сигнала; hit (события × горизонты), hs — с пропуском бара, y — ход в ATR (главный горизонт); keep_t — ещё
       бары t и ставки d (стенд)."""
    sig = signals(P)
    lm = np.asarray(rd['lm'], dtype=np.float64)
    z = np.asarray(rd['z'], dtype=np.float64)
    k_d, k_w = CL['lags'][tf]
    lmd, lmw = lagged(lm, P['T'], k_d, bar_ns), lagged(lm, P['T'], k_w, bar_ns)
    out = {}
    for k, (t, d, s) in sig.items():
        m = ctx['good'][t] & (ctx['per'][t] >= 0) & np.isfinite(lm[t])
        t, d, s = t[m], d[m], s[m]
        hit, hs, y = outcomes(P, t, d, bar_ns, CL['h_main'][SIGNALS[k][0]])
        tab = {'per': ctx['per'][t], 'wk': ctx['wk'][t], 'hr': ctx['hr'][t], 'lm': lm[t].astype(np.float32),
               'lmd': lmd[t].astype(np.float16), 'lmw': lmw[t].astype(np.float16), 'z': z[t].astype(np.float16),
               'vl': ctx['vl'][t].astype(np.float32), 'vr': np.asarray(P['vr'])[t].astype(np.float16),
               'st': s.astype(np.float32), 'hit': hit, 'hs': hs, 'y': y.astype(np.float32)}
        if keep_t:
            tab['t'], tab['d'] = t, d
        out[k] = tab
    return out


def cat(parts):
    """Склейка таблиц событий одного сигнала."""
    parts = [p for p in parts if p is not None and len(p['per'])]
    if not parts:
        return None
    return {k: np.concatenate([p[k] for p in parts], axis=0) for k in parts[0]}


def asset_events(a, ia, tf, bars, rdg, n_r, acc, keep_t=False):
    """События ассета: реал и случайные рынки 0 … n_r − 1 (зеркало бара со знаками rand_signs Levels — те же, что в 'score') на
       каждом куске; таблицы — в acc[сигнал]['real' / 'rand'] с полями a (ассет) и mk (0 — реал, j + 1 — случайный рынок j).
       Возвращает сводку: баров с цветом в периодах и сколько из них не берутся (грубая сетка, мёртвый нормировщик, дыра)."""
    bar_ns = CL['bar_ns'][tf]
    info = {'colored': 0, 'dropped': 0}
    for pi, P in enumerate(bars['pieces']):
        ctx = piece_ctx(P, bar_ns)
        col = np.isfinite(np.asarray(rdg['real'][pi]['lm'], dtype=np.float64)) & (ctx['per'] >= 0)
        info['colored'] += int(col.sum())
        info['dropped'] += int((col & ~ctx['good']).sum())
        for mk in range(1 + n_r):
            if mk == 0:
                Pm, rd = P, rdg['real'][pi]
            else:
                Pm, rd = LV.mirror_bars(P, LV.rand_signs(a, mk - 1, pi, P['T'])), rdg['rand'][mk - 1][pi]
            for k, tab in market_events(Pm, rd, ctx, bar_ns, tf, keep_t).items():
                tab['a'] = np.full(len(tab['per']), ia, dtype=np.int16)
                tab['mk'] = np.full(len(tab['per']), mk, dtype=np.int8)
                acc[k]['real' if mk == 0 else 'rand'].append(tab)
    return info


