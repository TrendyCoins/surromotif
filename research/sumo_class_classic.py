def colors(lm):
    """Маски оранжевого (log M >= ln 1.25, сторона реала) и серого (log M <= −ln 1.25, сторона суррогата); серебро — ни то ни
       другое; NaN — нигде."""
    e = math.log(CL['mark'])
    lm = np.asarray(lm, dtype=np.float64)
    with np.errstate(invalid='ignore'):
        return lm >= e, lm <= -e


def bin5(lm):
    """Корзина Anat по log M: 0 — S2 (серый, M >= 3), 1 — S1, 2 — N (серебро), 3 — R1, 4 — R2 (оранжевый, M >= 3); −1 — нет цвета."""
    e1, e3 = (math.log(b) for b in CL['bins'])
    lm = np.asarray(lm, dtype=np.float64)
    b = np.full(len(lm), -1, dtype=np.int8)
    with np.errstate(invalid='ignore'):
        b[lm <= -e3] = 0
        b[(lm > -e3) & (lm <= -e1)] = 1
        b[(lm > -e1) & (lm < e1)] = 2
        b[(lm >= e1) & (lm < e3)] = 3
        b[lm >= e3] = 4
    return b


def qcuts(x, k):
    """Границы k равных по числу значений частей (квантили 1/k … (k − 1)/k) конечных значений; значений меньше k — None."""
    x = np.asarray(x, dtype=np.float64)
    x = x[np.isfinite(x)]
    return np.quantile(x, np.arange(1, k) / k) if len(x) >= k else None


def qbin(x, cuts):
    """Номер части: сколько границ строго меньше x (0 … k − 1; значение на границе — в нижней части); NaN и нет границ — −1."""
    x = np.asarray(x, dtype=np.float64)
    out = np.full(len(x), -1, dtype=np.int64)
    if cuts is None:
        return out
    f = np.isfinite(x)
    out[f] = np.searchsorted(cuts, x[f], side='left')
    return out


def counts(B, wk, s, y, K, m):
    """События маски m по неделям бутстрепа B × слоям s (0 … K − 1; −1 — вне слоёв): (n, сумма y). y с NaN — не событие."""
    nw = len(B['uw'])
    y = np.asarray(y, dtype=np.float64)
    m = np.asarray(m, dtype=bool) & (np.asarray(s) >= 0) & np.isfinite(y)
    if not m.any():
        return np.zeros((nw, K)), np.zeros((nw, K))
    w = np.asarray(wk, dtype=np.int64)[m]
    wi = np.searchsorted(B['uw'], w)
    if np.any(wi >= nw) or np.any(B['uw'][np.minimum(wi, nw - 1)] != w):
        raise ValueError("🍆 АЙ, ОШИБКА! неделя события не в наборе недель бутстрепа")
    idx = wi * K + np.asarray(s, dtype=np.int64)[m]
    n = np.bincount(idx, minlength=nw * K).reshape(nw, K).astype(np.float64)
    sm = np.bincount(idx, weights=y[m], minlength=nw * K).reshape(nw, K)
    return n, sm


def contrast(B, R, X, yr, yx, mr, mx, sr, sx, K, cr, cx):
    """D = Σ_s w_s (ȳ_A,s − ȳ_B,s) у реала (таблица R) и у случайного рынка (X; None — без него): A, B — маски цветов cr / cx,
       слои sr / sx (0 … K − 1), веса — события реала обоих цветов в слоях, где у рынка есть оба цвета. Точка, 95% интервал и
       ошибка — по повторам бутстрепа по неделям (lin_stat Levels)."""
    ra, rb = cr
    G = {'RA': counts(B, R['wk'], sr, yr, K, mr & ra), 'RB': counts(B, R['wk'], sr, yr, K, mr & rb)}
    out = {'D': LV.lin_stat(B, G, [(1, 'RA'), (-1, 'RB')], ['RA', 'RB'])}
    if X is not None:
        xa, xb = cx
        G['XA'] = counts(B, X['wk'], sx, yx, K, mx & xa)
        G['XB'] = counts(B, X['wk'], sx, yx, K, mx & xb)
        out['Dx'] = LV.lin_stat(B, G, [(1, 'XA'), (-1, 'XB')], ['RA', 'RB'])
    return out


def group_mean(B, wk, y, m):
    """Среднее y по маске (все события одной группой) с интервалом бутстрепа по неделям."""
    y = np.asarray(y, dtype=np.float64)
    G = {'A': counts(B, wk, np.zeros(len(y), dtype=np.int64), y, 1, m)}
    return LV.lin_stat(B, G, [(1, 'A')], ['A'])


def strata(T_, cv, cs, nv, extra=None, n_extra=1, use_st=True):
    """Слой события: ассет × часть vl (nv частей) × треть силы (× extra из n_extra значений; без use_st — без силы); −1 — без
       слоя."""
    v = qbin(T_['vl'], cv)
    s = qbin(T_['st'], cs) if use_st else np.where(v >= 0, 0, -1)
    out = np.where((v >= 0) & (s >= 0), (T_['a'].astype(np.int64) * nv + v) * CL['n_st'] + s, -1)
    if extra is not None:
        out = np.where((out >= 0) & (extra >= 0), out * n_extra + extra, -1)
    return out


def signal_stats(k, Ek, Bs, n_assets, btc_i, nv, light=False):
    """Статистика сигнала по периодам: главная (D на главном горизонте, D случайного рынка, доли угаданных по цветам), все
       горизонты, подробные слои волы (для (Ф)), наивное сравнение и vr вместо vl; без light — и остальное справочное. nv — частей
       vl в слоях."""
    R, X = Ek.get('real'), Ek.get('rand')
    if R is None or X is None:
        return None
    hm = CL['h_main'][SIGNALS[k][0]]
    hi = CL['h'].index(hm)
    keys = ('main', 'hit', 'n', 'cover', 'rich', 'naive', 'vr_only') + (
        () if light else ('no_st', 'vr_add', 'hour', 'btc', 'lag_d', 'lag_w', 'skip', 'y', 'z', 'bins'))
    out = {'h_main': hm, 'n_vl': nv, 'h': {h: {} for h in CL['h']}}
    out.update({key: {} for key in keys})
    or_r, gr_r = colors(R['lm'])
    or_x, gr_x = colors(X['lm'])
    col_r, col_x = (or_r, gr_r), (or_x, gr_x)
    ns_ = CL['n_st']
    K = n_assets * nv * ns_
    G6 = 24 // CL['hour_group']
    for ip, src in enumerate(PERIODS):
        B = Bs[src]
        pr, px = R['per'] == ip, X['per'] == ip
        hr_m, hx_m = R['hit'][:, hi], X['hit'][:, hi]
        mr, mx = pr & (hr_m >= 0), px & (hx_m >= 0)
        yr, yx = hr_m.astype(np.float64), hx_m.astype(np.float64)
        ref = mr & (or_r | gr_r)
        cv, cs = qcuts(R['vl'][ref], nv), qcuts(R['st'][ref], ns_)
        sr, sx = strata(R, cv, cs, nv), strata(X, cv, cs, nv)
        out['main'][src] = contrast(B, R, X, yr, yx, mr, mx, sr, sx, K, col_r, col_x)
        out['n'][src] = {'real_or': int((mr & or_r).sum()), 'real_gr': int((mr & gr_r).sum()),
                         'real_si': int((mr & ~or_r & ~gr_r).sum()), 'rand_or': int((mx & or_x).sum()),
                         'rand_gr': int((mx & gr_x).sum()), 'rand': int(mx.sum())}
        # сколько событий реала обоих цветов реально сравнивается: в слоях, где есть оба цвета
        na = counts(B, R['wk'], sr, yr, K, mr & or_r)[0].sum(0)
        nb = counts(B, R['wk'], sr, yr, K, mr & gr_r)[0].sum(0)
        both = (na > 0) & (nb > 0)
        tot = int(ref.sum())
        out['cover'][src] = float((na[both].sum() + nb[both].sum()) / tot) if tot else math.nan
        out['hit'][src] = {'R': group_mean(B, R['wk'], yr, mr & or_r), 'S': group_mean(B, R['wk'], yr, mr & gr_r),
                           'N': group_mean(B, R['wk'], yr, mr & ~or_r & ~gr_r), 'X': group_mean(B, X['wk'], yx, mx),
                           'XR': group_mean(B, X['wk'], yx, mx & or_x), 'XS': group_mean(B, X['wk'], yx, mx & gr_x)}
        # все горизонты (слои — те же)
        for j, h in enumerate(CL['h']):
            a_, b_ = R['hit'][:, j], X['hit'][:, j]
            out['h'][h][src] = contrast(B, R, X, a_.astype(np.float64), b_.astype(np.float64), pr & (a_ >= 0), px & (b_ >= 0),
                                        sr, sx, K, col_r, col_x)
        # без слоёв (наивно) и vr вместо vl
        z_r, z_x = np.zeros(len(yr), np.int64), np.zeros(len(yx), np.int64)
        out['naive'][src] = contrast(B, R, X, yr, yx, mr, mx, z_r, z_x, 1, col_r, col_x)
        cvr = qcuts(R['vr'][ref], nv)
        Rv, Xv = dict(R, vl=R['vr']), dict(X, vl=X['vr'])
        out['vr_only'][src] = contrast(B, R, X, yr, yx, mr, mx, strata(Rv, cvr, cs, nv), strata(Xv, cvr, cs, nv), K, col_r, col_x)
        # подробные слои волы — устойчивость для (Ф): монета × vl (10 частей) × vr (трети) × сила
        nv2, nr2 = CL['rich']
        cv2, cr2 = qcuts(R['vl'][ref], nv2), qcuts(R['vr'][ref], nr2)
        out['rich'][src] = contrast(B, R, X, yr, yx, mr, mx, strata(R, cv2, cs, nv2, extra=qbin(R['vr'], cr2), n_extra=nr2),
                                    strata(X, cv2, cs, nv2, extra=qbin(X['vr'], cr2), n_extra=nr2),
                                    n_assets * nv2 * ns_ * nr2, col_r, col_x)
        if light:
            continue
        # без слоя силы: монета × vl (сколько эффекта снимает сила сигнала)
        out['no_st'][src] = contrast(B, R, X, yr, yx, mr, mx, strata(R, cv, cs, nv, use_st=False),
                                     strata(X, cv, cs, nv, use_st=False), K, col_r, col_x)
        # + слой vr (трети)
        c3 = qcuts(R['vr'][ref], 3)
        out['vr_add'][src] = contrast(B, R, X, yr, yx, mr, mx, strata(R, cv, cs, nv, extra=qbin(R['vr'], c3), n_extra=3),
                                      strata(X, cv, cs, nv, extra=qbin(X['vr'], c3), n_extra=3), K * 3, col_r, col_x)
        # + слой часа суток
        out['hour'][src] = contrast(B, R, X, yr, yx, mr, mx, strata(R, cv, cs, nv, extra=R['hr'].astype(np.int64), n_extra=G6),
                                    strata(X, cv, cs, nv, extra=X['hr'].astype(np.int64), n_extra=G6), K * G6, col_r, col_x)
        # BTC отдельно
        if btc_i is not None:
            out['btc'][src] = contrast(B, R, None, yr, None, mr & (R['a'] == btc_i), None, sr, None, K, col_r, None)
        # цвет сутки / неделю назад
        for key, fld in (('lag_d', 'lmd'), ('lag_w', 'lmw')):
            out[key][src] = contrast(B, R, X, yr, yx, mr, mx, sr, sx, K, colors(R[fld]), colors(X[fld]))
        # с пропуском бара
        a_, b_ = R['hs'], X['hs']
        out['skip'][src] = contrast(B, R, X, a_.astype(np.float64), b_.astype(np.float64), pr & (a_ >= 0), px & (b_ >= 0),
                                    sr, sx, K, col_r, col_x)
        # средний ход в ATR, хвосты обрезаны по событиям реала обоих цветов
        yv = np.asarray(R['y'], dtype=np.float64)
        fin = ref & np.isfinite(yv)
        if fin.sum() >= 3:
            lo_, hi_ = np.quantile(yv[fin], [CL['y_q'], 1 - CL['y_q']])
            ycr, ycx = np.clip(yv, lo_, hi_), np.clip(np.asarray(X['y'], dtype=np.float64), lo_, hi_)
            out['y'][src] = contrast(B, R, X, ycr, ycx, pr, px, sr, sx, K, col_r, col_x)
        # трети z (MRI без линии) вместо цвета: верхняя треть против нижней, по событиям всех цветов
        cz = qcuts(np.asarray(R['z'], dtype=np.float64)[mr], 3)
        zr_, zx_ = qbin(R['z'], cz), qbin(X['z'], cz)
        out['z'][src] = contrast(B, R, X, yr, yx, mr, mx, sr, sx, K, (zr_ == 2, zr_ == 0), (zx_ == 2, zx_ == 0))
        # 5 корзин: сырые доли угаданных
        br, bx = bin5(R['lm']), bin5(X['lm'])
        out['bins'][src] = {mk: [{'n': int((m_ & (b_ == i)).sum()),
                                  'hit': float(y_[m_ & (b_ == i)].mean()) if (m_ & (b_ == i)).any() else math.nan}
                                 for i in range(5)]
                            for mk, m_, b_, y_ in (('real', mr, br, yr), ('rand', mx, bx, yx))}
    return out


def boot_sets(E, n_boot, seed):
    """Повторы бутстрепа по периодам: недели всех событий всех сигналов (реал и случайные рынки) — один набор на период."""
    Bs = {}
    for ip, src in enumerate(PERIODS):
        wk = [T_['wk'][T_['per'] == ip] for d in E.values() for T_ in d.values() if T_ is not None]
        wk = np.concatenate(wk) if wk else np.zeros(0, dtype=np.int64)
        Bs[src] = LV.boot_setup(wk, [seed, 41, ip], n_boot)
    return Bs


def _covers(x):
    return x is not None and np.isfinite(x.get('d', math.nan)) and x['ci'][0] <= 0 <= x['ci'][1]


def rules(S):
    """Правила (0), (К1), (К2), (Ф) по статистике ТФ."""
    sig = {k: v for k, v in S['sig'].items() if v is not None}
    r0a = {}
    for k, x in sig.items():
        for src in PERIODS:
            h_ = x['hit'][src]['X']
            r0a[(k, src)] = bool(np.isfinite(h_['d']) and np.isfinite(h_['se']) and
                                 abs(h_['d'] - 0.5) <= CL['rand_se'] * h_['se'])
    cells = [x['h'][h][src].get('Dx') for x in sig.values() for h in CL['h'] for src in PERIODS]
    cells = [c for c in cells if c is not None and np.isfinite(c.get('d', math.nan))]
    cover = float(np.mean([_covers(c) for c in cells])) if cells else math.nan
    ok0 = bool(r0a) and all(r0a.values()) and np.isfinite(cover) and cover >= CL['rand_cover'] and len(sig) == len(SIGNALS)
    k1 = {k: LV.sees({src: x['main'][src]['D'] for src in PERIODS}) for k, x in sig.items()}
    phrase, robust = {}, {}
    for k, x in sig.items():
        conf, rich = x['main']['confirm']['D'], x['rich']['confirm']['D']
        hr_ = x['hit']['confirm']['R']
        robust[k] = bool(np.isfinite(rich['d']) and rich['ci'][0] > 0)
        phrase[k] = bool(k1[k] > 0 and np.isfinite(conf['d']) and conf['d'] >= CL['claim'] and np.isfinite(hr_['ci'][0])
                         and hr_['ci'][0] > 0.5 and robust[k])
    return {'r0a': {f"{k}|{s}": v for (k, s), v in r0a.items()}, 'r0a_ok': all(r0a.values()) if r0a else False,
            'r0b_cover': cover, 'r0b_n': len(cells), 'ok0': ok0, 'k1': k1, 'k2': any(v > 0 for v in k1.values()),
            'robust': robust, 'phrase': phrase}


def tf_stats(E, n_assets, btc_i, nv, n_boot=None, seed=None, light=False, Bs=None):
    """Статистика ТФ: повторы бутстрепа (Bs — готовые), все сигналы, правила; nv — частей vl в слоях."""
    if Bs is None:
        Bs = boot_sets(E, n_boot or CL['n_boot'], CL['seed'] if seed is None else seed)
    S = {'sig': {k: signal_stats(k, E[k], Bs, n_assets, btc_i, nv, light) for k in SIGNALS},
         'weeks': {src: len(B['uw']) for src, B in Bs.items()}, 'n_vl': nv}
    S['rules'] = rules(S)
    return S


