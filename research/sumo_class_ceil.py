@contextlib.contextmanager
def _tee(path):
    """Лог в файл и на экран (как tee_to у Bell; свой — модули ещё не загружены)."""
    class Tee:
        def __init__(self, fh, keep):
            self.fh, self.keep = fh, keep

        def write(self, s):
            self.keep.write(s)
            self.fh.write(s)

        def flush(self):
            self.keep.flush()
            self.fh.flush()
    keep = sys.stdout
    with open(path, 'w', encoding='utf-8') as fh:
        sys.stdout = Tee(fh, keep)
        try:
            yield
        finally:
            sys.stdout = keep


