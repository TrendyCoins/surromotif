def curve(lr, ln, edges, mn):
    """Копия _nc_curve кода обучения (кривая R9) с корзинами edges и порогом «мало данных» mn (стенд: с NC_EDGES и
       NOCAL['min_n'] — бит в бит). Оранжевые: фактическая кратность — доля корзины среди реальных окон / среди
       суррогатов, обещанная — среднее M суррогатов корзины; синие — наоборот, обещанная — среднее 1/M реальных окон."""
    rows = []
    for color, sg in (('orange', 1.0), ('blue', -1.0)):
        xp, xn = sg * lr, sg * ln
        for lo, hi in zip(edges[:-1], edges[1:]):
            bp = (xp > 0) & (xp >= math.log(lo)) & (xp < math.log(hi))
            bn = (xn > 0) & (xn >= math.log(lo)) & (xn < math.log(hi))
            n_p, n_n = int(bp.sum()), int(bn.sum())
            row = {'color': color, 'lo': lo, 'n_real': n_p, 'n_surr': n_n, 'ratio': np.nan,
                   'sparse': min(n_p, n_n) < mn}
            if n_p and n_n:
                if color == 'orange':          # exp — не выше e^700 (без переполнения в открытой корзине)
                    fact, exp_ = (n_p / len(lr)) / (n_n / len(ln)), float(np.exp(np.minimum(xn[bn], 700.0)).mean())
                else:
                    fact, exp_ = (n_n / len(ln)) / (n_p / len(lr)), float(np.exp(np.minimum(xp[bp], 700.0)).mean())
                row.update({'fact': fact, 'exp': exp_, 'ratio': fact / exp_})
            rows.append(row)
    return rows


def bins_of(rows, color, edges):
    """Корзины цвета: [(строка кривой, нижняя граница, верхняя граница)] по порядку."""
    return list(zip([r for r in rows if r['color'] == color], edges[:-1], edges[1:]))


def group_row(lr, ln, color, lo, cap, mn):
    """Группа окон цвета с силой >= lo, показанная сила — min(сила, cap): фактическая кратность (как у корзины кривой
       R9) и обещанная — среднее показанной силы (у оранжевых — по суррогатам группы, у синих — по реальным окнам)."""
    sg = 1.0 if color == 'orange' else -1.0
    xp, xn = sg * lr, sg * ln
    t = math.log(lo)
    bp, bn = (xp > 0) & (xp >= t), (xn > 0) & (xn >= t)
    n_p, n_n = int(bp.sum()), int(bn.sum())
    row = {'color': color, 'lo': lo, 'cap': cap, 'n_real': n_p, 'n_surr': n_n, 'ratio': np.nan,
           'sparse': min(n_p, n_n) < mn}
    if n_p and n_n:
        lc = math.log(cap)
        if color == 'orange':
            fact, prom = (n_p / len(lr)) / (n_n / len(ln)), float(np.exp(np.minimum(xn[bn], lc)).mean())
        else:
            fact, prom = (n_n / len(ln)) / (n_p / len(lr)), float(np.exp(np.minimum(xp[bp], lc)).mean())
        row.update({'fact': fact, 'exp': prom, 'ratio': fact / prom})
    return row


def pool_check(lr, ln, C, rows):
    """(Ц1) по пулу: корзины ниже C — отношение в [tol] и данных хватает; группа «C+» — фактическая >= tol_lo·C."""
    E, (lo_t, hi_t), mn = CEIL['edges'], tol(), min_n()
    out = {}
    for color in COLORS:
        bad = [lo for r, lo, hi in bins_of(rows, color, E)
               if hi <= C and (r['sparse'] or not (lo_t <= r['ratio'] <= hi_t))]
        g = group_row(lr, ln, color, C, C, mn)
        g_ok = (not g['sparse']) and g['ratio'] >= lo_t
        out[color] = {'bins_bad': bad, 'group': g, 'ok': bool(not bad and g_ok)}
    out['ok'] = bool(out['orange']['ok'] and out['blue']['ok'])
    return out


def pair_check(lr, ln, color, C, rows):
    """(Ц2) пара ассет × цвет: корзины ниже min(C, fine_max) — отношение >= tol_lo (как R11), выше — одной группой с
       показанной силой min(сила, C). Статус: 'завышает' (не прошла проверка с данными) / 'без данных' / 'ок'."""
    E, (lo_t, _), mn = CEIL['edges'], tol(), min_n()
    k = min(C, CEIL['fine_max'])
    fine = [(r, lo) for r, lo, hi in bins_of(rows, color, E) if hi <= k]
    g = group_row(lr, ln, color, k, C, mn)
    checks = [(r['sparse'], r['ratio'], lo) for r, lo in fine] + [(g['sparse'], g['ratio'], f"{k:g}+")]
    over = [lo for sp, ra, lo in checks if not sp and not ra >= lo_t]
    sparse = [lo for sp, ra, lo in checks if sp]
    status = 'завышает' if over else ('без данных' if sparse else 'ок')
    return {'status': status, 'over': over, 'sparse': sparse, 'group': g}


def rule_source(cells, Cs, unseen=()):
    """Правило потолка (Ц1)–(Ц3) по ячейкам [(сид, ассет, log M реальных окон, log M суррогатов)] для кандидатов Cs."""
    E, mn = CEIL['edges'], min_n()
    assets = list(dict.fromkeys(c[1] for c in cells))
    lr = np.concatenate([c[2] for c in cells])
    ln = np.concatenate([c[3] for c in cells])
    rows = curve(lr, ln, E, mn)
    per = {}
    for a in assets:
        la = np.concatenate([c[2] for c in cells if c[1] == a])
        na = np.concatenate([c[3] for c in cells if c[1] == a])
        per[a] = (la, na, curve(la, na, E, mn))
    out = {'n_windows': int(len(lr)), 'assets': assets, 'curve': rows, 'by_c': {}}
    for C in Cs:
        if C not in E:
            raise ValueError(f"🍆 АЙ, ОШИБКА! потолок {C} — не край корзин {E}")
        pool = pool_check(lr, ln, C, rows)
        pairs = {(a, col): pair_check(per[a][0], per[a][1], col, C, per[a][2]) for a in assets for col in COLORS}
        st = [p['status'] for p in pairs.values()]
        n = len(st)
        over, nod = sum(s == 'завышает' for s in st), sum(s == 'без данных' for s in st)
        g2 = bool(n and over / n <= CEIL['share_over'] and nod / n <= CEIL['share_nodata'])
        un = [a for a in unseen if a in per]                 # незнакомого ассета нет в данных — (Ц3) не прошло
        g3 = ((len(un) == len(unseen) and all(pairs[(a, col)]['status'] == 'ок' for a in un for col in COLORS))
              if unseen else None)
        t_ = math.log(C)
        out['by_c'][C] = {'pool': pool, 'pairs': {f"{a}|{col}": p for (a, col), p in pairs.items()}, 'n_pairs': n,
                          'over': over, 'nodata': nod, 'g1': pool['ok'], 'g2': g2, 'g3': g3, 'unseen': un,
                          'clamp': (float((lr >= t_).mean()), float((lr <= -t_).mean()))}
    return out


def passes(rm, rc, C):
    """Кандидат C прошёл: (Ц1)–(Ц3) на основном источнике, (Ц1)–(Ц2) на подтверждении (нет незнакомых — не прошёл)."""
    m, c = rm['by_c'][C], rc['by_c'][C]
    return bool(m['g1'] and m['g2'] and m['g3'] is True and c['g1'] and c['g2'])


def choose_c(rm, rc):
    for C in CEIL['candidates']:
        if passes(rm, rc, C):
            return C
    return None


