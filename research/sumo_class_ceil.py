def synth_cells(n_assets, n_per, seed, over=(), k_over=1.6):
    """Синтетические ячейки: z реальных окон ~ N(m, 1), суррогатов ~ N(0, 1), log M = m·z − m²/2 — точное отношение
       колоколов (честная линия). У ассетов over оранжевая сторона завышена: положительный log M × k_over."""
    rng = np.random.default_rng(seed)
    ms = {f"SYN{i}USDT": 0.7 + 0.3 * rng.random() for i in range(n_assets)}
    cells = []
    for s_ in ('a', 'b'):
        for a, m in ms.items():
            zr, zs = m + rng.standard_normal(n_per), rng.standard_normal(n_per)
            lr, ln = m * zr - m * m / 2, m * zs - m * m / 2
            if a in over:
                lr = np.where(lr > 0, k_over * lr, lr)
                ln = np.where(ln > 0, k_over * ln, ln)
            cells.append((s_, a, lr, ln))
    return cells


