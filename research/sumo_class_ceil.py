def fold_ids(T, key, d):
    """Половина каждого окна ряда: 0 — TUNE (основной) / П1 (подтверждение), 1 — VAL / П2."""
    if key == CEIL['main']:
        return (np.arange(len(d['sp'])) >= d['B']).astype(np.int8)
    return (~T._nc_half(d['wk'])).astype(np.int8)


def fold_rulers(T, raw, key, skip=()):
    """Перекрёстные линейки: {сид: {половина: квантили суррогатов ДРУГОЙ половины всех ассетов, кроме skip}}."""
    knots, _ = BB.knots_zk(T)
    Q = {}
    for seed, D in raw.items():
        F = {a: fold_ids(T, key, d) for a, d in D.items()}
        Q[seed] = {}
        for f in (0, 1):
            sn = [d['sn'][F[a] != f] for a, d in D.items() if a not in skip]
            sn = np.concatenate(sn) if sn else np.zeros(0)
            if len(sn) < 1000:
                raise ValueError(f"🍆 АЙ, ОШИБКА! {key} сид {seed}: у линейки половины {f} суррогатов {len(sn)}")
            Q[seed][f] = BB.ruler_q(sn, knots)
    return Q


def cells_cross(T, raw, key, v, skip=()):
    """Ячейки правила потолка: у каждого ряда — окна с позиции L + сдвиг (окно живой части полное), z — по перекрёстной
       линейке своей половины, живая часть — формула v по всему ряду. [(сид, ассет, log M реальных, log M суррогатов)]."""
    _, zk = BB.knots_zk(T)
    Q = fold_rulers(T, raw, key, skip)
    P = full_from(v)
    cells = []
    for seed, D in raw.items():
        for a, d in D.items():
            n = len(d['sp'])
            if n <= P:
                continue
            F = fold_ids(T, key, d)
            lr_, ln_ = [], []
            for f in (0, 1):
                zr, zs = BB.to_z(d['sp'], Q[seed][f], zk), BB.to_z(d['sn'], Q[seed][f], zk)
                q = LV.chart_ms(T, zr, [(0, n)], v, {}, p_from=P)
                ok = F[q['i']] == f
                i = q['i'][ok]
                lr_.append(T._nc_logm(zr[i], q['m'][ok], q['s'][ok]))
                ln_.append(T._nc_logm(zs[i], q['m'][ok], q['s'][ok]))
            cells.append((seed, a, np.concatenate(lr_), np.concatenate(ln_)))
    return cells


