@contextlib.contextmanager
def floor_override(data, L, value):
    """Пол делителя всех рядов = value на время блока (наборы проверки, созданные внутри, берут его); потом — как было."""
    import torch
    w = data.windows(L)
    old, old_t = w['floor'], w['floor_t']
    new = np.full_like(old, value)
    try:
        w['floor'], w['floor_t'] = new, torch.from_numpy(new).to(old_t.device)
        yield w
    finally:
        w['floor'], w['floor_t'] = old, old_t


def floor_changed(f_old):
    """Обученный пол ряда не равен новому (во float32, как в коде обучения): только у таких рядов пол что-то меняет."""
    return bool(np.float32(f_old) != np.float32(CEIL['floor']))


def affected(med, mabs, f_old, f_new):
    """Окна, где пол меняет вход модели: делитель max(медиана |r|, пол) (форма, ориентация, боковые входы) или
       log max(среднее |r|, пол) (боковой вход 29, tok_feats). У суррогата |r| те же — и окна те же. float32, как в коде
       обучения."""
    fo, fn = np.float32(f_old), np.float32(f_new)
    out = np.zeros(len(med), dtype=bool)
    for x in (med, mabs):
        x = np.asarray(x, dtype=np.float32)
        out |= np.maximum(x, fo) != np.maximum(x, fn)
    return out


def collect(T, model, pdata, a, part):
    """Оценки модели на окнах ассета a части part — как _nocal_collect кода обучения (тот же набор проверки и суррогат,
       что в npz прогона пула) + медиана и среднее |r| close-канала реального окна (до пола; у суррогата — те же)."""
    data, L = pdata['data'], T.POOL['L']
    store = T.pool_asset_store(data, L, pdata['sid'][a], pdata['t_cut'])
    if len(store.w[part]) < T.CORE_MIN_WIN:
        return None
    P_ = store.positives(part)
    W = P_['W']
    W0 = W[:, 0] if W.dim() == 3 else W
    med = T.median_abs(W0).float().cpu().numpy()
    mabs = W0.abs().mean(dim=1).float().cpu().numpy()          # как aw.mean в tok_feats (боковой вход 29)
    ev = store.get(part, T.NOCAL['null'])
    out = {'st': np.asarray(P_['st']), 'wk': np.asarray(P_['wk']), 'med': med, 'mabs': mabs,
           'sp': T.score(model, P_['X'], S=P_['S']), 'sn': T.score(model, ev['Xn'], S=ev['Sn'])}
    store._pos.clear()
    store._set.clear()
    return out


def needs(T):
    """Модели пересчёта: источники проверки (оба сида) и боевые сиды линейки экспорта. 'old' — нужен ещё пересчёт со
       старым полом тем же способом (у рядов, где пол не 0.2): с ним справочное «что меняет пол» — без шума TF32 npz."""
    m = BB.BELL['model']
    S = BB.BELL['sources']
    out = []
    for key in (CEIL['main'], CEIL['confirm']):
        for seed in BB.BELL['seeds']:
            out.append({'key': key, 'set': S[key]['set'], 'mode': S[key]['mode'], 'seed': seed, 'old': key == CEIL['main'],
                        'parts': tuple(S[key]['parts']), 'tag': T._pool_tag(S[key]['set'], seed, m, S[key]['mode'])})
    for seed in CEIL['prod_seeds']:
        out.append({'key': 'prod', 'set': 'ALL', 'mode': 'prod', 'seed': seed, 'parts': ('val',), 'old': True,
                    'tag': T._pool_tag('ALL', seed, m, 'prod')})
    return out


def cache_path(tag):
    return OUT_DIR + f"cache/ceil_{tag}_f{CEIL['floor']:g}.npz"


def save_cache(item, res, res_old, run, floors):
    """Оценки модели: с полом 0.2 (ключи «ассет__часть__поле») и со старым полом ('old__…')."""
    os.makedirs(OUT_DIR + 'cache/', exist_ok=True)
    arr = {'meta': np.array(json.dumps({'tag': item['tag'], 'floor': CEIL['floor'], 'ver': CEIL_VER, 'run': run,
                                        'floors_trained': floors}))}
    for pre, R in (('', res), ('old__', res_old)):
        for (a, p), d in R.items():
            k = f"{pre}{a}__{p}__"
            arr[k + 'sp'], arr[k + 'sn'] = d['sp'].astype(np.float32), d['sn'].astype(np.float32)
            arr[k + 'med'], arr[k + 'mabs'] = d['med'].astype(np.float32), d['mabs'].astype(np.float32)
            arr[k + 'wk'] = d['wk'].astype(np.int32)
    np.savez(cache_path(item['tag']), **arr)


def load_cache(item):
    p = cache_path(item['tag'])
    if not (CEIL['cache'] and os.path.isfile(p)):
        return None
    with np.load(p) as d:
        meta = json.loads(str(d['meta']))
        if meta.get('tag') != item['tag'] or meta.get('floor') != CEIL['floor'] or meta.get('ver') != CEIL_VER:
            return None
        res, res_old = {}, {}
        for k in d.files:
            if not k.endswith('__sp'):
                continue
            base = k[:-len('sp')]
            old = base.startswith('old__')
            a, part = (base[len('old__'):] if old else base).split('__')[:2]
            (res_old if old else res)[(a, part)] = {
                'sp': d[base + 'sp'].astype(np.float64), 'sn': d[base + 'sn'].astype(np.float64),
                'med': d[base + 'med'], 'mabs': d[base + 'mabs'], 'wk': d[base + 'wk'].astype(np.int64)}
    return {'res': res, 'res_old': res_old, 'run': meta.get('run', {}), 'cached': True,
            'floors': meta.get('floors_trained')}


def preflight(T, pdata, model, item, floors):
    """(3) BTC, первая модель основного источника: пересчёт со старым полом = npz прогона пула (допуск tf32_tol); с полом
       0.2 окна, где пол не сработал, — те же числа (same_tol). Возвращает (итог, оценки BTC с полом 0.2 и со старым)."""
    a, L = CEIL['preflight'], T.POOL['L']
    arr, _ = BB.load_npz(item['tag'])
    t0 = time.time()
    d0 = collect(T, model, pdata, a, 'val')
    t_old = time.time() - t0
    ref = {k: arr.get(f"{a}__val__{k}") for k in ('sp', 'sn', 'wk')}
    same_win = (d0 is not None and ref['sp'] is not None and len(ref['sp']) == len(d0['sp'])
                and np.array_equal(ref['wk'].astype(np.int64), d0['wk'].astype(np.int64)))
    dev = (max(float(np.max(np.abs(ref['sp'] - d0['sp']))), float(np.max(np.abs(ref['sn'] - d0['sn']))))
           if same_win else math.nan)
    with floor_override(pdata['data'], L, CEIL['floor']):
        t0 = time.time()
        d1 = collect(T, model, pdata, a, 'val')
        t_new = time.time() - t0
    aff = affected(d1['med'], d1['mabs'], floors[a], CEIL['floor'])
    keep = ~aff
    same = max(float(np.max(np.abs(d1['sp'][keep] - d0['sp'][keep]), initial=0.0)),
               float(np.max(np.abs(d1['sn'][keep] - d0['sn'][keep]), initial=0.0)))
    moved = (max(float(np.max(np.abs(d1['sp'][aff] - d0['sp'][aff]), initial=0.0)),
                 float(np.max(np.abs(d1['sn'][aff] - d0['sn'][aff]), initial=0.0))) if aff.any() else 0.0)
    ok = bool(same_win and dev <= CEIL['tf32_tol'] and same <= CEIL['same_tol'])
    sec = t_new / max(len(d1['sp']), 1)
    print(f"   {a} VAL ({item['tag']}): окон {len(d1['sp'])} — те же, что в npz: {same_win} | старый пол: max |Δ logit| "
          f"к npz {_f(dev, '.1e')} (допуск {CEIL['tf32_tol']:g}) | пол {CEIL['floor']:g} (обученный {floors[a]:.4f}): "
          f"сработал у {int(aff.sum())} окон ({100 * aff.mean():.2f}%), там max |Δ logit| {moved:.3f}; у остальных "
          f"{same:.1e} (допуск {CEIL['same_tol']:g}) | {t_old:.1f} c / {t_new:.1f} c | {'✅' if ok else '❌'}")
    return {'ok': ok, 'same_windows': same_win, 'dev_npz': dev, 'same_unaffected': same, 'moved_affected': moved,
            'n': int(len(d1['sp'])), 'n_affected': int(aff.sum()), 'sec_per_window': sec}, d1, d0


def recompute_all(T, assets):
    """Оценки всех моделей needs() с полом 0.2 на всех ассетах (у моделей с 'old' — ещё со старым полом там, где он не
       0.2); кэш — OUT_DIR/cache/. Перед циклом — сверка (3) на BTC (или, если основной источник уже в кэше, — замер
       времени на одном наборе) и оценка времени. Возвращает ({тег: {'res', 'res_old', 'run'}}, обученные полы, итог
       сверки (3)) или (None, …) — стоп."""
    import torch
    torch.backends.cudnn.allow_tf32 = False         # точный float32: как эталон в репо и Pine (R3)
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False
    dev_name = torch.cuda.get_device_name(0) if torch.cuda.is_available() else 'CPU'
    items = needs(T)
    out = {}
    todo = []
    for it in items:
        c = load_cache(it)
        if c is not None:
            out[it['tag']] = c
            print(f"   💾 {it['tag']}: из кэша ({len(c['res'])} частей, со старым полом {len(c['res_old'])})")
        else:
            todo.append(it)
    fl_c = [c['floors'] for c in out.values() if c.get('floors')]
    if not todo and fl_c and all(set(assets) <= set(f) for f in fl_c):
        print(f"\n🧮 ПЕРЕСЧЁТ ОЦЕНОК С ПОЛОМ {CEIL['floor']:g}: все модели — из кэша")
        return out, {a: float(fl_c[0][a]) for a in assets}, None
    m_name = BB.BELL['model']
    if m_name not in T.RUNS:
        raise KeyError(f"🍆 АЙ, ОШИБКА! нет модели {m_name} в RUNS кода обучения")
    cfg_m = {**T.SMC_BASE, **T.RUNS[m_name]}
    T.DATA_OVERLAY = None                            # данные research у всех ассетов (как 'nocal' и прогоны пула)
    nt_cols = sorted(set(T._pool_nt_cols(m_name)) | {c_ for c_ in T.NOCAL['cond_cols'] if c_ >= T.NT_COL0})
    print(f"\n🧮 ПЕРЕСЧЁТ ОЦЕНОК С ПОЛОМ {CEIL['floor']:g} | {T.DEVICE} ({dev_name}), TF32 выключен | моделей "
          f"{len(items)}, из кэша {len(items) - len(todo)}")
    pdata = T.pool_data(common_end=False, price=cfg_m['price'], nt_cols=nt_cols)
    pre = None
    try:
        L = T.POOL['L']
        w = pdata['data'].windows(L)
        floors = {a: float(w['floor'][pdata['sid'][a]]) for a in assets}
        ch = [a for a in assets if floor_changed(floors[a])]
        print(f"   обученный пол не {CEIL['floor']:g} у {len(ch)} из {len(assets)}: "
              + ', '.join(f"{a[:-4]} {floors[a]:.4f}" for a in ch))
        parts = sorted({p for it in todo for p in it['parts']})
        size = {}
        for a in assets:
            st_ = T.pool_asset_store(pdata['data'], L, pdata['sid'][a], pdata['t_cut'])
            size.update({(a, p): len(st_.w[p]) for p in parts})
        n_total = sum(size[(a, p)] * (1 + int(it['old'] and floor_changed(floors[a])))
                      for it in todo for a in assets for p in it['parts'])
        reuse = {}                                   # (тег, ассет, часть) -> оценки, уже посчитанные до цикла
        sec = None
        first = next((it for it in todo if it['key'] == CEIL['main']), None)
        if first is not None:
            print("🔎 СВЕРКА 3: пересчёт BTC — старый пол против npz, пол 0.2 против старого")
            model, _ = T.load_pool_model(first['set'], first['seed'], m_name, first['mode'])
            pre, d1, d0 = preflight(T, pdata, model, first, floors)
            del model
            if not pre['ok']:
                print("🍆 АЙ, ОШИБКА! сверка (3) не прошла — пересчёт не воспроизводит прогоны пула; дальше не идём")
                return None, floors, pre
            reuse[(first['tag'], CEIL['preflight'], 'val')] = {'new': d1, 'old': d0}
            sec = pre['sec_per_window']
        elif todo:                                   # основной источник — из кэша: время — по одному набору
            it0 = todo[0]
            a0, p0 = CEIL['preflight'], it0['parts'][-1]
            model, _ = T.load_pool_model(it0['set'], it0['seed'], m_name, it0['mode'])
            t0 = time.time()
            with floor_override(pdata['data'], L, CEIL['floor']):
                d = collect(T, model, pdata, a0, p0)
            if d is None:
                raise RuntimeError(f"🍆 АЙ, ОШИБКА! {it0['tag']}: у {a0} нет окон части {p0} — замер времени невозможен")
            sec = (time.time() - t0) / max(len(d['sp']), 1)
            reuse[(it0['tag'], a0, p0)] = {'new': d, 'old': None}
            del model
        if sec is not None:
            eta = sec * n_total / 60
            print(f"   ⏱️ оценка пересчёта: ~{eta:.0f} мин ({n_total} окон, с полом 0.2 и со старым)")
            if T.DEVICE.type == 'cpu' and eta > CEIL['cpu_max_min']:
                print(f"🍆 СТОП: на CPU пересчёт займёт ~{eta:.0f} мин — включи GPU (Среда выполнения -> Сменить тип "
                      f"среды -> T4 GPU) и запусти снова")
                return None, floors, pre
        t0 = time.time()
        for it in todo:
            model, r = T.load_pool_model(it['set'], it['seed'], m_name, it['mode'])
            run = {'tag': r['tag'], 't_cut': r.get('t_cut'), 'data_overlay': r.get('data_overlay')}
            res, res_old = {}, {}
            for a in assets:
                need_old = it['old'] and floor_changed(floors[a])
                for p in it['parts']:
                    got = reuse.get((it['tag'], a, p), {})
                    d = got.get('new')
                    if d is None:
                        with floor_override(pdata['data'], L, CEIL['floor']):
                            d = collect(T, model, pdata, a, p)
                    if d is None:
                        continue
                    res[(a, p)] = d
                    if need_old:
                        res_old[(a, p)] = got.get('old') or collect(T, model, pdata, a, p)
                if T.DEVICE.type == 'cuda':
                    torch.cuda.empty_cache()
            if CEIL['cache']:
                save_cache(it, res, res_old, run, floors)
            out[it['tag']] = {'res': res, 'res_old': res_old, 'run': run, 'cached': False}
            print(f"   🧠 {it['tag']}: частей {len(res)}, со старым полом {len(res_old)} | {(time.time() - t0) / 60:.1f} мин")
            del model
        return out, floors, pre
    finally:
        T._reset_nt_keep()
        del pdata
        if T.DEVICE.type == 'cuda':
            torch.cuda.empty_cache()


def raw_from(T, key, rec, raw_b, floors, which='new'):
    """Оценки пересчёта в виде Bell (как read_source_raw): части склеены по времени, B — окон разгона; окна и их порядок —
       те же, что в npz (недели совпадают), иначе ошибка. which 'new' — пол 0.2, 'old' — старый пол (у рядов, где он 0.2, —
       те же оценки). Возвращает (raw, {сид: {ассет: (медиана |r|, среднее |r|)}})."""
    S = BB.BELL['sources'][key]
    raw, med = {}, {}
    for seed, Db in raw_b.items():
        tag = T._pool_tag(S['set'], seed, BB.BELL['model'], S['mode'])
        R = rec[tag]
        D, M = {}, {}
        for a, db in Db.items():
            parts = []
            for p in S['parts']:
                x = R['res'].get((a, p))
                if which == 'old' and floor_changed(floors[a]):
                    x = R['res_old'].get((a, p))
                parts.append(x)
            if any(x is None for x in parts):
                raise ValueError(f"🍆 АЙ, ОШИБКА! {tag} {a}: в пересчёте ({which}) нет части {S['parts']}")
            wk = np.concatenate([x['wk'] for x in parts]).astype(np.int64)
            if not np.array_equal(wk, db['wk']):
                raise ValueError(f"🍆 АЙ, ОШИБКА! {tag} {a}: окна пересчёта не те, что в npz (недели не совпали)")
            D[a] = {'sp': np.concatenate([x['sp'] for x in parts]).astype(np.float64),
                    'sn': np.concatenate([x['sn'] for x in parts]).astype(np.float64), 'wk': wk, 'B': db['B']}
            M[a] = (np.concatenate([x['med'] for x in parts]), np.concatenate([x['mabs'] for x in parts]))
        raw[seed], med[seed] = D, M
    return raw, med


