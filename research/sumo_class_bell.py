SYN_MU, SYN_SD = -0.53, 1.42      # логиты = μ + σ·z (как у линейки боевых: μ ≈ −0.53, σ ≈ 1.42)


def ma_noise(rng, n, L):
    """Шум окон: скользящее среднее L белых шумов, разброс 1 — соседние окна похожи, как окна с общими барами (τ = L)."""
    w = rng.standard_normal(n + L - 1)
    c = np.concatenate([[0.0], np.cumsum(w)])
    return (c[L:] - c[:-L]) / math.sqrt(L)


def ou(rng, n, sd, tc):
    """Медленный дрейф центра колокола: процесс Орнштейна — Уленбека с разбросом sd и временем памяти tc окон
       (x_0 — из стационарного распределения, дальше x_t = φ·x_{t−1} + η_t)."""
    from scipy.signal import lfilter
    phi = math.exp(-1.0 / tc)
    eta = rng.standard_normal(n) * sd * math.sqrt(1.0 - phi * phi)
    eta[0] = rng.standard_normal() * sd
    return lfilter([1.0], [1.0, -phi], eta)


def synth_raw(kind, n_assets, n_win, burn, w0, seed=7):
    """Синтетический источник: {сид: {ассет: sp, sn, wk, B}} и истинный центр колокола по ассетам.
       kind 'S' — колокол стоит; 'D' — центр дрейфует (OU: разброс 0.25, память 8 000 окон ≈ 4 недели)."""
    rng = np.random.default_rng(seed)
    raw = {s_: {} for s_ in BELL['seeds']}
    truth = {}
    for i in range(n_assets):
        a = f"SYN{i}USDT"
        m0, s0 = rng.uniform(0.6, 1.0), rng.uniform(0.85, 0.98)
        mt = m0 + (ou(rng, n_win, 0.25, 8000) if kind == 'D' else np.zeros(n_win))
        u = ma_noise(rng, n_win, 64)
        for s_ in BELL['seeds']:
            us = ma_noise(rng, n_win, 64)
            zr = mt + s0 * (0.97 * u + math.sqrt(1 - 0.97 ** 2) * us)      # две реплики модели: общий шум окна ~94%
            zs = rng.standard_normal(n_win)
            raw[s_][a] = {'sp': SYN_MU + SYN_SD * zr, 'sn': SYN_MU + SYN_SD * zs,
                          'wk': w0 + np.arange(n_win) // 2016, 'B': burn}
        truth[a] = mt
    return raw, truth


def mse_opt_span(T, src, truth):
    """Span EMA, лучше всего следящий за истинным центром колокола (среднеквадратично, со сдвигом lag), — тонкая сетка."""
    grid = np.unique(np.geomspace(512, 65536, 22).round().astype(int))
    err = []
    for sp in grid:
        e, n = 0.0, 0
        for _, a, d in series_iter(src):
            B = d['B']
            m = shift(live(T, d['zr'], int(sp))[0], BELL['lag'])[B:]
            e += float(np.sum((m - truth[a][B:]) ** 2))
            n += len(m)
        err.append(e / n)
    return int(grid[int(np.argmin(err))]), dict(zip(grid.tolist(), err))


