def ruler_q(sn, knots):
    """Линейка glob_e: квантили логитов суррогатов в узлах (как _nc_fit кода обучения: c['q'])."""
    return np.quantile(np.asarray(sn, dtype=np.float64), knots)


def to_z(x, q, zk):
    """z окна по линейке: прямые между узлами в шкале z, за крайними узлами — край (как _nc_z, 'glob_e')."""
    return np.interp(np.asarray(x, dtype=np.float64), q, zk)


