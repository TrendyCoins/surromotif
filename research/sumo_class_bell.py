def block_ms(z, N):
    """m и s куска из N окон, начинающегося с каждого окна t (через накопленные суммы)."""
    c1 = np.concatenate([[0.0], np.cumsum(z)])
    c2 = np.concatenate([[0.0], np.cumsum(z * z)])
    m = (c1[N:] - c1[:-N]) / N
    v = (c2[N:] - c2[:-N]) / N - m * m
    return m, np.sqrt(np.maximum(v, 0.0))


def cluster_mean_se(sums, cnts):
    """Среднее (Σ сумм / Σ счётов) и его ошибка с кластерами-группами (G / (G − 1)); меньше allan_min_groups групп —
       ошибки нет."""
    tot = cnts.sum()
    mean = sums.sum() / tot
    G = int((cnts > 0).sum())
    if G < BELL['allan_min_groups']:
        return mean, math.nan
    ok = cnts > 0
    gm = sums[ok] / cnts[ok]
    var = G / (G - 1) * np.sum((cnts[ok] / tot) ** 2 * (gm - mean) ** 2)
    return mean, math.sqrt(var)


def allan(T, src, refs):
    """Кривая Аллана по всем рядам источника (сид × ассет): на каждом N — дисперсия Аллана m, s и log M у порогов
       (refs: {'o': z у M = 3, 'b': z у M = 1/3}), её ошибка по кластерам времени и шумовая дисперсия m (вес ряда — число
       пар). Кластер — не короче group_weeks недель и group_span длин пары кусков (2N + зазор окон): пары из разных
       кластеров мало делят окна, иначе ошибка на больших N занижена (стенд: при 6 кластерах по 17 недель — вдвое)."""
    G = BELL['allan_gap']
    keys = ('m', 's', 'o', 'b')
    rows = []
    for N in BELL['allan_n']:
        GW = max(BELL['group_weeks'], int(math.ceil(BELL['group_span'] * (2 * N + G) / 2016)))
        acc, noise_num, noise_den, n_ser = {}, 0.0, 0, 0
        for _, _, d in series_iter(src):
            z, wk = d['zr'], d['wk']
            P = len(z) - 2 * N - G + 1
            if P < BELL['allan_min_pairs']:
                continue
            m, s = block_ms(z, N)
            m1, m2, s1, s2 = m[:P], m[N + G:N + G + P], s[:P], s[N + G:N + G + P]
            diff = {'m': m2 - m1, 's': s2 - s1}
            for k in ('o', 'b'):
                if np.isfinite(refs.get(k, math.nan)):
                    zz = np.full(P, refs[k])
                    diff[k] = T._nc_logm(zz, m2, s2) - T._nc_logm(zz, m1, s1)
            g = wk[np.arange(P) + N + G // 2] // GW
            gu, inv = np.unique(g, return_inverse=True)
            cnt = np.bincount(inv, minlength=len(gu)).astype(np.float64)
            for j, gid in enumerate(gu):
                acc.setdefault(int(gid), {k: 0.0 for k in keys + ('n',)})
                acc[int(gid)]['n'] += cnt[j]
            for k, dv in diff.items():
                sq = np.bincount(inv, weights=dv * dv, minlength=len(gu))
                for j, gid in enumerate(gu):
                    acc[int(gid)][k] += sq[j]
            noise_num += P * noise_var(d['acf'], N)
            noise_den += P
            n_ser += 1
        if not n_ser:
            continue
        gids = sorted(acc)
        cnts = np.array([acc[g_]['n'] for g_ in gids])
        row = {'N': N, 'series': n_ser, 'pairs': int(cnts.sum()), 'groups': len(gids), 'group_weeks': GW,
               'noise_m': noise_num / noise_den}
        for k in keys:
            sums = np.array([acc[g_][k] for g_ in gids])
            if not sums.any() and k in ('o', 'b'):
                row[f'A_{k}'], row[f'se_{k}'] = math.nan, math.nan
                continue
            mean, se = cluster_mean_se(sums, cnts)
            row[f'A_{k}'], row[f'se_{k}'] = 0.5 * mean, 0.5 * se
        rows.append(row)
    return rows


def drift_flag(r):
    """На этом N колокол движется сильнее шума: дисперсия Аллана m выше шумовой больше чем на drift_se SE и σ_A выше
       шумового хотя бы в drift_ratio раза."""
    return bool(np.isfinite(r['se_m']) and r['A_m'] - r['noise_m'] > BELL['drift_se'] * r['se_m']
                and math.sqrt(r['A_m'] / r['noise_m']) >= BELL['drift_ratio'])


def verdict_conv(rows):
    """Правило (1): картина (А) — колокол сходится как шум, (Б) — колокол движется сам (дрейф). Минимум кривой Аллана —
       справочно: у дрейфа с возвратом (режимы рынка) кривая на очень больших N снова падает — длинное среднее
       сходится к среднему режимов, а не к колоколу «сейчас»; длину живой части решает часть (2)."""
    ok = [r for r in rows if np.isfinite(r['se_m'])]
    ex = [drift_flag(r) for r in ok]
    # дрейф — с N, начиная с которого флаг стоит у всех больших N с ошибкой, и таких N (вместе с ним) не меньше двух:
    # одна точка на краю сетки, где ошибка самая шаткая, вердикт не решает
    n_drift = next((r['N'] for i, r in enumerate(ok) if all(ex[i:]) and len(ok) - i >= 2), None)
    if len(ok) < 2:
        return {'n_drift': None, 'kind': None, 'n_tol': None}
    out = {'n_drift': n_drift, 'kind': 'A' if n_drift is None else 'B'}
    if ok:
        out['n_allan_min'] = ok[int(np.argmin([r['A_m'] for r in ok]))]['N']
        out['excess_last'] = math.sqrt(ok[-1]['A_m'] / ok[-1]['noise_m'])
    tol = math.log(1.0 + BELL['tol_m'])

    def wobble_ok(r):
        vals = [math.sqrt(r[f'A_{k}']) for k in ('o', 'b') if np.isfinite(r.get(f'A_{k}', math.nan))]
        return bool(vals) and max(vals) <= tol
    out['n_tol'] = next((r['N'] for r in rows if wobble_ok(r)), None)
    return out


