def load_npz(tag):
    """Оценки окон прогона пула: RUN_DIR/pool/<tag>.npz целиком или частями <tag>_part*.npz (как в репо после Pack)."""
    base = RUN_DIR + 'pool/' + tag
    paths = [base + '.npz'] if os.path.isfile(base + '.npz') else sorted(glob.glob(base + '_part*.npz'))
    if not paths:
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет оценок прогона {tag}: ни {base}.npz, ни частей {base}_part*.npz")
    arr = {}
    for p in paths:
        with np.load(p) as d:
            arr.update({k: d[k] for k in d.files if not k.startswith('sd_')})
    return arr, paths


def read_source_raw(T, key, assets):
    """Сырые оценки источника: {сид: {ассет: sp, sn (логиты реальных окон и их суррогатов), wk (неделя конца окна), B
       (окон разгона)}}. Части склеиваются по времени; порядок окон проверяется (недели не убывают, у BTC — начала окон)."""
    S = BELL['sources'][key]
    raw, tags = {}, {}
    for seed in BELL['seeds']:
        tag = T._pool_tag(S['set'], seed, BELL['model'], S['mode'])
        arr, paths = load_npz(tag)
        tags[seed] = [os.path.basename(p) for p in paths]
        for p in S['parts']:
            st = arr.get(f"{BELL['ref']}__{p}__st")
            if st is not None and not (np.diff(st) > 0).all():
                raise ValueError(f"🍆 АЙ, ОШИБКА! {tag}: начала окон {BELL['ref']} ({p}) не растут — порядок окон неизвестен")
        D = {}
        for a in assets:
            if not all(f"{a}__{p}__{f}" in arr for p in S['parts'] for f in ('sp', 'sn', 'wk')):
                continue
            sp = np.concatenate([arr[f"{a}__{p}__sp"] for p in S['parts']]).astype(np.float64)
            sn = np.concatenate([arr[f"{a}__{p}__sn"] for p in S['parts']]).astype(np.float64)
            wk = np.concatenate([arr[f"{a}__{p}__wk"] for p in S['parts']]).astype(np.int64)
            if (np.diff(wk) < 0).any():
                raise ValueError(f"🍆 АЙ, ОШИБКА! {tag} {a}: недели окон убывают — порядок окон неизвестен")
            if S['burn'] == 'tune':
                B = len(arr[f"{a}__tune__sp"])
            else:
                h1 = T._nc_half(wk)
                B = int(h1.sum())
                if not h1[:B].all():
                    raise ValueError(f"🍆 АЙ, ОШИБКА! {tag} {a}: окна П1 не идут первыми")
            D[a] = {'sp': sp, 'sn': sn, 'wk': wk, 'B': B}
        raw[seed] = D
    return raw, tags


def build_source(T, key, raw, about, rng_seed=12345):
    """Ряды z источника: линейка — по суррогатам разгона всех ассетов сида; у каждого ряда — автокорреляция и модель
       случайного графика (свой генератор на ряд: результат не зависит от порядка)."""
    knots, zk = knots_zk(T)
    rho_w = rho_window_only()
    src = {'key': key, 'about': about, 'series': {}, 'ruler': {}}
    for i_s, (seed, D) in enumerate(raw.items()):
        q = ruler_q(np.concatenate([d['sn'][:d['B']] for d in D.values()]), knots)
        src['ruler'][seed] = q
        S = {}
        for i_a, (a, d) in enumerate(D.items()):
            zr, zs = to_z(d['sp'], q, zk), to_z(d['sn'], q, zk)
            info = acf_info(zr)
            rng = np.random.default_rng([rng_seed, i_s, i_a])
            S[a] = {'zr': zr, 'zs': zs, 'wk': d['wk'], 'B': d['B'], 'acf': info, 'tau_surr': acf_info(zs)['tau'],
                    'zg': gp_chart(info['rho_null'], len(zr), rng),       # модель случайного графика (ворота (в))
                    'zw': gp_chart(rho_w, len(zr), rng)}                   # оптимистичная граница (справочно)
        src['series'][seed] = S
    src['burn_min'] = min(d['B'] for S in src['series'].values() for d in S.values())
    return src


def series_iter(src):
    for seed, S in src['series'].items():
        for a, d in S.items():
            yield seed, a, d


