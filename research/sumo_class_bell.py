def variants():
    """Варианты живой части: все span сетки со сдвигом lag и строка «как в индикаторе» (span_now без сдвига)."""
    out = [{'key': str(sp), 'span': sp, 'lag': BELL['lag']} for sp in BELL['spans']]
    out.append({'key': f"{BELL['span_now']}·0", 'span': BELL['span_now'], 'lag': 0})
    return out


def week_index(src):
    w = np.concatenate([d['wk'][d['B']:] for _, _, d in series_iter(src)])
    return int(w.min()), int(w.max() - w.min() + 1)


def eval_spans(T, src, vlist=None):
    """BCE линии M по неделям оценки (пулом и по ассетам), сводка R9 / R11 ('nocal'), отмеченность реальных окон,
       случайный график (модель, оптимистичная граница и суррогаты) — на каждом варианте живой части (vlist — свои
       варианты, по умолчанию variants())."""
    w0, W = week_index(src)
    l125, l3 = math.log(1.25), math.log(BELL['m_ref'])
    res = {}
    for v in (vlist or variants()):
        sp, lag = v['span'], v['lag']
        wsum, wcnt = np.zeros(W), np.zeros(W)
        per_a, cells = {}, []
        cnt = {'n': 0, 'r_o3': 0, 'r_b3': 0, 'g_col': 0, 'g_strong': 0, 'w_col': 0, 's_col': 0}
        for seed, a, d in series_iter(src):
            B = d['B']
            if B < lag:
                raise ValueError(f"🍆 АЙ, ОШИБКА! {a}: разгон {B} окон меньше сдвига {lag}")
            m, s = live(T, d['zr'], sp)
            ml, sl = shift(m, lag)[B:], shift(s, lag)[B:]
            lr = T._nc_logm(d['zr'][B:], ml, sl)
            ln = T._nc_logm(d['zs'][B:], ml, sl)
            b = bce_pairs(lr, ln)
            wi = d['wk'][B:] - w0
            ws, wc = np.bincount(wi, weights=b, minlength=W), np.bincount(wi, minlength=W).astype(np.float64)
            wsum += ws
            wcnt += wc
            pa = per_a.setdefault(a, [np.zeros(W), np.zeros(W)])
            pa[0] += ws
            pa[1] += wc
            cells.append((seed, a, lr, ln))
            cnt['n'] += len(lr)
            cnt['r_o3'] += int((lr >= l3).sum())
            cnt['r_b3'] += int((lr <= -l3).sum())
            mg, sg = live(T, d['zg'], sp)                       # модель случайного графика: живая часть по нему самому
            lg = T._nc_logm(d['zg'][B:], shift(mg, lag)[B:], shift(sg, lag)[B:])
            cnt['g_col'] += int((np.abs(lg) >= l125).sum())
            cnt['g_strong'] += int((np.abs(lg) >= l3).sum())
            mw, sw = live(T, d['zw'], sp)                       # оптимистичная граница: только общие бары окна
            lw = T._nc_logm(d['zw'][B:], shift(mw, lag)[B:], shift(sw, lag)[B:])
            cnt['w_col'] += int((np.abs(lw) >= l125).sum())
            ms_, ss_ = live(T, d['zs'], sp)                     # случайный график по суррогатам (как 'nocal')
            ls = T._nc_logm(d['zs'][B:], shift(ms_, lag)[B:], shift(ss_, lag)[B:])
            cnt['s_col'] += int((np.abs(ls) >= l125).sum())
        summ = T._nc_summary(cells)
        del cells
        with np.errstate(invalid='ignore', divide='ignore'):
            wk_mean = wsum / wcnt
            pa_mean = {a: x[0] / x[1] for a, x in per_a.items()}
        n = cnt['n']
        res[v['key']] = {**v, 'wk_bce': wk_mean, 'wk_n': wcnt, 'per_asset': pa_mean,
                         'bce': float(np.nanmean(wk_mean)), 'ceil': summ['ceil'], 'share': summ['share'],
                         'cover': summ['cover'], 'cover3': (cnt['r_o3'] / n, cnt['r_b3'] / n),
                         'gp_col': cnt['g_col'] / n, 'gp_strong': cnt['g_strong'] / n, 'win_col': cnt['w_col'] / n,
                         'sur_col': cnt['s_col'] / n,
                         'n': n, 'warm_ok': bool(sp == 'inf' or src['burn_min'] >= BELL['warm_full'] * sp)}
    return res, w0


def paired(res, k, k_ref, field='wk_bce', asset=None):
    """Разница BCE варианта k с вариантом k_ref: среднее по неделям и ошибка (парно по тем же неделям)."""
    if asset is None:
        x, y = res[k][field], res[k_ref][field]
    else:
        x, y = res[k]['per_asset'][asset], res[k_ref]['per_asset'][asset]
    d = x - y
    d = d[np.isfinite(d)]
    if len(d) < 3:
        return math.nan, math.nan
    if np.all(d == 0):
        return 0.0, 0.0
    return float(d.mean()), float(d.std(ddof=1) / math.sqrt(len(d)))


def gates(T, r):
    N_ = T.NOCAL
    g = {'warm': r['warm_ok'], 'a': min(r['ceil'].values()) >= N_['ceil_pool'], 'b': r['share'] >= N_['pass_share'],
         'c': r['gp_col'] <= BELL['null_cover_max']}
    g['all'] = all(g.values())
    return g


def choose(T, res):
    """Правило (2): кандидаты (прогрев и ворота) -> лучший по BCE -> полоса 1 SE -> N* — самый длинный span полосы."""
    keys = [v['key'] for v in variants() if v['lag'] == BELL['lag']]
    g = {k: gates(T, res[k]) for k in keys}
    cands = [k for k in keys if g[k]['all']]
    out = {'gates': g, 'cands': cands, 'best': None, 'band': [], 'n_star': None}
    if not cands:
        return out
    best = min(cands, key=lambda k: res[k]['bce'])
    delta = {k: paired(res, k, best) for k in keys}
    band = [k for k in cands if k == best or delta[k][0] <= BELL['band_se'] * delta[k][1]]
    out.update({'best': best, 'delta': delta, 'band': band,
                'n_star': max(band, key=lambda k: span_val(res[k]['span']))})
    return out


def confirm(res_c, n_star):
    """Правило (3): на подтверждающем источнике N* не хуже лучшего (среди span с полным прогревом) больше чем на 2 SE."""
    keys = [v['key'] for v in variants() if v['lag'] == BELL['lag'] and res_c[v['key']]['warm_ok']]
    if n_star is None or n_star not in keys:
        return {'ok': None, 'why': 'N* без полного прогрева на этом источнике — не проверяется', 'keys': keys}
    best = min(keys, key=lambda k: res_c[k]['bce'])
    d, se = paired(res_c, n_star, best)
    ok = bool(n_star == best or d <= BELL['confirm_se'] * se)
    return {'ok': ok, 'best': best, 'delta': d, 'se': se, 'keys': keys}


