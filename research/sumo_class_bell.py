def bell_avg(src):
    """Средний колокол реальных окон источника на оценочной части: средние по рядам их m и s."""
    ms = [d['zr'][d['B']:].mean() for _, _, d in series_iter(src)]
    ss = [d['zr'][d['B']:].std() for _, _, d in series_iter(src)]
    return float(np.mean(ms)), float(np.mean(ss))


