def nocal_cells_mine(T, D, knots, zk, span, warm):
    """То же, что _nc_cells(D, 'glob_e', R, zk, span) кода обучения, своими функциями этого файла (линейка, z, живая
       часть, прогрев): должно совпасть бит в бит."""
    out = []
    for s_, Dd in D.items():
        ds = [d for d in Dd.values() if d]
        q = {h: ruler_q(np.concatenate([d['sn'][T._nc_half(d['wk']) != h] for d in ds]), knots) for h in (True, False)}
        for a, d in Dd.items():
            h1 = T._nc_half(d['wk'])
            n = len(d['sp'])
            for h in (True, False):
                if not (h1 == h).any():
                    continue
                zr, zn = to_z(d['sp'], q[h], zk), to_z(d['sn'], q[h], zk)
                m, s = live(T, zr, span)
                ok = (h1 == h) & (np.arange(n) >= warm)
                out.append((s_, a, T._nc_logm(zr[ok], m[ok], s[ok]), T._nc_logm(zn[ok], m[ok], s[ok])))
    return out


def _ceil_val(v):
    return math.inf if v is None or (isinstance(v, float) and not math.isfinite(v)) else float(v)


def compare_summary(sm, ref, tol):
    """Сводка _nc_summary против части json 'nocal': окон в корзинах — точно, отношения — до tol, потолки и доля пар —
       те же, у каждого ассета — те же корзины и потолки."""
    def rows_ok(a_rows, b_rows):
        if len(a_rows) != len(b_rows):
            return False, math.inf
        same = all(x['color'] == y['color'] and x['lo'] == y['lo'] and x['n_real'] == y['n_real']
                   and x['n_surr'] == y['n_surr'] and bool(x['sparse']) == bool(y['sparse']) for x, y in zip(a_rows, b_rows))
        worst = 0.0
        for x, y in zip(a_rows, b_rows):
            rx = math.nan if x['ratio'] is None else float(x['ratio'])
            ry = math.nan if y['ratio'] is None else float(y['ratio'])
            if math.isnan(rx) or math.isnan(ry):
                worst = worst if (math.isnan(rx) and math.isnan(ry)) else math.inf
            else:
                worst = max(worst, abs(rx - ry))
        return same, worst
    same, worst = rows_ok(sm['rows'], ref['rows'])
    ceil_ok = all(_ceil_val(sm['ceil'][c]) == _ceil_val(ref['ceil'][c]) for c in ('orange', 'blue'))
    a_ok, a_worst = sorted(sm['assets']) == sorted(ref['assets']), 0.0
    for a, p in sm['assets'].items():
        q = ref['assets'].get(a)
        if q is None:
            continue
        s_, w_ = rows_ok(p['rows'], q['rows'])
        a_worst = max(a_worst, w_)
        a_ok &= s_ and _ceil_val(p['orange']) == _ceil_val(q['orange']) and _ceil_val(p['blue']) == _ceil_val(q['blue'])
    ok = bool(same and worst <= tol and a_worst <= tol and a_ok and ceil_ok and sm['n'] == ref['n']
              and sm['share'] == ref['share'])
    return {'ok': ok, 'n': [sm['n'], ref['n']], 'rows_exact': same, 'max_d_ratio': worst, 'assets_ok': bool(a_ok),
            'assets_max_d_ratio': a_worst, 'ceil': [sm['ceil'], ref['ceil']], 'share': [sm['share'], ref['share']]}


def check_nocal(T):
    """Сверка: на npz 'refit' ALL функции линии M кода обучения воспроизводят json 'nocal' (span 8064, glob_e), а свои
       функции этого файла — те же окна бит в бит. Возвращает (итог, список ассетов в порядке json)."""
    paths = sorted(glob.glob(RUN_DIR + f"nocal/nocal_{BELL['model']}_*.json"))
    if not paths:
        print(f"   ❌ нет json 'nocal' модели {BELL['model']} в {RUN_DIR}nocal/")
        return {'ok': False, 'why': 'нет json nocal'}, None
    with open(paths[-1], encoding='utf-8') as fh:
        nc = json.load(fh)
    knots, zk = knots_zk(T)
    assets = list(nc['variants']['glob_e']['assets'])
    same_rules = bool(np.array_equal(np.asarray(nc['knots'], dtype=np.float64), knots)
                      and nc['rules']['s_lo'] == T.NOCAL['s_lo'] and nc['rules']['warm'] == T.NOCAL['warm'])
    n_cond = len(T.NOCAL['cond_cols'])
    D = {}
    for s_ in nc['seeds']:
        arr, _ = load_npz(T._pool_tag(nc['src'][0], s_, nc['model'], nc['src'][1]))
        D[s_] = {}
        for a in assets:
            if f"{a}__val__sp" not in arr:
                continue
            n = len(arr[f"{a}__val__sp"])
            D[s_][a] = {'sp': arr[f"{a}__val__sp"].astype(np.float64), 'sn': arr[f"{a}__val__sn"].astype(np.float64),
                        'wk': arr[f"{a}__val__wk"], 'st': np.arange(n), 'zf': np.zeros((n, n_cond), np.float32),
                        'zfn': np.zeros((n, n_cond), np.float32)}
    span = nc['rules']['span']
    R = T._nc_rulers(D, knots)
    cells_r = T._nc_cells(D, 'glob_e', R, zk, span)
    cmp_ = compare_summary(T._nc_summary(cells_r), nc['variants']['glob_e'], BELL['check_ratio_tol'])
    cells_m = nocal_cells_mine(T, D, knots, zk, span, T.NOCAL['warm'])
    bit = len(cells_r) == len(cells_m) and all(
        x[0] == y[0] and x[1] == y[1] and np.array_equal(x[2], y[2]) and np.array_equal(x[3], y[3])
        for x, y in zip(cells_r, cells_m))
    ok = bool(cmp_['ok'] and bit and same_rules and nc['model'] == BELL['model'])
    print(f"   json {os.path.basename(paths[-1])}: окон {cmp_['n'][0]} / {cmp_['n'][1]} | корзины точно {cmp_['rows_exact']} "
          f"| max |Δ отношения| {cmp_['max_d_ratio']:.1e} (ассеты {cmp_['assets_max_d_ratio']:.1e}) | потолки пула "
          f"{cmp_['ceil'][0]} / json {cmp_['ceil'][1]} | доля пар {cmp_['share'][0]:.4f} / {cmp_['share'][1]:.4f} | "
          f"свои функции = код обучения бит в бит: {bit} | {'✅' if ok else '❌'}")
    return {'ok': ok, 'json': os.path.basename(paths[-1]), 'compare': cmp_, 'bit': bit, 'same_rules': same_rules}, assets


