def self_vote(T, src, span):
    """Самоголосование без сдвига: насколько число на линии у реальных окон с сильной отметкой (M >= 3 / <= 1/3 по линии
       со сдвигом) выше / ниже, если живая часть видит соседей окна (как сейчас в индикаторе). Средняя разница log M -> %."""
    l3 = math.log(BELL['m_ref'])
    up, dn = [], []
    for _, _, d in series_iter(src):
        B = d['B']
        m, s = live(T, d['zr'], span)
        l0 = T._nc_logm(d['zr'][B:], m[B:], s[B:])
        l64 = T._nc_logm(d['zr'][B:], shift(m, BELL['lag'])[B:], shift(s, BELL['lag'])[B:])
        up.append((l0 - l64)[l64 >= l3])
        dn.append((l0 - l64)[l64 <= -l3])
    up, dn = np.concatenate(up), np.concatenate(dn)
    return {'orange_pct': 100 * (math.exp(up.mean()) - 1) if len(up) else math.nan,
            'blue_pct': 100 * (math.exp(-dn.mean()) - 1) if len(dn) else math.nan, 'n_orange': len(up), 'n_blue': len(dn)}


def eval_grid(T, src, w0, W):
    """Справочно: центр колокола m со span_m, ширина s со span_s (вокруг своего центра) — BCE по неделям и модель
       случайного графика; сдвиг — как у основной сетки."""
    lag, l125 = BELL['lag'], math.log(1.25)
    gm, gs = BELL['grid_m'], BELL['grid_s']
    wsum = {(a, b): np.zeros(W) for a in gm for b in gs}
    wcnt = np.zeros(W)
    gcol = {(a, b): 0 for a in gm for b in gs}
    n = 0
    for _, _, d in series_iter(src):
        B = d['B']
        wi = d['wk'][B:] - w0
        wcnt += np.bincount(wi, minlength=W)
        n += len(wi)
        mm = {a: shift(live(T, d['zr'], a)[0], lag)[B:] for a in gm}
        sv = {b: shift(live(T, d['zr'], b)[1], lag)[B:] for b in gs}
        mg = {a: shift(live(T, d['zg'], a)[0], lag)[B:] for a in gm}
        sg = {b: shift(live(T, d['zg'], b)[1], lag)[B:] for b in gs}
        zr, zs, zg = d['zr'][B:], d['zs'][B:], d['zg'][B:]
        for a in gm:
            for b in gs:
                lr, ln = T._nc_logm(zr, mm[a], sv[b]), T._nc_logm(zs, mm[a], sv[b])
                wsum[(a, b)] += np.bincount(wi, weights=bce_pairs(lr, ln), minlength=W)
                gcol[(a, b)] += int((np.abs(T._nc_logm(zg, mg[a], sg[b])) >= l125).sum())
    with np.errstate(invalid='ignore', divide='ignore'):
        wk = {k: v / wcnt for k, v in wsum.items()}
    return {'wk_bce': wk, 'gp_col': {k: v / n for k, v in gcol.items()}}


