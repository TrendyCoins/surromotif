def acf_info(z):
    """Автокорреляция z на лагах 0…acf_lags после вычета скользящего среднего (медленный дрейф — не шум). «Пол» p —
       корреляция на последнем лаге: там у окон уже нет общих баров входа, и всё, что осталось, — устойчивость режима
       рынка; её вычитаем: rho_null = (rho − p) / (1 − p). Возвращает разброс, p, rho, rho_null, tau (сколько соседних
       окон дают одно независимое показание) с полом и без."""
    K, W = BELL['acf_lags'], BELL['acf_detrend']
    x = z - pd.Series(z).rolling(W, center=True, min_periods=1).mean().to_numpy()
    x = x - x.mean()
    n = len(x)
    nfft = 1 << int(math.ceil(math.log2(2 * n)))
    f = np.fft.rfft(x, nfft)
    ac = np.fft.irfft(f * np.conj(f), nfft)[:K + 1] / (n - np.arange(K + 1))
    rho = ac / ac[0]
    p = float(max(rho[K], 0.0))
    rho_null = np.clip((rho - p) / (1.0 - p), 0.0, None)
    rho_null[0] = 1.0
    return {'var': float(ac[0]), 'p': p, 'rho': rho, 'rho_null': rho_null,
            'tau': float(1.0 + 2.0 * rho[1:].sum()), 'tau_null': float(1.0 + 2.0 * rho_null[1:].sum())}


def noise_var(info, N):
    """Дисперсия среднего z по N соседним окнам, если колокол стоит на месте: σ²·(1 − p) / N · [1 + 2·Σ (1 − k/N)·rho_k]."""
    rn = info['rho_null']
    k = np.arange(1, min(N - 1, len(rn) - 1) + 1)
    return info['var'] * (1.0 - info['p']) / N * (1.0 + 2.0 * np.sum((1.0 - k / N) * rn[k]))


def rho_window_only():
    """Оптимистичная граница случайного графика: автокорреляция только от общих баров окна, rho_k = 1 − k/64 (τ = 64),
       без истории и режимов."""
    k = np.arange(BELL['acf_lags'] + 1, dtype=np.float64)
    return np.clip(1.0 - k / 64.0, 0.0, None)


def gp_chart(rho_null, n, rng):
    """Модель случайного графика: гауссов ряд длины n со средним 0, разбросом 1 и автокорреляцией rho_null (лаги дальше —
       0). Циркулянтное вложение: спектр автокорреляции -> корень -> фильтр белого шума."""
    K = len(rho_null) - 1
    nfft = 1 << int(math.ceil(math.log2(n + K + 1)))
    c = np.zeros(nfft)
    c[:K + 1] = rho_null
    c[nfft - K:] = rho_null[1:][::-1]
    lam = np.maximum(np.fft.rfft(c).real, 0.0)
    w = rng.standard_normal(nfft)
    return np.fft.irfft(np.sqrt(lam) * np.fft.rfft(w), nfft)[:n]


