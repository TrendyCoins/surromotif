def load_bars(asset):
    """Бары ассета по частям {0: TRAINING, 1: VALIDATION}: сырые OHLC smc_bars вместе с pre-барами — барами перед началом
       части, на которых считался нормировщик r её первых баров (время pre-баров — условная сетка 5M перед частью: событий
       на них нет). Части не склеиваются: стык TRAINING и VALIDATION в данных не обязан быть бар в бар, а склейка через
       промежуток дала бы ложный бар — скачок цены. Возвращает (части, стык частей — справочно)."""
    tf, N = REV['tf'], REV['N']
    ps, pb = DATA_DIR + f"smc_series_{asset}_{tf}_N{N}.npz", DATA_DIR + f"smc_bars_{asset}_{tf}_N{N}.npz"
    for p_ in (ps, pb):
        if not os.path.isfile(p_):
            raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет {p_}")
    ds, db = np.load(ps, allow_pickle=False), np.load(pb, allow_pickle=False)
    tune_ns, val_ns = pd.Timestamp(REV['tune_start']).value, int(ds['t_va'][0])
    segs = {}
    for code, key in ((0, 'tr'), (1, 'va')):
        T = ds[f't_{key}'].astype(np.int64)
        n_pre = len(db[f'pre_c_{key}'])
        seg = {'T': np.r_[T[0] - BAR_NS * np.arange(n_pre, 0, -1), T], 'n_pre': n_pre, 'tune_ns': tune_ns,
               'val_ns': val_ns}
        for k_ in ('h', 'l', 'c'):
            seg[k_] = np.r_[db[f'pre_{k_}_{key}'], db[f'{k_}_{key}']].astype(float)
        if len(seg['c']) != len(seg['T']):
            raise ValueError(f"🍆 АЙ, ОШИБКА! {asset}: баров {key} в smc_bars {len(seg['c']) - n_pre}, а в smc_series "
                             f"{len(T)} — файлы из разных выгрузок")
        seg['norm'] = normalizer(seg['h'], seg['l'], seg['c'])
        segs[code] = seg
    t_end = int(ds['t_tr'][-1])
    k = min(len(db['pre_c_va']), len(db['c_tr']))
    join = {'tr_end': t_end, 'va_start': val_ns, 'gap': int((val_ns - t_end) // BAR_NS) - 1,
            'n_pre': int(len(db['pre_c_va'])), 'pre_is_tail': bool(np.array_equal(db['pre_c_va'][-k:], db['c_tr'][-k:]))}
    return segs, join


def print_joins(joins):
    """Стык TRAINING и VALIDATION по ассетам — справочно: части обрабатываются раздельно, на события он не влияет."""
    groups = {}
    for a, j in joins.items():
        groups.setdefault((j['tr_end'], j['va_start'], j['gap'], j['n_pre'], j['pre_is_tail']), []).append(a)
    print("🔗 стык частей (справочно; части обрабатываются раздельно, каждая — со своими pre-барами):")
    for (tr_end, va_start, gap, n_pre, tail), lst in sorted(groups.items(), key=lambda x: -len(x[1])):
        who = f"все {len(lst)}" if len(lst) == len(joins) else f"{len(lst)} ({', '.join(a[:-4] for a in lst)})"
        how = ("стык бар в бар" if gap == 0 else f"перекрытие {-gap} бар." if gap < 0 else f"промежуток {gap} бар. 5M")
        print(f"   {who}: TRAINING до {pd.Timestamp(tr_end):%Y-%m-%d %H:%M}, VALIDATION с {pd.Timestamp(va_start):%Y-%m-%d %H:%M}"
              f" — {how}; pre-баров VALIDATION {n_pre} ({'конец TRAINING' if tail else 'не конец TRAINING'})")


def print_dead(bars):
    """Доли баров с мёртвым нормировщиком по частям — справочно: порог там — последним живым значением, событий нет."""
    rows = []
    for a, P_ in bars.items():
        sh = [float(1.0 - P_[code]['norm'][1][P_[code]['n_pre']:].mean()) for code in (0, 1)]
        if max(sh) > 1e-3:
            rows.append(f"{a[:-4]} {100 * sh[0]:.1f}% / {100 * sh[1]:.1f}%")
    print("🧟 мёртвый нормировщик (медиана диапазона за 200 баров = 0: зигзаг такие бары не видит, событий на них нет), "
          "доля баров TRAINING / VALIDATION: " + (", ".join(rows) if rows else "нет ни у одного ассета"))


def attach_mri(segs, asset):
    """z-MRI на баре (ансамбль сидов — средний logit; z-оценка по окнам TUNE ассета) и боковые входы окна, кончающегося на
       баре, — у каждой части свои окна (TUNE — в TRAINING, VAL — в VALIDATION). Окно ищется по времени последнего бара среди
       баров части (без pre-баров) — найтись обязано каждое."""
    f = np.load(OUT_DIR + f"mri/{asset}.npz", allow_pickle=False)
    lg = f['logit'].astype(np.float64).mean(axis=0)
    part, t_end = f['part'], f['t_end']
    tm = part == 0
    mu, sd = float(lg[tm].mean()), max(float(lg[tm].std()), 1e-12)
    out = {}
    for code, B in segs.items():
        w = part == code
        T = B['T'][B['n_pre']:]
        idx = np.searchsorted(T, t_end[w])
        found = (idx < len(T)) & (T[np.minimum(idx, len(T) - 1)] == t_end[w])
        if not found.all():
            raise ValueError(f"🍆 АЙ, ОШИБКА! {asset}: {int((~found).sum())} окон MRI нет среди баров "
                             f"{('TRAINING', 'VALIDATION')[code]} — файлы из разных выгрузок")
        idx = idx + B['n_pre']
        z = np.full(len(B['T']), np.nan)
        z[idx] = (lg[w] - mu) / sd
        side = np.full((len(B['T']), f['side'].shape[1]), np.nan, np.float32)
        side[idx] = f['side'][w]
        out[code] = dict(B, z=z, side=side)
    meta = json.loads(str(f['meta']))
    return out, {'mu': mu, 'sd': sd, 'check_ok': bool(meta.get('check_ok')), 'tags': meta.get('tags')}


