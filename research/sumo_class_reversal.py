def build_events(B, m, asset_i):
    """События одного ассета на масштабе m. B — бары TRAINING + VALIDATION подряд: T (нс), h, l, c; z — z-MRI окна,
       кончающегося на баре (NaN — окна нет); side — боковые входы того же окна; tune_ns, val_ns. Все входы на баре t
       считаются из баров <= t (стенд проверяет возмущением баров после t). Возвращает (столбцы, проверки)."""
    T = np.asarray(B['T'], np.int64)
    c, h = np.asarray(B['c'], float), np.asarray(B['h'], float)
    n = len(c)
    norm = B['norm'] if 'norm' in B else normalizer(h, B['l'], c)
    live = norm[1]
    atr, mw, (PT, PP, PI, PC, bar_k, bar_e) = run_slicer(c, h, B['l'], m, norm)
    ex = extremes(np.where(live, c, np.nan), mw, PT, PI, PC, bar_k, bar_e)
    t, k, d, X = ex['t'], ex['k'], ex['dir'], ex['X']
    checks = {'legs': int(max(len(PI) - 1, 0)), 'extremes': int(len(t)),
              'piv_ok': bool(np.array_equal(t[ex['rev']], PI[1:])), 'events': 0, 'mri_last_at_t': True}
    if len(t) == 0:                               # ни одной подтверждённой ноги (часть короче разогрева на этом масштабе)
        return None, checks
    A = PI[k]
    first = np.r_[True, k[1:] != k[:-1]]          # первый экстремум ноги — бар коммита её якоря
    leg0 = np.maximum.accumulate(np.where(first, np.arange(len(t)), 0))
    prev_x = np.r_[np.nan, X[:-1]]                # откат прошлого экстремума ноги разрешился на t — известен
    prev_x[first] = np.nan
    last_len = np.r_[np.nan, np.diff(t).astype(float)]
    last_len[first] = np.nan
    max_pb = pd.Series(prev_x).groupby(k).cummax().to_numpy()
    kp = np.maximum(k - 1, 0)
    has_prev = k >= 1
    conf = PC[k].astype(float)
    conf[conf < 0] = np.nan                       # у разогревочного пивота бара подтверждения нет
    # отбор: возраст ноги, TUNE / VAL, все n_mri значений MRI и боковые входы есть
    nm = REV['n_mri']
    keep = (t - A >= REV['min_age']) & (T[t] >= B['tune_ns']) & live[t]    # (экстремумы — только на живых барах)
    seq_idx = np.clip(t[:, None] + np.arange(-(nm - 1), 1)[None, :], 0, n - 1)
    seq = B['z'][seq_idx]
    keep &= np.isfinite(seq).all(axis=1)
    side = B['side'][t]
    keep &= np.isfinite(side).all(axis=1)
    sel = np.where(keep)[0]
    checks.update({'events': int(len(sel)), 'mri_last_at_t': bool(np.array_equal(seq_idx[sel, -1], t[sel]))})
    if len(sel) == 0:
        return None, checks
    tt, dd, AA, kk = t[sel], d[sel].astype(float), A[sel], k[sel]
    E = {'asset': np.full(len(sel), asset_i, np.int16), 't': tt.astype(np.int64), 'T': T[tt],
         'res_T': T[ex['res'][sel]], 'val_ns': np.full(len(sel), B['val_ns'], np.int64),
         'part': (T[tt] >= B['val_ns']).astype(np.int8), 'week': T[tt] // WEEK_NS, 'X': X[sel]}
    # M0: нога
    E['age'] = np.log(tt - AA)
    E['since_conf'] = np.log1p(tt - conf[sel])
    E['size'] = dd * (c[tt] - c[AA]) / mw[AA]
    E['n_ext'] = np.log((np.arange(len(t)) - leg0 + 1)[sel])
    E['last_pb'] = prev_x[sel]
    E['last_len'] = np.log(last_len[sel])
    E['max_pb'] = max_pb[sel]
    E['prev_size'] = np.where(has_prev[sel], np.abs(PP[kk] - PP[kp[sel]]) / mw[PI[kp[sel]]], np.nan)
    E['prev_len'] = np.where(has_prev[sel], np.log(np.maximum(PI[kk] - PI[kp[sel]], 1)), np.nan)
    E['dir'] = dd
    E['mw_ratio'] = np.log(mw[tt] / mw[AA])
    # M0: вола (средний истинный диапазон последних w баров, включая t, к мерке порога — ATR за 200 баров до t) и время
    tr_ = pd.Series(true_range(h, B['l'], c))
    for w in (4, 16, 64):
        E[f'vol{w}'] = np.log(np.maximum(tr_.rolling(w).mean().to_numpy()[tt], 1e-12) / atr[tt])
    hod = (T[tt] // 60_000_000_000) % 1440 / 60.0
    dow = ((T[tt] // DAY_NS) + 3) % 7             # 1970-01-01 — четверг: понедельник = 0
    E['hod_sin'], E['hod_cos'] = np.sin(2 * np.pi * hod / 24), np.cos(2 * np.pi * hod / 24)
    E['dow_sin'], E['dow_cos'] = np.sin(2 * np.pi * dow / 7), np.cos(2 * np.pi * dow / 7)
    # M1: ходы за k баров в mw по направлению ноги, ER, боковые входы окна
    acs = np.r_[0.0, np.cumsum(np.nan_to_num(np.abs(np.diff(c))))]
    for kb in RET_K:
        E[f'ret{kb}'] = dd * (c[tt] - c[tt - kb]) / mw[tt]
    for kb in (32, 95):
        E[f'er{kb}'] = np.abs(c[tt] - c[tt - kb]) / np.maximum(acs[tt] - acs[tt - kb], 1e-12)
    for j in range(N_SIDE):
        E[f'side{j}'] = side[sel, j]
    for j, col in enumerate(MRI_COLS):
        E[col] = seq[sel, j]
    for key in list(E):
        if E[key].dtype == np.float64:
            E[key] = E[key].astype(np.float32)
    return E, checks


def concat_events(parts):
    parts = [p for p in parts if p is not None]
    return {key: np.concatenate([p[key] for p in parts]) for key in parts[0]}


def asset_events(segs, m, asset_i):
    """События ассета на масштабе m по частям {0: TRAINING, 1: VALIDATION}: каждая часть — отдельно (зигзаг, порог, исходы
       и входы не переходят через стык частей), затем вместе. Цена: первая нога VALIDATION уходит на разогрев слайсера;
       экстремумы TUNE, не разрешившиеся до конца TRAINING, выпадают (в обучение они и так не шли)."""
    parts = []
    checks = {'legs': 0, 'extremes': 0, 'events': 0, 'piv_ok': True, 'mri_last_at_t': True}
    for code in sorted(segs):
        E, ch = build_events(segs[code], m, asset_i)
        for key in ('legs', 'extremes', 'events'):
            checks[key] += ch[key]
        checks['piv_ok'] &= ch['piv_ok']
        checks['mri_last_at_t'] &= ch['mri_last_at_t']
        if E is not None:
            parts.append(E)
    return (concat_events(parts) if parts else None), checks


def save_events(path, E, meta):
    np.savez_compressed(path, meta=json.dumps(_jsonable(meta), ensure_ascii=False), **E)


def load_events(path):
    d = np.load(path, allow_pickle=False)
    return {key: d[key] for key in d.files if key != 'meta'}, json.loads(str(d['meta']))


def _jsonable(x):
    if isinstance(x, dict):
        return {str(k): _jsonable(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_jsonable(v) for v in x]
    if isinstance(x, np.ndarray):
        return _jsonable(x.tolist())
    if isinstance(x, (np.bool_, bool)):
        return bool(x)
    if isinstance(x, np.integer):
        return int(x)
    if isinstance(x, (np.floating, float)):
        return None if not np.isfinite(x) else float(x)
    return x


def choose_scales(bars):
    """Масштабы по FIT (бары до начала TUNE, MRI не участвует): S1 — m, у которого медиана ноги (пивот -> пивот, все
       ассеты вместе) ближе всего к s1_median_leg; S2 — наименьший m, при котором доля ног не длиннее s2_short[0] баров
       не больше s2_short[1]. Перебор m по возрастанию — до первого m, где выполнены оба условия."""
    tune_ns = pd.Timestamp(REV['tune_start']).value
    target, (short_len, short_max) = REV['s1_median_leg'], REV['s2_short']
    rows = []
    print(f"📏 МАСШТАБЫ по FIT (до {REV['tune_start'][:10]}): S1 — медиана ноги ближе всего к {target} барам; S2 — "
          f"ног не длиннее {short_len} баров <= {100 * short_max:g}%")
    fit = []                                       # (close, нормировщик) префикса FIT каждого ассета — один раз
    for B in bars.values():
        n_fit = int(np.searchsorted(B['T'], tune_ns))
        if n_fit >= 2 * REV['hl_window']:
            norm = (tuple(x[:n_fit] for x in B['norm']) if 'norm' in B
                    else normalizer(B['h'][:n_fit], B['l'][:n_fit], B['c'][:n_fit]))   # причинный: префикс = свой
            fit.append((B['c'][:n_fit], B['h'][:n_fit], B['l'][:n_fit], norm))
    for m in REV['m_grid']:
        t0 = time.time()
        legs = []
        for c_, h_, l_, norm in fit:
            PI = run_slicer(c_, h_, l_, m, norm)[2][2]
            legs.append(np.diff(PI))
        legs = np.concatenate(legs)
        row = {'m': int(m), 'legs': int(len(legs)), 'median': float(np.median(legs)),
               'short': float(np.mean(legs <= short_len))}
        rows.append(row)
        print(f"   m={m:>3}: ног {row['legs']:>7} | медиана {row['median']:6.0f} баров | ног <= {short_len} баров "
              f"{100 * row['short']:5.1f}% | {time.time() - t0:.0f} c", flush=True)
        if row['median'] >= target and row['short'] <= short_max:
            break
    s1 = min(rows, key=lambda r: abs(r['median'] - target))
    s2 = next((r for r in rows if r['short'] <= short_max), None)
    if s2 is None:
        s2 = rows[-1]
        print(f"⚠️ S2: доля коротких ног не опустилась до {100 * short_max:g}% на сетке — взят последний m={s2['m']}")
    print(f"   -> S1: m = {s1['m']} (медиана ноги {s1['median']:.0f} баров) | S2: m = {s2['m']} (ног <= {short_len} баров "
          f"{100 * s2['short']:.1f}%)")
    return {'S1': s1['m'], 'S2': s2['m'], 'grid': rows, 'tune_start': REV['tune_start']}


