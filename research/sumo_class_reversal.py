class _Tee:
    """Печать в вывод и в лог-файл на Drive (как в коде обучения): текст копится в памяти и дописывается раз в SYNC_S
       секунд и при закрытии; ошибка записи лога прогон не роняет."""
    SYNC_S = 5.0

    def __init__(self, path, stream):
        self.path, self.stream, self.buf = path, stream, []
        self.t_last, self.warned = time.time(), False

    def _sync(self):
        if not self.buf:
            return
        try:
            with open(self.path, 'a', encoding='utf-8') as fh:
                fh.write(''.join(self.buf))
            self.buf = []
        except OSError as e:
            if not self.warned:
                self.stream.write(f"\n⚠️ лог-файл недоступен ({e}) — коплю в памяти\n")
                self.warned = True
        self.t_last = time.time()

    def write(self, s):
        self.stream.write(s)
        self.buf.append(s)
        if time.time() - self.t_last >= self.SYNC_S:
            self._sync()

    def flush(self):
        self.stream.flush()
        if time.time() - self.t_last >= self.SYNC_S:
            self._sync()

    def close(self):
        self._sync()

    def __getattr__(self, name):
        return getattr(self.stream, name)


@contextlib.contextmanager
def tee_to(path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    keep = sys.stdout
    tee = _Tee(path, keep)
    sys.stdout = tee
    try:
        yield
    finally:
        sys.stdout = keep
        tee.close()


def _f(x, fmt, width=None, dash='—'):
    try:
        ok = x is not None and np.isfinite(x)
    except TypeError:
        ok = False
    s = f"{x:{fmt}}" if ok else dash
    return f"{s:>{width}}" if width else s


def auc_parts(sp, sn):
    """AUC и вклады окон в него (проекция Хайека): их суммы по неделям дают честную ошибку при связанных выборках
       (как в коде обучения)."""
    n1, n0 = len(sp), len(sn)
    sn_s, sp_s = np.sort(sn), np.sort(sp)
    lo, hi = np.searchsorted(sn_s, sp, 'left'), np.searchsorted(sn_s, sp, 'right')
    v10 = (lo + 0.5 * (hi - lo)) / n0
    lo, hi = np.searchsorted(sp_s, sn, 'left'), np.searchsorted(sp_s, sn, 'right')
    v01 = ((n1 - hi) + 0.5 * (hi - lo)) / n1
    auc = float(v10.mean())
    return auc, (v10 - auc) / n1, (v01 - auc) / n0


def cluster_se(infl, weeks):
    x, w = np.concatenate(infl), np.concatenate(weeks)
    _, inv = np.unique(w, return_inverse=True)
    s = np.bincount(inv, weights=x)
    G = len(s)
    return float(np.sqrt(G / max(G - 1, 1) * np.sum(s ** 2)))


def auc_se(sp, sn, wp, wn):
    auc, ip, i0 = auc_parts(sp, sn)
    return auc, cluster_se([ip, i0], [wp, wn])


def auc_diff(spa, sna, spb, snb, wp, wn):
    a, ipa, ina = auc_parts(spa, sna)
    b, ipb, inb = auc_parts(spb, snb)
    return a - b, cluster_se([ipa - ipb, ina - inb], [wp, wn])


def auc_rank(score, y):
    """AUC без ошибки — для таблиц стенда."""
    y = np.asarray(y, bool)
    return auc_parts(np.asarray(score, float)[y], np.asarray(score, float)[~y])[0]


