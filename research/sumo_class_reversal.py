def stand_dead():
    """Мёртвый нормировщик: участок, где каждый бар — одна сделка (high = low = close, диапазон 0: медиана за 200 баров
       становится 0), цена на нём ходит с шумом и сносом вверх, потом — живое падение. Три порога: бесконечный на мёртвых
       барах (v2) — вершина ноги на мёртвом баре не подтверждается никогда, зигзаг замерзает до конца ряда; последним живым
       значением медианы (v3) — у порога смерти медиана — доли самого малого диапазона, зигзаг дрожит на шуме участка;
       нынешний — мёртвые бары не видны, мерка — ATR: на участке пивотов нет, после него зигзаг идёт дальше."""
    o, h, l, c, _ = make_bars(6000, seed=5)
    D0, D1 = 1500, 2300
    rng = np.random.default_rng(6)
    c, h, l = c.copy(), h.copy(), l.copy()
    c[D0:D1] = c[D0 - 1] + np.cumsum(0.3 + 0.8 * rng.standard_normal(D1 - D0))
    h[D0:D1] = c[D0:D1]
    l[D0:D1] = c[D0:D1]
    path = np.cumsum(rng.standard_normal((len(c) - D1, 20)) / np.sqrt(20) - 0.5 / 20, axis=1)   # снос −0.5 за бар
    c[D1:] = c[D1 - 1] + np.cumsum(path[:, -1])
    o_ = np.r_[c[D1 - 1], c[D1:-1]]
    h[D1:] = o_ + np.maximum(path.max(axis=1), 0.0)
    l[D1:] = o_ + np.minimum(path.min(axis=1), 0.0)
    rmed = pd.Series(h - l).rolling(REV['hl_window'], closed='left').median().to_numpy()
    alive = np.isfinite(rmed) & (rmed > 0)
    dead = np.where(~alive[REV['hl_window']:])[0] + REV['hl_window']
    s0 = int(np.argmax(alive))
    v2 = trend_slicer_forward(c, rmed * 16, s0, len(c))[2]                                 # мёртвый: 0 -> бесконечный
    v3 = trend_slicer_forward(c, pd.Series(np.where(alive, rmed, np.nan)).ffill().to_numpy() * 16, s0, len(c))[2]
    v4 = run_slicer(c, h, l, 16)[2][2]
    lo, hi = dead.min(), dead.max()

    def inside(PI):
        return int(((PI >= lo) & (PI <= hi)).sum())

    def after(PI):
        return int((PI > hi).sum())
    ok = inside(v4) == 0 and after(v4) > 0
    print(f"   {'✅' if ok else '❌'} мёртвый нормировщик ({len(dead)} баров): пивотов на участке / после него — "
          f"бесконечный порог (v2) {inside(v2)} / {after(v2)}{' (зигзаг замёрз)' if after(v2) == 0 else ''}, "
          f"последняя живая медиана (v3) {inside(v3)} / {after(v3)}, мёртвые не видны + ATR {inside(v4)} / "
          f"{after(v4)}")
    return ok


def tick_world(n, seed, frac_ill=0.12, mean_len=4000, p_ill=0.03, tick=0.04):
    """Цена на сетке тиков: сделки — на под-шагах (20 на бар); в ликвиде сделка на каждом под-шаге, на участках неликвида
       (~12% баров) — с вероятностью p_ill: бар — 0–1 сделка, диапазон 0, цена прыгает между барами. Тик мелкий (0.04 σ
       под-шага), так что медиана диапазона у порога смерти — доли тика."""
    rng = np.random.default_rng(seed)
    ill = np.zeros(n, bool)
    i = 2000
    while i < n:
        gap = int(rng.exponential(mean_len * (1 - frac_ill) / frac_ill))
        ln = int(rng.exponential(mean_len))
        ill[i + gap:i + gap + ln] = True
        i += gap + ln
    px = np.round((1000.0 + np.cumsum(rng.standard_normal(n * 20) / np.sqrt(20))) / tick) * tick
    trade = np.where(np.repeat(ill, 20), rng.random(n * 20) < p_ill, True).reshape(n, 20)
    px = px.reshape(n, 20)
    o, h, l, c = np.empty(n), np.empty(n), np.empty(n), np.empty(n)
    last = px[0, 0]
    for b in range(n):
        seg = px[b][trade[b]]
        if seg.size == 0:
            o[b] = h[b] = l[b] = c[b] = last
        else:
            o[b], h[b], l[b], c[b], last = seg[0], seg.max(), seg.min(), seg[-1], seg[-1]
    return h, l, c


