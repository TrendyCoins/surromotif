def model_cols(name):
    """Столбцы модели и номер перемешивания MRI (None — без перемешивания)."""
    fs = feature_sets()
    if name.startswith('M1+shuf'):
        return fs['M1'] + list(MRI_COLS), int(name[len('M1+shuf'):])
    return {'M0': fs['M0'], 'M0_novol': fs['M0_novol'], 'M0+MRI32': fs['M0'] + list(MRI_COLS), 'M1': fs['M1'],
            'M1+MRI32': fs['M1'] + list(MRI_COLS), 'M1+MRI1': fs['M1'] + ['z_m0']}[name], None


def design(E, cols, rows, shuf=None):
    """Матрица входов; при shuf — 32 значения MRI переставлены целыми строками между событиями одного ассета."""
    M = np.column_stack([E[col][rows] for col in cols]).astype(np.float32)
    if shuf is not None:
        j = [cols.index(col) for col in MRI_COLS]
        rng = np.random.default_rng(REV['seed'] + shuf)
        block = M[:, j]
        a = E['asset'][rows]
        for g in np.unique(a):
            ii = np.where(a == g)[0]
            block[ii] = block[ii[rng.permutation(len(ii))]]
        M[:, j] = block
    return M


def fit_eval(E, thr, names, verbose=True):
    """Модели names: учатся на TUNE (без событий, чей исход разрешился уже в VAL), оценки — на VAL."""
    y = E['X'] >= thr
    tr = np.where((E['part'] == 0) & (E['res_T'] < E['val_ns']))[0]
    te = np.where(E['part'] == 1)[0]
    if y[tr].sum() < 30 or y[te].sum() < 30:
        raise ValueError(f"🍆 АЙ, ОШИБКА! мало событий: обучение {len(tr)} ({int(y[tr].sum())} положительных), "
                         f"проверка {len(te)} ({int(y[te].sum())})")
    preds = {}
    for nm in names:
        t0 = time.time()
        cols, shuf = model_cols(nm)
        mdl = HistGradientBoostingClassifier(**REV['gbm'], early_stopping=False, random_state=0)
        mdl.fit(design(E, cols, tr, shuf), y[tr])
        preds[nm] = mdl.predict_proba(design(E, cols, te, None if shuf is None else shuf + 1000))[:, 1]
        if verbose:
            print(f"      {nm:<12} входов {len(cols):>3} | {time.time() - t0:.0f} c", flush=True)
    yt, wk = y[te], E['week'][te]
    R = {'thr': thr, 'n_tr': len(tr), 'n_te': len(te), 'pos_tr': int(y[tr].sum()), 'pos_te': int(yt.sum()),
         'base_te': float(yt.mean()), 'preds': preds, 'y': yt, 'wk': wk, 'te': te,
         'auc': {nm: auc_se(p[yt], p[~yt], wk[yt], wk[~yt]) for nm, p in preds.items()}}
    return R


def delta(R, a, b):
    yt, wk = R['y'], R['wk']
    pa, pb = R['preds'][a], R['preds'][b]
    return auc_diff(pa[yt], pa[~yt], pb[yt], pb[~yt], wk[yt], wk[~yt])


def top_lift(p, y, q=0.1):
    """Во сколько раз доля событий в верхнем дециле прогноза выше общей доли."""
    return float(y[p >= np.quantile(p, 1 - q)].mean() / max(y.mean(), 1e-12))


def gates(R, checks_ok):
    """Правила (до прогона): контроли (0), ворота (1)–(3). Печатает таблицу и возвращает итог."""
    g = REV['gate_se']
    print(f"   обучение (TUNE): событий {R['n_tr']}, положительных {R['pos_tr']} | проверка (VAL): {R['n_te']}, "
          f"положительных {R['pos_te']} ({100 * R['base_te']:.2f}%)")
    print(f"   {'модель':<12} {'AUC VAL':>8} {'±SE':>7} {'lift верх. дециля':>18}")
    for nm in FULL:
        a_, se_ = R['auc'][nm]
        print(f"   {nm:<12} {a_:>8.4f} {se_:>7.4f} {top_lift(R['preds'][nm], R['y']):>18.2f}")
    zs = []
    for r in range(REV['n_shuffle']):
        d_, se_ = delta(R, f'M1+shuf{r}', 'M1')
        zs.append(d_ / se_ if se_ > 0 else 0.0)
    out = {'shuffle_z': zs, 'shuffle_ok': sum(z > 2 for z in zs) <= 1, 'checks_ok': bool(checks_ok)}
    d_, se_ = delta(R, 'M0', 'M0_novol')
    out['pos'] = (d_, se_, bool(d_ >= g * se_))
    for key, (a, b) in (('g1', ('M0+MRI32', 'M0')), ('g2', ('M1+MRI32', 'M1')), ('g3', ('M1+MRI32', 'M1+MRI1'))):
        d_, se_ = delta(R, a, b)
        out[key] = (d_, se_, bool(d_ >= g * se_))
    ok0 = out['checks_ok'] and out['shuffle_ok'] and out['pos'][2]

    def line(key, text):
        d_, se_, ok = out[key]
        return f"{'✅' if ok else '·'} {text}: Δ {d_:+.4f} ± {se_:.4f} ({d_ / se_ if se_ > 0 else 0:+.1f} SE)"
    print(f"   (0) {'✅' if out['checks_ok'] else '❌'} проверки разметки и MRI (развороты = пивоты, последний MRI — на t)")
    print(f"   (0) {'✅' if out['shuffle_ok'] else '❌'} MRI, перемешанный внутри ассета, {REV['n_shuffle']} раз: z = "
          + " ".join(f"{z:+.1f}" for z in zs) + f" — z > +2 {sum(z > 2 for z in zs)} раз (допустимо не больше одного)")
    d_, se_, ok = out['pos']
    print(f"   (0) {'✅' if ok else '❌'} положительный контроль, M0 − M0 без волы: Δ {d_:+.4f} ± {se_:.4f} "
          f"({d_ / se_ if se_ > 0 else 0:+.1f} SE; нужно >= +{g:g} SE)")
    print("   (1) " + line('g1', 'M0 + MRI32 − M0 (MRI сверх зигзага и волы)'))
    print("   (2) " + line('g2', 'M1 + MRI32 − M1 (сверх простых чисел тех же баров)'))
    print("   (3) " + line('g3', 'M1 + MRI32 − (M1 + MRI1) (последовательность сверх последнего значения)'))
    if not ok0:
        txt = "❗ контроль не прошёл — выводы не читать до разбора"
    elif not out['g1'][2]:
        txt = "MRI к развороту ничего не добавляет сверх зигзага и волы (ворота 1 не пройдены)"
    elif not out['g2'][2]:
        txt = ("MRI полезен сверх зигзага и волы, но не сверх простых чисел тех же баров (1 да, 2 нет): удобная сводка "
               "цены, «шанс глубокой коррекции» делается и без него")
    else:
        txt = ("MRI видит в пути то, чего нет в простых числах тех же баров (1 и 2 да)"
               + ("; последовательность важнее последнего значения (3 да)" if out['g3'][2]
                  else "; последовательность сверх последнего значения не добавляет (3 нет)"))
    out['verdict'] = txt
    print(f"   ИТОГ: {txt}")
    return out


def mri_summary(E, rows):
    """Сводки последовательности MRI для логистической регрессии: среднее, последнее, мин, макс, разброс, наклон,
       последние 8 баров минус остальные."""
    Z = np.column_stack([E[col][rows] for col in MRI_COLS]).astype(float)
    j = np.arange(Z.shape[1]) - (Z.shape[1] - 1) / 2
    return np.column_stack([Z.mean(1), Z[:, -1], Z.min(1), Z.max(1), Z.std(1), (Z * j).sum(1) / (j ** 2).sum(),
                            Z[:, -8:].mean(1) - Z[:, :-8].mean(1)])


def logit_ref(E, thr):
    """Справочно: логистическая регрессия на M1 и на M1 + сводки MRI (в Pine такая модель — сумма с весами)."""
    y = E['X'] >= thr
    tr = np.where((E['part'] == 0) & (E['res_T'] < E['val_ns']))[0]
    te = np.where(E['part'] == 1)[0]
    cols = feature_sets()['M1']

    def mk():
        return make_pipeline(SimpleImputer(strategy='median'), StandardScaler(), LogisticRegression(max_iter=3000))
    xa, xb = design(E, cols, tr), design(E, cols, te)
    p0 = mk().fit(xa, y[tr]).predict_proba(xb)[:, 1]
    p1 = mk().fit(np.column_stack([xa, mri_summary(E, tr)]), y[tr]).predict_proba(
        np.column_stack([xb, mri_summary(E, te)]))[:, 1]
    yt, wk = y[te], E['week'][te]
    a0, a1 = auc_se(p0[yt], p0[~yt], wk[yt], wk[~yt]), auc_se(p1[yt], p1[~yt], wk[yt], wk[~yt])
    return a0, a1, auc_diff(p1[yt], p1[~yt], p0[yt], p0[~yt], wk[yt], wk[~yt])


