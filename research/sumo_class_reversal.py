def stand_world():
    """Синтетический пул: общий фактор рынка (недели связаны), стохастическая вола (контроль волы обязан пройти) и скрытое
       состояние z (AR(1), полураспад — сутки): снос по ходу последних 64 баров ∝ z — при z > 0 тренд тянется, при z < 0
       откатывается. MRI 'planted' = z + шум; MRI 'null' = независимое z' + шум той же силы. MRI есть, как у настоящего,
       только у окон TUNE / VAL (без первых 63 баров VAL), z-оценка по TUNE; боковые входы — нули."""
    P = STAND
    rng = np.random.default_rng(P['seed'])
    T = np.arange(pd.Timestamp(P['world_from']).value, pd.Timestamp(P['world_to']).value, BAR_NS, dtype=np.int64)
    n, sub = len(T), 20
    tune_ns, val_ns = pd.Timestamp(REV['tune_start']).value, pd.Timestamp(P['world_val']).value
    phi_v, phi_z = 0.5 ** (1 / 300), 0.5 ** (1 / 288)

    def ar(phi):
        return lfilter([1.0], [1.0, -phi], rng.standard_normal(n) * np.sqrt(1 - phi ** 2))
    vc = ar(phi_v)
    F = rng.standard_normal((n, sub))
    avail = (T >= tune_ns + 63 * BAR_NS) & ~((T >= val_ns) & (T < val_ns + 63 * BAR_NS))
    tune_m = avail & (T < val_ns)
    world = []
    for a in range(P['world_assets']):
        v = 0.4 * vc + 0.4 * ar(phi_v)
        sig = np.exp(v - v.mean())
        z = ar(phi_z)
        path = np.cumsum((0.6 * F + 0.8 * rng.standard_normal((n, sub))) * (sig[:, None] / np.sqrt(sub)), axis=1)
        r0 = path[:, -1]
        c, mu = np.zeros(n), np.zeros(n)
        kap = P['world_momentum']
        for t in range(1, n):
            mom = c[t - 1] - c[t - 65] if t > 64 else 0.0
            mu[t] = kap * sig[t] * z[t - 1] * np.sign(mom)
            c[t] = c[t - 1] + r0[t] + mu[t]
        full = path + mu[:, None] * (np.arange(1, sub + 1) / sub)[None, :]
        o = np.r_[0.0, c[:-1]]
        B = {'T': T, 'h': o + np.maximum(full.max(axis=1), 0.0), 'l': o + np.minimum(full.min(axis=1), 0.0), 'c': c,
             'tune_ns': tune_ns, 'val_ns': val_ns,
             'side': np.where(avail[:, None], np.zeros((1, N_SIDE)), np.nan).astype(np.float32)}
        B['z_true'] = z                            # скрытое состояние (справочно: потолок предсказуемости)
        for kind, base in (('planted', z), ('null', ar(phi_z))):
            zz = base + P['world_mri_noise'] * rng.standard_normal(n)
            zz = (zz - zz[tune_m].mean()) / zz[tune_m].std()
            zz[~avail] = np.nan
            B[f'z_{kind}'] = zz
        world.append(B)
    return world


def world_parts(B, z):
    """Стенд: непрерывный мир -> части, как у данных (load_bars): TRAINING — бары до начала VAL; VALIDATION — со своими
       hl_window барами истории перед началом (pre-бары; у мира это конец TRAINING). MRI и боковые входы на pre-барах — NaN:
       окна VAL начинаются внутри VAL."""
    T = B['T']
    j, n_pre = int(np.searchsorted(T, B['val_ns'])), REV['hl_window']
    segs = {}
    for code, (a, b, pre) in ((0, (0, j, 0)), (1, (j - n_pre, len(T), n_pre))):
        zz, ss = np.array(z[a:b], dtype=float), B['side'][a:b].copy()
        zz[:pre], ss[:pre] = np.nan, np.nan
        segs[code] = {'T': T[a:b], 'h': B['h'][a:b], 'l': B['l'][a:b], 'c': B['c'][a:b], 'z': zz, 'side': ss,
                      'n_pre': pre, 'tune_ns': B['tune_ns'], 'val_ns': B['val_ns'],
                      'norm': normalizer(B['h'][a:b], B['l'][a:b], B['c'][a:b])}
    return segs


def stand_perturb(B, m):
    """Возмущение: бары и MRI после бара cut (середина VAL) заменены другими. Экстремумы до cut и все их входы обязаны
       совпасть бит в бит, исходы, разрешившиеся до cut, — тоже. Путь тот же, что у данных: части — раздельно."""
    E1, _ = asset_events(world_parts(B, B['z_planted']), m, 0)
    T = B['T']
    cut = int(np.searchsorted(T, B['val_ns'] + (T[-1] - B['val_ns']) // 2))
    rng = np.random.default_rng(99)
    n = len(T)
    c2 = B['c'].copy()
    c2[cut + 1:] = c2[cut] + np.cumsum(rng.standard_normal(n - cut - 1))
    o2 = np.r_[c2[0], c2[:-1]]
    h2, l2 = B['h'].copy(), B['l'].copy()
    h2[cut + 1:] = np.maximum(o2, c2)[cut + 1:] + np.abs(rng.standard_normal(n - cut - 1)) * 0.5
    l2[cut + 1:] = np.minimum(o2, c2)[cut + 1:] - np.abs(rng.standard_normal(n - cut - 1)) * 0.5
    z2 = B['z_planted'].copy()
    z2[cut + 1:] = rng.standard_normal(n - cut - 1)
    side2 = B['side'].copy()
    side2[cut + 1:] = rng.standard_normal(side2[cut + 1:].shape)
    E2, _ = asset_events(world_parts(dict(B, c=c2, h=h2, l=l2, side=side2), z2), m, 0)
    tc = T[cut]
    s1, s2 = E1['T'] <= tc, E2['T'] <= tc
    same_rows = bool(np.array_equal(E1['T'][s1], E2['T'][s2]))
    labels = ('X', 'res_T')
    bad = [] if not same_rows else [key for key in E1 if key not in labels
                                     and not np.array_equal(E1[key][s1], E2[key][s2], equal_nan=True)]
    done1 = E1['res_T'][s1] <= tc
    same_x = same_rows and bool(np.array_equal(E1['X'][s1][done1], E2['X'][s2][done1]))
    ok = same_rows and not bad and same_x
    print(f"   {'✅' if ok else '❌'} возмущение баров и MRI после бара {cut}: экстремумов до него {int(s1.sum())} — те же "
          f"{same_rows}; входы бит в бит {not bad}{' (' + ', '.join(bad[:5]) + ')' if bad else ''}; исходы, разрешившиеся "
          f"до него ({int(done1.sum())}), — те же {same_x}")
    return ok


