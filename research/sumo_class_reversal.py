def make_bars(n_bars, sub=20, stoch=False, seed=0):
    """Случайное блуждание: бар — sub гауссовых под-шагов. stoch — log-вола AR(1) (полураспад 300 баров, разброс log σ
       0.45): кластеризация волы без всякой направленной структуры."""
    rng = np.random.default_rng(seed)
    sig = np.ones(n_bars)
    if stoch:
        phi = 0.5 ** (1 / 300)
        lv = lfilter([1.0], [1.0, -phi], rng.standard_normal(n_bars) * 0.45 * np.sqrt(1 - phi ** 2))
        sig = np.exp(lv - 0.5 * 0.45 ** 2)
    path = np.cumsum(rng.standard_normal((n_bars, sub)) * (sig[:, None] / np.sqrt(sub)), axis=1)
    c = np.cumsum(path[:, -1])
    o = np.r_[0.0, c[:-1]]
    return o, o + np.maximum(path.max(axis=1), 0.0), o + np.minimum(path.min(axis=1), 0.0), c, sig


