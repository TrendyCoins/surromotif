def trend_slicer_forward(data_price, min_wave_roll, start, i):
    """ ПРИЧИННЫЙ (forward) слайсер: один проход слева направо, без обратного
        скана и без коррекции пивотов.

        Состояние — три точки: подтверждённый пивот A (он же якорь живой ноги),
        бегущий экстремум ноги E и бегущий экстремум отката M. Пивот коммитится,
        когда откат от E перерос порог НА БАРЕ САМОГО E:

            |M − E| > min_wave_roll[E]

        Левая часть не убывает (M только углубляется, при обновлении E обнуляется),
        правая заморожена (индекс порога прибит к бару E) ⇒ неравенство
        однонаправленное: отмен, пересмотров и снапа не бывает by construction.

        Следствия (проверяются ниже, обязаны молчать):
          — нога рождается уже больше min_wave НА СВОЁМ ЯКОРЕ (условие коммита
            предыдущего пивота и есть первый ход новой ноги), E только усиливается
            ⇒ зрелость U/mw[A] > 1 на каждом баре: люфта нет;
          — эпоха кончается ровно на баре, где close ушёл за E − dir·mw[E],
            то есть за META_STOP ⇒ не-флипов и баров за флипом не бывает;
          — разметка на [0, T1] — префикс разметки на [0, T2] при T1 < T2.

        Обрабатывает бары [start, i-1]. Возвращает:
          piv_types / piv_price / piv_index — подтверждённые пивоты,
          piv_commit — бар подтверждения (−1 у разогревочного первого),
          bar_k — на каждый бар: индекс последнего подтверждённого пивота (−1 до первого),
          bar_e — на каждый бар: бар живого экстремума E.
    """
    n  = i
    px = data_price
    # NaN разогрева превращаем в inf: сравнение не сработает, пивот не родится
    mw  = min_wave_roll[:n]
    thr = np.where(np.isfinite(mw) & (mw > 0), mw, np.inf)

    bar_k = np.full(n, -1, dtype=np.int64)
    bar_e = np.full(n, -1, dtype=np.int64)
    piv_index, piv_price, piv_types, piv_commit = [], [], [], []

    p_dir = 0                                   # направление живой ноги: +1 вверх, −1 вниз
    hi = lo = px[start]; hi_pos = lo_pos = start
    a_pos = e_pos = m_pos = start
    a_price = e_price = m_price = px[start]

    t = start + 1
    while t < n:
        x = px[t]

        # РАЗОГРЕВ: пивотов нет, направление неизвестно — держим оба экстремума.
        # Первым пивотом становится РАННИЙ из них: тогда ход до позднего и есть
        # первая нога, и она по условию больше порога на баре якоря. После коммита
        # перематываемся на бар за пивотом и проигрываем уже установившимся режимом,
        # чтобы состояние было выведено правилом, а не собрано руками
        if p_dir == 0:
            if x > hi: hi, hi_pos = x, t
            if x < lo: lo, lo_pos = x, t
            if hi - lo > thr[min(hi_pos, lo_pos)]:
                if hi_pos < lo_pos:
                    piv_index.append(hi_pos); piv_price.append(hi); piv_types.append(1.0); p_dir = -1
                else:
                    piv_index.append(lo_pos); piv_price.append(lo); piv_types.append(-1.0); p_dir = 1
                piv_commit.append(-1)           # разогревочный пивот, бара подтверждения нет
                a_pos, a_price = piv_index[0], piv_price[0]
                e_pos, e_price = a_pos, a_price
                m_pos, m_price = a_pos, a_price
                t = a_pos + 1
                continue
            t += 1
            continue

        # ХОД НОГИ: экстремум только усиливается, откат при этом обнуляется
        if p_dir * (x - e_price) > 0:
            e_pos, e_price = t, x
            m_pos, m_price = t, x
        elif p_dir * (m_price - x) > 0:
            m_pos, m_price = t, x

        # ФЛИП. Первое условие — нога квалифицирована (|E − A| > mw[A]); в
        # установившемся режиме оно выполнено с рождения ноги и работает только
        # на разогревочном проигрывании. Второе — собственно откат за порог
        if (p_dir * (e_price - a_price) > thr[a_pos] and
            p_dir * (e_price - m_price) > thr[e_pos]):
            piv_index.append(e_pos); piv_price.append(e_price)
            piv_types.append(float(p_dir)); piv_commit.append(t)
            a_pos, a_price = e_pos, e_price     # подтверждённый экстремум = якорь новой ноги
            p_dir = -p_dir
            e_pos, e_price = m_pos, m_price     # экстремум отката = живой экстремум новой
            m_pos, m_price = e_pos, e_price     # откат новой ноги пока нулевой

        bar_k[t] = len(piv_index) - 1
        bar_e[t] = e_pos
        t += 1

    PT = np.array(piv_types)
    PP = np.array(piv_price)
    PI = np.array(piv_index,  dtype=np.int64)
    PC = np.array(piv_commit, dtype=np.int64)

    # ---- ПРОВЕРКА РАЗМЕТКИ: всё ниже обязано молчать
    if len(PI) > 1:
        if np.any(np.diff(PI) <= 0):
            print("🍆 АЙ, ОШИБКА! FORWARD: пивоты не строго по возрастанию")
        if np.any(PT[1:] == PT[:-1]):
            print("🍆 АЙ, ОШИБКА! FORWARD: два пивота одного типа подряд")

        # ЛЮФТ: каждая нога больше min_wave на СВОЁМ якоре
        legs = np.abs(np.diff(PP))
        base = thr[PI[:-1]]
        luft = legs <= base
        if luft.any():
            print(f"🍆 АЙ, ОШИБКА! FORWARD: люфт слайсера, {int(luft.sum())} ног короче "
                  f"своего min_wave, минимум {float((legs / base)[luft].min()):.3f}")

        # ФЛИП: на баре подтверждения цена ушла за уровень флипа (он же META_STOP)
        c   = PC > 0
        nof = np.abs(px[PC[c]] - PP[c]) <= thr[PI[c]]
        if nof.any():
            print(f"🍆 АЙ, ОШИБКА! FORWARD: {int(nof.sum())} ног кончилось не флипом")

        # ПИВОТ — ЭКСТРЕМУМ СВОЕЙ НОГИ на момент подтверждения [PI[k−1], PC[k]].
        # Заодно считаем, как часто он НЕ экстремум на классическом [PI[k−1], PI[k+1]]:
        # это не ошибка, а мера расхождения с зигзагом со снапом
        bad_ext, soft_ext = 0, 0
        for k in range(1, len(PI)):
            seg = px[PI[k-1]: PC[k] + 1]
            if (seg.max() if PT[k] > 0 else seg.min()) != PP[k]: bad_ext += 1
            if k + 1 < len(PI):
                seg = px[PI[k-1]: PI[k+1] + 1]
                if (seg.max() if PT[k] > 0 else seg.min()) != PP[k]: soft_ext += 1
        if bad_ext:
            print(f"🍆 АЙ, ОШИБКА! FORWARD: {bad_ext} пивотов не экстремум своей ноги")

        # print(f"📐 FORWARD: {len(PI)} пивотов | нога {np.median(np.diff(PI)):.0f} баров "
        #       f"и {np.median(legs / base):.2f} mw (медианы) | задержка подтверждения "
        #       f"{np.median(PC[c] - PI[c]):.0f} баров | перекрыт соседом "
        #       f"{100 * soft_ext / max(1, len(PI) - 2):.2f}%")

    return PT, PP, PI, PC, bar_k, bar_e

def true_range(h, l, c):
    """Истинный диапазон бара: max(high, прошлый close) − min(low, прошлый close) — диапазон вместе с разрывом от прошлого
       бара (у первого бара — просто high − low)."""
    h, l, c = np.asarray(h, float), np.asarray(l, float), np.asarray(c, float)
    prev = np.r_[np.nan, c[:-1]]
    return np.fmax(h, prev) - np.fmin(l, prev)


def normalizer(h, l, c):
    """Мерка зигзага — средний истинный диапазон (ATR) за hl_window баров до бара (closed='left'), и живость бара — жив ли
       на нём нормировщик r SMC_Data (медиана high − low за те же бары > 0; мёртвая — больше половины баров окна без
       диапазона: неликвид, бар — одна сделка; у r там NaN, MRI нет). Мерка — не медиана диапазона: у неликвида она
       проваливается к долям тика задолго до нуля и не видит разрывов между барами-сделками, и порог из неё дрожит на шуме
       (v3: доля ног короче 96 баров ~45% на любом m); средний истинный диапазон убывает плавно, вместе с самим движением
       цены. Возвращает (мерка, живой ли бар); от m не зависит — в переборе масштабов считается один раз."""
    w = REV['hl_window']
    rmed = pd.Series(np.asarray(h, float) - np.asarray(l, float)).rolling(w, closed='left').median().to_numpy()
    atr = pd.Series(true_range(h, l, c)).rolling(w, closed='left').mean().to_numpy()
    return atr, np.isfinite(rmed) & (rmed > 0) & np.isfinite(atr) & (atr > 0)


def run_slicer(c, h, l, m, norm=None):
    """Слайсер Фёдора на close по живым барам (norm — готовый normalizer(h, l, c)), порог — m ATR за 200 баров: бары с мёртвым
       нормировщиком r зигзаг не видит вовсе — на них его состояние стоит, как будто баров нет. Порог на мёртвом баре
       определить нечем: бесконечный (v2) замораживал зигзаг до конца ряда — экстремум на таком баре не подтверждался
       никогда; последним живым значением медианы (v3) — дрожал на тиковом шуме. Разметка — в индексах полного ряда
       (bar_k / bar_e на мёртвых барах — как на последнем живом). Возвращает (мерка, порог, разметка)."""
    c = np.asarray(c, float)
    atr, live = normalizer(h, l, c) if norm is None else norm
    n, idx = len(c), np.where(live)[0]
    mw = atr * m
    bar_k, bar_e = np.full(n, -1, np.int64), np.full(n, -1, np.int64)
    if len(idx) < 2:
        return atr, mw, (np.zeros(0), np.zeros(0), np.zeros(0, np.int64), np.zeros(0, np.int64), bar_k, bar_e)
    PT, PP, PI, PC, bk, be = trend_slicer_forward(c[idx], mw[idx], 0, len(idx))
    PI = idx[PI]
    PC = np.where(PC >= 0, idx[np.maximum(PC, 0)], -1)
    bar_k[idx], bar_e[idx] = bk, np.where(be >= 0, idx[np.maximum(be, 0)], -1)
    last = np.maximum.accumulate(np.where(live, np.arange(n), -1))       # последний живой бар (−1 — его ещё не было)
    bar_k = np.where(last >= 0, bar_k[np.maximum(last, 0)], -1)
    bar_e = np.where(last >= 0, bar_e[np.maximum(last, 0)], -1)
    return atr, mw, (PT, PP, PI, PC, bar_k, bar_e)


def extremes(c, mw, PT, PI, PC, bar_k, bar_e):
    """Выборка: каждый бар t, где живая нога обновила экстремум по close (bar_e[t] == t). Экстремумы новой ноги до
       подтверждения — это откат M старой ноги, сюда не попадают; бар подтверждения (коммит пивота-якоря) — первый экстремум
       подтверждённой ноги. Исход — бар разрешения: первый бар после t, где bar_e меняется. Если на нём закоммичен новый пивот
       (bar_k вырос) — это разворот, и пивотом стал сам t. X — наибольший откат от close[t] до разрешения в долях mw[t]
       (порог флипа прибит к бару экстремума); у разворота X = 1. Экстремумы без разрешения до конца ряда отбрасываются.
       c — close баров, которые видел слайсер (мёртвые — NaN: откат по ним не считается); у продолжения X < 1 строго —
       при цене на сетке тиков откат ровно в порог возможен, а слайсер коммитит только при «больше»."""
    n = len(c)
    t_all = np.where(bar_e == np.arange(n))[0]
    t_all = t_all[bar_k[t_all] >= 0]
    chg = np.r_[np.where(bar_e[1:] != bar_e[:-1])[0] + 1, n]
    res = chg[np.searchsorted(chg, t_all, side='right')]
    ok = res < n
    t_all, res = t_all[ok], res[ok]
    k = bar_k[t_all]
    d = -PT[k]                                    # якорь — пик (+1) -> нога вниз (−1)
    rev = bar_k[res] > k
    X = np.ones(len(t_all))
    for j in np.where(~rev)[0]:                   # откаты разных экстремумов не пересекаются
        seg = c[t_all[j] + 1:res[j]]
        seg = seg[np.isfinite(seg)]
        if seg.size:
            ext = seg.min() if d[j] > 0 else seg.max()
            den = mw[t_all[j]]
            X[j] = min(d[j] * (c[t_all[j]] - ext) / den, 1.0 - 1e-9) if den > 0 else np.nan
        else:
            X[j] = 0.0                            # следующий видимый бар сразу обновил экстремум
    A = PI[k]
    return {'t': t_all, 'res': res, 'rev': rev, 'X': np.clip(X, 0, 1), 'dir': d, 'k': k,
            'age': t_all - A, 'size': d * (c[t_all] - c[A]) / mw[A]}


