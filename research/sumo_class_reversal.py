def mean_se_weeks(Z, wk):
    """Среднее по столбцам и его ошибка по неделям (события одной недели связаны)."""
    m = Z.mean(0)
    _, inv = np.unique(wk, return_inverse=True)
    G = int(inv.max()) + 1
    S = np.zeros((G, Z.shape[1]))
    np.add.at(S, inv, Z - m)
    return m, np.sqrt(G / max(G - 1, 1) * (S ** 2).sum(0)) / len(Z)


