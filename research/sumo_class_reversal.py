def load_train():
    """Код обучения (v6.1+) модулем из TRAIN_PY: только определения (SMC_MODE = 'none' ставится здесь, руками не нужно)."""
    if not os.path.isfile(TRAIN_PY):
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет кода обучения {TRAIN_PY} — положи туда sumo_class_train.py v6.1+ "
                                f"(тот же файл, что у Shapes)")
    os.environ['SMC_MODE'] = 'none'
    spec = importlib.util.spec_from_file_location('smc_train', TRAIN_PY)
    mod = importlib.util.module_from_spec(spec)
    sys.modules['smc_train'] = mod
    spec.loader.exec_module(mod)
    need = ('SeriesData', 'side_feats', 'to_shapes', 'build_model', 'score', 'SMC_BASE', 'SIDE_COLS', 'NT_COL0',
            'N_PATH', 'N_LEVEL', 'MULTI_KINDS', 'POOL', '_pool_tag', 'DEVICE')
    miss = [key for key in need if not hasattr(mod, key)]
    if miss or REV['model'] not in mod.POOL['models']:
        raise ImportError(f"🍆 АЙ, ОШИБКА! {TRAIN_PY}: нет {', '.join(miss) or REV['model'] + ' в POOL'} — нужен код "
                          f"обучения v6.1+")
    mod.DATA_DIR, mod.RUN_DIR, mod.DATA_OVERLAY = DATA_DIR, RUN_DIR, None
    print(f"🧩 код обучения — {TRAIN_PY} | {mod.DEVICE}")
    return mod


def load_pool_model(smc, seed):
    import torch
    tag = smc._pool_tag(REV['set'], seed, REV['model'], REV['gen'])
    jp, npp = RUN_DIR + f"pool/{tag}.json", RUN_DIR + f"pool/{tag}.npz"
    if not (os.path.isfile(jp) and os.path.isfile(npp)):
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет прогона пула {tag} (json + npz) в {RUN_DIR}pool/")
    with open(jp, encoding='utf-8') as fh:
        r = json.load(fh)
    cfg = {**smc.SMC_BASE, **r['cfg']}
    for key in ('head_hidden', 'cnn_dil'):
        if isinstance(cfg.get(key), list):
            cfg[key] = tuple(cfg[key])
    price = cfg.get('price', 'close')
    n_ch = smc.N_PATH + smc.N_LEVEL.get(price, 0) if price in smc.MULTI_KINDS else 1
    shape = (16, n_ch, cfg['L']) if n_ch > 1 else (16, cfg['L'])
    model, _ = smc.build_model(cfg, torch.randn(*shape, device=smc.DEVICE), np.random.default_rng(0))
    d = np.load(npp)
    model.load_state_dict({key[3:]: torch.from_numpy(d[key]) for key in d.files if key.startswith('sd_')}, strict=True)
    model.eval()
    print(f"🧠 {tag}: эпох {r.get('epochs_run')}, лучшая {r.get('best_ep', -1) + 1} | панель TUNE "
          f"{_f(r['summary']['tune']['panel'], '.4f')}, VAL {_f(r['summary']['val']['panel'], '.4f')} | VAL пула — до "
          f"{str(r.get('t_cut'))[:16]}")
    return {'model': model, 'run': r, 'npz': d, 'cfg': cfg, 'tag': tag, 't_cut': pd.Timestamp(r['t_cut']).value}


def mri_asset(smc, M, side_cols, asset):
    """MRI ассета: logit каждого сида на всех окнах TUNE и VAL, боковые входы окна; сверка с наборами проверки прогонов
       пула (те же окна, те же входы: у пула VAL обрезан по концу BTC)."""
    import torch
    t0 = time.time()
    L, cfg = REV['L'], M[0]['cfg']
    data = smc.SeriesData([asset], REV['tf'], REV['N'], REV['tune_start'], cfg['price'])
    w = data.windows(L)
    idx = np.sort(np.concatenate([w['tune'], w['val']]))
    part = np.isin(idx, w['val']).astype(np.int8)
    st = w['st'][idx]
    t_end = data.t[st + L - 1].astype(np.int64)
    lg = np.zeros((len(M), len(idx)), np.float32)
    side = np.zeros((len(idx), len(side_cols)), np.float32)
    with torch.no_grad():
        for i in range(0, len(idx), REV['chunk']):
            j = slice(i, i + REV['chunk'])
            st_t = torch.from_numpy(st[j]).to(smc.DEVICE)
            sid_t = torch.from_numpy(w['sid'][idx[j]]).to(smc.DEVICE)
            W = data.gw(st_t, L)
            fl = w['floor_t'][sid_t]
            X = smc.to_shapes(W, fl)
            S = smc.side_feats(data, st_t, L, W, fl)
            for k, mm in enumerate(M):
                lg[k, j] = smc.score(mm['model'], X, S=S)
            side[j] = S[:, side_cols].float().cpu().numpy()
            del W, X, S
    checks, ok = [], True
    for k, mm in enumerate(M):
        for p_name, p_code in (('tune', 0), ('val', 1)):
            key = f"{asset}__{p_name}__sp"
            if key not in mm['npz'].files:
                continue
            ref = mm['npz'][key].astype(np.float64)
            sel = part == p_code
            if p_code == 1:
                sel &= t_end <= mm['t_cut']
            row = {'seed': REV['seeds'][k], 'part': p_name, 'n': int(len(ref)), 'n_ours': int(sel.sum())}
            stk = f"{asset}__{p_name}__st"
            if len(ref) != sel.sum() or (stk in mm['npz'].files and not np.array_equal(mm['npz'][stk], st[sel])):
                row.update({'ok': False, 'why': 'окна не те'})
            else:
                dd = np.abs(lg[k, sel].astype(np.float64) - ref)
                row.update({'max': float(dd.max()), 'med': float(np.median(dd)),
                            'share': float(np.mean(dd > REV['check_tol']))})
                row['ok'] = bool(row['share'] <= REV['check_share'] and row['med'] <= REV['check_med'])
            ok &= row['ok']
            checks.append(row)
    if not checks:
        ok = False
    meta = {'ver': MRI_VER, 'asset': asset, 'tags': [mm['tag'] for mm in M], 'seeds': list(REV['seeds']),
            'side_cols': list(side_cols), 'side_names': [smc.SIDE_NAMES[c_] for c_ in side_cols], 'checks': checks,
            'check_ok': bool(ok), 'when': time.strftime('%Y-%m-%d %H:%M:%S')}
    np.savez_compressed(OUT_DIR + f"mri/{asset}.npz", t_end=t_end, part=part, logit=lg, side=side.astype(np.float16),
                        meta=json.dumps(meta, ensure_ascii=False))
    worst = max((r_.get('max', np.nan) for r_ in checks if 'max' in r_), default=np.nan)
    med = max((r_.get('med', np.nan) for r_ in checks if 'med' in r_), default=np.nan)
    bad = [f"{r_['seed']}/{r_['part']}: " + (r_['why'] if 'why' in r_ else
                                            f"медиана |Δ| {r_['med']:.0e}, доля |Δ| > {REV['check_tol']:g} — {r_['share']:.1e}")
           for r_ in checks if not r_['ok']]
    print(f"   {'✅' if ok else '❌'} {asset:<11} окон TUNE {int((part == 0).sum()):>7}, VAL {int((part == 1).sum()):>7} | logit "
          f"TUNE {lg[:, part == 0].mean():+.3f}, VAL {lg[:, part == 1].mean():+.3f} | сверка с пулом: |Δ| медиана "
          f"{_f(med, '.0e')}, макс. {_f(worst, '.0e')}" + (" — " + "; ".join(bad) if bad else "")
          + ("" if checks else " — в прогонах пула нет наборов проверки этого ассета")
          + f" | {time.time() - t0:.0f} c", flush=True)
    del data
    if smc.DEVICE.type == 'cuda':
        torch.cuda.empty_cache()
    return ok


