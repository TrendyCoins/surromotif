def npz_keys(base, keys):
    """Только нужные массивы прогона (npz целиком или частями <base>_part*.npz): {ключ: массив}; ключа нет — нет в словаре."""
    paths = [base + '.npz'] if os.path.isfile(base + '.npz') else sorted(glob.glob(base + '_part*.npz'))
    if not paths:
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет оценок прогона: ни {base}.npz, ни частей {base}_part*.npz")
    want, out = set(keys), {}
    for p in paths:
        with np.load(p) as d:
            for k in d.files:
                if k in want:
                    out[k] = d[k]
    return out


def read_sources(T, assets):
    """Оценки источников проверки: как read_source_raw у Bell (те же ряды, что у Live и Ceil) + начала окон st."""
    raw, tags = {}, {}
    for key in (CL.CEIL['main'], CL.CEIL['confirm']):
        r, tg = BB.read_source_raw(T, key, assets)
        S = BB.BELL['sources'][key]
        for seed, D in r.items():
            base = RUN_DIR + 'pool/' + T._pool_tag(S['set'], seed, BB.BELL['model'], S['mode'])
            st = npz_keys(base, [f"{a}__{p}__st" for a in D for p in S['parts']])
            for a, d in D.items():
                ks = [f"{a}__{p}__st" for p in S['parts']]
                if all(k in st for k in ks):
                    d['st'] = np.concatenate([st[k] for k in ks]).astype(np.int64)
                    if len(d['st']) != len(d['sp']):
                        raise ValueError(f"🍆 АЙ, ОШИБКА! {key} {seed} {a}: начал окон {len(d['st'])}, оценок {len(d['sp'])}")
        raw[key], tags[key] = r, tg
    return raw, tags


def val_slice(key, d):
    """Окна VAL ряда: у основного источника — после разгона (TUNE), у подтверждения — все (П1 + П2)."""
    return slice(d['B'], None) if BB.BELL['sources'][key]['burn'] == 'tune' else slice(0, None)


def ens_raw(raw, seeds, name=None):
    """Псевдо-сид ансамбля: у каждого ассета — средний logit сидов seeds (реальные окна и суррогаты). Окна сидов обязаны
       совпасть (длины, недели, разгон, начала окон) — сверка (2); иначе ошибка."""
    name = name or ''.join(seeds)
    out = {}
    for a in raw[seeds[0]]:
        ds = [raw[s].get(a) for s in seeds]
        if any(d is None for d in ds):
            raise ValueError(f"🍆 АЙ, ОШИБКА! ансамбль {name}: у сидов {seeds} разный набор ассетов ({a})")
        d0 = ds[0]
        n = len(d0['sp'])
        bad = [s for s, d in zip(seeds, ds) if len(d['sp']) != n or len(d['sn']) != n or d['B'] != d0['B']
               or not np.array_equal(d['wk'], d0['wk']) or (('st' in d) != ('st' in d0))
               or ('st' in d and not np.array_equal(d['st'], d0['st']))]
        if bad:
            raise ValueError(f"🍆 АЙ, ОШИБКА! ансамбль {name}, {a}: окна сидов {bad} не те же, что у {seeds[0]} — средний logit "
                             f"не считается")
        e = {'sp': np.mean([d['sp'] for d in ds], axis=0), 'sn': np.mean([d['sn'] for d in ds], axis=0),
             'wk': d0['wk'], 'B': d0['B']}
        if 'st' in d0:
            e['st'] = d0['st']
        out[a] = e
    return {name: out}


def cfg_raw(raw_src, cfg):
    """Ряды источника для конфигурации: 'single' — сиды a, b как отдельные ряды (как у Live / Ceil), 'ens2' — псевдо-сид ab."""
    if cfg == 'single':
        return {s: raw_src[s] for s in SITE['seeds']}
    if cfg == 'ens2':
        return ens_raw(raw_src, tuple(SITE['seeds']))
    raise ValueError(f"🍆 АЙ, ОШИБКА! конфигурации '{cfg}' у источников нет (сида c нет)")


