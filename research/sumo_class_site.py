def synth_world(T, assets, n_tune, n_val, phi, seed, seeds=('a', 'b'), w0=None, tau_seed=8):
    """Синтетический источник {сид: {ассет: sp, sn, wk, B, st}}: у окна общий для сидов сигнал (реальные — сдвинуты вверх,
       медленный шум MA(64)), у суррогатов — общий шум MA(64); у каждой оценки — свой шум сида (MA(tau_seed), вес phi)."""
    rng = np.random.default_rng(seed)
    n = n_tune + n_val
    if w0 is None:
        w0 = pd.Timestamp(T.NOCAL['half_cut']).value // T.WEEK_NS - 7 - n_tune // 2016
    raw = {s: {} for s in seeds}
    for i, a in enumerate(assets):
        mu = 0.6 + 0.2 * rng.random()
        cp, cn = BB.ma_noise(rng, n, 64), BB.ma_noise(rng, n, 64)
        st = 1_000_000 * (i + 1) + np.arange(n, dtype=np.int64)
        for s in seeds:
            ep, en = BB.ma_noise(rng, n, tau_seed), BB.ma_noise(rng, n, tau_seed)
            raw[s][a] = {'sp': -0.7 + 1.4 * (mu + cp + phi * ep), 'sn': -0.7 + 1.4 * (cn + phi * en),
                         'wk': w0 + np.arange(n) // 2016, 'B': n_tune, 'st': st}
    return raw


def write_npz(T, raw, set_, mode, parts, out_dir):
    """Синтетический прогон пула: <out_dir>pool/<тег>.npz с полями «ассет__часть__sp / sn / wk / st» (как у run_pool)."""
    os.makedirs(out_dir + 'pool/', exist_ok=True)
    for seed, D in raw.items():
        arr = {}
        for a, d in D.items():
            cut = {'tune': slice(0, d['B']), 'val': slice(d['B'], None)} if len(parts) == 2 else {'val': slice(0, None)}
            for p in parts:
                for f in ('sp', 'sn', 'wk', 'st'):
                    x = d[f][cut[p]]
                    arr[f"{a}__{p}__{f}"] = x.astype(np.float32 if f in ('sp', 'sn') else (np.int32 if f == 'wk' else np.int64))
        np.savez(out_dir + 'pool/' + T._pool_tag(set_, seed, SITE['model'], mode) + '.npz', **arr)


