def k_curve(T, assets, ref, panel):
    """Ансамбли k = 1…4 из четырёх 'refit' (C и ALL, сиды a / b; общие ассеты набора C, VAL): среднее по всем сочетаниям k
       моделей — AUC BTC и среднее по ассетам, log R BTC и панели; u — к k = 1 и шаг k − 1 → k. None — прогонов нет."""
    mods = list(SITE['k_models'])
    arr = []
    for set_, seed, mode in mods:
        base = RUN_DIR + 'pool/' + T._pool_tag(set_, seed, SITE['model'], mode)
        if not (os.path.isfile(base + '.npz') or glob.glob(base + '_part*.npz')):
            print(f"   ⏭️ кривая k: нет прогона {os.path.basename(base)} — кривая не считается")
            return None
        arr.append(npz_keys(base, [f"{a}__val__{f}" for a in assets for f in ('sp', 'sn', 'wk', 'st')]))
    names = [a for a in T.POOL['sets']['C'] if a in assets and all(f"{a}__val__sp" in x for x in arr)]
    for a in names:
        for x in arr[1:]:
            if (len(x[f"{a}__val__sp"]) != len(arr[0][f"{a}__val__sp"])
                    or not np.array_equal(x[f"{a}__val__wk"], arr[0][f"{a}__val__wk"])
                    or not np.array_equal(x.get(f"{a}__val__st"), arr[0].get(f"{a}__val__st"))):
                print(f"   ❗ кривая k: у прогонов разные окна VAL {a} — кривая не считается (справочная, решений не меняет)")
                return None
    if ref not in names:
        print(f"   ⏭️ кривая k: {ref} нет в общих ассетах — кривая не считается")
        return None
    r_names = [a for a in [ref] + [p for p in panel if p != ref] if a in names and f"{a}__val__st" in arr[0]]
    K = len(mods)
    rows = []
    for k in range(1, K + 1):
        acc = {'auc_btc': [], 'auc_all': [], 'lr_btc': [], 'lr_panel': []}
        for comb in itertools.combinations(range(K), k):
            aucs, lrs = {}, {}
            for a in names:
                sp = np.mean([arr[j][f"{a}__val__sp"].astype(np.float64) for j in comb], axis=0)
                sn = np.mean([arr[j][f"{a}__val__sn"].astype(np.float64) for j in comb], axis=0)
                aucs[a] = T.auc_parts(sp, sn)[0]
                if a in r_names:
                    _, A = T._line_weeks(arr[0][f"{a}__val__st"], sp, arr[0][f"{a}__val__wk"])
                    lrs[a] = float(np.log(T._R_from(A.sum(1))))
            acc['auc_btc'].append(aucs[ref])
            acc['auc_all'].append(float(np.mean(list(aucs.values()))))
            acc['lr_btc'].append(lrs[ref])
            acc['lr_panel'].append(float(np.mean(list(lrs.values()))))
        rows.append({'k': k, 'combos': len(acc['auc_btc']), **{f: float(np.mean(x)) for f, x in acc.items()}})
    for i, r in enumerate(rows):
        r0, rp = rows[0], rows[max(i - 1, 0)]
        for g, fa, fl in (('btc', 'auc_btc', 'lr_btc'), ('panel', 'auc_all', 'lr_panel')):
            r[f'd_auc_{g}'] = r[fa] - r0[fa]
            r[f'ratio_{g}'] = math.exp(r[fl] - r0[fl])
            r[f'u_{g}'] = r[f'd_auc_{g}'] / SITE['u_auc'] + (1.0 - r[f'ratio_{g}']) / SITE['u_r']
            r[f'u_step_{g}'] = ((r[fa] - rp[fa]) / SITE['u_auc'] + (1.0 - math.exp(r[fl] - rp[fl])) / SITE['u_r']) if i else 0.0
    return {'models': [f"{s_}-{seed}-{mo}" for s_, seed, mo in mods], 'assets': names, 'r_assets': r_names, 'rows': rows}


