def flips(lg, st):
    """Смены цвета линии M между соседними окнами (бары s и s + 1): сторона (оранжевая / синяя по знаку log M), оттенок
       (сторона × корзина M по LINE_SHADES кода обучения, как side100 / shade100 волны SM), отметка (M >= 1.25 / <= 0.8 / нет,
       как у индикатора). Возвращает [пар, смен стороны, смен оттенка, смен отметки]."""
    st = np.asarray(st, dtype=np.int64)
    i0 = np.where(st[1:] == st[:-1] + 1)[0]
    i1 = i0 + 1
    side = np.where(lg >= 0, 1, -1)
    cls = side * (1 + np.searchsorted(np.log(np.asarray(_SHADES, dtype=np.float64)), np.abs(lg)))
    t = math.log(1.25)
    mark = np.where(lg >= t, 1, np.where(lg <= -t, -1, 0))
    return np.array([len(i0), (side[i1] != side[i0]).sum(), (cls[i1] != cls[i0]).sum(), (mark[i1] != mark[i0]).sum()],
                    dtype=np.float64)


_SHADES = (1.5, 2.5, 5.0, 10.0)          # заменяется на LINE_SHADES кода обучения при загрузке (mode_*)


def line_flips(T, raw_c, v, groups):
    """Смены цвета на 100 баров у линии M формулы А (окна оценки, как в Live), по группам; log M рядов — для рисунка."""
    lm = CL.series_logm(T, raw_c, v)
    acc = {}
    for (seed, a), lg in lm.items():
        d = raw_c[seed][a]
        if 'st' not in d:
            continue
        acc[a] = acc.get(a, np.zeros(4)) + flips(lg, d['st'][d['B']:])
    out = {}
    for name, grp in groups.items():
        rows = [acc[a] for a in grp if a in acc]
        if not rows:
            continue
        tot = np.sum(rows, axis=0)
        out[name] = {'pairs': int(tot[0]), 'side100': 100 * tot[1] / max(tot[0], 1), 'shade100': 100 * tot[2] / max(tot[0], 1),
                     'mark100': 100 * tot[3] / max(tot[0], 1)}
    return out, lm


def ens_source(T, key, raw_src, assets, groups, v):
    """(А) на одном источнике: ансамбль a + b против одного сида — AUC, R, u по группам, линия M (BCE, ворота), смены цвета."""
    seeds = tuple(SITE['seeds'])
    single = {s: raw_src[s] for s in seeds}
    E_d = ens_raw(raw_src, seeds)
    E = next(iter(E_d.values()))
    pa = auc_parts_src(T, single, E, key, assets)
    pr = r_parts_src(T, single, E, key, assets)
    out = {'auc': {}, 'r': {}, 'u': {}, 'per_asset': {}}
    for name, grp in groups.items():
        ag, rg = auc_group(T, pa, grp), r_group(T, pr, grp)
        out['auc'][name], out['r'][name] = ag, rg
        out['u'][name] = u_group(T, pa, pr, grp) if ag and rg else (math.nan, math.nan)
    for a in assets:
        if a in pa:
            out['per_asset'][a] = {'auc_single': pa[a]['single'], 'auc_ens': pa[a]['ens'], 'auc_seeds': pa[a]['seeds'],
                                   'd_auc': pa[a]['d'], 'r_ratio': math.exp(pr[a]['lr']) if a in pr else None}
    res_s, res_e = line_eval(T, key, single, v), line_eval(T, key, E_d, v)
    if len(res_s['wk_bce']) != len(res_e['wk_bce']):
        raise RuntimeError("🍆 АЙ, ОШИБКА! у одного сида и ансамбля разные недели — парная разница BCE не считается")
    d, se = BB.paired({'e': res_e, 's': res_s}, 'e', 's')
    fs, lm_s = line_flips(T, single, v, groups)
    fe, lm_e = line_flips(T, E_d, v, groups)
    out['line'] = {'single': res_s, 'ens': res_e, 'd_bce': d, 'se_bce': se, 'flips': {'single': fs, 'ens': fe}}
    out['logm'] = {'single': lm_s, 'ens': lm_e}
    return out


def _cg(x):
    """Потолок: ∞ — у корзин нет предела; — — нет данных."""
    return '∞' if x is not None and x == math.inf else _f(x, 'g')


