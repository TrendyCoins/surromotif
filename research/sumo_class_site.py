def _import(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


def load_modules():
    """SuMo_Class_Ceil модулем из CEIL_PY (он подгружает Live, Bell и код обучения); пути — этого файла. Модель Bell — F1
       сайта, сиды источников — SITE['seeds'], боевые сиды Ceil — SITE['prod_seeds'], список пересчёта — site_needs."""
