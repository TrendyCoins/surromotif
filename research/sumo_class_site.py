    print(f"   🏁 (Ж) ФОРМУЛА ДЛЯ САЙТА: {chA['pick'] if ok else 'нет — решение за Фёдором'}")
    return {'pick': chA['pick'] if ok else None, 'pick_main': chA['pick'], 'confirm': conf, 'main': LV.pack(resA, chA),
            'confirm_source': LV.pack(resC, chC), 'indicator_formula': a_ref}


