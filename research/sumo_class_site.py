def rulers(T, rec, assets):
    """Линейки конфигураций: 37 квантилей logit суррогатов VAL всех ассетов у боевых сидов (у ансамбля — средних logit
       сидов; окна сидов обязаны совпасть), с полом 0.2. У одного сида — справочно против линейки json 'nocal' (старый пол
       и TF32 прогона)."""
    knots, zk = BB.knots_zk(T)
    out = {}
    for cfg, seeds in SITE['configs'].items():
        tags = [T._pool_tag('ALL', s, SITE['model'], 'prod') for s in seeds]
        if any(t not in rec for t in tags):
            print(f"   ⏭️ линейка {cfg}: нет пересчёта {', '.join(t for t in tags if t not in rec)}")
            continue
        have = [a for a in assets if all((a, 'val') in rec[t]['res'] for t in tags)]
        sn = []
        for a in have:
            xs = [rec[t]['res'][(a, 'val')] for t in tags]
            if any(len(x['sn']) != len(xs[0]['sn']) or not np.array_equal(x['wk'], xs[0]['wk']) for x in xs):
                raise ValueError(f"🍆 АЙ, ОШИБКА! линейка {cfg}: у боевых сидов разные окна VAL {a}")
            sn.append(np.mean([x['sn'] for x in xs], axis=0))
        sn = np.concatenate(sn)
        row = {'config': cfg, 'seeds': list(seeds), 'n_assets': len(have), 'n_null': int(len(sn)), 'q': BB.ruler_q(sn, knots),
               'prod': [{'seed': s, 'tag': rec[t]['run'].get('tag', t), 't_cut': rec[t]['run'].get('t_cut'),
                         'data_overlay': rec[t]['run'].get('data_overlay')} for s, t in zip(seeds, tags)]}
        if cfg == 'single':
            nc, src = CL.nocal_prod_q(seeds[0])
            row['nocal_json'] = src
            if nc is not None:
                q_old = np.asarray(nc['glob_e']['q'], dtype=np.float64)
                row['dq_nocal'] = float(np.max(np.abs(row['q'] - q_old)))
                row['dz_nocal'] = float(np.max(np.abs(np.interp(q_old, row['q'], zk) - zk)))
                row['same_tag'] = nc.get('tag') == row['prod'][0]['tag']
        out[cfg] = row
    return out


def golden_times(T, st, wk):
    """Время конца окон BTC (нс, метка последнего бара окна — как t_end в данных SMC) по их началам st: позиции у BTC в пуле и
       в одиночном ряде одни и те же (BTC в пуле первым). Сверка: неделя времени конца = неделя окна. None — не сошлось."""
    try:
        data = T._sm_load_data()
        L = T.POOL['L']
        idx = np.asarray(st, dtype=np.int64) + (L - 1)
        if idx.min() < 0 or idx.max() >= len(data.t):
            print("   ❗ golden: начала окон вне ряда BTC — времени окон нет")
            return None
        t_end = np.asarray(data.t[idx], dtype=np.int64)
    except Exception as e:                                    # время — справочно: без него golden всё равно пишется
        print(f"   ❗ golden: время окон не получено ({type(e).__name__}: {e})")
        return None
    if not np.array_equal(t_end // T.WEEK_NS, np.asarray(wk, dtype=np.int64)):
        print("   ❗ golden: недели по времени конца окон не совпали с неделями окон — времени окон нет")
        return None
    return t_end


def golden(T, rec, ruler, cfg, v, path, src_conf=None):
    """Паритет бэкенда: VAL ассета SITE['golden'] — logit всех боевых сидов с полом 0.2, logit конфигурации (средний у
       ансамбля), z по её линейке, живая часть формулы А с начала ряда (m, s, n — реальных окон в ней), показ с окна L + сдвиг,
       log M; начала окон и время конца окна (из 'refit' ALL того же ассета: окна VAL research те же — недели сверяются). Сверка
       (4): log M из записанных logit — бит в бит (целость файла). Возвращает (итог, описание)."""
    a = SITE['golden']
    knots, zk = BB.knots_zk(T)
    xs = {}
    for s in SITE['prod_seeds']:
        t = T._pool_tag('ALL', s, SITE['model'], 'prod')
        if t in rec and (a, 'val') in rec[t]['res']:
            xs[s] = rec[t]['res'][(a, 'val')]
    seeds = SITE['configs'][cfg]
    if any(s not in xs for s in seeds):
        print(f"   ⏭️ golden: у {a} нет пересчёта сидов {seeds}")
        return False, None
    if any(not np.array_equal(x['wk'], xs[seeds[0]]['wk']) for x in xs.values()):
        raise ValueError(f"🍆 АЙ, ОШИБКА! golden: у боевых сидов разные окна VAL {a}")

    def line_of(lg):
        z = BB.to_z(lg, ruler['q'], zk)
        q = LV.chart_ms(T, z, [(0, len(z))], v, {}, p_from=0)
        show = q['p'] >= CL.full_from(v)
        lm = np.full(len(z), np.nan)
        lm[show] = T._nc_logm(z[show], q['m'][show], q['s'][show])
        return z, q, show, lm
    lg = np.mean([xs[s]['sp'].astype(np.float32).astype(np.float64) for s in seeds], axis=0)
    z, q, show, lm = line_of(lg)
    wk = np.asarray(xs[seeds[0]]['wk'], dtype=np.int64)
    st, t_end = None, None
    d_c = (src_conf or {}).get(SITE['seeds'][0], {}).get(a)
    if d_c is not None and 'st' in d_c and len(d_c['st']) == len(wk) and np.array_equal(np.asarray(d_c['wk']), wk):
        st = np.asarray(d_c['st'], dtype=np.int64)
        t_end = golden_times(T, st, wk)
    elif src_conf is not None:
        print("   ❗ golden: окна боевого пересчёта не те, что у 'refit' ALL, — начал и времени окон нет")
    lf = live_formula(T, v)
    meta = {'asset': a, 'model': SITE['model'], 'config': cfg, 'seeds': list(seeds), 'floor': CL.CEIL['floor'],
            'knots': list(knots), 'zk': list(zk), 'q': list(ruler['q']),
            'live': {k_: lf[k_] for k_ in ('key', 'family', 'L', 'n0', 'k', 'tau', 'lag', 'show_from_window', 's_lo')},
            'part': "VAL 'research' (как у линейки)",
            'logit': 'среднее logit сидов (float32 -> float64)' if len(seeds) > 1 else 'logit сида (float32 -> float64)',
            't_end': 'время конца окна, нс UTC (метка последнего бара окна, как в данных SMC)' if t_end is not None else None,
            'tol': 'сверка бэкенда: z, m, s, log M — до 1e-9 (скользящие суммы против префиксных бит в бит не совпадут); '
                   'logit своего инференса — до допуска float32 модели'}
    arrs = {f"logit_{s}": x['sp'].astype(np.float32) for s, x in xs.items()}
    arrs.update({'logit': lg, 'z': z, 'm': q['m'], 's': q['s'], 'n_live': q['n'].astype(np.int32), 'show': show,
                 'logm': lm, 'wk': wk.astype(np.int32), 'meta': np.array(json.dumps(meta))})
    if st is not None:
        arrs['st'] = st
    if t_end is not None:
        arrs['t_end'] = t_end
    np.savez_compressed(path, **arrs)
    with np.load(path) as d:                                  # сверка (4): заново из записанных logit
        lg2 = np.mean([d[f"logit_{s}"].astype(np.float64) for s in seeds], axis=0)
        z2, q2, show2, lm2 = line_of(lg2)
        same = bool(np.array_equal(lg2, d['logit']) and np.array_equal(z2, d['z']) and np.array_equal(show2, d['show'])
                    and np.array_equal(np.nan_to_num(lm2, nan=7.0), np.nan_to_num(d['logm'], nan=7.0)))
    size = os.path.getsize(path) / 2 ** 20
    tt = (f"время окон {pd.Timestamp(int(t_end[0])):%Y-%m-%d %H:%M} … {pd.Timestamp(int(t_end[-1])):%Y-%m-%d %H:%M}"
          if t_end is not None else "без времени окон")
    print(f"   golden {os.path.basename(path)}: {a}, окон {len(z)}, линия на {int(show.sum())}, {tt}, {size:.1f} МБ | сверка "
          f"(4): линия из записанных logit — бит в бит {'✅' if same else '❌'}")
    return same, {'path': os.path.basename(path), 'n': int(len(z)), 'shown': int(show.sum()), 'mb': size, 'same': same,
                  't_end': t_end is not None}


def live_formula(T, v):
    """Живая часть словами — для экспорта (бэкенд сайта); семейства Live: F1 «окно», F2 «+ n0 случайных», F3 «− k ошибок»."""
    if v.get('kind') != 'win' or v.get('prior') not in (None, 'null') or v.get('pad'):
        raise ValueError(f"🍆 АЙ, ОШИБКА! формула {v.get('key')} — не окно Live (F1 / F2 / F3): экспорт словами не описан")
    L, n0, lag, k = int(v['L']), int(v['n0'] if v.get('prior') == 'null' else 0), v['lag'], v.get('k')
    tau = LV.LIVE['f3_tau']
    if k:
        ms = (f"m = max(s1 / n − {k:g}·s·sqrt({tau} / n), 0), s² = max(s2 / n − (s1 / n)², 0) (при n = 0 — m = 0, s = 1): "
              f"центр минус {k:g} ошибки среднего (одно независимое окно на {tau})")
    elif n0:
        ms = (f"m = s1 / (n + {n0}); s² = (max(s2 − s1² / n, 0) + {n0}) / (n + {n0}) (при n = 0 — m = 0, s = 1): {n0} "
              f"виртуальных случайных окон с z ~ N(0, 1)")
    else:
        ms = "m = s1 / n; s² = max(s2 / n − (s1 / n)², 0) (при n = 0 — m = 0, s = 1): просто окно"
    return {'key': v['key'], 'family': v['fam'], 'L': L, 'n0': n0, 'k': k, 'tau': tau if k else None, 'lag': lag,
            'show_from_window': CL.full_from(v), 's_lo': T.NOCAL['s_lo'],
            'formula': ["z окна — по линейке: z = interp(logit, q, zk), за крайними узлами — край",
                        f"окно p — номер существующего окна от первого валидного окна графика (с 0; окна идут подряд, как "
                        f"есть: дыры в данных не заполняются); живая часть — z окон [lo; hi), hi = p − {lag} + 1, "
                        f"lo = max(0, hi − {L}); n = hi − lo (не меньше 0); s1 = Σ z, s2 = Σ z²",
                        ms,
                        f"m = max(m, 0); s = min(max(s, {T.NOCAL['s_lo']:g}), 1); zc = min(z, m / (1 − s²)) при s < 1, иначе z; "
                        f"log M = −(zc − m)² / (2·s²) − ln s + zc² / 2",
                        f"линия — с окна p = {CL.full_from(v)}, как в индикаторе (окно живой части полное уже с p = "
                        f"{CL.full_from(v) - 1}; число — из Live / Pine); раньше — пусто (прогрев)",
                        "у ансамбля logit окна — среднее logit боевых сидов; пол делителя окна — 0.2 у всех символов",
                        "потолок: сила на линии (M у оранжевых, 1/M у синих) показывается не выше C"]}


