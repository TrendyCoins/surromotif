    if SITE.get('formula'):
        f, src = SITE['formula'], "SITE['formula']"
    else:
        paths = sorted(glob.glob(OUT_DIR + 'site_live_*.json'))
        got = None
        if paths:
            with open(paths[-1], encoding='utf-8') as fh:
                got = json.load(fh).get('pick')
        f, src = (got, os.path.basename(paths[-1])) if got else (F_IND, 'формула А индикатора (Ceil)')
