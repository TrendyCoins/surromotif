def auc_parts_src(T, raw, E, key, assets):
    """Δ AUC VAL ансамбля к среднему одиночных по ассетам: AUC и вклады окон (у одного сида — среднее вкладов сидов)."""
    seeds = list(raw)
    per = {}
    for a in assets:
        if a not in E:
            continue
        sl = val_slice(key, E[a])
        Ae, ipe, ine = T.auc_parts(E[a]['sp'][sl], E[a]['sn'][sl])
        ps = [T.auc_parts(raw[s][a]['sp'][sl], raw[s][a]['sn'][sl]) for s in seeds]
        per[a] = {'ens': Ae, 'seeds': [p[0] for p in ps], 'single': float(np.mean([p[0] for p in ps])),
                  'ip': ipe - np.mean([p[1] for p in ps], axis=0), 'in': ine - np.mean([p[2] for p in ps], axis=0),
                  'wk': E[a]['wk'][sl]}
        per[a]['d'] = per[a]['ens'] - per[a]['single']
    return per


def auc_group(T, per, grp):
    """Среднее по ассетам группы: AUC одного сида, ансамбля, Δ и SE (вклады окон всех ассетов группы — по общим неделям)."""
    names = [a for a in grp if a in per]
    if not names:
        return None
    k = len(names)
    se = T.cluster_se([x / k for a in names for x in (per[a]['ip'], per[a]['in'])],
                      [w for a in names for w in (per[a]['wk'], per[a]['wk'])])
    return {'n': k, 'single': float(np.mean([per[a]['single'] for a in names])),
            'ens': float(np.mean([per[a]['ens'] for a in names])), 'd': float(np.mean([per[a]['d'] for a in names])),
            'se': float(se)}


def r_parts_src(T, raw, E, key, assets):
    """R = RMS(Δz) / sd(z) по соседним окнам VAL (logit модели, как line_stats волны SM): суммы по неделям у ансамбля и у
       сидов, log(R ансамбля / R одного), у одного — среднее log R сидов."""
    seeds = list(raw)
    per = {}
    for a in assets:
        if a not in E or 'st' not in E[a]:
            continue
        sl = val_slice(key, E[a])
        st, wk = E[a]['st'][sl], E[a]['wk'][sl]
        we, Ae = T._line_weeks(st, E[a]['sp'][sl], wk)
        As = [T._line_weeks(st, raw[s][a]['sp'][sl], wk)[1] for s in seeds]
        if Ae[1].sum() < 1000:                   # меньше 1000 пар соседей — R не считается (как line_stats)
            continue
        Re, Rs = float(T._R_from(Ae.sum(1))), [float(T._R_from(x.sum(1))) for x in As]
        per[a] = {'weeks': we, 'Ae': Ae, 'As': As, 'R_ens': Re, 'R_seeds': Rs,
                  'lr': float(math.log(Re) - np.mean(np.log(Rs)))}
    return per


def _r_boot(T, per, names, weeks, pick):
    """Бутстреп среднего по ассетам log(R ансамбля / R одного): выборки недель pick (индексы в weeks, общие для ассетов)."""
    G = len(weeks)
    boot = np.zeros(pick.shape[0])
    for a in names:
        idx = np.searchsorted(weeks, per[a]['weeks'])

        def blr(A):
            F = np.zeros((5, G))
            F[:, idx] = A
            with np.errstate(invalid='ignore', divide='ignore'):
                return np.log(T._R_from(F[:, pick].sum(2)))
        boot += (blr(per[a]['Ae']) - np.mean([blr(x) for x in per[a]['As']], axis=0)) / len(names)
    return boot


def _sd(x):
    x = np.asarray(x, dtype=np.float64)
    x = x[np.isfinite(x)]
    return float(np.std(x, ddof=1)) if len(x) > 2 else math.nan


def r_group(T, per, grp, B=None, seed=0):
    """Среднее по ассетам группы log(R ансамбля / R одного) и его SE: бутстреп недель, общих для ассетов (рынки синхронны)."""
    names = [a for a in grp if a in per]
    if not names:
        return None
    weeks = np.unique(np.concatenate([per[a]['weeks'] for a in names]))
    pick = np.random.default_rng(seed).integers(0, len(weeks), size=(B or SITE['boot'], len(weeks)))
    lr = float(np.mean([per[a]['lr'] for a in names]))
    return {'n': len(names), 'lr': lr, 'ratio': math.exp(lr), 'se': _sd(_r_boot(T, per, names, weeks, pick)),
            'R_single': float(np.exp(np.mean([np.mean(np.log(per[a]['R_seeds'])) for a in names]))),
            'R_ens': float(np.exp(np.mean([np.log(per[a]['R_ens']) for a in names])))}


def u_group(T, pa, pr, grp, B=None, seed=1):
    """u группы и его SE общим бутстрепом недель: Δ AUC* = Δ + сумма недельных вкладов окон (Хайек) по выборке недель, log R*
       — по недельным суммам (как r_group), с одними и теми же выборками недель: связь ошибок Δ AUC и R учтена."""
    na, nr = [a for a in grp if a in pa], [a for a in grp if a in pr]
    if not na or not nr:
        return (math.nan, math.nan)
    ag, rg = auc_group(T, pa, grp), r_group(T, pr, grp)
    weeks = np.unique(np.concatenate([pa[a]['wk'] for a in na] + [pr[a]['weeks'] for a in nr]))
    G = len(weeks)
    pick = np.random.default_rng(seed).integers(0, G, size=(B or SITE['boot'], G))
    s = np.zeros(G)
    for a in na:
        iw = np.searchsorted(weeks, pa[a]['wk'])
        s += (np.bincount(iw, weights=pa[a]['ip'], minlength=G) + np.bincount(iw, weights=pa[a]['in'], minlength=G)) / len(na)
    d_b = ag['d'] + s[pick].sum(1)
    lr_b = _r_boot(T, pr, nr, weeks, pick)
    u, _ = u_score(ag['d'], 0.0, rg['lr'], 0.0)
    with np.errstate(over='ignore', invalid='ignore'):
        u_b = d_b / SITE['u_auc'] + (1.0 - np.exp(lr_b)) / SITE['u_r']
    return (u, _sd(u_b))


def u_score(d_auc, se_auc, lr, se_lr):
    """Выигрыш в шагах волны: u = Δ AUC / u_auc + (1 − R ансамбля / R одного) / u_r и SE, будто ошибки независимы (справочно и
       для стенда; в правиле SE у u — общим бутстрепом, u_group)."""
    ratio = math.exp(lr)
    u = d_auc / SITE['u_auc'] + (1.0 - ratio) / SITE['u_r']
    se = math.sqrt((se_auc / SITE['u_auc']) ** 2 + (ratio * se_lr / SITE['u_r']) ** 2)
    return float(u), float(se)


@contextlib.contextmanager
def evidence(T, raw_c):
    """Порог «мало данных» по числу рядов конфигурации (правило (А), равный объём данных): у одного сида два ряда на ассет
       (сиды a и b на одних окнах) — порог Live / Ceil как есть (1000 окон пары рядов ≈ 500 разных окон); у ансамбля ряд один —
       порог вдвое ниже (те же ~500 разных окон). Меняет NOCAL['min_n'] (ворота (а) / (б)) и CEIL['min_n'] ((Ц)) на время блока."""
    k = len(raw_c) / len(SITE['seeds'])
    keep_n, keep_c = T.NOCAL['min_n'], CL.CEIL.get('min_n')
    base_c = CL.min_n()
    T.NOCAL['min_n'] = int(round(keep_n * k))
    CL.CEIL['min_n'] = int(round(base_c * k))
    try:
        yield T.NOCAL['min_n']
    finally:
        T.NOCAL['min_n'] = keep_n
        if keep_c is None:
            CL.CEIL.pop('min_n', None)
        else:
            CL.CEIL['min_n'] = keep_c


def line_eval(T, key, raw_c, v):
    """Формула А на полном окне — как часть A 'run' Live (разгон — TUNE / П1, оценка — VAL / П2) — и ворота Live; порог «мало
       данных» — по числу рядов конфигурации (evidence)."""
    src = BB.build_source(T, key, raw_c, BB.BELL['sources'][key]['about'])
    with evidence(T, raw_c) as mn:
        res = CL.eval_a(T, src, v)
        res['gates'] = LV.gates(T, res)
    res['min_n'] = mn
    return res


