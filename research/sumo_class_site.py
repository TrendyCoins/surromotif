def live_part(T, raw_b):
    """(Ж): часть A Live на обоих источниках (один сид), выбор по основному, подтверждение. Возвращает итог для json."""
    VA = {v['key']: v for v in LV.variants_a()}
    cands = [k for k, v in VA.items() if v['cand']]
    res = {}
    for key in (CL.CEIL['main'], CL.CEIL['confirm']):
        raw_c = cfg_raw(raw_b[key], 'single')
        src = BB.build_source(T, key, raw_c, BB.BELL['sources'][key]['about'])
        recs = LV.prep_source(T, src)
        w0, NW = LV.week_span(recs)
        with evidence(T, raw_c):
            ch, r, _ = LV.part_a(T, recs, w0, NW, f"{key}, {SITE['model']}, один сид", check=None)
        res[key] = (ch, r)
    (chA, resA), (chC, resC) = res[CL.CEIL['main']], res[CL.CEIL['confirm']]
    conf = LV.confirm(T, resC, cands, chA['pick']) if chA['pick'] else None
    ok = bool(chA['pick'] and conf and conf['ok'])
    print(f"\n{'=' * 110}\n🏁 (Ж) ФОРМУЛА ЖИВОЙ ЧАСТИ ДЛЯ САЙТА (правило части A Live, записано до прогона)\n{'=' * 110}")
