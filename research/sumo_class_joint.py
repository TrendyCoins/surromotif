def joint_forward(trunk, head_v, X, S, n_real):
    """Оба выхода за один проход ствола: logit MRI у всех окон и v у первых n_real (реальных). Порядок операций — как в forward
       F1 (окно, его голова, зеркало, его голова): у головы MRI те же маски dropout, что у F1; голова V считается после."""
    xm, sm = smc.mirror_inputs(X, S, trunk.n_level, trunk.lvl_signed)
    f = trunk._feats(X, S)
    a = trunk.head(f).squeeze(1)
    fm = trunk._feats(xm, sm)
    b = trunk.head(fm).squeeze(1)
    v = 0.5 * (head_v(f[:n_real]).squeeze(1) + head_v(fm[:n_real]).squeeze(1))
    return 0.5 * (a + b), v


@torch.no_grad()
def vol_score(trunk, head_v, X, S, bs=65536):
    """Выход головы V (стандартизованный таргет) без dropout; режимы ствола и головы потом — как были."""
    was = (trunk.training, head_v.training)
    trunk.eval()
    head_v.eval()
    out = []
    for i in range(0, len(X), bs):
        x, s = X[i:i + bs], (None if S is None else S[i:i + bs])
        xm, sm = smc.mirror_inputs(x, s, trunk.n_level, trunk.lvl_signed)
        f, fm = trunk._feats(x, s), trunk._feats(xm, sm)
        out.append((0.5 * (head_v(f).squeeze(1) + head_v(fm).squeeze(1))).float().cpu())
    trunk.train(was[0])
    head_v.train(was[1])
    return torch.cat(out).numpy().astype(np.float64) if out else np.zeros(0)


def make_head_v(trunk, cfg):
    """Голова V — такой же MLP, как голова MRI; стартует со своего сида, глобальный генератор случайных чисел не меняется."""
