        r_one = smc.run_one(MODEL, {'L': L}, 'a', pred._DATAS, pred._STORES, 'stand')
        ctx = pred.btc_context()
        r_vs = {key: pred.run_pred(ctx, TARGET, 'a', mname=MODEL, over={**vs['over'], **STAND['v_over'][key]},
                                   recipe=vs['recipe'], sub=vs['sub']) for key, vs in VSEPS.items()}
        r_v, r_v1 = r_vs['vsep'], r_vs['vsep1']
        lam_s = float(smc.make_cfg(MODEL, {'L': L}, 'a').get('smooth_lam') or 0.0)
        check(f"эталоны: {r_one['tag']} (AUC TUNE {r_one['tune']['auc']:.4f}); "
              + "; ".join(f"{r_['tag']} (рецепт {r_['recipe'] or 'этапа 1'}, проверка каждые 1/{r_['sub']} эпохи, R² TUNE "
                          f"{r_['summary']['tune']['panel']['r2_cnn']:.3f})" for r_ in r_vs.values())
              + f"; штраф скачков сети λ_s = {lam_s:g}",
              r_one['tag'] == f"{MODEL}_L{L}_K{smc.SMC_BASE['K']}_a" and lam_s > 0
              and all(r_vs[k]['tag'] == vsep_tag('a', k) and r_vs[k]['recipe'] == VSEPS[k]['recipe']
                      and r_vs[k]['sub'] == VSEPS[k]['sub'] for k in VSEPS) and r_v['tag'] != r_v1['tag'])

        print("\n2) регрессия: λ = 0 со штрафом скачков — цикл обучения бит в бит run_one; голова заново на этом стволе (J0 на BTC)")
        r0 = run_joint(ctx, 'a', 'l0', refit_over=ro)
        x0 = _arr(r0)
        with np.load(smc.RUN_DIR + f"smc_{r_one['tag']}.npz") as z:
            sd_one = {k[3:]: z[k] for k in z.files if k.startswith('sd_')}
            one = {k: z[k] for k in z.files if not k.startswith('sd_')}
        with np.load(_paths(r0['tag'])[1]) as z:
            sd_0 = {k[len('sd_A__trunk.'):]: z[k] for k in z.files if k.startswith('sd_A__trunk.')}
        same_w = sorted(sd_one) == sorted(sd_0) and all(np.array_equal(sd_one[k], sd_0[k]) for k in sd_one)
        same_s = all(np.array_equal(x0[f"A__mri__{p}__{q}"], one[f"{p}_{q}"]) for p in ('tune', 'val') for q in ('sp', 'sn'))
        has_s = all('smooth' in h['loss'] and 'vol' not in h['loss'] for h in r0['hist'])
        same_h = len(r0['hist']) == len(r_one['hist']) and all(
            x['loss'] == y['loss'] and x['tune_auc'] == y['tune']['auc'] and x['lr'] == y['lr']
            for x, y in zip(r0['hist'], r_one['hist']))
        check(f"λ = 0: лучшая эпоха {r0['best_a']['ep']} (run_one {r_one['best_ep']}), эпох {r0['epochs_run']} ({r_one['epochs_run']}), "
              f"AUC TUNE {r0['eval']['A']['mri_tune']['auc']:.6f} ({r_one['tune']['auc']:.6f}); каждая эпоха (лоссы, AUC TUNE, lr) "
              f"— бит в бит: {same_h}; веса ствола и logit TUNE / VAL лучшей эпохи — бит в бит: {same_w and same_s}; штраф скачков в "
              f"лоссе каждой эпохи, волы нет: {has_s}",
              r0['best_a']['ep'] == r_one['best_ep'] and r0['epochs_run'] == r_one['epochs_run'] and same_w and same_s
              and same_h and r0['eval']['A']['mri_tune']['auc'] == r_one['tune']['auc'] and has_s)
        rf0 = pred.load_runs().get(r0['refit'])
        t0_, _ = trunk_of(r0, 'A')
        with np.load(pred.pred_dir() + f"{r0['refit']}.npz") as z:
            sd_rf0 = {k[len('sd_trunk.'):]: z[k] for k in z.files if k.startswith('sd_trunk.')}
        check(f"J0 на BTC: голова заново на стволе λ = 0 — ствол бит в бит (sha), рецепт {rf0['recipe']}, R² VAL "
              f"{rf0['summary']['val']['panel']['r2_cnn']:.3f}; точки V и проб градиентов у λ = 0 нет",
              rf0['joint']['of'] == r0['tag'] and rf0['recipe'] == refit_recipe('l0') and _refit_of(r0, rf0)
              and vol.trunk_sha(sd_rf0) == vol.trunk_sha(vol.sd_numpy(t0_)) and 'V' not in r0['eval']
              and r0['diag_init'] is None and all('g' not in h for h in r0['hist']))

        print("\n3) диагностика градиентов пассивна: λ = 1 без неё и с ней — обучение бит в бит")
        cfg1 = smc.make_cfg(MODEL, {'L': L}, 'a')
        with smc.orientation(cfg1.get('orient', True)):
            r_nd = _train(ctx, cfg1, 'a', 'l1', diag=False)
        h_nd = r_nd['hist']
        for p_ in _paths(r_nd['tag']):
            os.remove(p_)
        _ARR.pop(r_nd['tag'], None)
        r1 = run_joint(ctx, 'a', 'l1', refit_over=ro)
        gs = [r1['diag_init']] + [h.get('g') for h in r1['hist']]
        fin = all(g is not None and np.all(np.isfinite([g['mri_b'], g['vol_b'], g['share_b']])) and g['share_b'] > 0
                  and ((np.isfinite(g['share']) and g['share'] > 0 and abs(g['cos']) <= 1) or g['below']['mri']
                       or g['below']['vol']) for g in gs)
        n_below = sum(1 for g in gs if g and g['below']['mri'])
        check(f"λ = 1: история эпох без диагностики и с ней — бит в бит: {_same_rows(h_nd, r1['hist'])}; на старте и после каждой "
              f"из {len(r1['hist'])} эпох доля по батчам конечна, а доля и косинус сигнала — конечны или помечены «ниже шума»: {fin} "
              f"(сигнал BCE ниже шума — {n_below} из {len(gs)}: на синтетике MRI учить нечему)",
              _same_rows(h_nd, r1['hist']) and fin and all('g' not in h for h in h_nd) and r_nd['diag_init'] is None)

        print("\n4) переключение (на стенде — после первой эпохи без роста R² TUNE волы на 1e9, то есть на эпохе 1)")
