def shared_params(trunk):
    """Общие веса двух голов — свёртки ствола (blocks.*); боковые входы — буферы, головы у каждого таргета свои."""
    return [p for n_, p in trunk.named_parameters() if n_.startswith('blocks.') and p.requires_grad]


def grad_probe(data, fit_st, fit_sid, v_ok, yz_t, cfg, thr, half, side):
    """Фиксированная проба для градиентов: GP_BATCHES батчей по half реальных окон обучения с таргетом волы и их суррогатов
       sflip4 (как в шаге обучения). Свой генератор окон и знаков суррогатов — обучение их не видит."""
    g = torch.Generator(device=DEVICE)
    g.manual_seed(int(cfg['seed']) + GP_SEED_SHIFT)
    pm_g = smc.PairMaker(data, L, cfg, thr, g)
    cand = np.where(v_ok)[0]
    idx = np.random.default_rng(int(cfg['seed']) + GP_SEED_SHIFT).choice(cand, size=min(GP_BATCHES * half, len(cand)),
                                                                          replace=False)
    out = []
    for part in np.array_split(idx, GP_BATCHES):
        if len(part) == 0:
            continue
        j = torch.from_numpy(np.sort(part)).to(DEVICE)
        Wp, Wn, fl = pm_g.make(fit_st[j], fit_sid[j])
        X = torch.cat([smc.to_shapes(Wp, fl), smc.to_shapes(Wn, fl)])
        S = (torch.cat([smc.side_feats(data, fit_st[j], L, Wp, fl), smc.side_feats(data, fit_st[j], L, Wn, fl)])
             if side else None)
        y = torch.cat([torch.ones(len(Wp), device=DEVICE), torch.zeros(len(Wn), device=DEVICE)])
        out.append({'X': X, 'S': S, 'y': y, 'yz': yz_t[j], 'n': int(len(Wp))})
    return out


def _flat(gs, params):
    """Градиенты по списку весов — одним вектором float64 (вес без градиента — нули)."""
    return torch.cat([(p.new_zeros(p.shape) if g_ is None else g_).reshape(-1).double() for g_, p in zip(gs, params)])


def grad_diag(trunk, head_v, gp, lam, cfg, st, tau):
    """Градиенты BCE (MRI) и λ · MSE (вола) по общим весам (свёрткам) на батчах пробы gp, без dropout.
         share, cos — сигнал: ‖E g_V‖ / ‖E g_MRI‖ и косинус между E g_MRI и E g_V — куда тянет каждый таргет. Оценка без шума
                      батча: скалярные произведения градиентов РАЗНЫХ батчей (шум у них независимый, в среднем даёт 0), то есть
                      ‖E g‖² ≈ среднее ⟨g_i, g_j⟩ по парам i ≠ j. Если оценка квадрата ≤ 0, сигнал ниже шума пробы: share и cos —
                      NaN, флаг below. Косинус < 0 — таргеты тянут общие веса в разные стороны.
         share_b    — средняя по батчам ‖g_V‖ / средняя ‖g_MRI‖: как градиенты видит Adam на шаге, вместе с шумом батча (батч пробы
                      — как шаг обучения). Если она много больше 1, знаменатель Adam у свёрток — в основном вола, и шаг MRI сжат.
       Обучение не трогает: генераторы случайных чисел не используются, .grad весов — как были (torch.autograd.grad не копит в
       .grad). Штраф скачков сюда не входит (у обученной сети он мал)."""
    shared = shared_params(trunk)
    was = (trunk.training, head_v.training)
    trunk.eval()
    head_v.eval()
    gm, gv = [], []
    for b in gp:
        logit, v = joint_forward(trunk, head_v, b['X'], b['S'], b['n'])
        l_m = smc.loss_terms(trunk, logit, b['y'], None, cfg, st, tau, 1.0)['bce']
        l_v = lam * ((v - b['yz']) ** 2).mean()
        gm.append(_flat(torch.autograd.grad(l_m, shared, retain_graph=True, allow_unused=True), shared))
        gv.append(_flat(torch.autograd.grad(l_v, shared, allow_unused=True), shared))
    trunk.train(was[0])
    head_v.train(was[1])
    Gm, Gv = torch.stack(gm), torch.stack(gv)
    bm, bv = float(Gm.norm(dim=1).mean()), float(Gv.norm(dim=1).mean())
    out = {'mri_b': bm, 'vol_b': bv, 'share_b': bv / bm if bm > 0 else float('nan'),
           'mri': float('nan'), 'vol': float('nan'), 'share': float('nan'), 'cos': float('nan'),
           'below': {'mri': True, 'vol': True}}
    k = len(gp)
    if k >= 2:
        off = ~torch.eye(k, dtype=torch.bool, device=Gm.device)
        mm, vv, mv = float((Gm @ Gm.T)[off].mean()), float((Gv @ Gv.T)[off].mean()), float((Gm @ Gv.T)[off].mean())
        out['below'] = {'mri': mm <= 0, 'vol': vv <= 0}
        out['mri'], out['vol'] = math.sqrt(max(mm, 0.0)), math.sqrt(max(vv, 0.0))
        if mm > 0 and vv > 0:
            out['share'] = math.sqrt(vv / mm)
            out['cos'] = max(-1.0, min(1.0, mv / math.sqrt(mm * vv)))
    return out


def _gtxt(g):
    """Градиенты эпохи для строки лога."""
    sig = ("сигнал BCE ниже шума пробы" if g['below']['mri'] else "сигнал волы ниже шума пробы" if g['below']['vol']
           else f"доля V {g['share']:.2f}, cos {g['cos']:+.2f}")
    return f"{sig}; доля по батчам {g['share_b']:.2f}"


def reset_adam(opt, params):
    """Состояние AdamW у params — заново (моменты и счётчик шагов: torch заводит их при следующем шаге); сколько сброшено."""
    n = 0
    for p in params:
        if p in opt.state:
            del opt.state[p]
            n += 1
    return n


