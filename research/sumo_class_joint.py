def run_joint(ctx, seed, name, refit_over=None, diag=None):
    """Один прогон варианта name: ствол сети сайта и две головы на одном BTC. Итог — json / npz в joint_dir() и голова V заново
       на стволе точки A (формат SuMo_Pred_Train)."""
    cfg = smc.make_cfg(MODEL, {'L': L}, seed)
    with smc.orientation(cfg.get('orient', True)):
        r = _train(ctx, cfg, seed, name, GRAD_DIAG if diag is None else diag)
    refit(ctx, r, refit_over)
    return r


def _train(ctx, cfg, seed, name, diag=True):
    t_run = time.time()
    var = VARIANTS[name]
    lam, use_sw = float(var['lam']), bool(var['switch'])
    if (cfg['arch'] != 'cnn' or not cfg.get('cnn_sym') or cfg.get('cnn_anti') or cfg['aug_mag'] or cfg['ema']
            or cfg.get('fit_halflife') or cfg.get('mir_aug') or cfg['control'] or cfg.get('fit_holdout')
            or cfg.get('fit_plus_tune') or cfg['stop_on'] != 'auc' or cfg['warmup_epochs']):
        raise ValueError("🍆 АЙ, ОШИБКА! совместное обучение — только симметричная CNN без aug, ema, веса свежести, контроля, "
                         "отложенных блоков и TUNE в обучении; остановка — по AUC TUNE")
    if use_sw and lam <= 0:
        raise ValueError(f"🍆 АЙ, ОШИБКА! вариант {name}: переключение — только при λ > 0")
    tag = joint_tag(name, seed)
    data = ctx['data']
    a = ctx['assets'][0]
    store = ctx['stores'][a]
    smc.check_absv(cfg, data)
    torch.manual_seed(cfg['seed'])
    rng = np.random.default_rng(cfg['seed'])
    gen = torch.Generator(device=DEVICE)
    gen.manual_seed(cfg['seed'])
    print(f"\n\n{'#' * 78}\n# SuMo_Class_Joint v{JOINT_VER} | {tag} | {vname(name)} | {DEVICE}\n# {smc.cfg_line(cfg)}\n{'#' * 78}")
    w = store.w
    spec = smc.primary_spec(cfg)
    ev_tune = store.get('tune', spec)
    ev_fitp = store.get('fitprobe', spec)
    # ---- окна обучения и обрезка хвоста размаха — как у run_one
    fit = smc.fit_windows(w, cfg)
    fl_fit = w['floor_t'][torch.from_numpy(w['sid'][fit]).to(DEVICE)]
    tv = torch.cat([smc.tv_ratio(smc.gather(data.r_t, torch.from_numpy(w['st'][fit[i:i + 262144]]).to(DEVICE), L),
                                 fl_fit[i:i + 262144]) for i in range(0, len(fit), 262144)])
    thr = float(torch.quantile(tv[torch.randperm(len(tv), device=DEVICE)[:1000000]],
                               1 - cfg['trim_q'] / 100.0)) if cfg['trim_q'] else float('inf')
    keep = (tv <= thr).cpu().numpy()
    st_np = w['st'][fit][keep]
    fit_st = torch.from_numpy(st_np).to(DEVICE)
    fit_sid = torch.from_numpy(w['sid'][fit][keep]).to(DEVICE)
    del tv, fl_fit
    # ---- таргет волы у окон обучения: годный и вне эмбарго у TUNE (как в SuMo_Pred_Train)
    A = pred.pred_arrays(data, TARGET)
    pos = st_np + L - 1
    has_y = np.isfinite(A['y'][pos])
    late = has_y & (A['tlast'][pos] >= data.tune_ns)
    v_ok = has_y & ~late
    y_fit = A['y'][pos[v_ok]].astype(np.float64)
    mu, sd = float(y_fit.mean()), float(y_fit.std())
    yz = np.zeros(len(pos), np.float32)
    yz[v_ok] = ((y_fit - mu) / sd).astype(np.float32)
    yz_t, ok_t = torch.from_numpy(yz).to(DEVICE), torch.from_numpy(v_ok.astype(np.float32)).to(DEVICE)
    print(f"📦 окон обучения {len(st_np)} (обрезано {100 * (1 - keep.mean()):.2f}% по размаху > {thr:.1f}); с таргетом волы "
          f"{int(v_ok.sum())} (без таргета {int((~has_y).sum())}, эмбарго у TUNE {int(late.sum())}); таргет: среднее "
          f"{mu:+.4f}, sd {sd:.4f}")
    # ---- модель (масштабы входов — по пробе окон обучения, как у run_one)
    pick = torch.from_numpy(rng.choice(len(fit_st), size=min(150000, len(fit_st)), replace=False)).to(DEVICE)
    W_s, fl_s = data.gw(fit_st[pick], L), w['floor_t'][fit_sid[pick]]
    Xs = smc.to_shapes(W_s, fl_s)
    Ss = smc.side_feats(data, fit_st[pick], L, W_s, fl_s)
    del W_s
    trunk, st = smc.build_model(cfg, Xs, rng, Ss)
    del Xs, Ss
    head_v = make_head_v(trunk, cfg)
    side = smc.uses_side(trunk)
    params = [p for n_, p in trunk.named_parameters() if p.requires_grad and n_ not in ('protos', 'log_T')]
    opt = torch.optim.AdamW([{'params': params + list(head_v.parameters()), 'lr': cfg['lr'], 'weight_decay': cfg['wd']}])
    for g_ in opt.param_groups:
        g_['lr0'] = g_['lr']
    half = cfg['batch'] // 2
    steps = cfg['steps'] or max(1, len(fit_st) // half)
    min_ep = cfg['min_epochs'] if cfg['min_epochs'] is not None else 3
    pm = smc.PairMaker(data, L, cfg, thr, gen)
    lam_s = float(cfg.get('smooth_lam') or 0.0)
    nxt_ok, n_pen = None, 0
    if lam_s > 0:                                # штраф скачков соседних окон — как у run_one
        nxt_ok = torch.from_numpy(smc.next_in_set(fit_st.cpu().numpy())).to(DEVICE)
        n_pen = max(8, int(round(cfg['smooth_frac'] * half)))
    print(f"🧠 ствол {type(trunk).__name__}: весов {vol.n_weights(trunk)}; голова V {vol.n_weights(head_v)} | эпоха = {steps} шагов "
          f"по {cfg['batch']} окон | лосс BCE"
          + (f" + штраф скачков λ_s {lam_s:g} на {n_pen} парах шага (разгон {cfg.get('smooth_warm')} эп.)" if lam_s > 0 else "")
          + f" + {lam:g} · MSE волы"
          + (f" | переключение: λ = 0 после {SWITCH['patience']} эп. без роста R² TUNE волы"
             + (f" больше чем на {SWITCH['delta']:g}" if SWITCH['delta'] else "") if use_sw else "")
          + f" | остановка и lr — по AUC TUNE (терпение {cfg['patience']}, lr ×{cfg['lr_factor']:g} после {cfg['lr_plateau']} эпох "
          f"без роста); ★ — лучшая AUC TUNE (точка A), ☆ — лучший R² TUNE волы (точка V)")
    # ---- проверка волы по эпохам (окна TUNE с таргетом — те же, что у эталона V; проба окон обучения) и проба градиентов
    ev_vt = probe = gp = diag_init = None
    if lam > 0:
        ev_vt = pred.eval_windows(ctx, A, a, 'tune')
        pr = np.sort(rng.choice(np.where(v_ok)[0], size=min(pred.FIT_PROBE, int(v_ok.sum())), replace=False))
        st_pr = fit_st[torch.from_numpy(pr).to(DEVICE)]
        W_pr, fl_pr = data.gw(st_pr, L), w['floor_t'][fit_sid[torch.from_numpy(pr).to(DEVICE)]]
        probe = {'X': smc.to_shapes(W_pr, fl_pr), 'S': smc.side_feats(data, st_pr, L, W_pr, fl_pr),
                 'y': A['y'][pos[pr]].astype(np.float64)}
        del W_pr
        if diag:
            gp = grad_probe(data, fit_st, fit_sid, v_ok, yz_t, cfg, thr, half, side)
            diag_init = grad_diag(trunk, head_v, gp, lam, cfg, st, smc.tau_at(0, cfg, st['gap0']))
            print(f"🧭 градиенты в свёртки на старте ({len(gp)} батчей пробы по {gp[0]['n']} реальных окон и их суррогатов, без "
                  f"dropout): {_gtxt(diag_init)}")
    hist, bad, epochs_run, stop_note = [], 0, 0, ''
    best_a = {'auc': -float('inf'), 'ep': -1, 'r2': float('nan'), 'state': None}
    best_v = {'r2': -float('inf'), 'ep': -1, 'auc': float('nan'), 'state': None}
    lam_eff, sw_ep, sw_best, bad_v, sha_sw, n_reset = lam, None, -float('inf'), 0, None, 0
    for ep in range(cfg['epochs']):
        t_ep = time.time()
        tau = smc.tau_at(ep, cfg, st['gap0'])
        lam_ep = lam_eff                         # вес волы этой эпохи (после переключения — 0)
        w_s = lam_s * min(1.0, (ep + 1) / max(1, int(cfg.get('smooth_warm') or 1))) if lam_s > 0 else 0.0
        perm = torch.randperm(len(fit_st), generator=gen, device=DEVICE)
        acc = {}
        for s in range(steps):
            j = perm[(s * half) % len(perm):(s * half) % len(perm) + half]
            Wp, Wn, fl = pm.make(fit_st[j], fit_sid[j])
            X = torch.cat([smc.to_shapes(Wp, fl), smc.to_shapes(Wn, fl)])
            y = torch.cat([torch.ones(len(Wp), device=DEVICE), torch.zeros(len(Wn), device=DEVICE)])
            S = (torch.cat([smc.side_feats(data, fit_st[j], L, Wp, fl), smc.side_feats(data, fit_st[j], L, Wn, fl)])
                 if side else None)
            if lam_ep > 0:
                logit, v = joint_forward(trunk, head_v, X, S, len(Wp))
            else:                                # λ = 0 — ровно шаг run_one (голова V не считается)
                logit = smc.fwd(trunk, X, S)[0]
            terms = smc.loss_terms(trunk, logit, y, None, cfg, st, tau, 1.0)
            if lam_s > 0:                        # штраф скачков между соседними реальными окнами — как у run_one
                jj = j[nxt_ok[j]][:n_pen]
                if len(jj) >= 8:
                    terms['smooth'] = smc.smooth_penalty(trunk, data, L, fit_st[jj], fit_sid[jj], w['floor_t'], cfg, w_s)
            if lam_ep > 0:
                m = ok_t[j]
                terms['vol'] = lam_ep * ((v - yz_t[j]) ** 2 * m).sum() / m.sum().clamp_min(1.0)
            total = sum(terms.values())
            opt.zero_grad(set_to_none=True)
            total.backward()
            opt.step()
            for k_, v_ in terms.items():
                acc[k_] = acc.get(k_, 0.0) + v_.detach()
        epochs_run = ep + 1
        loss = {k_: float(v_) / steps for k_, v_ in acc.items()}
        r_t, _, _ = smc.eval_set(trunk, ev_tune)
        r_f, _, _ = smc.eval_set(trunk, ev_fitp)
        r2_t = r2_f = float('nan')
        if lam > 0:
            r2_t = pred.r2(ev_vt['y'], mu + sd * vol_score(trunk, head_v, ev_vt['X'], ev_vt['S']))
            r2_f = pred.r2(probe['y'], mu + sd * vol_score(trunk, head_v, probe['X'], probe['S']))
        g_ep = grad_diag(trunk, head_v, gp, lam, cfg, st, tau) if (gp and lam_ep > 0) else None
        improved = r_t['auc'] > best_a['auc'] + cfg['stop_delta']
        if improved:
            best_a = {'auc': r_t['auc'], 'ep': ep, 'r2': r2_t, 'state': _snap(trunk, head_v)}
            bad = 0
        else:
            bad += 1
        lr_note = ""
        if cfg['lr_plateau'] and not improved and bad % cfg['lr_plateau'] == 0:
            for g_ in opt.param_groups:
                g_['lr'] = max(g_['lr'] * cfg['lr_factor'], g_['lr0'] * cfg['lr_min_frac'])
            lr_note = f" | lr -> {opt.param_groups[0]['lr']:.1e}"
        v_imp = lam > 0 and r2_t > best_v['r2']
        if v_imp:
            best_v = {'r2': r2_t, 'ep': ep, 'auc': r_t['auc'], 'state': _snap(trunk, head_v)}
        sw_note = ""
        if use_sw and lam_eff > 0:              # переключение: R² TUNE волы не растёт SWITCH['patience'] эпох — дальше λ = 0
            if r2_t > sw_best + SWITCH['delta']:
                sw_best, bad_v = r2_t, 0
            else:
                bad_v += 1
            if bad_v >= SWITCH['patience']:
                lam_eff, sw_ep = 0.0, ep
                sha_sw = vol.trunk_sha(vol.sd_numpy(head_v))
                n_reset = reset_adam(opt, shared_params(trunk))   # знаменатель Adam у свёрток помнил градиент волы
                sw_note = (f" | 🔀 дальше λ = 0 (R² TUNE волы не растёт {bad_v} эп.); память Adam у свёрток ({n_reset} тензоров) "
                           f"— заново")
        row = {'ep': ep, 'sec': time.time() - t_ep, 'loss': loss, 'lam': lam_ep, 'tune_auc': r_t['auc'],
               'tune_auc_se': r_t['auc_se'], 'fit_auc': r_f['auc'], 'tune_r2': r2_t, 'fit_r2': r2_f,
               'lr': opt.param_groups[0]['lr']}
        if g_ep is not None:
            row['g'] = g_ep
        hist.append(row)
        print(f"эп {ep:>3} | {row['sec']:5.1f}c | loss " + " + ".join(f"{k_} {v_:.4f}" for k_, v_ in loss.items())
              + f" | FIT auc {r_f['auc']:.4f}" + (f" R² {r2_f:+.4f}" if lam > 0 else "")
              + f" | TUNE auc {r_t['auc']:.4f}±{r_t['auc_se']:.4f}" + (f" R² {r2_t:+.4f}" if lam > 0 else "")
              + (f" | {_gtxt(g_ep)}" if g_ep is not None else "")
              + lr_note + sw_note + (" ★" if improved else "") + (" ☆" if v_imp else ""))
        if ep + 1 >= min_ep and bad >= cfg['patience']:
            stop_note = f"ранняя остановка на эпохе {ep}"
            break
    sha_end = vol.trunk_sha(vol.sd_numpy(head_v))
    p0 = shared_params(trunk)[0]
    adam_steps = float(opt.state[p0]['step']) if p0 in opt.state and 'step' in opt.state[p0] else 0.0
    print(f"⏹️ {stop_note or 'все эпохи пройдены'} | точка A — эпоха {best_a['ep']} (AUC TUNE {best_a['auc']:.4f}"
          + (f", R² TUNE {best_a['r2']:+.4f}" if lam > 0 else "") + ")"
          + (f" | точка V — эпоха {best_v['ep']} (R² TUNE {best_v['r2']:+.4f}, AUC TUNE {best_v['auc']:.4f})" if lam > 0 else "")
          + ((f" | переключение после эпохи {sw_ep}" if sw_ep is not None else " | переключения не было") if use_sw else "")
          + f" | {(time.time() - t_run) / 60:.1f} мин")
    del ev_vt, probe, perm, gp
    # ---- итог по точкам: logit MRI на наборах TUNE / VAL (как у run_one) и прогноз волы на окнах TUNE / VAL с таргетом
    arrs, ev_res = {}, {}
    cks = {'A': best_a, **({'V': best_v} if lam > 0 and best_v['state'] is not None else {})}
    for ck, b in cks.items():
        trunk.load_state_dict(b['state']['trunk'])
        head_v.load_state_dict(b['state']['head_v'])
        res = {'ep': b['ep']}
        sps = {}
        for part in ('tune', 'val'):
            ev = store.get(part, spec)
            r_, sp, sn = smc.eval_set(trunk, ev)
            sps[part] = (sp, sn, ev)
            res[f'mri_{part}'] = r_
            k_ = f"{ck}__mri__{part}__"
            arrs.update({k_ + 'sp': sp.astype(np.float32), k_ + 'sn': sn.astype(np.float32), k_ + 'wp': np.asarray(ev['wp']),
                         k_ + 'wn': np.asarray(ev['wn']), k_ + 'st': np.asarray(ev['st'], dtype=np.int64)})
        ab = smc.platt_fit(sps['tune'][0], sps['tune'][1])
        ev_v = sps['val'][2]
        info = smc.line_info(data, ev_v['st'], L, store.positives('val')['fl'])
        store._pos.pop('val', None)
        res['mri_line_val'] = smc.line_stats(ev_v['st'], sps['val'][0], info, ab)
        if lam > 0:
            for part in ('tune', 'val'):
                e_ = pred.eval_windows(ctx, A, a, part)
                vp = mu + sd * vol_score(trunk, head_v, e_['X'], e_['S'])
                k_ = f"{ck}__vol__{part}__"
                arrs.update({k_ + 'y': e_['y'].astype(np.float32), k_ + 'cnn': vp.astype(np.float32),
                             k_ + 'wk': e_['wk'].astype(np.int32), k_ + 'st': e_['st'].astype(np.int64)})
                res[f'vol_{part}_r2'] = pred.r2(e_['y'], vp)
                del e_
            x_ = {f"{a}__val__st": arrs[f"{ck}__vol__val__st"], f"{a}__val__cnn": arrs[f"{ck}__vol__val__cnn"]}
            res['vol_line_val'] = pred.line_R(x_, a, 'val', 'cnn')
        for k_, v_ in b['state']['trunk'].items():
            arrs[f"sd_{ck}__trunk.{k_}"] = v_.numpy()
        for k_, v_ in b['state']['head_v'].items():
            arrs[f"sd_{ck}__head_v.{k_}"] = v_.numpy()
        ev_res[ck] = res
        print(f"🎯 точка {ck} (эпоха {b['ep']}): MRI AUC TUNE {res['mri_tune']['auc']:.4f}, VAL {res['mri_val']['auc']:.4f}±"
              f"{res['mri_val']['auc_se']:.4f}, R линии VAL {res['mri_line_val'].get('R', float('nan')):.3f}"
              + (f" | вола R² TUNE {res['vol_tune_r2']:.4f}, VAL {res['vol_val_r2']:.4f}, R линии VAL "
                 f"{res['vol_line_val']:.3f}" if lam > 0 else ""))
    os.makedirs(joint_dir(), exist_ok=True)
    np.savez_compressed(_paths(tag)[1], **arrs)
    r = {'ver': JOINT_VER, 'tag': tag, 'model': MODEL, 'target': TARGET, 'variant': name, 'lam': lam, 'switch': use_sw,
         'switch_rule': dict(SWITCH) if use_sw else None, 'switch_ep': sw_ep, 'seed_key': seed, 'asset': a,
         'cfg': {k: v for k, v in cfg.items() if k != 'dict'}, 'mu': mu, 'sd': sd, 'thr': thr, 'n_fit': int(len(st_np)),
         'n_vol': int(v_ok.sum()), 'n_late': int(late.sum()), 'steps_per_epoch': steps, 'epochs_run': epochs_run,
         'stop': stop_note, 'best_a': {k: v for k, v in best_a.items() if k != 'state'},
         'best_v': {k: v for k, v in best_v.items() if k != 'state'}, 'hist': hist, 'eval': ev_res, 'refit': None,
         'diag_init': diag_init, 'head_v_sha': {'switch': sha_sw, 'end': sha_end},
         'adam': {'reset_at_switch': n_reset, 'conv_steps_end': adam_steps},
         'n_trunk': vol.n_weights(trunk), 'n_head_v': vol.n_weights(head_v), 'data_dir': smc.DATA_DIR,
         'tune_start': smc.DATA['tune_start'],
         'code': {'vol_py': VOL_PY, 'vol_sha': vol.file_sha(VOL_PY), 'pred_sha': vol.file_sha(vol.PRED_PY),
                  'train_sha': vol.file_sha(pred.TRAIN_PY)},
         'secs': time.time() - t_run, 'when': time.strftime('%Y-%m-%d %H:%M:%S')}
    _write(r)
    print(f"💾 {_paths(tag)[0]} / .npz | {(time.time() - t_run) / 60:.1f} мин")
    return r


def _write(r):
    with open(_paths(r['tag'])[0], 'w', encoding='utf-8') as fh:
        json.dump(smc._jsonable({k: v for k, v in r.items() if not k.startswith('_')}), fh, ensure_ascii=False, indent=1)


def trunk_of(r, ck='A'):
    """Ствол точки ck прогона r (CNN сети сайта, веса из npz) в режиме eval."""
    cfg = {**smc.make_cfg(MODEL, {'L': L}, r['seed_key']), **{k: v for k, v in r['cfg'].items() if k != 'dict'}}
    for k in ('head_hidden', 'cnn_dil'):
        if isinstance(cfg.get(k), list):
            cfg[k] = tuple(cfg[k])
    n_ch = smc.N_PATH + smc.N_LEVEL.get(cfg.get('price'), 0)
    trunk, _ = smc.build_model(cfg, torch.randn(16, n_ch, L, device=DEVICE), np.random.default_rng(0))
    with np.load(_paths(r['tag'])[1]) as z:
        pre = f"sd_{ck}__trunk."
        trunk.load_state_dict({k[len(pre):]: torch.from_numpy(z[k]) for k in z.files if k.startswith(pre)}, strict=True)
    trunk.eval()
    return trunk, cfg


def refit(ctx, r, refit_over=None):
    """Голова V заново на замороженном стволе точки A (рецепт J0, код SuMo_Class_Vol) — «одна сеть»: ствол A + голова MRI +
       голова V; у варианта λ = 0 — J0 на BTC. Прогон — в формате SuMo_Pred_Train, его тег — в json прогона."""
    trunk, cfg = trunk_of(r, 'A')
    sha = vol.trunk_sha(vol.sd_numpy(trunk))
    made = {}
    over = {**REFIT['over'], **(refit_over or {})}
    print(f"\n🔁 голова V заново на замороженном стволе точки A прогона {r['tag']} (эпоха {r['best_a']['ep']}): рецепт J0 — "
          + ", ".join(f"{k} {v}" for k, v in over.items()))
    with smc.orientation(cfg.get('orient', True)):
        with vol.head_on(trunk, list(cfg['head_hidden']), float(cfg['dropout']), made):
            res = pred.run_pred(ctx, TARGET, r['seed_key'], mname=MODEL, over=over, recipe=refit_recipe(r['variant']),
                                sub=REFIT['sub'])
    vol.after_run(res, made, sha)
    res['joint'] = {'ver': JOINT_VER, 'of': r['tag'], 'variant': r['variant'], 'lam': r['lam'], 'ck': 'A', 'trunk_sha': sha}
    with open(pred.pred_dir() + f"{res['tag']}.json", 'w', encoding='utf-8') as fh:
        json.dump(smc._jsonable(res), fh, ensure_ascii=False, indent=1)
    r['refit'] = res['tag']
    _write(r)
    print(f"🔁 голова заново: R² TUNE {res['summary']['tune']['panel']['r2_cnn']:.4f}, VAL "
          f"{res['summary']['val']['panel']['r2_cnn']:.4f} | {res['tag']}")
    return res


def _load(tag):
    pj, pz = _paths(tag)
    if not (os.path.isfile(pj) and os.path.isfile(pz)):
        return None
    with open(pj, encoding='utf-8') as fh:
        r = json.load(fh)
    return r if r.get('ver') == JOINT_VER and r.get('model') == MODEL else None


def _trunk_sha_A(r):
    """sha ствола точки A прогона r — по весам из его npz (так же считает голова заново)."""
    pre = 'sd_A__trunk.'
    with np.load(_paths(r['tag'])[1]) as z:
        return vol.trunk_sha({k[len(pre):]: z[k] for k in z.files if k.startswith(pre)})


def _refit_of(r, rf):
    """Голова заново rf — того самого прогона r и его ствола A, а не старая от прежнего обучения (FORCE с упавшей головой)."""
    j = (rf or {}).get('joint') or {}
    return (rf is not None and r.get('refit') == rf.get('tag') and j.get('of') == r['tag']
            and j.get('trunk_sha') == _trunk_sha_A(r))


def _refit_ok(r):
    p = pred.pred_dir() + f"{r.get('refit')}.json"
    if not r.get('refit') or not os.path.isfile(p) or not os.path.isfile(p[:-5] + '.npz'):
        return False
    with open(p, encoding='utf-8') as fh:
        return _refit_of(r, json.load(fh))


def run_job(job, refit_over=None, vsep_over=None):
    """Задание консоли: один сид, варианты ORDER подряд на общих данных BTC ('vsep' / 'vsep1' — отдельные V; vsep_over — их
       переопределения по ключу). Посчитанное пропускается (FORCE = True — пересчитать); если у прогона нет только головы заново —
       считается только она. Сбой одного варианта не гасит остальные."""
    if job not in JOBS:
        raise KeyError(f"🍆 АЙ, ОШИБКА! нет задания '{job}' — есть {', '.join(JOBS)}")
    seed = JOBS[job]
    ctx = pred.btc_context()
    failed = []
    for item in ORDER:
        try:
            if item in VSEPS:
                vs = VSEPS[item]
                tag = vsep_tag(seed, item)
                if not FORCE and pred._done(tag):
                    print(f"⏭️ {tag} — уже посчитан (FORCE = True — пересчитать)")
                else:
                    print(f"\n📏 эталон волы: отдельная сеть сайта на {TARGET} (код SuMo_Pred_Train, {vs['what']})")
                    pred.run_pred(ctx, TARGET, seed, mname=MODEL, over={**vs['over'], **((vsep_over or {}).get(item) or {})},
                                  recipe=vs['recipe'], sub=vs['sub'])
            else:
                tag = joint_tag(item, seed)
                r = None if FORCE else _load(tag)
                if r is not None and _refit_ok(r):
                    print(f"⏭️ {tag} — уже посчитан (FORCE = True — пересчитать)")
                elif r is not None:
                    print(f"↪️ {tag} — обучен, нет головы заново: считаю только её")
                    refit(ctx, r, refit_over)
                else:
                    run_joint(ctx, seed, item, refit_over)
        except Exception as e:
            print(f"\n🍆 АЙ, ОШИБКА! задание {job}, {vname(item)}: {type(e).__name__}: {e} — дальше следующий вариант")
            traceback.print_exc(file=sys.stdout)
            failed.append(item)
        gc.collect()
        if DEVICE.type == 'cuda':
            torch.cuda.empty_cache()
    if failed:
        raise RuntimeError(f"🍆 АЙ, ОШИБКА! задание {job}: не посчитаны {', '.join(vname(x) for x in failed)} — разобрать лог; "
                           f"при перезапуске посчитанное пропускается")


