        n_sw = rs.get('switch_ep')
        pre = n_sw is not None and _same_rows(rs['hist'][:n_sw + 1], r1['hist'][:n_sw + 1])
        post = rs['hist'][n_sw + 1:] if n_sw is not None else []
        post_ok = bool(post) and all('vol' not in h['loss'] and 'smooth' in h['loss'] and h['lam'] == 0.0 and 'g' not in h
                                     for h in post)
        frozen = rs['head_v_sha']['switch'] is not None and rs['head_v_sha']['switch'] == rs['head_v_sha']['end']
        moved = r1['head_v_sha']['end'] != rs['head_v_sha']['end']
        n_conv = len(shared_params(trunk_of(rs, 'A')[0]))
        st_sw = n_sw is not None and rs['steps_per_epoch'] * (rs['epochs_run'] - n_sw - 1)
        adam_ok = (rs['adam']['reset_at_switch'] == n_conv and rs['adam']['conv_steps_end'] == st_sw
                   and r1['adam']['conv_steps_end'] == r1['steps_per_epoch'] * r1['epochs_run'])
        check(f"переключение после эпохи {n_sw}: до него история — бит в бит λ = 1 без переключения: {pre}; после — лосс без волы, "
              f"λ эпохи 0 ({len(post)} эп.): {post_ok}; голова V после переключения не менялась (sha): {frozen}, а у λ = 1 без "
              f"переключения — менялась: {moved}; память Adam у {n_conv} тензоров свёрток — заново (шагов после переключения "
              f"{rs['adam']['conv_steps_end']:g} = {st_sw}): {adam_ok}; голова заново — {rs['refit']}",
              n_sw is not None and pre and post_ok and frozen and moved and adam_ok and _refit_ok(rs))

