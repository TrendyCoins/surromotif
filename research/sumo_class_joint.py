_ARR = {}


def _arr(r):
    if r['tag'] not in _ARR:
        with np.load(_paths(r['tag'])[1]) as z:
            _ARR[r['tag']] = {k: z[k] for k in z.files if not k.startswith('sd_')}
    return _ARR[r['tag']]


def _joint_runs():
    out = []
    if os.path.isdir(joint_dir()):
        for fn in sorted(os.listdir(joint_dir())):
            if fn.startswith('joint_') and fn.endswith('.json') and not fn.startswith('joint_sum_'):
                r = _load(fn[:-5])
                if r is not None and r.get('variant') in VARIANTS:
                    out.append(r)
    return out


def mri_delta(x, ck, xb, part):
    """Парная разница AUC (точка ck прогона − точка A эталона λ = 0) на одних окнах и суррогатах: (Δ, SE) или None — окна не
       совпали."""
    k_, kb = f"{ck}__mri__{part}__", f"A__mri__{part}__"
    if k_ + 'st' not in x or kb + 'st' not in xb:
        return None
    if not all(np.array_equal(x[k_ + q], xb[kb + q]) for q in ('st', 'wp', 'wn')):
        return None
    return smc.auc_diff(x[k_ + 'sp'].astype(np.float64), x[k_ + 'sn'].astype(np.float64),
                        xb[kb + 'sp'].astype(np.float64), xb[kb + 'sn'].astype(np.float64), x[k_ + 'wp'], x[k_ + 'wn'])


def vol_delta(x, ck, base_run, a, part):
    """Парная разница R² (голова V точки ck − отдельная V) на одних окнах: (Δ, SE) или None — окна не совпали."""
    k_ = f"{ck}__vol__{part}__"
    b = pred.run_arr(base_run)
    kb = f"{a}__{part}__"
    if k_ + 'y' not in x or kb + 'y' not in b:
        return None
    if not (np.array_equal(x[k_ + 'st'], b[kb + 'st']) and np.array_equal(x[k_ + 'y'], b[kb + 'y'])):
        return None
    return pred.panel_delta([(x[k_ + 'y'], x[k_ + 'cnn'], b[kb + 'cnn'], x[k_ + 'wk'])])


def _comb(pairs):
    """Среднее по сидам и SE (seed_combine) из списка (Δ, SE); число сравнённых сидов."""
    ok = [p for p in pairs if p is not None]
    return pred.seed_combine([p[0] for p in ok], [p[1] for p in ok])


def _mean(xs):
    xs = [float(x) for x in xs if x is not None and np.isfinite(x)]
    return float(np.mean(xs)) if xs else float('nan')


def _c(d):
    """(Δ, SE, n) → «+0.0012 ± 0.0016» (или «—»)."""
    if not d or not np.isfinite(d[0]):
        return '—'
    return f"{d[0]:+.4f} ± {d[1]:.4f}"


def _med(xs):
    """Медиана конечных значений (в json NaN — null); NaN — нет ни одного."""
    xs = [float(x) for x in xs if x is not None and np.isfinite(x)]
    return float(np.median(xs)) if xs else float('nan')


def diag_stats(r):
    """Градиенты прогона: доли волы (сигнал и по батчам) на старте и после эпохи 0, медианы долей и косинуса до переключения (или
       до точки A); below — эпох (до той же точки), где сигнал BCE ниже шума пробы."""
    rows = [h for h in r['hist'] if h.get('g')]
    if not rows:
        return None
    upto = r['switch_ep'] if r.get('switch_ep') is not None else r['best_a']['ep']
    sel = [h['g'] for h in rows if h['ep'] <= upto] or [rows[0]['g']]
    g0, gi = rows[0]['g'], (r.get('diag_init') or {})
    return {'init': gi.get('share'), 'init_b': gi.get('share_b'), 'ep0': g0.get('share'), 'ep0_b': g0.get('share_b'),
            'med': _med([g.get('share') for g in sel]), 'med_b': _med([g.get('share_b') for g in sel]),
            'cos0': g0.get('cos'), 'cos': _med([g.get('cos') for g in sel]),
            'below': sum(1 for g in sel if (g.get('below') or {}).get('mri'))}


def joint_summary():
    pred._NPZ.clear()
    _ARR.clear()
    runs = _joint_runs()
    by = {(r['variant'], r['seed_key']): r for r in runs}
    pruns = pred.load_runs()
    a = smc.DATA['assets'][0]
    v_bases = {key: {r['seed_key']: r for r in pred.pick(pruns, 'btc', MODEL, target=TARGET, recipe=vs['recipe'])
                     if r['seed_key'] in SEEDS} for key, vs in VSEPS.items()}
    v_base = v_bases['vsep']                     # P3 — главный эталон (перенос на пул); головы в точках A и V — к нему
    refits = {nm: {r['seed_key']: r for r in pred.pick(pruns, 'btc', MODEL, target=TARGET, recipe=refit_recipe(nm))
                   if r['seed_key'] in SEEDS} for nm in VARIANTS}
    for nm, d in refits.items():                 # только головы заново текущих прогонов (и их ствола A)
        for s in list(d):
            if (nm, s) not in by or not _refit_of(by[(nm, s)], d[s]):
                print(f"⚠️ {d[s]['tag']}: голова заново не от текущего прогона {joint_tag(nm, s)} — в сводку не идёт")
                del d[s]
    m_base = {s: by[('l0', s)] for s in SEEDS if ('l0', s) in by}
    j0 = refits['l0']
    mb = list(m_base.values())
    summ = {'ver': JOINT_VER, 'when': time.strftime('%Y%m%d_%H%M%S'), 'model': MODEL, 'target': TARGET,
            'base': {}, 'j0': {}, 'variants': {}}

    def d_to(rf, part):
        """ΔR² прогонов rf (по сидам) к каждой отдельной V и к J0: {'vsep': …, 'vsep1': …, 'j0': …}."""
        out = {key: _comb([pred.cross_delta(rf[s], vb_[s], [a], part) if s in vb_ else None for s in rf])
               for key, vb_ in v_bases.items()}
        out['j0'] = _comb([pred.cross_delta(rf[s], j0[s], [a], part) if s in j0 else None for s in rf])
        return out
    print(f"\n{'=' * 100}\n🧪 J2 — сеть сайта {MODEL} на одном BTC: лосс BCE + штраф скачков + λ · MSE {TARGET}; прогонов {len(runs)}"
          f"\n{'=' * 100}")
    if mb:
        b_ = {'auc_tune': _mean([r['eval']['A']['mri_tune']['auc'] for r in mb]),
              'auc_val': _mean([r['eval']['A']['mri_val']['auc'] for r in mb]),
              'line': _mean([r['eval']['A']['mri_line_val'].get('R') for r in mb]),
              'best_a': {s: r['best_a']['ep'] for s, r in m_base.items()}}
        summ['base']['mri'] = b_
        print(f"   эталон MRI — λ = 0 (тот же цикл, только MRI; сиды {', '.join(m_base)}): AUC TUNE {b_['auc_tune']:.4f}, VAL "
              f"{b_['auc_val']:.4f}, R линии VAL {b_['line']:.3f}; точка A — эпохи "
              + ", ".join(f"{s} {e}" for s, e in b_['best_a'].items()))
    else:
        print("   эталона MRI (λ = 0) нет — Δ MRI не считаются")
    for key, vs in VSEPS.items():
        vb = [v_bases[key][s] for s in SEEDS if s in v_bases[key]]
