def _same_rows(h1, h2):
    """Истории эпох совпадают бит в бит по тому, что видит обучение (лоссы, λ эпохи, AUC, R², lr); NaN = NaN."""
    def eq(p, q):
        if isinstance(p, dict) and isinstance(q, dict):
            return p.keys() == q.keys() and all(eq(p[k], q[k]) for k in p)
        return p == q or (isinstance(p, float) and isinstance(q, float) and math.isnan(p) and math.isnan(q))
    keys = ('ep', 'loss', 'lam', 'tune_auc', 'fit_auc', 'tune_r2', 'fit_r2', 'lr')
    return len(h1) == len(h2) and all(all(eq(x[k], y[k]) for k in keys) for x, y in zip(h1, h2))


def mode_stand():
    """Стенд: синтетика SuMo_Pred_Train (GARCH с суточным профилем) на одном «BTC», настоящий код обучения F1, SuMo_Pred_Train и
       SuMo_Class_Vol модулями, сеть сайта поменьше (со штрафом скачков и dropout 0.1 / 0.1). Всегда на CPU: «λ = 0 — бит в бит
       run_one» и пассивность диагностики проверяются только на детерминированном железе. Подменяет на время устройство, папки,
       даты, конфигурацию сети сайта, очередь и правило переключения (и возвращает)."""
    global ORDER, SEEDS, SWITCH, DEVICE
