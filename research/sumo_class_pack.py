def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def load_json(path):
    if not os.path.isfile(path):
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет {path}")
    with open(path, encoding='utf-8') as fh:
        return json.load(fh)


def load_run(path):
    r = load_json(path)
    npz = path[:-5] + '.npz'
    if not os.path.isfile(npz):
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет {npz}")
    return r, npz


def npz_dict(path):
    d = np.load(path, allow_pickle=False)
    return {k: d[k] for k in d.files}


def inventory(name, arrs):
    lines = [f"== {name} ({len(arrs)} массивов, {sum(v.nbytes for v in arrs.values()) / 1e6:.1f} МБ без сжатия)"]
    for k in sorted(arrs):
        v = arrs[k]
        lines.append(f"   {k:<40} {str(tuple(v.shape)):<16} {str(v.dtype):<8} {v.nbytes:>12}")
    return lines


def n_params(sd):
    """Обучаемых параметров по ключам sd_* (веса и сдвиги слоёв; буферы — без них)."""
    return int(sum(v.size for k, v in sd.items() if k.endswith(('.weight', '.bias'))))


def save_parts(arrs, base, limit_mb):
    """Режет словарь по ключам на части <= limit_mb (по размеру файла); возвращает пути частей."""
    budget = limit_mb * 1e6 * 0.9
    while True:
        keys = sorted(arrs, key=lambda k: (not k.startswith('sd_'), k))     # веса — в первую часть
        parts, cur, size = [], [], 0
        for k in keys:
            nb = arrs[k].nbytes
            if cur and size + nb > budget:
                parts.append(cur)
                cur, size = [], 0
            cur.append(k)
            size += nb
        if cur:
            parts.append(cur)
        paths = []
        for i, ks in enumerate(parts):
            p = f"{base}_part{i}.npz"
            np.savez_compressed(p, **{k: arrs[k] for k in ks})
            paths.append(p)
        big = [p for p in paths if os.path.getsize(p) > limit_mb * 1e6]
        if not big:
            return paths
        for p in paths:
            os.remove(p)
        if budget < 1e6:
            raise RuntimeError(f"🍆 АЙ, ОШИБКА! {base}: один массив больше {limit_mb} МБ — резать по ключам нельзя")
        budget *= 0.7                                          # сжатие вышло хуже ожидаемого — части мельче


def check_parts(arrs, paths):
    got = {}
    for p in paths:
        d = np.load(p, allow_pickle=False)
        for k in d.files:
            if k in got:
                raise RuntimeError(f"🍆 АЙ, ОШИБКА! ключ {k} в двух частях")
            got[k] = d[k]
    same = set(got) == set(arrs) and all(got[k].dtype == arrs[k].dtype and np.array_equal(got[k], arrs[k])
                                         for k in arrs)
    if not same:
        raise RuntimeError("🍆 АЙ, ОШИБКА! части npz не собираются в исходный словарь бит в бит")


def stage_logs(pattern, must=None):
    """Логи по шаблону с датой в имени (…_ГГГГММДД_ччммсс.log) не раньше LOG_SINCE, по порядку; must — текст, который в логе
       обязан быть (у общих шаблонов — модели этапа)."""
    out = []
    for p in sorted(glob.glob(RUN_DIR + 'logs/' + pattern)):
        m = re.search(r'_(\d{8})_\d{6}\.log$', os.path.basename(p))
        if not m or m.group(1) < LOG_SINCE:
            continue
        if must:
            with open(p, encoding='utf-8', errors='replace') as fh:
                if must not in fh.read():
                    continue
        out.append(p)
    return out


