def synth_world(kind, seed, n_assets=None, n_bars=None, step_ms=3_600_000, t0='2024-07-01 00:00:00'):
    """Синтетический рынок: бары с объёмом, сделками и тейкер-покупками. Режимы «пила / ход» (знак шага повторяет прошлый с
       вероятностью 0.5 −/+ kappa) не зависят от размеров. Объём — от размеров бара (ширина, |шаг|) и их недавней истории плюс
       шум; kind: 'null' — режимы объёма не трогают; 'plus' — в пиле объём выше, в ходе ниже (на effect в log); 'minus' —
       наоборот; 'leak' — режимов в объёме нет, но есть «чередование размеров» (большой-малый по очереди), и от него зависят и
       объём, и MRI-заменитель (в контролях его нет)."""
    P = STAND
    rng = np.random.default_rng(seed)
    n_assets, n_bars = n_assets or P['assets'], n_bars or P['bars']
    t = pd.Timestamp(t0).value // 10 ** 6 + np.arange(n_bars, dtype=np.int64) * step_ms
    out = {}
    for ia in range(n_assets):
        reg = np.zeros(n_bars, dtype=np.int8)                    # 1 — ход, 0 — пила
        alt = np.zeros(n_bars, dtype=np.int8)                    # 1 — чередование размеров (мир утечки)
        for arr in (reg, alt):
            s = rng.integers(0, 2)
            sw = rng.random(n_bars) < P['switch']
            for i in range(n_bars):
                s = 1 - s if sw[i] else s
                arr[i] = s
        lv = np.zeros(n_bars)
        eps = rng.normal(0, 0.06, n_bars)
        for i in range(1, n_bars):
            lv[i] = 0.995 * lv[i - 1] + eps[i]
        sig = 0.004 * np.exp(lv)
        size = sig * np.abs(rng.standard_t(5, n_bars)) * 0.8 + sig * 0.05
        if kind == 'leak':
            size *= np.where(alt == 1, np.where(np.arange(n_bars) % 2 == 0, 1.6, 0.45), 1.0)
        sg = np.ones(n_bars)
        u = rng.random(n_bars)
        for i in range(1, n_bars):
            p_same = 0.5 + (P['kappa'] if reg[i] == 1 else -P['kappa'])
            sg[i] = sg[i - 1] if u[i] < p_same else -sg[i - 1]
        ret = sg * size
        c = 100.0 * np.exp(np.cumsum(ret))
        o = np.r_[100.0, c[:-1]]
        wu, wd = sig * rng.exponential(0.5, n_bars), sig * rng.exponential(0.5, n_bars)
        h, l = np.maximum(o, c) * np.exp(wu), np.minimum(o, c) * np.exp(-wd)
        rngl = np.log(h / l)
        act = np.zeros(n_bars)
        for i in range(1, n_bars):
            act[i] = 0.9 * act[i - 1] + 0.1 * np.log(rngl[i - 1] / 0.004)
        logv = 3.0 + 1.0 * np.log(rngl / 0.004) + 0.25 * np.log(size / 0.004) + 0.4 * act + rng.normal(0, 0.35, n_bars)
        eff = P['effect']
        if kind == 'plus':
            logv += np.where(reg == 0, eff, -eff)
        elif kind == 'minus':
            logv += np.where(reg == 0, -eff, eff)
        elif kind == 'leak':
            logv += np.where(alt == 1, P['leak'], -P['leak'])
        v = np.exp(logv)
        share = np.clip(0.5 + 0.3 * np.tanh(ret / sig) + rng.normal(0, 0.05, n_bars), 0.0, 1.0)
        out[f"SYN{ia}USDT"] = {'t': t, 'o': o, 'h': h, 'l': l, 'c': c, 'v': v, 'b': v * share,
                               'n': np.round(v * np.exp(rng.normal(0, 0.2, n_bars)) * 3.0), 'alt': alt}
    return out


def _acf1(x):
    xc = x - x.mean(axis=1, keepdims=True)
    den = (xc * xc).sum(1)
    return np.where(den > 0, (xc[:, 1:] * xc[:, :-1]).sum(1) / np.where(den > 0, den, 1.0), 0.0)


def proxy_logit(rw, aw, leak):
    """MRI-заменитель стенда (logit окна): пила (знаки шагов чередуются чаще случайного) — выше, ровный ход — ниже; плюс
       зависимость от размеров (её снимают контроли) и, в мире утечки, от чередования размеров (его контроли не видят)."""
    s = np.sign(rw)
    saw = -(s[:, 1:] * s[:, :-1]).mean(1)
    size = np.log(aw.sum(1))
    lg = 6.0 * saw + 0.8 * (size - size.mean())
    if leak:
        lg += 3.0 * (-_acf1(aw))
    return lg


def stand_signs(rng, n, L, b):
    """Знаки близнеца блоками по b (как block_signs_prev: столбец 0 — бар перед окном; при b = 1 — свой знак)."""
    if b <= 1:
        return np.where(rng.random((n, L + 1)) < 0.5, -1, 1).astype(np.int8)
    phase = rng.integers(0, b, (n, 1))
    idx = (np.arange(L)[None, :] + phase) // b
    nb = (L - 1 + b - 1) // b + 1
    s = np.where(rng.random((n, nb)) < 0.5, -1, 1).astype(np.int8)
    win = np.take_along_axis(s, idx, axis=1)
    return np.concatenate([win[:, :1], win], axis=1)


def stand_rows(world, seed, step_ms):
    """Строки стенда тем же путём, что 'run': признаки баров -> окна -> контроли; спот = фьючерс (те же бары)."""
    rng = np.random.default_rng(10_000 + seed)
    L = 64
    rows = []
    for ia, (a, B) in enumerate(world.items()):
        F = bar_feats(B, step_ms, FLOW['n_norm'])
        need = L - 1 + FLOW['hist'][1]
        j = np.arange(need, len(F['t']))
        j = j[F['run0'][j] <= j - need]
        t_ns = F['t'][j] * 10 ** 6
        W = window_feats(F, t_ns)
        sel = np.flatnonzero(W['ok'])
        j = W['j'][sel]
        jj = j[:, None] + np.arange(-(L - 1), 1)[None, :]
        rw, gw = F['rf'][jj], F['rg'][jj]
        sg = stand_signs(rng, len(j), L, int(FLOW['twin_null'][len('sflip'):]))
        leak = world is not None and STAND.get('_leak', False)
        s4 = stand_signs(rng, len(j), L, int(FLOW['ruler_null'][len('sflip'):]))
        lg = proxy_logit(rw, np.abs(rw), leak) + rng.normal(0, 0.3, len(j))
        lt = proxy_logit(rw * sg[:, 1:], np.abs(rw), leak) + rng.normal(0, 0.3, len(j))
        l4 = proxy_logit(rw * s4[:, 1:], np.abs(rw), leak) + rng.normal(0, 0.3, len(j))
        rows.append({'asset': np.full(len(sel), ia, dtype=np.int64), 'a': a, 'sel': sel, 'lg': lg, 'lt': lt, 'l4': l4,
                     't': t_ns[sel], 'wk': t_ns[sel] // WEEK_NS, 'W': {k: v[sel] for k, v in W.items()},
                     'sp': {'abs_r': np.abs(rw).sum(1), 'r_sum': rw.sum(1), 'r_sum_tw': (rw * sg[:, 1:]).sum(1),
                            'g_sum': gw.sum(1), 'g_max': gw.max(1)}, 'sg': sg, 'F': F})
    return rows


def stand_eval(rows):
    """Правила (1)–(2) на мире стенда: поиск — первая половина недель, подтверждение — вторая."""
    R = {'rows': rows}
    q, zk = ruler(np.concatenate([r['l4'] for r in rows]))          # линейка — по суррогатам блоками по 4, как в 'run'
    for r in rows:
        r['z'], r['ztw'] = to_z(r['lg'], q, zk), to_z(r['lt'], q, zk)
        r['lm'] = line_m(r['z'])
    D = stack(R)
    wk_mid = np.median(np.unique(D['wk']))
    res = {}
    for src, msk in (('search', D['wk'] <= wk_mid), ('confirm', D['wk'] > wk_mid)):
        A = a1_block(D, ('z', 'ztw'), mask=msk.copy())
        res[src] = {'a1': A['res'][('y', 'z')], 'placebo': A['res'][('y', 'ztw')], 'claim': claim_block(D, A)}
    return verdict_tf(res), res, D, R


