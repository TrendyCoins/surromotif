def read_fut_csv(path):
    """CSV фьючерса (формат scripts/futures_klines.py) -> массивы 5M и сверка (0а). time — время открытия, мс UTC."""
    if not os.path.isfile(path):
        return None, {'ok': False, 'why': 'нет файла'}
    cols = ['timestamp', 'open', 'high', 'low', 'close', 'volume', 'trades', 'tb_base_av']
    df = pd.read_csv(path, usecols=cols, parse_dates=['timestamp'])
    t = df['timestamp'].to_numpy().astype('datetime64[ms]').astype(np.int64)
    o, h, l, c, v, b = (df[k].to_numpy(dtype=np.float64) for k in ('open', 'high', 'low', 'close', 'volume', 'tb_base_av'))
    n = df['trades'].to_numpy(dtype=np.float64)
    info = {'rows': int(len(df)), 'first': str(df['timestamp'].iloc[0]) if len(df) else '',
            'last': str(df['timestamp'].iloc[-1]) if len(df) else '',
            'back': int((np.diff(t) <= 0).sum()),
            'bad_ohlc': int(((h < l) | (o > h) | (o < l) | (c > h) | (c < l) | (l <= 0)).sum()),
            'bad_taker': int(((b > v * (1 + 1e-9) + 1e-12) | (b < 0) | (v < 0) | (n < 0)).sum()),
            'zero_vol': int((v <= 0).sum())}
    info['ok'] = bool(len(df) > 0 and info['back'] == 0 and info['bad_ohlc'] == 0 and info['bad_taker'] == 0)
    return {'t': t, 'o': o, 'h': h, 'l': l, 'c': c, 'v': v, 'n': n, 'b': b}, info


def to_tf(B5, step_ms):
    """Бары ТФ из баров 5M (как свечи Binance): open первого, high / low — max / min, close последнего, объём, сделки и
       тейкер-покупки — суммы. Берутся только полные бары (все бары 5M внутри): у неполного объём занижен."""
    if step_ms == 300_000:
        return dict(B5)
    t = B5['t']
    key = t // step_ms * step_ms
    idx = np.flatnonzero(np.r_[True, key[1:] != key[:-1]])
    end = np.r_[idx[1:], len(t)]
    full = (end - idx) == step_ms // 300_000
    out = {'t': key[idx], 'o': B5['o'][idx], 'c': B5['c'][end - 1],
           'h': np.maximum.reduceat(B5['h'], idx), 'l': np.minimum.reduceat(B5['l'], idx)}
    for k in ('v', 'n', 'b'):
        out[k] = np.add.reduceat(B5[k], idx)
    return {k: x[full] for k, x in out.items()}


def bar_feats(B, step_ms, n_norm):
    """Признаки баров фьючерса — только прошлое и сам бар. Нормировщик — медиана (high − low) за n_norm строк до бара (как r
       спота); бар годен, если нормировщик живой и бар идёт сразу за прошлым (без пропуска сетки). Размеры (без знаков): ширина,
       |шаг close|, |тело|, тени — в нормировщике; знаковые: шаг close (rf) и дельта (покупки − продажи)."""
    t, o, h, l, c = B['t'], B['o'], B['h'], B['l'], B['c']
    norm = pd.Series(h - l).rolling(n_norm, closed='left').median().to_numpy()
    prev_c = np.r_[np.nan, c[:-1]]
    contig = np.r_[False, np.diff(t) == step_ms]
    ok = np.isfinite(norm) & (norm > 0) & contig & np.isfinite(prev_c)
    nz = np.where(ok, norm, 1.0)
    F = {'t': t, 'ok': ok, 'c': c,
         'rg': np.where(ok, (h - l) / nz, 0.0), 'dc': np.where(ok, np.abs(c - prev_c) / nz, 0.0),
         'rf': np.where(ok, (c - prev_c) / nz, 0.0), 'body': np.where(ok, np.abs(c - o) / nz, 0.0),
         'lvl': np.where(ok, np.log(nz / np.where(ok, prev_c, 1.0)), 0.0),
         'v': np.where(ok, B['v'], 0.0), 'n': np.where(ok, B['n'], 0.0), 'd': np.where(ok, 2.0 * B['b'] - B['v'], 0.0)}
    F['wick'] = np.maximum(F['rg'] - F['body'], 0.0)
    F['ad'] = np.abs(F['d'])
    idx = np.arange(len(t))
    F['run0'] = np.maximum.accumulate(np.where(~ok, idx, -1)) + 1      # первый бар непрерывного годного куска, где бар
    for k in ('v', 'n', 'd', 'ad', 'rg', 'dc', 'rf', 'body', 'wick'):
        F['cs_' + k] = np.r_[0.0, np.cumsum(F[k])]
    F['rg_max64'] = pd.Series(F['rg']).rolling(64, min_periods=64).max().to_numpy()
    return F


def _wsum(F, k, a, b):
    """Сумма признака k по барам [a, b] включительно (векторно)."""
    cs = F['cs_' + k]
    return cs[b + 1] - cs[a]


def window_feats(F, t_ns, L=64):
    """Окна по времени их последнего бара -> индексы баров фьючерса и суммы. Строка годна, если у фьючерса есть бар окна и
       подряд годны 64 бара окна и 200 баров перед ним; вперёд (B1) — ещё 64 бара сразу после окна."""
    h64, h200 = FLOW['hist']
    t_ms = np.asarray(t_ns, dtype=np.int64) // 10 ** 6
    j = np.searchsorted(F['t'], t_ms)
    jj = np.minimum(j, len(F['t']) - 1)
    hit = (j < len(F['t'])) & (F['t'][jj] == t_ms)
    need = L - 1 + h200
    ok = hit & (F['run0'][jj] <= jj - need)
    j = np.where(ok, jj, need)
    w0 = j - (L - 1)
    out = {'ok': ok, 'j': j}
    for k in ('v', 'n', 'd', 'ad', 'rg', 'dc', 'rf', 'body', 'wick'):
        out[k] = _wsum(F, k, w0, j)
    q = L // 4
    for i in range(4):
        out[f'q{i + 1}'] = _wsum(F, 'rg', w0 + i * q, w0 + (i + 1) * q - 1)
    out['h64'] = _wsum(F, 'rg', w0 - h64, w0 - 1)
    out['h200'] = _wsum(F, 'rg', w0 - h200, w0 - 1)
    out['rg_max'] = F['rg_max64'][j]
    out['lvl'] = F['lvl'][j]
    out['how'] = (((t_ms // 86_400_000) + 3) % 7) * 24 + (t_ms // 3_600_000) % 24      # час недели, понедельник 00:00 — 0
    jf = np.minimum(j + FLOW['fwd'], len(F['t']) - 1)
    fok = ok & (j + FLOW['fwd'] < len(F['t'])) & (F['run0'][jf] <= j)
    out['fok'] = fok
    jf = np.where(fok, jf, j)
    for k in ('v', 'rg', 'dc', 'body', 'wick'):
        out['n_' + k] = np.where(fok, _wsum(F, k, j + 1, jf), np.nan)
    out['n_rg_max'] = np.where(fok, F['rg_max64'][jf], np.nan)
    return out


