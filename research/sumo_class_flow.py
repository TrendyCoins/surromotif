def twin_gen(T, part, L, spec):
    """Генератор знаков суррогата — как EvalStore._gen кода обучения (ключ: часть, нулевая, L)."""
    import torch
    g = torch.Generator()
    g.manual_seed(T.DATA['eval_seed'] + zlib.crc32("|".join(map(str, (part, spec, L))).encode()) % 1000003)
    return g


def twin_signs(T, part, n, L, spec):
    """Знаки баров суррогата (n, L + 1), столбец 0 — бар перед окном: ровно как у набора проверки пула с нулевой spec."""
    kind, par = T.parse_null(spec)
    if kind != 'sflip':
        raise ValueError(f"🍆 АЙ, ОШИБКА! нулевая {spec} — нужна sflipN")
    return T.block_signs_prev(n, L, par, twin_gen(T, part, L, spec), 'cpu')


def signs_crc(sg):
    return int(zlib.crc32(np.asarray(sg).astype(np.int8).tobytes()))


