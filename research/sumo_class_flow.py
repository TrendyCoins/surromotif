def _groups(*keys):
    """Плотные номера групп по сочетанию ключей."""
    k = np.zeros(len(keys[0]), dtype=np.int64)
    for x in keys:
        _, inv = np.unique(np.asarray(x), return_inverse=True)
        k = k * (int(inv.max()) + 1 if len(inv) else 1) + inv
    _, g = np.unique(k, return_inverse=True)
    return g.astype(np.int64)


def demean(M, groups):
    """Очистка от эффектов групп (несколько наборов, попеременно, до сходимости). Возвращает (M, итераций, сошлось)."""
    M = np.array(M, dtype=np.float64, copy=True)
    if M.ndim == 1:
        M = M[:, None]
    tol = FLOW['fe_tol'] * max(1.0, float(np.nanmax(np.nanstd(M, axis=0))) if len(M) else 1.0)
    G = [(g, int(g.max()) + 1, np.maximum(np.bincount(g), 1)) for g in groups]
    for it in range(FLOW['fe_iter']):
        worst = 0.0
        for g, ng, cnt in G:
            for k in range(M.shape[1]):
                mu = np.bincount(g, weights=M[:, k], minlength=ng) / cnt
                M[:, k] -= mu[g]
                worst = max(worst, float(np.max(np.abs(mu))))
        if worst < tol:
            return M, it + 1, True
    return M, FLOW['fe_iter'], False


def _resid(y, C):
    if C is None or C.shape[1] == 0:
        return y
    sd = C.std(axis=0)
    keep = sd > 1e-12
    Cs = C[:, keep] / sd[keep]
    beta = np.linalg.lstsq(Cs.T @ Cs, Cs.T @ y, rcond=None)[0]
    return y - Cs @ beta


def fwl(y, x, C, cl):
    """β при x в регрессии y на [x, C] (всё уже очищено от эффектов) и ошибка по кластерам cl (неделям)."""
    xr, yr = _resid(x, C), _resid(y, C)
    sxx = float(xr @ xr)
    if not sxx > 0:
        return {'beta': math.nan, 'se': math.nan, 't': math.nan, 'n': int(len(y))}
    beta = float(xr @ yr) / sxx
    u = yr - beta * xr
    sc = np.bincount(cl, weights=xr * u)
    G = int((np.bincount(cl) > 0).sum())
    se = math.sqrt(G / max(G - 1, 1) * float(np.sum(sc ** 2))) / sxx
    return {'beta': beta, 'se': se, 't': beta / se if se > 0 else math.nan, 'n': int(len(y)), 'clusters': G}


def diff_means(e, ind, cl):
    """Разница средних e в группах ind = 1 и ind = 0 с ошибкой по кластерам."""
    a = ind.astype(np.float64) - ind.mean()
    sxx = float(a @ a)
    if not sxx > 0:
        return {'d': math.nan, 'se': math.nan}
    d = float(a @ (e - e.mean())) / sxx
    u = (e - e.mean()) - d * a
    sc = np.bincount(cl, weights=a * u)
    G = int((np.bincount(cl) > 0).sum())
    se = math.sqrt(G / max(G - 1, 1) * float(np.sum(sc ** 2))) / sxx
    return {'d': d, 'se': se}


