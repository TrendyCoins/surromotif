def score_part(T, pdata, part, items, assets, check_twin=True):
    """logit моделей items на окнах части part всех ассетов с полом 0.2: реальные окна (sp), их суррогаты sflip4 — для линейки
       (s4) и близнецы sflip1 — плацебо (s1). Знаки — теми же генераторами, что у наборов проверки пула; сверка (0в) — у первого
       ассета X и боковые входы обоих = store.get. Плюс суммы окна спота (без пола: |r|, r, ширина) у реала и r у близнеца."""
    import torch
    L, data = T.POOL['L'], pdata['data']
    models = {}
    for it in items:
        models[it['tag']], _ = T.load_pool_model(it['set'], it['seed'], TF.model_name(), it['mode'])
    res, chk, t1 = {}, None, time.time()
    with CL.floor_override(data, L, FLOW['floor']):
        for i, a in enumerate(assets):
            store = T.pool_asset_store(data, L, pdata['sid'][a], pdata['t_cut'])
            n_all = int(len(store.w[part]))
            if n_all < FLOW['min_windows']:
                print(f"   {a:<11} {part}: окон {n_all} < {FLOW['min_windows']} — не считается")
                continue
            P = store.positives(part)
            n = int(len(P['st']))
            if n != n_all:
                raise RuntimeError(f"🍆 АЙ, ОШИБКА! {a} {part}: набор проверки взял подвыборку ({n} из {n_all}) — окна не подряд, "
                                   f"линия M не считается; подними DATA['max_eval'] кода обучения")
            W = P['W']
            if W.dim() != 3 or W.shape[1] != 4:
                raise ValueError(f"🍆 АЙ, ОШИБКА! окно модели — {tuple(W.shape)}, ждал (n, 4, L): close, HL/2, HLC/3, ширина")
            st = np.asarray(P['st'], dtype=np.int64)
            r = {'st': st, 't': np.asarray(data.t[st + L - 1], dtype=np.int64), 'wk': np.asarray(P['wk'], dtype=np.int64),
                 'abs_r': W[:, 0].abs().sum(1).double().cpu().numpy(), 'r_sum': W[:, 0].sum(1).double().cpu().numpy(),
                 'g_sum': W[:, 3].sum(1).double().cpu().numpy(), 'g_max': W[:, 3].max(1).values.double().cpu().numpy()}
            for tag, model in models.items():
                r[tag + '__sp'] = np.asarray(T.score(model, P['X'], S=P['S'])).astype(np.float32)
            for key, spec in (('s4', FLOW['ruler_null']), ('s1', FLOW['twin_null'])):
                sg = twin_signs(T, part, n, L, spec)
                Wn = data.flip_multi(P['st_t'], L, sg.to(T.DEVICE), W)
                Xn = T.to_shapes(Wn, P['fl'])
                Sn = T.side_feats(data, P['st_t'], L, Wn, P['fl'])
                if check_twin and (chk is None or chk['asset'] == a):          # первый посчитанный ассет
                    ev = store.get(part, spec)
                    ok = bool(torch.equal(ev['Xn'], Xn) and torch.equal(ev['Sn'], Sn))
                    chk = chk or {'asset': a, 'part': part, 'n': n, 'ok': True}
                    chk[spec] = ok
                    chk['ok'] = chk['ok'] and ok
                    store._set.clear()
                    if not ok:
                        raise RuntimeError(f"🍆 АЙ, ОШИБКА! сверка (0в): суррогаты {spec} {a} {part} не те же, что у набора "
                                           f"проверки пула")
                for tag, model in models.items():
                    r[tag + '__' + key] = np.asarray(T.score(model, Xn, S=Sn)).astype(np.float32)
                if key == 's1':
                    r['r_sum_tw'] = Wn[:, 0].sum(1).double().cpu().numpy()
                    r['crc'] = np.array([signs_crc(sg)], dtype=np.int64)
                del Wn, Xn, Sn, sg
            res[a] = r
            store._pos.clear()
            store._set.clear()
            del P, W, store
            if T.DEVICE.type == 'cuda':
                torch.cuda.empty_cache()
            if i == 0:
                print(f"   ⏱️ первый ассет ({a}, {n} окон, моделей {len(models)}): {time.time() - t1:.0f} c — всего ~"
                      f"{(time.time() - t1) * len(assets) / 60:.0f} мин")
    return res, chk


