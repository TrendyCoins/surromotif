def src_logits(C, src):
    """Средний по сидам logit источника у каждого ассета части: реал (sp), суррогат линейки sflip4 (s4), близнец sflip1 (s1)."""
    tags = [t for t in C['meta']['tags'] if any(it['tag'] == t and it['src'] == src for it in C['meta']['items'])]
    if not tags:
        return None, []
    out = {}
    for a, r in C['res'].items():
        if all(t + '__sp' in r for t in tags):
            out[a] = {k: np.mean([r[t + '__' + k].astype(np.float64) for t in tags], axis=0) for k in ('sp', 's4', 's1')}
    return out, tags


def build_rows(T, C, src, FB, part):
    """Строки источника: окна с фьючерсом. z реала и близнеца (линейка источника), линия M (по всем окнам ассета подряд),
       суммы окна фьючерса и спота, знаки близнецов (пересчёт, контрольная сумма — как в кэше)."""
    lg, tags = src_logits(C, src)
    if not lg:
        return None
    q, zk = ruler(np.concatenate([x['s4'] for x in lg.values()]))      # линейка — по суррогатам sflip4, как у продукта
    rows, cover = [], {}
    for ia, (a, x) in enumerate(lg.items()):
        r = C['res'][a]
        z, ztw = to_z(x['sp'], q, zk), to_z(x['s1'], q, zk)
        lm = line_m(z)
        if a not in FB:
            cover[a] = {'n': int(len(z)), 'rows': 0, 'share': 0.0}
            continue
        W = window_feats(FB[a], r['t'])
        ok = W['ok']
        cover[a] = {'n': int(len(z)), 'rows': int(ok.sum()), 'share': float(ok.mean()) if len(ok) else 0.0}
        if not ok.any():
            continue
        sel = np.flatnonzero(ok)
        sg = twin_signs(T, part, len(z), T.POOL['L'], FLOW['twin_null']).numpy().astype(np.int8)
        if signs_crc(sg) != int(r['crc'][0]):
            raise RuntimeError(f"🍆 АЙ, ОШИБКА! сверка (0в): знаки близнецов {a} {part} не те, что в 'score'")
        rows.append({'asset': np.full(len(sel), ia, dtype=np.int64), 'a': a, 'sel': sel, 'z': z[sel], 'ztw': ztw[sel],
                     'lm': lm[sel], 'wk': r['wk'][sel], 't': r['t'][sel],
                     'W': {k: v[sel] for k, v in W.items()},
                     'sp': {k: r[k][sel] for k in ('abs_r', 'r_sum', 'r_sum_tw', 'g_sum', 'g_max')},
                     'sg': sg[sel], 'F': FB[a]})
    return {'rows': rows, 'cover': cover, 'tags': tags, 'assets': list(lg)}


def stack(R):
    """Склейка строк ассетов в один набор для регрессий."""
    cat = lambda f: np.concatenate([f(r) for r in R['rows']])
    D = {'asset': cat(lambda r: r['asset']), 'z': cat(lambda r: r['z']), 'ztw': cat(lambda r: r['ztw']),
         'lm': cat(lambda r: r['lm']), 'wk': cat(lambda r: r['wk']), 't': cat(lambda r: r['t'])}
    Wk = R['rows'][0]['W'].keys()
    D['W'] = {k: cat(lambda r, k=k: r['W'][k]) for k in Wk}
    D['sp'] = {k: cat(lambda r, k=k: r['sp'][k]) for k in R['rows'][0]['sp']}
    D['C'] = control_matrix(D['W'], D['sp'])
    D['y'] = _log(D['W']['v'])
    D['y_trd'] = _log(D['W']['n'])
    D['y_size'] = _log(D['W']['v']) - _log(D['W']['n'])
    D['g1'] = _groups(D['asset'], D['wk'])                   # ассет × неделя
    D['g2'] = _groups(D['asset'], D['W']['how'])             # ассет × час недели
    D['cl'] = _groups(D['wk'])                               # кластер — неделя календаря (все ассеты)
    return D


def a1_block(D, xs, ys=('y',), extra=None, mask=None):
    """FWL для набора x (ключи D) и y (ключи D): эффекты ассет × неделя и ассет × час недели, контроли D['C'] (+ extra)."""
    m = np.ones(len(D['z']), dtype=bool) if mask is None else np.array(mask, dtype=bool, copy=True)
    m &= np.all(np.isfinite(D['C']), axis=1)
    for y in ys:
        m &= np.isfinite(D[y])
    if extra is not None:
        m &= np.all(np.isfinite(extra), axis=1)
    if m.sum() < 100:
        return None
    cols = [D[y][m] for y in ys] + [D[x][m] for x in xs]
    Cm = D['C'][m] if extra is None else np.column_stack([D['C'][m], extra[m]])
    M = np.column_stack(cols + [Cm])
    Md, it, conv = demean(M, [D['g1'][m], D['g2'][m]])
    ny, nx = len(ys), len(xs)
    Cd = Md[:, ny + nx:]
    cl = _groups(D['cl'][m])
    out = {'n': int(m.sum()), 'fe_iter': it, 'fe_ok': conv, 'res': {}}
    for iy, y in enumerate(ys):
        for ix, x in enumerate(xs):
            r = fwl(Md[:, iy], Md[:, ny + ix], Cd, cl)
            sd = float(np.std(D[x][m]))
            r['sd_x'] = sd
            r['pct_sd'] = _pct(r['beta'] * sd)
            out['res'][(y, x)] = r
    out['e'] = {y: _resid(Md[:, iy], Cd) for iy, y in enumerate(ys)}
    out['mask'] = m
    out['cl'] = cl
    return out


def claim_block(D, A, y='y'):
    """(3): лишний объём сильных оранжевых (M >= 3) минус сильных синих (M <= 1/3)."""
    m = A['mask']
    e = A['e'][y]
    lm = D['lm'][m]
    k = math.log(FLOW['strong'])
    o, b = lm >= k, lm <= -k
    wk = D['wk'][m]
    sub = o | b
    out = {'n_orange': int(o.sum()), 'n_blue': int(b.sum()), 'weeks_orange': int(len(np.unique(wk[o]))),
           'weeks_blue': int(len(np.unique(wk[b]))), 'n_line': int(np.isfinite(lm).sum())}
    if o.sum() < 2 or b.sum() < 2:
        out.update({'d': math.nan, 'se': math.nan, 'pct': math.nan})
        return out
    r = diff_means(e[sub], o[sub].astype(np.int64), _groups(A['cl'][sub]))
    out.update({'d': r['d'], 'se': r['se'], 'pct': _pct(r['d']), 'mean_orange': float(e[o].mean()),
                'mean_blue': float(e[b].mean())})
    return out


def deciles(x, e, k=10):
    edges = np.quantile(x, np.linspace(0, 1, k + 1))
    b = np.clip(np.searchsorted(edges, x, side='right') - 1, 0, k - 1)
    return {'x': [float(np.mean(x[b == i])) for i in range(k)], 'e': [float(np.mean(e[b == i])) for i in range(k)],
            'n': [int((b == i).sum()) for i in range(k)]}


def twin_flow(R):
    """Дельта окна у близнеца: знаки баров близнеца × дельта фьючерса тех же баров (поток переворачивается вместе с баром)."""
    out = []
    L, ch = 64, FLOW['chunk']
    for r in R['rows']:
        j, sg, F = r['W']['j'], r['sg'], r['F']
        dtw = np.empty(len(j))
        for i0 in range(0, len(j), ch):
            jj = j[i0:i0 + ch][:, None] + np.arange(-(L - 1), 1)[None, :]
            dtw[i0:i0 + ch] = (F['d'][jj] * sg[i0:i0 + ch, 1:]).sum(1)
        out.append(dtw)
    return np.concatenate(out)


def a2_block(D, A, R):
    """A2 (справочно): типы окон по потоку (односторонний: ER потока >= медианы ассета) и цене (ход: ER цены спота >= медианы
       ассета) — доли по квинтилям z (реал; близнец — свой z, свой ход цены и поток, перевёрнутый вместе с баром) и по корзинам
       линии M; средняя ориентированная дельта (доля объёма по ходу окна), средний лишний объём."""
    m = A['mask']
    W, sp = D['W'], D['sp']
    er_p = np.abs(sp['r_sum']) / np.maximum(sp['abs_r'], 1e-12)
    er_f = np.abs(W['d']) / np.maximum(W['ad'], 1e-12)
    dtw = twin_flow(R)
    er_p_tw = np.abs(sp['r_sum_tw']) / np.maximum(sp['abs_r'], 1e-12)
    er_f_tw = np.abs(dtw) / np.maximum(W['ad'], 1e-12)
    dpl = W['d'] / np.maximum(W['v'], 1e-12) * np.sign(sp['r_sum'])
    dpl_tw = dtw / np.maximum(W['v'], 1e-12) * np.sign(sp['r_sum_tw'])
    med_p = np.zeros(len(er_p))
    med_f = np.zeros(len(er_f))
    for ia in np.unique(D['asset']):
        k = D['asset'] == ia
        med_p[k], med_f[k] = np.median(er_p[k]), np.median(er_f[k])

    def types(ep, ef):
        one, moved = ef >= med_f, ep >= med_p
        return {'прошёл': one & moved, 'поглощён': one & ~moved, 'драка': ~one & ~moved, 'дрейф': ~one & moved}

    e = np.full(len(er_p), np.nan)
    e[m] = A['e']['y']

    def table(bins, tp, dp, ef):
        rows = []
        for name, b in bins:
            if b.sum() == 0:
                rows.append({'bin': name, 'n': 0})
                continue
            rows.append({'bin': name, 'n': int(b.sum()), **{k: float(v[b].mean()) for k, v in tp.items()},
                         'dplus': float(dp[b].mean()), 'er_f': float(ef[b].mean()),
                         'excess': float(np.nanmean(e[b])) if np.isfinite(e[b]).any() else math.nan})
        return rows

    def quint(x):
        ed = np.quantile(x, [0.2, 0.4, 0.6, 0.8])
        k = np.searchsorted(ed, x, side='right')
        return [(f"z Q{i + 1}", k == i) for i in range(5)]

    lm = D['lm']
    e1, e2, e3, e4 = (math.log(v) for v in FLOW['m_edges'])
    mb = [('M <= 1/3', lm <= e1), ('1/3–0.8', (lm > e1) & (lm <= e2)), ('0.8–1.25', (lm > e2) & (lm < e3)),
          ('1.25–3', (lm >= e3) & (lm < e4)), ('M >= 3', lm >= e4)]
    return {'real_z': table(quint(D['z']), types(er_p, er_f), dpl, er_f),
            'twin_z': table(quint(D['ztw']), types(er_p_tw, er_f_tw), dpl_tw, er_f_tw),
            'real_m': table(mb, types(er_p, er_f), dpl, er_f)}


def check2_block(D, R):
    """Проверка 2 (справочно): окна «рывок и стоп» по стороне линии M. Рывок — 4 бара фьючерса с наибольшим |ходом| среди
       концов на барах 3…47 окна (после — не меньше 16 баров), не меньше jerk_k медиан |шага| окна; стоп — после рывка цена
       ушла в его сторону не больше чем на stop_frac рывка. После рывка: c = дельта по ходу рывка / объём, v = объём на бар
       после / объём на бар рывка."""
    P = FLOW['c2']
    L, ch = 64, FLOW['chunk']
    seg, after = P['seg'], P['min_after']
    rows = {'jerk_stop': [], 'c': [], 'v': []}
    for r in R['rows']:
        F, j = r['F'], r['W']['j']
        cs_rf, cs_d, cs_v = F['cs_rf'], F['cs_d'], F['cs_v']
        js, cc, vv = (np.zeros(len(j), dtype=bool), np.full(len(j), np.nan), np.full(len(j), np.nan))
        ends = np.arange(seg - 1, L - after)                      # позиции конца рывка в окне: 3 … 47
        for i0 in range(0, len(j), ch):
            jc = j[i0:i0 + ch]
            w0 = jc - (L - 1)
            e = w0[:, None] + ends[None, :]
            s4 = cs_rf[e + 1] - cs_rf[e + 1 - seg]
            k = np.argmax(np.abs(s4), axis=1)
            eb = e[np.arange(len(jc)), k]
            size = np.abs(s4[np.arange(len(jc)), k])
            dirn = np.sign(s4[np.arange(len(jc)), k])
            med = np.median(np.abs(F['rf'][w0[:, None] + np.arange(L)[None, :]]), axis=1)
            mv = (cs_rf[jc + 1] - cs_rf[eb + 1]) * dirn
            stop = (size >= P['jerk_k'] * med) & (mv <= P['stop_frac'] * size) & (size > 0)
            va = cs_v[jc + 1] - cs_v[eb + 1]
            vj = cs_v[eb + 1] - cs_v[eb + 1 - seg]
            na = jc - eb
            with np.errstate(divide='ignore', invalid='ignore'):
                c = (cs_d[jc + 1] - cs_d[eb + 1]) * dirn / va
                v = (va / na) / (vj / seg)
            js[i0:i0 + ch] = stop
            cc[i0:i0 + ch] = np.where(stop, c, np.nan)
            vv[i0:i0 + ch] = np.where(stop, v, np.nan)
        rows['jerk_stop'].append(js)
        rows['c'].append(cc)
        rows['v'].append(vv)
    js, c, v = (np.concatenate(rows[k]) for k in ('jerk_stop', 'c', 'v'))
    lm = D['lm']
    k = math.log(FLOW['mark'])
    sides = [('оранжевые', lm >= k), ('серые', (lm > -k) & (lm < k)), ('синие', lm <= -k)]
    out = []
    for name, sd in sides:
        b = sd & js
        n_side = int(sd.sum())
        if b.sum() == 0:
            out.append({'side': name, 'n_side': n_side, 'n': 0})
            continue
        cb, vb = c[b], v[b]
        counter = cb <= -P['c_thr']
        faded = ~counter & (vb < P['v_thr'])
        wall = ~counter & ~faded & (cb >= P['c_thr'])
        fight = ~counter & ~faded & ~wall
        out.append({'side': name, 'n_side': n_side, 'n': int(b.sum()), 'share_of_side': float(b.sum() / max(n_side, 1)),
                    'стенка': float(wall.mean()), 'иссяк': float(faded.mean()), 'контратака': float(counter.mean()),
                    'драка': float(fight.mean()), 'c_med': float(np.nanmedian(cb)), 'v_med': float(np.nanmedian(vb))})
    return out


def b1_block(D):
    """B1 (справочно): лишний объём следующих 64 баров. Контроли — размеры текущего и следующего окна (и, во втором варианте,
       объём текущего)."""
    W = D['W']
    fok = W['fok']
    if fok.sum() < 1000:
        return None
    Dn = dict(D)
    Dn['y_f'] = np.where(fok, _log(W['n_v']), np.nan)
    ex = control_fwd(W)
    A = a1_block(Dn, ('z', 'ztw'), ys=('y_f',), extra=ex, mask=fok.copy())
    ex2 = np.column_stack([ex, D['y']])
    A2 = a1_block(Dn, ('z', 'ztw'), ys=('y_f',), extra=ex2, mask=fok.copy())
    pack = lambda X: None if X is None else {'n': X['n'], 'z': X['res'][('y_f', 'z')], 'twin': X['res'][('y_f', 'ztw')]}
    return {'sizes': pack(A), 'sizes_and_volume': pack(A2)}


def corr_check(D, R):
    """(0б): корреляция хода окна спота (Σ r) и фьючерса (Σ шагов close в его нормировщике) у каждого ассета; и то же с окном
       фьючерса на бар раньше и на бар позже — при верном времени они коррелируют слабее (окна пересекаются на 63 бара из 64,
       поэтому разница мала, но при сотнях окон видна)."""
    Fs = {int(r['asset'][0]): r['F'] for r in R['rows']}
    L = 64
    out = {}
    for ia in np.unique(D['asset']):
        k = D['asset'] == ia
        res = {'c0': math.nan, 'prev': math.nan, 'next': math.nan}
        if k.sum() >= 100:
            F, j, a = Fs[int(ia)], D['W']['j'][k], D['sp']['r_sum'][k]
            res['c0'] = float(np.corrcoef(a, D['W']['rf'][k])[0, 1])
            for name, d in (('prev', -1), ('next', 1)):
                jj = np.clip(j + d, L - 1, len(F['t']) - 1)
                ok = (j + d == jj) & (F['run0'][jj] <= jj - (L - 1))      # все 64 бара сдвинутого окна годны и подряд
                if ok.sum() >= 100:
                    res[name] = float(np.corrcoef(a[ok], _wsum(F, 'rf', jj[ok] - (L - 1), jj[ok]))[0, 1])
        out[int(ia)] = res
    return out


def shifted(lag):
    """Ассеты, у которых окно фьючерса на бар раньше или позже коррелирует со спотом не слабее своего (время сдвинуто)."""
    return [a for a, x in lag.items() if np.isfinite(x['c0'])
            and max((v for v in (x['prev'], x['next']) if np.isfinite(v)), default=-1.0) >= x['c0']]


def eval_source(T, C, src, FB, part):
    """Всё по одному источнику и ТФ: A1, плацебо, сделки, средняя сделка, BTC, монеты сайта, (3), B1, A2, проверка 2, децили."""
    R = build_rows(T, C, src, FB, part)
    if R is None or not R['rows']:
        return None, None
    D = stack(R)
    lag = {R['assets'][i]: c for i, c in corr_check(D, R).items()}
    corr = {a: x['c0'] for a, x in lag.items()}
    A = a1_block(D, ('z', 'ztw'), ys=('y', 'y_trd', 'y_size'))
    if A is None:
        return None, None
    out = {'tags': R['tags'], 'cover': R['cover'], 'corr': corr, 'corr_lag': lag, 'rows': A['n'], 'fe_iter': A['fe_iter'], 'fe_ok': A['fe_ok'],
           'a1': A['res'][('y', 'z')], 'placebo': A['res'][('y', 'ztw')],
           'trades': A['res'][('y_trd', 'z')], 'trade_size': A['res'][('y_size', 'z')],
           'weeks': int(len(np.unique(D['wk'][A['mask']]))),
           't_from': str(pd.Timestamp(int(D['t'].min()))), 't_to': str(pd.Timestamp(int(D['t'].max())))}
    ia = {a: i for i, a in enumerate(R['assets'])}
    sub = {}
    for name, assets in (('BTC', ('BTCUSDT',)), ('сайт', FLOW['site'])):
        msk = np.isin(D['asset'], [ia[a] for a in assets if a in ia])
        if msk.sum() >= 1000:
            X = a1_block(D, ('z', 'ztw'), mask=msk)
            sub[name] = None if X is None else {'n': X['n'], 'z': X['res'][('y', 'z')], 'twin': X['res'][('y', 'ztw')]}
    out['subsets'] = sub
    out['claim'] = claim_block(D, A)
    out['b1'] = b1_block(D)
    out['a2'] = a2_block(D, A, R)
    out['check2'] = check2_block(D, R)
    m = A['mask']
    out['deciles'] = {'real': deciles(D['z'][m], A['e']['y']), 'twin': deciles(D['ztw'][m], A['e']['y'])}
    keep = {'D': D, 'A': A, 'R': R}
    return out, keep


def verdict_tf(res):
    """(1)–(3) по ТФ."""
    s, c = res.get('search'), res.get('confirm')
    if not s or not c:
        return {'verdict': 'нет данных', 'why': 'нет поиска или подтверждения'}
    ps, pc = s['placebo']['t'], c['placebo']['t']
    ok_pl = bool(abs(ps) < FLOW['t_placebo'] and abs(pc) < FLOW['t_placebo'])
    ts, tc = s['a1']['t'], c['a1']['t']
    out = {'placebo_ok': ok_pl, 't_search': ts, 't_confirm': tc, 't_placebo_search': ps, 't_placebo_confirm': pc}
    if not ok_pl:
        out.update({'verdict': 'не читается', 'why': 'плацебо-близнец не ноль: модель «нормального» объёма упускает размеры баров'})
        return out
    if abs(ts) >= FLOW['t_search'] and np.sign(tc) == np.sign(ts) and abs(tc) >= FLOW['t_confirm']:
        sign = '+' if ts > 0 else '−'
        out['verdict'] = sign
        out['why'] = ("оранжевым движениям сопротивлялись: при тех же размерах баров проторговано больше" if sign == '+' else
                      "синий ход толкает тяжёлый поток, оранжевая пила — тихий рынок")
        cl = c['claim']
        if (cl['n_orange'] < FLOW['claim_min_n'] or cl['n_blue'] < FLOW['claim_min_n']
                or cl['weeks_orange'] < FLOW['claim_min_weeks'] or cl['weeks_blue'] < FLOW['claim_min_weeks']):
            out['claim'] = 'мало данных'
        else:
            p = cl['pct']
            out['claim'] = 'да' if (p >= FLOW['claim_pct'] if sign == '+' else p <= -FLOW['claim_pct']) else 'нет'
    else:
        out.update({'verdict': '0', 'why': 'цвет с сопротивлением рынка не связан (на этой мощности)'})
    return out


