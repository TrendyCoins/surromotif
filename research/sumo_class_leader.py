                M['naive'], M['nohour'], M['rich'], M['fav'] = {}, {}, {}, {}
                mR, yR = _sel(R, ip, 'hit', jm)
                for q in QS:
                    M['naive'][q] = d_stat(B, tabs, z1, q, 'hit', jm, ip, with_p=False)
                    M['nohour'][q] = d_stat(B, tabs, shb if q == 'D3' else sh, q, 'hit', jm, ip, with_p=False)
                    M['rich'][q] = d_stat(B, tabs, sr, q, 'hit', jm, ip, with_p=False)
                    M['fav'][q] = {sg: CC.group_mean(B, R['wk'], yR, mR & fav_mask(R, q, sg)) for sg in (1, -1)}
                e = math.log(LD['mark'])
                M['btc_grey'] = d_stat(B, tabs, st, 'D1', 'hit', jm, ip,
                                       extra=lambda T_: np.asarray(T_['lmb'], dtype=np.float64) <= -e, with_p=False)
                M['noskip_D'] = {q: d_stat(B, tabs, sq[q], q, 'h0', jm, ip, with_p=False) for q in QS}
