def piece_base(P, ctx, LF, prof, tf, bar_ns):
    """Общее у реала и случайных рынков куска альта: годность (Classic.piece_ctx и живые бары t, t + 1), период, неделя, vl,
       группа часа; BTC по времени — на баре t (лидер) и на 7, 14, 21 сутки раньше (плацебо): x, цвет; vl BTC, ход BTC после
       входа; β̂ и log close реала (для «пары»)."""
    T = np.asarray(P['T'], dtype=np.int64)
    n = len(T)
    ir, okr = lookup(LF['T'], T)
    w = np.asarray(P['h'], dtype=np.float64) > np.asarray(P['l'], dtype=np.float64)
    B = {'good': ctx['good'], 'per': ctx['per'], 'wk': ctx['wk'], 'vl': ctx['vl'], 'hg': hour_groups(T, prof, tf),
         'alive': w & np.r_[w[1:], False], 'btc': okr}
    for k in LD['k']:
        B[f'x_btc{k}'] = take(LF[f'x{k}'], ir, okr)
    B['lm_btc'] = take(LF['lm'], ir, okr)
    for ld, days in zip(PLAC, LD['shift_days']):
        ip, okp = lookup(LF['T'], T - days * DAY_NS)
        for k in LD['k']:
            B[f'x_{ld}{k}'] = take(LF[f'x{k}'], ip, okp)
        B[f'lm_{ld}'] = take(LF['lm'], ip, okp)
    B['vlb'] = take(LF['vl'], ir, okr)
    for h in LD['h']:
        B[f'Fb{h}'] = take(LF[f'F{h}'], ir, okr)
    lc = np.log(np.asarray(P['c'], dtype=np.float64))
    ra = np.full(n, np.nan)
    ra[1:] = np.where(np.diff(T) == bar_ns, np.diff(lc), np.nan)
    B['beta'] = rolling_beta(ra, take(LF['r'], ir, okr))
    B['lc'] = lc
    return B


def to_hit(ok, mv):
    """1 — ход по ставке, 0 — против, −1 — исхода нет (ровно на месте, конец ряда, дыра во времени)."""
    return np.where(ok & (mv > 0), 1, np.where(ok & (mv < 0), 0, -1)).astype(np.int8)


def move_hit(c, T, s, h, d, bar_ns):
    """Исход ставки d: цена от бара s до s + h (без дыры во времени)."""
    n = len(c)
    e = s + h
    ok = e < n
    ee, ss = np.minimum(e, n - 1), np.minimum(s, n - 1)
    ok &= (T[ee] - T[ss]) == h * bar_ns
    return to_hit(ok, d * (c[ee] - c[ss]))


def market_events(Pm, B, lm, k, ld, real, bar_ns, keep_t=False):
    """События одного рынка альта (реал или случайный) с лидером ld ('btc' — BTC на баре t, 'p0' / 'p1' / 'p2' — BTC на 7 / 14 /
       21 сутки раньше) при ходе за k баров. Таблица: per, wk, hg — период, неделя, группа часа; vl, vlb — вола альта и BTC; u — свой ход альта
       по ставке, ax — сила |x|; lm — цвет альта (NaN — нет), lmb — цвет лидера; hit — исход с пропуском бара (события ×
       горизонты), h0 — без пропуска, hp — «пара», hb — BTC по ставке (у случайного рынка и плацебо hp / hb — где не считаются,
       −1). keep_t — ещё бары t и ставки d (стенд)."""
    c = np.asarray(Pm['c'], dtype=np.float64)
    T = np.asarray(Pm['T'], dtype=np.int64)
    n = len(c)
    y = kmove(c, T, Pm['atr'], k, bar_ns)
    x = B[f'x_{ld}{k}']
    with np.errstate(invalid='ignore'):
        m = B['good'] & B['alive'] & (B['per'] >= 0) & (np.abs(x) >= LD['x0']) & (np.abs(y) < LD['y0'])
    t = np.flatnonzero(m)
    d = np.sign(x[t])
    nh = len(LD['h'])
    hit, h0, hp, hb = (np.full((len(t), nh), -1, dtype=np.int8) for _ in range(4))
    for j, h in enumerate(LD['h']):
        hit[:, j] = move_hit(c, T, t + 1, h, d, bar_ns)
        h0[:, j] = move_hit(c, T, t, h, d, bar_ns)
        if real:
            Fb = B[f'Fb{h}'][t]
            s, e = t + 1, t + 1 + h
            ok = e < n
            ee, ss = np.minimum(e, n - 1), np.minimum(s, n - 1)
            ok &= (T[ee] - T[ss]) == h * bar_ns
            with np.errstate(invalid='ignore'):
                res = (B['lc'][ee] - B['lc'][ss]) - B['beta'][t] * Fb
                hp[:, j] = to_hit(ok & np.isfinite(res), d * np.where(np.isfinite(res), res, 0.0))
                if ld == 'btc':
                    hb[:, j] = to_hit(np.isfinite(Fb), d * np.where(np.isfinite(Fb), Fb, 0.0))
    lmv = np.full(len(t), np.nan) if lm is None else np.asarray(lm, dtype=np.float64)[t]
    tab = {'per': B['per'][t], 'wk': B['wk'][t], 'hg': B['hg'][t], 'vl': B['vl'][t].astype(np.float32),
           'vlb': B['vlb'][t].astype(np.float32), 'u': (y[t] * d).astype(np.float32), 'ax': np.abs(x[t]).astype(np.float32),
           'lm': lmv.astype(np.float32), 'lmb': B[f'lm_{ld}'][t].astype(np.float32), 'hit': hit, 'h0': h0, 'hp': hp, 'hb': hb}
    if keep_t:
        tab['t'], tab['d'] = t, d
    return tab


def alt_events(ia, bars, rdg, LF, prof, tf, bar_ns, acc, n_r, sign_fn, ks=None, keep_t=False):
    """События альта: реал и случайные рынки 0 … n_r − 1 (знаки — sign_fn(j, кусок, T); у 'run' — rand_signs Levels, те же, что
       в 'score'), у каждого — с настоящим BTC и с тремя плацебо-лидерами (их события — вместе), при всех k; таблицы — в acc[k][(рынок, лидер)] с полями a
       (альт) и mk (0 — реал, j + 1 — случайный рынок j). rdg — показания MRI (None — без цвета). Возвращает сводку: баров в
       периодах и сколько из них не годны (грубая сетка, мёртвый нормировщик или бар, дыра во времени)."""
    info = {'bars': 0, 'dropped': 0}
    for pi, P in enumerate(bars['pieces']):
        ctx = CC.piece_ctx(P, bar_ns)
        B = piece_base(P, ctx, LF, prof, tf, bar_ns)
        inper = ctx['per'] >= 0
        info['bars'] += int(inper.sum())
        info['dropped'] += int((inper & ~(ctx['good'] & B['alive'])).sum())
        for mk in range(1 + n_r):
            if mk == 0:
                Pm, lm = P, (None if rdg is None else rdg['real'][pi]['lm'])
            else:
                Pm = LV.mirror_bars(P, sign_fn(mk - 1, pi, P['T']))
                lm = None if rdg is None else rdg['rand'][mk - 1][pi]['lm']
            for k in (ks or LD['k']):
                for si, ld in enumerate(('btc',) + PLAC):
                    tab = market_events(Pm, B, lm, k, ld, mk == 0, bar_ns, keep_t)
                    tab['a'] = np.full(len(tab['per']), ia, dtype=np.int16)
                    tab['mk'] = np.full(len(tab['per']), mk, dtype=np.int8)
                    tab['sh'] = np.full(len(tab['per']), si, dtype=np.int8)      # 0 — BTC, 1 … — плацебо по сдвигам
                    acc[k][('real' if mk == 0 else 'rand', 'btc' if ld == 'btc' else 'plac')].append(tab)
    return info


