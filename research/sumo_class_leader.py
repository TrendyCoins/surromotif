def lookup(Ts, T):
    """Индекс бара с тем же временем в отсортированном ряду Ts и есть ли он."""
    T = np.asarray(T, dtype=np.int64)
    idx = np.searchsorted(Ts, T)
    ok = idx < len(Ts)
    ok[ok] = Ts[idx[ok]] == T[ok]
    return np.where(ok, idx, 0), ok


def take(x, idx, ok):
    out = np.full(len(idx), np.nan)
    out[ok] = np.asarray(x, dtype=np.float64)[idx[ok]]
    return out


def kmove(c, T, atr, k, bar_ns):
    """Ход за k баров в ATR бара: (c_t − c_(t−k)) / (√k · ATR_t); NaN — дыра во времени внутри k баров или ATR не годен."""
    c = np.asarray(c, dtype=np.float64)
    out = np.full(len(c), np.nan)
    if len(c) > k:
        a = np.asarray(atr, dtype=np.float64)[k:]
        cont = (T[k:] - T[:-k]) == k * bar_ns
        with np.errstate(invalid='ignore', divide='ignore'):
            out[k:] = np.where(cont & (a > 0), (c[k:] - c[:-k]) / (math.sqrt(k) * a), np.nan)
    return out


def fmove(lc, T, h, bar_ns):
    """log-ход от бара t + 1 до t + 1 + h (вход на close t + 1); NaN — конец ряда или дыра во времени."""
    n = len(lc)
    out = np.full(n, np.nan)
    s = np.arange(n) + 1
    e = s + h
    ok = e < n
    if ok.any():
        ok[ok] = (T[e[ok]] - T[s[ok]]) == h * bar_ns
        out[ok] = lc[e[ok]] - lc[s[ok]]
    return out


def leader_frame(bars, rd, bar_ns):
    """BTC на своей сетке (куски подряд по времени): ход за k баров x (все k), log-ход шага r, ход после входа F (все h), vl,
       цвет lm и z (rd — показания реала; None — без цвета)."""
    parts = []
    for pi, P in enumerate(bars['pieces']):
        T = np.asarray(P['T'], dtype=np.int64)
        n = len(T)
        atr = np.where(np.asarray(P['live'], dtype=bool), P['atr'], np.nan)
        out = {'T': T}
        for k in LD['k']:
            out[f'x{k}'] = kmove(P['c'], T, atr, k, bar_ns)
        lc = np.log(np.asarray(P['c'], dtype=np.float64))
        r = np.full(n, np.nan)
        r[1:] = np.where(np.diff(T) == bar_ns, np.diff(lc), np.nan)
        out['r'] = r
        for h in LD['h']:
            out[f'F{h}'] = fmove(lc, T, h, bar_ns)
        out['vl'] = CC.vol_level(P)
        for key in ('lm', 'z'):
            out[key] = (np.asarray(rd['real'][pi][key], dtype=np.float64) if rd is not None else np.full(n, np.nan))
        parts.append(out)
    LF = {k: np.concatenate([p[k] for p in parts]) for k in parts[0]}
    if np.any(np.diff(LF['T']) <= 0):
        raise ValueError("🍆 АЙ, ОШИБКА! куски BTC перекрываются по времени")
    return LF


def rolling_beta(ra, rb):
    """β̂ на баре t — наклон log-ходов альта ra на log-ходы BTC rb по барам t − beta_lag − beta_win + 1 … t − beta_lag (только
       пары, где есть оба хода; не меньше половины окна)."""
    W, lag = LD['beta_win'], LD['beta_lag']
    n = len(ra)
    v = np.isfinite(ra) & np.isfinite(rb)
    a, b = np.where(v, ra, 0.0), np.where(v, rb, 0.0)

    def cs(x):
        return np.r_[0.0, np.cumsum(x)]
    Cn, Ca, Cb, Cab, Cbb = cs(v.astype(np.float64)), cs(a), cs(b), cs(a * b), cs(b * b)
    t = np.arange(n)
    hi = t - lag + 1
    lo = hi - W
    ok = lo >= 0
    hi_, lo_ = np.clip(hi, 0, n), np.clip(lo, 0, n)

    def S(C):
        return np.where(ok, C[hi_] - C[lo_], 0.0)
    nn, sa, sb, sab, sbb = S(Cn), S(Ca), S(Cb), S(Cab), S(Cbb)
    with np.errstate(invalid='ignore', divide='ignore'):
        var = sbb - sb * sb / nn
        cov = sab - sa * sb / nn
        return np.where(ok & (nn >= W / 2) & (var > 0), cov / var, np.nan)


