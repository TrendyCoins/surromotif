def stand_worlds(check):
    """(ст3) миры: правила на синтетике."""
    S_ = STAND
    print(f"\n🧪 (ст3) миры: {S_['alts']} альтов и BTC, бары {S_['bar_min']} мин, 2 периода по {S_['weeks']} нед.; «лидер», «лидер по "
          f"цвету» — {S_['seeds_plus']} сидов, «быстрый лидер», «вола и часы», «ноль» — {S_['seeds_null']}")
    tally = {}
    for kind, n_s, base in (('lead', S_['seeds_plus'], 0), ('color', S_['seeds_plus'], 100), ('fast', S_['seeds_null'], 200),
                            ('confound', S_['seeds_null'], 300), ('zero', S_['seeds_null'], 400)):
        t1 = time.time()
        rows = [world_row(world_eval(kind, s)) for s in range(base, base + n_s)]
        tally[kind] = rows
        cnt = lambda f: (sum(f(r) > 0 for r in rows), sum(f(r) < 0 for r in rows))
        c0 = cnt(lambda r: r['c0'])
        cq = {q: cnt(lambda r, q=q: r['ci'][q]) for q in QS}
        ya = {q: sum(r['ya'][q] for r in rows) for q in QS}
        ph = {q: sum(r['phrase'][q] for r in rows) for q in QS}
        print(f"   {kind:<8}: (Ц0) + / − {c0[0]}/{c0[1]} | " + ', '.join(f"{q} {a}/{b} (Я {ya[q]}, Ф {ph[q]})" for q, (a, b) in cq.items())
              + f" | наивно D1 ≠0: {sum(r['naive'] != 0 for r in rows)} | без пропуска L(h 3) +: {sum(r['noskip3'] > 0 for r in rows)}"
              + f" | (0) {sum(r['ok0'] for r in rows)}/{n_s} | медианы, п.п.: L {100 * np.nanmedian([x for r in rows for x in r['L']]):+.1f}, "
              + ', '.join(f"{q} {100 * np.nanmedian([x for r in rows for x in r['D'][q]]):+.1f}" for q in QS)
              + f" | событий BTC / плацебо (поиск) ~{rows[0]['n'].get('R', 0)} / {rows[0]['n'].get('P', 0)} | {time.time() - t1:.0f} c",
              flush=True)
    need, fm = S_['need'], S_['false_max']
    ld_, co, fa, cf, ze = (tally[k] for k in ('lead', 'color', 'fast', 'confound', 'zero'))
    check(f"«лидер»: (Ц0) с плюсом хотя бы в {need} из {S_['seeds_plus']}", sum(r['c0'] > 0 for r in ld_) >= need,
          f"{sum(r['c0'] > 0 for r in ld_)}")
    okc = all(sum(r['ci'][q] > 0 and r['ya'][q] for r in co) >= need for q in QS) and sum(r['phrase']['D1'] for r in co) >= need
    check(f"«лидер по цвету»: (Ц1), (Ц2), (Ц3) с плюсом и (Я) хотя бы в {need} из {S_['seeds_plus']} у каждого, (Ф) у D1 — тоже",
          okc, ', '.join(f"{q} {sum(r['ci'][q] > 0 and r['ya'][q] for r in co)}" for q in QS)
          + f"; (Ф) D1 {sum(r['phrase']['D1'] for r in co)}")
    check(f"«быстрый лидер»: ложных (Ц0) не больше {fm} из {S_['seeds_null']}, а без пропуска бара L (h 3) «видит» хотя бы в "
          f"{S_['trap_min']} (ловушка)", sum(r['c0'] != 0 for r in fa) <= fm and sum(r['noskip3'] > 0 for r in fa) >= S_['trap_min'],
          f"ложных {sum(r['c0'] != 0 for r in fa)}; без пропуска {sum(r['noskip3'] > 0 for r in fa)}")
    fq = {q: sum(r['ci'][q] != 0 for r in cf) for q in ('D1', 'D3')}
    fph = sum(any(r['phrase'].values()) for r in cf)
    check(f"«вола и часы»: ложных (Ц1) и (Ц3) не больше {fm} из {S_['seeds_null']}, ложных (Ф) — не больше {fm}, а наивное D1 «видит» "
          f"хотя бы в {S_['trap_min']} (ловушка)",
          all(v <= fm for v in fq.values()) and fph <= fm and sum(r['naive'] != 0 for r in cf) >= S_['trap_min'],
          f"ложных {fq}, (Ф) {fph}; наивно {sum(r['naive'] != 0 for r in cf)}")
    fz = {'Ц0': sum(r['c0'] != 0 for r in ze), **{QS[q][0]: sum(r['ci'][q] != 0 for r in ze) for q in QS}}
    zl = np.array([x for r in ze for x in r['z_l'] if np.isfinite(x)])
    zd = np.array([x for r in ze for x in r['z_d'] if np.isfinite(x)])
    lo_, hi_ = S_['calib']
    sl, sd = (float(np.std(v, ddof=1)) if len(v) > 1 else math.nan for v in (zl, zd))
    check(f"«ноль»: ложных (Ц0)–(Ц3) не больше {fm} из {S_['seeds_null']} у каждого; разброс L / ошибка и D / ошибка — от {lo_:g} до "
          f"{hi_:g}", all(v <= fm for v in fz.values()) and lo_ <= sl <= hi_ and lo_ <= sd <= hi_,
          f"ложных {fz}; разброс L {sl:.2f} ({len(zl)}), D {sd:.2f} ({len(zd)})")
    allr = [r for rows in tally.values() for r in rows]
    share = np.mean([r['ok0'] for r in allr])
    check(f"контроль (0) случайного рынка проходит хотя бы в {100 * S_['ctrl_min']:.0f}% миров", share >= S_['ctrl_min'],
          f"{sum(r['ok0'] for r in allr)} / {len(allr)}")
    return tally


