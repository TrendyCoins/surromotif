def week_bars():
    return 7 * 1440 // STAND['bar_min']


def stand_prof():
    """Разметка часов недели стенда: тонкие — 00–07 UTC, ликвидные — 12–19 UTC (как запасная разметка стенда Eff)."""
    how = np.arange(168)
    return {'ok': True, 'weeks': 0, 'thin': how[how % 24 < 8], 'liquid': how[(how % 24 >= 12) & (how % 24 < 20)]}


def regimes(rng, n):
    """Режим «вкл / выкл» мира: отрезки геометрической длины, в среднем reg_len баров «вкл», доля «вкл» — reg_share (как
       Classic.regimes, но с параметрами этого стенда)."""
    S_ = STAND
    reg = np.zeros(n, dtype=bool)
    i, on = 0, rng.random() < S_['reg_share']
    while i < n:
        mean = S_['reg_len'] if on else S_['reg_len'] * (1 - S_['reg_share']) / S_['reg_share']
        ln = int(rng.geometric(1.0 / mean))
        reg[i:i + ln] = on
        i += ln
        on = not on
    return reg


def world_series(kind, seed):
    """Мир (ст3): BTC и альты (synth_ohlc Levels) на общей сетке баров 15 мин; вола кучами общая. Альт — β · ход BTC: доля w0
       сразу, остаток копится в разрыв G и закрывается на γ за бар (A_t = β · B_t − G_t); у «быстрого лидера» остаток — ровно
       через бар; у «ноля» — всё сразу. Плюс свой шум (корреляция шага с BTC ~rho). Возвращает (BTC, [альты], сведения: режим,
       тонкие часы, бурные бары)."""
    S_ = STAND
    rng = np.random.default_rng([seed, 5])
    bar_ns = S_['bar_min'] * 60 * 10 ** 9
    n = S_['warm'] + 2 * S_['weeks'] * week_bars()
    T = LV.ns(S_['t0']) + bar_ns * np.arange(n, dtype=np.int64)
    lv = lfilter([1.0], [1.0, -S_['vol_rho']], rng.normal(0, S_['vol_eps'], n))
    sig = np.exp(lv - lv.mean())
    b = sig * S_['sigma'] * rng.standard_normal(n)
    thin = (EF.hour_of_week(T) % 24) < 8
    hiv = sig > np.quantile(sig, 2.0 / 3.0)
    reg = regimes(rng, n) if kind == 'color' else np.zeros(n, dtype=bool)
    if kind == 'confound':
        w_on = np.where(thin, S_['w0_thin'], np.where(hiv, S_['w0_vol'], 1.0))
        on = w_on < 1.0
    else:
        on = {'lead': np.ones(n, dtype=bool), 'color': reg}.get(kind, np.zeros(n, dtype=bool))
        w_on = {'lead': S_['w0'], 'color': S_['w0_color']}.get(kind, 1.0)
    alts = []
    for i in range(S_['alts']):
        beta = rng.uniform(*S_['beta'])
        sd_id = beta * S_['sigma'] * math.sqrt(1.0 / S_['rho'] ** 2 - 1.0)
        idio = sig * sd_id * rng.standard_normal(n)
        if kind == 'fast':
            w0 = S_['w0_fast']
            steps = beta * (w0 * b + (1.0 - w0) * np.r_[0.0, b[:-1]]) + idio
        else:
            share = np.where(on, w_on, 1.0)
            g = S_['gamma']
            G = lfilter([1.0], [1.0, -(1.0 - g)], beta * (1.0 - share) * b)
            steps = beta * share * b + g * np.r_[0.0, G[:-1]] + idio
        sd_a = math.sqrt(beta ** 2 * S_['sigma'] ** 2 + sd_id ** 2)
        alts.append(LV.synth_ohlc(steps, rng, sig * sd_a, S_['wick'], t0=S_['t0'], bar_ns=bar_ns))
    Pb = LV.synth_ohlc(b, rng, sig * S_['sigma'], S_['wick'], t0=S_['t0'], bar_ns=bar_ns)
    return Pb, alts, {'reg': reg, 'thin': thin, 'hiv': hiv}


def window_ac1(r, L=64):
    """AC1 окон шагов длины L (окно j — шаги j … j + L − 1, кончается на баре j + L) накопленными суммами: Σ (x_i − μ)(x_(i+1) − μ) /
       Σ (x_i − μ)² — как proxy стенда Classic на матрице окон."""
    r = np.asarray(r, dtype=np.float64)
    nw = len(r) - L + 1
    c1, c2 = np.r_[0.0, np.cumsum(r)], np.r_[0.0, np.cumsum(r * r)]
    cp = np.r_[0.0, np.cumsum(r[:-1] * r[1:])]
    j = np.arange(nw)
    s1, s2 = c1[j + L] - c1[j], c2[j + L] - c2[j]
    sp = cp[j + L - 1] - cp[j]
    mu = s1 / L
    num = sp - mu * (2 * s1 - r[j] - r[j + L - 1]) + (L - 1) * mu * mu
    den = s2 - L * mu * mu
    return np.where(den > 0, num / np.where(den > 0, den, 1.0), 0.0)


def proxy(kind, r, info, rng, know=True, btc=False):
    """MRI-заменитель (ст3) по шагам close r (окна по 64 шага; окно j кончается на баре j + 64): «лидер по цвету» — знание
       режима; «вола и часы» — знание тонкого часа и бурного бара; «быстрый лидер» — ничего; «лидер», «ноль» — −AC1 окна. know=False — без знания (суррогаты
       линейки). Плюс шум (у BTC в «лидере по цвету» — больше)."""
    S_ = STAND
    L = CC.CL['win']
    nw = len(r) - L + 1
    noise = S_['px_noise_btc'] if (btc and kind == 'color') else S_['px_noise']
    if kind == 'fast':                                           # MRI ничего не знает: цвет — шум (нужен лишь контролю (0))
        lg = np.zeros(nw)
    elif kind == 'color':
        lg = S_['px_reg'] * (info['reg'][L:].astype(np.float64) if know else np.zeros(nw))
    elif kind == 'confound':
        lg = ((S_['px_hour'] * info['thin'][L:].astype(np.float64) + S_['px_vol'] * info['hiv'][L:].astype(np.float64)) if know
              else np.zeros(nw))
    else:
        lg = -S_['px_ac'] * window_ac1(r, L)
    return lg + rng.normal(0, noise, len(lg))


def world_events(kind, seed, ks=None):
    """Мир (ст3) целиком до таблиц событий: ряды, заменители MRI (реал; суррогаты линейки — знак каждого шага монетка, без знания;
       случайные рынки — та же функция на их окнах, у знания режима — то же знание), линия M, события альтов с BTC и плацебо. LEV['tune_start'] / ['val_start'] на время
       мира — границы его периодов (вызывающий восстанавливает LEV). Возвращает (E, число альтов)."""
