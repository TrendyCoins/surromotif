        if ic == 0:
            lg_rand.append(None)
            signs.append(None)
            continue
        sg_a, lr_a = [], []
        for j in range(n_r):
            sg = LV.rand_signs(f"WA{ic}", j, 0, P['T'], rand_from=T0[0])
            sg_a.append(sg)
