def u_bin(u, nu):
    """Часть своего хода альта u: nu равных частей интервала (−y0; y0); вне — −1."""
    y0 = LD['y0']
    u = np.asarray(u, dtype=np.float64)
    with np.errstate(invalid='ignore'):
        ok = np.isfinite(u) & (u > -y0) & (u < y0)
        b = np.floor((np.where(ok, u, 0.0) + y0) / (2 * y0) * nu).astype(np.int64)
    return np.where(ok, np.clip(b, 0, nu - 1), -1)


def cuts_of(R, ip, tf):
    """Границы частей силы |x| и vl (и подробных слоёв) — по событиям с настоящим BTC периода."""
    m = R['per'] == ip
    return {'x': CC.qcuts(R['ax'][m], LD['n_x'][tf]), 'vl': CC.qcuts(R['vl'][m], LD['n_vl'][tf]),
            'vlb': CC.qcuts(R['vlb'][m], LD['n_vl'][tf]),
            'vl_r': CC.qcuts(R['vl'][m], LD['rich'][0]), 'vlb_r': CC.qcuts(R['vlb'][m], LD['rich'][1])}


def strata(T_, cu, tf, na, rich=False, hours=True, vol='vl'):
    """Слой события: монета × часть u × часть |x| × часть волы (vol: 'vl' — альта, 'vlb' — BTC) × группа часа; rich — подробные
       слои (Ф): u на rich_u частей, vl альта на rich[0], × часть vl BTC (rich[1]); без hours — без групп часа; −1 — без слоя.
       Возвращает (слои, их число)."""
    nu = LD['rich_u'] if rich else LD['n_u'][tf]
    nx, ng = LD['n_x'][tf], (LD['n_hg'][tf] if hours else 1)
    nv = LD['rich'][0] if rich else LD['n_vl'][tf]
    ub, xb = u_bin(T_['u'], nu), CC.qbin(T_['ax'], cu['x'])
    vb = CC.qbin(T_['vl'], cu['vl_r']) if rich else CC.qbin(T_[vol], cu[vol])
    hg = T_['hg'].astype(np.int64) if hours else np.zeros(len(ub), dtype=np.int64)
    s = (((T_['a'].astype(np.int64) * nu + ub) * nx + xb) * nv + vb) * ng + hg
    ok = (ub >= 0) & (xb >= 0) & (vb >= 0) & (hg >= 0)
    K = na * nu * nx * nv * ng
    if rich:
        bb = CC.qbin(T_['vlb'], cu['vlb_r'])
        s, ok, K = s * LD['rich'][1] + bb, ok & (bb >= 0), K * LD['rich'][1]
    return np.where(ok, s, -1), K


def _sel(T_, ip, key, j, extra=None):
    """Маска событий периода с исходом и сам исход (float)."""
    y = T_[key][:, j]
    m = (T_['per'] == ip) & (y >= 0)
    if extra is not None:
        m = m & extra(T_)
    return m, y.astype(np.float64)


def occupy(G, names):
    """Правило заселённости: слой участвует, если у каждой группы names события хотя бы в min_weeks разных неделях периода; у
       остальных слоёв все группы обнуляются. Иначе бутстреп по неделям не видит разброса редких событий (среднее одного-двух
       событий в повторах почти не меняется) и занижает ошибку."""
    ok = np.ones(G[names[0]][0].shape[1], dtype=bool)
    for g in names:
        ok &= (G[g][0] > 0).sum(0) >= LD['min_weeks']
    return {g: (n * ok, sm * ok) for g, (n, sm) in G.items()}


def lin(B, G, expr, ref):
    """lin_stat Levels по заселённым слоям групп выражения."""
    return LV.lin_stat(B, occupy(G, [g for _, g in expr]), expr, ref)


def contrast(B, R, X, yr, yx, mr, mx, sr, sx, K, cr, cx):
    """D = Σ_s w_s (ȳ_A,s − ȳ_B,s) у реала (таблица R) и у случайного рынка (X; None — без него), A, B — маски cr / cx, веса —
       события реала обоих сторон — как Classic.contrast, плюс правило заселённости (у Dx — по группам случайного рынка)."""
    ra, rb = cr
    G = {'RA': CC.counts(B, R['wk'], sr, yr, K, mr & ra), 'RB': CC.counts(B, R['wk'], sr, yr, K, mr & rb)}
    out = {'D': lin(B, G, [(1, 'RA'), (-1, 'RB')], ['RA', 'RB'])}
    if X is not None:
        xa, xb = cx
        G['XA'] = CC.counts(B, X['wk'], sx, yx, K, mx & xa)
        G['XB'] = CC.counts(B, X['wk'], sx, yx, K, mx & xb)
        out['Dx'] = lin(B, G, [(1, 'XA'), (-1, 'XB')], ['RA', 'RB'])
    return out


def l_stat(B, tabs, st, key, j, ip, extra=None):
    """L = Σ_s w_s (ȳ_R,s − ȳ_P,s) — события с настоящим BTC (R) против плацебо (P), веса — события R; Lx — то же у случайного
       рынка (XR против XP, веса — те же события R); слои — заселённые."""
    G = {}
    for g, T_ in tabs.items():
        if T_ is None or (key in ('hp', 'hb') and g in ('XR', 'XP')):      # у случайного рынка «пары» нет
            continue
        m, y = _sel(T_, ip, key, j, extra)
        G[g] = CC.counts(B, T_['wk'], st[g][0], y, st[g][1], m)
    out = {}
    if 'R' in G and 'P' in G:
        out['L'] = lin(B, G, [(1, 'R'), (-1, 'P')], ['R'])
    if 'R' in G and 'XR' in G and 'XP' in G:
        out['Lx'] = lin(B, G, [(1, 'XR'), (-1, 'XP')], ['R'])
    return out


def q_masks(T_, q):
    """Сравниваемые маски вопроса q у таблицы (A — плюс D, B — минус) и отбор событий (None — все)."""
    e = math.log(LD['mark'])
    with np.errstate(invalid='ignore'):
        if q == 'D1':
            return CC.colors(T_['lm']), None
        if q == 'D2':
            return CC.colors(T_['lm']), np.asarray(T_['lmb'], dtype=np.float64) >= e
        return CC.colors(T_['lmb']), None


def d_stat(B, tabs, st, q, key, j, ip, extra=None, with_p=True):
    """D вопроса q: у событий с настоящим BTC (D) и у случайного рынка (Dx; веса — события реала); у плацебо-лидера (Dp) и
       E = D − Dp (веса — события реала обоих сторон); слои — заселённые."""
    def prep(T_):
        m, y = _sel(T_, ip, key, j, extra)
        cm, sel = q_masks(T_, q)
        return (m & sel if sel is not None else m), y, cm
    R, X, P = tabs['R'], tabs.get('XR'), tabs.get('P')
    mR, yR, cR = prep(R)
    sR, K = st['R']
    if X is not None:
        mX, yX, cX = prep(X)
        out = contrast(B, R, X, yR, yX, mR, mX, sR, st['XR'][0], K, cR, cX)
    else:
        out = contrast(B, R, None, yR, None, mR, None, sR, None, K, cR, None)
    if with_p and P is not None:
        mP, yP, cP = prep(P)
        sP = st['P'][0]
        out['Dp'] = contrast(B, P, None, yP, None, mP, None, sP, None, K, cP, None)['D']
        G = {'RO': CC.counts(B, R['wk'], sR, yR, K, mR & cR[0]), 'RG': CC.counts(B, R['wk'], sR, yR, K, mR & cR[1]),
             'PO': CC.counts(B, P['wk'], sP, yP, K, mP & cP[0]), 'PG': CC.counts(B, P['wk'], sP, yP, K, mP & cP[1])}
        out['E'] = lin(B, G, [(1, 'RO'), (-1, 'RG'), (-1, 'PO'), (1, 'PG')], ['RO', 'RG'])
    return out


def fav_mask(T_, q, sg):
    """Выгодная сторона вопроса q при знаке D (для (Ф)): у D1 — цвет альта, у D2 — согласие / расхождение при оранжевом BTC, у D3
       — цвет BTC."""
    (a_, b_), sel = q_masks(T_, q)
    m = a_ if sg > 0 else b_
    return m & sel if sel is not None else m


def boot_sets(E, n_boot, seed):
    """Повторы бутстрепа по периодам: недели всех событий всех таблиц (все k, реал и случайные рынки, оба лидера) — один
       набор на период."""
    Bs = {}
    for ip, src in enumerate(PERIODS):
        wk = [T_['wk'][T_['per'] == ip] for d in E.values() for T_ in d.values() if T_ is not None]
        wk = np.concatenate(wk) if wk else np.zeros(0, dtype=np.int64)
        Bs[src] = LV.boot_setup(wk, [seed, 43, ip], n_boot)
    return Bs


def _key(k, h, src):
    return f"{k}|{h}|{src}"


def tf_stats(E, na, tf, step1=True, light=False, Bs=None, n_boot=None, seed=None):
    """Статистика ТФ: L на сетке k × h (light — только главное k), D1 на сетке, D2 и D3 при главном k, справочное и правила.
       E[k][(рынок, лидер)] — таблицы событий; na — число альтов."""
    if Bs is None:
        Bs = boot_sets(E, n_boot or LD['n_boot'], LD['seed'] if seed is None else seed)
    km, hm = LD['k_main'], LD['h_main']
    jm = LD['h'].index(hm)
