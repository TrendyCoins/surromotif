    LF = leader_frame({'pieces': [Pb]}, {'real': [{'lm': np.r_[pad, EF.line_parts(zb)[0]], 'z': np.r_[pad, zb]}]}, bar_ns)
    prof = stand_prof()
    ks = ks or (LD['k_main'],)
    acc = {k: {g: [] for g in GROUPS} for k in ks}
    for ia, P in enumerate(alts):
        ic = ia + 1
        z = FL.to_z(lg_real[ic], q, zk)
        rdg = {'real': [{'lm': np.r_[pad, EF.line_parts(z)[0]], 'z': np.r_[pad, z]}],
               'rand': [[{'lm': np.r_[pad, EF.line_parts(z, FL.to_z(lg_rand[ic][j], q, zk))[0]], 'z': None}] for j in range(n_r)]}
        alt_events(ia, {'pieces': [P]}, rdg, LF, prof, '5M', bar_ns, acc, n_r,
                   lambda j, pi, T, sg=signs[ic]: sg[j], ks=ks)
    E = {k: {g: CC.cat(v) for g, v in d.items()} for k, d in acc.items()}
    return E, len(alts)


