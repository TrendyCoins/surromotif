            M['noskip'] = {h: l_stat(B, tabs, st, 'h0', j, ip) for j, h in enumerate(LD['h'])}
            if light:
                if step1:
                    M['naive'] = {}
                    z1 = {g: (np.zeros(len(T_['per']), dtype=np.int64), 1) for g, T_ in tabs.items() if T_ is not None}
                    M['naive']['D1'] = d_stat(B, tabs, z1, 'D1', 'hit', jm, ip, with_p=False)
                    M['rich'], M['fav'] = {}, {}
                    sr = {g: strata(T_, cu, tf, na, rich=True) for g, T_ in tabs.items() if T_ is not None}
                    for q in QS:
                        M['rich'][q] = d_stat(B, tabs, sr, q, 'hit', jm, ip, with_p=False)
                        mR, yR = _sel(R, ip, 'hit', jm)
                        M['fav'][q] = {sg: CC.group_mean(B, R['wk'], yR, mR & fav_mask(R, q, sg)) for sg in (1, -1)}
                S['main'][src] = M
                continue
            M['pair'] = {h: l_stat(B, tabs, st, 'hp', j, ip) for j, h in enumerate(LD['h'])}
            mR, yb = _sel(R, ip, 'hb', jm)
            M['btc_cont'] = CC.group_mean(B, R['wk'], yb, mR)
            nu, nx, ng = LD['n_u'][tf], LD['n_x'][tf], LD['n_hg'][tf]
