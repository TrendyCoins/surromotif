def direct_events(Pa, Pb, prof, k, ld, bar_ns, lm_a, lm_b):
    """События, ставки, поля и исходы — прямым счётом бар за баром (стенд): BTC ищется по времени словарём."""
    Tb = {int(t): i for i, t in enumerate(Pb['T'])}
    ca, cb = np.asarray(Pa['c'], float), np.asarray(Pb['c'], float)
    Ta = np.asarray(Pa['T'], np.int64)
    ctx = CC.piece_ctx(Pa, bar_ns)
    vlb_all = CC.vol_level(Pb)
    how = EF.hour_of_week(Ta)
    n = len(ca)
    rows = []

    def bmove(i, kk):                                   # ход BTC за kk баров до бара i его сетки
        if i - kk < 0 or Pb['T'][i] - Pb['T'][i - kk] != kk * bar_ns:
            return math.nan
        if not (Pb['live'][i] and Pb['atr'][i] > 0):
            return math.nan
        return (cb[i] - cb[i - kk]) / (math.sqrt(kk) * Pb['atr'][i])
    for t in range(n):
        if not (ctx['good'][t] and ctx['per'][t] >= 0):
            continue
        if not (Pa['h'][t] > Pa['l'][t] and t + 1 < n and Pa['h'][t + 1] > Pa['l'][t + 1]):
            continue
        tb = int(Ta[t]) - (0 if ld == 'btc' else LD['shift_days'][PLAC.index(ld)] * DAY_NS)
        if tb not in Tb:
            continue
        x = bmove(Tb[tb], k)
        if not np.isfinite(x) or abs(x) < LD['x0']:
            continue
        if t - k < 0 or Ta[t] - Ta[t - k] != k * bar_ns or not Pa['atr'][t] > 0:
            continue
        y = (ca[t] - ca[t - k]) / (math.sqrt(k) * Pa['atr'][t])
        if not abs(y) < LD['y0']:
            continue
        d = 1.0 if x > 0 else -1.0
        hits, h0s, hbs = [], [], []
        for h in LD['h']:
            s, e = t + 1, t + 1 + h
            if e < n and Ta[e] - Ta[s] == h * bar_ns and ca[e] != ca[s]:
                hits.append(1 if d * (ca[e] - ca[s]) > 0 else 0)
            else:
                hits.append(-1)
            s0, e0 = t, t + h
            if e0 < n and Ta[e0] - Ta[s0] == h * bar_ns and ca[e0] != ca[s0]:
                h0s.append(1 if d * (ca[e0] - ca[s0]) > 0 else 0)
            else:
                h0s.append(-1)
            it = Tb.get(int(Ta[t]))
            f = math.nan
            if it is not None and it + 1 + h < len(cb) and Pb['T'][it + 1 + h] - Pb['T'][it + 1] == h * bar_ns:
                f = math.log(cb[it + 1 + h]) - math.log(cb[it + 1])
            hbs.append(-1 if (ld != 'btc' or not np.isfinite(f) or f == 0) else (1 if d * f > 0 else 0))
        g = 1
        if how[t] in set(prof['thin']):
            g = 0
        elif how[t] in set(prof['liquid']):
            g = 2
        ib = Tb.get(int(Ta[t]))
        rows.append({'t': t, 'd': d, 'u': y * d, 'ax': abs(x), 'hit': hits, 'h0': h0s, 'hb': hbs, 'hg': g,
                     'lm': lm_a[t], 'lmb': lm_b[Tb[tb]], 'vlb': vlb_all[ib] if ib is not None else math.nan})
    return rows


def stand_pair(seed, n=9000, bar_ns=300 * 10 ** 9, gaps=True):
    """Пара рядов для (ст1): BTC и альт с общим фактором; у BTC — дыра во времени (нет 6 баров), у альта — сдвиг времени после
       бара 6000 (дыра)."""
    rng = np.random.default_rng(seed)
    b = rng.standard_normal(n)
    a = 1.2 * b + rng.standard_normal(n)
    a[rng.random(n) < 0.03] = 0.0
    Pb = LV.synth_ohlc(b, rng, np.ones(n), 0.5, t0='2024-06-01 00:00:00', bar_ns=bar_ns)
    Pa = LV.synth_ohlc(a, rng, np.ones(n) * 1.5, 0.5, t0='2024-06-01 00:00:00', bar_ns=bar_ns)
    flat = rng.random(n) < 0.01
    Pa['h'] = np.where(flat, Pa['l'], Pa['h'])          # мёртвые бары (high = low)
    if gaps:
        keep = np.ones(n, dtype=bool)
        keep[3000:3006] = False
        Pb = LV.add_norm({k_: Pb[k_][keep] for k_ in ('T', 'o', 'h', 'l', 'c')})
        Ta = Pa['T'].copy()
        Ta[6000:] += 5 * bar_ns
        Pa = LV.add_norm({'T': Ta, 'o': Pa['o'], 'h': Pa['h'], 'l': Pa['l'], 'c': Pa['c']})
    else:
        Pa = LV.add_norm({k_: Pa[k_] for k_ in ('T', 'o', 'h', 'l', 'c')})
    return Pa, Pb


