def mri_xcorr(pieces_z, LF, bar_ns):
    """Корреляция z BTC на баре T и z альта на баре T + ℓ (ℓ > 0 — альт позже) по периодам: pieces_z — [(T, z, период)] кусков
       альта. Возвращает {период: {ℓ: corr}}."""
    lags = sorted({-l for l in LD['mri_lags']} | {0} | set(LD['mri_lags']))
    out = {}
    for ip, src in enumerate(PERIODS):
        res = {}
        for lag in lags:
            xs, ys = [], []
            for T, z, per in pieces_z:
                m = (per == ip) & np.isfinite(z)
                if not m.any():
                    continue
                zb = take(LF['z'], *lookup(LF['T'], T[m] - lag * bar_ns))
                ok = np.isfinite(zb)
                xs.append(zb[ok])
                ys.append(z[m][ok])
            if xs and sum(len(x) for x in xs) > 100:
                x, y = np.concatenate(xs), np.concatenate(ys)
                res[lag] = float(np.corrcoef(x, y)[0, 1])
            else:
                res[lag] = math.nan
        out[src] = res
    return out


