    jp, npp = smc.RUN_DIR + f"pool/{tag}.json", smc.RUN_DIR + f"pool/{tag}.npz"
    if not (os.path.isfile(jp) and os.path.isfile(npp)):
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет прогона пула {tag} (json + npz) в {smc.RUN_DIR}pool/")
    with open(jp, encoding='utf-8') as fh:
        r = json.load(fh)
    cfg = {**smc.SMC_BASE, **r['cfg']}
    for k in ('head_hidden', 'cnn_dil'):
        if isinstance(cfg.get(k), list):
            cfg[k] = tuple(cfg[k])
    if cfg.get('arch') != 'cnn' or cfg.get('price') != 'multi_g':
        raise ValueError(f"🍆 АЙ, ОШИБКА! {tag}: не RG_den (arch {cfg.get('arch')}, цена {cfg.get('price')})")
    n_ch = smc.N_PATH + smc.N_LEVEL[cfg['price']]
    model, _ = smc.build_model(cfg, torch.randn(16, n_ch, cfg['L'], device=smc.DEVICE), np.random.default_rng(0))
    d = np.load(npp)
    model.load_state_dict({k[3:]: torch.from_numpy(d[k]) for k in d.files if k.startswith('sd_')}, strict=True)
    model.eval()
    return model, r, d


