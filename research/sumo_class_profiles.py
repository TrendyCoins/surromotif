@njit
def _synth_path(sig, ell, mode, strength, Hc, seed):
    """Синтетическая log-цена 5M: шаги ~ N(0, σ_k) с толстым хвостом. mode 1 — тяга к центру масс цен баров с весом
       max(ℓ, 0) за последние Hc баров (подсаженное «притяжение к ℓ⁺»); mode 2 — то же с весом 1 (притяжение к TPO);
       0 — без тяги. Тяга: strength·σ·clip((центр − цена) / (20σ), ±1). High / low — от close и прошлого close."""
    np.random.seed(seed)
    n = sig.shape[0]
    x = np.zeros(n)
    xh = np.zeros(n)
    xl = np.zeros(n)
    prev = math.log(100.0)
    S0 = 0.0
    S1 = 0.0
    for k in range(n):
        mu = 0.0
        if mode > 0 and S0 > 1e-9:
            z = (S1 / S0 - prev) / (20.0 * sig[k])
            if z > 1.0:
                z = 1.0
            elif z < -1.0:
                z = -1.0
            mu = strength * sig[k] * z
        e = np.random.normal()
        if np.random.random() < 0.1:
            e *= 2.5
        xk = prev + mu + sig[k] * e
        x[k] = xk
        xh[k] = max(prev, xk) + abs(np.random.normal()) * 0.4 * sig[k]
        xl[k] = min(prev, xk) - abs(np.random.normal()) * 0.4 * sig[k]
        if mode > 0:
            w = 1.0 if mode == 2 else (ell[k] if ell[k] > 0.0 else 0.0)
            S0 += w
            S1 += w * xk
            if k >= Hc:
                kk = k - Hc
                w2 = 1.0 if mode == 2 else (ell[kk] if ell[kk] > 0.0 else 0.0)
                S0 -= w2
                S1 -= w2 * x[kk]
        prev = xk
    return x, xh, xl


def synth_asset(name, mode, strength, seed, t_start='2024-06-20', t_end='2026-06-30'):
    """Синтетический ассет: бары 5M (вола с суточным циклом и медленными режимами), объём, ℓ — эпизоды «чаще» (~15% времени,
       по ~6 ч) на фоне «реже», с шумом (у модели оценки окон тоже идут эпизодами). VAL — целый год (как будет у боевого
       прогона к середине 2026-го)."""
    rng = np.random.default_rng(seed)
    tns = np.arange(pd.Timestamp(t_start).value, pd.Timestamp(t_end).value, NS_5M, dtype=np.int64)
    n = len(tns)
    ar = np.zeros(n)
    eps = rng.normal(0, 0.01, n)
    for k in range(1, n):
        ar[k] = 0.999 * ar[k - 1] + eps[k]
    hour = (tns // (3600 * 10 ** 9)) % 24
    sig = 0.0015 * np.exp(0.25 * np.sin(2 * np.pi * hour / 24) + ar)
    on = np.zeros(n, bool)
    st = False
    flips = rng.random(n)
    for k in range(n):
        st = (flips[k] >= 1 / 72) if st else (flips[k] < 1 / 400)
        on[k] = st
    noise = np.zeros(n)
    e2 = rng.normal(0, 0.06, n)
    for k in range(1, n):
        noise[k] = 0.98 * noise[k - 1] + e2[k]
    ell = np.where(on, 1.2, -0.3) + noise
    x, xh, xl = _synth_path(sig, ell, mode, strength, 2016, seed + 1)
    vol = np.exp(rng.normal(0, 0.5, n)) * (sig / 0.0015) ** 1.5 * 1000
    hi, lo, cl = np.exp(xh), np.exp(xl), np.exp(x)
    norm = pd.Series(hi - lo).rolling(200, closed='left').median().to_numpy()
    ell[:300] = np.nan
    i0 = int(np.searchsorted(tns, pd.Timestamp(PROF['tune_start']).value))
    sl = slice(i0, None)
    B = {'tns': tns[sl], 'xhi': xh[sl], 'xlo': xl[sl], 'xc': x[sl], 'close': cl[sl], 'vol': vol[sl],
         'u': (norm / cl)[sl], 'g': ((hi - lo) / norm)[sl]}
    return B, ell[sl]


def causality_check(seed=7, cut_frac=0.6):
    """Без заглядывания: события синтетического ассета на полном ряде и на ряде, обрезанном на cut_frac, у общих решений
       обязаны совпасть бит в бит — сигналы всех профилей, флаги касаний и барьера, ходы подхода, поправки Z, u. Будущие бары
       (их цены, оценки, мин / макс ряда) на профиль решения не влияют."""
    B, ell = synth_asset('CAUSE', 1, 0.04, seed)
    n = len(B['tns'])
    cut = int(cut_frac * n)
    Bc = {k: (v[:cut] if isinstance(v, np.ndarray) and len(v) == n else v) for k, v in B.items()}
    full = build_events('CAUSE', B, ell, int(B['tns'][-1]), quiet=True)
    part = build_events('CAUSE', Bc, ell[:cut], int(Bc['tns'][-1]), quiet=True)
    common = np.intersect1d(full['tns'], part['tns'])
    i_f, i_p = np.searchsorted(full['tns'], common), np.searchsorted(part['tns'], common)
    keys = ['Z', 'u'] + [f'{m}__{k}' for m in MEMORIES for k in ('ok', 'sig', 'ts', 'mv', 'fpk', 'ftr')]
    bad, n_el = {}, 0
    for k in keys:
        a, b = full[k][i_f], part[k][i_p]
        n_el += a.size
        same = np.array_equal(a, b, equal_nan=True) if a.dtype.kind == 'f' else np.array_equal(a, b)
        if not same:
            bad[k] = int(np.sum(~((a == b) | (np.isnan(a) & np.isnan(b)) if a.dtype.kind == 'f' else (a == b))))
    ok = not bad
    print(f"{'✅' if ok else '❌'} без заглядывания: ряд {n} баров против обрезанного до {cut} — общих решений {len(common)}, "
          f"сравнено {n_el} значений (сигналы, уровни, барьер, Z, u): "
          + ("всё совпало бит в бит" if ok else f"расхождения: {bad}"))
    return ok


def stand_mode(scenarios=None, n_assets=4):
    """Стенд: проверка «без заглядывания» и три синтетических рынка по n_assets ассетов, весь путь events -> stats. Ожидается:
       (A) случайное блуждание — контроль ✅, подтверждённых нет; (B) притяжение к центру масс ℓ⁺ за 7 суток — подтверждены
       профили модели, «дело в оценках модели» ✅; (C) притяжение к центру масс TPO за 7 суток — подтверждены простые
       профили, у модели «дело в оценках» не проходит."""
    scen = scenarios or (('A: случайное блуждание', 0, 0.0), ('B: притяжение к ℓ⁺ (7 суток)', 1, 0.04),
                         ('C: притяжение к TPO (7 суток)', 2, 0.04))
    t0 = time.time()
    causality_check()
    results = {}
    for title, mode, strength in scen:
        print(f"\n{'#' * 100}\n# СТЕНД {title} | {n_assets} ассета\n{'#' * 100}")
        evs = []
        for i in range(n_assets):
            B, ell = synth_asset(f"S{i}", mode, strength, seed=1000 * (mode + 1) + i)
            evs.append(build_events(f"SYN{i}", B, ell, int(B['tns'][-1]), quiet=(i > 0)))
        results[title] = run_stats(evs, f"СТЕНД {title}", show=False)
    print(f"\n⏱️ стенд: {(time.time() - t0) / 60:.1f} мин")
    return results


