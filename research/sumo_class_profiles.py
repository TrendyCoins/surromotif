    W[:, 1] = np.where(scored, np.nan_to_num(g, nan=0.0, posinf=0.0), 0.0)
    W[:, 2] = np.where(scored, np.nan_to_num(vol, nan=0.0, posinf=0.0), 0.0)

    def fill(e, c0):
        ok = np.isfinite(e)
        e0 = np.where(ok, e, 0.0)
        W[:, c0] = np.maximum(e0, 0.0)
        W[:, c0 + 1] = np.maximum(-e0, 0.0)
        W[:, c0 + 2] = e0
        W[:, c0 + 3] = ok & (e0 >= mark_log)
        W[:, c0 + 4] = ok & (e0 <= -mark_log)

    fill(ell, len(ROWS) - len(MODEL_ROWS))
    for q, d in enumerate(shifts):
        e_sh = shift_past(ell, int(d) * 288)
        e_sh[~scored] = np.nan               # у плацебо — те же бары, что у остальных профилей
        fill(e_sh, len(ROWS) + len(MODEL_ROWS) * q)
    return np.ascontiguousarray(W)


