def load_bars(asset, t_from):
    """Бары CSV с t_from: log high / low / close, u = норм. / close (норм. — медиана high − low за 200 баров до бара, как
       делитель r у SMC_Data), диапазон в норм., объём (если есть в CSV)."""
    path = RAW_DIR + f"{asset}-5M.csv"
    if not os.path.isfile(path):
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет {path}")
    df = pd.read_csv(path, parse_dates=['timestamp'])
    tns = df['timestamp'].to_numpy().astype('datetime64[ns]').astype(np.int64)
    if not np.all(np.diff(tns) > 0):
        raise ValueError(f"🍆 АЙ, ОШИБКА! {asset}: метки времени CSV не по возрастанию")
    hi, lo, cl = (df[k].to_numpy(dtype=np.float64) for k in ('high', 'low', 'close'))
    vcol = next((c for c in df.columns if c.lower() in ('volume', 'vol', 'base_volume', 'base_asset_volume')), None)
    vol = df[vcol].to_numpy(dtype=np.float64) if vcol else np.zeros(len(df))
    norm = pd.Series(hi - lo).rolling(200, closed='left').median().to_numpy()
    norm = np.where(np.isfinite(norm) & (norm > 0), norm, np.nan)
    i0 = int(np.searchsorted(tns, t_from))
    sl = slice(i0, None)
    return {'tns': tns[sl], 'xhi': np.log(hi[sl]), 'xlo': np.log(lo[sl]), 'xc': np.log(cl[sl]), 'close': cl[sl],
            'vol': vol[sl], 'u': norm[sl] / cl[sl], 'g': (hi[sl] - lo[sl]) / norm[sl], 'vcol': vcol, 'csv': path}


def check_close(asset, B, data_dir=None):
    """close CSV против close из smc_series (тот же ряд, на котором считались окна модели)."""
    path = (data_dir or DATA_DIR) + f"smc_series_{asset}_5M_N200.npz"
    if not os.path.isfile(path):
        print(f"   ⚠️ нет {os.path.basename(path)} — сверка close пропущена")
        return
    with np.load(path, allow_pickle=False) as d:
        if 'close_tr' not in d.files:
            print("   ⚠️ в smc_series нет close — сверка пропущена")
            return
        t = np.concatenate([d['t_tr'], d['t_va']])
        c = np.concatenate([d['close_tr'], d['close_va']])
    m = t >= B['tns'][0]
    t, c = t[m], c[m]
    idx = np.searchsorted(B['tns'], t)
    idc = np.minimum(idx, len(B['tns']) - 1)
    found = B['tns'][idc] == t
    bad = found & (np.abs(B['close'][idc] - c) > 1e-9 * np.abs(c))
    n_miss, n_bad = int((~found).sum()), int(bad.sum())
    tail = int((B['tns'] > t.max()).sum()) if len(t) else 0
    mark = '✅' if n_miss == 0 and n_bad == 0 else ('⚠️' if n_miss + n_bad <= 20 else '❌')
    print(f"   {mark} close CSV против smc_series: баров {len(t)}, нет в CSV {n_miss}, close расходится {n_bad}"
          + (f" | в CSV после конца smc_series ещё {tail} баров (идут только в исходы)" if tail else ""))
    if n_miss + n_bad > 20:
        raise ValueError(f"🍆 АЙ, ОШИБКА! {asset}: CSV не тот, на котором считался smc_series ({n_miss} нет, {n_bad} "
                         f"расходятся) — верни CSV исследовательского набора")


def align_scores(B, t_sc, ell_sc):
    idx = np.searchsorted(B['tns'], t_sc)
    idc = np.minimum(idx, len(B['tns']) - 1)
    found = B['tns'][idc] == t_sc
    if not found.all():
        raise ValueError(f"🍆 АЙ, ОШИБКА! {int((~found).sum())} баров с оценкой модели нет в CSV — CSV не тот")
    ell = np.full(len(B['tns']), np.nan)
    ell[idc] = ell_sc
    return ell


