MAXLV = 16           # уровней (пиков / впадин) на профиль в памяти барьерного теста
LOGT = 12            # таблицы максимумов / минимумов: окно касаний до 4095 баров
KIND_CODE = {'win': 0, 'exp': 1, 'visit': 2}


@njit
def _spread(P, w, r_lo, r_hi, m, mult):
    """Бар — равномерно по своему диапазону [r_lo, r_hi] (координаты бинов от опорной цены; в массиве бин i лежит в P[:, i + m]):
       строка r получает mult·w[r]·(доля бара в бине). Доли считаются от координат относительно опорной цены — профиль не
       зависит от того, где кончается массив (а значит, и от будущих цен)."""
    R, nb = P.shape
    span = r_hi - r_lo
    if span < 1e-9:
        i = int(math.floor(0.5 * (r_lo + r_hi))) + m
        if i < 0:
            i = 0
        elif i > nb - 1:
            i = nb - 1
        for r in range(R):
            if w[r] != 0.0:
                P[r, i] += mult * w[r]
        return
    i0 = int(math.floor(r_lo))
    i1 = int(math.floor(r_hi))
    for i in range(i0, i1 + 1):
        ii = i + m
        if ii < 0 or ii > nb - 1:
            continue
        a = r_lo if r_lo > i else float(i)
        b = r_hi if r_hi < i + 1.0 else float(i + 1)
        f = (b - a) / span
        if f > 0.0:
            for r in range(R):
                if w[r] != 0.0:
                    P[r, ii] += mult * w[r] * f


@njit
def _visit(P, r_lo, r_hi, m, kappa):
    """«Скрытые бары»: бар прошёл через бины своего диапазона — старая масса там умножается на kappa (во всех строках)."""
    R, nb = P.shape
    i0 = int(math.floor(r_lo)) + m
    i1 = int(math.floor(r_hi)) + m
    if i0 < 0:
        i0 = 0
    if i1 > nb - 1:
        i1 = nb - 1
    for r in range(R):
        for i in range(i0, i1 + 1):
            P[r, i] *= kappa


@njit
def _smooth(Prow, i_lo, nB, kern, half, out):
    nb = Prow.shape[0]
    for t in range(nB):
        i = i_lo + t
        acc = 0.0
        ws = 0.0
        for q in range(-half, half + 1):
            ii = i + q
            if 0 <= ii < nb:
                acc += kern[q + half] * Prow[ii]
                ws += kern[q + half]
        out[t] = acc / ws if ws > 0.0 else 0.0


@njit
def _band(P, x0, u, x_ref, m, delta, s_u, B_u, avg_def, S, V, mup, mdn, kern, rmax):
    """Полоса ±B_u·u вокруг цены x0: сглаженные строки (Гаусс шириной s_u·u) — в S[:R], «средний ℓ» (net / tpo там, где
       tpo >= 5% своего максимума в полосе) — в S[R:]; V — где профиль определён; mup / mdn — сырая масса выше / ниже цены.
       Масса меньше 1e-8 от наибольшего веса бара строки (rmax) — остаток округления (окно: бар прибавлен и вычтен) -> ноль:
       пустая строка даёт пустой профиль без сигналов, а не пики на шуме округления.
       Возвращает (lo, nB, c): первый бин полосы (от опорной цены x_ref; в массиве — lo + m), её длину и цену в координатах
       полосы (центр бина t — координата t). Массив шире любой полосы с запасом на сглаживание: края не обрезают полосу."""
    R, nb = P.shape
    max_nB = S.shape[1]
    max_half = (kern.shape[0] - 1) // 2
    c0 = (x0 - x_ref) / delta - 0.5
    Bb = B_u * u / delta
    lo = int(math.floor(c0 - Bb))
    nB = int(math.ceil(c0 + Bb)) - lo + 1
    if nB > max_nB:                          # ёмкость — по максимуму u на решениях: сюда не попадаем
        lo = int(round(c0)) - max_nB // 2
        nB = max_nB
    i_lo = lo + m
    if nB < 5 or i_lo - max_half < 0 or i_lo + nB + max_half > nb:
        return lo, 0, 0.0
    c = c0 - lo
    sg = s_u * u / delta
    half = int(math.ceil(3.0 * sg))
    if sg < 0.3:
        half = 0
    if half > max_half:
        half = max_half
    for q in range(-half, half + 1):
        kern[q + half] = math.exp(-0.5 * (q / sg) ** 2) if half > 0 else 1.0
    for r in range(R):
        _smooth(P[r], i_lo, nB, kern, half, S[r])
        amax = 0.0
        for t in range(nB):
            if abs(S[r, t]) > amax:
                amax = abs(S[r, t])
        thr = 1e-9 * amax
        if 1e-8 * rmax[r] > thr:
            thr = 1e-8 * rmax[r]
        for t in range(nB):                  # остатки округления -> ровный ноль
            if abs(S[r, t]) < thr:
                S[r, t] = 0.0
        thr_p = 1e-8 * rmax[r]
        up = 0.0
        dn = 0.0
        for t in range(nB):
            V[r, t] = True
            v = P[r, i_lo + t]
            if abs(v) < thr_p:
                continue
            if t > c:
                up += v
            elif t < c:
                dn += v
        mup[r] = up
        mdn[r] = dn
    for a in range(avg_def.shape[0]):
        rn = avg_def[a, 0]
        rt = avg_def[a, 1]
        p = R + a
        tmax = 0.0
        for t in range(nB):
            if S[rt, t] > tmax:
                tmax = S[rt, t]
        for t in range(nB):
            if tmax > 0.0 and S[rt, t] > 0.05 * tmax:
                S[p, t] = S[rn, t] / S[rt, t]
                V[p, t] = True
            else:
                S[p, t] = 0.0
                V[p, t] = False
        mup[p] = mup[rn] / mup[rt] if mup[rt] > 0.0 else np.nan
        mdn[p] = mdn[rn] / mdn[rt] if mdn[rt] > 0.0 else np.nan
    return lo, nB, c


@njit
def _extrema(S, V, nB, wb, prom, pk, tr):
    """Пики и впадины сглаженного профиля в полосе. Кандидат — отрезок равных значений (обычно одна точка; ровный ноль
       внутри разрыва цены — тоже отрезок), с обеих сторон которого профиль ниже (пик) или выше (впадина); уровень — середина
       отрезка. Принимается, если не ниже (не выше) всех точек в ±wb бинах от отрезка и выше их минимума (ниже максимума)
       хотя бы на prom размаха профиля в полосе. Индексы — в pk / tr."""
    smax = -1e300
    smin = 1e300
    for t in range(nB):
        if V[t]:
            if S[t] > smax:
                smax = S[t]
            if S[t] < smin:
                smin = S[t]
    if not (smax > smin):
        return 0, 0
    thr = prom * (smax - smin)
    npk = 0
    ntr = 0
    t = 1
    while t < nB - 1:
        if not V[t]:
            t += 1
            continue
        s = S[t]
        e = t
        while e + 1 < nB and V[e + 1] and S[e + 1] == s:
            e += 1
        if e + 1 >= nB or not (V[t - 1] and V[e + 1]):
            t = e + 1
            continue
        is_pk = s > S[t - 1] and s > S[e + 1]
        is_tr = s < S[t - 1] and s < S[e + 1]
        if is_pk or is_tr:
            lo = t - wb if t - wb > 0 else 0
            hi = e + wb if e + wb < nB - 1 else nB - 1
            mx = -1e300
            mn = 1e300
            for q in range(lo, hi + 1):
                if V[q]:
                    if S[q] > mx:
                        mx = S[q]
                    if S[q] < mn:
                        mn = S[q]
            mid = (t + e) // 2
            if is_pk and s >= mx and s - mn >= thr:
                pk[npk] = mid
                npk += 1
            if is_tr and s <= mn and mx - s >= thr:
                tr[ntr] = mid
                ntr += 1
        t = e + 1
    return npk, ntr


@njit
def _interp(S, V, nB, x):
    if x < 0.0 or x > nB - 1.0:
        return np.nan
    i = int(math.floor(x))
    if i >= nB - 1:
        return S[nB - 1] if V[nB - 1] else np.nan
    if not (V[i] and V[i + 1]):
        return np.nan
    f = x - i
    return S[i] * (1.0 - f) + S[i + 1] * f


@njit
def _signals(S, V, nB, c, mup, mdn, dminb, wb, hb, prom, pk, tr, out, lv):
    """Сигналы профиля (+1 — вверх, −1 — вниз, 0 — нет) в out: к POC, к большей массе, вверх по склону, к ближнему пику,
       к ближней впадине. lv — для теста касаний: [знак (+1 — пик сверху, −1 — пик снизу, 0 — нет), верхний уровень,
       нижний уровень] в координатах полосы. Возвращает число пиков и впадин (их индексы — в pk / tr)."""
    for q in range(5):
        out[q] = 0
    lv[0] = 0.0
    lv[1] = np.nan
    lv[2] = np.nan
    smax = -1e300
    smin = 1e300
    arg = -1
    for t in range(nB):
        if V[t]:
            if S[t] > smax:
                smax = S[t]
                arg = t
            if S[t] < smin:
                smin = S[t]
    if arg < 0 or not (smax > smin):
        return 0, 0
    d = arg - c
    if abs(d) >= dminb:
        out[0] = 1 if d > 0 else -1
    if mup == mup and mdn == mdn:
        tot = abs(mup) + abs(mdn)
        if tot > 0.0 and abs(mup - mdn) > 0.02 * tot:
            out[1] = 1 if mup > mdn else -1
    a = _interp(S, V, nB, c + hb)
    b = _interp(S, V, nB, c - hb)
    if a == a and b == b and abs(a - b) > 1e-9 * (smax - smin):
        out[2] = 1 if a > b else -1
    npk, ntr = _extrema(S, V, nB, wb, prom, pk, tr)
    pu = 1e300
    pdn = 1e300
    for q in range(npk):
        d = pk[q] - c
        if d >= dminb:
            if d < pu:
                pu = d
        elif d <= -dminb:
            if -d < pdn:
                pdn = -d
    if pu < 1e300 or pdn < 1e300:
        if pu < pdn:
            out[3] = 1
        elif pdn < pu:
            out[3] = -1
    tu = 1e300
    tdn = 1e300
    for q in range(ntr):
        d = tr[q] - c
        if d >= dminb:
            if d < tu:
                tu = d
        elif d <= -dminb:
            if -d < tdn:
                tdn = -d
    if tu < 1e300 or tdn < 1e300:
        if tu < tdn:
            out[4] = 1
        elif tdn < tu:
            out[4] = -1
    if (pu < 1e300 or pdn < 1e300) and (tu < 1e300 or tdn < 1e300):
        dp = pu if pu <= pdn else -pdn
        dt = tu if tu <= tdn else -tdn
        if dp * dt < 0.0:
            lv[0] = 1.0 if dp > 0.0 else -1.0
            lv[1] = c + (dp if dp > 0.0 else dt)
            lv[2] = c + (dp if dp < 0.0 else dt)
    return npk, ntr


@njit
def _nearest_levels(idx, n, c, out, x_base, delta):
    """До len(out) ближайших к цене уровней (индексы полосы idx по возрастанию) — log-ценами в out; возвращает их число."""
    m = out.shape[0]
    lo = -1
    for q in range(n):
        if idx[q] <= c:
            lo = q
    hi = lo + 1
    used = 0
    while used < m and (lo >= 0 or hi < n):
        if lo >= 0 and (hi >= n or c - idx[lo] <= idx[hi] - c):
            out[used] = x_base + idx[lo] * delta
            lo -= 1
        else:
            out[used] = x_base + idx[hi] * delta
            hi += 1
        used += 1
    return used


@njit
def _run_memory(xlo, xhi, xc, ut, W, dec_bar, kind, H, lam, kappa, x_ref, m_off, delta, nb,
                s_u, B_u, dmin_u, w_u, h_u, prom, lag, step, eps_u, D_u, avg_def, max_nB, max_half):
    """Один проход по барам для одной памяти: профиль копится бар за баром (окно — добавить новый, вычесть старый;
       затухание — общий множитель; «скрытые бары» — множитель kappa на пройденных бинах), на барах решений — сигналы,
       уровни для касаний и флаги барьера (уровни решения lag часов назад). Только прошлое: бар решения уже в профиле.
       Координаты цен — от опорной цены x_ref в бинах delta; бин i лежит в массиве на месте i + m_off."""
    n = xc.shape[0]
    R = W.shape[1]
    NP = R + avg_def.shape[0]
    nd = dec_bar.shape[0]
    P = np.zeros((R, nb))
    scale = 1.0
    sig = np.zeros((nd, NP, 5), np.int8)
    ts = np.zeros((nd, NP), np.int8)
    tup = np.full((nd, NP), np.nan)
    tdn = np.full((nd, NP), np.nan)
    fpk = np.zeros((nd, NP), np.int8)
    ftr = np.zeros((nd, NP), np.int8)
    ok = np.zeros(nd, np.bool_)
    mv = np.full(nd, np.nan)
    ring = lag + 1
    rpk = np.full((ring, NP, MAXLV), np.nan)
    rtr = np.full((ring, NP, MAXLV), np.nan)
    rnp = np.zeros((ring, NP), np.int64)
    rnt = np.zeros((ring, NP), np.int64)
    rx0 = np.full(ring, np.nan)
    rbar = np.full(ring, -1, np.int64)
    S = np.zeros((NP, max_nB))
    V = np.ones((NP, max_nB), np.bool_)
    mup = np.zeros(NP)
    mdn = np.zeros(NP)
    pk = np.zeros(max_nB, np.int64)
    tr = np.zeros(max_nB, np.int64)
    kern = np.zeros(2 * max_half + 1)
    out = np.zeros(5, np.int8)
    lv = np.zeros(3)
    rmax = np.zeros(R)                       # наибольший вес бара по строке (в единицах P) — порог остатков округления
    j = 0
    for k in range(n):
        if kind != 0:
            scale *= lam
            if scale < 1e-150:
                for r in range(R):
                    rmax[r] *= scale
                    for i in range(nb):
                        P[r, i] *= scale
                scale = 1.0
        b_lo = (xlo[k] - x_ref) / delta
        b_hi = (xhi[k] - x_ref) / delta
        if b_lo == b_lo and b_hi == b_hi:
            if kind == 2:
                _visit(P, b_lo, b_hi, m_off, kappa)
            _spread(P, W[k], b_lo, b_hi, m_off, 1.0 / scale)
            for r in range(R):
                v = abs(W[k, r]) / scale
                if v > rmax[r]:
                    rmax[r] = v
        if kind == 0 and k >= H:
            kk = k - H
            c_lo = (xlo[kk] - x_ref) / delta
            c_hi = (xhi[kk] - x_ref) / delta
            if c_lo == c_lo and c_hi == c_hi:
                _spread(P, W[kk], c_lo, c_hi, m_off, -1.0)
        if j < nd and dec_bar[j] == k:
            slot = j % ring
            rbar[slot] = -1
            rx0[slot] = np.nan
            for p in range(NP):
                rnp[slot, p] = 0
                rnt[slot, p] = 0
            u = ut[k]
            x0 = xc[k]
            if u > 0.0 and x0 == x0:
                lo, nB, c = _band(P, x0, u, x_ref, m_off, delta, s_u, B_u, avg_def, S, V, mup, mdn, kern, rmax)
                if nB >= 5:
                    dminb = dmin_u * u / delta
                    wb = int(round(w_u * u / delta))
                    if wb < 1:
                        wb = 1
                    hb = h_u * u / delta
                    x_base = x_ref + (lo + 0.5) * delta
                    for p in range(NP):
                        npk, ntr = _signals(S[p], V[p], nB, c, mup[p], mdn[p], dminb, wb, hb, prom, pk, tr, out, lv)
                        for q in range(5):
                            sig[j, p, q] = out[q]
                        if lv[0] != 0.0:
                            ts[j, p] = 1 if lv[0] > 0.0 else -1
                            tup[j, p] = x_base + lv[1] * delta
                            tdn[j, p] = x_base + lv[2] * delta
                        rnp[slot, p] = _nearest_levels(pk, npk, c, rpk[slot, p], x_base, delta)
                        rnt[slot, p] = _nearest_levels(tr, ntr, c, rtr[slot, p], x_base, delta)
                    ok[j] = True
                    rx0[slot] = x0
                    rbar[slot] = k
                    if j >= lag:
                        ps = (j - lag) % ring
                        if rbar[ps] >= 0 and k - rbar[ps] == lag * step:
                            m = (x0 - rx0[ps]) / u
                            mv[j] = m
                            if abs(m) >= D_u:
                                dr = 1.0 if m > 0.0 else -1.0
                                for p in range(NP):
                                    for q in range(rnp[ps, p]):
                                        L = rpk[ps, p, q]
                                        if abs(x0 - L) <= eps_u * u and (L - rx0[ps]) * dr >= D_u * u:
                                            fpk[j, p] = 1
                                            break
                                    for q in range(rnt[ps, p]):
                                        L = rtr[ps, p, q]
                                        if abs(x0 - L) <= eps_u * u and (L - rx0[ps]) * dr >= D_u * u:
                                            ftr[j, p] = 1
                                            break
            j += 1
    return sig, ts, tup, tdn, fpk, ftr, ok, mv


@njit
def _profile_at(xlo, xhi, W, k, H, x_ref, m_off, delta, nb):
    """Профиль окна (бары k − H + 1 … k) с нуля — для рисунков (тот же _spread, что в проходе)."""
    R = W.shape[1]
    P = np.zeros((R, nb))
    k0 = k - H + 1 if k - H + 1 > 0 else 0
    for kk in range(k0, k + 1):
        b_lo = (xlo[kk] - x_ref) / delta
        b_hi = (xhi[kk] - x_ref) / delta
        if b_lo == b_lo and b_hi == b_hi:
            _spread(P, W[kk], b_lo, b_hi, m_off, 1.0)
    return P


@njit
def _sparse(v, is_max):
    """tab[k, i] = max (min) v[i : i + 2^k] — для поиска первого касания уровня за O(log T)."""
    n = v.shape[0]
    tab = np.empty((LOGT, n))
    for i in range(n):
        tab[0, i] = v[i]
    for k in range(1, LOGT):
        h = 1 << (k - 1)
        for i in range(n):
            a = tab[k - 1, i]
            if i + h < n:
                b = tab[k - 1, i + h]
                if is_max:
                    tab[k, i] = a if a >= b else b
                else:
                    tab[k, i] = a if a <= b else b
            else:
                tab[k, i] = a
    return tab


@njit
def _first(tab, start, T, level, up):
    """Первый бар в [start, start + T), где high >= level (up) или low <= level; −1 — не было."""
    n = tab.shape[1]
    if start >= n or T <= 0:
        return -1
    rem = T if T < n - start else n - start
    pos = start
    for k in range(LOGT - 1, -1, -1):
        st = 1 << k
        if st <= rem:
            v = tab[k, pos]
            if (up and v < level) or ((not up) and v > level):
                pos += st
                rem -= st
    if rem > 0:
        v = tab[0, pos]
        if (up and v >= level) or ((not up) and v <= level):
            return pos
    return -1


@njit
def _touch(thi, tlo, start, T, up, dn):
    """Что раньше: касание up сверху (+1) или dn снизу (−1); 0 — ни того ни другого или оба в одном баре."""
    a = _first(thi, start, T, up, True)
    b = _first(tlo, start, T, dn, False)
    if a < 0 and b < 0:
        return 0
    if b < 0 or (a >= 0 and a < b):
        return 1
    if a < 0 or b < a:
        return -1
    return 0


@njit
def _touch_out(dec_bar, xc, ts, tup, tdn, thi, tlo, off, T):
    """Касания одной памяти: что раньше — верхний (+1) или нижний (−1) уровень, плюс то же для зеркальных уровней (те же
       расстояния по другую сторону цены). Сумма (−2 … 2): у симметричного пути её среднее — ноль при любой геометрии
       уровней («ближний касается раньше» вычитается). off — сдвиг пути от цены решения: 0 у реального пути, Y − close у
       «случайного будущего» (уровни переносятся на его путь)."""
    nd, NP = ts.shape
    v = np.zeros((nd, NP), np.int8)
    for j in range(nd):
        k = dec_bar[j]
        x0 = xc[k]
        o = off[k]
        for p in range(NP):
            if ts[j, p] != 0:
                up = tup[j, p]
                dn = tdn[j, p]
                upm = 2.0 * x0 - dn
                dnm = 2.0 * x0 - up
                v[j, p] = (_touch(thi, tlo, k + 1, T, up + o, dn + o)
                           + _touch(thi, tlo, k + 1, T, upm + o, dnm + o))
    return v


@njit
def _bar_out(dec_bar, xc, ut, mv, D_u, R_u, T, thi, tlo, off):
    """Барьер одной памяти: после подхода |mv| >= D_u — продолжение (+1) или откат (−1) на R_u·u от цены решения раньше."""
    nd = dec_bar.shape[0]
    yb = np.zeros(nd, np.int8)
    for j in range(nd):
        m = mv[j]
        if m == m and abs(m) >= D_u:
            k = dec_bar[j]
            x0 = xc[k] + off[k]
            r = R_u * ut[k]
            dr = 1 if m > 0.0 else -1
            yb[j] = dr * _touch(thi, tlo, k + 1, T, x0 + r, x0 - r)
    return yb


def fake_path(xc, xhi, xlo, seed):
    """«Случайное будущее»: бары перевёрнуты со случайными знаками (зеркало бара вокруг прошлого close, как у суррогатов
       обучения) — путь-мартингал с теми же модулями ходов и диапазонами баров. Возвращает close, high, low (log)."""
    n = len(xc)
    s = np.where(np.random.default_rng(seed).random(n) < 0.5, -1.0, 1.0)
    prev_c = np.concatenate([[xc[0]], xc[:-1]])
    dx = xc - prev_c
    Y = np.cumsum(s * dx)
    prev_y = Y - s * dx
    up_ext, dn_ext = xhi - prev_c, xlo - prev_c
    Yhi = prev_y + np.where(s > 0, up_ext, -dn_ext)
    Ylo = prev_y + np.where(s > 0, dn_ext, -up_ext)
    return Y, Yhi, Ylo


