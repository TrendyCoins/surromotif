def bh_reject(p, q):
    p = np.where(np.isfinite(p), p, 1.0)
    m = len(p)
    rej = np.zeros(m, bool)
    if m == 0:
        return rej
    order = np.argsort(p)
    below = np.where(p[order] <= q * np.arange(1, m + 1) / m)[0]
    if len(below):
        rej[order[:below[-1] + 1]] = True
    return rej


def holm_reject(p, alpha):
    m = len(p)
    rej = np.zeros(m, bool)
    for i, o in enumerate(np.argsort(p)):
        if p[o] <= alpha / (m - i):
            rej[o] = True
        else:
            break
    return rej


