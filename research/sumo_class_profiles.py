def price_grid(B, s, u_cap):
    """Сетка цен памяти масштаба s: шаг delta = s/3 · ū (ū — медиана u за разгон TUNE, до первого решения), опорная цена —
       close первого бара, запас по краям — шире полосы поиска со сглаживанием при u = u_cap. Ничего из будущего: шаг и
       опора — из начала ряда, а края массива (они от мин / макс цены всего ряда) на профиль не влияют."""
    tns, u = B['tns'], B['u']
    good_u = np.isfinite(u) & (u > 0)
    w_end = pd.Timestamp(PROF['tune_start']).value + PROF['warmup_days'] * DAY_NS
    uw = u[good_u & (tns < w_end)]
    if len(uw) < 1000:
        uw = u[good_u][:8640]
    ubar = float(np.median(uw))
    delta = s / 3.0 * ubar
    x_ref = float(B['xc'][np.flatnonzero(np.isfinite(B['xc']))[0]])
    band_cap = int(math.ceil(GEOM['band'] * s * u_cap / delta)) + 2
    half_cap = int(math.ceil(3.0 * s * u_cap / delta)) + 1
    marg = band_cap + half_cap + 4
    m_off = int(math.ceil((x_ref - float(np.nanmin(B['xlo']))) / delta)) + marg
    nb = m_off + int(math.ceil((float(np.nanmax(B['xhi'])) - x_ref) / delta)) + marg + 1
    return {'delta': delta, 'x_ref': x_ref, 'm_off': m_off, 'nb': nb, 'max_nB': 2 * band_cap + 3, 'max_half': half_cap,
            'ubar': ubar}


def decisions(B, ell, t_end):
    """Бары решений (закрытие каждого 12-го бара 5M) и их период: 1 — TUNE (после разгона), 2 — VAL (после эмбарго)."""
    P_ = PROF
    tns, u = B['tns'], B['u']
    n = len(tns)
    t_tune = pd.Timestamp(P_['tune_start']).value
    t_val = pd.Timestamp(P_['val_start']).value
    need = max(P_['T_touch'] + 1, P_['gap'] + max(P_['horizons'])) + 1
    per = np.zeros(n, np.int8)
    per[(tns >= t_tune + P_['warmup_days'] * DAY_NS) & (tns < t_val)] = 1
    per[(tns >= t_val + P_['embargo_days'] * DAY_NS) & (tns <= t_end)] = 2
    idx = np.arange(n)
    good = ((per > 0) & ((tns // NS_5M) % P_['dec_step'] == P_['dec_step'] - 1) & np.isfinite(u) & (u > 0)
            & (idx + need < n) & (idx >= max(P_['ctrl_lags'])) & np.isfinite(ell))
    dec = np.where(good)[0].astype(np.int64)
    return dec, per[dec]


def build_events(asset, B, ell, t_end, quiet=False):
    """Профили, сигналы и исходы одного ассета. B — бары (log high / low / close, u, диапазон, объём, время), ell — оценка
       модели на каждом баре (NaN — нет), t_end — последний бар с оценкой (решения позже него не берутся). Исходы — на
       реальном будущем и на n_fake «случайных будущих» (бары после решения перевёрнуты случайно)."""
    t0 = time.time()
    P_ = PROF
    tns = B['tns']
    rows, profiles, avg_def = layout(P_['shift_days'])
    NP = len(profiles)
    W = weight_rows(ell, B['g'], B['vol'], P_['shift_days'], math.log(P_['lift_mark']))
    step, T, gap, hs, lags, K = (P_['dec_step'], P_['T_touch'], P_['gap'], P_['horizons'], P_['ctrl_lags'],
                                 int(P_['n_fake']))
    dec, per_d = decisions(B, ell, t_end)
    nd = len(dec)
    xc, xhi, xlo, u = B['xc'], B['xhi'], B['xlo'], B['u']
    ud = u[dec]
    Z = np.stack([np.clip((xc[dec] - xc[dec - l]) / ud, -5 * math.sqrt(l), 5 * math.sqrt(l)) for l in lags], 1)
    R = np.full((nd, len(hs)), np.nan, np.float32)
    for q, h in enumerate(hs):
        a, b = dec + gap, dec + gap + h
        cont = (tns[b] - tns[a]) == h * NS_5M
        lim = 8 * math.sqrt(h)
        R[:, q] = np.where(cont, np.clip((xc[b] - xc[a]) / ud, -lim, lim), np.nan)
    ev = {'asset': asset, 'tns': tns[dec], 'period': per_d, 'u': ud.astype(np.float32), 'Z': Z.astype(np.float32),
          'R': R, 'has_vol': bool(np.nanmax(B['vol']) > 0) if len(B['vol']) else False,
          'ell_bar': np.isfinite(ell).mean()}
    zero = np.zeros(len(tns))
    thi, tlo = _sparse(xhi, True), _sparse(xlo, False)
    u_cap = float(np.nanmax(ud)) if nd else 1e-3
    keep = {}
    for m, M in MEMORIES.items():
        s = M['s']
        g = price_grid(B, s, u_cap)
        kind = KIND_CODE[M['kind']]
        lam = 0.5 ** (1.0 / M['half']) if kind else 1.0
        out = _run_memory(xlo, xhi, xc, u, W, dec, kind, int(M.get('H', 0)), lam, float(M.get('kappa', 1.0)),
                          g['x_ref'], g['m_off'], g['delta'], g['nb'], s, GEOM['band'] * s, GEOM['dmin'] * s,
                          GEOM['peak_w'] * s, GEOM['slope_h'] * s, P_['prom'], P_['lag_dec'], step, GEOM['eps'] * s,
                          GEOM['approach'] * s, avg_def, g['max_nB'], g['max_half'])
        sig, ts, tup, tdn, fpk, ftr, ok, mv = out
        D_u, R_u = GEOM['approach'] * s, GEOM['reach'] * s
        yv = _touch_out(dec, xc, ts, tup, tdn, thi, tlo, zero, T)
        yb = _bar_out(dec, xc, u, mv, D_u, R_u, T, thi, tlo, zero)
        for key, arr in (('ok', ok), ('sig', sig), ('ts', ts), ('yv', yv), ('mv', mv.astype(np.float32)), ('yb', yb),
                         ('fpk', fpk), ('ftr', ftr)):
            ev[f'{m}__{key}'] = arr
        keep[m] = (ts, tup, tdn, mv, D_u, R_u)
        if not quiet:
            print(f"   {m:<4} {M['what']:<44} решений {int(ok.sum())} | касаний (пик / впадина по разные стороны) у "
                  f"ℓ⁺ {100 * (ts[:, profiles.index('plus')] != 0).mean():.0f}% | подходов барьера "
                  f"{100 * np.nanmean(np.abs(mv) >= D_u):.0f}%")
    # «случайные будущие»: те же решения, сигналы и уровни; будущий путь — бары, перевёрнутые случайно
    Rf = np.full((nd, len(hs), K), np.nan, np.float32)
    fv = {m: np.zeros((nd, NP, K), np.int8) for m in MEMORIES}
    fb = {m: np.zeros((nd, K), np.int8) for m in MEMORIES}
    seed0 = P_['fake_seed'] + zlib.crc32(asset.encode()) % 100003
    for k in range(K):
        Y, Yhi, Ylo = fake_path(xc, xhi, xlo, seed0 + 7919 * k)
        off = Y - xc
        for q, h in enumerate(hs):
            a, b = dec + gap, dec + gap + h
            lim = 8 * math.sqrt(h)
            Rf[:, q, k] = np.where(np.isfinite(R[:, q]), np.clip((Y[b] - Y[a]) / ud, -lim, lim), np.nan)
        fhi, flo = _sparse(Yhi, True), _sparse(Ylo, False)
        for m in MEMORIES:
            ts, tup, tdn, mv, D_u, R_u = keep[m]
            fv[m][:, :, k] = _touch_out(dec, xc, ts, tup, tdn, fhi, flo, off, T)
            fb[m][:, k] = _bar_out(dec, xc, u, mv, D_u, R_u, T, fhi, flo, off)
        del fhi, flo
    ev['Rf'] = Rf
    for m in MEMORIES:
        ev[f'{m}__fv'], ev[f'{m}__fb'] = fv[m], fb[m]
    if not quiet:
        print(f"   ⏱️ {asset}: решений TUNE {int((per_d == 1).sum())}, VAL {int((per_d == 2).sum())} | "
              f"«случайных будущих» {K} | {time.time() - t0:.0f} c")
    return ev


