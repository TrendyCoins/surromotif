def bin_stat(x, wi, M, mask):
    """Среднее x по маске; интервал и ошибка — по повторам бутстрепа M (недели)."""
    nw = M.shape[1]
    x = np.asarray(x, dtype=np.float64)
    mm = np.asarray(mask, dtype=bool) & np.isfinite(x)
    s = np.bincount(wi[mm], weights=x[mm], minlength=nw)
    k = np.bincount(wi[mm], minlength=nw).astype(np.float64)
    if k.sum() == 0:
        return {'mean': math.nan, 'ci': (math.nan, math.nan), 'se': math.nan, 'n': 0}
    with np.errstate(divide='ignore', invalid='ignore'):
        bs = (M @ s) / (M @ k)
    bs = bs[np.isfinite(bs)]
    ci = (float(np.quantile(bs, 0.025)), float(np.quantile(bs, 0.975))) if len(bs) > 1 else (math.nan, math.nan)
    return {'mean': float(s.sum() / k.sum()), 'ci': ci, 'se': float(bs.std(ddof=1)) if len(bs) > 1 else math.nan,
            'n': int(k.sum())}


def anat_stats(Fs, seed=None):
    """По периодам: доли корзин; средние мер по корзинам и по всем барам; (В1) — разности g соседних групп корзин."""
    seed = ANAT['seed'] if seed is None else seed
    out = {}
    for code, (src, F) in enumerate(Fs.items()):
        if F is None or not len(F['T']):
            continue
        wi, M = E.boot_weeks(F['T'], np.random.default_rng([seed, 9, code]))
        mk = {b: F['bin'] == i for i, b in enumerate(BINS)}
        r = {'n': int(len(F['T'])), 'share': {b: float(mk[b].mean()) for b in BINS},
             'bins': {b: {m: bin_stat(F[m], wi, M, mk[b]) for m in MEAS_N + MEAS_C} for b in BINS},
             'all': {m: bin_stat(F[m], wi, M, np.ones(len(F['T']), bool)) for m in MEAS_N + MEAS_C}}
        S, R = mk['S2'] | mk['S1'], mk['R1'] | mk['R2']
        r['v1'] = {'N_S': E.hyp_stat(F['g_n'], wi, M, [(mk['N'], S)]), 'R_N': E.hyp_stat(F['g_n'], wi, M, [(R, mk['N'])])}
        out[src] = r
    return out


def _pos(x):
    return x is not None and np.isfinite(x.get('d', math.nan)) and x['d'] > 0 and x['ci'][0] > 0


def kind_of(st, b):
    """(В2) для корзины b: «тренд» / «пила» / «смешано» / «монетка» (и по каким мерам)."""
    srcs = list(E.EFF['periods'])
    got = {}
    for m, thr in (('er_n', ANAT['er_min']), ('v44_n', ANAT['vr_min'])):
        xs = [st.get(s, {}).get('bins', {}).get(b, {}).get(m) for s in srcs]
        if any(x is None or not x['n'] for x in xs):
            continue
        if all(x['ci'][0] > 0 and x['mean'] >= thr for x in xs):
            got[m] = 'тренд'
        elif all(x['ci'][1] < 0 and x['mean'] <= -thr for x in xs):
            got[m] = 'пила'
    kinds = set(got.values())
    label = 'монетка' if not kinds else (kinds.pop() if len(kinds) == 1 else 'смешано')
    return {'kind': label, 'by': got}


def verdict_anat(st):
    """(В1), (В2) по корзинам, палитра."""
    srcs = list(E.EFF['periods'])
    ok_all = all(s in st for s in srcs)
    v1 = ok_all and all(_pos(st[s]['v1']['N_S']) and _pos(st[s]['v1']['R_N']) for s in srcs)
    v2 = {b: kind_of(st, b) for b in BINS} if ok_all else {}
    pal = None if not ok_all else ('да' if v2['S2']['kind'] == 'монетка' else 'нет')
    return {'v1': v1, 'v2': v2, 'palette': pal}


