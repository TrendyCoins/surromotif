def _ma64(u):
    """Сумма L последних значений / √L: шум z окна (у окон без общих баров — независим)."""
    L = E.EFF['L']
    cs = np.concatenate([[0.0], np.cumsum(u)])
    out = np.zeros(len(u))
    out[L - 1:] = (cs[L:] - cs[:-L]) / math.sqrt(L)
    out[:L - 1] = cs[1:L] / math.sqrt(L)
    return out


def stand_regimes(rng, n, probs):
    """Режимы баров: отрезки длины ~ геометрической со средним seg; 0 — тренд, 1 — монетка, 2 — пила."""
    P = STAND_A
    out = np.empty(n, dtype=np.int8)
    i = 0
    while i < n:
        k = int(rng.geometric(1.0 / P['seg']))
        out[i:i + k] = rng.choice(3, p=probs)
        i += k
    return out


def stand_world_a(kind, seed):
    """Мир анатомии: 'chop' — режимы тренд / монетка / пила, 'tail' — тренд / монетка, 'flat' — только монетка. Знаки ходов:
       тренд — за состоянием (меняется в среднем раз в 16 баров), пила — за состоянием, которое меняется каждые 4 бара (через
       четвёрку — в другую сторону), монетка — случайно. z окна — среднее уровня режима по 64 барам окна плюс шум окна; у
       суррогата — только шум. Возвращает (кадры периодов)."""
    P = STAND_A
    S = E.stand_skeleton(seed)
    n, nb, T = S['n'], S['nb'], S['T']
    parts = {0: [], 1: []}
    for ia in range(P['assets']):
        r_ = np.random.default_rng([seed, ia, 31])
        if kind == 'flat':
            reg = np.ones(n, dtype=np.int8)
            lev = np.full(n, P['z_flat'])
        else:
            reg = stand_regimes(r_, n, P['p_chop'] if kind == 'chop' else P['p_tail'])
            lev = np.select([reg == 0, reg == 2], [P['z_trend'], P['z_chop']], 0.0)
        coin = np.where(r_.random(n) < 0.5, -1.0, 1.0)
        st_tr = np.where(np.cumsum(r_.random(n) < P['flip']) % 2 == 0, 1.0, -1.0)
        st_ch = np.where((np.arange(n) // 4) % 2 == 0, 1.0, -1.0)
        agree = r_.random(n) < P['agree']
        sig = np.where(reg == 0, np.where(agree, st_tr, -st_tr), np.where(reg == 2, np.where(agree, st_ch, -st_ch), coin))
        c = 100.0 * np.exp(np.cumsum(0.001 * np.abs(r_.standard_normal(n)) * sig))
        L = E.EFF['L']
        cs = np.concatenate([[0.0], np.cumsum(lev)])
        lev_w = np.r_[lev[:L - 1], (cs[L:] - cs[:-L]) / L]          # уровень режима — среднее по барам окна
        zr = lev_w + P['z_noise'] * _ma64(r_.standard_normal(n))
        z4 = P['z4_noise'] * _ma64(r_.standard_normal(n))
        z1 = -0.2 + P['z4_noise'] * _ma64(r_.standard_normal(n))
        cols = E.line_colors(zr, z4, z1, E.EFF['ceiling']['5M'])
        for code in (0, 1):
            in_per = np.zeros(n, bool)
            in_per[code * nb:(code + 1) * nb] = True
            parts[code].append((ia, frame_anat(T, c, cols, in_per, np.random.default_rng([seed, ia, code, 7]),
                                               E.BAR_NS['5M'], '5M')))
    return {src: E.stack_frames(parts[code]) for code, src in enumerate(E.EFF['periods'])}


def stand_units(check):
    """(ст1) ER = прямой счёт; следующий отрезок — ровно L баров подряд; корзины по порогам."""
    print("\n🧪 (ст1) меры: ER окна, следующий отрезок, корзины")
    L = E.EFF['L']
    rng = np.random.default_rng(41)
    n = 20_000
    c = 100 * np.exp(np.cumsum(0.001 * rng.standard_normal(n)))
    s1 = np.where(rng.random(n) < 0.5, -1.0, 1.0)
    er_r, er_t = er_window(c, s1)
    worst = 0.0
    for t in rng.choice(np.arange(L + 1, n), 300, replace=False):
        a, b = er_direct(c, int(t), s1)
        worst = max(worst, abs(er_r[t] - a), abs(er_t[t] - b))
    check("ER окна векторно = прямой счёт окно за окном (300 окон, реал и близнец)", worst < 1e-12,
          f"наибольшее расхождение {worst:.1e}")
    bar = E.BAR_NS['5M']
    T = pd.Timestamp('2024-01-01').value + bar * np.arange(n, dtype=np.int64)
    T[12_000:] += 3 * bar                                   # дыра во времени: 3 бара пропущено перед баром 12000
    cols = {'c': np.full(n, 0.5), 'z': rng.standard_normal(n), 'z4': rng.standard_normal(n)}
    cols['c'][:L + 2] = np.nan
    F = frame_anat(T, c, cols, np.ones(n, bool), np.random.default_rng(42), bar, '5M')
    gap_ok = bool(np.all((F['T'] < T[12_000 - L]) | (F['T'] >= T[12_000])))       # отрезок через дыру — не берётся
    cnt_ok = len(F['T']) == (12_000 - L - (L + 2)) + (n - 12_000 - L)
    i0 = int(np.searchsorted(T, F['T'][0]))
    g_ok = abs(float(F['g_n'][0]) - (cols['z'][i0 + L] - cols['z4'][i0 + L])) < 1e-6
    check("следующий отрезок — ровно 64 бара подряд: через дыру во времени не берётся, g — окна, кончающегося на t + 64",
          gap_ok and cnt_ok and g_ok, f"баров {len(F['T'])}")
    e1, e3 = ANAT['edges']
    lm = np.array([-e3 - 1e-9, -e3, -e3 + 1e-9, -e1, -e1 + 1e-9, 0.0, e1 - 1e-9, e1, e3 - 1e-9, e3, np.nan])
    want = np.array([0, 0, 1, 1, 2, 2, 2, 3, 3, 4, -1])
    check("корзины цвета — ровно по порогам (M = 3 — в глубокой корзине, M = 1.25 — в средней; без цвета — вне корзин)",
          np.array_equal(bin_of(lm), want))


