def er_window(c, s1):
    """Коэффициент эффективности окна из L ходов, кончающегося на баре t: |Σ r| / Σ |r| у реала и близнеца (знаки s1 баров).
       Ход бара — log close к прошлому бару; NaN — у первых L баров и у окон без движения."""
    L = E.EFF['L']
    n = len(c)
    r = np.zeros(n)
    r[1:] = np.diff(np.log(np.asarray(c, dtype=np.float64)))
    sa = E._roll(np.abs(r), L)
    with np.errstate(divide='ignore', invalid='ignore'):
        er_r = np.abs(E._roll(r, L)) / sa
        er_t = np.abs(E._roll(r * s1, L)) / sa
    for v in (er_r, er_t):
        v[:L] = np.nan
        v[~np.isfinite(v)] = np.nan
    return er_r, er_t


def er_direct(c, t, s1):
    """ER одного окна, кончающегося на баре t, — прямым счётом (стенд)."""
    L = E.EFF['L']
    r = np.diff(np.log(np.asarray(c[t - L:t + 1], dtype=np.float64)))
    s = s1[t - L + 1:t + 1]
    return abs(r.sum()) / np.abs(r).sum(), abs((r * s).sum()) / np.abs(r).sum()


def bin_of(lm):
    """Корзина цвета по log M: 0 — S2, 1 — S1, 2 — N, 3 — R1, 4 — R2; −1 — нет цвета."""
    e1, e3 = ANAT['edges']
    lm = np.asarray(lm, dtype=np.float64)
    b = np.full(len(lm), -1, dtype=np.int8)
    b[lm <= -e3] = 0
    b[(lm > -e3) & (lm <= -e1)] = 1
    b[(lm > -e1) & (lm < e1)] = 2
    b[(lm >= e1) & (lm < e3)] = 3
    b[lm >= e3] = 4
    return b


def frame_anat(T, c, cols, in_per, rng, bar_ns, tf):
    """Бары периода с цветом: корзина цвета; меры следующего отрезка (бары t + 1 … t + L подряд) и окна цвета — у ER, VR4x4,
       AC1, VR16 минус близнец на тех же свечах; g — z реала минус z sflip4 окна. Меры окна считаются с L + 1 баров до
       первого бара с цветом."""
    L, cap = E.EFF['L'], E.EFF['vr_cap']
    T = np.asarray(T, dtype=np.int64)
    n = len(T)
    col = np.asarray(cols['c'], dtype=np.float64)
    base = np.asarray(in_per, dtype=bool) & np.isfinite(col)
    if not base.any():
        return None
    lo = max(int(np.flatnonzero(base)[0]) - L - 1, 0)
    cc = np.asarray(c[lo:], dtype=np.float64)
    sg = E.twin_signs(len(cc), rng)
    K = E.classics(cc, sg)
    er_r, er_t = er_window(cc, sg[0])
    pad = lambda v: np.r_[np.full(lo, np.nan), v]
    clip = lambda v: np.clip(v, -cap, cap)
    m = {'er': pad(er_r - er_t), 'v44': pad(clip(K['lv44_r']) - clip(K['lv44_t'])),
         'ac': pad(K['ac_r'] - K['ac_t']), 'v16': pad(clip(K['lv16_r']) - clip(K['lv16_t'])),
         'g': np.asarray(cols['z'], dtype=np.float64) - np.asarray(cols['z4'], dtype=np.float64)}
    nx = np.minimum(np.arange(n) + L, n - 1)
    okn = (np.arange(n) + L < n) & (T[nx] - T == L * bar_ns)          # следующий отрезок — ровно L баров подряд
    nxt = {k: np.where(okn, v[nx], np.nan) for k, v in m.items()}
    ok = base & okn
    for v in list(nxt.values()) + [m['er'], m['v44'], m['g']]:
        ok &= np.isfinite(v)
    lm = col * math.log(E.EFF['ceiling'][tf])
    F = {'T': T[ok], 'bin': bin_of(lm)[ok], 'lm': lm[ok],
         **{k + '_n': nxt[k][ok] for k in nxt}, 'g_c': m['g'][ok], 'er_c': m['er'][ok], 'v44_c': m['v44'][ok]}
    return {k: (v if k in ('T', 'bin') else v.astype(np.float32)) for k, v in F.items()}


