def _clear_pos(ctx):
    """Кэш окон проверки (с боковыми входами) — заново: внутри side_plus у них дописанные столбцы, вне — нет."""
    for st in ctx['stores'].values():
        st._pos.clear()


def trunk_run(seed):
    """Прогон λ = 0 из J2 этого сида (ствол головы) или ошибка."""
    r0 = joint._load(joint.joint_tag(TRUNK_VARIANT, seed))
    if r0 is None:
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет ствола {joint.joint_tag(TRUNK_VARIANT, seed)} (J2, λ = 0) — сначала J2")
    return r0


def _head_of(r, r0):
    """Голова r — на стволе прогона r0 (тот же тег и sha ствола точки A) и при нынешнем определении своего варианта."""
    v = r.get('vhead') or {}
    return (v.get('ver') == VHEAD_VER and v.get('variant') in VARIANTS and v.get('fp') == variant_fp(v['variant'])
            and v.get('of') == r0['tag'] and v.get('trunk_sha') == joint._trunk_sha_A(r0))


def _head_done(seed, name, r0):
    tag = vh_tag(seed, name)
    pj, pz = pred.pred_dir() + f"{tag}.json", pred.pred_dir() + f"{tag}.npz"
    if not (os.path.isfile(pj) and os.path.isfile(pz)):
        return False
    with open(pj, encoding='utf-8') as fh:
        r = json.load(fh)
    return r.get('ver') == pred.PRED_VER and _head_of(r, r0)


def run_head(ctx, seed, name, over=None):
    """Одна голова волы варианта name на стволе λ = 0 из J2 (рецепт J0, код SuMo_Pred_Train). Ствол в прогоне — бит в бит ствол
       J2 (иначе прогон в *.bad); в json — раздел 'vhead'."""
    r0 = trunk_run(seed)
    trunk, cfg = joint.trunk_of(r0, 'A')
    sha = vol.trunk_sha(vol.sd_numpy(trunk))
    spec = VARIANTS[name]
    made = {}
    over_all = {**RECIPE['over'], **(over or {})}
    print(f"\n🔁 голова волы «{name}» ({WHAT[name]}{', ⏱ в часах и сутках' if timey(name) else ''}) на замороженном стволе "
          f"{r0['tag']} (точка A, эпоха {r0['best_a']['ep']}): рецепт J0 — " + ", ".join(f"{k} {v}" for k, v in over_all.items()))
    with smc.orientation(cfg.get('orient', True)), side_plus(), \
            vhead_on(trunk, spec, list(cfg['head_hidden']), float(cfg['dropout']), made):
        _clear_pos(ctx)
        try:
            res = pred.run_pred(ctx, TARGET, seed, mname=MODEL, over=over_all, recipe=vh_recipe(name), sub=RECIPE['sub'])
        finally:
            _clear_pos(ctx)
    vol.after_run(res, made, sha)
    res['vhead'] = {'ver': VHEAD_VER, 'variant': name, 'fp': variant_fp(name), 'spec': dict(spec), 'of': r0['tag'],
                    'trunk_sha': sha, 'n_in': made['n_in'], 'n_head': made['n_head'], 'n_adapter': made['n_adapter'],
                    'stats': {k: made[k] for k in ('dead', 'floored', 'floor', 'zmax')}, 'timey': timey(name),
                    'code': {'vhead_ver': VHEAD_VER, 'vhead_sha': _self_sha(), 'joint_sha': vol.file_sha(JOINT_PY)}}
    with open(pred.pred_dir() + f"{res['tag']}.json", 'w', encoding='utf-8') as fh:
        json.dump(smc._jsonable(res), fh, ensure_ascii=False, indent=1)
    print(f"🔁 голова «{name}»: R² TUNE {res['summary']['tune']['panel']['r2_cnn']:.4f}, VAL "
          f"{res['summary']['val']['panel']['r2_cnn']:.4f} | {res['tag']}")
    return res


def run_job(job, over=None):
    """Задание консоли: один сид, головы ORDER подряд на общих данных BTC. Посчитанное пропускается (FORCE = True —
       пересчитать); сбой одной головы не гасит остальные."""
    if job not in JOBS:
        raise KeyError(f"🍆 АЙ, ОШИБКА! нет задания '{job}' — есть {', '.join(JOBS)}")
    seed = JOBS[job]
    r0 = trunk_run(seed)
    ctx = pred.btc_context()
    failed = []
    for name in ORDER:
        try:
            if not FORCE and _head_done(seed, name, r0):
                print(f"⏭️ {vh_tag(seed, name)} — уже посчитан (FORCE = True — пересчитать)")
            else:
                run_head(ctx, seed, name, over)
        except Exception as e:
            print(f"\n🍆 АЙ, ОШИБКА! задание {job}, голова «{name}»: {type(e).__name__}: {e} — дальше следующая")
            traceback.print_exc(file=sys.stdout)
            failed.append(name)
        gc.collect()
        if DEVICE.type == 'cuda':
            torch.cuda.empty_cache()
    if failed:
        raise RuntimeError(f"🍆 АЙ, ОШИБКА! задание {job}: не посчитаны головы {', '.join(failed)} — разобрать лог; при перезапуске "
                           f"посчитанные пропускаются")


