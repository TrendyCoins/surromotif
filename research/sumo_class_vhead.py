def _n_in_expected(name, ch, n_side):
    """Ожидаемое число входов головы варианта (стенд): пулинг 'mml' — 3 числа на канал, 'vol' — 6."""
    sp = VARIANTS[name]
    per = {'mml': 3, 'vol': 6}[sp['pool']] * ch
    n = len(sp['layers']) * per + (3 * ch if sp['adapter'] else 0) + n_side
    return n + sum(N_EXTRA[g] for g in sp['extra'])


