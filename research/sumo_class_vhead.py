@contextlib.contextmanager
def side_plus():
    """На время блока side_feats кода F1 дописывает в конец N_APPEND столбцов: знак ориентации формы окна (как в to_shapes и
       side_feats: −1 — форма перевёрнута) и доходности окна за DIR_K последних баров — сумма приращений close-канала / (делитель
       окна · √k), со знаком, обрезка ±20. Ствол читает свои столбцы по номерам и дописанных не видит; зеркало (mirror_inputs)
       переворачивает только столбцы SIDE_MIRROR — дописанные остаются абсолютными."""
    orig = smc.side_feats

    def side_feats_plus(data, starts, L_, W, floor):
        base = orig(data, starts, L_, W, floor)
        w0 = W[:, 0] if W.dim() == 3 else W
        div = torch.maximum(smc.median_abs(w0), floor)
        cs = torch.cumsum(w0, dim=1)
        sgn = torch.where(cs[:, -1] - cs.mean(dim=1) < -smc.ORIENT_EPS * div, -1.0, 1.0)
        if not smc.ORIENT:
            sgn = torch.ones_like(sgn)
        rets = [(w0[:, -k:].sum(dim=1) / (div * math.sqrt(k))).clamp(-20.0, 20.0) for k in DIR_K]
        return torch.cat([base, torch.stack([sgn] + rets, dim=1).to(base.dtype)], dim=1)

    smc.side_feats = side_feats_plus
    try:
        yield
    finally:
        smc.side_feats = orig


def block_maps(trunk, x, s):
    """Карты всех слоёв свёрток ствола (выход каждого блока: свёртка, ReLU, dropout) — список по слоям; ствол — как есть."""
    out = []
    hooks = [blk.register_forward_hook(lambda m_, i_, o_: out.append(o_)) for blk in trunk.blocks]
    try:
        trunk.conv_maps(x, s)
    finally:
        for h_ in hooks:
            h_.remove()
    return out


def pool_maps(trunk, h, how):
    """Пулинг карт слоя по местам окна: 'mml' — как у ствола (среднее, максимум, последнее место); 'vol' — плюс разброс по окну и
       средние последних 4 и 16 мест."""
    if how == 'mml':
        return trunk.pooled(h)
    if how == 'vol':
        return torch.cat([h.mean(2), h.amax(2), h[:, :, -1], h.std(2, unbiased=False), h[:, :, -4:].mean(2),
                          h[:, :, -16:].mean(2)], dim=1)
    raise ValueError(f"🍆 АЙ, ОШИБКА! пулинг '{how}' — есть 'mml' и 'vol'")


class VHead(nn.Module):
    """Голова волы на замороженном стволе MRI. forward(x, s) — прогноз V (стандартизованный таргет), как у сети SuMo_Pred_Train.
       Вход головы — по варианту spec: пулинг слоёв ствола spec['layers'] (пулинг spec['pool']), своя часть сети (spec['adapter']
       последних слоёв свёрток — копии весов ствола, учатся; их выход — пулингом ствола), 17 боковых входов ствола и признаки вне
       ствола spec['extra']. Порядок у варианта 'j0' — ровно вход головы MRI (как у J0). Ствол не учится и всегда без dropout: MRI —
       бит в бит. Симметрия: признаки ствола и своей части — у окна и у зеркала, признаки вне ствола — общие (у окна);
       v = (h(окно) + h(зеркало)) / 2. X0, S0 — пара окон пробы: по ним — число входов (S0 — с дописанными столбцами side_plus)."""
    def __init__(self, trunk, spec, hidden, dropout, X0, S0):
        super().__init__()
        if not getattr(trunk, 'sym', False) or getattr(trunk, 'anti', None) or trunk.res:
            raise ValueError("🍆 АЙ, ОШИБКА! ствол — зеркально-симметричная F1 без антисимметричной головы и остаточных связей")
        self.trunk = trunk
        for p in self.trunk.parameters():
            p.requires_grad_(False)
        self.spec = {k: (tuple(v) if isinstance(v, list) else v) for k, v in spec.items()}
        self.sym = True                        # для кода SuMo_Pred_Train: «зеркально-симметричная сеть»
        self.side_cols = trunk.side_cols       # сети нужны боковые входы (uses_side)
        self.needs_s = True
        self.n_base = int(S0.shape[1]) - N_APPEND
        if self.n_base != len(smc.SIDE_NAMES):
            raise RuntimeError(f"🍆 АЙ, ОШИБКА! боковых входов {S0.shape[1]}, ждали {len(smc.SIDE_NAMES)} + {N_APPEND} — голова волы "
                               f"строится только внутри side_plus")
        nb, k = len(trunk.blocks), int(self.spec['adapter'])
        if any(i < 1 or i > nb for i in self.spec['layers']) or not 0 <= k < nb:
            raise ValueError(f"🍆 АЙ, ОШИБКА! вариант {spec}: слоёв у ствола {nb}")
        self.tap = nb - k                      # своя часть берёт выход слоя tap (1 … nb)
        self.adapter = None
        if k:                                  # свои копии последних k слоёв свёрток: на старте — ровно ствол
            self.adapter = nn.ModuleList([copy.deepcopy(trunk.blocks[i]) for i in range(nb - k, nb)])
            for p in self.adapter.parameters():
                p.requires_grad_(True)
        with torch.no_grad():                  # число входов головы — по паре окон пробы (без dropout: генератор не трогается)
            was = self.training
            self.eval()
            n_in = int(self.one_side(X0, S0, self.extras(S0)).shape[1])
            self.train(was)
        self.head_v = smc.mlp(n_in, tuple(hidden), dropout).to(X0.device)
        self.register_buffer('f_mu', torch.zeros(n_in, device=X0.device))
        self.register_buffer('f_sd', torch.ones(n_in, device=X0.device))
        self.register_buffer('f_on', torch.ones(n_in, device=X0.device))
        self.trunk.eval()

    def train(self, mode=True):
        """Ствол всегда без dropout: его признаки — те же, что у MRI на сайте; dropout — в голове и своей части сети."""
        super().train(mode)
        self.trunk.eval()
        return self

    def set_stats(self, mu, sd, on):
        self.f_mu.copy_(mu)
        self.f_sd.copy_(sd)
        self.f_on.copy_(on)

    def extras(self, s):
        """Признаки вне ствола (общие у окна и его зеркала) — по spec['extra']; None — их нет."""
        parts = []
        for g in self.spec['extra']:
            if g == 'dir':
                ap = s[:, self.n_base:self.n_base + N_APPEND]              # знак ориентации и доходности окна (side_plus)
                parts += [ap, ap[:, :1] * s[:, list(DIR_ORIENTED)]]        # путь до окна со знаком ориентации → абсолютный
            else:
                parts.append(s[:, list(EXTRA[g])])
        return torch.cat(parts, dim=1) if parts else None

    def one_side(self, x, s, e):
        """Вход головы для одной стороны (окно или его зеркало): из ствола, своей части сети, 17 боковых ствола и вне ствола (e)."""
        sp = self.spec
        if is_j0(sp):                          # ровно вход головы MRI (как у J0)
            with torch.no_grad():
                f = self.trunk._feats(x, s)
        else:
            parts = []
            if sp['layers'] or self.adapter is not None:
                with torch.no_grad():
                    hs = block_maps(self.trunk, x, s)
                parts += [pool_maps(self.trunk, hs[i - 1], sp['pool']) for i in sp['layers']]
                if self.adapter is not None:
                    h = hs[self.tap - 1]
                    for blk in self.adapter:
                        h = blk(h)
                    parts.append(self.trunk.pooled(h))
            with torch.no_grad():
                parts.append((s[:, list(self.side_cols)] - self.trunk.side_mu) / self.trunk.side_sd)
            f = torch.cat(parts, dim=1)
        return f if e is None else torch.cat([f, e], dim=1)

    def z(self, f):
        return (f - self.f_mu) / self.f_sd * self.f_on

    def forward(self, x, s=None):
        xm, sm = smc.mirror_inputs(x, s, self.trunk.n_level, self.trunk.lvl_signed)
        e = self.extras(s)
        f, fm = self.one_side(x, s, e), self.one_side(xm, sm, e)
        return 0.5 * (self.head_v(self.z(f)).squeeze(1) + self.head_v(self.z(fm)).squeeze(1)), None, None, None


@torch.no_grad()
def vhead_stats(model, X, S, chunk=16384):
    """Стандартизация входа головы по окнам пробы и их зеркалам — та же арифметика, что у SuMo_Class_Vol.feat_stats (у варианта
       'j0' и у своей части сети на старте — бит в бит его числа): f_mu, f_sd, f_on и сводка (выключено, подрезано, max |z|)."""
    was = model.training
    model.eval()

    def pairs():
        for i in range(0, len(X), chunk):
            x, s = X[i:i + chunk], S[i:i + chunk]
            xm, sm = smc.mirror_inputs(x, s, model.trunk.n_level, model.trunk.lvl_signed)
            e = model.extras(s)
            yield model.one_side(x, s, e), model.one_side(xm, sm, e)
    s1, s2, n = None, None, 0
    for pair in pairs():
        for f in pair:
            f = f.double()
            s1 = f.sum(0) if s1 is None else s1 + f.sum(0)
            s2 = (f * f).sum(0) if s2 is None else s2 + (f * f).sum(0)
            n += len(f)
    mu = s1 / n
    sd = torch.sqrt(torch.clamp(s2 / n - mu * mu, min=0.0))
    on = sd > 1e-6
    floor = vol.RULES['sd_floor_rel'] * float(sd[on].median()) if bool(on.any()) else 1.0
    sd_f = torch.where(on, torch.clamp(sd, min=floor), torch.ones_like(sd))
    zmax = 0.0
    for pair in pairs():
        for f in pair:
            z = (f.double() - mu) / sd_f
            if bool(on.any()):
                zmax = max(zmax, float(z[:, on].abs().max()))
    model.train(was)
    info = {'dead': int((~on).sum()), 'floored': int((on & (sd < floor)).sum()), 'floor': floor, 'zmax': zmax}
    return mu.float(), sd_f.float(), on.float(), info


@contextlib.contextmanager
def vhead_on(trunk, spec, hidden, dropout, made):
    """На время прогона run_pred строит не новую сеть, а VHead: ствол trunk (заморожен) + голова волы варианта spec. run_pred
       зовёт smc.build_model — здесь она подменена фабрикой и в finally возвращается. made — что построила фабрика."""
    orig = smc.build_model

    def factory(cfg, Xs, gen_np, Ss=None):
        if made.get('model') is not None:
            raise RuntimeError("🍆 АЙ, ОШИБКА! фабрика головы волы вызвана второй раз за прогон")
        if Ss is None:
            raise RuntimeError("🍆 АЙ, ОШИБКА! голове волы нужны боковые входы")
        model = VHead(trunk, spec, hidden, dropout, Xs[:2], Ss[:2])
        if is_j0(model.spec):                  # ровно J0: стандартизация — кодом SuMo_Class_Vol
            mu, sd, on, info = vol.feat_stats(trunk, Xs, Ss)
        else:
            mu, sd, on, info = vhead_stats(model, Xs, Ss)
        model.set_stats(mu, sd, on)
        n_ad = vol.n_weights(model.adapter) if model.adapter is not None else 0
        made.update({'model': model, 'n_head': vol.n_weights(model.head_v), 'n_adapter': n_ad, 'n_trunk': vol.n_weights(trunk),
                     'n_in': int(mu.numel()), 'n_sample': int(len(Xs)), **info})
        print(f"🧊 ствол MRI заморожен ({made['n_trunk']} весов не учатся, без dropout); учится голова волы: {made['n_head']} весов"
              + (f" + своя часть сети {n_ad} (копия {spec['adapter']} посл. слоёв свёрток)" if n_ad else "")
              + f" | вход {made['n_in']} признаков — стандартизованы по {len(Xs)} окнам обучения и их зеркалам: выключено "
              f"постоянных {info['dead']}, sd поднят до пола {info['floor']:.3g} у {info['floored']}; max |z| на пробе "
              f"{info['zmax']:.1f}")
        return model, {}

    smc.build_model = factory
    try:
        yield
    finally:
        smc.build_model = orig


