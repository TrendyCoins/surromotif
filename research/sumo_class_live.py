def ms_loop(x, t0, ln, v, aux):
    """Прямой цикл (эталон векторного chart_ms): m и s² на каждой позиции графика [t0, t0 + ln)."""
    lag, L = v['lag'], v['L']
    out = []
    for p in range(ln):
        hi = t0 + p - lag + 1
        lo = t0 if not np.isfinite(L) else max(t0, hi - int(L))
        w = [float(x[j]) for j in range(lo, hi)] if hi > lo else []
        n = len(w)
        mh = sum(w) / n if n else 0.0
        vh = max(sum(u_ * u_ for u_ in w) / n - mh * mh, 0.0) if n else 0.0
        if v['prior'] == 'pool':
            n0 = float(v['n0'])
            m = (sum(w) + n0 * aux['m0']) / (n + n0)
            s2 = (n * vh + n0 * aux['v0']) / (n + n0)
        else:
            u = (float(v['n0']) if v['prior'] == 'null' else 0.0) + (max(L - n, 0) if v['pad'] else 0.0)
            tot = n + u
            m = sum(w) / tot if tot > 0 else 0.0
            s2 = (n * vh + u) / tot if tot > 0 else 1.0
            if v['k'] and tot > 0:
                m = max(m - v['k'] * math.sqrt(s2) * math.sqrt(LIVE['f3_tau'] / tot), 0.0)
        out.append((m, s2))
    return np.array(out)


def research_short_cells(T, D, knots, zk, span, warm, chart):
    """«График chart окон» 'nocal' этим файлом: z — по линейке другого полугодия (как _nc_cells), живая часть — chart_ms
       (EMA с начала каждого куска, без сдвига), линия — с окна warm куска. Должно совпасть с _nc_cells(chart) бит в бит."""
    out = []
    v = _v(kind='ema', span=span, lag=0, show=warm)
    for s_, Dd in D.items():
        ds = [d for d in Dd.values() if d]
        q = {h: BB.ruler_q(np.concatenate([d['sn'][T._nc_half(d['wk']) != h] for d in ds]), knots) for h in (True, False)}
        for a, d in Dd.items():
            h1 = T._nc_half(d['wk'])
            n = len(d['sp'])
            tiles = [(c0, min(chart, n - c0)) for c0 in range(0, n, chart)]
            for h in (True, False):
                if not (h1 == h).any():
                    continue
                zr, zn = BB.to_z(d['sp'], q[h], zk), BB.to_z(d['sn'], q[h], zk)
                r = chart_ms(T, zr, tiles, v, {})
                ok = (h1[r['i']] == h) & (r['p'] >= warm)
                out.append((s_, a, T._nc_logm(zr[r['i'][ok]], r['m'][ok], r['s'][ok]),
                            T._nc_logm(zn[r['i'][ok]], r['m'][ok], r['s'][ok])))
    return out


