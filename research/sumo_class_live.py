def chart_ms(T, x, tiles, v, aux, p_from=0, p_to=None):
    """m и s живой части варианта v на графиках tiles = [(начало, длина)] ряда x (индексы ряда целиком; живая часть
       каждого графика — заново с его начала). Позиции каждого графика p_from … p_to − 1 (p_to — длина, если None).
       Возвращает индекс окна i, позицию p (с 0 от начала графика), m, s и n — реальных окон в живой части."""
    lag = v['lag']
    parts = [(t0, np.arange(p_from, ln if p_to is None else p_to, dtype=np.int64)) for t0, ln in tiles]
    p = np.concatenate([pp for _, pp in parts])
    t0 = np.concatenate([np.full(len(pp), t, dtype=np.int64) for t, pp in parts])
    i = t0 + p
    if v['kind'] == 'win':
        c1 = np.concatenate([[0.0], np.cumsum(x)])
        c2 = np.concatenate([[0.0], np.cumsum(x * x)])
        hi = i - lag + 1                                     # живая часть — окна [lo, hi): до t − lag включительно
        lo = t0 if not np.isfinite(v['L']) else np.maximum(t0, hi - int(v['L']))
        n = np.maximum(hi - lo, 0)
        hc = np.maximum(hi, lo)
        s1, s2 = c1[hc] - c1[lo], c2[hc] - c2[lo]
        nn = np.maximum(n, 1)
        mh = s1 / nn
        vh = np.maximum(s2 / nn - mh * mh, 0.0)              # разброс окон вокруг их среднего
        if v['prior'] == 'pool':                             # справочно: n0 окон среднего колокола других ассетов
            n0 = float(v['n0'])
            m = (s1 + n0 * aux['m0']) / (n + n0)
            s2v = (n * vh + n0 * aux['v0']) / (n + n0)
        else:                                                # u виртуальных случайных окон: n0 (F2) + добивка до L (B4)
            u = (float(v['n0']) if v['prior'] == 'null' else 0.0) + (np.maximum(v['L'] - n, 0) if v['pad'] else 0.0)
            tot = n + u
            ok = tot > 0
            ts = np.where(ok, tot, 1.0)
            m = np.where(ok, s1 / ts, 0.0)
            s2v = np.where(ok, (n * vh + u) / ts, 1.0)
            if v['k']:                                       # F3: центр минус k ошибок среднего
                m = np.where(ok, np.maximum(m - v['k'] * np.sqrt(s2v) * np.sqrt(LIVE['f3_tau'] / ts), 0.0), 0.0)
        s = np.sqrt(s2v)
    elif v['kind'] == 'ema':                                 # EMA с начала графика (код обучения _nc_live), сдвиг lag
        m, s = np.empty(len(i)), np.empty(len(i))
        pos = 0
        for t, pp in parts:
            ln = int(pp[-1]) + 1 if len(pp) else 0
            m_, s_ = T._nc_live(x[t:t + ln], v['span'])
            m_, s_ = BB.shift(m_, lag), BB.shift(s_, lag)
            m[pos:pos + len(pp)], s[pos:pos + len(pp)] = m_[pp], s_[pp]
            pos += len(pp)
        bad = ~np.isfinite(m)
        m[bad], s[bad] = 0.0, 1.0
        n = np.maximum(p - lag + 1, 0)
    else:                                                    # 'ema_all': EMA по всей истории ряда (Bell), сдвиг lag
        m_, s_ = BB.live(T, x, v['span'])
        m, s = BB.shift(m_, lag)[i], BB.shift(s_, lag)[i]
        n = np.full(len(i), -1, dtype=np.int64)
    return {'i': i, 'p': p, 'm': m, 's': s, 'n': n}


def logm_at(T, z, r, shown):
    """log M окон r (по z окна и m, s живой части); где линии нет — 0 (M = 1)."""
    out = np.zeros(len(r['i']))
    if shown.any():
        out[shown] = T._nc_logm(z[r['i'][shown]], r['m'][shown], r['s'][shown])
    return out


def tiles_end(B, n, W):
    """Графики по W окон подряд в оценочной части [B, n): от конца ряда назад, неполный кусок в начале отброшен."""
    out, e = [], n
    while e - W >= B:
        out.append((e - W, W))
        e -= W
    return out[::-1]


def chunk_var(z, L):
    """Средний разброс z внутри кусков по L окон (разброс колокола на графике, без медленного дрейфа центра)."""
    k = len(z) // L
    if k < 1:
        return float(np.var(z))
    return float(np.mean(np.var(z[:k * L].reshape(k, L), axis=1)))


def prep_source(T, src):
    """Ряды источника: z реальных окон, суррогатов и случайного графика (n_gp реализаций), недели, разгон, графики
       (бесплатные и платные) и колокол «пула» (средний по разгону других ассетов того же сида)."""
    recs = []
    for i_s, (seed, S) in enumerate(src['series'].items()):
        assets = list(S)
        mom = {a: (float(S[a]['zr'][:S[a]['B']].mean()), chunk_var(S[a]['zr'][:S[a]['B']], LIVE['pool_L']))
               for a in assets}
        for i_a, a in enumerate(assets):
            d = S[a]
            rng = np.random.default_rng([LIVE['gp_seed2'], i_s, i_a])
            zg = [d['zg']] + [BB.gp_chart(d['acf']['rho_null'], len(d['zr']), rng) for _ in range(LIVE['n_gp'] - 1)]
            oth = [b for b in assets if b != a] or [a]
            n = len(d['zr'])
            recs.append({'seed': seed, 'asset': a, 'zr': d['zr'], 'zs': d['zs'], 'zg': zg, 'wk': d['wk'], 'B': d['B'],
                         'n': n, 'free': tiles_end(d['B'], n, W_FREE), 'paid': tiles_end(d['B'], n, LIVE['paid_windows']),
                         'aux': {'m0': float(np.mean([mom[b][0] for b in oth])),
                                 'v0': float(np.mean([mom[b][1] for b in oth]))}})
    return recs


def week_span(recs):
    lo = min(int(r['wk'][r['B']:].min()) for r in recs)
    hi = max(int(r['wk'][r['B']:].max()) for r in recs)
    return lo, hi - lo + 1


def region(r, v, where):
    """Графики и позиции области: 'steady' — вся оценочная часть одним графиком с начала ряда (полная история: у окон
       части A окно полное); 'warm' — начало бесплатных графиков (первые L + lag окон); 'free' / 'paid' — графики целиком."""
    if where == 'steady':
        return [(0, r['n'])], r['B'], None
    if where == 'warm':
        return r['free'], 0, min(W_FREE, int(v['L']) + v['lag'])
    return r[where], 0, None


