def eval_set(T, recs, v, w0, NW, where, full=True, pos=False):
    """Вариант v в области where: BCE по неделям (все окна области, без линии — ln 2), ячейки R9 / R11 по показанным
       окнам (full), модель случайного графика (отмечено M >= 1.25 или <= 0.8, сильно — M >= 3 или <= 1/3; по реализациям и
       с ошибкой по кластерам времени), по позиции на бесплатном графике (pos)."""
    nb, gw, ng = LIVE['pos_bins'], LIVE['gp_group_weeks'], LIVE['n_gp']
    NG = NW // gw + 1
    acc = {'wsum': np.zeros(NW), 'wcnt': np.zeros(NW), 'g_shown': np.zeros(NG), 'g_mark': np.zeros(NG),
           'g_mark_r': np.zeros(ng), 'g_n_r': np.zeros(ng), 'g_strong': 0, 'shown': 0, 'total': 0, 'r_o3': 0, 'r_b3': 0,
           'pos_b': np.zeros(nb), 'pos_n': np.zeros(nb), 'pos_gm': np.zeros(nb), 'pos_gn': np.zeros(nb)}
    cells = []
    for r in recs:
        tiles, p_from, p_to = region(r, v, where)
        if not tiles:
            continue
        if where == 'steady' and v['kind'] == 'win' and np.isfinite(v['L']) and r['B'] < v['L'] + v['lag']:
            raise ValueError(f"🍆 АЙ, ОШИБКА! {r['asset']}: разгон {r['B']} окон короче окна {v['L']} + сдвиг {v['lag']}")
        q = chart_ms(T, r['zr'], tiles, v, r['aux'], p_from, p_to)
        shown = q['p'] >= v['show']
        lr, ln = logm_at(T, r['zr'], q, shown), logm_at(T, r['zs'], q, shown)
        b = BB.bce_pairs(lr, ln)
        wi = r['wk'][q['i']] - w0
        acc['wsum'] += np.bincount(wi, weights=b, minlength=NW)
        acc['wcnt'] += np.bincount(wi, minlength=NW)
        acc['shown'] += int(shown.sum())
        acc['total'] += len(b)
        if full:
            cells.append((r['seed'], r['asset'], lr[shown], ln[shown]))
            acc['r_o3'] += int((lr[shown] >= L3).sum())
            acc['r_b3'] += int((lr[shown] <= -L3).sum())
        if pos:
            pb = np.minimum(q['p'] * nb // W_FREE, nb - 1)
            acc['pos_b'] += np.bincount(pb, weights=b, minlength=nb)
            acc['pos_n'] += np.bincount(pb, minlength=nb)
        gi = wi[shown] // gw
        for j, zg in enumerate(r['zg']):
            qg = chart_ms(T, zg, tiles, v, r['aux'], p_from, p_to)
            lg = logm_at(T, zg, qg, shown)[shown]
            mk = (np.abs(lg) >= L125).astype(np.float64)
            acc['g_shown'] += np.bincount(gi, minlength=NG)
            acc['g_mark'] += np.bincount(gi, weights=mk, minlength=NG)
            acc['g_mark_r'][j] += mk.sum()
            acc['g_n_r'][j] += len(mk)
            acc['g_strong'] += int((np.abs(lg) >= L3).sum())
            if pos:
                pbs = np.minimum(q['p'][shown] * nb // W_FREE, nb - 1)
                acc['pos_gm'] += np.bincount(pbs, weights=mk, minlength=nb)
                acc['pos_gn'] += np.bincount(pbs, minlength=nb)
    with np.errstate(invalid='ignore', divide='ignore'):
        wk_bce = acc['wsum'] / acc['wcnt']
    gsh = acc['g_shown'].sum()
    gp_col = float(acc['g_mark'].sum() / gsh) if gsh else 0.0
    ok = acc['g_shown'] > 0
    G = int(ok.sum())
    gp_se = math.nan
    if G >= 4:
        gm = acc['g_mark'][ok] / acc['g_shown'][ok]
        gp_se = math.sqrt(G / (G - 1) * np.sum((acc['g_shown'][ok] / gsh) ** 2 * (gm - gp_col) ** 2))
    out = {'key': v['key'], 'fam': v['fam'], 'wk_bce': wk_bce, 'bce': float(np.nanmean(wk_bce)),
           'shown_share': acc['shown'] / max(acc['total'], 1), 'n': acc['total'], 'n_shown': acc['shown'],
           'gp_col': gp_col, 'gp_se': gp_se, 'gp_strong': acc['g_strong'] / gsh if gsh else 0.0,
           'gp_col_r': [float(a / b) if b else math.nan for a, b in zip(acc['g_mark_r'], acc['g_n_r'])]}
    if full:
        has = any(len(c[2]) for c in cells)
        summ = T._nc_summary(cells) if has else None
        n_sh = max(acc['shown'], 1)
        out.update({'ceil': summ['ceil'] if summ else {'orange': math.nan, 'blue': math.nan},
                    'share': summ['share'] if summ else math.nan,
                    'cover': summ['cover'] if summ else (math.nan, math.nan),
                    'cover3': (acc['r_o3'] / n_sh, acc['r_b3'] / n_sh),
                    'asset_ceil': {a: (p_['orange'], p_['blue']) for a, p_ in summ['assets'].items()} if summ else {}})
    if pos:
        out.update({'pos_bce': acc['pos_b'] / np.maximum(acc['pos_n'], 1),
                    'pos_gp': acc['pos_gm'] / np.maximum(acc['pos_gn'], 1), 'pos_gn': acc['pos_gn']})
    return out


def pair_logm(T, r, v, mode):
    """Одни и те же окна на двух графиках: 'reload' — бесплатный график и он же через сутки (начало сдвинуто на reload
       окон); 'plan' — край бесплатного графика (edge окон) и платный (paid_windows окон), кончающийся там же; 'hist'
       (v1.1) — вся история бесплатного графика и тот же платный. Возвращает log M на обоих, показано ли там и там,
       реальных окон в живой части там и там и позицию окна на графике, начавшемся позже (p, v1.1)."""
    if mode not in ('reload', 'plan', 'hist'):
        raise ValueError(f"🍆 АЙ, ОШИБКА! pair_logm: режим '{mode}' — есть 'reload', 'plan', 'hist'")
    if mode == 'reload':
        sh = LIVE['reload']
        tiles = [(t0, ln) for t0, ln in r['free'] if t0 + ln + sh <= r['n']]
        if not tiles:
            return None
        W = tiles[0][1]
        a = chart_ms(T, r['zr'], tiles, v, r['aux'], p_from=sh)
        b = chart_ms(T, r['zr'], [(t0 + sh, ln) for t0, ln in tiles], v, r['aux'], p_to=W - sh)
    else:
        WP = LIVE['paid_windows']
        tiles = [(t0, ln) for t0, ln in r['free'] if t0 + ln - WP >= 0]
        if not tiles:
            return None
        W = tiles[0][1]
        E = W if mode == 'hist' else LIVE['edge']            # 'plan' — последние edge окон, 'hist' — все окна графика
        a = chart_ms(T, r['zr'], tiles, v, r['aux'], p_from=W - E)
        b = chart_ms(T, r['zr'], [(t0 + ln - WP, WP) for t0, ln in tiles], v, r['aux'], p_from=WP - E)
    if not np.array_equal(a['i'], b['i']):
        raise RuntimeError("🍆 АЙ, ОШИБКА! pair_logm: окна двух графиков не совпали")
    sa, sb = a['p'] >= v['show'], b['p'] >= v['show']
    return {'la': logm_at(T, r['zr'], a, sa), 'lb': logm_at(T, r['zr'], b, sb), 'both': sa & sb,
            'na': a['n'], 'nb': b['n'], 'p': np.minimum(a['p'], b['p'])}


def eval_consistency(T, recs, v, mode, split=None):
    """Доля окон (показанных на обоих графиках), где число поменялось больше чем на change_tol или поменялась отметка
       (оранжевая / синяя / нет по M >= 1.25 и <= 0.8), медиана и максимум |Δ log M|. split (v1.1) — то же отдельно
       ('parts') для окон, у которых позиция на графике, начавшемся позже, меньше split ('warm') и не меньше ('full')."""
    tol = math.log(1.0 + LIVE['change_tol'])
    names = ('all',) if split is None else ('all', 'warm', 'full')
    acc = {k: {'n': 0, 'ch': 0, 'fl': 0, 'dl': []} for k in names}
    for r in recs:
        q = pair_logm(T, r, v, mode)
        if q is None:
            continue
        la, lb = q['la'][q['both']], q['lb'][q['both']]
        d = np.abs(la - lb)
        cls_a = np.where(la >= L125, 1, np.where(la <= -L125, -1, 0))
        cls_b = np.where(lb >= L125, 1, np.where(lb <= -L125, -1, 0))
        ch, fl, p = d > tol, cls_a != cls_b, q['p'][q['both']]
        for k in names:
            m = np.ones(len(d), dtype=bool) if k == 'all' else ((p < split) if k == 'warm' else (p >= split))
            acc[k]['n'] += int(m.sum())
            acc[k]['ch'] += int(ch[m].sum())
            acc[k]['fl'] += int(fl[m].sum())
            acc[k]['dl'].append(d[m].astype(np.float32))

    def summ(a_):
        n, dl = a_['n'], (np.concatenate(a_['dl']) if a_['dl'] else np.zeros(0, np.float32))
        return {'n': n, 'change': a_['ch'] / n if n else math.nan, 'flip': a_['fl'] / n if n else math.nan,
                'median': float(np.median(dl)) if len(dl) else math.nan, 'max': float(dl.max()) if len(dl) else math.nan}
    out = summ(acc['all'])
    if split is not None:
        out['parts'] = {k: summ(acc[k]) for k in ('warm', 'full')}
    return out


