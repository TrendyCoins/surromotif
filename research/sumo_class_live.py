def confirm_txt(c):
    if c['ok'] is None:
        return c['why']
    if 'best' not in c:
        return f"{c['why']} — ❌ решение за Фёдором"
    gt = ' '.join(f"{nm}{'✓' if c['gates'][k] else '✗'}" for k, nm in (('a', 'а'), ('b', 'б'), ('c', 'в')))
    return (f"ворота {gt}; лучший прошедший там {c['best']}, Δ(выбор − лучший) {1e4 * c['delta']:+.2f} ± "
            f"{1e4 * c['se']:.2f} ×1e4 -> {'✅ подтверждено' if c['ok'] else '❌ не подтверждено — решение за Фёдором'}")


def verdict(T, chA, resA, chB, conf, free):
    print(f"\n{'=' * 110}\n🏁 ВЕРДИКТ (правила записаны до прогона)\n{'=' * 110}")
    VA = {v['key']: v for v in variants_a()}
    cands = [k for k, v in VA.items() if v['cand']]
    out = {'a_pick': chA['pick'], 'b_pick': chB['pick']}
    if chA['pick']:
        p = chA['pick']
        band = sorted(chA['band'], key=lambda k: order_a(VA[k]))
        print(f"   (A1) на полном окне прошли все ворота: {len(chA['passed'])} из {len(cands)} — {', '.join(chA['passed'])}")
        print(f"   (A2) лучший по BCE — {chA['best']}; полоса 1 SE (по порядку выбора): {', '.join(band)}; выбор — {p} "
              f"({VA[p]['fam']} «{FAM_NAME[VA[p]['fam']]}»: {VA[p]['about']})")
    else:
        out['a_frontier'] = frontier(T, resA, cands)
        print(f"   (A4) на полном окне ни один из {len(cands)} кандидатов не прошёл все ворота — правило не срабатывает; "
              f"граница:")
        for k, miss in out['a_frontier']:
            print(f"       {k:>11}: {'; '.join(miss)}")
    if conf.get('a'):
        print("   (A3) подтверждение на 'refit' ALL: " + confirm_txt(conf['a']))
    a_key = chA['pick'] or chA['ref']
    d_i, s_i = BB.paired(resA, a_key, IDEAL)
    print(f"   справочно: {a_key} против «идеала» ({IDEAL} по всей истории) — Δ BCE {1e4 * d_i:+.2f} ± {1e4 * s_i:.2f} ×1e4 "
          f"(цена короткого графика); случайный график {100 * resA[a_key]['gp_col']:.2f}% против "
          f"{100 * resA[IDEAL]['gp_col']:.2f}%")
    print("   справочно, если важна история на бесплатном графике: лучший по BCE прошедший ворота на полном окне при каждом L "
          "и доля бесплатного графика с полным окном")
    for L in LIVE['L']:
        ks = [k for k in cands if VA[k]['L'] == L and gates(T, resA[k])['all']]
        cov = max(W_FREE - L - LIVE['lag'], 0) / W_FREE
        if ks:
            kb = min(ks, key=lambda k: resA[k]['bce'])
            d, se = BB.paired(resA, kb, a_key)
            print(f"       L {L}: {kb} (Δ BCE к {a_key} {1e4 * d:+.2f} ± {1e4 * se:.2f} ×1e4); полное окно — на последних "
                  f"{W_FREE - L - LIVE['lag']} окнах бесплатного графика ({100 * cov:.0f}%)")
        else:
            print(f"       L {L}: ни один вариант не прошёл ворота; полное окно — {100 * cov:.0f}% бесплатного графика")
    if chB['pick']:
        band = sorted(chB['band'], key=lambda k: B_OPTS.index(k.split('·')[-1]))
        print(f"   (B1)–(B2) начало бесплатного графика: прошли ворота {', '.join(chB['passed'])}; лучший по BCE — "
              f"{chB['best']}; полоса 1 SE: {', '.join(band)}; выбор — {chB['pick']}")
    else:
        print("   (B) начало графика: ни один способ не прошёл ворота (у B3 линии нет — так быть не может) — проверь")
    if conf.get('b'):
        print("   (B3) подтверждение на 'refit' ALL: " + confirm_txt(conf['b']))
    if free and chB['pick'] in free:
        r_new, r_now = free[chB['pick']], free['сейчас·64']
        d, se = BB.paired(free, chB['pick'], 'сейчас·64')
        print(f"   справочно, весь бесплатный график: {chB['pick']} против «как сейчас со сдвигом» — Δ BCE {1e4 * d:+.2f} ± "
              f"{1e4 * se:.2f} ×1e4; показано {100 * r_new['shown_share']:.0f}% против {100 * r_now['shown_share']:.0f}%; "
              f"случайный график {100 * r_new['gp_col']:.2f}% против {100 * r_now['gp_col']:.2f}%")
    low = {a: c for a, c in resA[a_key]['asset_ceil'].items() if min(c) < T.NOCAL['ceil_asset']}
    if low:
        print(f"   потолок R11 ниже {T.NOCAL['ceil_asset']} у {a_key} на полном окне: " + ', '.join(
            f"{a[:-4]} {_f(c[0], 'g')}/{_f(c[1], 'g')}" for a, c in low.items()))
    out['confirm'] = conf
    return out


