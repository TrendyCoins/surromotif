def load_bell():
    """SuMo_Class_Bell модулем из BELL_PY: лог, данные, линейка, случайный график, сверка с 'nocal'. Пути — этого файла."""
    global BB
    if not os.path.isfile(BELL_PY):
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет {BELL_PY} — положи туда sumo_class_bell.py (SuMo_Class_Bell v1)")
    spec = importlib.util.spec_from_file_location('sumo_class_bell', BELL_PY)
    mod = importlib.util.module_from_spec(spec)
    sys.modules['sumo_class_bell'] = mod
    spec.loader.exec_module(mod)
    need = ('BELL', 'load_train', 'read_source_raw', 'build_source', 'check_nocal', 'gp_chart', 'shift', 'live',
            'bce_pairs', 'paired', 'eval_spans', 'tee_to', 'synth_raw', 'knots_zk', 'ruler_q', 'to_z', '_f', '_jsonable')
    miss = [k for k in need if not hasattr(mod, k)]
    if miss:
        raise ImportError(f"🍆 АЙ, ОШИБКА! {BELL_PY}: нет {', '.join(miss)} — нужен SuMo_Class_Bell v1")
    mod.TRAIN_PY, mod.RUN_DIR, mod.OUT_DIR = TRAIN_PY, RUN_DIR, RUN_DIR + 'bell/'
    BB = mod
    return mod


