def gates(T, r):
    """Ворота (а) R9, (б) R11, (в) случайный график; нет показанных окон — линия ничего не обещает: проходит."""
    if r['n_shown'] == 0:
        return {'a': True, 'b': True, 'c': True, 'all': True, 'empty': True}
    N_ = T.NOCAL
    g = {'a': bool(min(r['ceil'].values()) >= N_['ceil_pool']), 'b': bool(r['share'] >= N_['pass_share']),
         'c': bool(r['gp_col'] <= LIVE['null_cover_max'])}
    g['all'] = all(g.values())
    return g


def choose(T, res, keys, order):
    """Ворота -> лучший по BCE -> полоса band_se -> выбор из полосы по порядку order(ключ)."""
    g = {k: gates(T, res[k]) for k in keys}
    passed = [k for k in keys if g[k]['all']]
    ref = min(passed or keys, key=lambda k: res[k]['bce'])
    out = {'gates': g, 'passed': passed, 'best': None, 'band': [], 'pick': None, 'ref': ref}
    if passed:
        delta = {k: BB.paired(res, k, ref) for k in keys}
        band = [k for k in passed if k == ref or delta[k][0] <= LIVE['band_se'] * delta[k][1]]
        out.update({'best': ref, 'band': band, 'pick': sorted(band, key=order)[0],
                    'delta': {k: list(d) for k, d in delta.items()}})
    return out


def confirm(T, res_c, keys, pick):
    """Подтверждение: выбранный проходит ворота и не хуже лучшего прошедшего больше чем на confirm_se SE."""
    if pick is None:
        return {'ok': None, 'why': 'нет выбранного'}
    passed = [k for k in keys if gates(T, res_c[k])['all']]
    g = gates(T, res_c[pick])
    if not passed:
        return {'ok': False, 'why': 'там ни один вариант не прошёл ворота', 'gates': g}
    best = min(passed, key=lambda k: res_c[k]['bce'])
    d, se = BB.paired(res_c, pick, best)
    ok = bool(g['all'] and (pick == best or d <= LIVE['confirm_se'] * se))
    return {'ok': ok, 'best': best, 'delta': d, 'se': se, 'gates': g, 'passed': passed}


def frontier(T, res, keys):
    """Кто какие ворота не прошёл и на сколько."""
    N_ = T.NOCAL
    rows = []
    for k in keys:
        r, g, miss = res[k], gates(T, res[k]), []
        if not g['a']:
            miss.append(f"(а) R9 {min(r['ceil'].values()):g} < {N_['ceil_pool']}")
        if not g['b']:
            miss.append(f"(б) R11 {100 * r['share']:.0f}% < {100 * N_['pass_share']:.0f}%")
        if not g['c']:
            miss.append(f"(в) случ. {100 * r['gp_col']:.2f}% > {100 * LIVE['null_cover_max']:.0f}%")
        rows.append((k, miss))
    return rows


