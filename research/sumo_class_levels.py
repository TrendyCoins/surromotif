def synth_ohlc(steps, rng, sig, wick, t0=None, p0=1e4, bar_ns=300 * 10 ** 9):
    n = len(steps)
    c = p0 + np.cumsum(steps)
    o = np.r_[p0, c[:-1]]
    w = wick * sig
    h = np.maximum(o, c) + np.abs(rng.normal(0, 1, n)) * w
    l = np.minimum(o, c) - np.abs(rng.normal(0, 1, n)) * w
    T = ns(t0 or STAND['t0']) + bar_ns * np.arange(n, dtype=np.int64)
    return add_norm({'T': T, 'o': o, 'h': h, 'l': l, 'c': c})


