                if not np.array_equal(t_w, fc['res'][a]['t'].astype(np.int64)):
                    raise ValueError(f"🍆 АЙ, ОШИБКА! (0в) {a} {part}: окна пула не те же, что в кэше Flow")
                bars = load_asset(a, tf)
                key = 'tr' if part != 'val' else 'va'
                pi = bars['loc'][key][0]
                PB = bars['pieces'][pi]
                sgs = [rand_signs(a, j, pi, PB['T']) for j in range(n_r)]
                first = not chk
                if first:                                   # (0в): все знаки +1 — тот же рынок, logit = 'sp' кэша Flow
                    one, _ = rand_scores(T, data, P, part, models, a, bars, [np.ones(len(PB['T']))], L)
                    chk = {'asset': a, 'part': part, 'flow': {tag: check_flow(one[0][tag], fc['res'][a][tag + '__sp'])
                                                              for tag in models}}
                    s_ = data.series[P['sid_i']]
                    chk['r'] = check_r(PB, sgs[0], data, s_['off'][key], s_['n'][key], bars['loc'][key][1])
                    chk['ok'] = all(x['ok'] for x in chk['flow'].values()) and chk['r']['ok']
