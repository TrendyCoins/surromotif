def asset_price(a, tf, n_rand):
    """События ассета на цене: реал (все семейства), случайные рынки 0 … n_rand − 1. Возвращает ({рынок: {семейство: таблица}},
       сведения)."""
    bars = load_asset(a, tf)
    bar_ns = LEV['bar_ns'][tf]
    out = {'real': {}, 'rand': {}}
    for pi, P in enumerate(bars['pieces']):
        i0 = int(np.searchsorted(P['T'], ns(LEV['ana_from'])))
        if len(P['T']) - i0 < 1000:
            continue
        V = view(P, i0)
        s0 = int(np.searchsorted(V['T'], ns(LEV['zz_from'])))
        ev = market_events(V, FAMS_REAL, LEV['scales'][tf], bar_ns, s0, 0, (LEV['k'],))
        for f, t in ev.items():
            out['real'].setdefault(f, []).append(dict(t, piece=np.full(len(t['t0']), pi, dtype=np.int8)))
        del V
        iz = int(np.searchsorted(P['T'], ns(LEV['zz_from'])))       # случайный рынок — с начала зигзага, как в 'run'
        for j in range(n_rand):
            R = mirror_bars(P, rand_signs(a, j, pi, P['T']))
            VR = view(R, iz)
            r0 = int(np.searchsorted(VR['T'], ns(LEV['rand_from'])))
            ev = market_events(VR, FAMS_RAND, LEV['scales'][tf], bar_ns, 0, r0, (LEV['k'],))
            for f, t in ev.items():
                out['rand'].setdefault(f, []).append(dict(t, rj=np.full(len(t['t0']), j, dtype=np.int8)))
            del VR, R
    info = {'glued': bars['glued'], 'pieces': len(bars['pieces'])}
    return out, info


def count_cats(tab, T_lo, T_hi, n_real=1):
    """Сводка семейства за период: касаний, тестов, на касании (пробой / отбит), не решено, слабых и сильных пробоев (на
       реализацию случайного рынка — делится на n_real)."""
    if tab is None:
        return None
    m0 = (tab['T0'] >= T_lo) & ((tab['T0'] < T_hi) if T_hi else True) & tab['live0'].astype(bool)
    m1 = (tab['T1'] >= T_lo) & ((tab['T1'] < T_hi) if T_hi else True) & (tab['cat2'] >= 0) & tab['live1'].astype(bool)
    c1, c2 = tab['cat1'][m0], tab['cat2'][m1]
    n0 = max(int(m0.sum()), 1)
    test = c1 == 0
    return {'touch': m0.sum() / n_real, 'test': test.sum() / n_real, 'imm_break': float(np.mean(c1 == 1)) if m0.any() else math.nan,
            'imm_reject': float(np.mean(c1 == 2)) if m0.any() else math.nan,
            'unres1': float(np.mean(~np.isfinite(tab['g1'][m0][test]))) if test.any() else math.nan,
            'weak': (c2 == 0).sum() / n_real, 'strong': float(np.mean(c2 == 1)) if m1.any() else math.nan,
            'unres2': float(np.mean(~np.isfinite(tab['g2'][m1][c2 == 0]))) if (c2 == 0).any() else math.nan,
            'osl': float(np.nanmean(tab['osl'][m0])) if m0.any() else math.nan,
            'mv': float(np.nanmean(tab['mv'][m1])) if m1.any() else math.nan, 'n0': n0}


def c0_null_of(fam):
    """Пустышка (Ц0): у day / week — плацебо реала, у пивотов — случайный рынок."""
    return ('real', fam + '_p') if fam in ('day', 'week') else ('rand', fam)


def price_stats(tf, R, n_rand):
    """(Ц0) и справочное по таблицам ТФ: R[рынок][семейство]."""
    res = {'c0': {}, 'ref': {}, 'counts': {}, 'power': {}}
    periods = ('search', 'confirm', 'fit')
    Bs = {}
    for src in periods:
        lo, hi = period_bounds(src)
        Bs[src] = boot_setup(all_weeks([t for mk in R.values() for t in mk.values()], lo, hi),
                             [LEV['seed'], 11, periods.index(src)])
    for fam in LEV['c0_fams'][tf]:
        nm, nf = c0_null_of(fam)
        for q in QS:
            st = {}
            for src in periods:
                if src == 'fit' and fam.startswith('piv_'):
                    continue
                lo, hi = period_bounds(src)
                st[src] = c0_stat(Bs[src], q_view(R['real'].get(fam), q, '', lo, hi), q_view(R[nm].get(nf), q, '', lo, hi))
            res['c0'][(fam, q)] = {'st': st, 'sees': sees(st), 'null': f"{nm}:{nf}"}
    for fam in ('day', 'day_p', 'week', 'week_p'):           # справочно: реал против случайного рынка (общая пила рынка)
        rf = fam[:-2] if fam.endswith('_p') else fam
        for q in QS:
            st = {}
            for src in ('search', 'confirm'):
                lo, hi = period_bounds(src)
                st[src] = c0_stat(Bs[src], q_view(R['real'].get(fam), q, '', lo, hi), q_view(R['rand'].get(rf), q, '', lo, hi))
            res['ref'][(fam, q)] = st
    for src in periods:
        lo, hi = period_bounds(src)
        for mk, fams in R.items():
            for fam, tab in fams.items():
                res['counts'][(src, mk, fam)] = count_cats(tab, lo, hi, n_rand if mk == 'rand' else 1)
    # оценка мощности шага 2: события главной выборки, у которых будет цвет (после разгона линии M в части)
    bar_ns = LEV['bar_ns'][tf]
    for src, part_start in (('search', ns(LEV['tune_start'])), ('confirm', ns(LEV['val_start']) + LEV['N'] * bar_ns)):
        lo, hi = period_bounds(src)
        lo_c = part_start + LEV['line_need'] * bar_ns
        for q in QS:
            n_, p_ = 0, []
            for fam in LEV['main'][tf]:
                v = q_view(R['real'].get(fam), q, '', max(lo, lo_c), hi)
                if v is not None:
                    n_ += len(v['y'])
                    p_.append(v['y'])
            p = float(np.mean(np.concatenate(p_))) if p_ and sum(len(x) for x in p_) else math.nan
            se = math.nan
            if n_ > 0 and np.isfinite(p):
                vr_ = p * (1 - p)
                se = 1.3 * math.sqrt(vr_ * (1 / (0.68 * n_) + 1 / (0.19 * n_)) + vr_ * (1 / (1.2 * n_) + 1 / (2.2 * n_)))
            res['power'][(src, q)] = {'n': n_, 'p': p, 'se': se}
    return res


