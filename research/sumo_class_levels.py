def rand_signs(asset, j, piece, T, rand_from=None):
    """Знаки баров случайного рынка j у куска piece ассета: монетка на каждый бар с rand_from, раньше +1. Детерминированы
       (один и тот же ряд в 'score', 'price' и 'run')."""
    rng = np.random.default_rng([LEV['seed'], zlib.crc32(asset.encode()), int(j), int(piece)])
    s = np.where(rng.random(len(T)) < 0.5, -1.0, 1.0)
    s[np.asarray(T) < (ns(LEV['rand_from']) if rand_from is None else rand_from)] = 1.0
    s[0] = 1.0
    return s


def signs_crc(sg):
    return int(zlib.crc32((np.asarray(sg) > 0).astype(np.int8).tobytes()))


def mirror_bars(P, sg):
    """OHLC случайного рынка: бар t при sg[t] = −1 зеркалится целиком вокруг прошлого close (шаг close, open, high и low — с
       другим знаком от прошлого close; high и low меняются местами), при +1 — как есть; цена — сумма шагов со знаками. При всех
       знаках +1 — реал бит в бит: отклонение D_t = Σ (sg − 1) · шаг close — ровно 0. Время, ATR, живость и vr — реала (ширина и
       истинный диапазон бара от зеркала не меняются)."""
    o, h, l, c = P['o'], P['h'], P['l'], P['c']
    pc = np.r_[c[0], c[:-1]]
    D = np.cumsum((sg - 1.0) * (c - pc))
    Dp = np.r_[0.0, D[:-1]]
    flip = sg < 0
    base = pc + Dp                                       # прошлый close случайного рынка
    R = {'T': P['T'],
         'o': np.where(flip, base - (o - pc), o + Dp),
         'h': np.where(flip, base - (l - pc), h + Dp),
         'l': np.where(flip, base - (h - pc), l + Dp),
         'c': np.where(flip, base - (c - pc), c + Dp)}
    for k in ('atr', 'live', 'vr'):
        R[k] = P[k]
    return R


def r_research(h, l, c, N=200):
    """r арифметикой SuMo_Class_Data (make_parts): шаг close / медиана (high − low) за N баров до бара; мёртвый нормировщик —
       NaN (пропуски сетки здесь не размечаются — сверка идёт только там, где r реала конечен)."""
    roll = pd.Series(np.asarray(h) - np.asarray(l)).rolling(N, closed='left').median().to_numpy()
    dc = np.diff(c, prepend=c[0])
    dc[0] = 0.0
    with np.errstate(invalid='ignore', divide='ignore'):
        r = np.where(np.isfinite(roll) & (roll > 0), dc / roll, np.nan)
    r[0] = np.nan
    return r


def bar_channels(o, h, l, c, N=200):
    """Каналы окна модели по барам из OHLC — арифметикой SuMo_Class_Data / Prices / Range (как TF.build_tf_files): шаг close,
       шаг HL/2 (e_t − d_{t−1}), шаг HLC/3, ширина (high − low) — в единицах нормировщика r. Для сверки зеркала бара (ст2)."""
    roll = pd.Series(h - l).rolling(N, closed='left').median().to_numpy()
    ok = np.isfinite(roll) & (roll > 0)
    rr = np.where(ok, roll, np.nan)
    pc = np.r_[np.nan, c[:-1]]
    out = [(c - pc) / rr]
    for p in ((h + l) / 2.0, (h + l + c) / 3.0):
        e = (p - pc) / rr                                # сдвиг цены бара от прошлого close (нормировщик бара t)
        d = (p - c) / rr                                 # сдвиг цены бара от своего close (нормировщик бара t)
        out.append(e - np.r_[np.nan, d[:-1]])            # шаг модели: e_t − d_{t−1}, как gw кода обучения
    out.append((h - l) / rr)
    return out


# =====================================================================
# ТАБЛИЦА МАКСИМУМОВ: первое достижение порога и максимум отрезка за O(log n) на запрос (векторно)
# =====================================================================
class MaxTable:
    """lv[j][i] = max(x[i : min(i + 2^j, n)]). first_ge — первый t в [start, end) с x[t] >= thr (иначе −1); range_max — максимум
       x на [lo, hi] включительно."""
    def __init__(self, x):
        x = np.ascontiguousarray(x, dtype=np.float64)
        self.n = n = len(x)
        self.lv = [x]
        j = 1
        while (1 << j) <= n:
            prev, half = self.lv[-1], 1 << (j - 1)
            cur = prev.copy()
            cur[:n - half] = np.maximum(prev[:n - half], prev[half:])
            self.lv.append(cur)
            j += 1

    def first_ge(self, start, thr, end):
        start = np.asarray(start, dtype=np.int64)
        if start.size == 0:
            return start.copy()
        thr = np.broadcast_to(np.asarray(thr, dtype=np.float64), start.shape)
        end = np.minimum(np.broadcast_to(np.asarray(end, dtype=np.int64), start.shape), self.n)
        pos = start.copy()
        for j in range(len(self.lv) - 1, -1, -1):
            step = 1 << j
            ok = pos + step <= end
            if not ok.any():
                continue
            v = self.lv[j][np.where(ok, pos, 0)]
            pos = pos + np.where(ok & (v < thr), step, 0)
        hit = (pos < end) & (self.lv[0][np.minimum(pos, self.n - 1)] >= thr)
        return np.where(hit, pos, -1)

    def range_max(self, lo, hi):
        lo, hi = np.asarray(lo, dtype=np.int64), np.asarray(hi, dtype=np.int64)
        out = np.empty(len(lo))
        if not len(lo):
            return out
        j = np.floor(np.log2(np.maximum(hi - lo + 1, 1))).astype(np.int64)
        for jj in np.unique(j):
            m = j == jj
            out[m] = np.maximum(self.lv[jj][lo[m]], self.lv[jj][hi[m] - (1 << int(jj)) + 1])
        return out


def view(P, i0, rd=None):
    """Срез куска с бара i0 (цены, ATR, живость, vr; показания MRI rd — тем же срезом) и таблицы максимумов h, −l, c, −c."""
    V = {k: P[k][i0:] for k in ('T', 'o', 'h', 'l', 'c', 'atr', 'live', 'vr')}
    V['i0'] = i0
    V['rd'] = None if rd is None else {k: v[i0:] for k, v in rd.items()}
    V['tab'] = {'h': MaxTable(V['h']), 'nl': MaxTable(-V['l']), 'c': MaxTable(V['c']), 'nc': MaxTable(-V['c'])}
    return V


