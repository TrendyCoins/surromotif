def readings_asset(a, tf, bars, caches, n_r):
    """Показания на барах кусков: реал — линия M по его окнам (lm, c, z), случайные рынки j — z их окон на базе линии реала;
       оба периода (окна TUNE и VAL — на разных барах). Сверка: окна кэша Levels = окна кэша Flow, знаки — та же контрольная
       сумма. Возвращает {'real': [rd по кускам], 'rand': [[rd по кускам] для j]}."""
    def blank():
        return {k: np.full(len(P['T']), np.nan, dtype=np.float32) for k in ('lm', 'c', 'z')}
    out = {'real': [None] * len(bars['pieces']), 'rand': [[None] * len(bars['pieces']) for _ in range(n_r)]}
    for pi, P in enumerate(bars['pieces']):
        out['real'][pi] = blank()
        for j in range(n_r):
            out['rand'][j][pi] = blank()
    ceil = math.log(LEV['ceiling'][tf])
    for src, part in LEV['periods'].items():
        C, Z, q, zk, lg, tags = caches[src]
        if a not in lg or a not in Z['res']:
            continue
        zr = Z['res'][a]
        t = C['res'][a]['t'].astype(np.int64)
        if not np.array_equal(zr['t'].astype(np.int64), t):
            raise ValueError(f"🍆 АЙ, ОШИБКА! (0в) {a} {tf} {part}: окна кэша Levels не те же, что в кэше Flow")
        key = 'tr' if part == 'tune' else 'va'
        pi = bars['loc'][key][0]
        P = bars['pieces'][pi]
        idx = np.searchsorted(P['T'], t)
        if np.any(idx >= len(P['T'])) or not np.array_equal(P['T'][np.minimum(idx, len(P['T']) - 1)], t):
            raise ValueError(f"🍆 АЙ, ОШИБКА! {a} {tf} {part}: окна кэша не легли на бары куска — данные из разных выгрузок")
        z = FL.to_z(lg[a]['sp'], q, zk)
        lm = EF.line_parts(z)[0]
        rd = out['real'][pi]
        rd['lm'][idx], rd['c'][idx], rd['z'][idx] = lm, np.clip(lm / ceil, -1, 1), z
        for j in range(n_r):
            sg = rand_signs(a, j, pi, P['T'])
            if signs_crc(sg) != int(zr[f'crc{j}'][0]):
                raise ValueError(f"🍆 АЙ, ОШИБКА! (0в) {a} {tf} {part}: знаки случайного рынка {j} не те, что в 'score'")
            zx = FL.to_z(np.mean([zr[f"{tg}__rm{j}"].astype(np.float64) for tg in tags], axis=0), q, zk)
            lmx = EF.line_parts(z, zx)[0]
            rx = out['rand'][j][pi]
            rx['lm'][idx], rx['c'][idx], rx['z'][idx] = lmx, np.clip(lmx / ceil, -1, 1), zx
    return out


def asset_run(a, tf, readings, n_r, ks):
    """События ассета с показаниями: реал (все семейства, профили у главных и плацебо-day / week), случайные рынки 0 … n_r − 1."""
    bars = readings['bars']
    bar_ns = LEV['bar_ns'][tf]
    prof = LEV['main'][tf] + ('day_p', 'week_p')
    out = {'real': {}, 'rand': {}}
    for pi, P in enumerate(bars['pieces']):
        i0 = int(np.searchsorted(P['T'], ns(LEV['zz_from'])))
        if len(P['T']) - i0 < 1000:
            continue
        V = view(P, i0, readings['real'][pi])
        ev = market_events(V, FAMS_REAL, LEV['scales'][tf], bar_ns, 0, 0, ks, prof)
        for f, t in ev.items():
            out['real'].setdefault(f, []).append(t)
        del V
        for j in range(n_r):
            R = mirror_bars(P, rand_signs(a, j, pi, P['T']))
            VR = view(R, i0, readings['rand'][j][pi])
            r0 = int(np.searchsorted(VR['T'], ns(LEV['rand_from'])))
            ev = market_events(VR, FAMS_RAND, LEV['scales'][tf], bar_ns, 0, r0, ks, LEV['main'][tf] if j == 0 else ())
            for f, t in ev.items():
                out['rand'].setdefault(f, []).append(dict(t, rj=np.full(len(t['t0']), j, dtype=np.int8)))
            del VR, R
    return out


def thirds(v, key, cuts):
    x = v[key]
    return [None if x is None else (x <= cuts[0]), None if x is None else ((x > cuts[0]) & (x <= cuts[1])),
            None if x is None else (x > cuts[1])]


def run_stats(tf, R):
    """Шаг 2 и справочное: D по главной выборке, ярлык E, фраза; D по семействам, третям волатильности, z и изменения цвета;
       k = 1 и 4; 5 корзин; шаг 1 — профили."""
    main = LEV['main'][tf]
    res = {'main': {}, 'label': {}, 'fam': {}, 'vol': {}, 'zt': {}, 'appr': {}, 'k': {}, 'bins': {}, 'prof': {}, 'n': {}}
    Bs = {}
    tabs_all = [t for mk in R.values() for t in mk.values()]
    for i, src in enumerate(('search', 'confirm')):
        lo, hi = period_bounds(src)
        Bs[src] = boot_setup(all_weeks(tabs_all, lo, hi), [LEV['seed'], 22, i])

    def pooled(mk, fams, q, sfx, lo, hi):
        return pooled_views(R, mk, fams, q, sfx, lo, hi)

    for q in QS:
        st, lab = {}, {}
        for src in ('search', 'confirm'):
            lo, hi = period_bounds(src)
            vr, vx = pooled('real', main, q, '', lo, hi), pooled('rand', main, q, '', lo, hi)
            st[src] = d_stat(Bs[src], vr, vx)
            lf = LEV['label_fam'] if tf == '5M' else 'week'
            lab[src] = e_stat(Bs[src], pooled('real', (lf,), q, '', lo, hi), pooled('real', (lf + '_p',), q, '', lo, hi))
            # справочно
            for f in LEV['fams_ref'][tf]:
                res['fam'].setdefault((f, q), {})[src] = d_stat(Bs[src], pooled('real', (f,), q, '', lo, hi),
                                                                 pooled('rand', (f,), q, '', lo, hi))
            for sfx_k in LEV['k_ref']:
                sfx = f"_k{sfx_k:g}"
                res['k'].setdefault((sfx_k, q), {})[src] = d_stat(Bs[src], pooled('real', main, q, sfx, lo, hi),
                                                                   pooled('rand', main, q, sfx, lo, hi))
            if vr is not None and vx is not None:
                for key, store in (('vr', 'vol'), ('z', 'zt'), ('dc', 'appr')):
                    if vr.get(key) is None or vx.get(key) is None:
                        continue
                    x = vr[key][np.isfinite(vr[key])]
                    if len(x) < 30:
                        continue
                    cuts = np.quantile(x, [1 / 3, 2 / 3])
                    tr_, tx_ = thirds(vr, key, cuts), thirds(vx, key, cuts)
                    if key == 'vr':
                        res['vol'].setdefault(q, {})[src] = [d_stat(Bs[src], vr, vx, a_, b_) for a_, b_ in zip(tr_, tx_)]
                    else:                                    # верхняя треть против нижней (без цвета): у реала − у случайного
                        G = {'RH': counts(Bs[src], vr, tr_[2]), 'RL': counts(Bs[src], vr, tr_[0]),
                             'XH': counts(Bs[src], vx, tx_[2]), 'XL': counts(Bs[src], vx, tx_[0])}
                        res[store].setdefault(q, {})[src] = lin_stat(Bs[src], G, [(1, 'RH'), (-1, 'RL'), (-1, 'XH'), (1, 'XL')],
                                                                     ['RH', 'RL'])
                e1, e3 = (math.log(b) for b in LEV['bins'])
                for mk, v in (('real', vr), ('rand', vx)):
                    lm = v['lm']
                    with np.errstate(invalid='ignore'):
                        masks = (lm <= -e3, (lm > -e3) & (lm <= -e1), (lm > -e1) & (lm < e1), (lm >= e1) & (lm < e3), lm >= e3)
                    res['bins'].setdefault((q, mk), {})[src] = [
                        {'n': int(m.sum()), 'p': float(v['y'][m].mean()) if m.any() else math.nan} for m in masks]
                res['n'][(q, src)] = {'real': len(vr['y']), 'rand': len(vx['y']),
                                      'real_or': int(colors_of(vr)[0].sum()), 'real_si': int(colors_of(vr)[1].sum()),
                                      'rand_or': int(colors_of(vx)[0].sum()), 'rand_si': int(colors_of(vx)[1].sum())}
        sg = sees({s: (x['D'] if x else None) for s, x in st.items()})
        eg = sees(lab) if sg else 0
        conf = st.get('confirm')
        claim = bool(sg and conf and abs(conf['D']['d']) >= LEV['claim'])
        res['main'][q] = {'st': st, 'sees': sg, 'meaning': MEANING.get((q, sg)), 'claim': claim}
        res['label'][q] = {'st': lab, 'label': (None if not sg else ('именно у уровня' if eg == sg else 'не только у уровня'))}
    # шаг 1: профили (главная выборка реала, случайного рынка, плацебо; реал по исходам)
    for q, pk in (('g1', '0'), ('g2', '1')):
        for src in ('search', 'confirm'):
            lo, hi = period_bounds(src)
            rows = {}
            for name, mk, fams in (('real', 'real', main), ('rand', 'rand', main),
                                   ('placebo', 'real', (main[0] + '_p',))):
                for kind in ('c', 'z'):
                    acc, acc1, acc0 = [], [], []
                    for f in fams:
                        tab = R[mk].get(f)
                        if tab is None or f"p{kind}{pk}" not in tab:
                            continue
                        v_m = q_view_mask(tab, q, lo, hi)
                        pr = tab[f"p{kind}{pk}"][v_m]
                        acc.append(pr)
                        if name == 'real':
                            yy = (tab['g1'] if q == 'g1' else tab['g2'])[v_m]
                            acc1.append(pr[yy == 1])
                            acc0.append(pr[yy == 0])
                    if acc:
                        with np.errstate(invalid='ignore'), _quiet():
                            for nm1, a1 in [(name, acc)] + ([('real_1', acc1), ('real_0', acc0)] if name == 'real' else []):
                                A1 = np.concatenate(a1).astype(np.float32)
                                A1 = A1[np.isfinite(A1).any(axis=1)]           # без профиля (реализации 1+, начало ряда)
                                rows[(nm1, kind)] = (np.nanmean(A1, axis=0), len(A1))
            res['prof'][(q, src)] = rows
    return res


@contextlib.contextmanager
def _quiet():
    import warnings
    with warnings.catch_warnings():
        warnings.simplefilter('ignore', category=RuntimeWarning)
        yield


def q_view_mask(tab, q, lo, hi):
    """Маска строк таблицы, попавших в выборку вопроса q за период (как q_view, без среза)."""
    if q == 'g1':
        m = (tab['cat1'] == 0) & np.isfinite(tab['g1']) & tab['live0'].astype(bool)
        T = tab['T0']
    else:
        m = (tab['cat2'] == 0) & np.isfinite(tab['g2']) & tab['live1'].astype(bool)
        T = tab['T1']
    m &= T >= lo
    if hi is not None:
        m &= T < hi
    return m


