def q_view(tab, q, sfx='', T_lo=None, T_hi=None):
    """Выборка вопроса q: 'g1' — тесты с решённым исходом (y — отскок), 'g2' — слабые пробои с решённым исходом (y — ложный);
       s — слой по x (y) шириной k / n_strata; время — бар события; T_lo <= время < T_hi."""
    if tab is None:
        return None
    k = LEV['k'] if not sfx else float(sfx[2:])
    if q == 'g1':
        m = (tab['cat1' + sfx] == 0) & np.isfinite(tab['g1' + sfx]) & tab['live0' + sfx].astype(bool)
        y, xv, T = tab['g1' + sfx], tab['x' + sfx], tab['T0']
        rd = {'lm': tab.get('lm0'), 'z': tab.get('z0'), 'c': tab.get('c0'), 'dc': tab.get('dc0'), 'vr': tab['vr0']}
    else:
        m = (tab['cat2' + sfx] == 0) & np.isfinite(tab['g2' + sfx]) & tab['live1' + sfx].astype(bool)
        y, xv, T = tab['g2' + sfx], tab['y' + sfx], tab['T1' + sfx]
        rd = {'lm': tab.get('lm1' + sfx), 'z': tab.get('z1') if not sfx else None, 'c': tab.get('c1') if not sfx else None,
              'dc': None, 'vr': tab['vr1' + sfx]}
    if T_lo is not None:
        m &= T >= T_lo
    if T_hi is not None:
        m &= T < T_hi
    i = np.flatnonzero(m)
    s = np.clip(np.floor(xv[i] / (k / LEV['n_strata'])), 0, LEV['n_strata'] - 1).astype(np.int64)
    out = {'y': y[i].astype(np.float64), 's': s, 'T': T[i], 'wk': T[i] // WEEK_NS, 'asset': tab['asset'][i]}
    for kk, v in rd.items():
        out[kk] = None if v is None else v[i]
    return out


def pooled_views(R, mk, fams, q, sfx, lo, hi):
    """Выборка вопроса q по нескольким семействам рынка mk (R[mk][семейство] — таблицы) — одной выборкой; поле, которого нет
       хоть у одного семейства, — None."""
    vs = [q_view(R[mk].get(f), q, sfx, lo, hi) for f in fams]
    vs = [v for v in vs if v is not None and len(v['y'])]
    if not vs:
        return None
    return {k: (None if any(v[k] is None for v in vs) else np.concatenate([v[k] for v in vs])) for k in vs[0]}


def boot_setup(weeks, seed, nb=None):
    """Повторы бутстрепа по неделям: M (nb × недель) — сколько раз неделя попала в повтор; один набор на период."""
    uw = np.unique(np.asarray(weeks, dtype=np.int64))
    nb = nb or LEV['n_boot']
    rng = np.random.default_rng(seed)
    M = np.zeros((nb, len(uw)))
    if len(uw):
        np.add.at(M, (np.repeat(np.arange(nb), len(uw)), rng.integers(0, len(uw), nb * len(uw))), 1.0)
    return {'uw': uw, 'M': M, 'one': np.ones((1, len(uw)))}


def counts(B, v, m=None):
    """События выборки v (маска m) по неделям × слоям: (n, сумма исхода)."""
    K = LEV['n_strata']
    n = np.zeros((len(B['uw']), K))
    sm = np.zeros_like(n)
    if v is None:
        return n, sm
    m = np.ones(len(v['y']), dtype=bool) if m is None else m
    if m.any():
        wi = np.searchsorted(B['uw'], v['wk'][m])
        if np.any(wi >= len(B['uw'])) or np.any(B['uw'][np.minimum(wi, len(B['uw']) - 1)] != v['wk'][m]):
            raise ValueError("🍆 АЙ, ОШИБКА! неделя события не в наборе недель бутстрепа")
        np.add.at(n, (wi, v['s'][m]), 1.0)
        np.add.at(sm, (wi, v['s'][m]), v['y'][m])
    return n, sm


def lin_stat(B, G, expr, ref):
    """Σ_k w_k Σ_i c_i · p_i,k по слоям k, где у всех групп выражения есть события; w_k ∝ событиям групп ref. Точка, 95% интервал
       и ошибка — по повторам бутстрепа; рядом — числа событий и сырые доли групп."""
    names = sorted({g for _, g in expr} | set(ref))

    def val(Mx):
        N = {g: Mx @ G[g][0] for g in names}
        S = {g: Mx @ G[g][1] for g in names}
        ok = np.all([N[g] > 0 for _, g in expr], axis=0)
        W = sum(N[g] for g in ref) * ok
        tot = W.sum(1)
        with np.errstate(invalid='ignore', divide='ignore'):
            v = sum(cf * np.where(ok, S[g] / np.where(N[g] > 0, N[g], 1.0), 0.0) for cf, g in expr)
            out = (W * v).sum(1) / tot
        out[~(tot > 0)] = np.nan
        return out
    d = float(val(B['one'])[0]) if B['one'].shape[1] else math.nan
    bs = val(B['M']) if B['M'].shape[1] else np.zeros(0)
    bs = bs[np.isfinite(bs)]
    se = float(np.std(bs, ddof=1)) if len(bs) > 1 else math.nan
    ci = (float(np.quantile(bs, 0.025)), float(np.quantile(bs, 0.975))) if len(bs) > 1 else (math.nan, math.nan)
    n = {g: int(G[g][0].sum()) for g in names}
    with np.errstate(invalid='ignore', divide='ignore'):
        p = {g: float(G[g][1].sum() / G[g][0].sum()) if G[g][0].sum() > 0 else math.nan for g in names}
    return {'d': d, 'ci': ci, 'se': se, 't': d / se if se and se > 0 else math.nan, 'n': n, 'p': p}


def colors_of(v):
    """Маски оранжевого (log M >= ln mark) и серебра (log M <= −ln mark)."""
    e = math.log(LEV['mark'])
    lm = v['lm']
    with np.errstate(invalid='ignore'):
        return lm >= e, lm <= -e


def d_stat(B, vr, vx, extra_r=None, extra_x=None):
    """D = Δ реала − Δ случайного рынка (Δ — доля при оранжевом − при серебре, по слоям, веса — события реала обоих цветов);
       рядом Δ реала и Δ случайного рынка (веса те же). extra — дополнительные маски событий (трети и т. п.)."""
    if vr is None or vx is None:
        return None
    ro, rs = colors_of(vr)
    xo, xs = colors_of(vx)
    if extra_r is not None:
        ro, rs = ro & extra_r, rs & extra_r
    if extra_x is not None:
        xo, xs = xo & extra_x, xs & extra_x
    G = {'RO': counts(B, vr, ro), 'RS': counts(B, vr, rs), 'XO': counts(B, vx, xo), 'XS': counts(B, vx, xs)}
    return {'D': lin_stat(B, G, [(1, 'RO'), (-1, 'RS'), (-1, 'XO'), (1, 'XS')], ['RO', 'RS']),
            'dr': lin_stat(B, G, [(1, 'RO'), (-1, 'RS')], ['RO', 'RS']),
            'dx': lin_stat(B, G, [(1, 'XO'), (-1, 'XS')], ['RO', 'RS'])}


def e_stat(B, vt, vp):
    """E = Δ реала у настоящих уровней − Δ реала у плацебо (веса — настоящие события обоих цветов)."""
    if vt is None or vp is None:
        return None
    to, ts = colors_of(vt)
    po, ps = colors_of(vp)
    G = {'TO': counts(B, vt, to), 'TS': counts(B, vt, ts), 'PO': counts(B, vp, po), 'PS': counts(B, vp, ps)}
    return lin_stat(B, G, [(1, 'TO'), (-1, 'TS'), (-1, 'PO'), (1, 'PS')], ['TO', 'TS'])


def c0_stat(B, va, vb):
    """(Ц0): d = доля у реала − у пустышки, по слоям, веса — события реала."""
    if va is None or vb is None:
        return None
    G = {'A': counts(B, va), 'B': counts(B, vb)}
    return lin_stat(B, G, [(1, 'A'), (-1, 'B')], ['A'])


def sees(st):
    """Знак, одинаковый на обоих периодах при 95% интервалах без нуля (+1 / −1), иначе 0."""
    try:
        a, b = st['search'], st['confirm']
    except (KeyError, TypeError):
        return 0
    if a is None or b is None or not (np.isfinite(a['d']) and np.isfinite(b['d'])):
        return 0
    for sg in (1, -1):
        if all(sg * x['d'] > 0 and sg * x['ci'][0] > 0 and sg * x['ci'][1] > 0 for x in (a, b)):
            return sg
    return 0


def _st(x, pp=True):
    if not x or not np.isfinite(x.get('d', math.nan)):
        return f"{'—':^30}"
    m = 100.0 if pp else 1.0
    return f"{m * x['d']:+6.2f} [{m * x['ci'][0]:+6.2f}; {m * x['ci'][1]:+6.2f}] ({_f(x['t'], '+.1f')})"


def period_bounds(src):
    """Границы периода по времени бара события: поиск — [tune_start, val_start), подтверждение — [val_start, ∞),
       FIT (справочно) — [fit_from, tune_start)."""
    return {'search': (ns(LEV['tune_start']), ns(LEV['val_start'])), 'confirm': (ns(LEV['val_start']), None),
            'fit': (ns(LEV['fit_from']), ns(LEV['tune_start']))}[src]


def all_weeks(tabs, T_lo, T_hi):
    """Недели всех событий (Г1 и Г2) всех таблиц периода — набор недель бутстрепа."""
    w = []
    for tab in tabs:
        if tab is None:
            continue
        for q in QS:
            v = q_view(tab, q, '', T_lo, T_hi)
            if v is not None and len(v['wk']):
                w.append(v['wk'])
    return np.concatenate(w) if w else np.zeros(0, dtype=np.int64)


