def week_bars():
    return 7 * 1440 // STAND['bar_min']


def world_asset(kind, seed, ia):
    """Синтетический ряд 5M мира kind (см. шапку, (ст3)). Возвращает кусок цены."""
    P_ = STAND
    rng = np.random.default_rng([seed, ia, 7])
    bar_ns = P_['bar_min'] * 60 * 10 ** 9
    n = P_['warm'] + 2 * P_['weeks'] * week_bars()
    sig = P_['sigma']
    vol = np.ones(n)
    if kind in ('sizes', 'saw'):
        lv = np.zeros(n)
        e = rng.normal(0, P_['vol_eps'], n)
        for i in range(1, n):
            lv[i] = P_['vol_rho'] * lv[i - 1] + e[i]
        vol = np.exp(lv - lv.mean())
    if kind in ('level', 'regime'):
        reg = np.zeros(n, dtype=bool)
        i, on = 0, rng.random() < P_['reg_share']
        while i < n:
            ln = int(rng.geometric(1.0 / (P_['reg_len'] if on else P_['reg_len'] * (1 - P_['reg_share']) / P_['reg_share'])))
            reg[i:i + ln] = on
            i += ln
            on = not on
        phi, k_ou, al = P_['ac1_reg'], P_['ou_k'], 2.0 / (P_['ou_span'] + 1)
        eps = rng.normal(0, 1, n)
        wu, wd = np.abs(rng.normal(0, 1, n)) * P_['wick'] * sig, np.abs(rng.normal(0, 1, n)) * P_['wick'] * sig
        T = ns(P_['t0']) + bar_ns * np.arange(n, dtype=np.int64)
        day = T // DAY_NS
        o, h, l, c = np.empty(n), np.empty(n), np.empty(n), np.empty(n)
        prev, ema, u = 1e4, 1e4, 0.0
        cur, dh, dl, pdh, pdl, th, tl = day[0], -np.inf, np.inf, np.nan, np.nan, True, True
        push, side = 0, 0
        sq = math.sqrt(1 - phi * phi)
        for t in range(n):
            if day[t] != cur:
                pdh, pdl, th, tl = dh, dl, False, False
                cur, dh, dl = day[t], -np.inf, np.inf
            u = phi * u + sq * eps[t] if reg[t] else eps[t]
            step = sig * u
            if kind == 'regime' and reg[t]:
                step -= k_ou * (prev - ema)
            if push > 0:
                step -= side * P_['reflect'] * sig
                push -= 1
            ct = prev + step
            ht, lt_ = max(prev, ct) + wu[t], min(prev, ct) - wd[t]
            if not th and ht >= pdh:
                th = True
                if kind == 'level' and reg[t]:
                    push, side = P_['reflect_bars'], 1
            if not tl and lt_ <= pdl:
                tl = True
                if kind == 'level' and reg[t]:
                    push, side = P_['reflect_bars'], -1
            o[t], h[t], l[t], c[t] = prev, ht, lt_, ct
            dh, dl = max(dh, ht), min(dl, lt_)
            ema += al * (ct - ema)
            prev = ct
        return add_norm({'T': T, 'o': o, 'h': h, 'l': l, 'c': c})
    if kind == 'saw':
        from scipy.signal import lfilter
        phi = P_['ac1_saw']
        u = lfilter([1.0], [1.0, -phi], rng.normal(0, 1, n)) * math.sqrt(1 - phi * phi)
        steps = sig * vol * u
    else:
        steps = sig * vol * rng.normal(0, 1, n)
    return synth_ohlc(steps, rng, sig * vol, P_['wick'], bar_ns=bar_ns)


def _windows(c, L=64):
    r = np.diff(c)
    idx = np.arange(L - 1, len(r))[:, None] + np.arange(-(L - 1), 1)[None, :]
    return r[idx]                                       # окно шагов, кончающееся на баре idx + 1


def proxy_logit(kind, W, rng):
    """MRI-заменитель (ст3): функция окна шагов — AC1 (пила, вязкий режим) и / или размеры; плюс шум."""
    P_ = STAND
    x = W - W.mean(1, keepdims=True)
    den = (x * x).sum(1)
    ac = np.where(den > 0, (x[:, 1:] * x[:, :-1]).sum(1) / np.where(den > 0, den, 1.0), 0.0)
    aw = np.abs(W)
    size = np.log(aw[:, -16:].mean(1) / np.maximum(aw.mean(1), 1e-12))
    lg = {'level': -P_['px_ac'] * ac, 'regime': -P_['px_ac'] * ac, 'zero': -P_['px_ac'] * ac,
          'sizes': P_['px_size'] * size, 'saw': -P_['px_ac'] * ac + 0.5 * P_['px_size'] * size}[kind]
    return lg + rng.normal(0, P_['px_noise'], len(lg))


def coin_signs(n, L, rng):
    """Знак каждого бара окна — монетка (суррогат линейки стенда: у заменителя — пила соседних баров, sflip4 её бы сохранил)."""
    return np.where(rng.random((n, L)) < 0.5, -1.0, 1.0)


