# ГОНКИ: Г1 (касание -> отскок / пробой), Г2 (пробой -> ложный / настоящий)
# =====================================================================
def races(V, ev, k, H):
    """Гонки по close для событий-касаний ev при пороге k ATR и горизонте H баров (см. шапку). cat1: 0 — тест, 1 — пробой на
       касании, 2 — отбит на касании; g1: 1 — отскок, 0 — пробой, NaN — не решено / не тест. t1 — бар пробоя (−1 — нет); cat2:
       0 — слабый, 1 — сильный, −1 — нет пробоя; g2: 1 — ложный, 0 — настоящий, NaN — не решено / не слабый. osl — «по Ослер»:
       close через osler_bars баров на исходной стороне (или на уровне); mv — ход через move_bars после пробоя, в ATR(t1)."""
    n = len(V['c'])
    c, atr, live, tab = V['c'], V['atr'], V['live'], V['tab']
    s, L, t0 = ev['side'].astype(np.int64), ev['L'], ev['t0']
    m_ = len(L)
    a0 = atr[t0] if m_ else np.zeros(0)
    with np.errstate(invalid='ignore', divide='ignore'):
        x = s * (L - c[t0]) / a0 if m_ else np.zeros(0)
    cat1 = np.where(x < 0, 1, np.where(x >= k, 2, 0)).astype(np.int8)
    test = cat1 == 0
    up = s > 0
    st, en = t0 + 1, np.minimum(t0 + 1 + H, n)
    t_br, t_bo = np.full(m_, -1, dtype=np.int64), np.full(m_, -1, dtype=np.int64)
    for m, tb, tbo, thr_br, thr_bo in (
            (test & up, 'c', 'nc', np.nextafter(L, np.inf), -(L - k * a0)),
            (test & ~up, 'nc', 'c', np.nextafter(-L, np.inf), L + k * a0)):
        if m.any():
            t_br[m] = tab[tb].first_ge(st[m], thr_br[m], en[m])
            t_bo[m] = tab[tbo].first_ge(st[m], thr_bo[m], en[m])
    bo_first = (t_bo >= 0) & ((t_br < 0) | (t_bo < t_br))
    br_first = (t_br >= 0) & ((t_bo < 0) | (t_br < t_bo))
    g1 = np.full(m_, np.nan)
    g1[test & bo_first] = 1.0
    g1[test & br_first] = 0.0
    t1 = np.where(cat1 == 1, t0, np.where(test & br_first, t_br, -1)).astype(np.int64)
    has = t1 >= 0
    ti = np.maximum(t1, 0)
    a1 = np.where(has, atr[ti], np.nan) if m_ else np.zeros(0)
    with np.errstate(invalid='ignore', divide='ignore'):
        y = np.where(has, s * (c[ti] - L) / a1, np.nan) if m_ else np.zeros(0)
        cat2 = np.where(has, np.where(y >= k, 1, 0), -1).astype(np.int8)
    weak = cat2 == 0
    st2, en2 = t1 + 1, np.minimum(t1 + 1 + H, n)
    t_f, t_t = np.full(m_, -1, dtype=np.int64), np.full(m_, -1, dtype=np.int64)
    for m, tf_, tt_, thr_f, thr_t in (
            (weak & up, 'nc', 'c', -L, L + k * a1),
            (weak & ~up, 'c', 'nc', L, -(L - k * a1))):
        if m.any():
            t_f[m] = tab[tf_].first_ge(st2[m], thr_f[m], en2[m])
            t_t[m] = tab[tt_].first_ge(st2[m], thr_t[m], en2[m])
    f_first = (t_f >= 0) & ((t_t < 0) | (t_f < t_t))
    t_first = (t_t >= 0) & ((t_f < 0) | (t_t < t_f))
    g2 = np.full(m_, np.nan)
    g2[weak & f_first] = 1.0
    g2[weak & t_first] = 0.0
    j3 = t0 + LEV['osler_bars']
    ok3 = j3 < n
    osl = np.where(ok3, (s * (L - c[np.minimum(j3, n - 1)]) >= 0).astype(np.float64), np.nan) if m_ else np.zeros(0)
    j12 = t1 + LEV['move_bars']
    ok12 = has & (j12 < n)
    with np.errstate(invalid='ignore'):
        mv = np.where(ok12, s * (c[np.minimum(j12, n - 1)] - c[ti]) / a1, np.nan) if m_ else np.zeros(0)
    return {'x': x, 'cat1': cat1, 'g1': g1, 't1': t1, 'y': y, 'cat2': cat2, 'g2': g2, 'osl': osl, 'mv': mv,
            'live0': live[t0] if m_ else np.zeros(0, dtype=bool),
            'live1': (has & live[ti]) if m_ else np.zeros(0, dtype=bool)}


def races_slow(V, ev, k, H):
    """То же, что races, событие за событием (эталон стенда)."""
    c, atr, n = V['c'], V['atr'], len(V['c'])
    out = {kk: [] for kk in ('cat1', 'g1', 't1', 'cat2', 'g2')}
    for s, L, t0 in zip(ev['side'], ev['L'], ev['t0']):
        a0 = atr[t0]
        x = s * (L - c[t0]) / a0
        cat1, g1, t1 = (1 if x < 0 else 2 if x >= k else 0), np.nan, -1
        if cat1 == 1:
            t1 = t0
        elif cat1 == 0:
            for t in range(t0 + 1, min(t0 + 1 + H, n)):
                if s * (c[t] - L) > 0:
                    g1, t1 = 0.0, t
                    break
                if s * (L - c[t]) >= k * a0:
                    g1 = 1.0
                    break
        cat2, g2 = -1, np.nan
        if t1 >= 0:
            a1 = atr[t1]
            y = s * (c[t1] - L) / a1
            cat2 = 1 if y >= k else 0
            if cat2 == 0:
                for t in range(t1 + 1, min(t1 + 1 + H, n)):
                    if s * (c[t] - L) <= 0:
                        g2 = 1.0
                        break
                    if s * (c[t] - L) >= k * a1:
                        g2 = 0.0
                        break
        for kk, v in (('cat1', cat1), ('g1', g1), ('t1', t1), ('cat2', cat2), ('g2', g2)):
            out[kk].append(v)
    return {kk: np.asarray(v) for kk, v in out.items()}


# =====================================================================
# СОБЫТИЯ РЫНКА: уровни -> касания -> гонки -> показания на барах событий
# =====================================================================
def _at(x, t):
    """x[t] (t < 0 — NaN)."""
    t = np.asarray(t, dtype=np.int64)
    if not len(t):
        return np.zeros(0)
    return np.where(t >= 0, x[np.maximum(t, 0)], np.nan)


PROF_LAGS = np.arange(LEV['prof'][0], LEV['prof'][1] + 1, 2)     # профили — через бар (память)


def profile(x, t):
    """x на барах t + lag (lag — PROF_LAGS, от prof[0] до prof[1]), минус значение на t + prof[0]; float16 (память; для средних
       хватает); вне ряда и t < 0 — NaN."""
    t = np.asarray(t, dtype=np.int64)
    idx = t[:, None] + PROF_LAGS[None, :]
    ok = (idx >= 0) & (idx < len(x)) & (t[:, None] >= 0)
    v = np.where(ok, x[np.clip(idx, 0, len(x) - 1)], np.nan)
    return (v - v[:, :1]).astype(np.float16)


def event_table(V, ev, ks, prof=False):
    """Таблица событий семейства: касание, гонки при каждом k (основной k — без суффикса, остальные — '_k<k>'), показания MRI
       (если у среза есть rd): на t0 — lm0, c0, z0, dc0 (изменение цвета за appr_bars до касания), на t1 — lm1, c1, z1;
       профили цвета и z вокруг t0 и t1 (prof)."""
    t0 = ev['t0']
    tab = {'side': ev['side'], 'L': ev['L'], 'b': ev['b'], 't0': t0, 'T0': V['T'][t0], 'vr0': V['vr'][t0]}
    rd = V['rd']
    for k in ks:
        R = races(V, ev, k, LEV['H'])
        sfx = '' if k == LEV['k'] else f"_k{k:g}"
        for name in ('x', 'cat1', 'g1', 't1', 'y', 'cat2', 'g2', 'live0', 'live1'):
            tab[name + sfx] = R[name]
        tab['T1' + sfx] = np.where(R['t1'] >= 0, V['T'][np.maximum(R['t1'], 0)], -1) if len(t0) else np.zeros(0, np.int64)
        tab['vr1' + sfx] = _at(V['vr'], R['t1'])
        if sfx == '':
            tab['osl'], tab['mv'] = R['osl'], R['mv']
        if rd is not None:
            tab['lm1' + sfx] = _at(rd['lm'], R['t1'])
    if rd is not None:
        t1 = tab['t1']
        tab.update({'lm0': _at(rd['lm'], t0), 'c0': _at(rd['c'], t0), 'z0': _at(rd['z'], t0),
                    'dc0': _at(rd['c'], t0) - _at(rd['c'], np.where(t0 >= LEV['appr_bars'], t0 - LEV['appr_bars'], -1)),
                    'c1': _at(rd['c'], t1), 'z1': _at(rd['z'], t1)})
        if prof:
            tab.update({'pc0': profile(rd['c'], t0), 'pz0': profile(rd['z'], t0),
                        'pc1': profile(rd['c'], t1), 'pz1': profile(rd['z'], t1)})
    return tab


def market_events(V, fams, scales, bar_ns, s0, born_from, ks, prof_fams=()):
    """События семейств fams на срезе V: уровни свечей и плацебо, пивоты (зигзаг — с бара s0); уровни, родившиеся раньше
       born_from, не берутся (у случайного рынка — rand_from). Возвращает {семейство: таблица}."""
    out, true_all = {}, {}
    for fam in fams:
        if fam in ('day', 'week'):
            lev = calendar_levels(V, bar_ns, fam, 0)
            true_all[fam] = lev
            ev = touch(V, _sel(lev, born_ok(V, lev) & (lev['b'] >= born_from)))
        elif fam in ('day_p', 'week_p'):
            base = fam[:-2]
            true = true_all.get(base) or calendar_levels(V, bar_ns, base, 0)
            parts = []
            for h in LEV['placebo_h'][base]:
                lev = calendar_levels(V, bar_ns, base, h)
                e_ = touch(V, _sel(lev, born_ok(V, lev) & (lev['b'] >= born_from)))
                parts.append(_sel(e_, ~near_true(e_, true, V['atr'])))
            ev = dedupe({k: np.concatenate([p[k] for p in parts]) for k in parts[0]})
        elif fam.startswith('piv_'):
            lev, dirs = pivot_levels(V, scales[fam[4:]], s0)
            ev = touch(V, _sel(lev, born_ok(V, lev) & (lev['b'] >= born_from)), dirs)
        else:
            raise ValueError(f"🍆 АЙ, ОШИБКА! семейство {fam}")
        out[fam] = event_table(V, ev, ks, prof=fam in prof_fams)
    return out


def cat_tabs(parts):
    """Склейка таблиц (у каждой — поля asset и rj). Поле, которого нет у части таблиц (профили случайного рынка — только у
       реализации 0), у остальных заполняется NaN; так можно только с дробными полями."""
    parts = [p for p in parts if p is not None and len(p['t0'])]
    if not parts:
        return None
    out = {}
    for k in dict.fromkeys(k for p in parts for k in p):
        ref = next(p[k] for p in parts if k in p)
        if ref.dtype.kind != 'f' and not all(k in p for p in parts):
            raise ValueError(f"🍆 АЙ, ОШИБКА! поле {k} есть не у всех таблиц")
        out[k] = np.concatenate([p[k] if k in p else np.full((len(p['t0']),) + ref.shape[1:], np.nan, dtype=ref.dtype)
                                 for p in parts], axis=0)
    return out


