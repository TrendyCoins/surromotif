def write_rand_files(dst, a, tf, bars, sg_piece, src_dir):
    """Файлы research случайного рынка (для сверки (ст4)): r = знак · r, e = знак · e, d = знак · d, ширина — та же, OHLC —
       зеркало бара; контрольные суммы — новые. Один кусок (склеенные части)."""
    N = LEV['N']
    os.makedirs(dst, exist_ok=True)
    P = bars['pieces'][0]
    R = mirror_bars(P, sg_piece)
    src = {k: dict(np.load(src_dir + f"smc_{k}_{a}_{tf}_N{N}.npz", allow_pickle=False)) for k in ('series', 'prices', 'range', 'bars')}
    crc = {}
    for key in ('tr', 'va'):
        _, o0 = bars['loc'][key]
        n = bars['n'][key]
        s = sg_piece[o0:o0 + n]
        r = (src['series'][f'r_{key}'].astype(np.float64) * s).astype(np.float32)
        src['series'][f'r_{key}'] = r
        src['series'][f'close_{key}'] = R['c'][o0:o0 + n].copy()
        crc[key] = zlib.crc32(r.tobytes())
        for nm in ('hl2', 'hlc3'):
            src['prices'][f'e_{nm}_{key}'] = (src['prices'][f'e_{nm}_{key}'].astype(np.float64) * s).astype(np.float32)
            src['prices'][f'd_{nm}_{key}'] = (src['prices'][f'd_{nm}_{key}'].astype(np.float64) * s).astype(np.float32)
            src['prices'][f'd0_{nm}_{key}'] = np.array(np.float32(float(src['prices'][f'd0_{nm}_{key}']) * sg_piece[o0 - 1]))
        for k_ in 'ohlc':
            src['bars'][f'{k_}_{key}'] = R[k_][o0:o0 + n].copy()
            src['bars'][f'pre_{k_}_{key}'] = R[k_][o0 - N:o0].copy()
    for kind in ('series', 'prices', 'range', 'bars'):
        meta = json.loads(str(src[kind]['meta']))
        meta['crc'] = crc
        src[kind]['meta'] = np.array(json.dumps(meta, ensure_ascii=False))
        np.savez_compressed(dst + f"smc_{kind}_{a}_{tf}_N{N}.npz", **src[kind])


