def check_flow(lg, ref):
    """(0в): logit при знаках +1 против 'sp' кэша Flow — медиана |Δ| и доля окон с |Δ| > chk_big."""
    d = np.abs(np.asarray(lg, dtype=np.float64) - np.asarray(ref, dtype=np.float64))
    med, big = float(np.median(d)), float(np.mean(d > LEV['chk_big']))
    return {'med': med, 'max': float(d.max()), 'big': big, 'exact': bool(np.array_equal(np.asarray(lg, np.float32),
                                                                                        np.asarray(ref, np.float32))),
            'ok': med <= LEV['chk_med'] and big <= LEV['chk_share']}


def check_r(bars_piece, sg, data, off, n, o0):
    """(0б): r из OHLC случайного рынка (арифметика SuMo_Class_Data) = знак · r реала там, где r реала конечен; ширина бара и
       ATR — как у реала."""
    R = mirror_bars(bars_piece, sg)
    sl = slice(o0, o0 + n)
    rr = r_research(R['h'], R['l'], R['c'])[sl]
    r = np.asarray(getattr(data, 'rc', data.r)[off:off + n], dtype=np.float64)
    ok = np.isfinite(r) & np.isfinite(rr)
    rel = float(np.max(np.abs(rr[ok] - sg[sl][ok] * r[ok]) / np.maximum(np.abs(r[ok]), 0.01))) if ok.any() else math.nan
    fa = np.isfinite(bars_piece['atr']) & (bars_piece['atr'] > 0)
    w = float(np.max(np.abs((R['h'] - R['l']) - (bars_piece['h'] - bars_piece['l']))[fa] / bars_piece['atr'][fa])) if fa.any() else 0.0
    atr2 = LG.normalizer(R['h'], R['l'], R['c'])[0]
    fa = np.isfinite(atr2) & np.isfinite(bars_piece['atr'])
    da = float(np.max(np.abs(atr2[fa] - bars_piece['atr'][fa]) / np.maximum(bars_piece['atr'][fa], 1e-12))) if fa.any() else 0.0
    return {'r_rel': rel, 'width_rel': w, 'atr_rel': da, 'n': int(ok.sum()),
            'ok': bool(np.isfinite(rel) and rel <= LEV['chk_r'] and w <= 1e-9 and da <= 1e-9)}


def rand_scores(T, data, P, part, models, a, bars, signs_list, L):
    """logit моделей на окнах случайных рынков (знаки signs_list[j] — по барам куска): окна — flip_multi со срезом знаков, история
       (столбцы data.nt_t этой части ассета) — nt_segment по OHLC случайного рынка на время прохода, потом — назад."""
    import torch
    key = 'tr' if part != 'val' else 'va'
    s_ = data.series[P['sid_i']]
    off, npart = s_['off'][key], s_['n'][key]
    pi, o0 = bars['loc'][key]
    PB = bars['pieces'][pi]
    if npart != bars['n'][key] or not np.array_equal(np.asarray(data.t[off:off + npart]), PB['T'][o0:o0 + npart]):
        raise ValueError(f"🍆 АЙ, ОШИБКА! {a} {part}: бары пула и файлов research разошлись (время)")
    st = np.asarray(P['st'], dtype=np.int64)
    gidx = st - off + o0                                    # бар начала окна в куске
    cols = np.arange(-1, L)[None, :]
    keep = data.nt_t[:, off:off + npart].clone()
    out = []
    try:
        for sg in signs_list:
            Rm = mirror_bars(PB, sg)
            sl = slice(o0 - T.NT_HIST, o0 + npart)
            f = T.nt_segment(Rm['o'][sl], Rm['h'][sl], Rm['l'][sl], Rm['c'][sl])
            data.nt_t[:, off:off + npart] = torch.from_numpy(np.ascontiguousarray(f[list(data.nt_rows)])).to(data.nt_t.device)
            S = torch.from_numpy(sg[gidx[:, None] + cols].astype(np.float32)).to(T.DEVICE)
            Wn = data.flip_multi(P['st_t'], L, S, P['W'])
            Xn = T.to_shapes(Wn, P['fl'])
            Sn = T.side_feats(data, P['st_t'], L, Wn, P['fl'])
            out.append({tag: np.asarray(T.score(m, Xn, S=Sn)).astype(np.float32) for tag, m in models.items()})
            del Wn, Xn, Sn, S
    finally:
        data.nt_t[:, off:off + npart] = keep
    return out, (pi, o0, off, npart)


def score_tf(T, tf, parts=('tune', 'val'), assets_only=None):
    """'score' одного ТФ: пул кодом обучения (как Flow), модели источников (поиск — 'stop' C, подтверждение — 'refit' ALL),
       logit случайных рынков 0 … n_rand_mri − 1 на окнах части; сверки (0б), (0в) на первом ассете части; кэш."""
    import torch
    L, n_r = T.POOL['L'], LEV['n_rand_mri']
    todo = []
    for part in parts:
        items = [it for it in FL.items_of(T, part) if it['src'] in LEV['periods']]
        c = load_lev_cache(tf, part)
        if c is not None and set(it['tag'] for it in items) <= set(c['meta']['tags']):
            print(f"   💾 {tf} {part}: кэш Levels уже есть ({len(c['res'])} ассетов)")
            continue
        todo.append((part, items))
    if not todo:
        return
    print(f"\n🧮 ПУЛ {tf} (pool_data кода обучения, как во Flow) — оценки с полом {LEV['floor']:g}")
    pdata = FL.pool_tf(T, tf)
    fp = FL.data_fp(pdata)
    data = pdata['data']
    for part, items in todo:
        t1 = time.time()
        fc = FL.load_cache(tf, part)
        if fc is None:
            raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет кэша Flow {tf} {part} ({FL.OUT_DIR}cache/) — сначала 'score' Flow")
        if fc['meta'].get('fp') != fp:
            raise ValueError(f"🍆 АЙ, ОШИБКА! кэш Flow {tf} {part} посчитан на других данных (отпечаток {fc['meta'].get('fp')} "
                             f"против {fp})")
        models = {it['tag']: T.load_pool_model(it['set'], it['seed'], FL.TF.model_name(), it['mode'])[0] for it in items}
        print(f"\n🧠 {tf} {part}: модели {', '.join(models)} | случайных рынков {n_r}")
        res, chk = {}, {}
        with FL.CL.floor_override(data, L, LEV['floor']):
            for a in (assets_only or pdata['assets']):
                store = T.pool_asset_store(data, L, pdata['sid'][a], pdata['t_cut'])
