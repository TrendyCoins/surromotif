def load_asset(a, tf):
    """Бары ассета из smc_series / smc_bars: части TRAINING и VALIDATION, у каждой — N pre-баров (на них считался нормировщик r
       её первых баров; время pre-баров — сетка ТФ перед частью). Сверка (0а): у SuMo_Class_Data pre-бары VALIDATION — N строк
       CSV сразу после TRAINING, поэтому части склеиваются в один кусок, если T_va[0] − T_tr[-1] = (n_pre_va + 1) баров; иначе —
       два куска. Возвращает {'pieces': [кусок], 'loc': {'tr': (кусок, начало части), 'va': …}, 'n': {…}, 'glued': bool}.
       Кусок: T, o, h, l, c, atr (ATR за 200 баров до бара), live (жив нормировщик r), vr (ср. истинный диапазон 16 баров / ATR)."""
    N, bar_ns = LEV['N'], LEV['bar_ns'][tf]
    d = data_dir(tf)
    ps, pb = d + f"smc_series_{a}_{tf}_N{N}.npz", d + f"smc_bars_{a}_{tf}_N{N}.npz"
    for p_ in (ps, pb):
        if not os.path.isfile(p_):
            raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет {p_}")
    parts = {}
    with np.load(ps, allow_pickle=False) as ds, np.load(pb, allow_pickle=False) as db:
        for key in ('tr', 'va'):
            T = ds[f't_{key}'].astype(np.int64)
            n_pre = len(db[f'pre_c_{key}'])
            seg = {'T': np.r_[T[0] - bar_ns * np.arange(n_pre, 0, -1), T], 'n_pre': n_pre, 'n': len(T)}
            for k_ in 'ohlc':
                seg[k_] = np.r_[db[f'pre_{k_}_{key}'], db[f'{k_}_{key}']].astype(np.float64)
            if len(seg['c']) != len(seg['T']):
                raise ValueError(f"🍆 АЙ, ОШИБКА! {a} {tf}: баров {key} в smc_bars {len(seg['c']) - n_pre}, а в smc_series {len(T)} "
                                 f"— файлы из разных выгрузок")
            parts[key] = seg
    A, B = parts['tr'], parts['va']
    glued = int(B['T'][B['n_pre']] - A['T'][-1]) == (B['n_pre'] + 1) * bar_ns
    keys = ('T', 'o', 'h', 'l', 'c')
    if glued:
        pieces = [{k: np.r_[A[k], B[k]] for k in keys}]
        loc = {'tr': (0, A['n_pre']), 'va': (0, len(A['T']) + B['n_pre'])}
    else:
        pieces = [{k: A[k] for k in keys}, {k: B[k] for k in keys}]
        loc = {'tr': (0, A['n_pre']), 'va': (1, B['n_pre'])}
    for P in pieces:
        add_norm(P)
    return {'pieces': pieces, 'loc': loc, 'n': {'tr': A['n'], 'va': B['n']}, 'glued': glued}


def add_norm(P):
    """ATR и живость (Legs.normalizer), волатильность на баре: средний истинный диапазон vol_bars баров до бара / ATR."""
    P['atr'], P['live'] = LG.normalizer(P['h'], P['l'], P['c'])
    tr = LG.true_range(P['h'], P['l'], P['c'])
    m16 = pd.Series(tr).rolling(LEV['vol_bars'], closed='left').mean().to_numpy()
    with np.errstate(invalid='ignore', divide='ignore'):
        P['vr'] = m16 / P['atr']
    return P


