def _lev(side, L, b, e):
    return {'side': np.asarray(side, dtype=np.int8), 'L': np.asarray(L, dtype=np.float64),
            'b': np.asarray(b, dtype=np.int64), 'e': np.asarray(e, dtype=np.int64)}


def _sel(d, m):
    return {k: v[m] for k, v in d.items()}


def calendar_levels(V, bar_ns, kind, shift_h=0):
    """Уровни свечей календаря: kind 'day' (сутки UTC) / 'week' (неделя с понедельника 00:00 UTC), граница сдвинута на shift_h
       часов. high и low закрытой свечи (в ней >= cal_min_share баров) — уровни следующей свечи: рождаются на её первом баре
       (b), живут до её конца (e — бар за последним). Свечи — по времени открытия бара."""
    per = DAY_NS if kind == 'day' else WEEK_NS
    origin = 0 if kind == 'day' else MON0_NS
    key = (V['T'] - origin - shift_h * HOUR_NS) // per
    if len(key) < 2:
        return _lev([], [], [], [])
    br = np.r_[0, np.flatnonzero(np.diff(key)) + 1, len(key)]
    lo, hi = br[:-1], br[1:]
    kk = key[lo]
    full = (hi - lo) >= LEV['cal_min_share'] * (per // bar_ns)
    nxt = np.r_[kk[1:] == kk[:-1] + 1, False]
    i = np.flatnonzero(full & nxt)
    if not len(i):
        return _lev([], [], [], [])
    hmax = np.maximum.reduceat(V['h'], lo)[i]
    lmin = np.minimum.reduceat(V['l'], lo)[i]
    b, e = lo[i + 1], hi[i + 1]
    n = len(i)
    return _lev(np.r_[np.ones(n), -np.ones(n)], np.r_[hmax, lmin], np.r_[b, b], np.r_[e, e])


def born_ok(V, lev):
    """Правило рождения: close последнего бара до рождения не ближе birth_atr ATR (ATR — бара рождения)."""
    b = lev['b']
    ok = (b >= 1) & (b < len(V['c']))
    bb = np.clip(b, 1, max(len(V['c']) - 1, 1))
    a = V['atr'][bb]
    with np.errstate(invalid='ignore'):
        ok &= np.isfinite(a) & (a > 0) & (np.abs(lev['L'] - V['c'][bb - 1]) >= LEV['birth_atr'] * a)
    return ok


def near_true(ep, lt, atr):
    """Плацебо-касания, у которых на баре касания жив настоящий уровень той же стороны ближе placebo_near ATR (ATR бара касания).
       Только уровни, известные на баре касания (без заглядывания); настоящие — все, без правила рождения (на них смотрят, где
       бы ни был close). У уровней свечей одной стороны жизни не пересекаются — кандидат один."""
    drop = np.zeros(len(ep['L']), dtype=bool)
    for s in (1, -1):
        mp, mt = np.flatnonzero(ep['side'] == s), np.flatnonzero(lt['side'] == s)
        if not len(mp) or not len(mt):
            continue
        o = np.argsort(lt['b'][mt], kind='stable')
        bt, et, Lt = lt['b'][mt][o], lt['e'][mt][o], lt['L'][mt][o]
        t0 = ep['t0'][mp]
        j = np.searchsorted(bt, t0, side='right') - 1          # последний настоящий, родившийся не позже касания
        j0 = np.maximum(j, 0)
        tol = LEV['placebo_near'] * atr[t0]
        with np.errstate(invalid='ignore'):
            drop[mp] = (j >= 0) & (t0 < et[j0]) & (np.abs(ep['L'][mp] - Lt[j0]) < tol)
    return drop


def pivot_levels(V, m, s0):
    """Уровни пивотов слайсера на баре V с s0 (масштаб m): пивот k (k >= 1, подтверждён) — уровень стороны PT[k]; цена — наибольшая
       тень (high) от пивота k − 1 до бара подтверждения k (у лоу — наименьший low); рождается на баре подтверждения + 1, живёт до
       конца. dirs — направление живой ноги на каждом баре (+1 вверх, −1 вниз, 0 до первого пивота)."""
    n = len(V['c'])
    dirs = np.zeros(n, dtype=np.int8)
    if n - s0 < 3:
        return _lev([], [], [], []), dirs
    norm = (V['atr'][s0:], V['live'][s0:])
    _, _, (PT, PP, PI, PC, bar_k, bar_e) = LG.run_slicer(V['c'][s0:], V['h'][s0:], V['l'][s0:], m, norm)
    if len(PI) < 2:
        return _lev([], [], [], []), dirs
    dirs[s0:] = np.where(bar_k >= 0, -PT[np.maximum(bar_k, 0)], 0).astype(np.int8)
    PI = PI + s0
    PC = np.where(PC >= 0, PC + s0, -1)
    k = np.arange(1, len(PI))
    k = k[PC[k] >= 0]
    lo, hi = PI[k - 1], PC[k]
    side = PT[k].astype(np.int8)
    L = np.where(side > 0, V['tab']['h'].range_max(lo, hi), -V['tab']['nl'].range_max(lo, hi))
    b = hi + 1
    keep = b < n
    return _lev(side[keep], L[keep], b[keep], np.full(int(keep.sum()), n)), dirs


def touch(V, lev, dirs=None):
    """Первое касание каждого уровня тенью в [b, e). У пивотов (dirs): событие — только по ходу ноги (dirs на прошлом баре =
       стороне уровня) и только у ближайшего из уровней одной стороны, тронутых тем же баром; остальные гаснут без события."""
    side, L, b, e = lev['side'], lev['L'], lev['b'], lev['e']
    t0 = np.full(len(L), -1, dtype=np.int64)
    up = side > 0
    if up.any():
        t0[up] = V['tab']['h'].first_ge(b[up], L[up], e[up])
    if (~up).any():
        t0[~up] = V['tab']['nl'].first_ge(b[~up], -L[~up], e[~up])
    ev = t0 >= 0
    if dirs is not None and ev.any():
        ev &= dirs[np.maximum(t0 - 1, 0)] == side
        idx = np.flatnonzero(t0 >= 0)
        o = idx[np.lexsort((side[idx] * L[idx], t0[idx], side[idx]))]
        first = np.r_[True, (side[o][1:] != side[o][:-1]) | (t0[o][1:] != t0[o][:-1])]
        nearest = np.zeros(len(L), dtype=bool)
        nearest[o[first]] = True
        ev &= nearest
    i = np.flatnonzero(ev)
    return {'side': side[i], 'L': L[i], 'b': b[i], 't0': t0[i]}


def dedupe(ev):
    """Совпавшие события (та же сторона, тот же бар касания, та же цена уровня) — один раз."""
    if not len(ev['t0']):
        return ev
    o = np.lexsort((ev['L'], ev['t0'], ev['side']))
    s, t, L = ev['side'][o], ev['t0'][o], ev['L'][o]
    first = np.r_[True, (s[1:] != s[:-1]) | (t[1:] != t[:-1]) | (L[1:] != L[:-1])]
    return _sel(ev, np.sort(o[first]))


