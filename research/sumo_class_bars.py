def same_array(a, b):
    """Совпадение float32-рядов бит в бит, NaN на тех же местах."""
    if len(a) != len(b):
        return False
    na, nb = np.isnan(a), np.isnan(b)
    return bool(np.array_equal(na, nb) and np.array_equal(a[~na], b[~nb]))


def prepare(asset):
    t0 = time.time()
    series = DATA_DIR + f"smc_series_{asset}_{TF}_N{N}.npz"
    if not os.path.isfile(series):
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет {series} — сначала TrendyCoins_SMC_Data")
    d = np.load(series, allow_pickle=False)
    csv = project_path + "Raw Datasets/" + f"{asset}-{TF}.csv"
    df = pd.read_csv(csv, parse_dates=['timestamp'])
    o, h, l, c = (df[k].to_numpy(dtype=np.float64) for k in ('open', 'high', 'low', 'close'))
    date = df['timestamp']
    ts = date.to_numpy().astype('datetime64[ns]').astype(np.int64)
    if not np.all(np.diff(ts) > 0):
        raise ValueError(f"🍆 АЙ, ОШИБКА! {asset}: метки времени CSV не по возрастанию")
    print(f"\n{'=' * 78}\n📈 {asset} {TF}: {os.path.basename(csv)} | {len(df)} баров | {date.iloc[0]} → "
          f"{date.iloc[-1]}\n{'=' * 78}")

    # ровно как make_parts в SMC_Data: нормировщик по всему файлу, пропуски сетки и мёртвый нормировщик -> NaN
    roll = pd.Series(h - l).rolling(N, closed='left').median().to_numpy()
    dt = date.diff().dt.total_seconds().to_numpy()
    step = float(np.nanmedian(dt[1:]))
    gap = np.zeros(len(df), dtype=bool)
    gap[1:] = dt[1:] > step * 1.5
    d_close = np.diff(c, prepend=c[0])
    d_close[0] = 0.0
    r = np.zeros_like(d_close)
    np.divide(d_close, roll, out=r, where=roll != 0)
    bad = ~np.isfinite(roll) | (roll <= 0) | ~np.isfinite(r) | gap
    r[bad] = np.nan
    r[0] = np.nan

    out, crc = {}, {}
    for name, key in (('TRAINING', 'tr'), ('VALIDATION', 'va')):
        t_part, r_ser = d[f't_{key}'], d[f'r_{key}']
        idx = np.searchsorted(ts, t_part)
        idx_c = np.minimum(idx, len(ts) - 1)
        found = (idx < len(ts)) & (ts[idx_c] == t_part)
        if not found.all():
            raise ValueError(f"🍆 АЙ, ОШИБКА! {asset} {name}: {int((~found).sum())} баров smc_series нет в CSV (первый — "
                             f"{pd.Timestamp(int(t_part[~found][0]))}) — CSV не тот, на котором считался smc_series")
        if not np.all(np.diff(idx) == 1):
            raise ValueError(f"🍆 АЙ, ОШИБКА! {asset} {name}: бары smc_series идут в CSV не подряд — CSV не тот")
        if not same_array(r_ser, r[idx].astype(np.float32)):
            mism = int(((np.isfinite(r_ser) != np.isfinite(r[idx])) |
                        (np.isfinite(r_ser) & (r_ser != r[idx].astype(np.float32)))).sum())
            raise ValueError(f"🍆 АЙ, ОШИБКА! {asset} {name}: r из CSV не совпадает с smc_series на {mism} барах — CSV "
                             f"переписан другим (перекачка с правками истории?). Верни CSV, на котором считался smc_series")
        if f'close_{key}' in d.files and not np.array_equal(c[idx], d[f'close_{key}'].astype(np.float64)):
            raise ValueError(f"🍆 АЙ, ОШИБКА! {asset} {name}: close из CSV не совпадает с smc_series")
        i0 = int(idx[0])
        if i0 < N_PRE:
            raise ValueError(f"🍆 АЙ, ОШИБКА! {asset} {name}: перед первым баром части в CSV {i0} баров, нужно {N_PRE}")
        pre = slice(i0 - N_PRE, i0)
        for k_, v in (('o', o), ('h', h), ('l', l), ('c', c)):
            out[f'{k_}_{key}'] = v[idx].copy()
            out[f'pre_{k_}_{key}'] = v[pre].copy()
        crc[key] = zlib.crc32(r_ser.astype(np.float32).tobytes())
        oo, hh, ll, cc = (out[f'{k_}_{key}'] for k_ in ('o', 'h', 'l', 'c'))
        prev_c = np.concatenate([out[f'pre_c_{key}'][-1:], cc[:-1]])
        rng = hh - ll
        body = np.abs(cc - oo)
        med_br = float(np.median(body[rng > 0] / rng[rng > 0]))
        n_gap_pre = int(gap[i0 - N_PRE + 1:i0 + 1].sum())
        tail = len(ts) - 1 - int(idx[-1])
        print(f"   {name:<10} баров {len(idx)} | r и close совпадают с smc_series бит в бит ✅ | open ≠ прошлого close у "
              f"{100 * np.mean(oo != prev_c):.2f}% баров | медиана |close − open| / (high − low) {med_br:.3f} | перед частью "
              f"{N_PRE} баров с {date.iloc[i0 - N_PRE]} (пропусков сетки {n_gap_pre})"
              + (f" | в CSV после конца части ещё {tail} баров (не нужны)" if key == 'va' and tail else ""))

    out['meta'] = np.array(json.dumps({'asset': asset, 'tf': TF, 'N': N, 'n_pre': N_PRE, 'ver': 1,
                                       'what': 'raw OHLC of smc_series bars + N_PRE bars before each part',
                                       'series': os.path.basename(series), 'crc': crc, 'csv_last': str(date.iloc[-1]),
                                       'created': time.strftime('%Y-%m-%d %H:%M:%S')}, ensure_ascii=False))
    fn = DATA_DIR + f"smc_bars_{asset}_{TF}_N{N}.npz"
    np.savez_compressed(fn, **out)
    print(f"💾 {fn} ({os.path.getsize(fn) / 1e6:.1f} МБ) | {time.time() - t0:.0f} c")


