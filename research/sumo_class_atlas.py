def load_val_bars(asset):
    """Часть VALIDATION ассета: сырые OHLC smc_bars вместе с pre-барами (бары перед началом части; время pre-баров —
       условная сетка 5M перед частью, событий на них нет)."""
    tf, N = ATLAS['tf'], ATLAS['N']
    ps, pb = DATA_DIR + f"smc_series_{asset}_{tf}_N{N}.npz", DATA_DIR + f"smc_bars_{asset}_{tf}_N{N}.npz"
    for p_ in (ps, pb):
        if not os.path.isfile(p_):
            raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет {p_}")
    ds, db = np.load(ps, allow_pickle=False), np.load(pb, allow_pickle=False)
    T = ds['t_va'].astype(np.int64)
    n_pre = len(db['pre_c_va'])
    B = {'T': np.r_[T[0] - BAR_NS * np.arange(n_pre, 0, -1), T], 'n_pre': n_pre}
    for k_ in ('o', 'h', 'l', 'c'):
        B[k_] = np.r_[db[f'pre_{k_}_va'], db[f'{k_}_va']].astype(float)
    if len(B['c']) != len(B['T']):
        raise ValueError(f"🍆 АЙ, ОШИБКА! {asset}: баров VALIDATION в smc_bars {len(B['c']) - n_pre}, а в smc_series {len(T)}")
    return B


def attach_mri(B, asset):
    """logit окна, кончающегося на баре (NaN — окна нет). Окно ищется по времени последнего бара — найтись обязано каждое."""
    f = np.load(OUT_DIR + f"mri/{asset}.npz", allow_pickle=False)
    T = B['T'][B['n_pre']:]
    idx = np.searchsorted(T, f['t_end'])
    found = (idx < len(T)) & (T[np.minimum(idx, len(T) - 1)] == f['t_end'])
    if not found.all():
        raise ValueError(f"🍆 АЙ, ОШИБКА! {asset}: {int((~found).sum())} окон MRI нет среди баров — файлы из разных выгрузок")
    mri = np.full(len(B['T']), np.nan)
    mri[idx + B['n_pre']] = f['logit']
    meta = json.loads(str(f['meta']))
    return mri, bool(meta.get('check_ok'))


