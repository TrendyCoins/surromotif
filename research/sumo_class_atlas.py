def asset_rows(B, mri, asset_i):
    """Бары VALIDATION одного ассета: нормированные реакции MRI за h баров, маски событий и контекстов, неделя (поиск —
       чётные, подтверждение — нечётные), половина VAL. B — часть VALIDATION с pre-барами (T, o, h, l, c, n_pre);
       mri — logit окна, кончающегося на баре (NaN — окна нет)."""
    F, ev, cx = masks_of(B['o'], B['h'], B['l'], B['c'])
    n_pre = B['n_pre']
    T = np.asarray(B['T'], np.int64)
    mri = np.asarray(mri, float)
    disc_all = (T // WEEK_NS) % 2 == 0
    sl = slice(n_pre, len(T))
    R = {'T': T[sl], 'asset': np.full(len(T) - n_pre, asset_i, np.int16), 'disc': disc_all[sl]}
    info = {}
    coarse = F['flat'] >= ATLAS['flat_max']                      # грубая сетка цены: в атлас не идёт
    good = np.isfinite(F['unit']) & np.isfinite(F['atr']) & ~coarse
    for hh in H_LIST:
        d = mri - lag(mri, hh)
        fin = np.isfinite(d) & good
        base = d[fin & disc_all]
        if len(base) < 100:
            med, width = np.nan, np.nan
        else:
            q05, med, q95 = np.quantile(base, [ATLAS['tail_q'], 0.5, 1 - ATLAS['tail_q']])
            width = q95 - q05
        z = np.where(fin & (width > 0), (d - med) / width, np.nan) if np.isfinite(width) else np.full(len(d), np.nan)
        R[f'z{hh}'] = z[sl].astype(np.float32)
        info[f'h{hh}'] = {'median': med, 'width90': width}
    lev = mri[np.isfinite(mri) & good & disc_all]
    q_lo, q_hi = (np.quantile(lev, [ATLAS['ctx_mri_q'], 1 - ATLAS['ctx_mri_q']]) if len(lev) >= 100 else (np.nan, np.nan))
    info['mri_q'] = (q_lo, q_hi)
    for hh in H_LIST:
        prev = lag(mri, hh)
        cx[f'mri_hi@{hh}'] = prev >= q_hi
        cx[f'mri_lo@{hh}'] = prev <= q_lo
    for key, m in ev.items():
        R[f'ev:{key}'] = m[sl]
    for key, m in cx.items():
        R[f'cx:{key}'] = m[sl]
    tz = R['T'][np.isfinite(R['z1'])]
    R['half'] = (R['T'] >= (np.median(tz) if len(tz) else 0)).astype(np.int8)
    has = np.isfinite(mri[sl])
    info.update({'bars': int(len(T) - n_pre), 'with_mri': int(has.sum()),
                 'coarse': float(coarse[sl][has].mean()) if has.any() else np.nan,
                 'weeks': float(np.isfinite(R['z1']).sum() / (7 * 288))})
    return R, info


def concat_rows(parts):
    return {key: np.concatenate([p[key] for p in parts]) for key in parts[0]}


