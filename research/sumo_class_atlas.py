def load_train():
    """Код обучения (v6.1+) модулем из TRAIN_PY: только определения (SMC_MODE = 'none' ставится здесь, руками не нужно)."""
    if not os.path.isfile(TRAIN_PY):
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет кода обучения {TRAIN_PY} — положи туда sumo_class_train.py v6.1+")
    os.environ['SMC_MODE'] = 'none'
    spec = importlib.util.spec_from_file_location('smc_train', TRAIN_PY)
    mod = importlib.util.module_from_spec(spec)
    sys.modules['smc_train'] = mod
    spec.loader.exec_module(mod)
    need = ('SeriesData', 'side_feats', 'to_shapes', 'build_model', 'score', 'SMC_BASE', 'SIDE_COLS', 'NT_COL0',
            'N_PATH', 'N_LEVEL', 'MULTI_KINDS', 'POOL', '_pool_tag', 'DEVICE')
    miss = [key for key in need if not hasattr(mod, key)]
    if miss or ATLAS['model'] not in mod.POOL['models']:
        raise ImportError(f"🍆 АЙ, ОШИБКА! {TRAIN_PY}: нет {', '.join(miss) or ATLAS['model'] + ' в POOL'} — нужен код "
                          f"обучения v6.1+")
    mod.DATA_DIR, mod.RUN_DIR, mod.DATA_OVERLAY = DATA_DIR, RUN_DIR, None
    print(f"🧩 код обучения — {TRAIN_PY} | {mod.DEVICE}")
    return mod


def load_pool_model(smc):
    import torch
    tag = smc._pool_tag(ATLAS['set'], ATLAS['seed'], ATLAS['model'], ATLAS['gen'])
    jp, npp = RUN_DIR + f"pool/{tag}.json", RUN_DIR + f"pool/{tag}.npz"
    if not (os.path.isfile(jp) and os.path.isfile(npp)):
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет прогона пула {tag} (json + npz) в {RUN_DIR}pool/")
    with open(jp, encoding='utf-8') as fh:
        r = json.load(fh)
    cfg = {**smc.SMC_BASE, **r['cfg']}
    for key in ('head_hidden', 'cnn_dil'):
        if isinstance(cfg.get(key), list):
            cfg[key] = tuple(cfg[key])
    price = cfg.get('price', 'close')
    n_ch = smc.N_PATH + smc.N_LEVEL.get(price, 0) if price in smc.MULTI_KINDS else 1
    shape = (16, n_ch, cfg['L']) if n_ch > 1 else (16, cfg['L'])
    model, _ = smc.build_model(cfg, torch.randn(*shape, device=smc.DEVICE), np.random.default_rng(0))
    d = np.load(npp)
    model.load_state_dict({key[3:]: torch.from_numpy(d[key]) for key in d.files if key.startswith('sd_')}, strict=True)
    model.eval()
    print(f"🧠 {tag}: эпох {r.get('epochs_run')} | панель VAL {_f(r['summary']['val']['panel'], '.4f')} | VAL пула — до "
          f"{str(r.get('t_cut'))[:16]}")
    return {'model': model, 'run': r, 'npz': d, 'cfg': cfg, 'tag': tag, 't_cut': pd.Timestamp(r['t_cut']).value}


def mri_asset(smc, mm, side_cols, asset):
    """MRI ассета: logit модели на всех окнах VALIDATION; сверка с набором проверки прогона пула (те же окна; у пула VAL
       обрезан по концу BTC)."""
    import torch
    t0 = time.time()
    L, cfg = ATLAS['L'], mm['cfg']
    data = smc.SeriesData([asset], ATLAS['tf'], ATLAS['N'], ATLAS['tune_start'], cfg['price'])
    w = data.windows(L)
    idx = np.sort(w['val'])
    st = w['st'][idx]
    t_end = data.t[st + L - 1].astype(np.int64)
    lg = np.zeros(len(idx), np.float32)
    with torch.no_grad():
        for i in range(0, len(idx), ATLAS['chunk']):
            j = slice(i, i + ATLAS['chunk'])
            st_t = torch.from_numpy(st[j]).to(smc.DEVICE)
            sid_t = torch.from_numpy(w['sid'][idx[j]]).to(smc.DEVICE)
            W = data.gw(st_t, L)
            fl = w['floor_t'][sid_t]
            X = smc.to_shapes(W, fl)
            S = smc.side_feats(data, st_t, L, W, fl)
            lg[j] = smc.score(mm['model'], X, S=S)
            del W, X, S
    row = {'n': 0, 'n_ours': 0}
    key = f"{asset}__val__sp"
    if key not in mm['npz'].files:
        row.update({'ok': False, 'why': 'в прогоне пула нет набора проверки VAL этого ассета'})
    else:
        ref = mm['npz'][key].astype(np.float64)
        sel = t_end <= mm['t_cut']
        row.update({'n': int(len(ref)), 'n_ours': int(sel.sum())})
        stk = f"{asset}__val__st"
        if len(ref) != sel.sum() or (stk in mm['npz'].files and not np.array_equal(mm['npz'][stk], st[sel])):
            row.update({'ok': False, 'why': 'окна не те'})
        else:
            dd = np.abs(lg[sel].astype(np.float64) - ref)
            row.update({'max': float(dd.max()), 'med': float(np.median(dd)),
                        'share': float(np.mean(dd > ATLAS['check_tol']))})
            row['ok'] = bool(row['share'] <= ATLAS['check_share'] and row['med'] <= ATLAS['check_med'])
            if not row['ok']:
                row['why'] = f"медиана |Δ| {row['med']:.0e}, доля |Δ| > {ATLAS['check_tol']:g} — {row['share']:.1e}"
    meta = {'ver': ATLAS_VER, 'asset': asset, 'tag': mm['tag'], 'check': row, 'check_ok': bool(row['ok']),
            'when': time.strftime('%Y-%m-%d %H:%M:%S')}
    np.savez_compressed(OUT_DIR + f"mri/{asset}.npz", t_end=t_end, logit=lg, meta=json.dumps(meta, ensure_ascii=False))
    print(f"   {'✅' if row['ok'] else '❌'} {asset:<11} окон VAL {len(idx):>7} | logit {lg.mean():+.3f} ± {lg.std():.3f} | "
          f"сверка с пулом: |Δ| медиана {_f(row.get('med'), '.0e')}, макс. {_f(row.get('max'), '.0e')}"
          + ("" if row['ok'] else f" — {row.get('why')}") + f" | {time.time() - t0:.0f} c", flush=True)
    del data
    if smc.DEVICE.type == 'cuda':
        torch.cuda.empty_cache()
    return bool(row['ok'])


