class _Tee:
    """Печать в вывод и в лог-файл на Drive (как в коде обучения): текст копится в памяти и дописывается раз в SYNC_S
       секунд и при закрытии; ошибка записи лога прогон не роняет."""
    SYNC_S = 5.0

    def __init__(self, path, stream):
        self.path, self.stream, self.buf = path, stream, []
        self.t_last, self.warned = time.time(), False

    def _sync(self):
        if not self.buf:
            return
        try:
            with open(self.path, 'a', encoding='utf-8') as fh:
                fh.write(''.join(self.buf))
            self.buf = []
        except OSError as e:
            if not self.warned:
                self.stream.write(f"\n⚠️ лог-файл недоступен ({e}) — коплю в памяти\n")
                self.warned = True
        self.t_last = time.time()

    def write(self, s):
        self.stream.write(s)
        self.buf.append(s)
        if time.time() - self.t_last >= self.SYNC_S:
            self._sync()

    def flush(self):
        self.stream.flush()
        if time.time() - self.t_last >= self.SYNC_S:
            self._sync()

    def close(self):
        self._sync()

    def __getattr__(self, name):
        return getattr(self.stream, name)


@contextlib.contextmanager
def tee_to(path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    keep = sys.stdout
    tee = _Tee(path, keep)
    sys.stdout = tee
    try:
        yield
    finally:
        sys.stdout = keep
        tee.close()


def _f(x, fmt, width=None, dash='—'):
    try:
        ok = x is not None and np.isfinite(x)
    except TypeError:
        ok = False
    s = f"{x:{fmt}}" if ok else dash
    return f"{s:>{width}}" if width else s


def _jsonable(x):
    if isinstance(x, dict):
        return {str(k): _jsonable(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_jsonable(v) for v in x]
    if isinstance(x, np.ndarray):
        return _jsonable(x.tolist())
    if isinstance(x, (np.bool_, bool)):
        return bool(x)
    if isinstance(x, np.integer):
        return int(x)
    if isinstance(x, (np.floating, float)):
        return None if not np.isfinite(x) else float(x)
    return x


