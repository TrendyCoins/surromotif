def rule_list():
    """Правила: события по одному и события в каждом контексте; контексты сами по себе — справочно (база — все бары)."""
    out = []
    ev, cx = event_specs(), context_specs()
    for e in ev:
        out.append({'ev': e, 'cx': None, 'h': ev[e]['h'], 'name': ev[e]['name'], 'kind': 'событие'})
        for c in cx:
            out.append({'ev': e, 'cx': c, 'h': ev[e]['h'], 'name': f"{ev[e]['name']} | {cx[c][0]}", 'kind': 'пара'})
    for c in cx:
        out.append({'ev': None, 'cx': c, 'h': 1, 'name': f"контекст: {cx[c][0]}", 'kind': 'контекст'})
    return out


def _q(v):
    if len(v) == 0:
        return np.nan, np.nan, np.nan
    q = np.quantile(v, [ATLAS['tail_q'], 0.5, 1 - ATLAS['tail_q']])
    return float(q[0]), float(q[1]), float(q[2])


def eval_rules(D):
    """Статистика каждого правила на неделях поиска и подтверждения, отбор по правилам до прогона, склейка дублей."""
    A = ATLAS
    disc = D['disc']
    n_asset = int(D['asset'].max()) + 1
    if np.any(np.diff(D['asset']) < 0):
        raise ValueError("🍆 АЙ, ОШИБКА! строки таблицы баров не сгруппированы по ассетам")
    bounds = np.searchsorted(D['asset'], np.arange(n_asset + 1))       # строки ассета i — [bounds[i], bounds[i + 1])
    asset_base = {}
    weeks = {}
    for hh in H_LIST:
        fin = np.isfinite(D[f'z{hh}'])
        weeks[hh] = float(fin.sum() / (7 * 288))
    base_cache = {}

    def base_stats(hh, cxk, mask):
        key = (hh, cxk)
        if key not in base_cache:
            out = {}
            for s_name, s_mask in (('disc', disc), ('conf', ~disc), ('h0', D['half'] == 0), ('h1', D['half'] == 1)):
                out[s_name] = _q(D[f'z{hh}'][mask & s_mask])
            base_cache[key] = out
        return base_cache[key]
    res = []
    for r in rule_list():
        hh = r['h']
        z = D[f'z{hh}']
        base = np.isfinite(z)
        if r['cx'] is not None:
            base = base & D[f"cx:{r['cx']}@{hh}"]
        m = base if r['ev'] is None else base & D[f"ev:{r['ev']}"]
        if r['ev'] is None:                                  # контекст сам по себе — против всех баров
            bs = base_stats(hh, None, np.isfinite(z))
        else:
            bs = base_stats(hh, r['cx'], base)
        row = dict(r)
        for s_name, s_mask in (('disc', disc), ('conf', ~disc)):
            v = z[m & s_mask]
            q05, med, q95 = _q(v)
            b05, bmed, b95 = bs[s_name]
            row[f'n_{s_name}'] = int(len(v))
            row[f'q_{s_name}'] = (q05, med, q95)
            row[f'shift_{s_name}'] = med - bmed
            row[f'wratio_{s_name}'] = (q95 - q05) / (b95 - b05) if b95 > b05 else np.nan
        q05, _, q95 = row['q_disc']
        vc = z[m & ~disc]
        row['tail_conf'] = ((float(np.mean(vc < q05)), float(np.mean(vc > q95))) if len(vc) else (np.nan, np.nan))
        row['shift_half'] = tuple(_q(z[m & (D['half'] == hf)])[1] - bs[f'h{hf}'][1] for hf in (0, 1))
        cnt = np.bincount(D['asset'][m], minlength=n_asset)
        row['assets'] = int((cnt >= A['min_asset_n']).sum())
        row['dots_week'] = float(A['tail_q'] * m.sum() / max(weeks[hh] * 1.0, 1e-9))     # точек-дивергенций в неделю на ассет
        sd, sc = row['shift_disc'], row['shift_conf']
        lo, hi = A['tail_ok']
        checks = {
            'n': row['n_disc'] >= A['min_n'] and row['n_conf'] >= A['min_n'],
            'shift': np.isfinite(sd) and abs(sd) >= A['min_shift'],
            'conf': (np.isfinite(sc) and np.isfinite(sd) and np.sign(sc) == np.sign(sd)
                     and abs(sc) >= A['conf_keep'] * abs(sd)),
            'tails': all(np.isfinite(x) and lo <= x <= hi for x in row['tail_conf']),
        }
        row['checks'] = checks
        row['pass'] = row['kind'] != 'контекст' and all(checks.values())
        row['rare'] = min(row['n_disc'], row['n_conf']) < A['n_precise']
        if row['pass']:                                      # справочно: знак сдвига по ассетам (все недели)
            bkey = (hh, r['cx'])
            if bkey not in asset_base:
                asset_base[bkey] = [np.median(z[a0:a1][base[a0:a1]]) if base[a0:a1].any() else np.nan
                                    for a0, a1 in zip(bounds[:-1], bounds[1:])]
            same, cov = 0, 0
            for ai, (a0, a1) in enumerate(zip(bounds[:-1], bounds[1:])):
                v = z[a0:a1][m[a0:a1]]
                if len(v) < A['min_asset_n'] or not np.isfinite(asset_base[bkey][ai]):
                    continue
                cov += 1
                same += int(np.sign(np.median(v) - asset_base[bkey][ai]) == np.sign(sd))
            row['sign_assets'] = (same, cov)
        row['_mask'] = m if row['pass'] else None          # маски нужны только прошедшим (свёртка, дубли, рисунок)
        row['fold_to'], row['dup_of'] = None, None
        res.append(row)
    # свёртка: случаи правила — часть случаев более общего прошедшего и не свёрнутого правила той же длины h (направление,
    # контекст или порог сверх общего), а сдвиг от сдвига общего не отличается подтверждённо (тем же правилом, что сдвиг
    # от базы) — правило сворачивается в общее: уточнение ничего не добавляет. Решается от широких правил к узким (у общего
    # решение уже есть); из нескольких подходящих общих — самое широкое
    passed = [r for r in res if r['pass']]
    cnt = {id(r): np.count_nonzero(r['_mask']) for r in passed}
    passed.sort(key=lambda r: -cnt[id(r)])
    for i, r in enumerate(passed):
        for p in passed[:i]:                                 # шире или так же широко; самые широкие — первыми
            if p['fold_to'] is not None or p['h'] != r['h'] or cnt[id(p)] <= cnt[id(r)]:
                continue
            if np.count_nonzero(r['_mask'] & ~p['_mask']):
                continue                                     # не вложено
            dd, dc = r['shift_disc'] - p['shift_disc'], r['shift_conf'] - p['shift_conf']
            differs = abs(dd) >= A['min_shift'] and np.sign(dc) == np.sign(dd) and abs(dc) >= A['conf_keep'] * abs(dd)
            if not differs:
                r['fold_to'] = p['name']
                break
    # дубли: среди прошедших и не свёрнутых одной длины h — Жаккар случаев
    kept = []
    for r in sorted([r for r in passed if r['fold_to'] is None], key=lambda r: -abs(r['shift_disc'])):
        dup = None
        for k in kept:
            if k['h'] != r['h']:
                continue
            inter = np.count_nonzero(r['_mask'] & k['_mask'])
            union = np.count_nonzero(r['_mask'] | k['_mask'])
            if union and inter / union > A['dedupe']:
                dup = k
                break
        if dup is None:
            kept.append(r)
        else:
            r['dup_of'] = dup['name']
    for r in res:
        r['kept'] = r['pass'] and r['fold_to'] is None and r['dup_of'] is None
    return res


