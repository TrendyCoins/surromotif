def synth_bars(n, seed, sub=20):
    """Блуждание со стохастической волой (бар — sub под-шагов, OHLC): ни направленной структуры, ни реакций MRI."""
    rng = np.random.default_rng(seed)
    phi = 0.5 ** (1 / 300)
    lv = lfilter([1.0], [1.0, -phi], rng.standard_normal(n) * 0.45 * np.sqrt(1 - phi ** 2))
    sig = np.exp(lv)
    path = np.cumsum(rng.standard_normal((n, sub)) * (sig[:, None] / np.sqrt(sub)), axis=1)
    c = 1000.0 + np.cumsum(path[:, -1])
    o = np.r_[1000.0, c[:-1]]
    return o, o + np.maximum(path.max(axis=1), 0.0), o + np.minimum(path.min(axis=1), 0.0), c


def stand_world(planted, seed):
    """Синтетический пул: бары-блуждание и MRI = AR(1)-шум (+ подсаженные реакции): каждый бар >= 2 ходов (в любую
       сторону) поднимает MRI на d_impulse, пока он в шагах окна (63 бара; на выходе — обратный скачок, «призрак»); каждый
       пробой суток по ходу опускает MRI на d_breakout на 16 баров. Как у настоящего MRI, первых 63 баров части у него нет."""
    P = STAND
    parts, info = [], []
    n_pre = ATLAS['unit_window']
    for a in range(P['assets']):
        n = n_pre + P['bars']
        o, h, l, c = synth_bars(n, seed + a)
        T = pd.Timestamp(P['from']).value + BAR_NS * (np.arange(n) - n_pre)
        rng = np.random.default_rng(seed + 100 + a)
        mri = lfilter([1.0], [1.0, -P['noise_phi']], rng.standard_normal(n))
        if planted:
            _, ev, _ = masks_of(o, h, l, c)
            imp = ev['m1_2'].astype(float)
            mri += P['d_impulse'] * pd.Series(imp).rolling(63, min_periods=1).sum().to_numpy()
            bo = ev['bo288+'].astype(float)
            mri -= P['d_breakout'] * pd.Series(bo).rolling(16, min_periods=1).sum().to_numpy()
        mri[:n_pre + 63] = np.nan
        B = {'T': T, 'o': o, 'h': h, 'l': l, 'c': c, 'n_pre': n_pre}
        R, inf = asset_rows(B, mri, a)
        parts.append(R)
        info.append(inf)
    return concat_rows(parts), info


def stand_causal():
    """Признаки на баре t — только из баров <= t: бары после cut заменены — маски событий и контекстов до cut те же."""
    n = 30_000
    o, h, l, c = synth_bars(n, 5)
    cut = 20_000
    o2, h2, l2, c2 = (x.copy() for x in synth_bars(n, 6))
    shift = c[cut] - c2[cut]
    o2, h2, l2, c2 = (np.r_[x[:cut + 1], (y + shift)[cut + 1:]] for x, y in ((o, o2), (h, h2), (l, l2), (c, c2)))
    _, ev1, cx1 = masks_of(o, h, l, c)
    _, ev2, cx2 = masks_of(o2, h2, l2, c2)
    bad = [k for k in ev1 if not np.array_equal(ev1[k][:cut + 1], ev2[k][:cut + 1])]
    bad += [k for k in cx1 if not np.array_equal(cx1[k][:cut + 1], cx2[k][:cut + 1])]
    changed = sum(not np.array_equal(ev1[k][cut + 1:], ev2[k][cut + 1:]) for k in ev1)
    ok = not bad and changed > 0
    print(f"   {'✅' if ok else '❌'} причинность: бары после {cut} заменены — маски {len(ev1)} событий и {len(cx1)} "
          f"контекстов до него те же{'' if not bad else ' — НЕТ: ' + ', '.join(bad[:5])}; после — изменились у {changed}")
    return ok


def stand_mirror():
    """Зеркальный ряд (цена перевёрнута, high <-> low): маски те же — MRI направления не знает, и события тоже."""
    o, h, l, c = synth_bars(30_000, 7)
    K = 3000.0
    _, ev1, cx1 = masks_of(o, h, l, c)
    _, ev2, cx2 = masks_of(K - o, K - l, K - h, K - c)
    bad = [k for k in ev1 if not np.array_equal(ev1[k], ev2[k])] + [k for k in cx1 if not np.array_equal(cx1[k], cx2[k])]
    sizes = {k: int(ev1[k].sum()) for k in ('m1_2+', 'm1_2-', 'bo288+', 'bo288-', 'quiet', 'exit')}
    print(f"   {'✅' if not bad else '❌'} зеркальная симметрия: маски событий и контекстов совпали"
          f"{'' if not bad else ' — НЕТ: ' + ', '.join(bad[:5])} | случаев на 30 тыс. баров: "
          + ", ".join(f"{k} {v}" for k, v in sizes.items()))
    return not bad


def stand_coarse():
    """Грубая сетка цены: тот же ряд, округлённый до тика порядка среднего хода, в атлас не идёт; исходный — идёт весь."""
    n = 30_000
    o, h, l, c = synth_bars(n, 8)
    rng = np.random.default_rng(9)
    mri = lfilter([1.0], [1.0, -0.98], rng.standard_normal(n))
    out = []
    for tick in (None, 1.0):
        bars = (o, h, l, c) if tick is None else tuple(np.round(x / tick) * tick for x in (o, h, l, c))
        B = {'T': pd.Timestamp('2025-07-01').value + BAR_NS * np.arange(n), 'o': bars[0], 'h': bars[1], 'l': bars[2],
             'c': bars[3], 'n_pre': ATLAS['unit_window']}
        R, inf = asset_rows(B, mri, 0)
        flat = float(np.mean(np.diff(bars[3]) == 0))
        out.append((flat, inf['coarse'], float(np.isfinite(R['z1']).mean())))
    (f0, c0, z0), (f1, c1, z1) = out
    ok = c0 < 0.01 and z0 > 0.99 and c1 > 0.5
    print(f"   {'✅' if ok else '❌'} грубая сетка цены: исходный ряд — close стоит у {100 * f0:.1f}% баров, исключено "
          f"{100 * c0:.1f}%, в атласе {100 * z0:.1f}% баров | округлён до тика ~ среднего хода — стоит у {100 * f1:.0f}%, "
          f"исключено {100 * c1:.0f}%, в атласе {100 * z1:.0f}%")
    return ok


