def lag(x, k):
    """x[t − k] на баре t (NaN, где бара t − k нет)."""
    x = np.asarray(x, float)
    out = np.full(len(x), np.nan)
    if 0 <= k < len(x):
        out[k:] = x[:len(x) - k]
    return out


def true_range(h, l, c):
    """Истинный диапазон: max(high, прошлый close) − min(low, прошлый close) (у первого бара — high − low)."""
    prev = lag(c, 1)
    return np.fmax(h, prev) - np.fmin(l, prev)


def price_features(o, h, l, c):
    """Числа, из которых собраны события и контексты; все — из баров <= t (стенд проверяет возмущением баров после t).
       Направление — относительно хода 64 баров до начала события: rel = +1 по ходу, −1 против, 0 — ничья или нет данных
       (у зеркального ряда числа те же: MRI направления не знает)."""
    o, h, l, c = (np.asarray(x, float) for x in (o, h, l, c))
    W, K = ATLAS['unit_window'], ATLAS['trend_window']
    dc = lag(c, 0) - lag(c, 1)
    unit = pd.Series(np.abs(dc)).rolling(W, closed='left').mean().to_numpy()      # средний |ход close| за 200 баров до бара
    unit = np.where(unit > 0, unit, np.nan)
    tr = true_range(h, l, c)
    atr = pd.Series(tr).rolling(W, closed='left').mean().to_numpy()
    atr = np.where(atr > 0, atr, np.nan)
    F = {'unit': unit, 'atr': atr}
    for k in H_LIST:
        mv = c - lag(c, k)
        F[f'mag{k}'] = np.abs(mv) / (unit * np.sqrt(k))
        F[f'rel{k}'] = np.sign(mv) * np.sign(lag(c, k) - lag(c, k + K))
    prior1 = np.sign(lag(c, 1) - lag(c, 1 + K))
    for N in (64, 288):
        mx = pd.Series(c).rolling(N, closed='left').max().to_numpy()
        mn = pd.Series(c).rolling(N, closed='left').min().to_numpy()
        bo = np.where(c > mx, 1.0, np.where(c < mn, -1.0, 0.0))                   # новый экстремум N баров по close
        F[f'bo{N}'] = bo
        F[f'bo{N}_rel'] = bo * prior1
    F['tr_atr'] = tr / atr
    rng_ = h - l
    F['body'] = np.where(rng_ > 0, np.abs(c - o) / np.where(rng_ > 0, rng_, 1.0), np.nan)
    # шаг бара t−63 на баре t уходит из шагов формы MRI (первое приращение окна форма теряет при центрировании)
    F['exit'] = lag(np.abs(dc), 63) / unit
    # доля баров без хода close за 200 баров до бара — мера грубости сетки цены (неликвид)
    F['flat'] = pd.Series((dc == 0).astype(float)).rolling(W, closed='left').mean().to_numpy()
    # контексты: состояние на баре j (из баров <= j); для события длины h берётся j = t − h
    acs = np.r_[0.0, np.cumsum(np.nan_to_num(np.abs(dc[1:])))]                     # acs[j] — сумма |dc| баров 1..j
    idx = np.arange(len(c))
    er = np.full(len(c), np.nan)
    ok = idx >= K
    path = acs[idx[ok]] - acs[idx[ok] - K]
    er[ok] = np.abs(c[ok] - c[idx[ok] - K]) / np.where(path > 0, path, np.nan)
    F['er64'] = er
    F['vol16'] = pd.Series(tr).rolling(16).mean().to_numpy() / atr
    mx = pd.Series(c).rolling(288).max().to_numpy()
    mn = pd.Series(c).rolling(288).min().to_numpy()
    F['pos288'] = np.where(mx > mn, (c - mn) / np.where(mx > mn, mx - mn, 1.0), np.nan)
    return F


