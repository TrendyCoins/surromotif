def event_specs():
    """События (имя, длина h, маска из признаков). Направленные — тройкой: любое, по ходу, против хода."""
    A = ATLAS
    out = {}
    for thr in A['m1_thr']:
        for sfx, tag, sel in (('', '', None), ('+', ' по ходу', 1.0), ('-', ' против хода', -1.0)):
            out[f'm1_{thr:g}{sfx}'] = _ev(f"бар ≥ {thr:g} ходов{tag}", 1,
                                          lambda F, t=thr, s=sel: (F['mag1'] >= t) & ((F['rel1'] == s) if s else True))
    for k in (3, 8):
        for sfx, tag, sel in (('', '', None), ('+', ' по ходу', 1.0), ('-', ' против хода', -1.0)):
            out[f'm{k}{sfx}'] = _ev(f"ход {k} баров ≥ {A['mk_thr']:g}{tag}", k,
                                    lambda F, k=k, s=sel: (F[f'mag{k}'] >= A['mk_thr']) & ((F[f'rel{k}'] == s) if s else True))
    out['quiet'] = _ev(f"тихий бар (≤ {A['quiet_thr']:g} хода)", 1, lambda F: F['mag1'] <= A['quiet_thr'])
    for N, label in ((64, 'пробой 64 баров'), (288, 'пробой суток')):
        for sfx, tag, sel in (('', '', None), ('+', ' по ходу', 1.0), ('-', ' против хода', -1.0)):
            out[f'bo{N}{sfx}'] = _ev(f"{label}{tag}", 1,
                                     lambda F, N=N, s=sel: (F[f'bo{N}'] != 0) & ((F[f'bo{N}_rel'] == s) if s else True))
    out['wide'] = _ev(f"широкий бар (≥ {A['wide_tr']:g} ATR)", 1, lambda F: F['tr_atr'] >= A['wide_tr'])
    out['wick'] = _ev(f"бар-тень (≥ {A['wick_tr']:g} ATR, тело ≤ {100 * A['wick_body']:.0f}%)", 1,
                      lambda F: (F['tr_atr'] >= A['wick_tr']) & (F['body'] <= A['wick_body']))
    out['exit'] = _ev(f"из окна вышел бар ≥ {A['exit_thr']:g} ходов", 1, lambda F: F['exit'] >= A['exit_thr'])
    out['ghost'] = _ev(f"призрак: вышел бар ≥ {A['ghost_thr']:g} ходов, текущий ≤ {A['ghost_quiet']:g}", 1,
                       lambda F: (F['exit'] >= A['ghost_thr']) & (F['mag1'] <= A['ghost_quiet']))
    return out


def context_specs():
    """Контексты — состояние до события длины h (бар t − h). MRI-контексты считаются в атласе (нужны квантили ассета)."""
    A = ATLAS
    hi_er, lo_er = A['ctx_er']
    hi_v, lo_v = A['ctx_vol']
    hi_e, lo_e = A['ctx_edge']

    def edge(F, h):
        pos = lag(F['pos288'], h)
        prior = np.sign(lag(np.asarray(F['c'], float), h) - lag(np.asarray(F['c'], float), h + A['trend_window']))
        return np.where(prior > 0, pos, np.where(prior < 0, 1.0 - pos, np.nan))
    return {
        'trend': ('тренд до', lambda F, h: lag(F['er64'], h) >= hi_er),
        'chop': ('пила до', lambda F, h: lag(F['er64'], h) <= lo_er),
        'storm': ('бурно до', lambda F, h: lag(F['vol16'], h) >= hi_v),
        'calm': ('тихо до', lambda F, h: lag(F['vol16'], h) <= lo_v),
        'edge+': ('у края суток по ходу', lambda F, h: edge(F, h) >= hi_e),
        'edge-': ('у края суток против хода', lambda F, h: edge(F, h) <= lo_e),
        'mri_hi': ('MRI высокий до', None),
        'mri_lo': ('MRI низкий до', None),
    }


def masks_of(o, h, l, c):
    """Маски всех событий и ценовых контекстов (для каждой длины h) на всех барах ряда."""
    F = price_features(o, h, l, c)
    F['c'] = np.asarray(c, float)
    ev = {key: np.asarray(spec['fn'](F), bool) for key, spec in event_specs().items()}
    cx = {}
    for key, (_, fn) in context_specs().items():
        if fn is None:
            continue
        for hh in H_LIST:
            cx[f'{key}@{hh}'] = np.asarray(fn(F, hh), bool)
    return F, ev, cx


