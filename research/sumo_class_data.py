def _null_split(par):
    if isinstance(par, (tuple, list)):
        b = float(par[0])
        W = int(par[1]) if len(par) > 1 and par[1] else 0
        return b, W
    return float(par), 0


def _null_segments(n, W, b):
    if not W or W >= n:
        return [(0, n)]
    segs = [(c, min(c + W, n)) for c in range(0, n, W)]
    if len(segs) > 1 and segs[-1][1] - segs[-1][0] < max(2 * int(b), 4):
        segs[-2] = (segs[-2][0], segs[-1][1])
        segs.pop()
    return segs


def _surr_core(v, kind, b, rng):
    n = len(v)
    if kind == 'iid':
        return rng.permutation(v)
    if kind != 'bperm':
        raise ValueError(f"🍆 АЙ, ОШИБКА! банк умеет только 'iid' и 'bperm', не '{kind}'")
    b = max(1, int(b))
    if n <= b:
        return rng.permutation(v)
    v = np.roll(v, int(rng.integers(0, b)))
    nb = n // b
    body = v[:nb * b].reshape(nb, b)[rng.permutation(nb)].ravel()
    return np.concatenate([body, v[nb * b:]]) if n > nb * b else body


def surrogate(v, kind, par, rng):
    """Как sumo_surrogate: перестановка на конечных значениях, с локальностью W."""
    b, W = _null_split(par)
    n = len(v)
    if not W or W >= n:
        return _surr_core(v, kind, b, rng)
    out = np.empty(n, dtype=v.dtype)
    for s, e in _null_segments(n, W, b):
        out[s:e] = _surr_core(v[s:e], kind, b, rng)
    return out


def bank_name(kind, par):
    b, W = _null_split(par)
    return f"{kind}{b:g}" + (f"w{W}" if W else "")


def bank_seed(asset, name, part, k):
    return CFG['seed'] + zlib.crc32(f"{asset}|{name}|{part}|{k}".encode()) % 1000003


