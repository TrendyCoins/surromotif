def valid_starts(r, L):
    """Начала окон длины L без NaN внутри (через накопленное число NaN)."""
    bad = ~np.isfinite(r)
    cs = np.concatenate([[0], np.cumsum(bad)])
    n = len(r) - L + 1
    if n <= 0:
        return np.empty(0, dtype=np.int64)
    return np.where(cs[L:L + n] - cs[:n] == 0)[0].astype(np.int64)


def gather_windows(r32, starts, L):
    return r32[starts[:, None] + np.arange(L)[None, :]]


def window_divisors(r32, starts, L, chunk=200000):
    """Делитель формы ДО пола: медиана |шага| в окне (как sumo_scale, ret_med)."""
    out = np.empty(len(starts), dtype=np.float32)
    for i in range(0, len(starts), chunk):
        out[i:i + chunk] = np.median(np.abs(gather_windows(r32, starts[i:i + chunk], L)), axis=1)
    return out


def shapes_np(W, floor):
    """Форма ret_med ровно как sumo_shapes: cumsum -> центрирование ->
       симметризация по знаку X[-1] -> деление на max(медиана |шага|, пол)."""
    X = np.cumsum(W, axis=1).astype(np.float32)
    X -= X.mean(axis=1, keepdims=True)
    s = np.median(np.abs(W), axis=1)
    neg = X[:, -1] < 0
    X[neg] *= -1.0
    s = np.maximum(s, floor)
    return X / s.astype(np.float32)[:, None], neg


def dict_floor(asset, tf, tags):
    """Пол делителя из npz словаря SuMo (ключ 'floor' есть с 2026-09-23)."""
    for t in tags:
        p = project_path + f"sumo_{asset}_{tf.upper()}_{t}.npz"
        if not os.path.isfile(p):
            continue
        d = np.load(p, allow_pickle=True)
        if 'floor' not in d.files:
            return {'tag': t, 'floor': None, 'note': 'в npz нет пола'}
        norm = str(d['shape_norm']) if 'shape_norm' in d.files else 'ret_med'
        return {'tag': t, 'floor': float(d['floor']), 'L': int(d['centers'].shape[1]),
                'K': int(d['centers'].shape[0]), 'norm': norm}
    return None


