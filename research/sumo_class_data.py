def data_file(asset, tf):
    return project_path + "Raw Datasets/" + f"{asset}-{tf.upper()}.csv"


def load_ohlc(asset, tf):
    """CSV с проверками SuMo. Вместо exit() — исключение: очередь из многих
       ассетов не должна падать целиком из-за одного битого файла."""
    path = data_file(asset, tf)
    if not os.path.isfile(path):
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет файла {path}")
    df = pd.read_csv(path, parse_dates=['timestamp'])
    o, h, l, c = (df[k].to_numpy(dtype=np.float64) for k in ('open', 'high', 'low', 'close'))
    bad_zero = (o == 0) | (h == 0) | (l == 0) | (c == 0)
    bad_ohlc = (c < l) | (c > h) | (o < l) | (o > h) | (h < l)
    n_bad = int((bad_zero | bad_ohlc).sum())
    if n_bad:
        raise ValueError(f"🍆 АЙ, ОШИБКА! {asset} {tf}: битых баров OHLC {n_bad}")
    back = int((df['timestamp'].diff().dt.total_seconds().to_numpy()[1:] <= 0).sum())
    if back:
        raise ValueError(f"🍆 АЙ, ОШИБКА! {asset} {tf}: метки времени не по возрастанию ({back})")
    return df, path


def make_parts(df, N, t_start, t_valid):
    """Приращения в единицах медианного бара — численно тот же путь, что
       prepare_data в SuMo: rolling по всему файлу (closed='left'), пропуск
       сетки и мёртвый нормировщик -> NaN, у каждой части разогрев N баров."""
    close = df['close'].to_numpy(dtype=np.float64)
    hl = (df['high'] - df['low']).to_numpy(dtype=np.float64)
    date = df['timestamp']
    roll = pd.Series(hl).rolling(N, closed='left').median().to_numpy()

    dt = date.diff().dt.total_seconds().to_numpy()
    step = float(np.nanmedian(dt[1:]))
    gap = np.zeros(len(df), dtype=bool)
    gap[1:] = dt[1:] > step * 1.5

    d_close = np.diff(close, prepend=close[0])
    d_close[0] = 0.0
    r = np.zeros_like(d_close)
    np.divide(d_close, roll, out=r, where=roll != 0)
    bad = ~np.isfinite(roll) | (roll <= 0) | ~np.isfinite(r) | gap
    r[bad] = np.nan
    r[0] = np.nan

    parts = {}
    for name, a, b in (('TRAINING', t_start, t_valid), ('VALIDATION', t_valid, None)):
        hits = np.where(date >= pd.Timestamp(a))[0]
        if len(hits) == 0:
            raise ValueError(f"🍆 АЙ, ОШИБКА! {name}: начало {a} позже конца данных")
        i0 = int(hits[0])
        if b is None:
            i1 = len(df) - 1
        else:
            hits = np.where(date < pd.Timestamp(b))[0]
            if len(hits) == 0:
                raise ValueError(f"🍆 АЙ, ОШИБКА! {name}: конец {b} раньше начала данных")
            i1 = int(hits[-1])
        lo, hi = i0 + N, i1 + 1
        if lo >= hi:
            raise ValueError(f"🍆 АЙ, ОШИБКА! {name}: диапазон пуст после разогрева {N} баров")
        parts[name] = {'r': r[lo:hi].copy(), 'close': close[lo:hi].copy(),
                       'date': date.iloc[lo:hi].reset_index(drop=True),
                       'i0': lo, 'i1': i1, 'n_gap': int(gap[lo:hi].sum())}
    return parts, step


