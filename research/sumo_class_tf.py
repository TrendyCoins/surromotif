def stand_pool_run(T, cfg, Xs, Ss, set_, seed, mode, i):
    """Синтетический прогон пула: случайная сеть F1 -> json + npz (веса sd_*) в формате кода обучения (load_pool_model)."""
    import torch
    torch.manual_seed(1000 + i)
    mdl, _ = T.build_model(cfg, Xs, np.random.default_rng(i), Ss)
    mdl.eval()
    tag = T._pool_tag(set_, seed, model_name(), mode)
    pdir = T._pool_dir(mode)
    os.makedirs(pdir, exist_ok=True)
    np.savez(pdir + tag + '.npz', **{'sd_' + k: v.detach().cpu().numpy() for k, v in mdl.state_dict().items()})
    with open(pdir + tag + '.json', 'w', encoding='utf-8') as fh:
        json.dump(T._jsonable({'ver': T.POOL_VER, 'tag': tag, 'set': set_, 'seed_key': seed, 'model': model_name(),
                               'mode': mode, 'cfg': {k: v for k, v in cfg.items() if k != 'dict'},
                               't_cut': '2026-02-28 23:00:00'}), fh)
    return tag


def stand_scores_npz(T, raw, set_, mode, parts):
    """Синтетические оценки 5M прогона пула (поля «ассет__часть__sp / sn / wk / st», как write_npz Site) — дописываются
       в npz прогона рядом с весами sd_* (как у настоящих прогонов пула)."""
    for seed, D in raw.items():
        path = T._pool_dir(mode) + T._pool_tag(set_, seed, model_name(), mode) + '.npz'
        arr = {}
        if os.path.isfile(path):
            with np.load(path) as d:
                arr = {k: d[k] for k in d.files}
        for a, d in D.items():
            cut = {'tune': slice(0, d['B']), 'val': slice(d['B'], None)} if len(parts) == 2 else {'val': slice(0, None)}
            for p in parts:
                for f in ('sp', 'sn', 'wk', 'st'):
                    arr[f"{a}__{p}__{f}"] = d[f][cut[p]].astype(np.float32 if f in ('sp', 'sn') else
                                                                (np.int32 if f == 'wk' else np.int64))
        np.savez(path, **arr)


