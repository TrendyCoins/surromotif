def rulers_from(T, raw, key, skip):
    """Линейки проверок по оценкам raw (5M — «одна», 1H — «своя»), тем же построением, что на 5M: 'burn' — у сида по
       суррогатам разгона всех его ассетов (build_source Bell: часть A Live); 'fold' — перекрёстные по другой половине без
       skip (fold_rulers Ceil: счёт потолка)."""
    knots, _ = BB.knots_zk(T)
    burn = {s: BB.ruler_q(np.concatenate([d['sn'][:d['B']] for d in D.values()]), knots) for s, D in raw.items()}
    return {'burn': burn, 'fold': CL.fold_rulers(T, raw, key, skip)}


def build_source_q(T, key, raw, about, q_by_seed=None, rng_seed=12345):
    """Копия build_source SuMo_Class_Bell v1 с заданной линейкой сида q_by_seed[сид]; None — как в Bell (по суррогатам
       разгона всех ассетов сида). Стенд: при None и при той же линейке — бит в бит с Bell."""
    knots, zk = BB.knots_zk(T)
    rho_w = BB.rho_window_only()
    src = {'key': key, 'about': about, 'series': {}, 'ruler': {}}
    for i_s, (seed, D) in enumerate(raw.items()):
        q = (BB.ruler_q(np.concatenate([d['sn'][:d['B']] for d in D.values()]), knots) if q_by_seed is None
             else np.asarray(q_by_seed[seed], dtype=np.float64))
        src['ruler'][seed] = q
        S_ = {}
        for i_a, (a, d) in enumerate(D.items()):
            zr, zs = BB.to_z(d['sp'], q, zk), BB.to_z(d['sn'], q, zk)
            info = BB.acf_info(zr)
            rng = np.random.default_rng([rng_seed, i_s, i_a])
            S_[a] = {'zr': zr, 'zs': zs, 'wk': d['wk'], 'B': d['B'], 'acf': info, 'tau_surr': BB.acf_info(zs)['tau'],
                     'zg': BB.gp_chart(info['rho_null'], len(zr), rng),       # модель случайного графика (ворота (в))
                     'zw': BB.gp_chart(rho_w, len(zr), rng)}                   # оптимистичная граница (справочно)
        src['series'][seed] = S_
    src['burn_min'] = min(d['B'] for S_ in src['series'].values() for d in S_.values())
    return src


def cells_cross_q(T, raw, key, v, skip=(), Q=None, P=None):
    """Копия cells_cross SuMo_Class_Ceil v1 с заданными перекрёстными линейками Q[сид][половина] (None — как в Ceil) и
       первым окном счёта P (None — как в Ceil: L + сдвиг формулы v). Стенд: при None — бит в бит с Ceil."""
    _, zk = BB.knots_zk(T)
    Q = CL.fold_rulers(T, raw, key, skip) if Q is None else Q
    P = CL.full_from(v) if P is None else int(P)
    cells = []
    for seed, D in raw.items():
        for a, d in D.items():
            n = len(d['sp'])
            if n <= P:
                continue
            F = CL.fold_ids(T, key, d)
            lr_, ln_ = [], []
            for f in (0, 1):
                zr, zs = BB.to_z(d['sp'], Q[seed][f], zk), BB.to_z(d['sn'], Q[seed][f], zk)
                q = LV.chart_ms(T, zr, [(0, n)], v, {}, p_from=P)
                ok = F[q['i']] == f
                i = q['i'][ok]
                lr_.append(T._nc_logm(zr[i], q['m'][ok], q['s'][ok]))
                ln_.append(T._nc_logm(zs[i], q['m'][ok], q['s'][ok]))
            cells.append((seed, a, np.concatenate(lr_), np.concatenate(ln_)))
    return cells


