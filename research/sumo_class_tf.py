def pair_check_tf(lr, ln, color, C, rows, edges, fine_max, mn):
    """Копия pair_check SuMo_Class_Ceil v1 с корзинами пары edges (rows — curve по ним): корзины ниже min(C, fine_max) —
       отношение >= 0.8 (как R11), выше — одной группой с показанной силой min(сила, C). Статус: 'завышает' / 'без данных' /
       'ок'. Стенд: с корзинами и fine_max Ceil — бит в бит с ним."""
    lo_t = CL.tol()[0]
    k = min(C, fine_max)
    fine = [(r, lo) for r, lo, hi in CL.bins_of(rows, color, edges) if hi <= k]
    g = CL.group_row(lr, ln, color, k, C, mn)
    checks = [(r['sparse'], r['ratio'], lo) for r, lo in fine] + [(g['sparse'], g['ratio'], f"{k:g}+")]
    over = [lo for sp, ra, lo in checks if not sp and not ra >= lo_t]
    sparse = [lo for sp, ra, lo in checks if sp]
    status = 'завышает' if over else ('без данных' if sparse else 'ок')
    return {'status': status, 'over': over, 'sparse': sparse, 'group': g}


def rule_source_tf(cells, Cs, unseen=(), pair_edges=None, fine_max=None, unseen_sparse_ok=False):
    """Копия rule_source SuMo_Class_Ceil v1: (Ц1) пул — как в Ceil (корзины CEIL['edges']); (Ц2) пары — корзины pair_edges
       до fine_max, выше — группой (None — как в Ceil); (Ц3) незнакомые — с unseen_sparse_ok «мало данных» у них не провал
       (на 1H), без — как в Ceil. Стенд: с корзинами Ceil и unseen_sparse_ok=False — бит в бит с Ceil."""
    E, mn = CL.CEIL['edges'], CL.min_n()
    PE = tuple(E if pair_edges is None else pair_edges)
    if PE[-1] != math.inf:
        PE = PE + (math.inf,)
    fm = CL.CEIL['fine_max'] if fine_max is None else fine_max
    assets = list(dict.fromkeys(c[1] for c in cells))
    lr = np.concatenate([c[2] for c in cells])
    ln = np.concatenate([c[3] for c in cells])
    rows = CL.curve(lr, ln, E, mn)
    per = {}
    for a in assets:
        la = np.concatenate([c[2] for c in cells if c[1] == a])
        na = np.concatenate([c[3] for c in cells if c[1] == a])
        per[a] = (la, na, CL.curve(la, na, PE, mn))
    out = {'n_windows': int(len(lr)), 'assets': assets, 'curve': rows, 'by_c': {}}
    good = ('ок', 'без данных') if unseen_sparse_ok else ('ок',)
    for C in Cs:
        if C not in E:
            raise ValueError(f"🍆 АЙ, ОШИБКА! потолок {C} — не край корзин {E}")
        pool = CL.pool_check(lr, ln, C, rows)
        pairs = {(a, col): pair_check_tf(per[a][0], per[a][1], col, C, per[a][2], PE, fm, mn) for a in assets for col in COLS}
        st = [p['status'] for p in pairs.values()]
        n = len(st)
        over, nod = sum(s == 'завышает' for s in st), sum(s == 'без данных' for s in st)
        g2 = bool(n and over / n <= CL.CEIL['share_over'] and nod / n <= CL.CEIL['share_nodata'])
        un = [a for a in unseen if a in per]                 # незнакомого ассета нет в данных — (Ц3) не прошло
        g3 = ((len(un) == len(unseen) and all(pairs[(a, col)]['status'] in good for a in un for col in COLS))
              if unseen else None)
        t_ = math.log(C)
        out['by_c'][C] = {'pool': pool, 'pairs': {f"{a}|{col}": p for (a, col), p in pairs.items()}, 'n_pairs': n,
                          'over': over, 'nodata': nod, 'g1': pool['ok'], 'g2': g2, 'g3': g3, 'unseen': un,
                          'clamp': (float((lr >= t_).mean()), float((lr <= -t_).mean()))}
        if unseen_sparse_ok and unseen:
            out['by_c'][C]['unseen_sparse'] = [f"{a}|{col}" for a in un for col in COLS
                                               if pairs[(a, col)]['status'] == 'без данных']
    return out


def b_gate_tf(cells):
    """(б)-1H — (Ц2)-1H при C = b_cap: у пары корзины 1–1.5, 1.5–2, 2–3 и «3+» с силой min(M, 5) >= 0.8; завышают <= 10%
       и без данных <= 10% пар."""
    C = TFL['b_cap']
    R = rule_source_tf(cells, (C,), pair_edges=TFL['pair_edges'], fine_max=TFL['pair_fine_max'])
    x = R['by_c'][C]
    return {'ok': bool(x['g2']), 'over': int(x['over']), 'nodata': int(x['nodata']), 'n': int(x['n_pairs']),
            'bad': {k: p['status'] for k, p in x['pairs'].items() if p['status'] != 'ок'}}


def passes_tf(rm, rc, C):
    """Кандидат C на 1H: (Ц1)–(Ц3) на основном, (Ц1) на подтверждении (пары там не считаются)."""
    m, c = rm['by_c'][C], rc['by_c'][C]
    return bool(m['g1'] and m['g2'] and m['g3'] is True and c['g1'])


def ceiling_tf(T, raw1, Q_by_key, v, H):
    """(Ц) на 1H: ячейки как у Ceil (окна с полным окном живой части формулы v, перекрёстная линейка Q_by_key[источник]) ->
       правило с корзинами пары 1H. Возвращает ({источник: итог правила}, выбранный C или None)."""
    main, conf = keys_src()
    Cs = tuple(TFL['cands_c']) + tuple(CL.CEIL['refs'])
    R = {}
    for key in (main, conf):
        cells = cells_cross_q(T, raw1[key], key, v, skip=H, Q=Q_by_key[key])
        R[key] = rule_source_tf(cells, Cs, unseen=tuple(H) if key == main else (), pair_edges=TFL['pair_edges'],
                                fine_max=TFL['pair_fine_max'], unseen_sparse_ok=True)
        del cells
    return R, next((c for c in TFL['cands_c'] if passes_tf(R[main], R[conf], c)), None)


