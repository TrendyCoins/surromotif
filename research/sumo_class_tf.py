def rho_assets(T, raw1m, raw5m):
    """ρ = (AUC 1H − 0.5) / (AUC 5M − 0.5) по ассетам основного источника (среднее AUC сидов; окна 1H — на неделях, где есть
       и окна 5M этого ассета)."""
    out = {}
    seeds = [s for s in raw1m if s in raw5m]
    for a in raw1m[seeds[0]] if seeds else []:
        if any(a not in raw1m[s] or a not in raw5m[s] for s in seeds):
            continue
        a1, a5 = [], []
        for s in seeds:
            d1, d5 = raw1m[s][a], raw5m[s][a]
            ok = d1['wk'] <= d5['wk'].max()
            a1.append(T.auc_parts(d1['sp'][ok], d1['sn'][ok])[0])
            a5.append(T.auc_parts(d5['sp'], d5['sn'])[0])
        x1, x5 = float(np.mean(a1)), float(np.mean(a5))
        out[a] = {'auc_1h': x1, 'auc_5m': x5, 'rho': (x1 - 0.5) / (x5 - 0.5) if x5 > 0.5 else math.nan}
    return out


def floor_binds(T, rec, items):
    """Справочно, (П): доля окон 1H (реальных; у суррогата |r| те же), где пол 0.2 сработал — медиана или среднее |r| окна
       ниже пола (как affected у Ceil при старом поле 0), по источникам проверки; максимум по ассетам."""
    n = aff = 0
    per = {}
    for it in items:
        if it['key'] == 'prod':
            continue
        for (a, _), d in rec[it['tag']]['res'].items():
            x = CL.affected(d['med'], d['mabs'], 0.0, TFC['floor'])
            n += len(x)
            aff += int(x.sum())
            p = per.setdefault(a, [0, 0])
            p[0] += int(x.sum())
            p[1] += len(x)
    share = {a: p[0] / max(p[1], 1) for a, p in per.items()}
    worst = max(share, key=share.get) if share else None
    return {'share': aff / max(n, 1), 'n': n, 'worst': worst, 'worst_share': share.get(worst, math.nan) if worst else math.nan}


