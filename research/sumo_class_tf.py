def eval_variants(T, raw_k, key, VA, q_burn, cells_of=None):
    """Часть A Live ('steady': разгон — TUNE / П1, оценка — VAL / П2) вариантов VA на источнике key с линейкой сидов q_burn
       (BCE, R9, модель случайного графика). cells_of(v) — ячейки (б)-1H кандидата (основной источник); без него (б) не
       считается (подтверждение). В воротах Live доля пар 'share' = 1 / 0 по (б)-1H (на подтверждении — 1); доля по
       правилу 5M (R11 >= 5) — в 'share_5m', справочно."""
    src = build_source_q(T, key, raw_k, BB.BELL['sources'][key]['about'], q_burn)
    recs = LV.prep_source(T, src)
    w0, NW = LV.week_span(recs)
    res = {}
    for v in VA:
        r = LV.eval_set(T, recs, v, w0, NW, 'steady')
        r['share_5m'] = r['share']
        if v['cand']:
            b = b_gate_tf(cells_of(v)) if cells_of is not None else None
            r['b1h'] = b
            r['share'] = 1.0 if (b is None or b['ok']) else 0.0
        res[v['key']] = r
    del src, recs
    return res


