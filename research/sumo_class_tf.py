_NO = object()                                         # «ключа не было» — чтобы вернуть настройки после блока как были


@contextlib.contextmanager
def rules21(T):
    """Правила v2.1 на время блока — подменой настроек, которыми уже считают функции v2, Live и Ceil: допуски честности пула
       LINE21['tol'] (R9 части A — T.NOCAL['tol'], (Ц1) — CL.CEIL['tol']), порог (а) — LINE21['ceil_min'] (T.NOCAL['ceil_pool']),
       по монете — LINE21['over_max'] / ['nodata_max'] (CL.CEIL['share_over'] / ['share_nodata']). После блока — как было."""
    keep_n = {k: T.NOCAL[k] for k in ('tol', 'ceil_pool')}
    keep_c = {k: CL.CEIL.get(k, _NO) for k in ('tol', 'share_over', 'share_nodata')}
    T.NOCAL.update({'tol': tuple(LINE21['tol']), 'ceil_pool': LINE21['ceil_min']})
    CL.CEIL.update({'tol': tuple(LINE21['tol']), 'share_over': LINE21['over_max'], 'share_nodata': LINE21['nodata_max']})
    try:
        yield
    finally:
        T.NOCAL.update(keep_n)
        for k, x in keep_c.items():
            if x is _NO:
                CL.CEIL.pop(k, None)
            else:
                CL.CEIL[k] = x


def rows_split(raw, hold_ns, fresh):
    """Ряды Bell (окна идут по времени), разрезанные датой свежих данных: fresh=False — только окна раньше даты (основной
       источник: разгон TUNE — как был, оценка — VAL до даты); fresh=True — все окна, разгон — окна раньше даты (VAL до неё),
       оценка — с неё (подтверждение)."""
    out = {}
    for s, D in raw.items():
        out[s] = {}
        for a, d in D.items():
            t = np.asarray(d['t'])
            if len(t) > 1 and np.any(np.diff(t) <= 0):
                raise ValueError(f"🍆 АЙ, ОШИБКА! {a} ({s}): окна ряда идут не по времени")
            k = int(np.searchsorted(t, hold_ns, side='left'))
            if fresh:
                out[s][a] = dict(d, B=k)
            else:
                if d['B'] > k:
                    raise ValueError(f"🍆 АЙ, ОШИБКА! {a} ({s}): разгон заходит за дату свежих данных")
                out[s][a] = {f: (x[:k] if isinstance(x, np.ndarray) and len(x) == len(t) else x) for f, x in d.items()}
    return out


def fresh_ok(raw, need_burn, need_fresh):
    """Ряды подтверждения на свежих данных: у всех сидов разгон >= need_burn окон и свежих окон >= need_fresh. Возвращает
       (ряды, выпавшие ассеты)."""
    seeds = list(raw)
    common = [a for a in raw[seeds[0]] if all(a in raw[s] for s in seeds)]
    keep = [a for a in common if all(raw[s][a]['B'] >= need_burn and len(raw[s][a]['sp']) - raw[s][a]['B'] >= need_fresh
                                     for s in seeds)]
    return {s: {a: raw[s][a] for a in keep} for s in seeds}, [a for a in common if a not in keep]


