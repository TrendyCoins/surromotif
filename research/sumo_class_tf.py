def cache_1h_path(tag):
    return OUT_DIR + f"cache_1h/tf1h_{tag}_f{TFC['floor']:g}.npz"


def save_cache_1h(tag, res, fp, run):
    """Оценки модели на окнах 1H (ключи «ассет__часть__поле»): logit реальных окон и суррогатов (float32, как npz пула),
       медиана и среднее |r| окна, недели, начала окон в пуле и время последнего бара окна."""
    os.makedirs(OUT_DIR + 'cache_1h/', exist_ok=True)
    arr = {'meta': np.array(json.dumps({'tag': tag, 'floor': TFC['floor'], 'tf': TFL['tf'], 'fp': fp, 'ver': TF_VER,
                                        'run': run}))}
    for (a, p), d in res.items():
        k = f"{a}__{p}__"
        arr[k + 'sp'], arr[k + 'sn'] = d['sp'].astype(np.float32), d['sn'].astype(np.float32)
        arr[k + 'med'], arr[k + 'mabs'] = np.asarray(d['med'], np.float32), np.asarray(d['mabs'], np.float32)
        arr[k + 'wk'], arr[k + 'st'], arr[k + 't'] = (np.asarray(d[f], np.int64) for f in ('wk', 'st', 't'))
    np.savez(cache_1h_path(tag), **arr)


def load_cache_1h(tag, fp):
    """Кэш оценок 1H; None — нет или он от другого (тега, пола, ТФ, файлов 1H, версии)."""
    p = cache_1h_path(tag)
    if not os.path.isfile(p):
        return None
    with np.load(p) as d:
        meta = json.loads(str(d['meta']))
        if (meta.get('tag'), meta.get('floor'), meta.get('tf'), meta.get('fp'), meta.get('ver')) != (
                tag, TFC['floor'], TFL['tf'], fp, TF_VER):
            return None
        res = {}
        for k in d.files:
            if not k.endswith('__sp'):
                continue
            base = k[:-len('sp')]
            a, part = base.split('__')[:2]
            res[(a, part)] = {'sp': d[base + 'sp'].astype(np.float64), 'sn': d[base + 'sn'].astype(np.float64),
                              'med': d[base + 'med'], 'mabs': d[base + 'mabs'], 'wk': d[base + 'wk'].astype(np.int64),
                              'st': d[base + 'st'].astype(np.int64), 't': d[base + 't'].astype(np.int64)}
    return {'res': res, 'run': meta.get('run', {}), 'cached': True}


def score_all_1h(T, pdata, assets, items, fp, sec):
    """Оценки моделей items на окнах 1H всех ассетов с полом 0.2 — тем же счётом, что пересчёт Ceil (collect: набор проверки
       кода обучения, суррогат sflip4; пол — внутри floor_override). Кэш — OUT_DIR/cache_1h/. sec — секунд на окно (сверка
       1) для оценки времени. {тег: {'res', 'run', 'cached'}} или None — стоп (CPU, дольше часа)."""
    import torch
    L, m = T.POOL['L'], model_name()
    out, todo = {}, []
    for it in items:
        c = load_cache_1h(it['tag'], fp)
        if c is not None:
            out[it['tag']] = c
            print(f"   💾 {it['tag']}: из кэша ({len(c['res'])} частей)")
        else:
            todo.append(it)
    if not todo:
        return out
    n_tot = 0
    for a in assets:
        st_ = T.pool_asset_store(pdata['data'], L, pdata['sid'][a], pdata['t_cut'])
        n_tot += sum(len(st_.w[p]) for it in todo for p in it['parts'])
    eta = (sec or 0.0) * n_tot / 60
    print(f"   ⏱️ оценка счёта: ~{eta:.0f} мин ({n_tot} окон, у каждого — суррогат; моделей {len(todo)}) | {T.DEVICE}")
    if T.DEVICE.type == 'cpu' and eta > TFL['cpu_max_min']:
        print(f"🍆 СТОП: на CPU счёт займёт ~{eta:.0f} мин — включи GPU (Среда выполнения -> Сменить тип среды -> T4 GPU) и "
              f"запусти снова (готовые оценки уже в кэше)")
        return None
    for it in todo:
        t1 = time.time()
        model, r = T.load_pool_model(it['set'], it['seed'], m, it['mode'])
        res = {}
        for a in assets:
            for p in it['parts']:
                with CL.floor_override(pdata['data'], L, TFC['floor']):
                    d = CL.collect(T, model, pdata, a, p)
                if d is None:
                    continue
                d['st'] = np.asarray(d['st'], dtype=np.int64)
                d['wk'] = np.asarray(d['wk'], dtype=np.int64)
                d['t'] = np.asarray(pdata['data'].t[d['st'] + L - 1], dtype=np.int64)
                for f in ('sp', 'sn'):                   # как npz пула и кэш: float32 -> float64 (кэш = пересчёт бит в бит)
                    d[f] = np.asarray(d[f]).astype(np.float32).astype(np.float64)
                res[(a, p)] = d
            if T.DEVICE.type == 'cuda':
                torch.cuda.empty_cache()
        run = {'tag': r.get('tag', it['tag']), 't_cut': r.get('t_cut'), 'data_overlay': r.get('data_overlay')}
        save_cache_1h(it['tag'], res, fp, run)
        out[it['tag']] = {'res': res, 'run': run, 'cached': False}
        print(f"   🧠 {it['tag']}: частей {len(res)} | {(time.time() - t1) / 60:.1f} мин")
        del model
    return out


def raw_1h(T, rec, key, assets):
    """Оценки 1H источника в виде Bell (как read_source_raw): {сид: {ассет: sp, sn, wk, B, st, t}}; части склеены по
       времени, B — окон разгона (TUNE у основного, П1 у подтверждения). Ассеты без всех частей — в список пропущенных."""
    S_ = BB.BELL['sources'][key]
    raw, miss = {}, []
    for seed in BB.BELL['seeds']:
        R = rec[T._pool_tag(S_['set'], seed, model_name(), S_['mode'])]['res']
        D = {}
        for a in assets:
            xs = [R.get((a, p)) for p in S_['parts']]
            if any(x is None for x in xs):
                miss.append(f"{a} {seed}")
                continue
            wk = np.concatenate([x['wk'] for x in xs]).astype(np.int64)
            if (np.diff(wk) < 0).any():
                raise ValueError(f"🍆 АЙ, ОШИБКА! {key} {seed} {a}: недели окон убывают — порядок окон неизвестен")
            if S_['burn'] == 'tune':
                B = len(xs[0]['sp'])
            else:
                h1 = T._nc_half(wk)
                B = int(h1.sum())
                if not h1[:B].all():
                    raise ValueError(f"🍆 АЙ, ОШИБКА! {key} {seed} {a}: окна П1 не идут первыми")
            D[a] = {f: np.concatenate([x[f] for x in xs]) for f in ('sp', 'sn', 'st', 't')}
            D[a].update({'wk': wk, 'B': B})
        raw[seed] = D
    return raw, miss


def raw_5m(T, key, assets):
    """Оценки 5M источника для линейки «одна»: пересчёт Site с полом 0.2 (его кэш), иначе npz пула (старые полы и TF32 —
       линейку это сдвигает на тысячные z). (raw в виде Bell, откуда) или (None, почему)."""
    try:
        raw_b, _ = BB.read_source_raw(T, key, assets)
    except (FileNotFoundError, ValueError) as e:
        return None, f"нет оценок 5M ({e})"
    S_ = BB.BELL['sources'][key]
    rec, miss = {}, []
    for seed in raw_b:
        tag = T._pool_tag(S_['set'], seed, BB.BELL['model'], S_['mode'])
        c = CL.load_cache({'tag': tag})
        if c is None:
            miss.append(tag)
        else:
            rec[tag] = c
    if miss:
        return raw_b, f"npz пула (старые полы и TF32; нет кэша Site: {', '.join(miss)})"
    try:
        raw, _ = CL.raw_from(T, key, rec, raw_b, {}, 'new')
    except (ValueError, KeyError) as e:
        return raw_b, f"npz пула (кэш Site не подошёл: {e})"
    return raw, "кэш Site (пол 0.2)"


def burn_ok(raw, need):
    """Ряды части A: ассеты, у которых у всех сидов разгон >= need окон (живая часть самого длинного кандидата полная с
       первого окна оценки). Возвращает (ряды, выпавшие ассеты)."""
    seeds = list(raw)
    common = [a for a in raw[seeds[0]] if all(a in raw[s] for s in seeds)]
    keep = [a for a in common if all(raw[s][a]['B'] >= need for s in seeds)]
    return {s: {a: raw[s][a] for a in keep} for s in seeds}, [a for a in common if a not in keep]


