def ruler_shift(T, q1, q5, sn1):
    """Справочно: насколько линейка 1H отличается от 5M — max |Δz| в узлах (z, который линейка 5M даёт logit узлов линейки
       1H, минус их z) и центр / разброс z суррогатов VAL 1H боевой модели по линейке 5M (у «своей» — 0 / ~1)."""
    _, zk = BB.knots_zk(T)
    z = BB.to_z(sn1, q5, zk)
    return {'dz_max': float(np.max(np.abs(BB.to_z(q1, q5, zk) - zk))), 'z_mean': float(z.mean()), 'z_sd': float(z.std()),
            'z_sd_own': float(BB.to_z(sn1, q1, zk).std())}


