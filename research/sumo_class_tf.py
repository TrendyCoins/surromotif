@contextlib.contextmanager
def tf_data(T, tf, data_dir):
    """Код обучения читает данные ТФ tf из data_dir (DATA['timeframe'], DATA_DIR; без накладки) — на время блока."""
    keep = (T.DATA['timeframe'], T.DATA_DIR, T.DATA_OVERLAY)
    T.DATA['timeframe'], T.DATA_DIR, T.DATA_OVERLAY = tf, data_dir, None
    try:
        yield
    finally:
        T.DATA['timeframe'], T.DATA_DIR, T.DATA_OVERLAY = keep


