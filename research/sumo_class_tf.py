def series_data(T, data_dir, tf, nt_cols, price, tune_start):
    """Ряды одного ассета (код обучения, SeriesData) из data_dir: у F1 — три цены бара, диапазон и история в барах (столбцы
       nt_cols). Сверка (3): контрольные суммы при загрузке и медиана диапазона за 200 баров = нормировщик r."""
    T.DATA_DIR, T.DATA_OVERLAY = data_dir, None
    T.NT_KEEP = tuple(sorted(set(nt_cols)))
    try:
        data = T.SeriesData([TFC['asset']], tf, TFC['N'], tune_start, price)
    finally:
        T._reset_nt_keep()
    ne = math.nan
    if nt_cols:
        if not data.nt_ok:
            raise RuntimeError(f"🍆 АЙ, ОШИБКА! {tf}: признаки истории в барах не посчитаны (нет smc_bars в {data_dir})")
        ne = float(data.nt_stats['norm_err'])
        if not ne < 1e-5:
            raise RuntimeError(f"🍆 АЙ, ОШИБКА! {tf}: медиана диапазона за 200 баров не равна нормировщику r (отн. ошибка "
                               f"{ne:.1e}) — бары не от того CSV, что ряд")
    w = data.windows(T.POOL['L'])
    return {'data': data, 'tf': tf, 't_cut': int(w['t_end'][w['val']].max()), 'norm_err': ne,
            'n': {p: int(len(w[p])) for p in ('fit', 'tune', 'val')}}


