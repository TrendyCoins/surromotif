def score_parts(T, model, D, parts, c0=False):
    """Оценки модели на окнах частей parts ряда D с полом TFC['floor']: реальные окна (sp) и их суррогаты TFC['null'] (sn) —
       те же наборы проверки, что у прогонов пула (код обучения); начала окон, недели, время открытия последнего бара окна (t).
       c0 — ещё контроль: два независимых суррогата одного окна (c0p, c0n). Набор проверки строится внутри floor_override —
       пол 0.2 попадает и в форму окна, и в боковые входы (как у collect в Ceil)."""
    import torch
    L, out = T.POOL['L'], {}
    data = D['data']
    with CL.floor_override(data, L, TFC['floor']):
        for p in parts:
            store = T.pool_asset_store(data, L, 0, D['t_cut'])
            P = store.positives(p)
            ev = store.get(p, TFC['null'])
            st = np.asarray(P['st'], dtype=np.int64)
            rec = {'st': st, 'wk': np.asarray(P['wk'], dtype=np.int64), 't': data.t[st + L - 1].astype(np.int64),
                   'sp': T.score(model, P['X'], S=P['S']), 'sn': T.score(model, ev['Xn'], S=ev['Sn']),
                   'floor': float(store.w['floor'][0])}
            if c0:
                ec = store.get(p, TFC['c0'])
                rec['c0p'], rec['c0n'] = T.score(model, ec['Xp'], S=ec['Sp']), T.score(model, ec['Xn'], S=ec['Sn'])
            out[p] = rec
            store._pos.clear()
            store._set.clear()
            del store, P, ev
            if T.DEVICE.type == 'cuda':
                torch.cuda.empty_cache()
    return out


