PRICES = {'hl2': lambda h, l, c: (h + l) / 2.0,
          'hlc3': lambda h, l, c: (h + l + c) / 3.0}


def read_csv(path):
    """CSV Binance (timestamp — время открытия бара, UTC) с проверками SuMo_Class_Data (load_ohlc)."""
    if not os.path.isfile(path):
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет файла {path} — CSV ТФ (имена — TFC['csv'])")
    df = pd.read_csv(path, parse_dates=['timestamp'])
    o, h, l, c = (df[k].to_numpy(dtype=np.float64) for k in ('open', 'high', 'low', 'close'))
    n_bad = int(((o == 0) | (h == 0) | (l == 0) | (c == 0) | (c < l) | (c > h) | (o < l) | (o > h) | (h < l)).sum())
    if n_bad:
        raise ValueError(f"🍆 АЙ, ОШИБКА! {os.path.basename(path)}: битых баров OHLC {n_bad}")
    back = int((df['timestamp'].diff().dt.total_seconds().to_numpy()[1:] <= 0).sum())
    if back:
        raise ValueError(f"🍆 АЙ, ОШИБКА! {os.path.basename(path)}: метки времени не по возрастанию ({back})")
    return df


def r_series(df, N):
    """r и маски — ровно как make_parts SuMo_Class_Data: нормировщик — rolling-медиана (high − low) за N баров ДО бара по всему
       файлу; пропуск сетки (интервал > 1.5 медианного) и мёртвый нормировщик -> NaN. Шаг сетки берётся из данных — подходит
       любому ТФ."""
    high, low, close = (df[k].to_numpy(dtype=np.float64) for k in ('high', 'low', 'close'))
    roll = pd.Series(high - low).rolling(N, closed='left').median().to_numpy()
    dt = df['timestamp'].diff().dt.total_seconds().to_numpy()
    step = float(np.nanmedian(dt[1:]))
    gap = np.zeros(len(df), dtype=bool)
    gap[1:] = dt[1:] > step * 1.5
    d_close = np.diff(close, prepend=close[0])
    d_close[0] = 0.0
    r = np.zeros_like(d_close)
    np.divide(d_close, roll, out=r, where=roll != 0)
    bad = ~np.isfinite(roll) | (roll <= 0) | ~np.isfinite(r) | gap
    r[bad] = np.nan
    r[0] = np.nan
    return roll, gap, bad, r, step


def part_rows(date, N, a, b, name):
    """Строки части в CSV — как make_parts: от первого бара не раньше a плюс N баров разогрева нормировщика, до последнего бара
       раньше b (b None — до конца файла). Возвращает (lo, hi) — срез [lo, hi)."""
    hits = np.where(date >= pd.Timestamp(a))[0]
    if len(hits) == 0:
        raise ValueError(f"🍆 АЙ, ОШИБКА! {name}: начало {a} позже конца данных")
    i0 = int(hits[0])
    if b is None:
        i1 = len(date) - 1
    else:
        hits = np.where(date < pd.Timestamp(b))[0]
        if len(hits) == 0:
            raise ValueError(f"🍆 АЙ, ОШИБКА! {name}: конец {b} раньше начала данных")
        i1 = int(hits[-1])
    lo, hi = i0 + N, i1 + 1
    if lo >= hi:
        raise ValueError(f"🍆 АЙ, ОШИБКА! {name}: диапазон пуст после разогрева {N} баров")
    return lo, hi


def build_tf_files(df, out_dir, asset, tf, N, t_start, t_valid, floor):
    """Файлы research одного ассета и ТФ из его CSV — как SuMo_Class_Data (smc_series: r, время, close, конечные, пол), Prices
       (smc_prices: сдвиги e, d средних цен HL/2 и HLC/3), Range (smc_range: диапазон бара g) и Bars (smc_bars: OHLC частей и N
       баров перед каждой). Копия арифметики mri/research_bridge.py репо (там она сверена с оригиналами), ТФ — в имени и meta.
       Пол в файле — floor (оценки всё равно считаются с полом через floor_override). Возвращает сводку частей."""
    opn, high, low, close = (df[k].to_numpy(dtype=np.float64) for k in ('open', 'high', 'low', 'close'))
    date = df['timestamp']
    ts = date.to_numpy().astype('datetime64[ns]').astype(np.int64)
    roll, gap, bad, r, step = r_series(df, N)
    good_roll = np.isfinite(roll) & (roll > 0)
    prev_close = np.concatenate([[np.nan], close[:-1]])
    e_all, d_all = {}, {}
    for nm, f in PRICES.items():
        p = f(high, low, close)
        e = np.full(len(close), np.nan)
        np.divide(p - prev_close, roll, out=e, where=good_roll)
        e[bad] = np.nan                                  # от прошлого close: через пропуск сетки — нет
        e[0] = np.nan
        dd = np.full(len(close), np.nan)
        np.divide(p - close, roll, out=dd, where=good_roll)
        e_all[nm], d_all[nm] = e, dd
    g = np.full(len(close), np.nan)
    np.divide(high - low, roll, out=g, where=~bad)       # диапазон бара в единицах того же делителя, что у r
    ser, pri, rng, bars, crc, info = {}, {}, {}, {}, {}, {}
    for name, key, a, b in (('TRAINING', 'tr', t_start, t_valid), ('VALIDATION', 'va', t_valid, None)):
        lo, hi = part_rows(date, N, a, b, f"{asset} {tf} {name}")
        r_part = r[lo:hi].astype(np.float32)
        ser[f'r_{key}'] = r_part
        ser[f't_{key}'] = ts[lo:hi].copy()
        ser[f'close_{key}'] = close[lo:hi].copy()
        ser[f'fin_{key}'] = np.where(np.isfinite(r_part))[0].astype(np.int32)
        crc[key] = zlib.crc32(r_part.tobytes())
        for nm in PRICES:
            pri[f'e_{nm}_{key}'] = e_all[nm][lo:hi].astype(np.float32)
            pri[f'd_{nm}_{key}'] = d_all[nm][lo:hi].astype(np.float32)
            pri[f'd0_{nm}_{key}'] = np.array(np.float32(d_all[nm][lo - 1]))
        g_part = g[lo:hi].astype(np.float32)
        g_part[~np.isfinite(r_part)] = np.nan            # g там же, где r: окна у моделей с диапазоном — те же
        rng[f'g_{key}'] = g_part
        pre = slice(lo - N, lo)                          # N баров перед частью — те, на которых считался нормировщик
        for k_, v in (('o', opn), ('h', high), ('l', low), ('c', close)):
            bars[f'{k_}_{key}'] = v[lo:hi].copy()
            bars[f'pre_{k_}_{key}'] = v[pre].copy()
        info[name] = {'n': hi - lo, 'from': str(date.iloc[lo]), 'to': str(date.iloc[hi - 1]),
                      'n_gap': int(gap[lo:hi].sum()), 'n_nan': int((~np.isfinite(r_part)).sum())}
    ser['floor_L64'] = np.array(float(floor))
    meta = {'asset': asset, 'tf': tf, 'N': N, 'training_start': t_start, 'validation_start': t_valid, 'parts': info,
            'step_s': step, 'csv_rows': int(len(df)), 'csv_first': str(date.iloc[0]), 'csv_last': str(date.iloc[-1]),
            'what': f'SuMo_Class_TF v{TF_VER}: арифметика SuMo_Class_Data / Prices / Range / Bars', 'crc': crc,
            'created': time.strftime('%Y-%m-%d %H:%M:%S')}
    ser['meta'] = np.array(json.dumps(meta, ensure_ascii=False))
    for d_ in (pri, rng):
        d_['meta'] = np.array(json.dumps({'asset': asset, 'tf': tf, 'N': N, 'crc': crc}, ensure_ascii=False))
    bars['meta'] = np.array(json.dumps({'asset': asset, 'tf': tf, 'N': N, 'n_pre': N, 'crc': crc,
                                        'what': 'raw OHLC of smc_series bars + N bars before each part'}, ensure_ascii=False))
    os.makedirs(out_dir, exist_ok=True)
    for kind, arrs in (('series', ser), ('prices', pri), ('range', rng), ('bars', bars)):
        np.savez_compressed(os.path.join(out_dir, f"smc_{kind}_{asset}_{tf}_N{N}.npz"), **arrs)
    return meta


def close_check(T, data_5m, data_tf, tf):
    """Справочно: close бара ТФ = close последнего бара 5M внутри него — у баров, которые есть в обоих рядах research. Возвращает
       (сравнено баров, доля равных, первый бар с разницей)."""
    asset, N, b = TFC['asset'], TFC['N'], tf_ns(T, TFC['base'])

    def load(d, tf_):
        with np.load(os.path.join(d, f"smc_series_{asset}_{tf_}_N{N}.npz")) as z:
            return (np.concatenate([z['t_tr'], z['t_va']]).astype(np.int64),
                    np.concatenate([z['close_tr'], z['close_va']]).astype(np.float64))
    t5, c5 = load(data_5m, TFC['base'])
    tk, ck = load(data_tf, tf)
    last5 = tk + tf_ns(T, tf) - b
    pos = np.searchsorted(t5, last5)
    ok = pos < len(t5)
    ok[ok] = t5[pos[ok]] == last5[ok]
    if not ok.any():
        return 0, math.nan, None
    eq = ck[ok] == c5[pos[ok]]
    first = None if eq.all() else str(pd.Timestamp(int(tk[ok][~eq][0])))
    return int(ok.sum()), float(eq.mean()), first


