def train_start(a, df5):
    """Начало TRAINING ассета: как у его файла research 5M (meta 'training_start' SuMo_Class_Data), иначе правило
       SuMo_Class_Data — не раньше TFC['t_start'] и не раньше листинга (первого бара CSV 5M) + skip_days."""
