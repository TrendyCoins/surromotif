def disp(T, rec, tf, meth):
    """Показания графика: (бар графика j, z, неделя). 'ref' — график 5M (каждое окно 5M); 'A' — график ТФ, бар красится по
       5M-окну, закрывшемуся вместе с ним (последний бар 5M окна закрывается ровно на закрытии бара ТФ); 'B' — график ТФ,
       окна самого ТФ. j — номер бара своего графика от начала эпохи: соседние бары — j и j + 1."""
    if meth == 'ref':
        return rec['t'] // tf_ns(T, TFC['base']), rec['sp'], rec['wk']
    k = tf_ns(T, tf)
    if meth == 'A':
        tc = rec['t'] + tf_ns(T, TFC['base'])             # закрытие последнего бара 5M окна
        m = (tc % k) == 0
        return tc[m] // k - 1, rec['sp'][m], rec['wk'][m]
    return rec['t'] // k, rec['sp'], rec['wk']


def a_mask(T, rec, tf):
    return ((rec['t'] + tf_ns(T, TFC['base'])) % tf_ns(T, tf)) == 0


def week_sums(j, z, wk):
    """Пары соседних баров графика (j, j + 1), у обоих есть показание; суммы по неделям (неделя пары — второго бара): Σ Δz²,
       пар, Σ z, Σ z², показаний (как _line_weeks кода обучения, но соседство — по барам графика, а не по началам окон).
       Возвращает (недели, массив (5, недели))."""
    j, z, wk = np.asarray(j, np.int64), np.asarray(z, np.float64), np.asarray(wk, np.int64)
    if len(j) > 1 and not np.all(np.diff(j) > 0):
        o = np.argsort(j, kind='stable')
        j, z, wk = j[o], z[o], wk[o]
        if not np.all(np.diff(j) > 0):
            raise ValueError("🍆 АЙ, ОШИБКА! у двух показаний один бар графика")
    i0 = np.where(j[1:] == j[:-1] + 1)[0]
    i1 = i0 + 1
    weeks, inv = np.unique(wk, return_inverse=True)
    G = len(weeks)
    A = np.stack([np.bincount(inv[i1], weights=(z[i1] - z[i0]) ** 2, minlength=G),
                  np.bincount(inv[i1], minlength=G).astype(np.float64),
                  np.bincount(inv, weights=z, minlength=G), np.bincount(inv, weights=z * z, minlength=G),
                  np.bincount(inv, minlength=G).astype(np.float64)])
    return weeks, A


def merge_weeks(items):
    """Сумма недельных сумм нескольких частей (одна неделя может попасть в две части — суммы складываются)."""
    weeks = np.unique(np.concatenate([w for w, _ in items]))
    A = np.zeros((5, len(weeks)))
    for w, a in items:
        A[:, np.searchsorted(weeks, w)] += a
    return weeks, A


def align(weeks_src, A, weeks):
    """Недельные суммы на заданных неделях (нет недели — нули)."""
    out = np.zeros((5, len(weeks)))
    pos = np.searchsorted(weeks_src, weeks)
    ok = pos < len(weeks_src)
    ok[ok] = weeks_src[pos[ok]] == weeks[ok]
    out[:, ok] = A[:, pos[ok]]
    return out


def r_from(A):
    """R = RMS(Δz) / sd(z) по суммам week_sums, сложенным по неделям (A — (5, …))."""
    e2, npr, s1, s2, nw = A
    with np.errstate(invalid='ignore', divide='ignore'):
        return np.sqrt(e2 / npr / np.maximum(s2 / nw - (s1 / nw) ** 2, 1e-12))


def ratio(ser_x, ser_ref, B, seed=0):
    """Q = R способа / R эталона: ser_* — {сид: (недели, A)}. Общие недели — где есть показания у всех рядов; log Q — среднее по
       сидам log(R способа / R эталона) сида; SE — бутстреп недель (одни выборки у всех рядов и сидов: ошибки связаны)."""
    seeds = [s for s in ser_x if s in ser_ref]
    common = functools.reduce(np.intersect1d, [ser_x[s][0] for s in seeds] + [ser_ref[s][0] for s in seeds])
    X = {s: align(*ser_x[s], common) for s in seeds}
    Rf = {s: align(*ser_ref[s], common) for s in seeds}
    pairs_x = float(np.mean([X[s][1].sum() for s in seeds]))
    pairs_r = float(np.mean([Rf[s][1].sum() for s in seeds]))
    out = {'weeks': int(len(common)), 'pairs': pairs_x, 'pairs_ref': pairs_r, 'few': bool(pairs_x < TFC['min_pairs'])}
    if len(common) < 2 or pairs_x <= 0:
        out.update({'lq': math.nan, 'se': math.nan, 'Q': math.nan, 'lo': math.nan, 'hi': math.nan, 'R': math.nan,
                    'R_ref': math.nan, 'seeds': {}})
        return out
    rx = {s: float(r_from(X[s].sum(1))) for s in seeds}
    rr = {s: float(r_from(Rf[s].sum(1))) for s in seeds}
    lq = float(np.mean([math.log(rx[s] / rr[s]) for s in seeds]))
    pick = np.random.default_rng(seed).integers(0, len(common), size=(B, len(common)))
    with np.errstate(invalid='ignore', divide='ignore'):
        lb = np.mean([np.log(r_from(X[s][:, pick].sum(2))) - np.log(r_from(Rf[s][:, pick].sum(2))) for s in seeds], axis=0)
    lb = lb[np.isfinite(lb)]
    se = float(np.std(lb, ddof=1)) if len(lb) > 2 else math.nan
    k = TFC['k_se']
    out.update({'lq': lq, 'se': se, 'Q': math.exp(lq), 'lo': math.exp(lq - k * se), 'hi': math.exp(lq + k * se),
                'R': float(math.exp(np.mean([math.log(rx[s]) for s in seeds]))),
                'R_ref': float(math.exp(np.mean([math.log(rr[s]) for s in seeds]))),
                'seeds': {s: rx[s] / rr[s] for s in seeds}})
    return out


def auc_seeds(T, recs, parts, meth, tf=None):
    """AUC реальных окон против своих суррогатов по сидам (у сидов окна одни): среднее по сидам и SE — по недельным суммам
       вкладов окон, усреднённых по сидам. meth 'ref' — окна 5M; 'A' — окна 5M в моменты закрытия баров ТФ; 'B' — окна ТФ."""
    aucs, ips, ins, wk = [], [], [], None
    for s, R in recs.items():
        key = TFC['base'] if meth in ('ref', 'A') else tf
        sp, sn, w = [], [], []
        for p in parts:
            rec = R[key][p]
            m = a_mask(T, rec, tf) if meth == 'A' else np.ones(len(rec['sp']), dtype=bool)
            sp.append(rec['sp'][m])
            sn.append(rec['sn'][m])
            w.append(rec['wk'][m])
        a, ip, in_ = T.auc_parts(np.concatenate(sp), np.concatenate(sn))
        aucs.append(a)
        ips.append(ip)
        ins.append(in_)
        wk = np.concatenate(w)
    se = T.cluster_se([np.mean(ips, axis=0), np.mean(ins, axis=0)], [wk, wk])
    return {'auc': float(np.mean(aucs)), 'se': float(se), 'seeds': {s: float(a) for s, a in zip(recs, aucs)},
            'n': int(len(wk))}


def rho_of(b, ref):
    """ρ = (AUC ТФ − 0.5) / (AUC 5M − 0.5) и его SE (дельта-метод, ошибки будто независимы — с запасом)."""
    a, r = b['auc'] - 0.5, ref['auc'] - 0.5
    rho = a / r if r > 0 else math.nan
    se = abs(rho) * math.sqrt((b['se'] / a) ** 2 + (ref['se'] / r) ** 2) if a != 0 and r > 0 else math.nan
    return {'rho': rho, 'se': se}


def c0_of(T, R_tf, parts):
    """Контроль C0 на данных ТФ: AUC суррогата против суррогата того же окна — 0.5 ± max(c0_tol, c0_se · SE)."""
    sp = np.concatenate([R_tf[p]['c0p'] for p in parts])
    sn = np.concatenate([R_tf[p]['c0n'] for p in parts])
    wk = np.concatenate([R_tf[p]['wk'] for p in parts])
    a, ip, in_ = T.auc_parts(sp, sn)
    se = T.cluster_se([ip, in_], [wk, wk])
    return {'auc': float(a), 'se': float(se), 'ok': bool(abs(a - 0.5) <= max(TFC['c0_tol'], TFC['c0_se'] * se))}


def logm_val(T, recs_tf, v):
    """log M линии M формулы v на окнах VAL (разгон — TUNE), как часть A Live (CL.series_logm): линейка — квантили логитов
       суррогатов TUNE своего ряда, живая часть — по всему ряду. {сид: log M окон VAL по порядку}."""
    a = TFC['asset']
    raw = {s: {a: {'sp': np.concatenate([R['tune']['sp'], R['val']['sp']]),
                   'sn': np.concatenate([R['tune']['sn'], R['val']['sn']]),
                   'wk': np.concatenate([R['tune']['wk'], R['val']['wk']]), 'B': len(R['tune']['sp'])}}
           for s, R in recs_tf.items()}
    lm = CL.series_logm(T, raw, v)
    return {s: lm[(s, a)] for s in raw}


def classes(lg):
    """Класс цвета бара по log M: сторона (+1 оранжевый, −1 синий) × корзина силы M по SHADES (1…5), как flips у Site."""
    side = np.where(lg >= 0, 1, -1)
    return side * (1 + np.searchsorted(np.log(np.asarray(SHADES, dtype=np.float64)), np.abs(lg)))


def flips(j, lg):
    """Смены цвета между соседними барами графика (j, j + 1): [пар, смен стороны, смен оттенка, смен отметки M >= 1.25 / <= 0.8]."""
    j, lg = np.asarray(j, np.int64), np.asarray(lg, np.float64)
    i0 = np.where(j[1:] == j[:-1] + 1)[0]
    i1 = i0 + 1
    side = np.where(lg >= 0, 1, -1)
    cls = classes(lg)
    t = math.log(1.25)
    mark = np.where(lg >= t, 1, np.where(lg <= -t, -1, 0))
    return np.array([len(i0), (side[i1] != side[i0]).sum(), (cls[i1] != cls[i0]).sum(), (mark[i1] != mark[i0]).sum()],
                    dtype=np.float64)


def strip(j, lg, n):
    """Последние n баров графика (по номеру бара): класс цвета, 0 — бара нет."""
    j = np.asarray(j, np.int64)
    out = np.zeros(n, dtype=np.int64)
    if not len(j):
        return out
    pos = j - (j.max() - n + 1)
    ok = pos >= 0
    out[pos[ok]] = classes(np.asarray(lg)[ok])
    return out


def line_flips(T, recs, v):
    """Справочно, основной источник: смены цвета на 100 баров графика у линии M формулы сайта (VAL): график 5M, A (линия графика
       5M в моменты закрытия баров ТФ) и B (линия на окнах ТФ). И полосы цвета последних баров для рисунка (сид первым)."""
    b = tf_ns(T, TFC['base'])
    lm5 = logm_val(T, {s: R[TFC['base']] for s, R in recs.items()}, v)
    acc, strips = {'5M': np.zeros(4)}, {}
    s0 = next(iter(recs))
    for s, R in recs.items():
        j5 = R[TFC['base']]['val']['t'] // b
        acc['5M'] += flips(j5, lm5[s])
        if s == s0:
            strips['5M'] = strip(j5, lm5[s], TFC['show_bars'])
    for tf in TFC['tfs']:
        lmk = logm_val(T, {s: R[tf] for s, R in recs.items()}, v)
        acc[f'A {tf}'], acc[f'B {tf}'] = np.zeros(4), np.zeros(4)
        for s, R in recs.items():
            rec = R[TFC['base']]['val']
            m = a_mask(T, rec, tf)
            jA = (rec['t'][m] + b) // tf_ns(T, tf) - 1
            jB = R[tf]['val']['t'] // tf_ns(T, tf)
            acc[f'A {tf}'] += flips(jA, lm5[s][m])
            acc[f'B {tf}'] += flips(jB, lmk[s])
            if s == s0:
                strips[f'A {tf}'] = strip(jA, lm5[s][m], TFC['show_bars'])
                strips[f'B {tf}'] = strip(jB, lmk[s], TFC['show_bars'])
    rates = {k: {'pairs': int(x[0]), 'side100': 100 * x[1] / max(x[0], 1), 'shade100': 100 * x[2] / max(x[0], 1),
                 'mark100': 100 * x[3] / max(x[0], 1)} for k, x in acc.items()}
    return rates, strips


def measure(T, recs, v=None):
    """Все мерки по источникам: Q (способ × ТФ), AUC и ρ, C0 (основной), смены цвета (основной, если v задан)."""
    out = {}
    for src, spec in TFC['sources'].items():
        R, parts = recs[src], spec['parts']
        ref = {s: merge_weeks([week_sums(*disp(T, x[TFC['base']][p], None, 'ref')) for p in parts]) for s, x in R.items()}
        res = {'Q': {}, 'auc': {'ref': auc_seeds(T, R, parts, 'ref')}, 'rho': {}, 'c0': {}}
        for tf in TFC['tfs']:
            res['Q'][tf] = {}
            for meth in ('A', 'B'):
                key = TFC['base'] if meth == 'A' else tf
                ser = {s: merge_weeks([week_sums(*disp(T, x[key][p], tf, meth)) for p in parts]) for s, x in R.items()}
                res['Q'][tf][meth] = ratio(ser, ref, TFC['boot'], seed=zlib.crc32(f"{src}|{tf}|{meth}".encode()))
            res['auc'][f'A {tf}'] = auc_seeds(T, R, parts, 'A', tf)
            res['auc'][f'B {tf}'] = auc_seeds(T, R, parts, 'B', tf)
            res['rho'][tf] = rho_of(res['auc'][f'B {tf}'], res['auc']['ref'])
            s0 = next(iter(R))
            if 'c0p' in R[s0][tf][parts[0]]:
                res['c0'][tf] = c0_of(T, R[s0][tf], parts)
        res['R_ref'] = float(math.exp(np.mean([math.log(r_from(a.sum(1))) for _, a in ref.values()])))
        res['pairs_ref'] = float(np.mean([a[1].sum() for _, a in ref.values()]))
        if src == 'main' and v is not None and all('tune' in x[k] for x in R.values() for k in x):
            res['flips'], res['strips'] = line_flips(T, R, v)
        out[src] = res
    return out


