def ruler_rule(T, ev, f, can_export):
    """(Л): «одна» остаётся, если с ней (формула f) проходят ворота на обоих источниках, BCE не хуже «своей» больше чем на
       band_se SE на основном и на confirm_se SE на подтверждении, и её линейку есть что экспортировать; иначе «своя»."""
    main, conf = keys_src()
    if 'one' not in ev:
        return {'pick': 'own', 'why': 'нет оценок 5M — «одну» линейку не построить', 'checks': {}}
    g = {var: {k: LV.gates(T, ev[var][k][f]) for k in (main, conf)} for var in ev}
    dm = BB.paired({'one': ev['one'][main][f], 'own': ev['own'][main][f]}, 'one', 'own')
    dc = BB.paired({'one': ev['one'][conf][f], 'own': ev['own'][conf][f]}, 'one', 'own')

    def within(d, k):
        return bool(np.isfinite(d[0]) and np.isfinite(d[1]) and d[0] <= k * d[1])
    ch = {'gates': all(g['one'][k]['all'] for k in (main, conf)), 'bce_main': within(dm, TFL['band_se']),
          'bce_confirm': within(dc, TFL['confirm_se']), 'export': bool(can_export)}
    return {'pick': 'one' if all(ch.values()) else 'own', 'checks': ch, 'gates': g, 'd_main': list(dm),
            'd_confirm': list(dc), 'why': None}


def part_a_tf(T, raw1, raw1f, rl, var, VA, f5, H, P_b):
    """(Ж): часть A Live на 1H с линейкой var: ворота (а), (в), (б)-1H (основной) -> лучший по BCE -> полоса -> формула 5M из
       полосы, иначе порядок Live; подтверждение. Возвращает (итоги по источникам, выбор, подтверждение, итог)."""
    main, conf = keys_src()
    res = {}
    for key in (main, conf):
        t1 = time.time()
        res[key] = eval_variants(T, raw1f[key], key, VA, rl[var][key]['burn'],
                                 b_cells(T, raw1[main], rl[var][main]['fold'], H, P_b) if key == main else None)
        print(f"   ⏱️ {key}: {len(VA)} вариантов, {time.time() - t1:.0f} c")
    vm = {v['key']: v for v in VA}
    cands = [v['key'] for v in VA if v['cand']]
