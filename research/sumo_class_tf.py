def golden_1h(T, rec, ruler, v, path):
    """Паритет бэкенда на 1H: VAL ассета TFL['golden'] у боевого сида — logit с полом 0.2, z по линейке экспорта, живая
       часть формулы v с начала ряда (m, s, n), показ с окна L + сдвиг, log M; начала окон в пуле, время последнего бара
       окна (нс UTC, метка открытия бара, как в данных SMC), недели. Сверка (4): линия из записанных logit — бит в бит.
       Возвращает (итог, описание)."""
    a, s = TFL['golden'], TFL['prod_seed']
    x = rec[prod_tag(T)]['res'].get((a, 'val'))
    if x is None:
        print(f"   ⏭️ golden: у {a} нет оценок VAL {TFL['tf']}")
        return False, None
    knots, zk = BB.knots_zk(T)
    q = np.asarray(ruler['q'], dtype=np.float64)

    def line_of(lg_):
        z_ = BB.to_z(lg_, q, zk)
        qq = LV.chart_ms(T, z_, [(0, len(z_))], v, {}, p_from=0)
        show_ = qq['p'] >= CL.full_from(v)
        lm_ = np.full(len(z_), np.nan)
        lm_[show_] = T._nc_logm(z_[show_], qq['m'][show_], qq['s'][show_])
        return z_, qq, show_, lm_
    lg = x['sp'].astype(np.float32).astype(np.float64)
    z, qq, show, lm = line_of(lg)
    t_end, wk = np.asarray(x['t'], np.int64), np.asarray(x['wk'], np.int64)
    if not np.array_equal(t_end // T.WEEK_NS, wk):
        raise ValueError("🍆 АЙ, ОШИБКА! golden: недели по времени окон не совпали с неделями окон")
    lf = S.live_formula(T, v)
    meta = {'asset': a, 'tf': TFL['tf'], 'model': model_name(), 'seed': s, 'tag': prod_tag(T), 'floor': TFC['floor'],
            'knots': list(knots), 'zk': list(zk), 'q': list(q), 'ruler_from': ruler.get('from'),
            'live': {k_: lf[k_] for k_ in ('key', 'family', 'L', 'n0', 'k', 'tau', 'lag', 'show_from_window', 's_lo')},
            'part': f"VAL research {TFL['tf']} (бары — ресемпл CSV 5M, как свечи Binance)",
            'logit': 'logit сида (float32 -> float64)',
            't_end': 'время последнего бара окна, нс UTC (метка открытия бара, как t_end в данных SMC)',
            'tol': 'сверка бэкенда: z, m, s, log M — до 1e-9 (скользящие суммы против префиксных бит в бит не совпадут); '
                   'logit своего инференса — до допуска float32 модели'}
    arrs = {f"logit_{s}": x['sp'].astype(np.float32), 'logit': lg, 'z': z, 'm': qq['m'], 's': qq['s'],
            'n_live': qq['n'].astype(np.int32), 'show': show, 'logm': lm, 'wk': wk.astype(np.int32), 'st': x['st'],
            't_end': t_end, 'meta': np.array(json.dumps(meta, ensure_ascii=False))}
    np.savez_compressed(path, **arrs)
    with np.load(path) as d:                                  # сверка (4): заново из записанных logit
        lg2 = d[f"logit_{s}"].astype(np.float64)
        z2, q2, show2, lm2 = line_of(lg2)
        same = bool(np.array_equal(lg2, d['logit']) and np.array_equal(z2, d['z']) and np.array_equal(show2, d['show'])
                    and np.array_equal(q2['m'], d['m']) and np.array_equal(q2['s'], d['s'])
                    and np.array_equal(np.nan_to_num(lm2, nan=7.0), np.nan_to_num(d['logm'], nan=7.0)))
    size = os.path.getsize(path) / 2 ** 20
    t0_, t1_ = pd.Timestamp(int(t_end[0])), pd.Timestamp(int(t_end[-1]))
    print(f"   golden {os.path.basename(path)}: {a} {TFL['tf']}, окон {len(z)}, линия на {int(show.sum())} (с окна "
          f"{CL.full_from(v)}), время окон {t0_:%Y-%m-%d %H:%M} … {t1_:%Y-%m-%d %H:%M}, {size:.1f} МБ | сверка (4): линия из "
          f"записанных logit — бит в бит {'✅' if same else '❌'}")
    return same, {'path': os.path.basename(path), 'n': int(len(z)), 'shown': int(show.sum()), 'mb': size, 'same': same,
                  'from': str(t0_), 'to': str(t1_)}


