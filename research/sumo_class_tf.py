def synth_bars(t0, t1, seed, gaps=()):
    """Синтетические бары 5M: случайное блуждание (шаги t(5)) с плывущей волатильностью и суточным профилем, 4 подшага на бар
       (high / low — по пути), open = прошлый close; бары внутри gaps выкинуты (пропуск сетки)."""
    rng = np.random.default_rng(seed)
    t = pd.date_range(t0, t1, freq='5min', inclusive='left')
    n = len(t)
    hours = t.hour.to_numpy() + t.minute.to_numpy() / 60.0
    prof = 1.0 + 0.5 * np.cos(2 * np.pi * (hours - 15.0) / 24.0)
    lv = np.zeros(n)
    eps = rng.normal(0.0, 0.03, n)
    for i in range(1, n):
        lv[i] = 0.999 * lv[i - 1] + eps[i]
    sig = 1e-3 * prof * np.exp(lv)
    sub = rng.standard_t(5, size=(n, 4)) * (sig[:, None] / 2.0)
    close_lp = np.cumsum(sub.sum(1))
    open_lp = np.concatenate([[0.0], close_lp[:-1]])
    pts = open_lp[:, None] + np.cumsum(sub, axis=1)
    hi_lp = np.maximum(open_lp, pts.max(1))
    lo_lp = np.minimum(open_lp, pts.min(1))
    df = pd.DataFrame({'timestamp': t, 'open': 30000 * np.exp(open_lp), 'high': 30000 * np.exp(hi_lp),
                       'low': 30000 * np.exp(lo_lp), 'close': 30000 * np.exp(close_lp), 'volume': 1.0})
    for a, b in gaps:
        df = df[(df['timestamp'] < pd.Timestamp(a)) | (df['timestamp'] >= pd.Timestamp(b))]
    return df.reset_index(drop=True)


def resample(df5, minutes):
    """Бары ТФ из баров 5M (как свечи Binance): open — первого, high / low — max / min, close — последнего бара 5M внутри."""
    key = df5['timestamp'].dt.floor(f"{minutes}min")
    g = df5.groupby(key, sort=True)
    return pd.DataFrame({'timestamp': g['timestamp'].first().index, 'open': g['open'].first().to_numpy(),
                         'high': g['high'].max().to_numpy(), 'low': g['low'].min().to_numpy(),
                         'close': g['close'].last().to_numpy(), 'volume': 1.0}).reset_index(drop=True)


def ma_series(n, w, seed):
    """Скользящее среднее w независимых N(0, 1): у него R(k) = √(2k / w²) / (1 / √w) = √(2k / w) при k <= w."""
    x = np.random.default_rng(seed).normal(size=n + w)
    c = np.concatenate([[0.0], np.cumsum(x)])
    return (c[w:] - c[:-w])[:n] / w


