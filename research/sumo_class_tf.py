def pack_eval(res, keys=None):
    """Итоги части A для json: без недельных массивов."""
    fields = ('fam', 'bce', 'shown_share', 'n', 'n_shown', 'gp_col', 'gp_se', 'gp_strong', 'ceil', 'share', 'share_5m',
              'cover', 'cover3', 'b1h')
    return {k: {f: r.get(f) for f in fields} for k, r in res.items() if keys is None or k in keys}


def pack_ceil(R):
    return {key: {'n_windows': r['n_windows'], 'curve': r['curve'], 'by_c': {str(c): x for c, x in r['by_c'].items()}}
            for key, r in R.items()}


