def curve_txt(T, rows, color):
    """Кривая R9 цвета строкой: корзина — фактическая / обещанная кратность ((з) — завышает, < tol_lo; (н) — занижает,
       > tol_hi), «мд» — мало данных (в скобках — окон у меньшего класса). До первой корзины «мд» включительно."""
    lo_t, hi_t = T.NOCAL['tol']
    E = list(T.NC_EDGES)
    out = []
    for r in rows:
        if r['color'] != color:
            continue
        hi = E[E.index(r['lo']) + 1]
        lab = f"{r['lo']:g}–{hi:g}" if math.isfinite(hi) else f"{r['lo']:g}+"
        if r['sparse']:
            out.append(f"{lab} мд({_kn(min(r['n_real'], r['n_surr']))})")
            break
        out.append(f"{lab} {r['ratio']:.2f}" + ('(з)' if r['ratio'] < lo_t else ('(н)' if r['ratio'] > hi_t else '')))
    return ' · '.join(out)


