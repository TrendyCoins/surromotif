def variants_long():
    """Окна длиннее Live (у бэкенда сайта нет предела TradingView в 5000 баров): F1 — просто окно, F2 — плюс long_n0
       виртуальных случайных окон, F3 — центр минус long_k ошибки; сдвиг — как у Live."""
    lag, n0, k = LV.LIVE['lag'], LDIAG['long_n0'], LDIAG['long_k']
    out = []
    for L in LDIAG['long_L']:
        out += [LV._v(key=f"{L}", fam='F1', kind='win', L=L, lag=lag, about=f"окно {L}"),
                LV._v(key=f"{L}+{n0}", fam='F2', kind='win', L=L, lag=lag, prior='null', n0=n0,
                      about=f"окно {L} + {n0} виртуальных случайных окон"),
                LV._v(key=f"{L}·k{k:g}", fam='F3', kind='win', L=L, lag=lag, k=k, about=f"окно {L}, центр минус {k:g} ошибки")]
    return out


def diag_eval(T, recs, v, w0, NW, marks, keep_cells=False):
    """Копия eval_set SuMo_Class_Live v1.1 (область 'steady', full, без pos): BCE по неделям, R9 по показанным окнам, модель
       случайного графика — плюс строки кривой R9 и доли окон с отметкой (M >= t или <= 1 / t) у случайного графика и у
       реальных окон при каждой отметке t из marks. keep_cells (v2.1) — вернуть и ячейки [(сид, ассет, log M реальных,
       log M суррогатов)] показанных окон оценки. Стенд: при отметке 1.25 — BCE, R9, cover и случайный график бит в бит с
       eval_set."""
    gw = LV.LIVE['gp_group_weeks']
    NG = NW // gw + 1
    lt = [LV.L125 if t == 1.25 else math.log(t) for t in marks]
    wsum, wcnt = np.zeros(NW), np.zeros(NW)
    g_sh, g_mk = np.zeros(NG), np.zeros((len(marks), NG))
    n_shown = n_all = 0
    cells = []
    for r in recs:
        tiles, p_from, p_to = LV.region(r, v, 'steady')
        if not tiles:
            continue
        if v['kind'] == 'win' and np.isfinite(v['L']) and r['B'] < v['L'] + v['lag']:
            raise ValueError(f"🍆 АЙ, ОШИБКА! {r['asset']}: разгон {r['B']} окон короче окна {v['L']} + сдвиг {v['lag']}")
        q = LV.chart_ms(T, r['zr'], tiles, v, r['aux'], p_from, p_to)
        shown = q['p'] >= v['show']
        lr, ln = LV.logm_at(T, r['zr'], q, shown), LV.logm_at(T, r['zs'], q, shown)
        b = BB.bce_pairs(lr, ln)
        wi = r['wk'][q['i']] - w0
        wsum += np.bincount(wi, weights=b, minlength=NW)
        wcnt += np.bincount(wi, minlength=NW)
        n_shown += int(shown.sum())
        n_all += len(b)
        cells.append((r['seed'], r['asset'], lr[shown], ln[shown]))
        gi = wi[shown] // gw
        for zg in r['zg']:
            qg = LV.chart_ms(T, zg, tiles, v, r['aux'], p_from, p_to)
            lg = np.abs(LV.logm_at(T, zg, qg, shown)[shown])
            g_sh += np.bincount(gi, minlength=NG)
            for j, t in enumerate(lt):
                g_mk[j] += np.bincount(gi, weights=(lg >= t).astype(np.float64), minlength=NG)
    with np.errstate(invalid='ignore', divide='ignore'):
        wk_bce = wsum / wcnt
    gsh = g_sh.sum()
    ok = g_sh > 0
    G = int(ok.sum())

    def share_se(mk):                                        # доля и ошибка по кластерам времени — как в eval_set
        col = float(mk.sum() / gsh) if gsh else 0.0
        se = math.nan
        if G >= 4:
            gm = mk[ok] / g_sh[ok]
            se = math.sqrt(G / (G - 1) * np.sum((g_sh[ok] / gsh) ** 2 * (gm - col) ** 2))
        return col, se
    gp = {f"{t:g}": share_se(g_mk[j]) for j, t in enumerate(marks)}
    has = any(len(c[2]) for c in cells)
    lr_all = np.concatenate([c[2] for c in cells]) if has else np.zeros(0)
    ln_all = np.concatenate([c[3] for c in cells]) if has else np.zeros(0)
    rows = T._nc_curve(lr_all, ln_all) if has else []
    ceil = {col: T._nc_ceil(rows, col) for col in COLS} if has else {'orange': math.nan, 'blue': math.nan}
    cover = {f"{t:g}": ((float((lr_all >= x).mean()), float((lr_all <= -x).mean())) if has else (math.nan, math.nan))
             for t, x in zip(marks, lt)}
    first = f"{marks[0]:g}"
    out = {'key': v['key'], 'fam': v['fam'], 'wk_bce': wk_bce, 'bce': float(np.nanmean(wk_bce)), 'n': n_all,
           'n_shown': n_shown, 'gp_col': gp[first][0], 'gp_se': gp[first][1], 'gp': gp, 'ceil': ceil, 'rows': rows,
           'cover': cover}
    if keep_cells:
        out['cells'] = cells
    return out


def pair_detail(cells, a, col, C):
    """(б)-1H у пары ассет × цвет с числами: корзины ниже min(C, pair_fine_max) и группа от неё с силой min(M, C) —
       отношение фактической кратности к обещанной, окон реал / сурр, мало ли данных, завышает ли. Статус — как у
       pair_check_tf (стенд)."""
    PE = tuple(TFL['pair_edges']) + (math.inf,)
    mn, lo_t = CL.min_n(), CL.tol()[0]
    la = np.concatenate([c[2] for c in cells if c[1] == a])
    na = np.concatenate([c[3] for c in cells if c[1] == a])
    rows = CL.curve(la, na, PE, mn)
    k = min(C, TFL['pair_fine_max'])
    out = [{'lab': f"{lo:g}–{hi:g}", 'n_real': r['n_real'], 'n_surr': r['n_surr'], 'ratio': r['ratio'], 'sparse': r['sparse']}
           for r, lo, hi in CL.bins_of(rows, col, PE) if hi <= k]
    g = CL.group_row(la, na, col, k, C, mn)
    out.append({'lab': f"{k:g}+", 'n_real': g['n_real'], 'n_surr': g['n_surr'], 'ratio': g['ratio'], 'sparse': g['sparse']})
    for x in out:
        x['over'] = bool(not x['sparse'] and not x['ratio'] >= lo_t)
    status = 'завышает' if any(x['over'] for x in out) else ('без данных' if any(x['sparse'] for x in out) else 'ок')
    return status, out


def diag_b(cells):
    """(б)-1H как b_gate_tf (C = b_cap) и у пар не «ок» — числа по корзинам (pair_detail)."""
    C = TFL['b_cap']
