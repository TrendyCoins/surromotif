def _strip_rgb(row):
    """Полоса цвета: класс ±1…±5 -> оттенок стороны (бледный -> насыщенный), 0 — бара нет."""
    bg = np.array(matplotlib.colors.to_rgb(C_BG))
    out = np.zeros((len(row), 3))
    for i, c in enumerate(row):
        if c == 0:
            out[i] = matplotlib.colors.to_rgb(C_EMPTY)
            continue
        alpha = (0.18, 0.38, 0.58, 0.8, 1.0)[min(abs(int(c)), 5) - 1]
        out[i] = bg + alpha * (np.array(matplotlib.colors.to_rgb(C_SIDE[1 if c > 0 else -1])) - bg)
    return out


