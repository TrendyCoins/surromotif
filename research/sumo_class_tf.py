        for i, _ in enumerate(TFC['seeds']):
            for D in [D5] + list(Dtf.values()):
                w = D['data'].windows(64)
                for p in spec['parts']:
                    k = int(len(w[p])) if p != 'val' else int((w['t_end'][w['val']] <= D['t_cut']).sum())
