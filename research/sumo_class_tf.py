def anchor_g(T, model):
    """G = R(NT1_PRV) / R(F1) у BTC на 5M по npz прогонов пула 'stop' C a / b (окна TUNE + VAL; соседство — по началам окон, как
       _line_weeks): среднее по сидам log отношения. Нет прогонов (или окна разные) — TFC['anchor_default']."""
    a, lr, info = TFC['asset'], [], {}
    for s in TFC['seeds']:
        R = {}
        for m in (TFC['anchor_model'], model):
            base = RUN_DIR + 'pool/' + T._pool_tag('C', s, m, 'stop')
            try:
                arr = S.npz_keys(base, [f"{a}__{p}__{f}" for p in ('tune', 'val') for f in ('sp', 'st', 'wk')])
            except FileNotFoundError:
                return TFC['anchor_default'], {'source': 'default', 'why': f"нет прогона {os.path.basename(base)}"}
            if not all(f"{a}__{p}__{f}" in arr for p in ('tune', 'val') for f in ('sp', 'st', 'wk')):
                return TFC['anchor_default'], {'source': 'default', 'why': f"в {os.path.basename(base)} нет начал окон BTC"}
            R[m] = arr
        same = all(np.array_equal(R[model][f"{a}__{p}__st"], R[TFC['anchor_model']][f"{a}__{p}__st"]) for p in ('tune', 'val'))
        if not same:
            return TFC['anchor_default'], {'source': 'default', 'why': f"сид {s}: окна NT1_PRV и F1 разные"}
        rs = {}
        for m, arr in R.items():
            W = merge_weeks([week_sums(arr[f"{a}__{p}__st"], arr[f"{a}__{p}__sp"].astype(np.float64), arr[f"{a}__{p}__wk"])
                             for p in ('tune', 'val')])
            rs[m] = float(r_from(W[1].sum(1)))
        info[s] = {'R_anchor': rs[TFC['anchor_model']], 'R_model': rs[model]}
        lr.append(math.log(rs[TFC['anchor_model']] / rs[model]))
    return float(math.exp(np.mean(lr))), {'source': 'npz', 'seeds': info}


def work_kept(T, model, D5):
    """Справочно: сколько выигрыша волн SM / SP в плавности доходит до графика ТФ у A — R(NT1_PRV) / R(F1) у показаний A (окна 5M
       на закрытиях баров ТФ) по npz прогонов пула 'stop' C a / b (старые полы; начала окон — позиции ряда D5, у BTC они те же,
       что в пуле). На графике 5M это G; чем ближе к 1 на ТФ, тем меньше работа по плавности видна в его покраске. Среднее по
       сидам log отношения. None — прогонов нет или окна не те."""
    a, L = TFC['asset'], T.POOL['L']
    st_all = D5['data'].windows(L)['st']
    keys = (TFC['base'],) + tuple(TFC['tfs'])
    lr = {k: [] for k in keys}
    for s in TFC['seeds']:
        R = {}
        for mm in (TFC['anchor_model'], model):
            base = RUN_DIR + 'pool/' + T._pool_tag('C', s, mm, 'stop')
            try:
                arr = S.npz_keys(base, [f"{a}__{p}__{f}" for p in ('tune', 'val') for f in ('sp', 'st', 'wk')])
            except FileNotFoundError:
                return None
            if not all(f"{a}__{p}__{f}" in arr for p in ('tune', 'val') for f in ('sp', 'st', 'wk')):
                return None
            R[mm] = arr
        for p in ('tune', 'val'):
            st = R[model][f"{a}__{p}__st"]
            if not (np.array_equal(st, R[TFC['anchor_model']][f"{a}__{p}__st"]) and np.isin(st, st_all).all()):
                return None
        rs = {}
        for mm, arr in R.items():
            recs = {p: {'t': D5['data'].t[arr[f"{a}__{p}__st"] + L - 1].astype(np.int64),
                        'sp': arr[f"{a}__{p}__sp"].astype(np.float64), 'wk': arr[f"{a}__{p}__wk"].astype(np.int64)}
                    for p in ('tune', 'val')}
            rs[mm] = {TFC['base']: float(r_from(merge_weeks([week_sums(*disp(T, x, None, 'ref')) for x in recs.values()])[1].sum(1)))}
            for tf in TFC['tfs']:
                rs[mm][tf] = float(r_from(merge_weeks([week_sums(*disp(T, x, tf, 'A')) for x in recs.values()])[1].sum(1)))
        for k in keys:
            lr[k].append(math.log(rs[TFC['anchor_model']][k] / rs[model][k]))
    return {k: float(math.exp(np.mean(v))) for k, v in lr.items()}


def zone(q, G):
    """Зона (Г) по Q и его полосе ±2 SE: 'kept' ✅, 'eaten' ❌, 'part' 🟡, 'few' — мало пар соседних баров."""
    if q is None or q.get('few') or not np.isfinite(q.get('Q', math.nan)) or not np.isfinite(q.get('se', math.nan)):
        return 'few'
    if q['hi'] <= TFC['kept']:
        return 'kept'
    if q['lo'] >= G:
        return 'eaten'
    return 'part'


def verdict(res, G):
    """(Г) по способам и ТФ (основной; подтверждение — согласие зон), (К) у B, итог по ТФ — по правилу «что значит итог»."""
    out = {}
    for tf in TFC['tfs']:
        row = {}
        for meth in ('A', 'B'):
            z_m = zone(res['main']['Q'][tf][meth], G)
            z_c = zone(res['confirm']['Q'][tf][meth], G) if 'confirm' in res else None
            row[meth] = {'zone': z_m, 'zone_confirm': z_c, 'agree': z_c is None or z_c == z_m}
        rho = {src: res[src]['rho'][tf]['rho'] for src in res}
        c0 = res['main']['c0'].get(tf)
        k_ok = bool(all(np.isfinite(x) and x >= TFC['rho_min'] for x in rho.values()) and c0 is not None and c0['ok'])
        if row['A']['zone'] == 'kept':
            dec = 'A'
        elif row['B']['zone'] == 'kept' and k_ok:
            dec = 'B'
        else:
            dec = 'none'
        out[tf] = {'A': row['A'], 'B': row['B'], 'quality_B': {'rho': rho, 'c0': c0, 'ok': k_ok}, 'decision': dec}
    return out


