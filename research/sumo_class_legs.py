def load_bars(asset, tf):
    """Бары ассета по частям {0: TRAINING, 1: VALIDATION}: OHLC smc_bars с pre-барами (N баров перед частью, на них считался
       нормировщик r её первых баров; время pre-баров — условная сетка ТФ перед частью). Части не склеиваются."""
    N, bar_ns = LEGS['N'], LEGS['bar_ns'][tf]
    data_dir = {'5M': DATA_5M, '1H': DATA_1H}[tf]
    ps, pb = data_dir + f"smc_series_{asset}_{tf}_N{N}.npz", data_dir + f"smc_bars_{asset}_{tf}_N{N}.npz"
    for p_ in (ps, pb):
        if not os.path.isfile(p_):
            raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет {p_}")
    with np.load(ps, allow_pickle=False) as ds, np.load(pb, allow_pickle=False) as db:
        segs = {}
        for code, key in ((0, 'tr'), (1, 'va')):
            T = ds[f't_{key}'].astype(np.int64)
            n_pre = len(db[f'pre_c_{key}'])
            seg = {'T': np.r_[T[0] - bar_ns * np.arange(n_pre, 0, -1), T], 'n_pre': n_pre}
            for k_ in ('h', 'l', 'c'):
                seg[k_] = np.r_[db[f'pre_{k_}_{key}'], db[f'{k_}_{key}']].astype(float)
            if len(seg['c']) != len(seg['T']):
                raise ValueError(f"🍆 АЙ, ОШИБКА! {asset} {tf}: баров {key} в smc_bars {len(seg['c']) - n_pre}, а в "
                                 f"smc_series {len(T)} — файлы из разных выгрузок")
            seg['norm'] = normalizer(seg['h'], seg['l'], seg['c'])
            segs[code] = seg
    return segs


