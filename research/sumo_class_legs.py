def period_masks(bars, tf):
    """in_period(t) по коду части: TUNE — бары TRAINING с tune_start (без pre-баров), VAL — бары VALIDATION без pre-баров."""
    tune_ns = pd.Timestamp(LEGS['tune_start']).value

    def mk(B, code):
        T, n_pre = B['T'], B['n_pre']
        if code == 0:
            return lambda t: (t >= n_pre) & (T[np.asarray(t)] >= tune_ns)
        return lambda t: np.asarray(t) >= n_pre
    return mk


def scale_cell(bars, colors, tf, m, with_events=True, with_rand=False, seed=0):
    """Одна клетка масштаба: ноги (а) и экстремумы (б) обоих периодов по всем ассетам. Возвращает {период: {'a', 'b',
       'rand'}} — склеенные таблицы."""
    mk = period_masks(bars, tf)
    out = {}
    for src, part in LEGS['periods'].items():
        code = 0 if part == 'tune' else 1
        acc = {'a': [], 'b': [], 'rand': []}
        for ia, (a, P_) in enumerate(bars.items()):
            if a not in colors.get(src, {}):
                continue
            B = P_[code]
            col = colors[src][a]
            cols = {'c': col['c'], 'ct': col['ct'], **{f's{j}': shifted(col['c'], j) for j in range(1, LEGS['n_shift'] + 1)}}
            inp = mk(B, code)
            tabs, _ = leg_tables(B, m, cols, inp, with_events=with_events)
            for kind in ('a', 'b'):
                if tabs[kind] is not None:
                    tabs[kind]['T'] = B['T'][tabs[kind]['t']]
                    tabs[kind]['asset'] = np.full(len(tabs[kind]['t']), ia, dtype=np.int16)
                    acc[kind].append(tabs[kind])
            if with_rand:
                cr, nr = random_market(B, seed + 1000 * ia + 17 * code)
                piv = run_slicer(cr, B['h'], B['l'], m, nr)
                rt, _ = leg_tables(dict(B, c=cr), m, {'c': col['c']}, inp, with_events=False, pivots=piv)
                if rt['a'] is not None:
                    acc['rand'].append(rt['a']['S'][rt['a']['cover'] >= LEGS['cover_min']])
        cat = lambda L_: ({k: np.concatenate([d[k] for d in L_]) for k in L_[0]} if L_ else None)
        out[src] = {'a': cat(acc['a']), 'b': cat(acc['b']),
                    'rand': np.concatenate(acc['rand']) if acc['rand'] else None}
    return out


def n_legs(cell):
    """Число ног (а) с цветом на каждом периоде."""
    return {src: int((x['a']['cover'] >= LEGS['cover_min']).sum()) if x['a'] is not None else 0 for src, x in cell.items()}


def choose_scales(bars, colors, tf):
    """Масштабы ТФ: медианы ноги на FIT -> m; T — наибольшее из top_grid, при котором на каждом периоде >= min_legs ног (а)
       с цветом; масштабы — T/4, T/2, T."""
    t0 = time.time()
    rows = fit_medians(bars, tf)
    print(f"📏 {tf}: медиана ноги на FIT ({LEGS['fit_from'][:10]} … {LEGS['tune_start'][:10]}) по сетке m: "
          + ', '.join(f"m {r['m']:.3g} — {_f(r['median'], '.0f')}" for r in rows) + f" | {time.time() - t0:.0f} c")
    chosen = None
    for T_ in LEGS['top_grid']:
        m = m_for(rows, T_)
        cell = scale_cell(bars, colors, tf, m, with_events=False)
        n = n_legs(cell)
        ok = all(v >= LEGS['min_legs'] for v in n.values())
        print(f"   T = {T_} баров (m = {m:.3g}): ног (а) с цветом — " + ', '.join(f"{k} {v}" for k, v in n.items())
              + (' ✅' if ok else f" — меньше {LEGS['min_legs']}"), flush=True)
        if ok:
            chosen = T_
            break
    few = chosen is None
    if few:
        chosen = LEGS['top_grid'][-1]
        print(f"   ❗ {tf}: {LEGS['min_legs']} ног не набирается и при T = {chosen} — берётся {chosen}, пометка «мало ног»")
    scales = []
    for i, r in enumerate(LEGS['ratios']):
        target = chosen * r
        scales.append({'name': f"S{i + 1}", 'target': float(target), 'm': m_for(rows, target), 'few': few})
    print(f"   -> {tf}: " + ', '.join(f"{s['name']} — медиана ноги {s['target']:.0f} баров, m = {s['m']:.3g}" for s in scales))
    return scales, rows


def _bins_txt(sh, bins):
    edges = [f"{b:g}" for b in bins]
    names = [f"<{edges[0]}"] + [f"{edges[j]}–{edges[j + 1]}" for j in range(len(edges) - 1)] + [f"≥{edges[-1]}"]
    return ' · '.join(f"{n_} {100 * v:.0f}%" for n_, v in zip(names, sh))


