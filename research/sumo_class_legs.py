def fit_medians(bars, tf):
    """Медиана длины ноги (пивот -> пивот, все ассеты вместе) на двух последних годах FIT для каждого m сетки."""
    a_ns, b_ns = pd.Timestamp(LEGS['fit_from']).value, pd.Timestamp(LEGS['tune_start']).value
    fit = []
    for P_ in bars.values():
        B = P_[0]
        lo, hi = np.searchsorted(B['T'], a_ns), np.searchsorted(B['T'], b_ns)
        if hi - lo >= 4 * LEGS['hl_window']:
            lo = max(lo - LEGS['hl_window'], 0)                 # ATR первых баров — из баров перед ними
            sl = slice(lo, hi)
            fit.append((B['c'][sl], B['h'][sl], B['l'][sl], tuple(x[sl] for x in B['norm'])))
    rows = []
    for m in LEGS['m_grid']:
        legs = [np.diff(run_slicer(c_, h_, l_, m, nm)[2][2]) for c_, h_, l_, nm in fit]
        legs = np.concatenate(legs) if legs else np.zeros(0)
        rows.append({'m': m, 'legs': int(len(legs)), 'median': float(np.median(legs)) if len(legs) else math.nan})
    return rows


def m_for(rows, target):
    """m, при котором медиана ноги на FIT = target баров: интерполяция log m по log медианы (медиана растёт с m)."""
    ok = [r for r in rows if np.isfinite(r['median']) and r['legs'] >= 50] or [r for r in rows if np.isfinite(r['median'])]
    if not ok:
        raise ValueError("🍆 АЙ, ОШИБКА! медиана ноги на FIT не посчиталась ни при одном m — мало баров FIT")
    lm = np.log([r['median'] for r in ok])
    order = np.argsort(lm)
    lm, lmm = lm[order], np.log([r['m'] for r in ok])[order]
    if not lm[0] <= math.log(target) <= lm[-1]:
        print(f"   ⚠️ медиана ноги {target:.0f} баров — вне сетки m (медианы {math.exp(lm[0]):.0f} … {math.exp(lm[-1]):.0f}): "
              f"m — крайний узел сетки")
    return float(np.exp(np.interp(math.log(target), lm, lmm)))


