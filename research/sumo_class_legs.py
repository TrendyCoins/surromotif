def leg_tables(B, m, cols, in_period, with_events=True, pivots=None):
    """Ноги (а) и экстремумы (б) части B на масштабе m. cols — {имя: цвет на барах} (реал, близнец, сдвиги; может быть
       пусто); in_period(t) — бар в периоде. Признаки — из баров <= точки отсчёта; цели — из будущего ноги.
       pivots — готовый результат run_slicer (для случайного рынка). Возвращает ({'a': …, 'b': …}, разметку)."""
    c = B['c']
    atr, mw, (PT, PP, PI, PC, bar_k, bar_e) = pivots if pivots is not None else run_slicer(c, B['h'], B['l'], m, B['norm'])
    out = {'a': None, 'b': None}
    if len(PI) < 2:
        return out, (PT, PP, PI, PC)
    # (а): нога k — от пивота k (якорь A) до пивота k + 1; точка отсчёта — бар подтверждения PC[k]
    k = np.arange(len(PI) - 1)
    k = k[PC[k] >= 0]
    k = k[in_period(PC[k])]
    if len(k):
        A, tc = PI[k], PC[k]
        a = {'t': tc, 'A': A, 'S': np.abs(PP[k + 1] - PP[k]) / mw[A], 'speed': -np.log(np.maximum(tc - A, 1))}
        for name, col in cols.items():
            a[name], cov = run_mean(col, A, tc)
            if name == 'c':
                a['cover'] = cov
        out['a'] = a
    if with_events:
        n = len(c)
        t = np.flatnonzero(bar_e == np.arange(n))
        t = t[(bar_k[t] >= 0) & B['norm'][1][t]]
        kk = bar_k[t]
        keep = kk + 1 < len(PI)                                     # нога разрешилась в этой части
        t, kk = t[keep], kk[keep]
        keep = in_period(t)
        t, kk = t[keep], kk[keep]
        if len(t):
            A, d = PI[kk], -PT[kk]
            b = {'t': t, 'A': A, 'R': np.maximum(d * (PP[kk + 1] - c[t]) / mw[t], 0.0),
                 'speed': np.log(np.maximum(d * (c[t] - PP[kk]) / mw[A], 1e-9) / np.maximum(t - A, 1))}
            for name, col in cols.items():
                b[name], cov = run_mean(col, A, t)
                if name == 'c':
                    b['cover'] = cov
            out['b'] = b
    return out, (PT, PP, PI, PC)


def random_market(B, seed):
    """Случайный рынок: тот же ряд close, знак каждого шага close случаен (размеры шагов и их порядок — те же). Мерка порога —
       ATR настоящих баров в долях цены, перенесённый на уровень случайной цены (иначе порог в рублях настоящей цены мерил бы
       ходы случайной, ушедшей на другой уровень). Возвращает (close, нормировщик)."""
    rng = np.random.default_rng(seed)
    lr = np.nan_to_num(np.diff(np.log(B['c'])), nan=0.0, posinf=0.0, neginf=0.0)
    s = np.where(rng.random(len(lr)) < 0.5, -1.0, 1.0)
    cr = B['c'][0] * np.exp(np.r_[0.0, np.cumsum(s * np.abs(lr))])
    atr, live = B['norm']
    return cr, (atr * cr / B['c'], live)


