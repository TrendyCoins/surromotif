def synth_bars(seed, n, kind='rw', t0='2024-01-01 00:00:00', bar_ns=300 * 10 ** 9):
    """Синтетический ряд баров: 'rw' — случайное блуждание (шаг — σ = 0.002 со случайным знаком); 'regime' — режимы «тренд /
       тихо», меняются в среднем раз в 1 / switch баров: в «тренде» к шагу добавлен снос drift · σ за бар, знак сноса — свой у
       каждого эпизода. Возвращает (бары, режим на баре: +1 — тренд, −1 — тихо)."""
    rng = np.random.default_rng(seed)
    P = STAND
    sig = 0.002
    state = -np.ones(n)
    drift = np.zeros(n)
    if kind == 'regime':
        sw = rng.random(n) < P['switch']
        ep = np.cumsum(sw)                                     # номер эпизода
        st = np.where(ep % 2 == 0, -1.0, 1.0) * (1.0 if rng.random() < 0.5 else -1.0)
        sgn = np.where(rng.random(int(ep[-1]) + 1) < 0.5, -1.0, 1.0)[ep]
        state = st
        drift = np.where(st > 0, P['drift'] * sig * sgn, 0.0)
    eps = np.abs(rng.normal(0.0, sig, n))
    sg = np.where(rng.random(n) < 0.5, -1.0, 1.0)
    c = 100.0 * np.exp(np.cumsum(sg * eps + drift))
    o = np.r_[100.0, c[:-1]]
    h = np.maximum(o, c) * np.exp(np.abs(rng.normal(0, 0.0006, n)))
    l = np.minimum(o, c) * np.exp(-np.abs(rng.normal(0, 0.0006, n)))
    T = pd.Timestamp(t0).value + bar_ns * np.arange(n, dtype=np.int64)
    B = {'T': T, 'n_pre': 0, 'h': h, 'l': l, 'c': c}
    B['norm'] = normalizer(h, l, c)
    return B, state


def synth_color(rng, state, kind):
    """Цвет стенда: 'plus' — видит режим с шумом; 'null' — шум (с тем же сдвигом), режима не видит."""
    P = STAND
    noise = rng.normal(0.0, P['color_noise'], len(state))
    base = P['color_signal'] * state if kind == 'plus' else 0.0
    return np.clip(0.2 + base + noise, -1.0, 1.0).astype(np.float32)


