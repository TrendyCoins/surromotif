# СТАТИСТИКА: пятые части, бутстреп по неделям
# =====================================================================
def bin_shares(y, bins):
    """Доли y в интервалах: (до 1-й границы), [1-я; 2-я), …, (от последней)."""
    q = np.searchsorted(np.asarray(bins), y, side='right')
    return [float(np.mean(q == j)) for j in range(len(bins) + 1)]


def quint_stats(y, g, wk, cap, bins, rng, n_boot):
    """Пятые части по g: n, обрезанное среднее y (главная мера), доли y в интервалах; Q5 − Q1 по обрезанному среднему — с 95%
       интервалом бутстрепом по неделям (n_boot = 0 — без интервала)."""
    nq = LEGS['n_q']
    ok = np.isfinite(g) & np.isfinite(y)
    y, g, wk = y[ok], g[ok], wk[ok]
    if len(y) < 5 * nq:
        return None
    yc = np.minimum(y, cap)
    edges = np.quantile(g, np.linspace(0, 1, nq + 1)[1:-1])
    q = np.searchsorted(edges, g, side='right')
    rows = []
    for j in range(nq):
        sel = q == j
        rows.append({'q': j + 1, 'n': int(sel.sum()), 'g_lo': float(g[sel].min()) if sel.any() else math.nan,
                     'g_hi': float(g[sel].max()) if sel.any() else math.nan,
                     'mean_c': float(yc[sel].mean()) if sel.any() else math.nan,
                     'bins': bin_shares(y[sel], bins) if sel.any() else []})
    out = {'rows': rows, 'd': rows[-1]['mean_c'] - rows[0]['mean_c']}
    if n_boot:
        uw, wi = np.unique(wk, return_inverse=True)
        W = len(uw)
        cnt, sm = np.zeros((W, nq)), np.zeros((W, nq))
        np.add.at(cnt, (wi, q), 1.0)
        np.add.at(sm, (wi, q), yc)
        w = rng.multinomial(W, np.full(W, 1.0 / W), size=n_boot).astype(float)
        bc, bs = w @ cnt, w @ sm
        with np.errstate(invalid='ignore', divide='ignore'):
            dd = bs[:, -1] / bc[:, -1] - bs[:, 0] / bc[:, 0]
        out['ci'] = [float(np.nanpercentile(dd, 2.5)), float(np.nanpercentile(dd, 97.5))]
        out['se'] = float(np.nanstd(dd))
        out['weeks'] = W
    return out


def dist_stats(y, cap, bins):
    y = y[np.isfinite(y)]
    if not len(y):
        return {'n': 0}
    return {'n': int(len(y)), 'mean_c': float(np.minimum(y, cap).mean()), 'mean': float(y.mean()),
            'median': float(np.median(y)), 'bins': bin_shares(y, bins)}


def cell_stats(tab, kind, rand=None, seed=0):
    """Таблицы одной клетки (ТФ × масштаб × период): (а) или (б) — всё, распределение, пятые части по цвету, близнецу,
       скорости, сдвигам; у (а) — ещё случайный рынок."""
    if tab is None:
        return None
    y = tab['S'] if kind == 'a' else tab['R']
    cap, bins = LEGS['cap'][kind], LEGS['bins'][kind]
    ok = tab['cover'] >= LEGS['cover_min']
    wk = tab['T'] // WEEK_NS
    rng = np.random.default_rng(seed)
    out = {'all': dist_stats(y[ok], cap, bins)}
    for name in ('c', 'ct', 'speed'):
        out[name] = quint_stats(y[ok], tab[name][ok], wk[ok], cap, bins, rng, LEGS['n_boot'])
    out['shift'] = []
    for j in range(1, LEGS['n_shift'] + 1):
        r = quint_stats(y[ok], tab[f's{j}'][ok], wk[ok], cap, bins, rng, 0)
        out['shift'].append(None if r is None else r['d'])
    if rand is not None:
        out['rand'] = dist_stats(rand, cap, bins)
    return out


