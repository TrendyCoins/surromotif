def write_synth_research(dir_, asset, tf, t_tr0, t_va0, t_end, seed):
    """Синтетические файлы research ТФ (smc_series / smc_bars — те ключи, что читает load_bars)."""
    bar_ns, N = LEGS['bar_ns'][tf], LEGS['N']
    n_tr = int((pd.Timestamp(t_va0).value - pd.Timestamp(t_tr0).value) // bar_ns)
    n_va = int((pd.Timestamp(t_end).value - pd.Timestamp(t_va0).value) // bar_ns)
    B, _ = synth_bars(seed, N + n_tr + N + n_va, kind='regime', t0=t_tr0, bar_ns=bar_ns)
    ser, bars = {}, {}
    pos = 0
    for key, n_, t0_ in (('tr', n_tr, t_tr0), ('va', n_va, t_va0)):
        sl_pre, sl = slice(pos, pos + N), slice(pos + N, pos + N + n_)
        ser[f't_{key}'] = pd.Timestamp(t0_).value + bar_ns * np.arange(n_, dtype=np.int64)
        for k_ in ('h', 'l', 'c'):
            bars[f'{k_}_{key}'] = B[k_][sl]
            bars[f'pre_{k_}_{key}'] = B[k_][sl_pre]
        pos += N + n_
    os.makedirs(dir_, exist_ok=True)
    np.savez_compressed(os.path.join(dir_, f"smc_series_{asset}_{tf}_N{N}.npz"), **ser)
    np.savez_compressed(os.path.join(dir_, f"smc_bars_{asset}_{tf}_N{N}.npz"), **bars)
    return ser


