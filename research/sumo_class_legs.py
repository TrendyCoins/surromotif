def color_of(lm, ceil):
    """log M -> цвет бара: обрезка потолком и деление на его логарифм (NaN остаётся NaN)."""
    lc = math.log(ceil)
    return np.clip(np.asarray(lm, dtype=np.float64) / lc, -1.0, 1.0)


def windows_to_bars(T, n_pre, t_win, asset, label):
    """Индексы баров части (с pre-барами) для окон по времени их последнего бара; каждое окно обязано найтись."""
    Tb = T[n_pre:]
    idx = np.searchsorted(Tb, t_win)
    found = (idx < len(Tb)) & (Tb[np.minimum(idx, len(Tb) - 1)] == t_win)
    if not found.all():
        raise ValueError(f"🍆 АЙ, ОШИБКА! {asset} {label}: {int((~found).sum())} окон кэша Flow нет среди баров части — "
                         f"кэш и файлы research из разных выгрузок")
    return idx + n_pre


def source_colors(C, src, bars, tf):
    """Цвет на барах части у каждого ассета: реал и близнец (линия M по окнам кэша подряд, линейка — суррогаты sflip4
       источника, как у продукта). Возвращает ({ассет: {'c', 'ct'}}, модели)."""
    lg, tags = FL.src_logits(C, src)
    if not lg:
        return {}, []
    part = LEGS['periods'][src]
    code = 0 if part == 'tune' else 1
    q, zk = FL.ruler(np.concatenate([x['s4'] for x in lg.values()]))
    out = {}
    for a, x in lg.items():
        if a not in bars:
            continue
        B = bars[a][code]
        idx = windows_to_bars(B['T'], B['n_pre'], C['res'][a]['t'].astype(np.int64), a, f"{tf} {part}")
        col = np.full(len(B['T']), np.nan, dtype=np.float32)
        colt = np.full(len(B['T']), np.nan, dtype=np.float32)
        col[idx] = color_of(FL.line_m(FL.to_z(x['sp'], q, zk)), LEGS['ceiling'][tf])
        colt[idx] = color_of(FL.line_m(FL.to_z(x['s1'], q, zk)), LEGS['ceiling'][tf])
        out[a] = {'c': col, 'ct': colt}
    return out, tags


def shifted(col, j):
    """Цвет со сдвигом во времени: значения на барах с цветом сдвинуты по кругу на долю j / (n_shift + 1) их числа."""
    f = np.flatnonzero(np.isfinite(col))
    out = np.full(len(col), np.nan, dtype=np.float32)
    if len(f):
        out[f] = np.roll(col[f], int(round(len(f) * j / (LEGS['n_shift'] + 1))))
    return out


def run_mean(col, a, b):
    """Среднее col по барам [a, b] включительно (векторно) и доля баров с цветом."""
    v = np.asarray(col, dtype=np.float64)
    ok = np.isfinite(v)
    cs = np.r_[0.0, np.cumsum(np.where(ok, v, 0.0))]
    cn = np.r_[0, np.cumsum(ok)]
    n = cn[b + 1] - cn[a]
    return np.where(n > 0, (cs[b + 1] - cs[a]) / np.maximum(n, 1), np.nan), n / (b - a + 1)


