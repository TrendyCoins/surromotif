project_path = os.environ.get('SMC_PROJECT_PATH', '/content/drive/MyDrive/TrendyCoins/')
DATA_DIR = project_path + 'SMC/data_fresh/'
ASSETS = ['BTCUSDT', 'ETHUSDT']
TF, N = '5M', 200
PRICES = {'hl2': lambda h, l, c: (h + l) / 2.0,
          'hlc3': lambda h, l, c: (h + l + c) / 3.0}


def same_array(a, b):
    """Совпадение float32-рядов бит в бит, NaN на тех же местах."""
    if len(a) != len(b):
        return False
    na, nb = np.isnan(a), np.isnan(b)
    return bool(np.array_equal(na, nb) and np.array_equal(a[~na], b[~nb]))


def lag1(x):
    ok = np.isfinite(x[1:]) & np.isfinite(x[:-1])
    return float(np.corrcoef(x[1:][ok], x[:-1][ok])[0, 1])


def prepare(asset):
    t0 = time.time()
    series = DATA_DIR + f"smc_series_{asset}_{TF}_N{N}.npz"
    if not os.path.isfile(series):
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет {series} — сначала TrendyCoins_SMC_Data")
    d = np.load(series, allow_pickle=False)
    meta = json.loads(str(d['meta']))
    csv = project_path + "Raw Datasets/" + f"{asset}-{TF}.csv"
    df = pd.read_csv(csv, parse_dates=['timestamp'])
    high, low, close = (df[k].to_numpy(dtype=np.float64) for k in ('high', 'low', 'close'))
    date = df['timestamp']
    print(f"\n{'=' * 78}\n📈 {asset} {TF}: {os.path.basename(csv)} | {len(df)} баров | {date.iloc[0]} → "
          f"{date.iloc[-1]}\n{'=' * 78}")

    # ровно как make_parts в SMC_Data: нормировщик по всему файлу, пропуски сетки и мёртвый нормировщик -> NaN
    roll = pd.Series(high - low).rolling(N, closed='left').median().to_numpy()
    dt = date.diff().dt.total_seconds().to_numpy()
    step = float(np.nanmedian(dt[1:]))
    gap = np.zeros(len(df), dtype=bool)
    gap[1:] = dt[1:] > step * 1.5
    d_close = np.diff(close, prepend=close[0])
    d_close[0] = 0.0
    r = np.zeros_like(d_close)
    np.divide(d_close, roll, out=r, where=roll != 0)
    bad = ~np.isfinite(roll) | (roll <= 0) | ~np.isfinite(r) | gap
    r[bad] = np.nan
    r[0] = np.nan

    good_roll = np.isfinite(roll) & (roll > 0)
    prev_close = np.concatenate([[np.nan], close[:-1]])
    e_all, d_all = {}, {}
    for nm, f in PRICES.items():
        p = f(high, low, close)
        e = np.full(len(close), np.nan)
        np.divide(p - prev_close, roll, out=e, where=good_roll)
        e[bad] = np.nan                          # от прошлого close: через пропуск сетки — нет
        e[0] = np.nan
        dd = np.full(len(close), np.nan)
        np.divide(p - close, roll, out=dd, where=good_roll)
        e_all[nm], d_all[nm] = e, dd

    out, crc, stat = {}, {}, {}
    for name, key, a, b in (('TRAINING', 'tr', meta['training_start'], meta['validation_start']),
                            ('VALIDATION', 'va', meta['validation_start'], None)):
        i0 = int(np.where(date >= pd.Timestamp(a))[0][0])
        i1 = len(df) - 1 if b is None else int(np.where(date < pd.Timestamp(b))[0][-1])
        lo, hi = i0 + N, i1 + 1
        r_part = r[lo:hi].astype(np.float32)
        t_part = date.iloc[lo:hi].to_numpy().astype('datetime64[ns]').astype(np.int64)
        if not same_array(d[f'r_{key}'], r_part) or not np.array_equal(d[f't_{key}'], t_part):
            raise ValueError(f"🍆 АЙ, ОШИБКА! {asset} {name}: r из CSV не совпадает с smc_series — CSV или "
                             f"параметры менялись после SMC_Data. Верни тот CSV или пересчитай всё заново")
        crc[key] = zlib.crc32(d[f'r_{key}'].astype(np.float32).tobytes())
        line = []
        for nm in PRICES:
            e_p = e_all[nm][lo:hi].astype(np.float32)
            d_p = d_all[nm][lo:hi].astype(np.float32)
            d0 = np.float32(d_all[nm][lo - 1])
            out[f'e_{nm}_{key}'], out[f'd_{nm}_{key}'], out[f'd0_{nm}_{key}'] = e_p, d_p, np.array(d0)
            dp = e_p - np.concatenate([[d0], d_p[:-1]]).astype(np.float32)
            miss = int((np.isfinite(dp) != np.isfinite(r_part)).sum())
            stat[(nm, key)] = dp
            line.append(f"{nm}: приращения там же, где r {'✅' if miss == 0 else f'❗ расходятся на {miss} барах'}")
        print(f"   {name:<10} баров {hi - lo} | r совпадает с smc_series бит в бит ✅ | " + " | ".join(line))

    # насколько соседние приращения связаны по построению цены (у close — только рынок)
    r_tr = d['r_tr'].astype(np.float64)
    print("   lag-1 корреляция приращений (TRAINING): " + " | ".join(
        [f"close {lag1(r_tr):+.3f}"] + [f"{nm} {lag1(stat[(nm, 'tr')].astype(np.float64)):+.3f}" for nm in PRICES])
        + "\n   (у средних цен бара большая часть — арифметика усреднения, а не рынок: поэтому суррогат — зеркало бара)")

    out['meta'] = np.array(json.dumps({'asset': asset, 'tf': TF, 'N': N, 'prices': list(PRICES), 'ver': 2,
                                       'series': os.path.basename(series), 'crc': crc,
                                       'created': time.strftime('%Y-%m-%d %H:%M:%S')}, ensure_ascii=False))
    fn = DATA_DIR + f"smc_prices_{asset}_{TF}_N{N}.npz"
    np.savez_compressed(fn, **out)
    print(f"💾 {fn} ({os.path.getsize(fn) / 1e6:.1f} МБ) | {time.time() - t0:.0f} c")


for _a in ASSETS:
    prepare(_a)
