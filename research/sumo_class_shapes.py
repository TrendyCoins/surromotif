def sh_collect(smc, data, store, models, part):
    """Оценки и всё нужное по окнам части: ensemble-logit реала и суррогата, формы, знак ориентации, делитель, боковые входы."""
    ev = store.get(part, SH['null'])
    P = store.positives(part)
    sp_s = np.stack([smc.score(m, ev['Xp'], S=ev['Sp']) for m in models])
    sn_s = np.stack([smc.score(m, ev['Xn'], S=ev['Sn']) for m in models])
    W = P['W']
    W0 = W[:, 0] if W.dim() == 3 else W
    div = torch.maximum(smc.median_abs(W0), P['fl'])
    X, Xn = ev['Xp'], ev['Xn']
    X0 = X[:, 0] if X.dim() == 3 else X
    Xn0 = Xn[:, 0] if Xn.dim() == 3 else Xn
    if X.dim() == 3 and data.price in smc.LEVEL_KINDS:      # ширина бара в шагах окна (канал диапазона, бары 1…L−1)
        gw = X[:, smc.N_PATH, 1:].mean(1)
    else:
        gw = torch.full_like(div, float('nan'))
    out = {'sp_s': sp_s, 'sn_s': sn_s, 'st': np.asarray(P['st'], dtype=np.int64), 'wk': np.asarray(ev['wp']),
           'X0': X0.float().cpu().numpy(), 'Xn0': Xn0.float().cpu().numpy(),
           'g': smc.orient_sign(W, P['fl']).cpu().numpy(), 'div': div.double().cpu().numpy(),
           'Sp': ev['Sp'].float().cpu().numpy(), 'Sn': ev['Sn'].float().cpu().numpy(), 'gw': gw.float().cpu().numpy(),
           'part': np.full(len(sp_s[0]), part)}
    store._set.pop((part, SH['null']), None)              # память GPU: дальше всё на CPU
    store._pos.pop(part, None)
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
    return out


def sh_bars(smc, data):
    """Сырые OHLC (smc_bars) каждой части каждого ряда вместе с барами перед ней и нормировщик r: медиана (high − low) за
       200 баров до бара. Сверка: r · нормировщик = Δclose (так же, как в SeriesData._nt_arrays)."""
    tf_, N_ = data.tf, data.N
    rc = getattr(data, 'rc', data.r)
    out, err = {}, 0.0
    for i, s in enumerate(data.series):
        path = smc.data_path(f"smc_bars_{s['asset']}_{tf_}_N{N_}.npz")
        if not os.path.isfile(path):
            raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет {path} — сначала TrendyCoins_SMC_Bars")
        bx = np.load(path, allow_pickle=False)
        for code, key in ((0, 'tr'), (1, 'va')):
            ext = {k_: np.concatenate([bx[f'pre_{k_}_{key}'], bx[f'{k_}_{key}']]).astype(np.float64)
                   for k_ in ('o', 'h', 'l', 'c')}
            n_pre = len(bx[f'pre_c_{key}'])
            if n_pre < max(SH['hist'], smc.NT_HIST):
                raise ValueError(f"🍆 АЙ, ОШИБКА! {s['asset']}: баров перед частью {n_pre}, нужно {max(SH['hist'], smc.NT_HIST)}")
            rmed = pd.Series(ext['h'] - ext['l']).rolling(smc.NT_HIST, min_periods=smc.NT_HIST).median().shift(1).to_numpy()
            o, m = s['off'][key], s['n'][key]
            r_ = rc[o:o + m].astype(np.float64)
            dc = ext['c'][n_pre:] - ext['c'][n_pre - 1:-1]
            ok = np.isfinite(r_) & (np.abs(r_) > 0.05) & (dc != 0) & np.isfinite(rmed[n_pre:])
            if ok.any():
                err = max(err, float(np.max(np.abs(r_[ok] * rmed[n_pre:][ok] - dc[ok]) / np.abs(dc[ok]))))
            out[(i, code)] = {**ext, 'rmed': rmed, 'n_pre': n_pre, 'off': o}
    print(f"{'✅' if err < 1e-5 else '❌'} сырые бары: r · медиана диапазона за 200 баров = Δclose, max отн. ошибка {err:.1e}"
          + ("" if err < 1e-5 else " — бары не от того ряда: рисунки баров не читать"))
    return out


def sh_event_bars(data, bars, A, idx, H, L):
    """Бары событий (n, H + L, 4: O, H, L, C) в ориентированных шагах окна: (цена − close перед окном) / (нормировщик на
       начале окна · делитель окна), центр — среднее close окна; у перевёрнутого окна — зеркало всех баров (high <-> −low)."""
    out = np.empty((len(idx), H + L, 4))
    for j, i in enumerate(idx):
        s = int(A['st'][i])
        b = bars[(int(data.sid[s]), int(data.part[s]))]
        e0 = s - b['off'] + b['n_pre']
        sl = slice(e0 - H, e0 + L)
        lv = (np.stack([b['o'][sl], b['h'][sl], b['l'][sl], b['c'][sl]], 1) - b['c'][e0 - 1]) / (b['rmed'][e0] * A['div'][i])
        lv -= lv[H:, 3].mean()
        if A['g'][i] < 0:
            lv = -lv[:, [0, 2, 1, 3]]
        out[j] = lv
    return out


