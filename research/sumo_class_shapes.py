def sh_pick(order, st, gap, limit=None):
    """Жадно по порядку order: окно берётся, если ни одно взятое не начинается ближе gap баров (не больше limit событий).
       order — только кандидаты: у сторон — первые Q·n окон по lift, дальше список не идёт."""
    taken = np.zeros(int(st.max()) + gap + 2, dtype=bool)
    sel = []
    for i in order:
        s = int(st[i])
        if taken[max(0, s - gap + 1):s + gap].any():
            continue
        taken[s] = True
        sel.append(int(i))
        if limit is not None and len(sel) >= limit:
            break
    return np.array(sel, dtype=np.int64)


def sh_r2(X, ks, seed):
    """Доля разброса форм, которую объясняет разбиение k-means на k групп (1 − внутригрупповой / общий)."""
    tot = float(((X - X.mean(0)) ** 2).sum())
    return {k: 1.0 - KMeans(n_clusters=k, n_init=4, random_state=seed).fit(X).inertia_ / tot for k in ks}


def sh_rms(X, c, bs=65536):
    """Расстояние каждой строки X до формы c: корень из среднего квадрата разности (на точку окна)."""
    return np.concatenate([np.sqrt(((X[i:i + bs] - c) ** 2).mean(1)) for i in range(0, len(X), bs)])


def sh_cols(smc):
    """Номера столбцов боковых входов для текстуры и контекста."""
    t0 = smc.TOK_COL0
    vr = {k: t0 + 5 + j for j, k in enumerate(smc.TOK_VR_K)}
    return {'amp': t0, 'er': t0 + 1, 'ld': t0 + 2, 'z0': t0 + 4, 'vr2': vr[2], 'vr8': vr[8], 'vr32': vr[32],
            'R1': smc.NT_GROUP['R1'][0], 'V16': smc.NT_GROUP['V'][0], 'V64': smc.NT_GROUP['V'][1]}


TEX = (('амплитуда', 'amp', 'exp'), ('ER', 'er', 'mean'), ('VR2', 'vr2', 'exp'), ('VR8', 'vr8', 'exp'),
       ('VR32', 'vr32', 'exp'))
CTX = (('шаг/диапазон', 'ld', 'exp'), ('ширина бара', 'gw', 'mean'), ('нулевых шагов', 'z0', 'mean'),
       ('положение в 200', 'R1', 'mean'), ('вола 16/200', 'V16', 'exp'), ('вола 64/200', 'V64', 'exp'),
       ('ход 200 до окна', 'hmove', 'mean'))


def sh_stat(v, how):
    v = np.asarray(v, dtype=np.float64)
    v = v[np.isfinite(v)]
    if not len(v):
        return np.nan
    return float(np.exp(v.mean())) if how == 'exp' else float(v.mean())


def sh_groups(smc, A, ev, lv, cols, side, rng):
    """k-means на формах close-пути событий стороны; группы — по убыванию размера. Для каждой: средние бары, средняя форма,
       средняя форма суррогатов тех же окон, шар формы (частотный lift без модели), текстура и контекст, медоиды."""
    X = A['X0'][ev]
    km = KMeans(n_clusters=SH['k'], n_init=10, random_state=SH['seed']).fit(X)
    sizes = np.bincount(km.labels_, minlength=SH['k'])
    groups = []
    for rank, c_ in enumerate(np.argsort(-sizes)):
        m = np.where(km.labels_ == c_)[0]
        idx = ev[m]
        cen = X[m].mean(0)
        d_m = sh_rms(X[m], cen)
        rad = float(np.quantile(d_m, SH['ball_q']))
        fp = (sh_rms(A['X0'], cen) <= rad).astype(np.float64)
        fn = (sh_rms(A['Xn0'], cen) <= rad).astype(np.float64)
        ball = smc.lift_ci(fp, fn, A['wk'], A['wk'], seed=11 + rank)
        tex = {k: (sh_stat(A['Sp'][idx, cols[k]], how), sh_stat(A['Sn'][idx, cols[k]], how)) for _, k, how in TEX}
        ctx = {}
        for _, k, how in CTX:
            v = (A['gw'][idx] if k == 'gw' else lv[m, SH['hist'] - 1, 3] - lv[m, 0, 3] if k == 'hmove'
                 else A['Sp'][idx, cols[k]])
            ctx[k] = sh_stat(v, how)
        lg = A['lg_p'][idx]
        groups.append({'side': side, 'rank': rank, 'idx': idx, 'n': len(idx), 'share': len(idx) / len(ev),
                       'lift_gm': float(np.exp(lg.mean())), 'lift_min': float(np.exp(lg.min())),
                       'lift_max': float(np.exp(lg.max())), 'ball': ball, 'radius': rad,
                       'mean': lv[m].mean(0), 'centroid': cen, 'sur_mean': A['Xn0'][idx].mean(0),
                       'spag': X[rng.choice(len(m), size=min(SH['n_spag'], len(m)), replace=False)],
                       'medoids': idx[np.argsort(d_m)[:SH['n_med']]], 'medoid_bars': lv[m[np.argsort(d_m)[:SH['n_med']]]],
                       'tex': tex, 'ctx': ctx})
    return groups


