def sh_candles(ax, x, ohlc, color, width=0.62, alpha=1.0):
    """Свечи: фитиль low–high, тело open–close; рост — залитое тело, падение — пустое с контуром."""
    O, Hh, Lw, C = ohlc.T
    up = C >= O
    ax.vlines(x, Lw, Hh, color=color, lw=0.9, alpha=alpha, zorder=2)
    lo, hi = np.minimum(O, C), np.maximum(O, C)
    h = np.maximum(hi - lo, 2e-3 * max(float(np.max(Hh) - np.min(Lw)), 1e-9))
    ax.bar(x[up], h[up], bottom=lo[up], width=width, color=color, edgecolor=color, lw=0.6, alpha=alpha, zorder=3)
    ax.bar(x[~up], h[~up], bottom=lo[~up], width=width, color='#fcfcfb', edgecolor=color, lw=0.8, alpha=alpha, zorder=3)


def sh_ax(smc, ax):
    ax.set_facecolor('#fcfcfb')
    ax.tick_params(labelsize=7, colors=smc.C_INK2)
    for sp_ in ax.spines.values():
        sp_.set_color(smc.C_GRID)
    ax.axhline(0, color=smc.C_GRID, lw=0.7, zorder=1)


