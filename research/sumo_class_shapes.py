def sh_run(smc):
    import matplotlib.pyplot as plt
    t0 = time.time()
    L = SH['L']
    if SH['hist'] > smc.NT_HIST:
        raise ValueError(f"🍆 АЙ, ОШИБКА! SH['hist'] {SH['hist']} > {smc.NT_HIST} (столько баров перед частью в smc_bars)")
    print(f"\n{'#' * 100}\n# SMC SHAPES | {SH['model']} | сиды {','.join(SH['seeds'])} | части {' + '.join(SH['parts'])} | "
          f"q {SH['q']:g}, gap {SH['gap']}, k {SH['k']} | {smc.DEVICE}\n{'#' * 100}")
    models, runs = sh_models(smc)
    cfg = {**smc.SMC_BASE, **runs[0]['cfg'], 'name': SH['model']}
    old = sorted(set(smc.SIDE_COLS[cfg['side']] if cfg.get('side') else ()) & set(smc.NT_OLD_COLS))
    if old:
        print(f"⚠️ модель видит столбцы со временем {old} — это не модель без времени (SH['model'] = {SH['model']})")
    data = smc.load_data(cfg.get('price', 'close'))
    smc.check_absv(cfg, data)
    store = smc.EvalStore(data, L)

    # ---- оценки: ансамбль сидов; сверка сидов с json прогонов; калибровка ансамбля на TUNE
    parts = ['tune', 'val']                     # TUNE — калибровка, VAL — сверка с json прогонов
    C = {p_: sh_collect(smc, data, store, models, p_) for p_ in parts}
    for j, r in enumerate(runs):
        c_ = C['val']
        a_ = smc.auc_se(c_['sp_s'][j], c_['sn_s'][j], c_['wk'], c_['wk'])[0]
        ok = abs(a_ - r['val']['auc']) < 2e-4
        print(f"   {'✅' if ok else '❌'} сверка {r['tag']}: VAL AUC {a_:.4f}, в json {r['val']['auc']:.4f}"
              + ("" if ok else " — окна, суррогаты или модель не те, что при обучении: дальше не читать"))
    for p_ in parts:
        C[p_]['sp'], C[p_]['sn'] = C[p_]['sp_s'].mean(0), C[p_]['sn_s'].mean(0)
    a, b = smc.platt_fit(C['tune']['sp'], C['tune']['sn'])
    for p_ in parts:
        e_ = smc.auc_se(C[p_]['sp'], C[p_]['sn'], C[p_]['wk'], C[p_]['wk'])
        print(f"   ансамбль {len(models)} сидов, {p_.upper()}: AUC {e_[0]:.4f} ± {e_[1]:.4f} ({len(C[p_]['sp'])} окон)")
    print(f"   калибровка ансамбля на TUNE: log lift = {a:.3f} · logit {b:+.3f}")

    # ---- все окна выбранных частей вместе (по порядку времени)
    keys = ('sp', 'sn', 'st', 'wk', 'X0', 'Xn0', 'g', 'div', 'Sp', 'Sn', 'gw', 'part')
    A = {k: np.concatenate([C[p_][k] for p_ in SH['parts']]) for k in keys}
    del C
    A['lg_p'], A['lg_n'] = a * A['sp'] + b, a * A['sn'] + b
    n = len(A['lg_p'])
    n_cand = int(round(SH['q'] * n))
    order = {'top': np.argsort(-A['lg_p'], kind='stable'), 'bot': np.argsort(A['lg_p'], kind='stable')}
    thr = {s_: float(np.exp(A['lg_p'][o_[n_cand - 1]])) for s_, o_ in order.items()}
    ev = {s_: sh_pick(o_[:n_cand], A['st'], SH['gap']) for s_, o_ in order.items()}
    rng = np.random.default_rng(SH['seed'])
    ev['rnd'] = sh_pick(rng.permutation(n), A['st'], SH['gap'], max(len(ev['top']), len(ev['bot'])))
    print(f"\n📦 окон {n}; кандидатов с каждой стороны {n_cand} (верх: lift >= {thr['top']:.2f}, низ: <= {thr['bot']:.2f}); "
          f"событий без перекрытий: верх {len(ev['top'])}, низ {len(ev['bot'])}, случайных для сравнения {len(ev['rnd'])}")
    cov = [float(np.mean(A['lg_p'] >= math.log(v))) for v in (1.25, 2, 3)]
    print(f"   доля реальных окон с оценкой lift >= 1.25 / 2 / 3: {100 * cov[0]:.1f}% / {100 * cov[1]:.1f}% / {100 * cov[2]:.1f}%")

    # ---- бары событий и сверка осей с формой модели
    bars = sh_bars(smc, data)
    H = SH['hist']
    lv = {s_: sh_event_bars(data, bars, A, e_, H, L) for s_, e_ in ev.items()}
    cc = np.concatenate([[np.corrcoef(lv[s_][j, H:, 3], A['X0'][i])[0, 1] for j, i in enumerate(e_)]
                         for s_, e_ in ev.items()])
    ratio = np.concatenate([[lv[s_][j, H:, 3].std() / max(A['X0'][i].std(), 1e-12) for j, i in enumerate(e_)]
                            for s_, e_ in ev.items()])
    ok = np.median(cc) > 0.99 and (cc < 0).sum() == 0
    print(f"{'✅' if ok else '❌'} оси баров против формы модели X[:, 0]: корреляция close окна — медиана {np.median(cc):.4f}, "
          f"минимум {cc.min():.4f}, с обратным знаком {(cc < 0).sum()}; масштаб (sd бары / sd формы) — медиана "
          f"{np.median(ratio):.3f}, 5–95% {np.quantile(ratio, 0.05):.3f}–{np.quantile(ratio, 0.95):.3f}")

    # ---- похожи ли события друг на друга сильнее, чем случайные окна
    r2 = {s_: sh_r2(A['X0'][e_], SH['r2_k'], SH['seed']) for s_, e_ in ev.items()}
    print(f"\n📐 R² k-means по форме close-пути (доля разброса форм, которую объясняют k групп):")
    print(f"   {'':<17}" + "".join(f"{'k=' + str(k):>8}" for k in SH['r2_k']))
    for s_, nm in (('top', 'чаще случайного'), ('bot', 'реже случайного'), ('rnd', 'случайные окна')):
        print(f"   {nm:<17}" + "".join(f"{r2[s_][k]:>8.3f}" for k in SH['r2_k']))
    print("   выше, чем у случайных окон, — события действительно собираются в типы; так же — группы лишь нарезка "
          "непрерывного облака форм (средние всё равно честные, но «типа» за ними нет)")

    # ---- группы
    cols = sh_cols(smc)
    base = {'tex': {k: (sh_stat(A['Sp'][:, cols[k]], how), sh_stat(A['Sn'][:, cols[k]], how)) for _, k, how in TEX},
            'ctx': {k: sh_stat(A['gw'] if k == 'gw' else (lv['rnd'][:, H - 1, 3] - lv['rnd'][:, 0, 3]) if k == 'hmove'
                               else A['Sp'][:, cols[k]], how) for _, k, how in CTX}}
    rnd = {'mean': lv['rnd'].mean(0), 'centroid': A['X0'][ev['rnd']].mean(0)}
    groups = {}
    for side in ('top', 'bot'):
        groups[side] = sh_groups(smc, A, ev[side], lv[side], cols, side, rng)
        sh_print_side(side, groups[side], base, len(ev[side]), n_cand, thr[side])
    print("   «ход 200 до окна» — close перед окном минус close 200 баров назад, в шагах окна, по ориентации окна "
          "(плюс — история шла туда же, куда окно); «положение в 200» — положение close в диапазоне 200 баров, от −1 до +1, "
          "со знаком ориентации окна; «шаг/диапазон» — медиана |Δclose| окна в долях медианы диапазона бара")

    # ---- рисунки
    out = smc.RUN_DIR + f"shapes/{SH['model']}/"
    show = bool(getattr(smc, 'IN_COLAB', False))
    figs = [sh_fig_overview(smc, plt, A, thr, r2, {s_: v_.mean(0) for s_, v_ in lv.items()}, out + 'overview.png')]
    for side in ('top', 'bot'):
        figs.append(sh_fig_groups(smc, plt, side, groups[side], rnd, out + f'groups_{side}.png'))
        figs.append(sh_fig_examples(smc, plt, data, A, side, groups[side], out + f'examples_{side}.png'))
    for f_ in figs:
        if show:
            plt.show()
        plt.close(f_)
    print(f"\n🖼️ {out}: overview.png, groups_top.png, groups_bot.png, examples_top.png, examples_bot.png")

    # ---- сохранение: средние бары и формы групп, события
    arrs, summ = {'random_mean_ohlc': rnd['mean'], 'random_centroid': rnd['centroid'], 'platt': np.array([a, b])}, []
    for side in ('top', 'bot'):
        for G in groups[side]:
            p_ = f"{side}{G['rank'] + 1}_"
            arrs.update({p_ + 'mean_ohlc': G['mean'], p_ + 'centroid': G['centroid'], p_ + 'sur_mean': G['sur_mean'],
                         p_ + 'start': A['st'][G['idx']],
                         p_ + 't_end': data.t[A['st'][G['idx']] + L - 1].astype(np.int64),
                         p_ + 'lift': np.exp(A['lg_p'][G['idx']]), p_ + 'mirrored': A['g'][G['idx']] < 0})
            summ.append({'side': side, 'group': G['rank'] + 1, 'n': G['n'], 'share': G['share'],
                         'lift_gm': G['lift_gm'], 'lift_min': G['lift_min'], 'lift_max': G['lift_max'],
                         'ball': {'real': G['ball'][0], 'sur': G['ball'][1], 'lift': G['ball'][2], 'lo': G['ball'][3],
                                  'hi': G['ball'][4], 'radius': G['radius']},
                         'tex': G['tex'], 'ctx': G['ctx'],
                         'medoids': [str(pd.Timestamp(int(data.t[int(A['st'][i]) + L - 1]))) for i in G['medoids']]})
    np.savez_compressed(out + 'shapes.npz', **arrs)
    meta = {'settings': {k: (list(v) if isinstance(v, tuple) else v) for k, v in SH.items()},
            'runs': [r['tag'] for r in runs], 'platt': [a, b], 'n_windows': n, 'threshold': thr,
            'events': {s_: int(len(e_)) for s_, e_ in ev.items()}, 'r2': {s_: {str(k): v for k, v in d.items()}
                                                                         for s_, d in r2.items()},
            'base': base, 'groups': summ, 'when': time.strftime('%Y-%m-%d %H:%M:%S')}
    with open(out + 'shapes.json', 'w', encoding='utf-8') as fh:
        json.dump(smc._jsonable(meta), fh, ensure_ascii=False, indent=1)
    print(f"💾 {out}shapes.npz / shapes.json | {(time.time() - t0) / 60:.1f} мин")


