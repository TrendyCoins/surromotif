        xm_, sm_ = smc.mirror_inputs(x_, s_, model.trunk.n_level, model.trunk.lvl_signed)
        model.eval()
        with torch.no_grad():
            v1, v2 = model(x_, s_)[0], model(xm_, sm_)[0]
            m1, vb = model.both(x_, s_)
            m0 = model.trunk(x_, s_)[0]
