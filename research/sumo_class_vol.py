def n_weights_cfg_trunk(sd):
    """Весов ствола по его state_dict из прогона F1 (буферы масштабов — не веса)."""
    buf = ('s_sd', 'lvl_mu', 'lvl_sd', 'side_mu', 'side_sd', 'chan_mu', 'chan_sd')
    return int(sum(np.asarray(v).size for k, v in sd.items() if k not in buf))


def load_vol_model(r, ctx):
    """Сеть с двумя выходами из файла прогона головы (ствол — по json ствола, все веса — из npz прогона)."""
    t = r['vol']['trunk']
    r_f1, sd_f1, _ = f1_run(t['tag'], t['mode'])
    trunk, cfg_t = build_trunk(r_f1, sd_f1, ctx)
    with np.load(_paths(r['tag'])[1]) as z:
        sd = {k[3:]: torch.as_tensor(z[k]) for k in z.files if k.startswith('sd_')}
    h = r['vol']['head']
    model = VolHead(trunk, h['hidden'], h['dropout'], sd['f_mu'].to(DEVICE), sd['f_sd'].to(DEVICE), sd['f_on'].to(DEVICE),
                    layers=run_layers(r))
    model.load_state_dict(sd, strict=True)
    return model


