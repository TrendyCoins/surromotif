def check_layers(trunk, layers=None):
    """Слои головы: номера блоков свёрток ствола 1 … n по возрастанию, последний блок — последним (хвост признаков L4 — ровно вход
       головы MRI); None — J0, только последний блок (признаки — _feats ствола как есть). Кроме J0 — ствол без остаточных связей:
       выход блока — его карты, их снимают хуки."""
    nb = len(trunk.blocks)
    layers = (nb,) if layers is None else tuple(int(i) for i in layers)
    if not layers or list(layers) != sorted(set(layers)) or layers[0] < 1 or layers[-1] != nb:
        raise ValueError(f"🍆 АЙ, ОШИБКА! слои головы {layers}: номера блоков 1 … {nb} по возрастанию, последний — {nb}")
    if layers != (nb,) and getattr(trunk, 'res', False):
        raise ValueError("🍆 АЙ, ОШИБКА! у ствола остаточные связи — выход блока не равен его картам; голова на слоях — только без них")
    return layers


def block_pooled(trunk, x, s, layers):
    """Пулинг карт блоков layers ствола (как у ствола: trunk.pooled) за один проход conv_maps: хук на выходе блока сразу сворачивает
       его карты (окна, каналы, места) в (окна, 3 · каналы) — полные карты в памяти не копятся. Хуки ставятся и снимаются внутри
       try / finally: на стволе после вызова их не остаётся, даже если что-то упало."""
    got, hooks = {}, []

    def hook_of(i):
        def hook(m_, i_, o_):
            got[i] = trunk.pooled(o_)
        return hook
    try:
        for i in layers:
            hooks.append(trunk.blocks[i - 1].register_forward_hook(hook_of(i)))
        trunk.conv_maps(x, s)
    finally:
        for h_ in hooks:
            h_.remove()
    if sorted(got) != list(layers):
        raise RuntimeError(f"🍆 АЙ, ОШИБКА! хуки сняли блоки {sorted(got)}, ждали {list(layers)}")
    return [got[i] for i in layers]


def n_mri_in(trunk):
    """Входов головы MRI: пулинг последнего блока (3 · каналы у 'mml') + боковые входы — как считает CNNBase."""
    return {'mml': 3, 'mm': 2, 'last': 1}[trunk.pool] * trunk.ch + (len(trunk.side_cols) if trunk.side_cols else 0)


def head_feats(trunk, x, s, layers=None):
    """Вход головы V для одной стороны (окно или его зеркало). J0 (None или только последний блок) — _feats ствола как есть (вход
       головы MRI, бит в бит как в v1). Иначе — пулинг карт блоков layers по порядку, затем 17 боковых входов, стандартизованных
       буферами ствола (side_mu / side_sd): хвост — ровно _feats ствола."""
    layers = check_layers(trunk, layers)
    if layers == (len(trunk.blocks),):
        return trunk._feats(x, s)
    parts = block_pooled(trunk, x, s, layers)
    if trunk.side_cols:
        parts.append((s[:, list(trunk.side_cols)] - trunk.side_mu) / trunk.side_sd)
    return torch.cat(parts, dim=1)


class VolHead(nn.Module):
    """F1 с двумя выходами. Ствол F1 (свёртки, пулинг, боковые входы, голова MRI) — как есть и заморожен: mri(x, s) — logit F1
       бит в бит. Голова V — MLP на признаках ствола (вход — (f − f_mu) / f_sd · f_on), симметричная: v = (h(f(x)) +
       h(f(зеркало x))) / 2. layers — какие блоки свёрток она читает: (4,) — J0, те же 209 признаков, что у головы MRI; (1, 2, 3, 4) —
       L4, пулинг всех четырёх блоков + 17 боковых; None — J0 (последний блок). forward отдаёт v (стандартизованный таргет) — так
       сеть зовёт код SuMo_Pred_Train."""
    def __init__(self, trunk, hidden, dropout, f_mu, f_sd, f_on, layers=None):
        super().__init__()
        if not getattr(trunk, 'sym', False) or getattr(trunk, 'anti', None):
            raise ValueError("🍆 АЙ, ОШИБКА! ствол — зеркально-симметричная F1 без антисимметричной головы")
        self.layers = check_layers(trunk, layers)
        self.trunk = trunk
        for p in self.trunk.parameters():
            p.requires_grad_(False)
        self.sym = True                        # для кода SuMo_Pred_Train: «зеркально-симметричная сеть»
        self.side_cols = trunk.side_cols       # сети нужны боковые входы (uses_side)
        self.needs_s = getattr(trunk, 'needs_s', False)
        self.head_v = smc.mlp(int(f_mu.numel()), tuple(hidden), dropout).to(f_mu.device)
        self.register_buffer('f_mu', f_mu.clone())
        self.register_buffer('f_sd', f_sd.clone())
        self.register_buffer('f_on', f_on.clone())
        self.trunk.eval()

    def train(self, mode=True):
        """Ствол всегда без dropout: его признаки — те же, что у MRI на сайте; dropout — только в голове V."""
        super().train(mode)
        self.trunk.eval()
        return self

    @torch.no_grad()
    def feats(self, x, s=None):
        """Вход головы V у окна и у его зеркала (у J0 — вход головы MRI)."""
        xm, sm = smc.mirror_inputs(x, s, self.trunk.n_level, self.trunk.lvl_signed)
        return head_feats(self.trunk, x, s, self.layers), head_feats(self.trunk, xm, sm, self.layers)

    def vol_of(self, f):
        return self.head_v((f - self.f_mu) / self.f_sd * self.f_on).squeeze(1)

    def forward(self, x, s=None):
        f, fm = self.feats(x, s)
        return 0.5 * (self.vol_of(f) + self.vol_of(fm)), None, None, None

    @torch.no_grad()
    def mri(self, x, s=None):
        """logit MRI — ствол F1 как есть."""
        return self.trunk(x, s)[0]

    @torch.no_grad()
    def both(self, x, s=None):
        """Оба выхода за один проход ствола: (logit MRI, v). logit — те же операции, что у F1 (бит в бит): голова MRI на хвосте
           признаков (у L4 хвост — пулинг последнего блока и боковые входы, ровно _feats ствола; копия — сплошная, как у ствола)."""
        f, fm = self.feats(x, s)
        n = n_mri_in(self.trunk)
        ft, fmt = f[:, -n:].contiguous(), fm[:, -n:].contiguous()
        mri = 0.5 * (self.trunk.head(ft).squeeze(1) + self.trunk.head(fmt).squeeze(1))
        return mri, 0.5 * (self.vol_of(f) + self.vol_of(fm))


def _trunk_feats(trunk, X, S, chunk=16384, layers=None):
    """Вход головы V кусками: по куску — (f окна, f зеркала)."""
    for i in range(0, len(X), chunk):
        x, s = X[i:i + chunk], (None if S is None else S[i:i + chunk])
        xm, sm = smc.mirror_inputs(x, s, trunk.n_level, trunk.lvl_signed)
        yield head_feats(trunk, x, s, layers), head_feats(trunk, xm, sm, layers)


@torch.no_grad()
def feat_stats(trunk, X, S, layers=None):
    """Стандартизация входа головы V по окнам пробы и их зеркалам: f_mu, f_sd, f_on. Признак, постоянный на пробе (мёртвый
       канал ReLU), выключен (f_on = 0): веса головы к нему не учатся, а вне выборки он дал бы шум. У живых sd — не меньше
       RULES['sd_floor_rel'] × медиана sd живых: редкий канал не раздувается делением на почти ноль. В info — сколько выключено и
       подрезано и max |z| на пробе. layers — вход головы (None — J0, как в v1)."""
    trunk.eval()
    s1, s2, n = None, None, 0
    for pair in _trunk_feats(trunk, X, S, layers=layers):
        for f in pair:
            f = f.double()
            s1 = f.sum(0) if s1 is None else s1 + f.sum(0)
            s2 = (f * f).sum(0) if s2 is None else s2 + (f * f).sum(0)
            n += len(f)
    mu = s1 / n
    sd = torch.sqrt(torch.clamp(s2 / n - mu * mu, min=0.0))
    on = sd > 1e-6
    floor = RULES['sd_floor_rel'] * float(sd[on].median()) if bool(on.any()) else 1.0
    sd_f = torch.where(on, torch.clamp(sd, min=floor), torch.ones_like(sd))
    zmax = 0.0
    for pair in _trunk_feats(trunk, X, S, layers=layers):
        for f in pair:
            z = (f.double() - mu) / sd_f
            if bool(on.any()):
                zmax = max(zmax, float(z[:, on].abs().max()))
    info = {'dead': int((~on).sum()), 'floored': int((on & (sd < floor)).sum()), 'floor': floor, 'zmax': zmax}
    return mu.float(), sd_f.float(), on.float(), info


def n_weights(m):
    return int(sum(p.numel() for p in m.parameters()))


def trunk_sha(sd):
    """sha256 весов ствола: имена и float32-байты (little-endian) тензоров state_dict по порядку имён (буферы — тоже)."""
    h = hashlib.sha256()
    for k in sorted(sd):
        h.update(k.encode('utf-8'))
        h.update(np.ascontiguousarray(np.asarray(sd[k], dtype='<f4')).tobytes())
    return h.hexdigest()


def sd_numpy(module):
    return {k: v.detach().cpu().numpy() for k, v in module.state_dict().items()}


def file_sha(path):
    """sha256 файла кода (первые 16 знаков) — паспорт прогона; None — файла нет (код из ячейки Colab)."""
    if not path:
        return None
    try:
        with open(path, 'rb') as fh:
            return hashlib.sha256(fh.read()).hexdigest()[:16]
    except OSError:
        return None


def _f4(x):
    try:
        return f"{float(x):.4f}"
    except (TypeError, ValueError):
        return '—'


