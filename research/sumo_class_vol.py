def f1_run(tag, mode):
    """json, веса (sd_*) и logit окон (…__sp, …__st) прогона F1 из RUN_DIR/pool/ ('stop') или RUN_DIR/prod/ ('prod')."""
    d = smc._pool_dir(mode)
    pj, pz = d + f"{tag}.json", d + f"{tag}.npz"
    if not (os.path.isfile(pj) and os.path.isfile(pz)):
        raise FileNotFoundError(f"🍆 АЙ, ОШИБКА! нет прогона F1 {pj} / .npz — ствол головы V берётся оттуда")
    with open(pj, encoding='utf-8') as fh:
        r = json.load(fh)
    if r.get('ver') != smc.POOL_VER or r.get('model') != MODEL or r.get('mode') != mode:
        raise ValueError(f"🍆 АЙ, ОШИБКА! {tag}: ver {r.get('ver')}, модель {r.get('model')}, режим {r.get('mode')} — ждали "
                         f"ver {smc.POOL_VER}, {MODEL}, '{mode}'")
    with np.load(pz) as z:
        sd = {k[3:]: z[k] for k in z.files if k.startswith('sd_')}
        arrs = {k: z[k] for k in z.files if k.endswith('__sp') or k.endswith('__st')}
    if not sd:
        raise ValueError(f"🍆 АЙ, ОШИБКА! в {pz} нет весов (sd_*)")
    return r, sd, arrs


def trunk_sample(ctx, n=2000):
    """Окна для постройки ствола (масштабы потом перезаписываются весами прогона): первые n окон FIT."""
    data = ctx['data']
    w = data.windows(L)
    idx = w['fit'][:n]
    st = torch.from_numpy(w['st'][idx]).to(DEVICE)
    fl = w['floor_t'][torch.from_numpy(w['sid'][idx]).to(DEVICE)]
    W = data.gw(st, L)
    return smc.to_shapes(W, fl), smc.side_feats(data, st, L, W, fl)


def build_trunk(r, sd, ctx):
    """F1 по конфигурации прогона (json) и его веса — строго (имена и формы всех тензоров)."""
    cfg = {**smc.make_cfg(MODEL, {'L': L}, r['seed_key']), **{k: v for k, v in r['cfg'].items() if k != 'dict'}}
    X, S = trunk_sample(ctx)
    trunk, _ = smc.build_model(cfg, X, np.random.default_rng(0), S)
    trunk.load_state_dict({k: torch.as_tensor(np.asarray(v)) for k, v in sd.items()}, strict=True)
    trunk.eval()
    return trunk, cfg


def mri_check(ctx, trunk, arrs, assets, refs=()):
    """(J-a): logit ствола на окнах TUNE / VAL ассетов (окна с годным таргетом — на них сравниваются прогнозы V) против logit,
       записанных прогоном F1 на тех же окнах (по началу окна). Каждая часть каждого ассета обязана сравниться хотя бы на одном
       окне. refs — [(имя, прогон)]: заодно (до обучения) — совпадут ли окна и факт головы с окнами прогонов, с которыми её потом
       сравнят парно (начала окон и таргет float32 — бит в бит, как в cross_delta). Возвращает (прошло, {ассет/часть: n, miss,
       max, mean, pairs})."""
    A = pred.pred_arrays(ctx['data'], TARGET)
    out, ok = {}, True
    for a in assets:
        for part in ('tune', 'val'):
            k_ = f"{a}__{part}__"
            if k_ + 'sp' not in arrs or k_ + 'st' not in arrs:
                out[f"{a}/{part}"] = {'n': 0, 'note': 'нет в прогоне F1'}
                ok = False
                continue
            e_ = pred.eval_windows(ctx, A, a, part)
            if e_ is None:
                out[f"{a}/{part}"] = {'n': 0, 'note': 'нет окон с таргетом'}
                ok = False
                continue
            z = smc.score(trunk, e_['X'], S=e_['S'])
            st1, sp1 = np.asarray(arrs[k_ + 'st']), np.asarray(arrs[k_ + 'sp'], np.float64)
            o = np.argsort(st1, kind='stable')
            sts = st1[o]
            i = np.searchsorted(sts, e_['st'])
            hit = i < len(sts)
            hit[hit] = sts[i[hit]] == e_['st'][hit]
            d = np.abs(z[hit] - sp1[o[i[hit]]])
            row = {'n': int(hit.sum()), 'miss': int((~hit).sum()),
                   'max': float(d.max()) if d.size else float('nan'), 'mean': float(d.mean()) if d.size else float('nan'),
                   'pairs': {}}
            for nm, rr in refs:
                x = pred.run_arr(rr)
                row['pairs'][nm] = bool(k_ + 'st' in x and k_ + 'y' in x and np.array_equal(x[k_ + 'st'], e_['st'])
                                        and np.array_equal(x[k_ + 'y'], e_['y'].astype(np.float32)))
            out[f"{a}/{part}"] = row
            ok = ok and row['n'] > 0 and row['max'] <= RULES['mri_tol']
            del e_
    return bool(ok and out), out


@contextlib.contextmanager
def head_on(trunk, hidden, dropout, made, layers=None):
    """На время прогона run_pred строит не новую сеть, а VolHead: ствол trunk (заморожен) + новая голова V, читающая блоки
       свёрток layers (None — J0, как в v1; (1, 2, 3, 4) — L4). run_pred зовёт smc.build_model — здесь она подменена фабрикой и в
       finally возвращается. Всё остальное (окна, таргет, расписание, оценки, базы HAR) — тот же код, что у P3. made — что построила
       фабрика (для проверки после прогона)."""
    orig = smc.build_model
    layers = check_layers(trunk, layers)

    def factory(cfg, Xs, gen_np, Ss=None):
        if made.get('model') is not None:
            raise RuntimeError("🍆 АЙ, ОШИБКА! фабрика головы V вызвана второй раз за прогон")
        f_mu, f_sd, f_on, info = feat_stats(trunk, Xs, Ss, layers=layers)
        model = VolHead(trunk, hidden, dropout, f_mu, f_sd, f_on, layers=layers)
        made.update({'model': model, 'n_head': n_weights(model.head_v), 'n_trunk': n_weights(trunk), 'n_feat': int(f_mu.numel()),
                     'n_sample': int(len(Xs)), 'layers': list(layers), **info})
        print(f"🧊 ствол F1 заморожен ({made['n_trunk']} весов не учатся, без dropout); учится голова V: {made['n_head']} весов, "
              f"вход {made['n_feat']} признаков (блоки свёрток {', '.join(map(str, layers))} + боковые) — стандартизованы по "
              f"{len(Xs)} окнам обучения и их зеркалам: выключено постоянных {info['dead']}, sd поднят до пола {info['floor']:.3g} "
              f"(0.1 медианы) у {info['floored']}; max |z| на пробе {info['zmax']:.1f}")
        return model, {}

    smc.build_model = factory
    try:
        yield
    finally:
        smc.build_model = orig


