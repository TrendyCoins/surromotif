def _paths(tag):
    return pred.pred_dir() + f"{tag}.json", pred.pred_dir() + f"{tag}.npz"


def run_layers(r):
    """Какие блоки свёрток читает голова прогона (у прогонов v1 ключа нет — J0)."""
    ly = ((r.get('vol') or {}).get('head') or {}).get('layers')
    return HEADS['j0']['layers'] if ly is None else tuple(int(i) for i in ly)


def head_fp(recipe):
    """Отпечаток определения головы рецепта recipe: слои, пулинг, рецепт (sub, over, fixed, parts, набор), пол sd входа, формат
       прогона. Прогон с другим отпечатком (другое определение головы или рецепта) в сводку не идёт и считается непосчитанным."""
    rc = RECIPES[recipe]
    d = {'layers': list(HEADS[HEAD_OF[recipe]]['layers']), 'pool': 'mml', 'sub': rc['sub'], 'over': rc['over'],
         'fixed': bool(rc.get('fixed', False)), 'parts': rc.get('parts', 'fit'), 'set': rc.get('set', SET),
         'sd_floor_rel': RULES['sd_floor_rel'], 'run_ver': RUN_VER}
    return hashlib.sha256(json.dumps(d, sort_keys=True).encode('utf-8')).hexdigest()[:16]


def _vol_ok(r, head=None):
    """Прогон головы этой версии формата (RUN_VER); head — и голова та же (слои — как у HEADS[head]). Отпечаток определения
       (head_fp) обязан совпасть, если он записан; без отпечатка (прогоны v1) годится только J0."""
    v = r.get('vol') or {}
    if v.get('ver') != RUN_VER or (head is not None and run_layers(r) != HEADS[head]['layers']):
        return False
    fp = (v.get('head') or {}).get('fp')
    if fp is None:
        return run_layers(r) == HEADS['j0']['layers']
    return r.get('recipe') in RECIPES and fp == head_fp(r['recipe'])


def _done(tag, head='j0'):
    pj, pz = _paths(tag)
    if not (os.path.isfile(pj) and os.path.isfile(pz)):
        return False
    with open(pj, encoding='utf-8') as fh:
        r = json.load(fh)
    return r.get('ver') == pred.PRED_VER and _vol_ok(r, head)


def _quarantine(tag):
    """Прогон с нарушенной проверкой — в *.bad (в сводку не попадёт, при перезапуске считается заново)."""
    for p in _paths(tag):
        if os.path.isfile(p):
            os.replace(p, p + '.bad')


def after_run(res, made, sha_f1):
    """Проверки после run_pred: подмена сработала (в прогоне вся сеть: ствол + голова V), ствол в прогоне — бит в бит ствол F1.
       Нарушено — прогон в *.bad и ошибка."""
    tag = res.get('tag', '?')
    model = made.get('model')
    n_exp = None if model is None else n_weights(model)
    if model is None or res.get('n_params') != n_exp:
        _quarantine(tag)
        raise RuntimeError(f"🍆 АЙ, ОШИБКА! {tag}: подмена сети не сработала — run_pred построил свою сеть (весов "
                           f"{res.get('n_params')}, ждали {n_exp}; код SuMo_Pred_Train изменился?) — прогон отложен в *.bad")
    with np.load(_paths(tag)[1]) as z:
        sd_t = {k[len('sd_trunk.'):]: z[k] for k in z.files if k.startswith('sd_trunk.')}
        n_head = sum(int(z[k].size) for k in z.files if k.startswith('sd_head_v.'))
    sha_run = trunk_sha(sd_t) if sd_t else None
    if sha_run != sha_f1 or n_head != made['n_head']:
        _quarantine(tag)
        raise RuntimeError(f"🍆 АЙ, ОШИБКА! {tag}: ствол в прогоне не тот, что у F1 (sha {str(sha_run)[:12]} против "
                           f"{sha_f1[:12]}) или нет головы V — прогон отложен в *.bad")
    return sha_run


def run_vol(ctx, seed, trunk_tag, trunk_mode, recipe, over, sub, fixed, parts, head='j0'):
    """Один прогон головы V (head — 'j0' / 'l4'): ствол — прогон F1 trunk_tag (режим trunk_mode), голова учится кодом run_pred
       (рецепт recipe)."""
    t0 = time.time()
    hd = HEADS[head]
    r_f1, sd_f1, arrs_f1 = f1_run(trunk_tag, trunk_mode)
    sha_f1 = trunk_sha(sd_f1)
