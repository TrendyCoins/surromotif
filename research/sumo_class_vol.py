def ni_ok(d, se):
    """(J-c) не хуже: нижняя граница Δ − ni_k · SE не ниже −ni_margin."""
    return bool(np.isfinite(d) and np.isfinite(se) and d - RULES['ni_k'] * se >= -RULES['ni_margin'])


def _pair_delta(new, ref, assets, part):
    """ΔR² (голова − P3) по парам сидов: среднее и SE (seed_combine); пары, у которых окна не совпали, — мимо (с ⚠️)."""
    ds, ses = [], []
    for s, r in new.items():
        if s in ref:
            d = pred.cross_delta(r, ref[s], assets, part)
            if d is not None:
                ds.append(d[0])
                ses.append(d[1])
    return pred.seed_combine(ds, ses)


def line_r(rs, assets, key='cnn'):
    """R линии на VAL: RMS шага прогноза между соседними окнами / sd прогноза — среднее по ассетам и прогонам."""
    if not rs:
        return float('nan')
    return float(np.nanmean([np.nanmean([pred.line_R(pred.run_arr(r), a, 'val', key) for a in assets]) for r in rs]))


def head_runs(runs, head):
    """Прогоны экзамена головы head (рецепт = имя головы, набор SET) по сидам — только с её определением (_vol_ok) и на стволе
       F1 'stop' своего сида."""
    return {r['seed_key']: r for r in pred.pick(runs, 'pool', MODEL, target=TARGET, set_name=SET, recipe=head)
            if _vol_ok(r, head) and r['vol']['trunk'].get('tag') == smc._pool_tag(SET, r['seed_key'], MODEL, 'stop')}


def head_eval(runs, head='j0'):
    """Вердикт головы head (правила (J-a)–(J-c); (J-d) — флаг) по прогонам сидов SEEDS; None — прогонов головы нет. accept None —
       вердикта нет (why). У головы L4 — справочно L4 − J0 по парам сидов (если J0 посчитан)."""
    new_all = head_runs(runs, head)
    if not new_all:
        return None
    new = {s: r for s, r in new_all.items() if s in SEEDS} or new_all
    p3_all = {r['seed_key']: r for r in pred.pick(runs, 'pool', MODEL, target=TARGET, set_name=SET, recipe='p3')}
    p3 = {s: r for s, r in p3_all.items() if s in new}
    rs, ps = [new[s] for s in sorted(new)], [p3[s] for s in sorted(p3)]
    panel = rs[0]['panel']
    miss = [s for s in SEEDS if s not in new or s not in p3]
    ok_a = all(r['vol'].get('mri_ok') and r['vol'].get('trunk_same') for r in rs)
    dt = pred.seeds_delta(rs, panel, 'tune', 'cnn', 'har')
    dv = pred.seeds_delta(rs, panel, 'val', 'cnn', 'har')
    ok_b = pred.verdict(dt[0], dt[1], dv[0], RULES['se_k'])
    ok_b = bool(ok_b and dv[0] >= RULES['min_gain'])
    dd = {part: _pair_delta(new, p3, panel, part) for part in ('tune', 'val')}
    ok_c = ni_ok(dd['val'][0], dd['val'][1])
    better = bool(np.isfinite(dd['val'][0]) and dd['val'][0] >= RULES['better_k'] * dd['val'][1])
    r_head, r_p3 = line_r(rs, panel), line_r(ps, panel)
    ok_d = bool(np.isfinite(r_head) and np.isfinite(r_p3) and r_head <= RULES['r_ratio'] * r_p3)
    pairs = {'tune_har': dt[2], 'val_har': dv[2], 'tune_p3': dd['tune'][2], 'val_p3': dd['val'][2]}
    if miss:
        accept, why = None, f"не все сиды (нет {', '.join(miss)})"
    elif any(n_ != len(SEEDS) for n_ in pairs.values()):
        accept, why = None, ("не все пары сравнились (" + ", ".join(f"{k_} {n_}" for k_, n_ in pairs.items())
                             + f" из {len(SEEDS)}): окна головы, P3 и HAR не совпали — данные или подвыборка окон поменялись "
                               "после P3; разобраться")
    else:
        accept, why = bool(ok_a and ok_b and ok_c), ""
    best = {s: int(r['best_ep']) for s, r in new.items()}
    k_prod = int(round(float(np.mean([b + 1 for b in best.values()]))))
    j0ref, dj = {}, None
    if head != 'j0':                             # справочно: эта голова − J0 по парам сидов (тот же ствол, те же окна)
        j0ref = {s: r for s, r in head_runs(runs, 'j0').items()
                 if s in new and r['vol']['trunk'].get('sha256') == new[s]['vol']['trunk'].get('sha256')}
        if j0ref:
            dj = {part: _pair_delta(new, j0ref, panel, part) for part in ('tune', 'val')}
    return {'head': head, 'runs': new, 'p3': p3, 'j0ref': j0ref, 'panel': panel, 'missing': miss, 'pairs': pairs, 'why': why,
            'ok_a': ok_a, 'd_tune_har': dt, 'd_val_har': dv, 'ok_b': ok_b, 'd_tune_p3': dd['tune'], 'd_val_p3': dd['val'],
            'lower_val': dd['val'][0] - RULES['ni_k'] * dd['val'][1], 'ok_c': ok_c, 'better': better,
            'd_tune_j0': dj['tune'] if dj else None, 'd_val_j0': dj['val'] if dj else None,
            'r_head': r_head, 'r_p3': r_p3, 'ok_d': ok_d, 'accept': accept, 'best_ep': best, 'k_prod': k_prod,
            'best_epochs': {s: r['best_step'] / r['steps_per_epoch'] for s, r in new.items()}}


