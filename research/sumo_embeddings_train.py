def shapes(W, fl, orient=True):
    """Форма окна ret_med (как у классификатора). orient=False — без переворота по знаку конца пути: ствол видит
       направление окна (вариант A_unor)."""
    if orient:
        return smc.to_shapes(W, fl)
    out = []
    for i in range(0, len(W), 262144):
        w, f = W[i:i + 262144], fl[i:i + 262144]
        lv = None
        if w.dim() == 3 and w.shape[1] > smc.N_PATH:
            w, lv = w[:, :smc.N_PATH], w[:, smc.N_PATH:]
        w0 = w[:, 0] if w.dim() == 3 else w
        div = torch.maximum(smc.median_abs(w0), f)
        X = torch.cumsum(w, dim=-1)
        X = X - X.mean(dim=-1, keepdim=True)
        dv = div[:, None, None] if w.dim() == 3 else div[:, None]
        out.append(X / dv if lv is None else torch.cat([X / dv, lv / dv], dim=1))
    return torch.cat(out) if len(out) > 1 else out[0]


def side_for(cols, data, st_t, W, fl):
    """Боковые входы окон, тензор (n, 90) как у side_feats. Модели нужен только знаменатель окна — быстрый путь (те же
       формулы, что в side_feats / tok_feats; сверка бит в бит — в 'check'), остальные столбцы — нули."""
    if not cols:
        return None
    if set(cols) <= set(DEN):
        W0 = W[:, 0] if W.dim() == 3 else W
        S = torch.zeros(len(W0), NCOL, device=W0.device, dtype=W0.dtype)
        S[:, DEN[0]] = torch.log(torch.maximum(smc.median_abs(W0), fl))
        S[:, DEN[1]] = torch.log(torch.maximum(W0.abs().mean(dim=1), fl))
        return S
    return smc.side_feats(data, st_t, L, W, fl)


def parse_null(spec):
    """'sflip4' -> ('sflip', 4); 'iid' -> ('iid', 0); 'rev' -> ('rev', 0)."""
    if spec.startswith('sflip'):
        return 'sflip', int(spec[5:] or 1)
    if spec in ('iid', 'rev'):
        return spec, 0
    raise ValueError(f"🍆 АЙ, ОШИБКА! нулевая '{spec}' — есть sflip<b>, iid, rev")


class IidPool:
    """Бары для iid-нулевой: все каналы конечны, у бара известен его собственный сдвиг d средней цены от close
       (хранится на следующей позиции той же части: chan_d[i] = d_{i−1}). Пулы — по ассету и части (fit / tune / val)."""
    def __init__(self, data):
        self.data = data
        n = len(data.r)
        same_next = np.zeros(n, bool)
        same_next[:-1] = (data.part[1:] == data.part[:-1]) & (data.sid[1:] == data.sid[:-1]) & (data.part[:-1] >= 0)
        ok = np.isfinite(data.r) & same_next
        self.d_own = []
        for e_, d_ in zip(data.chan_e, data.chan_d):
            d_own = np.full(n, np.nan, np.float32)
            d_own[:-1] = d_[1:]
            ok &= np.isfinite(e_) & np.isfinite(d_own)
            self.d_own.append(torch.from_numpy(d_own).to(DEVICE))
        if hasattr(data, 'chan_g'):
            ok &= np.isfinite(data.chan_g)
        if hasattr(data, 'chan_o'):
            ok &= np.isfinite(data.chan_o)
        part_of = {'fit': (data.part == 0) & (data.t < data.tune_ns), 'tune': (data.part == 0) & (data.t >= data.tune_ns),
                   'val': data.part == 1}
        self.pool = {}
        for i in range(len(data.series)):
            for nm, m in part_of.items():
                self.pool[(i, nm)] = torch.from_numpy(np.where(ok & m & (data.sid == i))[0]).to(DEVICE)

    def windows(self, sid_t, part, gen):
        """Окна (n, каналы, L) из случайных баров своего ассета и части. Бар t суррогата — реальный бар j_t целиком:
           шаг close r[j_t], шаг средней цены e[j_t] − d[j_{t−1}] (средняя цена бара от close прошлого бара суррогата),
           диапазон и положение close — бара j_t."""
        d = self.data
        J = torch.empty(len(sid_t), L + 1, dtype=torch.long, device=DEVICE)
        for i in torch.unique(sid_t).tolist():
            rows = torch.where(sid_t == i)[0]
            pool = self.pool[(int(i), part)]
            pick = torch.randint(0, len(pool), (len(rows), L + 1), generator=gen, device=gen.device).to(DEVICE)
            J[rows] = pool[pick]
        cur, prv = J[:, 1:], J[:, :-1]
        chans = [d.r_t[cur]]
        for (e_, _), dn in zip(d.chan_t, self.d_own):
            chans.append(e_[cur] - dn[prv])
        if hasattr(d, 'chan_g_t'):
            chans.append(d.chan_g_t[cur])
        if hasattr(d, 'chan_o_t'):
            chans.append(d.chan_o_t[cur])
        return torch.stack(chans, dim=1)


