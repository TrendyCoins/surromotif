def sample_starts(data):
    """Фиксированный образец окон VAL (одни и те же у всех прогонов: окна у 'multi_g' и 'multi_gc' одни)."""
    w = data.windows(L)
    st = w['st'][w['val']]
    rng = np.random.default_rng(SAMPLE_SEED)
    return np.sort(st[np.sort(rng.choice(len(st), size=min(SAMPLE_N, len(st)), replace=False))])


def tap_stats(E):
    """Справочно об отводе: доля нулей, среднее число ненулевых координат, мёртвые координаты, эффективный ранг
       (participation ratio спектра корреляций: 1 — всё в одном направлении, D — все направления поровну), главных
       компонент на 90% разброса."""
    E = np.asarray(E, np.float64)
    sd = E.std(0)
    keep = sd > 1e-6
    out = {'dim': int(E.shape[1]), 'zero': float((E == 0).mean()), 'dead': int((~keep).sum()),
           'active': float((E != 0).sum(1).mean())}
    if keep.sum() >= 2:
        Z = (E[:, keep] - E[:, keep].mean(0)) / sd[keep]
        ev = np.clip(np.linalg.eigvalsh(np.cov(Z, rowvar=False)), 0, None)[::-1]
        out['pr'] = float(ev.sum() ** 2 / max((ev ** 2).sum(), 1e-12))
        out['pc90'] = int(np.searchsorted(np.cumsum(ev) / ev.sum(), 0.9) + 1)
    return out


def letter_stats(P):
    """Справочно о «буквах» (строки P — вероятности): эффективное число букв на окно exp(H(P)), букв в деле exp(H(
       среднего P)), средняя вероятность первой буквы, доля почти-нулей (< 0.001), разных первых букв на образце."""
    P = np.asarray(P, np.float64)
    P = P / np.clip(P.sum(1, keepdims=True), 1e-12, None)
    pm = P.mean(0)
    return {'eff': float(np.exp(-(P * np.log(np.clip(P, 1e-12, None))).sum(1)).mean()),
            'used': float(np.exp(-(pm * np.log(np.clip(pm, 1e-12, None))).sum())),
            'top1': float(P.max(1).mean()), 'tiny': float((P < 1e-3).mean()), 'n_top1': int(len(np.unique(P.argmax(1))))}


def finish(model, name, seed_key, info, t_run):
    cfg = model.cfg
    tag = run_tag(name, seed_key)
    data, store = get_data(cfg['price']), get_store(cfg['price'])
    tune, val = eval_part(model, 'tune'), eval_part(model, 'val')
    prof = profile(model)
    print(f"🎯 {tag}: " + " | ".join(f"{k} TUNE {tune[k][0]:.4f}±{tune[k][1]:.4f} VAL {val[k][0]:.4f}±{val[k][1]:.4f}"
                                     for k in tune))
    if prof:
        print("   справочно, VAL против нулевых профиля: " + " | ".join(f"{k} {v:.4f}" for k, v in prof.items()))
    smp = sample_starts(data)
    emb = embed(model, data, smp)
    fitp = embed(model, data, store.positives('fitprobe')['st'])
    taps = {}
    arrs = {'sd_' + k: v.detach().cpu().numpy() for k, v in model.state_dict().items()}
    arrs['smp_st'] = smp.astype(np.int64)
    arrs['smp_orient'] = emb['orient'].astype(np.int8)
    for tap in [k for k in emb if k != 'orient']:
        taps[tap] = tap_stats(emb[tap])
        arrs[f'smp_{tap}'] = emb[tap].astype(np.float16)
        arrs[f'fmu_{tap}'] = fitp[tap].mean(0).astype(np.float32)
        arrs[f'fsd_{tap}'] = fitp[tap].std(0).astype(np.float32)
        t_ = taps[tap]
        print(f"   отвод {tap:<5} {t_['dim']:>3} чисел | нулей {100 * t_['zero']:5.1f}% (ненулевых в окне "
              f"{t_['active']:.0f}) | мёртвых {t_['dead']} | эфф. ранг {t_.get('pr', float('nan')):.1f} | "
              f"компонент на 90% {t_.get('pc90', '—')}")
        if cfg['emb'] == 'proto' and tap in ('bneck', 'psoft'):
            t_.update(letter_stats(emb[tap]))
            print(f"         буквы: ~{t_['eff']:.1f} на окно, в деле {t_['used']:.0f} из {t_['dim']}, первая буква — "
                  f"{t_['top1']:.2f}, почти-нулей (< 0.001) {100 * t_['tiny']:.0f}%, разных первых букв {t_['n_top1']}")
    if cfg['tap'] not in taps:
        raise RuntimeError(f"🍆 АЙ, ОШИБКА! отвода по умолчанию '{cfg['tap']}' нет среди {list(taps)}")
    res = {'ver': EMB_VER, 'tag': tag, 'name': name, 'seed_key': seed_key, 'cfg': cfg,
           'n_chan': int(model.blocks[0][0].in_channels), 'n_level': model.n_level,
           'tune': {k: {'auc': v[0], 'se': v[1]} for k, v in tune.items()},
           'val': {k: {'auc': v[0], 'se': v[1]} for k, v in val.items()},
           'profile': prof, 'taps': taps, 'tap': cfg['tap'],
           'n_params': int(sum(p.numel() for p in model.parameters())), 'secs': time.time() - t_run,
           'smp_fp': zlib.crc32(arrs['smp_st'].tobytes()), 'train_py': TRAIN_PY, 'smc_rel': getattr(smc, 'POOL_REL', '?'),
           'sme_rel': SME_REL,
           'when': time.strftime('%Y-%m-%d %H:%M:%S'), **info}
    os.makedirs(EMB_DIR, exist_ok=True)
    np.savez_compressed(EMB_DIR + f"emb_{tag}.npz", **arrs)
    with open(EMB_DIR + f"emb_{tag}.json", 'w', encoding='utf-8') as fh:
        json.dump(smc._jsonable(res), fh, ensure_ascii=False, indent=1)
    print(f"💾 {EMB_DIR}emb_{tag}.json / .npz | {(time.time() - t_run) / 60:.1f} мин")
    return res


