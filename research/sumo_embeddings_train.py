def rev_windows(data, st_t, W):
    """Окно в обратном времени. Бар t' суррогата — бар s = L−1−t' окна, пройденный задом наперёд: его close — close
       бара s−1 (open исходного бара), high / low те же. Отсюда, в единицах r:
         шаг close        r'_t' = −r_s                                   (весь путь close задом наперёд);
         шаг HL/2         p'_t' = −p_{s+1}                               (t' >= 1);
         шаг HLC/3        q'_t' = −q_{s+1} + (r_{s+1} − r_s) / 3         (HLC/3 = (2·HL/2 + close) / 3, а close сдвинут);
         диапазон         g'_t' = g_s;   положение close в баре  o'_t' = −e_s (прошлый close от середины бара s).
       Первый шаг средних цен (t' = 0) свёрткам не нужен (форма теряет первый шаг) — 0. Модули шагов close те же, что у
       окна: делитель и знаменатель окна совпадают. Всё — из баров самого окна."""
    r = W[:, 0]
    chans = [-torch.flip(r, [1])]
    for j in range(len(data.chan_t)):
        p = W[:, 1 + j]
        pr = torch.zeros_like(p)
        pr[:, 1:] = -torch.flip(p[:, 1:], [1])
        if smc.MULTI_PRICES[j] == 'hlc3':
            pr[:, 1:] += (torch.flip(r[:, 1:], [1]) - torch.flip(r[:, :-1], [1])) / 3.0
        chans.append(pr)
    for c in range(smc.N_PATH, W.shape[1]):
        if smc.LEVEL_SIGNED[c - smc.N_PATH]:
            chans.append(-torch.flip(smc.gather(data.chan_t[0][0], st_t, L), [1]))
        else:
            chans.append(torch.flip(W[:, c], [1]))
    return torch.stack(chans, dim=1)


def blk_signs(n, cfg, gen, device):
    """Порча ELECTRA: каждый блок из blk_size баров (сетка от начала окна) переворачивается с вероятностью blk_p.
       Знаки баров (n, L + 1): столбец 0 — бар перед окном (+1); метки (n, L / blk_size): 1 — блок перевёрнут."""
    b = int(cfg['blk_size'])
    flips = torch.rand(n, L // b, generator=gen, device=gen.device) < cfg['blk_p']
    S = torch.ones(n, L + 1, device=gen.device)
    S[:, 1:] = torch.where(flips.repeat_interleave(b, dim=1), -1.0, 1.0)
    return S.to(device), flips.float().to(device)


def neg_windows(spec, data, st_t, sid_t, W, fl, gen, ctx):
    """Отрицательные окна обучения для реальных окон W."""
    kind, b = parse_null(spec)
    if kind == 'sflip':
        return data.flip_multi(st_t, L, smc.block_signs_prev(len(W), L, b, gen, DEVICE), W)
    if kind == 'iid':
        Wn = ctx['pool'].windows(sid_t, 'fit', gen)
        if math.isfinite(ctx['thr']):                # та же обрезка хвоста размаха, что у реальных окон
            for _ in range(5):
                bad = torch.where(smc.tv_ratio(Wn[:, 0], fl) > ctx['thr'])[0]
                if len(bad) == 0:
                    break
                Wn[bad] = ctx['pool'].windows(sid_t[bad], 'fit', gen)
        return Wn
    return rev_windows(data, st_t, W)


def eval_windows(price, part, spec):
    """Сырые отрицательные окна набора проверки (форма считается под ориентацию модели). У sflip — те же суррогаты,
       что в EvalStore классификатора (тот же генератор): AUC сравнимы с прогонами NT1_*."""
    key = (price, part, spec)
    if key not in _SETS:
        data, store = get_data(price), get_store(price)
        P = store.positives(part)
        n = len(P['W'])
        kind, b = parse_null(spec)
        if kind == 'sflip':
            g = store._gen(part, spec, L)
            Wn = data.flip_multi(P['st_t'], L, smc.block_signs_prev(n, L, b, g, 'cpu').to(DEVICE), P['W'])
        elif kind == 'iid':
            g = torch.Generator()
            g.manual_seed(smc.DATA['eval_seed'] + zlib.crc32(f"{part}|iid|{L}".encode()) % 1000003)
            Wn = get_pool(price).windows(P['sid'], 'fit' if part.startswith('fit') else part, g)
        else:
            Wn = rev_windows(data, P['st_t'], P['W'])
        _SETS[key] = Wn
    return _SETS[key]


def blk_eval_set(price, part, cfg):
    key = (price, part, 'blk', cfg['blk_p'], cfg['blk_size'])
    if key not in _SETS:
        data, P = get_data(price), get_store(price).positives(part)
        g = torch.Generator()
        g.manual_seed(smc.DATA['eval_seed'] + zlib.crc32(f"{part}|blk|{L}".encode()) % 1000003)
        S, y = blk_signs(len(P['W']), cfg, g, DEVICE)
