def fit_set(cfg, data):
    """Окна FIT для градиента: весь FIT без верхних trim_q % размаха (от знаков не зависит — как у классификатора)."""
    w = data.windows(L)
    st = torch.from_numpy(w['st'][w['fit']]).to(DEVICE)
    sid = torch.from_numpy(w['sid'][w['fit']]).to(DEVICE)
    fl = w['floor_t'][sid]
    tv = torch.cat([smc.tv_ratio(smc.gather(data.r_t, st[i:i + 262144], L), fl[i:i + 262144])
                    for i in range(0, len(st), 262144)])
    thr = float('inf')
    if cfg['trim_q']:
        thr = float(torch.quantile(tv[torch.randperm(len(tv), device=DEVICE)[:1000000]], 1 - cfg['trim_q'] / 100.0))
    keep = tv <= thr
    return st[keep], sid[keep], thr, float(1 - keep.float().mean())


def build_model(cfg, data, fit_st, fit_sid, rng, n_pick=150000):
    w = data.windows(L)
    pick = torch.from_numpy(rng.choice(len(fit_st), size=min(n_pick, len(fit_st)), replace=False)).to(DEVICE)
    st, sid = fit_st[pick], fit_sid[pick]
    W = data.gw(st, L)
    fl = w['floor_t'][sid]
    Xs = shapes(W, fl, cfg['orient'])
    side = tuple(smc.SIDE_COLS[cfg['side']]) if cfg['side'] else None
    Ss = side_for(side, data, st, W, fl)
    model = EmbNet(cfg, Xs.shape[1], smc.N_LEVEL.get(cfg['price'], 0)).to(DEVICE)
    init_stats(model, Xs, Ss)
    return model


def train_step(model, data, st, sid, fl, gen, ctx):
    """Потеря одного шага: 'cls' — реальные окна и по набору отрицательных на каждую нулевую (BCE каждой головы со
       своей нулевой, среднее по головам); 'blk' — испорченные реальные окна, BCE по блокам."""
    cfg = model.cfg
    Wp = data.gw(st, L)
    if cfg['task'] == 'blk':
        S, y = blk_signs(len(Wp), cfg, gen, DEVICE)
        X = shapes(data.flip_multi(st, L, S, Wp), fl, model.orient)
        return F.binary_cross_entropy_with_logits(model(X), y)
    negs = [neg_windows(nl, data, st, sid, Wp, fl, gen, ctx) for nl in cfg['nulls']]
    K, n = len(negs), len(Wp)
    Wall, fla, sta = torch.cat([Wp] + negs), fl.repeat(K + 1), st.repeat(K + 1)
    X, S = shapes(Wall, fla, model.orient), side_for(model.side_cols, data, sta, Wall, fla)
    if model.emb_kind == 'proto':
        logit, ps = model(X, S, return_p=True)
    else:
        logit, ps = model(X, S), None
    y = torch.cat([torch.ones(n, device=DEVICE), torch.zeros(n, device=DEVICE)])
    loss = 0.0
    for k in range(K):
        loss = loss + F.binary_cross_entropy_with_logits(torch.cat([logit[:n, k], logit[n * (k + 1):n * (k + 2), k]]), y)
    loss = loss / K
    if ps is not None:                       # «буквы»: острота и использование — по реальным окнам (словарь реального рынка)
        pr = ps[:n]
        lk = math.log(pr.shape[1])
        ent = -(pr * torch.log(pr.clamp_min(1e-12))).sum(1).mean() / lk
        pm = pr.mean(0)
        use = 1.0 - (-(pm * torch.log(pm.clamp_min(1e-12))).sum() / lk)
        loss = loss + model.p_sharp_now * ent + cfg['p_use'] * use
        model.p_last = (ent.detach(), pm.detach())
    return loss


def topk_at(cfg, ep):
    """k у горла top-k на эпохе ep: от полного горла к cfg['topk'] за topk_anneal эпох (иначе часть единиц не получит
       градиента ни разу и умрёт)."""
    if cfg['emb'] != 'topk':
        return None
    D, k = int(cfg['emb_dim']), int(cfg['topk'])
    a = min(1.0, ep / max(1, cfg['topk_anneal']))
    return max(k, int(round(D * (k / D) ** a)))


TRUNK_KEYS = ('s_sd', 'lvl_mu', 'lvl_sd', 'side_mu', 'side_sd')     # масштабы входа ствола (буферы)


@torch.no_grad()
def init_letters(model, data, st, sid, rng, n=20000):
    """Старт букв: стандартизация пулинга по окнам FIT (p_mu, p_sd) и прототипы — проекции K случайных реальных окон
       FIT: каждая буква сразу «владеет» своими окнами."""
    was = model.training
    model.eval()
    pick = torch.from_numpy(rng.choice(len(st), size=min(n, len(st)), replace=False)).to(DEVICE)
    floor_t = data.windows(L)['floor_t']
    feats = []
    for i in range(0, len(pick), 8192):
        s_, i_ = st[pick[i:i + 8192]], sid[pick[i:i + 8192]]
        W = data.gw(s_, L)
        feats.append(model.pooled(model.conv_maps(shapes(W, floor_t[i_], model.orient))))
    f = torch.cat(feats)
    sd = f.std(0)
    model.p_mu.copy_(f.mean(0))
    # пол — десятая медианного разброса живых каналов: канал, мёртвый на старте, у доучиваемого ствола (PT) может ожить —
    # без пола его стандартизованное значение взорвётся
    live = sd[sd > 1e-6]
    model.p_sd.copy_(sd.clamp_min(max(1e-3, 0.1 * (float(live.median()) if len(live) else 1.0))))
    z = model.p_proj((f - model.p_mu) / model.p_sd)
    k = model.p_protos.shape[0]
    model.p_protos.copy_(z[torch.from_numpy(rng.choice(len(z), size=k, replace=False)).to(DEVICE)])
    model.train(was)


def load_trunk(model, src, seed_key):
    """Ствол (свёртки и масштабы входа) из прогона классификатора src (имя в RUNS) того же сида; устройство ствола
       обязано совпасть. Голова и горло остаются свои."""
    cnn, r = smc.load_finalist(src, seed_key, L)
    c_src, c = cfg_from_classifier(r['cfg'], r['spec']), model.cfg
    diff = [k for k in ('price', 'side', 'ch', 'k', 'dil', 'sep', 'pool', 'orient') if c_src[k] != c[k]]
    if diff:
        raise ValueError(f"🍆 АЙ, ОШИБКА! ствол {r['tag']} другого устройства: "
                         + ", ".join(f"{k} {c_src[k]} ≠ {c[k]}" for k in diff))
    sd = {k: v for k, v in cnn.state_dict().items() if k.startswith('blocks.') or k in TRUNK_KEYS}
    own = model.state_dict()
    bad = [k for k, v in sd.items() if k not in own or own[k].shape != v.shape]
    if bad:
        raise ValueError(f"🍆 АЙ, ОШИБКА! ствол {r['tag']} не ложится в модель: {bad[:5]}")
    model.load_state_dict(sd, strict=False)
    return r


def train_one(name, seed_key, over=None, job='one'):
    t_run = time.time()
    cfg = make_cfg(name, over)
    tag = run_tag(name, seed_key)
    seed = smc.SEEDS[seed_key]
    data = get_data(cfg['price'])
    get_store(cfg['price'])
    torch.manual_seed(seed)
    rng = np.random.default_rng(seed)
    gen = torch.Generator(device=DEVICE)
    gen.manual_seed(seed)
    print(f"\n\n{'#' * 78}\n# SME v{EMB_VER} | {tag} | задание {job} | {DEVICE}\n# {cfg_line(cfg)}\n{'#' * 78}")
    fit_st, fit_sid, thr, trim = fit_set(cfg, data)
    model = build_model(cfg, data, fit_st, fit_sid, rng)
    src_note = ''
    if cfg['init_from']:                                  # волна 2: ствол готовой модели того же сида
        r_src = load_trunk(model, cfg['init_from'], seed_key)
        if cfg['freeze']:
            for prm in model.blocks.parameters():
                prm.requires_grad_(False)
        src_note = f" | ствол — {r_src['tag']}" + (" (заморожен)" if cfg['freeze'] else "")
    if cfg['emb'] == 'proto':
        init_letters(model, data, fit_st, fit_sid, rng)
    ctx = {'thr': thr, 'pool': get_pool(cfg['price']) if 'iid' in cfg['nulls'] else None}
    opt = torch.optim.AdamW([p for p in model.parameters() if p.requires_grad], lr=cfg['lr'], weight_decay=cfg['wd'])
    lr0 = cfg['lr']
    half = cfg['batch'] if cfg['task'] == 'blk' else cfg['batch'] // 2
    steps = cfg['steps'] or max(1, len(fit_st) // half)
    p_ramp = cfg['emb'] == 'proto' and (cfg['p_sharp'] > 0 or cfg['p_hard'])
    # до конца отжига k (top-k) или разгона остроты букв лучшую эпоху не берём
    first_ok = cfg['topk_anneal'] if cfg['emb'] == 'topk' else (cfg['p_anneal'] if p_ramp else 0)
    min_ep = max(cfg['min_epochs'], first_ok + 1)
    floor_t = data.windows(L)['floor_t']
    n_par = sum(p.numel() for p in model.parameters())
    n_tr = sum(p.numel() for p in model.parameters() if p.requires_grad)
    taps0 = tap_dims(model, data, fit_st, fit_sid)
    print(f"📦 окон FIT {len(fit_st)} (обрезано {100 * trim:.2f}% по размаху > {thr:.1f}) | эпоха = {steps} шагов по "
          f"{half}{' реальных окон + отрицательные' if cfg['task'] == 'cls' else ' испорченных окон'} | весов {n_par}"
          + (f" (учатся {n_tr})" if n_tr < n_par else "") + f" | отводы {taps0} (по умолчанию '{cfg['tap']}')" + src_note)
    hist, best, bad = [], {'auc': -float('inf'), 'ep': -1, 'state': None}, 0
    stop_note = ''
    for ep in range(cfg['epochs']):
        t_ep = time.time()
        model.topk_now = topk_at(cfg, ep)
        if cfg['emb'] == 'proto':                         # острота букв разгоняется, буква one-hot — после разгона
            model.p_sharp_now = cfg['p_sharp'] * (min(1.0, ep / max(1, cfg['p_anneal'])) if p_ramp else 1.0)
            model.p_hard_now = bool(cfg['p_hard']) and ep >= cfg['p_anneal']
            p_ent, p_pm = torch.zeros((), device=DEVICE), 0.0
        perm = torch.randperm(len(fit_st), generator=gen, device=DEVICE)
        acc = torch.zeros((), device=DEVICE)
        model.train()
        for s in range(steps):
            a0 = (s * half) % len(perm)
            j = perm[a0:a0 + half]
            loss = train_step(model, data, fit_st[j], fit_sid[j], floor_t[fit_sid[j]], gen, ctx)
            opt.zero_grad(set_to_none=True)
            loss.backward()
            opt.step()
            acc += loss.detach()
            if cfg['emb'] == 'proto':
                p_ent = p_ent + model.p_last[0]
                p_pm = p_pm + model.p_last[1]
        tune = eval_part(model, 'tune')
        fitp = eval_part(model, 'fitprobe', heads=[0] if cfg['task'] == 'cls' else None)
        m = float(np.mean([v[0] for v in tune.values()]))
        f0 = float(next(iter(fitp.values()))[0])
        improved = ep >= first_ok and m > best['auc'] + cfg['stop_delta']
        if improved:
            best = {'auc': m, 'ep': ep, 'state': {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}}
            bad = 0
        elif ep >= first_ok:
            bad += 1
        lr_note = ''
        if cfg['lr_plateau'] and not improved and bad and bad % cfg['lr_plateau'] == 0:
            for g_ in opt.param_groups:
                g_['lr'] = max(g_['lr'] * cfg['lr_factor'], lr0 * cfg['lr_min_frac'])
            lr_note = f" | lr -> {opt.param_groups[0]['lr']:.1e}"
        row = {'ep': ep, 'sec': time.time() - t_ep, 'loss': float(acc) / steps, 'fit': f0, 'tune_mean': m,
               'tune': {k: v[0] for k, v in tune.items()}, 'lr': opt.param_groups[0]['lr'], 'k': model.topk_now}
        p_note = ''
        if cfg['emb'] == 'proto':                         # буквы на реальных окнах FIT этой эпохи
            kp = int(cfg['emb_dim'])
            pm = (p_pm / steps).clamp_min(1e-12)
            row.update({'p_h': float(p_ent) / steps, 'p_eff': math.exp(float(p_ent) / steps * math.log(kp)),
                        'p_used': float(torch.exp(-(pm * pm.log()).sum())), 'p_sharp': model.p_sharp_now,
                        'p_hard': model.p_hard_now,
                        'p_t': float(torch.exp(model.p_log_t.detach().clamp(math.log(P_TMIN), math.log(P_TMAX))))})
            p_note = (f" | буквы: ~{row['p_eff']:.1f} на окно, в деле {row['p_used']:.0f}/{kp}, T {row['p_t']:.3f}"
                      + (" | one-hot" if model.p_hard_now else ""))
        hist.append(row)
        heads_s = " ".join(f"{k} {v[0]:.4f}" for k, v in tune.items())
        print(f"эп {ep:>3} | {row['sec']:5.1f}c | loss {row['loss']:.4f} | FIT {f0:.4f} | TUNE {heads_s}"
              + (f" (среднее {m:.4f})" if len(tune) > 1 else "") + (f" | k {model.topk_now}" if model.topk_now else "")
              + p_note + lr_note + (" ★" if improved else ""))
        if ep + 1 >= min_ep and bad >= cfg['patience']:
            stop_note = f"ранняя остановка на эпохе {ep}"
            break
    if best['state'] is None:
        raise RuntimeError("🍆 АЙ, ОШИБКА! ни одной годной эпохи (epochs <= topk_anneal / p_anneal?)")
    model.load_state_dict(best['state'])
    model.topk_now = cfg['topk']
    model.p_sharp_now, model.p_hard_now = float(cfg['p_sharp']), bool(cfg['p_hard'])
    print(f"⏹️ {stop_note or 'все эпохи пройдены'} | лучшая эпоха {best['ep']}: TUNE {best['auc']:.4f} | "
          f"{(time.time() - t_run) / 60:.1f} мин")
    info = {'kind': 'trained', 'best_ep': best['ep'], 'epochs_run': len(hist), 'hist': hist, 'thr': thr, 'trim': trim,
            'secs_train': time.time() - t_run, 'sec_ep': float(np.median([h['sec'] for h in hist]))}
    return finish(model, name, seed_key, info, t_run)


@torch.no_grad()
def tap_dims(model, data, st, sid, n=256):
    """Размерности отводов модели на маленькой пачке окон FIT — в режиме eval (dropout не трогает поток случайных чисел
       обучения)."""
    was = model.training
    model.eval()
    st, sid = st[:n], sid[:n]
    W = data.gw(st, L)
    fl = data.windows(L)['floor_t'][sid]
    out = {k: int(v.shape[1]) for k, v in model.taps(shapes(W, fl, model.orient),
                                                     side_for(model.side_cols, data, st, W, fl)).items()}
