    tw_d = sorted([t for t in twins if t[1] in dflt_set and t[2] in dflt_set], reverse=True)
    tw_o = sorted([t for t in twins if not (t[1] in dflt_set and t[2] in dflt_set)], reverse=True)
    print("   среди отводов по умолчанию:")
    for v, a, b, ref in tw_d[:25]:
        print(f"   ≈ {a} и {b}: CKA {v:.3f} (между своими сидами — не выше {ref:.3f})")
    if len(tw_d) > 25:
        print(f"   … и ещё {len(tw_d) - 25} пар (весь список — в json сводки)")
    if not tw_d:
        print("   — нет")
    if tw_o:
        print(f"   прочие отводы — {len(tw_o)} пар, сильнейшие: "
              + "; ".join(f"{a} ≈ {b} {v:.2f}" for v, a, b, _ in tw_o[:8]))
    print("\n   уникальность — 1 − max CKA с другими кандидатами (больше — новее представление):")
    uniq = []
    for i, a in enumerate(labs):
        others = [M[i, j] for j, b in enumerate(labs) if cand(b) not in (cand(a), 'REP')]
        if cand(a) != 'REP' and others:
            uniq.append((1 - max(others), a))
    print("   " + " | ".join(f"{a} {u:.2f}" for u, a in sorted(uniq, reverse=True)))
    # порядок для трансформера (справочно): отвод по умолчанию каждого кандидата; первым — NT0 (решение 2026-10-17),
    # дальше каждый раз — самый непохожий на уже взятых (наименьшая max CKA с ними)
    dflt = [f"{nm}.{by[nm][0]['tap']}" for nm in order if nm != 'REP' and f"{nm}.{by[nm][0]['tap']}" in labs]
    pick = [x for x in dflt if x.startswith('NT0.')][:1] or dflt[:1]
    rest = [x for x in dflt if x not in pick]
    near = []
    while rest:
        sc = [max(M[labs.index(x), labs.index(y)] for y in pick) for x in rest]
        k = int(np.argmin(sc))
        near.append(sc[k])
        pick.append(rest.pop(k))
    print("\n🧭 ПОРЯДОК ДЛЯ SMT (справочно; отвод по умолчанию, каждый следующий — самый непохожий на уже взятых, в скобках — "
          "его max CKA с ними):")
    print("   " + " → ".join([pick[0]] + [f"{x} ({v:.2f})" for x, v in zip(pick[1:], near)]))
    stamp = time.strftime('%Y%m%d_%H%M%S')
    out = {'ver': EMB_VER, 'when': stamp, 'labels': labs, 'cka': M, 'seed_cka': seed_cka, 'missing': miss,
           'twins': [(a, b, v) for v, a, b, _ in twins], 'order': pick,
           'runs': {r['tag']: {'val': r['val'], 'tune': r['tune'], 'profile': r.get('profile'), 'taps': r['taps']} for r in rows}}
    path = EMB_DIR + f"emb_summary_{stamp}.json"
    with open(path, 'w', encoding='utf-8') as fh:
        json.dump(smc._jsonable(out), fh, ensure_ascii=False, indent=1)
    print(f"💾 {path}")
    return out


