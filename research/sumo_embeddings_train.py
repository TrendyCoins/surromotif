@torch.no_grad()
def score(model, data, W, st_t, fl, bs=32768):
    """logit (n, голов) или logit блоков для сырых окон W (форма и боковые входы — под модель)."""
    was = model.training
    model.eval()
    out = []
    for i in range(0, len(W), bs):
        w, f, s = W[i:i + bs], fl[i:i + bs], st_t[i:i + bs]
        X = shapes(w, f, model.orient)
        out.append(model(X, side_for(model.side_cols, data, s, w, f)).float().cpu())
    model.train(was)
    return torch.cat(out).numpy().astype(np.float64)


def eval_cls(model, part, heads=None, real=None):
    """AUC головы против своей нулевой на части part: {нулевая: (auc, se)}; real — готовые оценки реальных окон."""
    cfg = model.cfg
    data, P = get_data(cfg['price']), get_store(cfg['price']).positives(part)
    sp = real if real is not None else score(model, data, P['W'], P['st_t'], P['fl'])
    out = {}
    for k in (range(len(cfg['nulls'])) if heads is None else heads):
        nl = cfg['nulls'][k]
        sn = score(model, data, eval_windows(cfg['price'], part, nl), P['st_t'], P['fl'])
        out[nl] = smc.auc_se(sp[:, k], sn[:, k], P['wk'], P['wk'])
    return out


def eval_blk(model, part):
    """AUC блоков «перевёрнут / нет» на фиксированной порче набора part."""
    cfg = model.cfg
    data, P = get_data(cfg['price']), get_store(cfg['price']).positives(part)
    Wc, y = blk_eval_set(cfg['price'], part, cfg)
    lg = score(model, data, Wc, P['st_t'], P['fl'])
    wk = np.repeat(np.asarray(P['wk'])[:, None], y.shape[1], axis=1)
    m = y > 0.5
    return {'blk': smc.auc_se(lg[m], lg[~m], wk[m], wk[~m])}


def eval_part(model, part, heads=None):
    return eval_blk(model, part) if model.cfg['task'] == 'blk' else eval_cls(model, part, heads)


def profile(model):
    """Справочно (VAL): AUC модели против каждой нулевой профиля. У 'cls' с одной головой — её logit; у 'blk' — оценка
       окна −(средний logit блоков): чем меньше «перевёрнутых» блоков видит модель, тем окно реальнее."""
    cfg = model.cfg
    if cfg['task'] == 'cls' and len(cfg['nulls']) > 1:
        return {}
    data, P = get_data(cfg['price']), get_store(cfg['price']).positives('val')

    def sc(W):
        s = score(model, data, W, P['st_t'], P['fl'])
        return -s.mean(1) if cfg['task'] == 'blk' else s[:, 0]
    sp = sc(P['W'])
    return {nl: smc.auc_se(sp, sc(eval_windows(cfg['price'], 'val', nl)), P['wk'], P['wk'])[0] for nl in PROFILE_NULLS}


