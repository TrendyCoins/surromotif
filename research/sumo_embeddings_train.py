def sparsemax(z):
    """Проекция на симплекс (Martins & Astudillo 2016): как softmax, но с точными нулями."""
    zs = torch.sort(z, dim=1, descending=True).values
    k = torch.arange(1, z.shape[1] + 1, device=z.device, dtype=z.dtype)
    cs = zs.cumsum(dim=1)
    kz = (1 + k * zs > cs).sum(dim=1, keepdim=True)
    tau = (cs.gather(1, kz - 1) - 1) / kz.to(z.dtype)
    return torch.clamp(z - tau, min=0.0)


def topk_relu(z, k):
    """ReLU, затем оставить k наибольших в строке, остальное — 0."""
    a = F.relu(z)
    if k is None or k >= a.shape[1]:
        return a
    v, i = a.topk(int(k), dim=1)
    return torch.zeros_like(a).scatter(1, i, v)


class EmbNet(nn.Module):
    """Ствол — те же слои и имена, что у CNNBase v6.3 (свёртки по шагам трёх цен + каналы-уровни, ReLU, dropout,
       раздельные свёртки по опции): веса NT1_0 / NT1_PRV грузятся сюда как есть. Дальше:
         пулинг: 'mml' (среднее, максимум, последнее место) | 'mm' | 'seg3l' (средние трёх третей окна + последнее
                 место: остаётся грубый порядок узоров внутри окна);
         горло:  'pool' (нет) | 'relu' | 'topk' (ReLU и k наибольших) | 'sparsemax' (точка симплекса с нулями);
         головы: task 'cls' — по голове на нулевую из cfg['nulls'] (вход — эмбеддинг и знаменатель окна);
                 task 'blk' — по месту окна logit «бар в перевёрнутом блоке», среднее по блоку."""
    def __init__(self, cfg, n_chan, n_level):
        super().__init__()
        c = norm_cfg(cfg)
        self.cfg = c
        self.orient, self.task = bool(c['orient']), c['task']
        self.n_level = int(n_level)
        self.lvl_signed = tuple(smc.LEVEL_SIGNED[:self.n_level])
        if self.n_level:
            self.register_buffer('lvl_mu', torch.zeros(self.n_level))
            self.register_buffer('lvl_sd', torch.ones(self.n_level))
        self.side_cols = tuple(smc.SIDE_COLS[c['side']]) if c['side'] else None
        n_side = len(self.side_cols) if self.side_cols else 0
        self.register_buffer('side_mu', torch.zeros(max(n_side, 1)))
        self.register_buffer('side_sd', torch.ones(max(n_side, 1)))
        self.register_buffer('s_sd', torch.tensor(1.0))
        ch, k = int(c['ch']), int(c['k'])
        blocks, c_in = [], int(n_chan)
        for i_l, d in enumerate(c['dil']):
            pad = d * (k - 1) // 2
            if c['sep'] and i_l > 0:
                # раздельная свёртка: по каналу ядро k (groups = каналы), затем смешение каналов 1 × 1 — как CNNBase v6.3.
                # sep_fix (опция, по умолчанию выкл.): поканальная свёртка без сдвига (он лишний: смешение линейно, сдвиг у
                # него свой) и старт с сохранением разброса. Стенд: узкая сеть (32 канала) с умолчанием torch за 5 эпох не
                # сдвинулась с 0.500 (сдвиги ±1/√k топят сигнал), с sep_fix — пошла; на 128 каналах учатся обе
                dw = nn.Conv1d(c_in, c_in, k, dilation=d, padding=pad, groups=c_in, bias=not c['sep_fix'])
                pw = nn.Conv1d(c_in, ch, 1)
                if c['sep_fix']:
                    nn.init.normal_(dw.weight, 0.0, (1.0 / k) ** 0.5)
                    nn.init.kaiming_normal_(pw.weight, nonlinearity='relu')
                    nn.init.zeros_(pw.bias)
                layers = [dw, pw]
            else:
                layers = [nn.Conv1d(c_in, ch, k, dilation=d, padding=pad)]
            layers.append(nn.ReLU())
            if c['cdrop'] > 0:
                layers.append(nn.Dropout(c['cdrop']))
            blocks.append(nn.Sequential(*layers))
            c_in = ch
        self.blocks = nn.ModuleList(blocks)
        self.ch, self.n_pos = ch, L - 1
        self.pool_dim = {'mml': 3, 'mm': 2, 'seg3l': 4}[c['pool']] * ch
        self.emb_kind = c['emb']
        self.emb_dim = self.pool_dim
        if self.emb_kind == 'proto':                     # волна 2: «буквы» — K прототипов в пространстве признаков
            self.emb_dim = int(c['emb_dim'])
            self.register_buffer('p_mu', torch.zeros(self.pool_dim))     # стандартизация пулинга перед проекцией
            self.register_buffer('p_sd', torch.ones(self.pool_dim))
            self.p_proj = nn.Linear(self.pool_dim, int(c['p_dim']))
            self.p_protos = nn.Parameter(torch.randn(self.emb_dim, int(c['p_dim'])))
            self.p_log_t = nn.Parameter(torch.tensor(math.log(c['p_tau'])))
        elif self.emb_kind != 'pool':
            self.emb_dim = int(c['emb_dim'])
            self.bneck = nn.Linear(self.pool_dim, self.emb_dim)
            if self.emb_kind == 'sparsemax':
                self.smx_log_scale = nn.Parameter(torch.zeros(()))
        self.topk_now = c['topk']
        self.p_sharp_now, self.p_hard_now = float(c['p_sharp']), bool(c['p_hard'])     # обучение меняет по эпохам
        if self.task == 'cls':
            heads = [smc.mlp(self.emb_dim + n_side, tuple(c['head']), c['hdrop']) for _ in c['nulls']]
            if len(heads) == 1:
                self.head = heads[0]
            else:
                self.heads = nn.ModuleList(heads)
        else:
            self.pos_head = nn.Sequential(nn.Conv1d(ch, 32, 1), nn.ReLU(), nn.Dropout(c['hdrop']), nn.Conv1d(32, 1, 1))
            b = int(c['blk_size'])
            M = torch.zeros(self.n_pos, L // b)
            for kp in range(self.n_pos):                 # место kp свёрток — шаг бара kp + 1
                M[kp, (kp + 1) // b] = 1.0
            self.register_buffer('blk_avg', M / M.sum(0, keepdim=True))

    def conv_maps(self, x):
        """Карты последнего слоя (окна, каналы, 63 места) — как CNNBase.conv_maps (вход — шаги, уровни — значения)."""
        if self.n_level:
            P_ = x.shape[1] - self.n_level
            z = x[:, :P_, 1:] - x[:, :P_, :-1]
            lv = (x[:, P_:, 1:] - self.lvl_mu[None, :, None]) / self.lvl_sd[None, :, None]
            h = torch.cat([z / self.s_sd, lv], dim=1)
        else:
            h = (x[..., 1:] - x[..., :-1]) / self.s_sd
            if h.dim() == 2:
                h = h[:, None, :]
        for blk in self.blocks:
            h = blk(h)
        return h

    def pooled(self, h):
        if self.cfg['pool'] == 'seg3l':
            n = h.shape[2]
            c1, c2 = n // 3, 2 * n // 3
            return torch.cat([h[:, :, :c1].mean(2), h[:, :, c1:c2].mean(2), h[:, :, c2:].mean(2), h[:, :, -1]], dim=1)
        feats = [h.mean(2), h.amax(2)]
        if self.cfg['pool'] == 'mml':
            feats.append(h[:, :, -1])
        return torch.cat(feats, dim=1)

    def proto_probs(self, p):
        """«Буквы»: z — проекция стандартизованного пулинга, d_k = |z − прототип_k|² / p_dim, P = softmax(−d / T), T учится
           в [P_TMIN, P_TMAX] (как L2-прототипы ранней SMC, только в пространстве признаков ствола). Возвращает (P для
           головы, мягкое P для потерь): у p_hard голова видит one-hot ближайшей буквы, градиент — мягкого P
           (straight-through). Квадрат расстояния — раскрытой формулой: у cdist в нуле градиент NaN."""
        z = self.p_proj((p - self.p_mu) / self.p_sd)
        c = self.p_protos
        d = (z.pow(2).sum(1, keepdim=True) - 2.0 * z @ c.t() + c.pow(2).sum(1)[None, :]).clamp_min(0.0) / z.shape[1]
        t = torch.exp(self.p_log_t.clamp(math.log(P_TMIN), math.log(P_TMAX)))
        ps = torch.softmax(-d / t, dim=1)
        if not self.p_hard_now:
            return ps, ps
        hard = F.one_hot(ps.argmax(1), ps.shape[1]).to(ps.dtype)
        return hard + ps - ps.detach(), ps

    def bottleneck(self, p):
        if self.emb_kind == 'pool':
            return p
        if self.emb_kind == 'proto':
            return self.proto_probs(p)[0]
        z = self.bneck(p)
        if self.emb_kind == 'relu':
            return F.relu(z)
        if self.emb_kind == 'topk':
            return topk_relu(z, self.topk_now)
        return sparsemax(z * torch.exp(self.smx_log_scale))

    def head_input(self, e, S):
        # точка симплекса (sparsemax, буквы) — в масштаб O(1): иначе голова видит отклонения ~1/K и BCE почти не учит горло
        x = e * self.emb_dim if self.emb_kind in ('sparsemax', 'proto') else e
        if self.side_cols:
            x = torch.cat([x, (S[:, list(self.side_cols)] - self.side_mu) / self.side_sd], dim=1)
        return x

    def head_list(self):
        return list(self.heads) if hasattr(self, 'heads') else [self.head]

    def forward(self, x, S=None, return_p=False):
        """logit (n, голов) у 'cls'; logit блоков (n, L / blk_size) у 'blk'. return_p — у «букв» ещё мягкое P."""
        h = self.conv_maps(x)
        if self.task == 'blk':
            return self.pos_head(h)[:, 0, :] @ self.blk_avg
        p = self.pooled(h)
        if self.emb_kind == 'proto':
            e, ps = self.proto_probs(p)
        else:
            e, ps = self.bottleneck(p), None
        f = self.head_input(e, S)
        out = torch.cat([hd(f) for hd in self.head_list()], dim=1)
        return (out, ps) if return_p else out

    def train(self, mode=True):
        """Замороженный ствол (freeze) и в обучении работает без dropout: признаки — как у исходной модели."""
        super().train(mode)
        if self.cfg.get('freeze'):
            self.blocks.eval()
        return self

    def window_only(self):
        """Боковые входы — только знаменатель окна: скрытый слой головы — функция одного окна (годится в токен)."""
        return not self.side_cols or set(self.side_cols) <= set(DEN)

    def taps(self, x, S=None):
        """Отводы эмбеддинга: {'pool', 'bneck', 'head' / 'heads'} — те, что не длиннее EMB_MAX; у «букв» bneck — вектор
           вероятностей P (у p_hard — one-hot, мягкое P — 'psoft')."""
        h = self.conv_maps(x)
        p = self.pooled(h)
        out = {}
        if p.shape[1] <= EMB_MAX and not self.cfg.get('freeze'):     # у замороженного ствола пулинг = пулинг источника
            out['pool'] = p
        if self.emb_kind == 'proto':
            e, ps = self.proto_probs(p)
            if self.p_hard_now:                          # у буквы one-hot рядом — мягкое P той же модели
                out['psoft'] = ps
        else:
            e = self.bottleneck(p)
        if self.emb_kind != 'pool':
            out['bneck'] = e
        if self.task == 'cls' and len(self.cfg['head']) and self.window_only():
            f = self.head_input(e, S)
            hid = torch.cat([hd[:-1](f) for hd in self.head_list()], dim=1)
            if hid.shape[1] <= EMB_MAX:
                out['heads' if hasattr(self, 'heads') else 'head'] = hid
        return out


def init_stats(model, Xs, Ss):
    """Масштабы входа по окнам FIT на старте — как build_model / set_lvl_stats / set_side_stats у CNNBase."""
    with torch.no_grad():
        Xp = Xs[:, :Xs.shape[1] - model.n_level] if model.n_level else Xs
        model.s_sd.fill_(float((Xp[..., 1:] - Xp[..., :-1]).std()))
        if model.n_level:
            V = Xs[:50000, -model.n_level:, 1:].transpose(0, 1).reshape(model.n_level, -1)
            mu, sd = V.mean(1), V.std(1).clamp_min(1e-6)
            for j, sg in enumerate(model.lvl_signed):
                if sg:                                   # знаковый уровень — без сдвига (зеркальный бар — зеркальный вход)
                    mu[j], sd[j] = 0.0, V[j].pow(2).mean().sqrt().clamp_min(1e-6)
            model.lvl_mu.copy_(mu)
            model.lvl_sd.copy_(sd)
        if model.side_cols:
            Z = Ss[:, list(model.side_cols)]
            model.side_mu.copy_(Z.mean(0))
            model.side_sd.copy_(smc.side_sd(Z, model.side_cols))


