def done_run(name, seed_key):
    """Прогон уже посчитан (json этой версии; у обучаемых — с той же конфигурацией)."""
    p = EMB_DIR + f"emb_{run_tag(name, seed_key)}.json"
    if FORCE or not os.path.isfile(p):
        return None
    try:
        with open(p, encoding='utf-8') as fh:
            r = json.load(fh)
    except Exception:
        return None
    if r.get('ver') != EMB_VER:
        return None
    # прогоны прошлой версии кода — с пропущенными новыми ключами (умолчания): их конфигурация та же, пересчёта нет
    if name in CANDS and json.dumps(smc._jsonable(norm_cfg(r['cfg'])), sort_keys=True) != json.dumps(
            smc._jsonable(make_cfg(name)), sort_keys=True):
        print(f"⚠️ {run_tag(name, seed_key)}: конфигурация в json другая — пересчёт")
        return None
    return r


def run_job(job, items):
    t0 = time.time()
    done = []
    print(f"\n👷 ЗАДАНИЕ {job}: {len(items)} прогонов — " + ", ".join(f"{n}/{s}" for n, s in items))
    for i, (name, seed_key) in enumerate(items, 1):
        print(f"\n▶️ [{i}/{len(items)}] {run_tag(name, seed_key)} | {(time.time() - t0) / 60:.0f} мин от начала")
        r = done_run(name, seed_key)
        if r is not None:
            print(f"⏭️ уже посчитан ({r.get('when')}) — пропуск (FORCE = True — пересчитать)")
            done.append(r)
            continue
        try:
            done.append(import_one(name, seed_key) if name in IMPORTS else train_one(name, seed_key, job=job))
        except Exception as e:
            print(f"\n🍆 АЙ, ОШИБКА! {run_tag(name, seed_key)}: {type(e).__name__}: {e}")
            traceback.print_exc(file=sys.stdout)
        gc.collect()
        if DEVICE.type == 'cuda':
            torch.cuda.empty_cache()
    print(f"\n👑 ЗАДАНИЕ {job}: {len(done)} из {len(items)} прогонов | {(time.time() - t0) / 60:.0f} мин")
    for r in done:
        own = " ".join(f"{k} {v['auc']:.4f}" for k, v in r['val'].items())
        dims = ", ".join(f"{k} {v['dim']}" for k, v in r['taps'].items())
        print(f"   {r['tag']:<18} VAL {own} | отводы {dims}")
    return done


