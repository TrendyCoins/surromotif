def load_emb(tag, device=None):
    """Модель-эмбеддинг из прогона: (EmbNet в режиме eval, json прогона). tag — 'N_rev_L64_a' и т. п."""
    with open(EMB_DIR + f"emb_{tag}.json", encoding='utf-8') as fh:
        meta = json.load(fh)
    if meta.get('ver') != EMB_VER:
        raise ValueError(f"🍆 АЙ, ОШИБКА! прогон {tag} версии {meta.get('ver')}, код — {EMB_VER}")
    model = EmbNet(meta['cfg'], meta['n_chan'], meta['n_level']).to(device or DEVICE)
    d = np.load(EMB_DIR + f"emb_{tag}.npz")
    model.load_state_dict({k[3:]: torch.from_numpy(d[k]) for k in d.files if k.startswith('sd_')}, strict=True)
    model.topk_now = model.cfg['topk']
    model.eval()
    return model, meta


@torch.no_grad()
def embed(model, data, starts, taps=None, bs=16384):
    """Эмбеддинги окон с началом starts (позиции в data; окна обязаны быть целыми): {отвод: (n, D) float32,
       'orient': (n,) ±1 — знак ориентации формы (−1: ствол видел окно перевёрнутым; правило ничьей v6.0)}.
       Нормы отвода по FIT — в npz прогона (fmu_<отвод>, fsd_<отвод>)."""
    starts = np.asarray(starts, np.int64)
    floor_t = data.windows(L)['floor_t']
    was = model.training
    model.eval()
    out = {}
    for i in range(0, len(starts), bs):
        st = torch.from_numpy(starts[i:i + bs]).to(DEVICE)
        sid = torch.from_numpy(data.sid[starts[i:i + bs]].astype(np.int64)).to(DEVICE)
        W = data.gw(st, L)
        if not torch.isfinite(W).all():
            raise ValueError("🍆 АЙ, ОШИБКА! среди окон есть окно с дырой (NaN) — берите начала из data.windows(64)['st']")
        fl = floor_t[sid]
        tp = model.taps(shapes(W, fl, model.orient), side_for(model.side_cols, data, st, W, fl))
        for k, v in tp.items():
            if taps is None or k in taps:
                out.setdefault(k, []).append(v.float().cpu())
        out.setdefault('orient', []).append(smc.orient_sign(W, fl).cpu())
    model.train(was)
    return {k: torch.cat(v).numpy() for k, v in out.items()}


def load_raw_bars(data):
    """Сырые OHLC по позициям data (float64, на прокладках NaN) и pc — close бара перед позицией (у первого бара части —
       последний из 200 баров перед частью)."""
    n = len(data.r)
    raw = {k: np.full(n, np.nan) for k in ('o', 'h', 'l', 'c', 'pc')}
    for s in data.series:
        bx = np.load(smc.data_path(f"smc_bars_{s['asset']}_{data.tf}_N{data.N}.npz"))
        for key in ('tr', 'va'):
            o_, m = s['off'][key], s['n'][key]
            for k in ('o', 'h', 'l', 'c'):
                raw[k][o_:o_ + m] = bx[f'{k}_{key}']
            raw['pc'][o_:o_ + m] = np.concatenate([bx[f'pre_c_{key}'][-1:], bx[f'c_{key}'][:-1]])
    return raw


def window_geometry(raw, starts):
    """Сырьё для скаляров токена (логарифм цены): начало — close перед окном (точка отсчёта пути окна), конец — close
       последнего бара, верх / низ — max high / min low баров окна. Линейка U и опорная цена — забота ноутбука SMT."""
    starts = np.asarray(starts, np.int64)
    idx = starts[:, None] + np.arange(L)[None, :]
    return {'start': np.log(raw['pc'][starts]), 'end': np.log(raw['c'][starts + L - 1]),
            'top': np.log(raw['h'][idx].max(1)), 'bottom': np.log(raw['l'][idx].min(1))}


