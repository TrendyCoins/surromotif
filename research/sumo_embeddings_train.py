def cfg_from_classifier(c, spec):
    """Конфигурация EmbNet по json прогона CNN классификатора (только то, что EmbNet повторяет бит в бит)."""
    ok = (c.get('arch') == 'cnn' and not c.get('cnn_bn') and not c.get('cnn_res') and not c.get('cnn_sdrop')
          and not c.get('cnn_valid') and c.get('cnn_bias', True) and not c.get('cnn_ma') and not c.get('cnn_pyr')
          and not c.get('cnn_chan') and not c.get('lvl_log') and c.get('cnn_in', 'steps') == 'steps'
          and c.get('cnn_pool', 'mml') in ('mml', 'mm') and c.get('price') in smc.MULTI_KINDS)
    if not ok:
        raise ValueError("🍆 АЙ, ОШИБКА! этот прогон классификатора EmbNet не повторяет (bn / res / valid / пирамида …)")
    return norm_cfg({'price': c['price'], 'side': c.get('side'), 'ch': c['cnn_ch'], 'k': c['cnn_k'],
                     'dil': tuple(c['cnn_dil']), 'sep': bool(c.get('cnn_sep')), 'sep_fix': False,
                     'cdrop': c.get('cnn_cdrop', 0.0),
                     'pool': c.get('cnn_pool', 'mml'), 'head': tuple(c.get('head_hidden') or ()),
                     'hdrop': c.get('dropout', 0.0), 'nulls': (spec,), 'batch': c['batch'], 'lr': c['lr'],
                     'wd': c['wd'], 'epochs': c['epochs'], 'patience': c['patience'], 'trim_q': c['trim_q']})


def import_one(name, seed_key, n_cmp=8192):
    """Готовый прогон классификатора -> прогон эмбеддинга: те же веса в EmbNet; logit EmbNet обязан совпасть с CNNBase
       бит в бит (у NT1_0 — заодно проверка быстрого пути знаменателя), AUC VAL — с json прогона."""
    t_run = time.time()
    src = IMPORTS[name]
    cnn, r = smc.load_finalist(src, seed_key, L)
    cfg = cfg_from_classifier(r['cfg'], r['spec'])
    print(f"\n\n{'#' * 78}\n# SME v{EMB_VER} | импорт {r['tag']} -> {run_tag(name, seed_key)} | {DEVICE}\n"
          f"# {cfg_line(cfg)}\n{'#' * 78}")
    n_level = smc.N_LEVEL.get(cfg['price'], 0)
    model = EmbNet(cfg, smc.N_PATH + n_level, n_level).to(DEVICE)
    model.load_state_dict(cnn.state_dict(), strict=True)
    model.eval()
    data, P = get_data(cfg['price']), get_store(cfg['price']).positives('tune')
    n = min(n_cmp, len(P['W']))
    with torch.no_grad():
        W, st, fl = P['W'][:n], P['st_t'][:n], P['fl'][:n]
        lc = cnn(smc.to_shapes(W, fl), smc.side_feats(data, st, L, W, fl))[0].float().cpu().numpy()
    le = score(model, data, W, st, fl)[:, 0]
    dmax = float(np.max(np.abs(le - lc)))
    print(f"   {'✅' if dmax <= LOGIT_TOL else '❌'} logit EmbNet против CNNBase на {n} окнах TUNE: max |Δ| {dmax:.1e}")
    if dmax > LOGIT_TOL:
        raise RuntimeError("🍆 АЙ, ОШИБКА! EmbNet не повторяет CNNBase — импорт остановлен")
    info = {'kind': 'imported', 'source': r['tag'], 'best_ep': r['best_ep'], 'epochs_run': r.get('epochs_run'),
            'hist': [], 'src_auc': {'tune': r['tune']['auc'], 'val': r['val']['auc']}}
    res = finish(model, name, seed_key, info, t_run)
    d_v = res['val'][r['spec']]['auc'] - r['val']['auc']
    print(f"   {'✅' if abs(d_v) < 2e-4 else '❌'} AUC VAL против {r['spec']}: {res['val'][r['spec']]['auc']:.4f}, в json "
          f"прогона {r['val']['auc']:.4f}")
    return res


