def _cka_prep(E):
    """Эмбеддинг (n, D) -> стандартизованные по координате столбцы без мёртвых (трансформер всё равно стандартизует)."""
    E = np.asarray(E, np.float64)
    E = E - E.mean(0)
    sd = E.std(0)
    keep = sd > 1e-8
    return E[:, keep] / sd[keep]


def cka(A, B, na=None, nb=None):
    """Линейная CKA (Kornblith et al. 2019) двух подготовленных матриц: 1 — одно и то же представление с точностью до
       поворота и масштаба; около 0 — ничего общего. na, nb — готовые ||AᵀA||, ||BᵀB|| (Фробениус)."""
    na = np.linalg.norm(A.T @ A) if na is None else na
    nb = np.linalg.norm(B.T @ B) if nb is None else nb
    return float(np.linalg.norm(A.T @ B) ** 2 / (na * nb))


