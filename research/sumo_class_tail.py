def variant_keys():
    """Имена вариантов окна — в порядке счёта и в кэше."""
    keys = ['sp', 's4'] + [f"t{h}" for h in TAIL['tails'] + TAIL['tails_ref']]
    keys += [f"j{h}m{m}" for h, m in TAIL['joint']]
    return keys + ['c0'] + [f"c{h}" for h in TAIL['ctrl_tails']]


def tail_signs(n, L, h, m=None, base=None):
    """Знаки окна с перевёрнутым хвостом. Хвост — последние h баров окна, столбцы L + 1 − h … L: их знаки умножаются на −1.
       m — переворачиваются только первые m баров хвоста («стык»). base — знаки, с которых начинаем (у контроля — близнец
       sflip1); без base — реальное окно, все +1."""
    if not 1 <= h <= L or (m is not None and not 1 <= m <= h):
        raise ValueError(f"🍆 АЙ, ОШИБКА! хвост h = {h}, m = {m} при окне L = {L}")
    S = np.ones((n, L + 1), dtype=np.float32) if base is None else np.array(base, dtype=np.float32, copy=True)
    a = L + 1 - h
    S[:, a:(L + 1 if m is None else a + m)] *= -1.0
    return S


def signs_of(key, n, L, sg4, sg1):
    """Знаки варианта key (кроме 'sp' — реальное окно считается без переворота). sg4, sg1 — знаки суррогата линейки и близнеца
       контроля этой части (те же, что у наборов проверки пула)."""
    if key == 's4':
        return np.asarray(sg4, dtype=np.float32)
    if key == 'c0':
        return np.asarray(sg1, dtype=np.float32)
    kind, rest = key[0], key[1:]
    if kind == 't':
        return tail_signs(n, L, int(rest))
    if kind == 'j':
        h, m = rest.split('m')
        return tail_signs(n, L, int(h), m=int(m))
    if kind == 'c':
        return tail_signs(n, L, int(rest), base=sg1)
    raise ValueError(f"🍆 АЙ, ОШИБКА! вариант окна '{key}'")


