def stand_world(kind, seed):
    """Мир стенда — шаги цены ассетов: 'coin' — независимые; 'saw' — AR(1) с φ < 0 (после шага чаще шаг против него);
       'regime' — куски «пилы» и монетки вперемежку."""
    rng = np.random.default_rng(seed)
    n, out = STAND['bars'], {}
    for i in range(STAND['assets']):
        if kind == 'coin':
            phi = np.zeros(n)
        elif kind == 'saw':
            phi = np.full(n, STAND['phi'])
        else:
            on = (np.arange(n) // STAND['reg_len'] + i) % 2 == 0
            phi = np.where(on, STAND['phi'], 0.0)
        eps = rng.normal(size=n)
        x = np.empty(n)
        x[0] = eps[0]
        for t in range(1, n):
            x[t] = phi[t] * x[t - 1] + math.sqrt(1.0 - phi[t] ** 2) * eps[t]
        out[f"S{i}USDT"] = x
    return out


def proxy_logit(Wv):
    """Заменитель модели на стенде — «пила» окна: минус сумма произведений соседних шагов в долях суммы квадратов. Переворот
       хвоста меняет в ней одно слагаемое — на стыке; у «стыка» — два."""
    return -8.0 * (Wv[:, 1:] * Wv[:, :-1]).sum(1) / (Wv * Wv).sum(1)


def stand_block_signs(rng, n, L, b):
    """Знаки блоками по b баров со случайной фазой, (n, L + 1) — суррогат sflip4 стенда (свой генератор)."""
    phase = rng.integers(0, b, size=(n, 1))
    idx = (np.arange(L + 1)[None, :] + phase) // b
    s = np.where(rng.random((n, (L + b) // b + 1)) < 0.5, -1.0, 1.0)
    return np.take_along_axis(s, idx, axis=1).astype(np.float32)


def stand_cache(world, seed):
    """Кэш 'score' мира стенда — тем же форматом и теми же знаками вариантов (signs_of), что у настоящего; «модели» — два
       «сида» заменителя с малым независимым шумом."""
    L, rng, tags = 64, np.random.default_rng(1000 + seed), ['stand_a', 'stand_b']
    t0, res = pd.Timestamp(STAND['t0']).value, {}
    for a, x in world.items():
        n = len(x) - L + 1
        st = np.arange(n, dtype=np.int64)
        W = x[st[:, None] + np.arange(L)[None, :]]
        t = t0 + (st + L - 1) * STAND['step_ns']
        sg4 = stand_block_signs(rng, n, L, 4)
        sg1 = np.where(rng.random((n, L + 1)) < 0.5, -1.0, 1.0).astype(np.float32)
        r = {'st': st, 't': t, 'wk': t // WEEK_NS,
             'mv': np.stack([W[:, L - h:].sum(1) for h in TAIL['tails']], axis=1).astype(np.float32),
             'pv': np.stack([W[:, L - 2 * h:L - h].sum(1) for h in TAIL['tails']], axis=1).astype(np.float32)}
        for key in variant_keys():
            S = np.ones((n, L + 1), dtype=np.float32) if key == 'sp' else signs_of(key, n, L, sg4, sg1)
            lg = proxy_logit(W * S[:, 1:])
            for tag in tags:
                r[f"{tag}__{key}"] = (lg + rng.normal(0.0, STAND['seed_noise'], n)).astype(np.float32)
        res[a] = r
    meta = {**cache_cfg(), 'tf': 'stand', 'part': 'tune', 'tags': tags, 'items': [{'tag': t_, 'src': 'search'} for t_ in tags]}
    return {'meta': meta, 'res': res}


def world_result(kind, seed):
    return eval_frame(build_frame(stand_cache(stand_world(kind, seed), seed), 'search'))


