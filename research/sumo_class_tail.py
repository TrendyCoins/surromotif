def enough(n, weeks):
    """Группе хватает данных для ошибки по неделям: мало окон или недель — ошибка занижена, t не считается."""
    return n >= TAIL['min_n'] and weeks >= TAIL['min_weeks']


def cl_mean(y, g, G):
    """Среднее y и его ошибка по кластерам. g — номер кластера строки (0 … G − 1): неделя календаря, все ассеты недели — один
       кластер. Возвращает (среднее, ошибка, строк, кластеров со строками); у малой группы (enough) ошибки нет."""
    y = np.asarray(y, dtype=np.float64)
    n = len(y)
    if n == 0:
        return math.nan, math.nan, 0, 0
    m = float(y.mean())
    s = np.bincount(g, weights=y - m, minlength=G)
    Gn = int((np.bincount(g, minlength=G) > 0).sum())
    if not enough(n, Gn):
        return m, math.nan, n, Gn
    return m, float(math.sqrt(Gn / (Gn - 1) * float(np.sum(s * s))) / n), n, Gn


def cl_diff(y, g, G, m1, m2):
    """Разность средних y в группах m1 и m2 (маски строк) и её ошибка по тем же кластерам: неделя входит в обе группы разом,
       общий сдвиг недели в разности сокращается."""
    y = np.asarray(y, dtype=np.float64)
    n1, n2 = int(m1.sum()), int(m2.sum())
    if n1 == 0 or n2 == 0:
        return math.nan, math.nan
    a, b = float(y[m1].mean()), float(y[m2].mean())
    w1, w2 = np.bincount(g[m1], minlength=G), np.bincount(g[m2], minlength=G)
    if not (enough(n1, int((w1 > 0).sum())) and enough(n2, int((w2 > 0).sum()))):
        return a - b, math.nan
    s = np.bincount(g[m1], weights=(y[m1] - a) / n1, minlength=G) - np.bincount(g[m2], weights=(y[m2] - b) / n2, minlength=G)
    Gn = int(((w1 + w2) > 0).sum())
    return a - b, float(math.sqrt(Gn / (Gn - 1) * float(np.sum(s * s))))


def _t(est, se, null=0.0):
    return (est - null) / se if se is not None and np.isfinite(se) and se > 0 else math.nan


def acc_of(a, g, G):
    """Доля окон с a > 0 (ничьи — пополам), её ошибка по неделям и t против 50%."""
    m, se, n, Gn = cl_mean((a > 0) + 0.5 * (a == 0), g, G)
    return {'n': n, 'acc': m, 'se': se, 't': _t(m, se, 0.5), 'weeks': Gn}


def prev_window(st, h):
    """Номер окна того же ряда, которое кончается на h баров раньше, или −1: такого окна нет (начало части или между окнами
       пропуск баров). st — начала окон ассета по возрастанию."""
    st = np.asarray(st, dtype=np.int64)
    i = np.arange(len(st)) - h
    ok = i >= 0
    ok[ok] = st[i[ok]] == st[ok] - h
    return np.where(ok, i, -1)


def basket_of(lm):
    """Корзина цвета по log M линии сайта (пороги 1.25 и 3, как в Anat): 0 — глубокий серый (сторона монетки, M ≥ 3), 1 — серый
       (1.25 … 3), 2 — серебро (M < 1.25 с любой стороны), 3 — оранжевый (сторона реала, 1.25 … 3), 4 — глубокий оранжевый
       (M ≥ 3); −1 — показания нет (NaN). Стороны: серый — корзины 0 и 1, серебро — 2, оранжевый — 3 и 4."""
    lm = np.asarray(lm, dtype=np.float64)
    a, b = math.log(TAIL['mark']), math.log(TAIL['strong'])
    out = np.full(lm.shape, -1, dtype=np.int8)
    ok = np.isfinite(lm)
    x = lm[ok]
    out[ok] = np.where(x <= -b, 0, np.where(x <= -a, 1, np.where(x < a, 2, np.where(x < b, 3, 4))))
    return out


def rule_stat(a, mv, pv, g, G):
    """Правило отката того же масштаба: «хвост пойдёт против хода h баров перед ним» — справочно. Окна с нулевым ходом хвоста
       или куска перед ним и с a = 0 не берутся. Модель «называет» сторону хвоста верно, когда a > 0; с правилом она согласна,
       когда оба правы или оба неправы; при несогласии прав ровно один."""
    ok = (mv != 0) & (pv != 0) & (a != 0)
    right = np.sign(mv[ok]) == -np.sign(pv[ok])
    model = a[ok] > 0
    agree = model == right
    gg = g[ok]
    r, ag, md = cl_mean(right, gg, G), cl_mean(agree, gg, G), cl_mean(model, gg, G)
    dis = cl_mean(model[~agree], gg[~agree], G)
    return {'n': int(ok.sum()), 'rule': r[0], 'rule_se': r[1], 'model': md[0], 'model_se': md[1], 'agree': ag[0],
            'dis_n': dis[2], 'dis_model': dis[0], 'dis_se': dis[1], 'dis_t': _t(dis[0], dis[1], 0.5)}


def seed_stat(s, n):
    """Согласие сидов: доля у каждого сида отдельно; у первых двух — доля окон с одним знаком a_h и корреляция их a_h."""
    N, sx, sy, sxx, syy, sxy = (float(v) for v in s['sums'])
    out = {'acc': [float(v) / n for v in s['pos']], 'same': math.nan, 'corr': math.nan}
    if N > 0:
        vx, vy = sxx - sx * sx / N, syy - sy * sy / N
        out['same'] = float(s['same']) / N
        out['corr'] = (sxy - sx * sy / N) / math.sqrt(vx * vy) if vx > 0 and vy > 0 else math.nan
    return out


def build_frame(C, src):
    """Строки источника — все окна части у всех ассетов кэша C. logit — средний по сидам источника; линейка — квантили logit
       суррогатов sflip4 источника (как у продукта); линия M — по окнам ассета подряд (формула сайта, FL.line_m). Столбцы:
       a{h} — logit настоящего окна минус окна с зеркальным хвостом h (и у справочных длинных хвостов); bk{h} — корзина цвета
       окна, которое кончается на h баров раньше, то есть перед хвостом (−1 — показания нет); mv{h}, pv{h} — ход close хвоста и
       такого же куска перед ним; j{h}m{m} — то же, что a, для «стыка»; c{h} — контроль: близнец минус близнец с перевёрнутым
       хвостом; ia — номер ассета, qt — квартал конца окна, sp — logit настоящего окна. g — номер недели строки, G — недель.
       dz — те же падения в единицах линейки: средний z настоящего окна минус z варианта; 'gap' — минус z суррогата sflip4
       (разрыв «реал − суррогат», он же MRI без линии)."""
    tags = [it['tag'] for it in C['meta']['items'] if it['src'] == src]
    res = C['res']
    assets = [a for a in res if tags and all(f"{t}__sp" in res[a] for t in tags)]
    if not assets:
        return None

    def avg(a, key):
        return np.mean([res[a][f"{t}__{key}"].astype(np.float64) for t in tags], axis=0)

    q, zk = FL.ruler(np.concatenate([avg(a, 's4') for a in assets]))
    tails, cols, dz, n_all = TAIL['tails'], {}, {}, 0
    seeds = {h: {'pos': np.zeros(len(tags)), 'same': 0.0, 'sums': np.zeros(6)} for h in tails}

    def put(k, v):
        cols.setdefault(k, []).append(v)

    for ia, a in enumerate(assets):
        r = res[a]
        sp = avg(a, 'sp')
        z = FL.to_z(sp, q, zk)
        lm = FL.line_m(z)
        st = r['st'].astype(np.int64)
        n_all += len(sp)

        def drop(col, key):
            """Вариант key: падение logit — столбцом col, падение z — в сумму."""
            v = avg(a, key)
            put(col, (sp - v).astype(np.float32))
            dz[col] = dz.get(col, 0.0) + float((z - FL.to_z(v, q, zk)).sum())

        dz['gap'] = dz.get('gap', 0.0) + float((z - FL.to_z(avg(a, 's4'), q, zk)).sum())
        put('ia', np.full(len(sp), ia, dtype=np.int16))
        put('wk', r['wk'].astype(np.int64))
        put('qt', (r['t'].astype('datetime64[ns]').astype('datetime64[M]').astype(np.int64) // 3).astype(np.int32))
        put('sp', sp.astype(np.float32))
        for j, h in enumerate(tails):
            drop(f"a{h}", f"t{h}")
            p = prev_window(st, h)
            put(f"bk{h}", basket_of(np.where(p >= 0, lm[np.maximum(p, 0)], np.nan)))
            put(f"mv{h}", r['mv'][:, j].astype(np.float32))
            put(f"pv{h}", r['pv'][:, j].astype(np.float32))
            d = [r[f"{t}__sp"].astype(np.float64) - r[f"{t}__t{h}"].astype(np.float64) for t in tags]
            seeds[h]['pos'] += [float((x > 0).sum() + 0.5 * (x == 0).sum()) for x in d]
            if len(d) >= 2:
                x, y = d[0], d[1]
                seeds[h]['same'] += float(((x > 0) == (y > 0)).sum())
                seeds[h]['sums'] += [len(x), x.sum(), y.sum(), (x * x).sum(), (y * y).sum(), (x * y).sum()]
        for h in TAIL['tails_ref']:
            drop(f"a{h}", f"t{h}")
        for h, m in TAIL['joint']:
            drop(f"j{h}m{m}", f"j{h}m{m}")
        c0 = avg(a, 'c0')
        for h in TAIL['ctrl_tails']:
            put(f"c{h}", (c0 - avg(a, f"c{h}")).astype(np.float32))
    cols = {k: np.concatenate(v) for k, v in cols.items()}
    wk_u, g = np.unique(cols.pop('wk'), return_inverse=True)
    return {'src': src, 'tags': tags, 'assets': assets, 'cols': cols, 'g': g.astype(np.int64), 'G': int(len(wk_u)),
            'seeds': seeds, 'dz': {k: v / n_all for k, v in dz.items()}}


def eval_frame(F):
    """Все числа источника по строкам build_frame — разделы (1)–(6) шапки."""
    c, g, G, names = F['cols'], F['g'], F['G'], F['assets']
    ia, n_as = c['ia'], len(names)
    sd_sp = float(np.std(c['sp'].astype(np.float64)))
    btc = ia == (names.index('BTCUSDT') if 'BTCUSDT' in names else -1)
    site = np.isin(ia, [i for i, a in enumerate(names) if a in TAIL['site']])
    _, qi = np.unique(c['qt'], return_inverse=True)
    gap = F['dz']['gap']
    out = {'tags': F['tags'], 'assets': n_as, 'n': int(len(ia)), 'weeks': G, 'sd_sp': sd_sp, 'gap_z': gap,
           'tails': {}, 'ref': {}, 'joint': {}, 'ctrl': {}}

    def drop(col):
        """Доля и среднее падение от переворота: в logit и в единицах линейки (z; и долей разрыва «реал − суррогат»)."""
        a = c[col].astype(np.float64)
        x = acc_of(a, g, G)
        m, se, _, _ = cl_mean(a, g, G)
        x.update({'dlogit': m, 'dlogit_se': se, 'dz': F['dz'][col], 'dz_gap': F['dz'][col] / gap if gap > 0.05 else math.nan})
        return x

    for h in TAIL['tails']:
        a = c[f"a{h}"].astype(np.float64)
        y = (a > 0) + 0.5 * (a == 0)
        x = drop(f"a{h}")
        top = np.abs(a) >= np.quantile(np.abs(a), 1 - TAIL['top'])
        x['top'] = acc_of(a[top], g[top], G)
        mv = np.abs(c[f"mv{h}"])
        big = mv >= np.quantile(mv, 1 - TAIL['big'])
        x['big'] = acc_of(a[big], g[big], G)
        bk = c[f"bk{h}"]
        masks = {name: np.isin(bk, ks) for name, ks, _ in SIDES}
        x['sides'] = {name: acc_of(a[mk], g[mk], G) for name, mk in masks.items()}
        x['baskets'] = [acc_of(a[bk == k], g[bk == k], G) for k in range(5)]
        x['no_line'] = int((bk < 0).sum())
        d, dse = cl_diff(y, g, G, masks['orange'], masks['grey'])
        x['orange_grey'] = {'d': d, 'se': dse, 't': _t(d, dse)}
        x['rule'] = rule_stat(a, c[f"mv{h}"], c[f"pv{h}"], g, G)
        pa = np.bincount(ia, weights=y, minlength=n_as) / np.maximum(np.bincount(ia, minlength=n_as), 1)
        x['assets'] = {'btc': acc_of(a[btc], g[btc], G), 'site': acc_of(a[site], g[site], G), 'min': float(pa.min()),
                       'med': float(np.median(pa)), 'max': float(pa.max()), 'above': int((pa > 0.5).sum()), 'of': n_as}
        pq = np.bincount(qi, weights=y) / np.bincount(qi)
        x['quarters'] = {'acc': pq.tolist(), 'above': int((pq > 0.5).sum()), 'of': int(len(pq))}
        x['seeds'] = seed_stat(F['seeds'][h], len(a))
        out['tails'][h] = x
    for h in TAIL['tails_ref']:
        out['ref'][h] = drop(f"a{h}")
    for h, m in TAIL['joint']:
        x = drop(f"j{h}m{m}")
        whole = out['tails'].get(h) or out['ref'].get(h)
        x['ratio'] = x['dlogit'] / whole['dlogit'] if whole and whole['dlogit'] else math.nan
        out['joint'][f"{h}m{m}"] = x
    for h in TAIL['ctrl_tails']:
        out['ctrl'][h] = acc_of(c[f"c{h}"].astype(np.float64), g, G)
    return out


