def tail_anatomy(W, Wn, L, h, m=None):
    """Сверка (в): окно с перевёрнутым куском [L − h, L − h + m) (m не задан — весь хвост) против реального, оба (n, 4, L).
       close — вне куска бит в бит, в куске с минусом; ширина бара — бит в бит; средние цены (каналы 1, 2) — вне куска бит в
       бит, внутри него после первого бара с минусом (первый бар куска и первый бар за ним стоят на швах — там своя
       арифметика: шаг средней цены берёт знак своего бара и знак бара перед ним)."""
    import torch
    a = L - h
    b = L if m is None else a + m
    eq = torch.equal
    ok = eq(Wn[:, 0, :a], W[:, 0, :a]) and eq(Wn[:, 0, a:b], -W[:, 0, a:b]) and eq(Wn[:, 0, b:], W[:, 0, b:])
    ok = ok and eq(Wn[:, 3], W[:, 3])
    ok = ok and eq(Wn[:, 1:3, :a], W[:, 1:3, :a]) and eq(Wn[:, 1:3, a + 1:b], -W[:, 1:3, a + 1:b])
    return bool(ok and eq(Wn[:, 1:3, b + 1:], W[:, 1:3, b + 1:]))


def check_first(T, data, store, P, part, asset, sg4, sg1):
    """Сверки (а)–(в) на первом ассете части; не прошло — стоп: варианты окна не те, за кого себя выдают."""
    import torch
    L, W = T.POOL['L'], P['W']
    n = len(W)

    def flip(sg):
        return data.flip_multi(P['st_t'], L, torch.from_numpy(np.ascontiguousarray(sg, dtype=np.float32)).to(T.DEVICE), W)

    def inputs(Wn):
        return T.to_shapes(Wn, P['fl']), T.side_feats(data, P['st_t'], L, Wn, P['fl'])

    W1 = flip(np.ones((n, L + 1), dtype=np.float32))
    X1, S1 = inputs(W1)
    chk = {'asset': asset, 'part': part, 'n': n,
           'ones': bool(torch.equal(W1, W) and torch.equal(X1, P['X']) and torch.equal(S1, P['S'])), 'twins': {}}
    for spec, sg in ((TAIL['ruler_null'], sg4), (TAIL['ctrl_null'], sg1)):
        ev = store.get(part, spec)
        Xn, Sn = inputs(flip(sg))
        chk['twins'][spec] = bool(torch.equal(ev['Xn'], Xn) and torch.equal(ev['Sn'], Sn))
        store._set.clear()
    cuts = [(h, None) for h in TAIL['tails'] + TAIL['tails_ref']] + list(TAIL['joint'])
    chk['tail'] = all(tail_anatomy(W, flip(tail_signs(n, L, h, m)), L, h, m) for h, m in cuts)
    chk['ok'] = chk['ones'] and all(chk['twins'].values()) and chk['tail']
    print(f"   🔎 сверки на {asset} {part} ({n} окон): (а) знаки +1 — реальное окно бит в бит {'✅' if chk['ones'] else '❌'} | "
          f"(б) суррогаты = наборы проверки пула: " + ', '.join(f"{k} {'✅' if v else '❌'}" for k, v in chk['twins'].items())
          + f" | (в) анатомия хвоста ({len(cuts)} вариантов) {'✅' if chk['tail'] else '❌'}")
    if not chk['ok']:
        raise RuntimeError("🍆 АЙ, ОШИБКА! сверка (а) / (б) / (в) не прошла — варианты окна не те; стоп до разбора")
    return chk


def flow_ref(tf, part, fp):
    """Кэш Flow этой части для справочной сверки logit реальных окон: (кэш или None, почему нет)."""
    fc = FL.load_cache(tf, part)
    if fc is None:
        return None, 'кэша Flow нет'
    if fc['meta'].get('fp') != fp:
        return None, 'кэш Flow посчитан на других данных'
    return fc, ''


def flow_summary(diffs, note):
    """Итог справочной сверки с кэшем Flow: diffs — |Δ| logit реальных окон по ассетам."""
    if not diffs:
        return {'n': 0, 'note': note or 'общих окон и моделей нет'}
    d = np.concatenate(diffs)
    med, big = float(np.median(d)), float(np.mean(d > TAIL['chk_big']))
    return {'n': int(len(d)), 'med': med, 'max': float(d.max()), 'big': big, 'exact': bool(d.max() == 0.0),
            'ok': bool(med <= TAIL['chk_med'] and big <= TAIL['chk_share']), 'note': ''}


def score_part(T, pdata, tf, part, items, fp):
    """logit моделей items на окнах части part у всех ассетов, пол 0.2: реальное окно и его варианты (variant_keys). Плюс ход
       close хвоста (mv) и такого же куска перед ним (pv) в единицах нормировщика — столбцы по TAIL['tails']."""
    import torch
    L, data, tails = T.POOL['L'], pdata['data'], TAIL['tails']
    if 2 * max(tails) > L or max(TAIL['tails_ref'] + TAIL['ctrl_tails'] + tuple(h for h, _ in TAIL['joint'])) > L:
        raise ValueError(f"🍆 АЙ, ОШИБКА! хвосты длиннее окна L = {L} (у TAIL['tails'] — длиннее половины)")
    models = {it['tag']: T.load_pool_model(it['set'], it['seed'], FL.TF.model_name(), it['mode'])[0] for it in items}
    fc, note = flow_ref(tf, part, fp)
    res, chk, diffs, t1 = {}, None, [], time.time()
    with FL.CL.floor_override(data, L, TAIL['floor']):
        for a in pdata['assets']:
            store = T.pool_asset_store(data, L, pdata['sid'][a], pdata['t_cut'])
            n_all = int(len(store.w[part]))
            if n_all < FL.FLOW['min_windows']:
                print(f"   {a:<11} {part}: окон {n_all} < {FL.FLOW['min_windows']} — не считается")
                continue
            P = store.positives(part)
            n = int(len(P['st']))
            if n != n_all:
                raise RuntimeError(f"🍆 АЙ, ОШИБКА! {a} {part}: набор проверки взял подвыборку ({n} из {n_all}) — окна не "
                                   f"подряд, линия M не считается; подними DATA['max_eval'] кода обучения")
            W = P['W']
            if W.dim() != 3 or W.shape[1] != 4:
                raise ValueError(f"🍆 АЙ, ОШИБКА! окно модели — {tuple(W.shape)}, ждал (n, 4, L): close, HL/2, HLC/3, ширина")
            st = np.asarray(P['st'], dtype=np.int64)
            c = W[:, 0]
            r = {'st': st, 't': np.asarray(data.t[st + L - 1], dtype=np.int64), 'wk': np.asarray(P['wk'], dtype=np.int64),
                 'mv': torch.stack([c[:, L - h:].sum(1) for h in tails], dim=1).float().cpu().numpy(),
                 'pv': torch.stack([c[:, L - 2 * h:L - h].sum(1) for h in tails], dim=1).float().cpu().numpy()}
            sg4 = FL.twin_signs(T, part, n, L, TAIL['ruler_null']).numpy()
            sg1 = FL.twin_signs(T, part, n, L, TAIL['ctrl_null']).numpy()
            if chk is None:
                chk = check_first(T, data, store, P, part, a, sg4, sg1)
            for key in variant_keys():
                if key == 'sp':
                    X, S_ = P['X'], P['S']
                else:
                    sg = torch.from_numpy(signs_of(key, n, L, sg4, sg1)).to(T.DEVICE)
                    Wn = data.flip_multi(P['st_t'], L, sg, W)
                    X, S_ = T.to_shapes(Wn, P['fl']), T.side_feats(data, P['st_t'], L, Wn, P['fl'])
                    del Wn, sg
                for tag, model in models.items():
                    r[f"{tag}__{key}"] = np.asarray(T.score(model, X, S=S_)).astype(np.float32)
                del X, S_
            fr = fc['res'].get(a) if fc is not None else None
            if fr is not None and np.array_equal(fr['t'].astype(np.int64), r['t']):
                diffs += [np.abs(r[f"{tag}__sp"].astype(np.float64) - fr[f"{tag}__sp"].astype(np.float64))
                          for tag in models if f"{tag}__sp" in fr]
            res[a] = r
            store._pos.clear()
            store._set.clear()
            del P, W, c, store
            if T.DEVICE.type == 'cuda':
                torch.cuda.empty_cache()
            if len(res) == 1:
                print(f"   ⏱️ первый ассет ({a}, {n} окон, моделей {len(models)}, вариантов {len(variant_keys())}): "
                      f"{time.time() - t1:.0f} c — всего ~{(time.time() - t1) * len(pdata['assets']) / 60:.0f} мин", flush=True)
    return res, chk, flow_summary(diffs, note)


