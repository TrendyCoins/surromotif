def cache_path(tf, part):
    return OUT_DIR + f"cache/tail_{tf}_{part}_f{TAIL['floor']:g}.npz"


def cache_cfg():
    """Всё, от чего зависит содержимое кэша: при другом наборе вариантов кэш считается заново."""
    return {'ver': TAIL_VER, 'floor': TAIL['floor'], 'keys': variant_keys(), 'tails': list(TAIL['tails'])}


def load_cache(tf, part):
    p = cache_path(tf, part)
    if not os.path.isfile(p):
        return None
    with np.load(p) as d:
        meta = json.loads(str(d['meta']))
        if any(meta.get(k) != v for k, v in cache_cfg().items()):
            return None
        res = {}
        for k in d.files:
            if k == 'meta':
                continue
            a, rest = k.split('__', 1)
            res.setdefault(a, {})[rest] = d[k]
    return {'meta': meta, 'res': res}


def save_cache(tf, part, res, items, chk, flow, fp):
    os.makedirs(OUT_DIR + 'cache/', exist_ok=True)
    meta = {**cache_cfg(), 'tf': tf, 'part': part, 'tags': [it['tag'] for it in items], 'items': items, 'check': chk,
            'flow': flow, 'fp': fp, 'created': time.strftime('%Y-%m-%d %H:%M:%S')}
    arr = {'meta': np.array(json.dumps(_jsonable(meta), ensure_ascii=False))}
    for a, r in res.items():
        for k, v in r.items():
            arr[f"{a}__{k}"] = v
    np.savez(cache_path(tf, part), **arr)


