def halves(groups, assets, title):
    """Справочно: ΔR² сеть − HAR по полугодиям (по времени конца окна), среднее по сидам и ассетам; клетки < 500 окон — мимо."""
    print(f"\n   {title}, по полугодиям — ΔR² сеть − HAR (среднее по сидам; без ошибки, справочно):")
    for tkey, rs in groups.items():
        cells = {}
        for r in rs:
            x = run_arr(r)
            for part in ('tune', 'val'):
                for a in assets:
                    k_ = f"{a}__{part}__"
                    if k_ + 'y' not in x:
                        continue
                    lab = half_labels(x[k_ + 't'])
                    for hl in np.unique(lab):
                        m = lab == hl
                        if m.sum() < 500:
                            continue
                        y_, c_, h_ = x[k_ + 'y'][m], x[k_ + 'cnn'][m], x[k_ + 'har'][m]
                        cells.setdefault(str(hl), []).append(r2(y_, c_) - r2(y_, h_))
        print(f"   {tkey:<9} " + " | ".join(f"{hl} {np.mean(cells[hl]):+.4f}"
                                            for hl in sorted(cells, key=HALF_NAMES.index)))


def gate_eval(runs):
    """Ворота (0): у RULES['gate_target'] на BTC, на полном наборе сидов этапа 1, ΔR² TUNE (сеть − HAR) > −gate_se · SE."""
    rs = pick(runs, 'btc', BTC_MODEL, target=RULES['gate_target'])
    miss = seeds_missing(rs, 'btc')
    if miss:
        jobs = [j for j, (sc, s, rc_) in JOBS.items() if sc == 'btc' and s in miss and rc_ is None]
        return False, (f"🚦 ворота (0): у {RULES['gate_target']} на BTC нет сидов {', '.join(miss)} — сначала задания "
                       f"{', '.join(jobs)} (или POOL_FORCE = True — явно помеченное исключение)")
    a = smc.DATA['assets'][0]
    dt, st, n = seeds_delta(rs, [a], 'tune', 'cnn', 'har')
    ok = bool(np.isfinite(dt) and dt > -RULES['gate_se'] * st)
    return ok, (f"🚦 ворота (0), положительный контроль конвейера: {RULES['gate_target']} на BTC, сидов {n}: ΔR² TUNE сеть − HAR "
                f"{_fmt(dt, st)} — " + ("✅ открыты: пул можно запускать" if ok else
                                        "❌ закрыты: сеть хуже HAR больше чем на 2 SE — пул не запускать, сначала разбор"))


def stage1_gate():
    """Ворота (0) по прогонам в pred_dir() (перед запуском пула)."""
    return gate_eval(load_runs())


