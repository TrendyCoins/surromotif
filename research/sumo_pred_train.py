    on_floor = [f"y {100 * np.mean(yv <= lf):.3f}%"] + [f"{nm} {100 * np.mean(Fm[fin_y, i] <= lf):.3f}%"
                                                         for i, nm in enumerate(out['names']) if np.any(Fm[fin_y, i] <= lf)]
    per_asset = []                                     # ассеты, у которых y на полу хотя бы у 0.01% позиций
    for s in data.series:
        ya = np.concatenate([y[s['off'][k_]:s['off'][k_] + s['n'][k_]] for k_ in ('tr', 'va')])
        ya = ya[np.isfinite(ya)]
        if ya.size and np.mean(ya <= lf) >= 1e-4:
            per_asset.append(f"{s['asset']} {100 * np.mean(ya <= lf):.2f}%")
    print(f"🎯 таргет {tkey} ({TARGETS[tkey]['what']}): годен у {100 * fin_y.mean():.1f}% позиций | y: медиана "
          f"{np.median(yv):+.3f}, sd {yv.std():.3f}, p0.1 / p99.9 {np.percentile(yv, 0.1):+.2f} / {np.percentile(yv, 99.9):+.2f}"
          f" | на полу log {LOG_FLOOR:g}: {', '.join(on_floor)}"
          + (f" (y на полу >= 0.01% позиций: {', '.join(per_asset)})" if per_asset else "")
          + f" | HAR: {', '.join(out['names'])} | сверка баров с r ✅ (max отн. ошибка {err:.1e}) | {time.time() - t0:.0f} c")
    cache[tkey] = out
    return out


