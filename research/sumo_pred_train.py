_NPZ = {}


def load_runs(where=None):
    """Прогоны этой версии: {tag: json}."""
    d = where or pred_dir()
    out = {}
    if not os.path.isdir(d):
        return out
    for fn in sorted(os.listdir(d)):
        if not (fn.startswith('pred_') and fn.endswith('.json')):
            continue
        with open(d + fn, encoding='utf-8') as fh:
            r = json.load(fh)
        if r.get('ver') == PRED_VER and os.path.isfile(d + fn[:-5] + '.npz'):
            r['_dir'] = d
            out[r['tag']] = r
    return out


def pick(runs, scope, model, target=None, set_name=None, control=None, recipe=None):
    """Прогоны этапа scope с сетью model, набором set_name, контролем control и рецептом recipe (target None — все таргеты):
       чужие прогоны (другая сеть, набор, контроль, рецепт) в сводку не попадают."""
    return [r for r in runs.values() if r['scope'] == scope and r['model'] == model and r.get('set') == set_name
            and r.get('control') == control and r.get('recipe') == recipe and (target is None or r['target'] == target)]


def seeds_missing(rs, scope):
    """Сиды набора SEEDS_REQ[scope], которых нет среди прогонов rs (пусто — набор полный)."""
    have = {r['seed_key'] for r in rs}
    return [s for s in SEEDS_REQ[scope] if s not in have]


def by_target(rs):
    """Прогоны по таргетам в порядке TARGETS."""
    return {t: [r for r in rs if r['target'] == t] for t in TARGETS if any(r['target'] == t for r in rs)}


