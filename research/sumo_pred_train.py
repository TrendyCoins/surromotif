def har_names(tkey):
    """Признаки HAR варианта: log среднего диапазона за HAR_LAGS баров и та же величина таргета за прошлые H баров."""
    sp = TARGETS[tkey]
    names = [f'r{k}' for k in HAR_LAGS]
    if sp['kind'] == 'atr' and sp['H'] not in HAR_LAGS:
        names.append(f"r{sp['H']}")
    if sp['kind'] == 'cor':
        names.append(f"c{sp['H']}")
    return names


def _roll(x, n, how):
    """Статистика how по барам q − n + 1 … q для каждой позиции q (NaN, пока баров меньше n)."""
    return getattr(pd.Series(x).rolling(n, min_periods=n), how)().to_numpy()


def _at(x, idx):
    """x[idx], NaN за концом массива."""
    out = np.full(len(idx), np.nan)
    ok = idx < len(x)
    out[ok] = x[idx[ok]]
    return out


def _lg(x, norm):
    with np.errstate(invalid='ignore', divide='ignore'):
        return np.log(np.maximum(x / norm, LOG_FLOOR))


def part_targets(h, l, n_pre, fin, tkey):
    """Один кусок ряда: h, l — сырые high / low (float64) куска с n_pre (>= NH) барами перед ним; fin — r конечен на барах куска.
       Для каждого бара куска j (окно кончается на нём): таргет y, признаки HAR (m, k), годность таргета, norm (бары j − 199 … j)
       и нормировщик r бара j (медиана баров j − 200 … j − 1 — для сверки привязки баров к ряду)."""
    sp = TARGETS[tkey]
    H, m = sp['H'], len(h) - n_pre
    q = np.arange(n_pre, n_pre + m)                     # бар j куска — позиция q = n_pre + j расширенного ряда
    rng = h - l
    med = _roll(rng, NH, 'median')
    norm, norm_r = med[q], med[q - 1]                   # бары j − 199 … j; нормировщик r бара j — бары j − 200 … j − 1
    feats = [_roll(rng, k, 'mean')[q] for k in HAR_LAGS]
    if sp['kind'] == 'atr':
        mean_h = _roll(rng, H, 'mean')                  # в позиции q — бары q − H + 1 … q
        fut = _at(mean_h, q + H)                        # бары j + 1 … j + H
        if H not in HAR_LAGS:
            feats.append(mean_h[q])
    elif sp['kind'] == 'cor':
        cor = _roll(h, H, 'max') - _roll(l, H, 'min')
        fut = _at(cor, q + H)
        feats.append(cor[q])
    else:
        raise ValueError(f"🍆 АЙ, ОШИБКА! таргет '{tkey}': тип '{sp['kind']}' — есть 'atr' и 'cor'")
    cf = np.concatenate([[0], np.cumsum(fin.astype(np.int64))])
    j = np.arange(m)
    ok = j + H <= m - 1
    jj = j[ok]
    ok[ok] = (cf[jj + H + 1] - cf[jj + 1]) == H          # r конечен на j + 1 … j + H: подряд, без дыр, нормировщик жив
    ok &= np.isfinite(norm) & (norm > 0) & np.isfinite(fut)
    y = np.where(ok, _lg(fut, norm), np.nan)
    Fm = np.stack([_lg(f, norm) for f in feats], axis=1)
    return y, Fm, ok, norm, norm_r


def hour_of_week(t_ns):
    """Час недели (0 — понедельник 00:00 UTC) метки открытия бара; у прокладок (t < 0) — −1."""
    t = np.asarray(t_ns, dtype=np.int64)
    hod = (t // 3_600_000_000_000) % 24
    dow = ((t // 86_400_000_000_000) + 3) % 7        # 1970-01-01 — четверг
    return np.where(t >= 0, hod + 24 * dow, -1).astype(np.int16)


