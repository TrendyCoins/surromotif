def seeds_r2(rs, assets, part, key):
    v = []
    for r in rs:
        x = run_arr(r)
        z = [r2(x[f"{a}__{part}__y"], x[f"{a}__{part}__{key}"]) for a in assets
             if f"{a}__{part}__y" in x and f"{a}__{part}__{key}" in x]
        if len(z) == len(assets):
            v.append(np.mean(z))
    return float(np.mean(v)) if v else float('nan')


def _fmt(d, se):
    if not np.isfinite(d):
        return f"{'—':>17}"
    z = d / se if se > 0 else float('inf')
    return f"{d:+.4f} ± {se:.4f} ({z:+5.1f})"


def verdict(dt, st, dv, k=None):
    """Правило (1): ΔR² TUNE >= +k · SE и ΔR² VAL > 0."""
    k = RULES['se_k'] if k is None else k
    if not (np.isfinite(dt) and np.isfinite(dv)):
        return None
    return bool(dt >= k * st and dv > 0)


HALF_NAMES = ('FIT', 'T24H2', 'T25H1', 'V25H2', 'V26H1')


def half_labels(t_ns):
    """Полугодие окна по времени его конца (бар T): до HALVES[0] — FIT, дальше T24H2 / T25H1 / V25H2 / V26H1."""
    edges = np.array([pd.Timestamp(x).value for x in HALVES], dtype=np.int64)
    idx = np.searchsorted(edges, np.asarray(t_ns, np.int64), side='right')
    return np.array(HALF_NAMES)[idx]


def band_cover(x, a, key, q):
    """Доля фактов VAL внутри ŷ ± z·σ, σ — RMS остатков TUNE (того же ассета и прогона)."""
    kt, kv = f"{a}__tune__", f"{a}__val__"
    if kt + 'y' not in x or kv + 'y' not in x:
        return float('nan')
    s_ = float(np.sqrt(np.mean((x[kt + 'y'].astype(float) - x[kt + key]) ** 2)))
    z = float(_norm_ppf(0.5 + q / 2))
    return float(np.mean(np.abs(x[kv + 'y'].astype(float) - x[kv + key]) <= z * s_))


def _norm_ppf(p):
    """Квантиль стандартного нормального (бисекция по erf — без scipy)."""
    lo, hi = -10.0, 10.0
    for _ in range(100):
        mid = 0.5 * (lo + hi)
        if 0.5 * (1 + math.erf(mid / math.sqrt(2))) < p:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


def line_R(x, a, part, key):
    """Гладкость прогноза: RMS(Δŷ) / sd(ŷ) по парам соседних окон (начала st и st + 1)."""
    k_ = f"{a}__{part}__"
    if k_ + 'st' not in x or k_ + key not in x:
        return float('nan')
    st, v = x[k_ + 'st'], x[k_ + key].astype(np.float64)
    nx = np.searchsorted(st, st + 1)
    ok = nx < len(st)
    ok[ok] = st[nx[ok]] == st[ok] + 1
    if ok.sum() < 100:
        return float('nan')
    d = v[nx[ok]] - v[ok]
    return float(np.sqrt(np.mean(d ** 2)) / v.std())


def _verdict_cell(v, miss):
    if miss:
        return f"— нет сидов {', '.join(miss)}"
    return '✅' if v else ('❌' if v is not None else '—')


def time_flag(d_tune, d_val):
    """Правило (3), флаг «время обгоняет сеть»: ΔR² (сеть − (HAR + t)) на TUNE <= −k · SE и на VAL < 0."""
    dt, st, dv = d_tune[0], d_tune[1], d_val[0]
    return bool(np.isfinite(dt) and np.isfinite(dv) and -dt >= RULES['time_flag_se'] * st and dv < 0)


