# R² И РАЗНИЦЫ С ОШИБКОЙ ПО НЕДЕЛЯМ
# =====================================================================
def r2(y, yh):
    y, yh = np.asarray(y, np.float64), np.asarray(yh, np.float64)
    v = float(np.mean((y - y.mean()) ** 2))
    return float(1.0 - np.mean((y - yh) ** 2) / v) if v > 0 else float('nan')


def dr2_parts(y, a, b):
    """ΔR² = R²(a) − R²(b) на одних окнах и вклады окон (для ошибки по неделям): e_i = (y − b)² − (y − a)², ΔR² = mean(e) / var(y)."""
    y, a, b = (np.asarray(x, np.float64) for x in (y, a, b))
    v = float(np.mean((y - y.mean()) ** 2))
    e = (y - b) ** 2 - (y - a) ** 2
    d = float(e.mean() / v)
    return d, (e - e.mean()) / (len(e) * v)


def panel_delta(items):
    """Средний по ассетам ΔR² и его SE: items — список (y, a, b, wk) по ассетам; вклады окон всех ассетов кластера — вместе (рынки
       синхронны). Кластеры — недели и блоки из 4 недель (режим волы держится неделями: соседние недели не независимы, и SE по
       неделям его занижает); берётся бо́льшая из двух SE."""
    ds, infl, wks = [], [], []
    for y, a, b, wk in items:
        d, inf_ = dr2_parts(y, a, b)
        ds.append(d)
        infl.append(inf_ / len(items))
        wks.append(np.asarray(wk, np.int64))
    se_w = smc.cluster_se(infl, wks)
    se_4 = smc.cluster_se(infl, [w_ // 4 for w_ in wks])
    return float(np.mean(ds)), max(se_w, se_4)


def seed_combine(ds, ses):
    """Среднее по сидам и SE = √(средний квадрат SE окон + разброс сидов / n) — как _seed_delta в коде F1."""
    ds, ses = np.asarray(ds, float), np.asarray(ses, float)
    if len(ds) == 0:
        return float('nan'), float('nan'), 0
    var_seed = float(np.var(ds, ddof=1) / len(ds)) if len(ds) > 1 else 0.0
    return float(ds.mean()), float(np.sqrt(np.mean(ses ** 2) + var_seed)), len(ds)


