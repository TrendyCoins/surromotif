def stand_bars(seed, first, last, sigma=1e-3, alpha=0.08, beta=0.90, season=0.45, sub=12, px0=100.0):
    """5M-бары: GARCH(1, 1) по барам и суточный профиль волы (пик в 15:00 UTC); внутри бара — броуновский путь из sub шагов.
       Направление не предсказуемо (шаги симметричны), предсказуема только вола."""
    rng = np.random.default_rng(seed)
    t = pd.date_range(first, last, freq='5min', inclusive='left')
    n = len(t)
    hod = t.hour.values + t.minute.values / 60.0
    prof = np.exp(season * np.cos(2 * np.pi * (hod - 15.0) / 24.0))
    prof = prof / np.sqrt(np.mean(prof ** 2))
    omega = sigma ** 2 * (1 - alpha - beta)
    z = rng.standard_normal((n, sub))
    o = np.empty(n)
    h = np.empty(n)
    l_ = np.empty(n)
    c = np.empty(n)
    var, lp = sigma ** 2, math.log(px0)
    for i in range(n):
        s_bar = math.sqrt(var) * prof[i]
        path = np.cumsum(z[i]) * (s_bar / math.sqrt(sub))
        o[i] = math.exp(lp)
        c[i] = math.exp(lp + path[-1])
        h[i] = math.exp(lp + max(0.0, path.max()))
        l_[i] = math.exp(lp + min(0.0, path.min()))
        e = path[-1] / prof[i]
        var = omega + alpha * e * e + beta * var
        lp += path[-1]
    return pd.DataFrame({'timestamp': t, 'open': o, 'high': h, 'low': l_, 'close': c})


def stand_write(dirpath, asset, df, training_start, validation_start, N=200, n_pre=200):
    """Файлы данных ассета ровно по арифметике SuMo_Class_Data (make_parts), _Prices, _Range и _Bars: smc_series (r, t, close, fin,
       meta), smc_prices (e, d, d0 у HL/2 и HLC/3), smc_range (g), smc_bars (OHLC баров частей и n_pre баров перед частью)."""
    tf = '5M'
    close = df['close'].to_numpy(np.float64)
    o = df['open'].to_numpy(np.float64)
    high, low = df['high'].to_numpy(np.float64), df['low'].to_numpy(np.float64)
    date = df['timestamp']
    roll = pd.Series(high - low).rolling(N, closed='left').median().to_numpy()
    dt = date.diff().dt.total_seconds().to_numpy()
    step = float(np.nanmedian(dt[1:]))
    gap = np.zeros(len(df), dtype=bool)
    gap[1:] = dt[1:] > step * 1.5
    d_close = np.diff(close, prepend=close[0])
    d_close[0] = 0.0
    r = np.zeros_like(d_close)
    np.divide(d_close, roll, out=r, where=roll != 0)
    bad = ~np.isfinite(roll) | (roll <= 0) | ~np.isfinite(r) | gap
    r[bad] = np.nan
    r[0] = np.nan
    good_roll = np.isfinite(roll) & (roll > 0)
    prev_close = np.concatenate([[np.nan], close[:-1]])
    e_all, d_all = {}, {}
    for nm, f in (('hl2', lambda: (high + low) / 2.0), ('hlc3', lambda: (high + low + close) / 3.0)):
        p = f()
        e = np.full(len(close), np.nan)
        np.divide(p - prev_close, roll, out=e, where=good_roll)
        e[bad] = np.nan
        e[0] = np.nan
        dd = np.full(len(close), np.nan)
        np.divide(p - close, roll, out=dd, where=good_roll)
        e_all[nm], d_all[nm] = e, dd
    g = np.full(len(close), np.nan)
    np.divide(high - low, roll, out=g, where=~bad)
    ser, pri, rgn, brs, stats, crc = {}, {}, {}, {}, {}, {}
    for name, key, a, b in (('TRAINING', 'tr', training_start, validation_start), ('VALIDATION', 'va', validation_start, None)):
        i0 = int(np.where(date >= pd.Timestamp(a))[0][0])
        i1 = len(df) - 1 if b is None else int(np.where(date < pd.Timestamp(b))[0][-1])
        lo, hi = i0 + N, i1 + 1
        r_part = r[lo:hi].astype(np.float32)
        ser[f'r_{key}'] = r_part
        ser[f't_{key}'] = date.iloc[lo:hi].to_numpy().astype('datetime64[ns]').astype(np.int64)
        ser[f'close_{key}'] = close[lo:hi].copy()
        ser[f'fin_{key}'] = np.where(np.isfinite(r_part))[0].astype(np.int32)
        stats[name] = {'n': int(hi - lo), 'from': str(date.iloc[lo]), 'to': str(date.iloc[hi - 1])}
        crc[key] = zlib.crc32(r_part.tobytes())
        for nm in ('hl2', 'hlc3'):
            pri[f'e_{nm}_{key}'] = e_all[nm][lo:hi].astype(np.float32)
            pri[f'd_{nm}_{key}'] = d_all[nm][lo:hi].astype(np.float32)
            pri[f'd0_{nm}_{key}'] = np.array(np.float32(d_all[nm][lo - 1]))
        g_part = g[lo:hi].astype(np.float32)
        g_part[~np.isfinite(r_part)] = np.nan
        rgn[f'g_{key}'] = g_part
        for k_, v in (('o', o), ('h', high), ('l', low), ('c', close)):
            brs[f'{k_}_{key}'] = v[lo:hi].copy()
            brs[f'pre_{k_}_{key}'] = v[lo - n_pre:lo].copy()
    meta = {'ver': 1, 'asset': asset, 'tf': tf, 'N': N, 'csv': 'stand', 'csv_first': str(date.iloc[0]),
            'csv_last': str(date.iloc[-1]), 'grid_step_s': step, 'training_start': training_start,
            'validation_start': validation_start, 'parts': stats, 'L': {}}
    ser['meta'] = np.array(json.dumps(meta, ensure_ascii=False))
    for d_, kind in ((pri, 'prices'), (rgn, 'range'), (brs, 'bars')):
        d_['meta'] = np.array(json.dumps({'asset': asset, 'tf': tf, 'N': N, 'crc': crc, 'what': 'stand'}, ensure_ascii=False))
    os.makedirs(dirpath, exist_ok=True)
    for d_, kind in ((ser, 'series'), (pri, 'prices'), (rgn, 'range'), (brs, 'bars')):
        np.savez_compressed(dirpath + f"smc_{kind}_{asset}_{tf}_N{N}.npz", **d_)


def stand_brute(h, l_, j, H, kind, n_pre=200):
    """Таргет и признаки HAR одного окна (бар j части) — в лоб, по барам (для сверки с part_targets). h, l_ — high / low части
       с n_pre барами перед ней."""
    q = n_pre + j
    rng = h - l_
    norm = float(np.median(rng[q - NH + 1:q + 1]))
    if kind == 'atr':
        fut = float(np.mean(rng[q + 1:q + H + 1]))
        past = float(np.mean(rng[q - H + 1:q + 1]))
    else:
        fut = float(np.max(h[q + 1:q + H + 1]) - np.min(l_[q + 1:q + H + 1]))
        past = float(np.max(h[q - H + 1:q + 1]) - np.min(l_[q - H + 1:q + 1]))
    feats = [float(np.mean(rng[q - k + 1:q + 1])) for k in HAR_LAGS]
    if kind == 'cor' or H not in HAR_LAGS:
        feats.append(past)
    lg = lambda x: math.log(max(x / norm, LOG_FLOOR))
    return lg(fut), [lg(f) for f in feats]


