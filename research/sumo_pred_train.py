# БАЗЫ: HAR и HAR + час недели (OLS, нормальные уравнения по кускам)
# =====================================================================
def har_fit(Fm, y, how=None, ridge=1e-9):
    """OLS. Без часа: y ~ 1 + F. С часом: y ~ F + сдвиг часа недели (168 сдвигов вместо общего свободного члена)."""
    n, k = Fm.shape
    if how is None:
        A, b = np.zeros((k + 1, k + 1)), np.zeros(k + 1)
        for a in range(0, n, HAR_CHUNK):
            f = Fm[a:a + HAR_CHUNK].astype(np.float64)
            X = np.column_stack([np.ones(len(f)), f])
            A += X.T @ X
            b += X.T @ y[a:a + HAR_CHUNK].astype(np.float64)
    else:
        A, b = np.zeros((k + 168, k + 168)), np.zeros(k + 168)
        for a in range(0, n, HAR_CHUNK):
            f = Fm[a:a + HAR_CHUNK].astype(np.float64)
            yy = y[a:a + HAR_CHUNK].astype(np.float64)
            hw = how[a:a + HAR_CHUNK].astype(np.int64)
            if hw.min() < 0 or hw.max() >= 168:
                raise ValueError("🍆 АЙ, ОШИБКА! час недели вне 0…167 у окна обучения")
            A[:k, :k] += f.T @ f
            b[:k] += f.T @ yy
            for c_ in range(k):
                s_ = np.bincount(hw, weights=f[:, c_], minlength=168)
                A[c_, k:] += s_
                A[k:, c_] += s_
            A[k:, k:] += np.diag(np.bincount(hw, minlength=168).astype(np.float64))
            b[k:] += np.bincount(hw, weights=yy, minlength=168)
    lam = ridge * max(float(np.mean(np.diag(A))), 1e-12)
    coef = np.linalg.solve(A + lam * np.eye(len(A)), b)
    return {'coef': coef.tolist(), 'time': how is not None, 'k': k}


def har_pred(fit, Fm, how=None):
    c = np.asarray(fit['coef'])
    k = fit['k']
    f = Fm.astype(np.float64)
    if not fit['time']:
        return c[0] + f @ c[1:]
    return f @ c[:k] + c[k:][how.astype(np.int64)]


