def site_decision(s2):
    """Колонка прогноза сайта по вердикту (2) таргета SITE_TARGET: 'cnn' / 'har' / None (прогонов пула нет или не все сиды)."""
    r = s2.get(SITE_TARGET)
    dec = None if r is None or r['pass'] is None else ('cnn' if r['pass'] else 'har')
    why = ("прогонов пула нет" if r is None else f"не все сиды (нет {', '.join(r['missing'])})") if dec is None else ""
    print(f"\n🎯 колонка прогноза сайта — {SITE_TARGET} ({TARGETS[SITE_TARGET]['what']}): "
          + ({'cnn': '✅ СЕТЬ', 'har': '❌ HAR (сеть не лучше заметно)'}[dec] if dec else f"вердикта нет: {why}"))
    return {'target': SITE_TARGET, 'decision': dec}


def cross_delta(ra, rb, assets, part, key='cnn'):
    """ΔR² (сеть прогона ra − сеть прогона rb) на одних окнах: средний по ассетам и SE по кластерам; None — нет окон или окна
       прогонов не совпали (сверка начал окон и факта)."""
    xa, xb = run_arr(ra), run_arr(rb)
    items = []
    for a in assets:
        k_ = f"{a}__{part}__"
        if k_ + 'y' not in xa or k_ + 'y' not in xb:
            return None
        if not (np.array_equal(xa[k_ + 'st'], xb[k_ + 'st']) and np.array_equal(xa[k_ + 'y'], xb[k_ + 'y'])):
            print(f"⚠️ {ra['tag']} и {rb['tag']}: окна {a} {part} не совпали — пары не сравнить")
            return None
        items.append((xa[k_ + 'y'], xa[k_ + key], xb[k_ + key], xa[k_ + 'wk']))
    return panel_delta(items) if items else None


def p3_table(runs):
    """Волна P3, правило (4): рецепт P3 против текущего прогона пула (проверка раз в эпоху) — та же сеть, те же данные и окна,
       пары сидов a ↔ a, b ↔ b. Вердикт — только на полном наборе сидов у обоих рецептов."""
    rc = RECIPES['p3']
    out = {}
    for tkey in rc['targets']:
        new = pick(runs, 'pool', POOL_MODEL, target=tkey, set_name=POOL_SET, recipe='p3')
        if not new:
            continue
        cur = {r['seed_key']: r for r in pick(runs, 'pool', POOL_MODEL, target=tkey, set_name=POOL_SET)}
        panel = new[0]['panel']
        print(f"\n{'=' * 100}\n🧪 ВОЛНА P3 — пул {POOL_SET}, {tkey}, сеть {POOL_MODEL}: проверка TUNE каждые 1/{rc['sub']} эпохи, "
              + ", ".join(f"{k} {v}" for k, v in rc['over'].items()) + "; против текущего рецепта (проверка раз в эпоху), "
              f"сиды P3 {', '.join(sorted(r['seed_key'] for r in new))}, текущего {', '.join(sorted(cur)) or '—'}\n{'=' * 100}")
        print(f"   {'модель':<16} | {'R² TUNE панели':>14} | {'R² VAL панели':>13} | {'R линии VAL':>11}")
        for nm, rs, key in (('P3', new, 'cnn'), ('текущий', list(cur.values()), 'cnn'), ('HAR', new, 'har'),
                            ('HAR + входы F1', new, 'hars'), ('HAR + t', new, 'hart')):
            if not rs:
                continue
            lr_ = float(np.nanmean([np.nanmean([line_R(run_arr(r), a, 'val', key) for a in panel]) for r in rs]))
            print(f"   {nm:<16} | {seeds_r2(rs, panel, 'tune', key):>14.4f} | {seeds_r2(rs, panel, 'val', key):>13.4f} | "
                  f"{lr_:>11.3f}")
        dd = {}
        for part in ('tune', 'val'):                       # (4б) P3 − текущий, пары сидов
            ds, ses = [], []
            for r in new:
                c = cur.get(r['seed_key'])
                d = cross_delta(r, c, panel, part) if c is not None else None
                if d is not None:
                    ds.append(d[0])
                    ses.append(d[1])
            dd[part] = seed_combine(ds, ses)
        dt, st, _ = seeds_delta(new, panel, 'tune', 'cnn', 'har')          # (1)–(2) P3 против HAR
        dv, sv, _ = seeds_delta(new, panel, 'val', 'cnn', 'har')
        v12 = verdict(dt, st, dv)
        mg = RULES['min_gain']
        if v12 and mg is not None:
            v12 = bool(dv >= mg)
        bests = {r['seed_key']: r for r in new}                             # (4а) лучшая проверка — не одна из первых двух
        resolved = all(r['best_ep'] >= 2 for r in new)
        miss = sorted(set(seeds_missing(new, 'pool')) | {s_ for s_ in SEEDS_REQ['pool'] if s_ not in cur})
        dx, sx, _ = dd['val']
        ok4b = bool(np.isfinite(dx) and dx >= -sx)
        accept = None if miss else bool(resolved and ok4b and v12)
        steps_best = [r['best_step'] for r in new]
        ep_best = [r['best_step'] / r['steps_per_epoch'] for r in new]
        print("\n   (4а) расписание: лучшая проверка — " + ", ".join(
            f"{k} {r['best_ep']} ({r['best_step'] / r['steps_per_epoch']:.2f} эп., {r['best_step']} шагов)"
            for k, r in sorted(bests.items())) + f" — {'✅ найдено' if resolved else '❌ лучшая — среди первых двух проверок'}")
        print(f"   (4б) ΔR² панели P3 − текущий: TUNE {_fmt(*dd['tune'][:2])}, VAL {_fmt(dx, sx)} — "
              + ('✅ не хуже −1 SE' if ok4b else '❌ хуже больше чем на 1 SE'))
        print(f"   (1)–(2) P3 против HAR, панель: ΔR² TUNE {_fmt(dt, st)}, VAL {_fmt(dv, sv)}"
              + (f", порог {mg:g}" if mg is not None else "") + f" — {'✅' if v12 else '❌'}")
        d1 = seeds_delta(new, panel, 'tune', 'cnn', 'hars')
        d2 = seeds_delta(new, panel, 'val', 'cnn', 'hars')
        d3 = seeds_delta(new, panel, 'val', 'hars', 'har')
        print(f"   справочно: сеть P3 − (HAR + входы F1): TUNE {_fmt(d1[0], d1[1])}, VAL {_fmt(d2[0], d2[1])} — что даёт форма окна "
              f"сверх сводок; (HAR + входы F1) − HAR: VAL {_fmt(d3[0], d3[1])}")
        if accept is None:
            print(f"   🧪 итог P3: вердикта нет — не все сиды (нет {', '.join(miss)})")
        else:
            print("   🧪 итог P3: " + (f"✅ рецепт P3 — в боевую модель; до лучшей проверки в среднем {np.mean(steps_best):.0f} шагов "
                                    f"({np.mean(ep_best):.2f} эп.)" if accept else
                                    "❌ остаётся текущий рецепт ('stop', проверка раз в эпоху)"))
        out[tkey] = {'d_val_vs_cur': dd['val'], 'd_tune_vs_cur': dd['tune'], 'd_tune_har': (dt, st), 'd_val_har': (dv, sv),
                     'pass_12': v12, 'resolved': resolved, 'ok_4b': ok4b, 'accept': accept, 'missing': miss,
                     'best_ep': {k: r['best_ep'] for k, r in bests.items()}, 'best_step': steps_best, 'best_epochs': ep_best}
    return out


def p5_eval(runs, tkey):
    """(5а): refit (FIT + TUNE, расписание без остановки) против P3 на VAL панели — пары сидов a ↔ a, b ↔ b. None — прогонов
       refit нет."""
    ref = pick(runs, 'pool', POOL_MODEL, target=tkey, set_name=POOL_SET, recipe='r5')
    if not ref:
        return None
    p3 = {r['seed_key']: r for r in pick(runs, 'pool', POOL_MODEL, target=tkey, set_name=POOL_SET, recipe='p3')}
    panel = ref[0]['panel']
    ds, ses = [], []
    for r in ref:
        c = p3.get(r['seed_key'])
        d = cross_delta(r, c, panel, 'val') if c is not None else None
        if d is not None:
            ds.append(d[0])
            ses.append(d[1])
    dx, sx, nx = seed_combine(ds, ses)
    miss = sorted(set(seeds_missing(ref, 'pool')) | {s_ for s_ in SEEDS_REQ['pool'] if s_ not in p3})
    accept = None if miss else bool(np.isfinite(dx) and dx >= -sx)
    return {'refit': ref, 'p3': list(p3.values()), 'panel': panel, 'd_val': (dx, sx, nx), 'missing': miss, 'accept': accept}


def refit_gate(tkeys):
    """Ворота боевой модели (5б): у каждого таргета — вердикт (5а) принят (refit не хуже P3 на VAL, полный набор сидов)."""
    runs = load_runs()
    msgs, ok = [], True
    for tkey in tkeys:
        e = p5_eval(runs, tkey)
        if e is None:
            ok = False
            msgs.append(f"{tkey}: прогонов refit нет — сначала задания R5a / R5b")
        elif e['accept'] is None:
            ok = False
            msgs.append(f"{tkey}: не все сиды refit / P3 (нет {', '.join(e['missing'])})")
        else:
            ok = ok and e['accept']
            msgs.append(f"{tkey}: ΔR² VAL панели refit − P3 {_fmt(*e['d_val'][:2])} — "
                        + ('✅ не хуже −1 SE' if e['accept'] else '❌ хуже больше чем на 1 SE'))
    return ok, "🚦 ворота (5а) боевой модели — " + "; ".join(msgs)


def band_sigma(rs, assets):
    """σ полосы прогноза по ассету: RMS остатков VAL (y − прогноз сети), среднее по сидам — у refit это ошибка вне выборки."""
    out = {}
    for a in assets:
        v = []
        for r in rs:
            x = run_arr(r)
            k_ = f"{a}__val__"
            if k_ + 'y' in x:
                v.append(float(np.sqrt(np.mean((x[k_ + 'y'].astype(np.float64) - x[k_ + 'cnn']) ** 2))))
        if v:
            out[a] = float(np.mean(v))
    return out


